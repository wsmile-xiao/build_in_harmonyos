#!/usr/bin/env python3
"""finalcut 0.9.1 — FINAL CUT C++ TUI library (autotools).

OHOS adaptation notes:
- Autotools project; autoreconf-generated config.guess/config.sub do not
  recognize HarmonyOS, so build() applies the tested OHOS triplet handling
  inline after autoreconf (without platform macros in .patch files).
- Requires termcap headers/library for FTermcap; provided by ncurses/6.6
  (OHOS binary), linked statically to avoid system-lib conflicts (E028).
- 0001-ftermlinux-isa-guard.patch guards ISA_SYSCTL_SUPPORT-only fields in
  ftermlinux.h to satisfy clang -Wall -Werror on aarch64/OHOS.
"""
import os
import re

from conan import ConanFile
from conan.tools.files import copy, get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


# ---------------------------------------------------------------------------
# R04: pure-Python source text transforms (replacement for sed/perl calls).
# The remote CI worker PATH has no sed/perl, so every textual patch must be
# done with Python str operations. All helpers are idempotent on re-run.
# ---------------------------------------------------------------------------

def _rewrite_text_file(path, old, new):
    """In-place replace of `old` by `new` in a text file, preserving encoding
    (ASCII/Latin1 as generated by autoreconf); bytes-safe for the shebang."""
    with open(path, "r", encoding="utf-8", errors="surrogatepass") as fh:
        data = fh.read()
    if old not in data:
        return
    data = data.replace(old, new)
    with open(path, "w", encoding="utf-8", errors="surrogatepass") as fh:
        fh.write(data)


def _patch_config_guess_ohos(path):
    """E007: make generated config.guess recognize HarmonyOS. Idempotent."""
    with open(path, "r", encoding="utf-8", errors="surrogatepass") as fh:
        data = fh.read()
    changed = False

    # 1.1: add __OHOS__ LIBC detection right after __ANDROID__ LIBC=android.
    # Anchors are indentation-insensitive (generated files use tabs).
    if "__OHOS__" not in data:
        m = re.search(r"#if\s+defined\(__ANDROID__\)[ \t]*\n[ \t]*LIBC=android", data)
        if m:
            insert_at = m.end()
            data = data[:insert_at] + "\n#elif defined(__OHOS__)\n\tLIBC=ohos" + data[insert_at:]
            changed = True

    # 1.2: insert HarmonyOS case block before the NetBSD case
    if "HarmonyOS" not in data:
        block = (
            "\t*:HarmonyOS:*:*)\n"
            "\tcase \"$UNAME_MACHINE\" in\n"
            "\t    aarch64|arm64) MACHINE=aarch64 ;;\n"
            "\t    armv7*|armv8*) MACHINE=arm ;;\n"
            "\t    x86_64|amd64)  MACHINE=x86_64 ;;\n"
            "\t    i?86)         MACHINE=i686 ;;\n"
            "\t    *)            MACHINE=\"$UNAME_MACHINE\" ;;\n"
            "\tesac\n"
            "\tGUESS=${MACHINE}-unknown-linux-ohos\n"
            "\t;;\n\n")
        m = re.search(r"^[ \t]*\*:NetBSD:\*:\*\)", data, re.MULTILINE)
        if m:
            data = data[:m.start()] + block + data[m.start():]
            changed = True

    if changed:
        with open(path, "w", encoding="utf-8", errors="surrogatepass") as fh:
            fh.write(data)


def _patch_config_sub_ohos(path):
    """E007: make generated config.sub recognize aarch64-linux-ohos. Idempotent."""
    with open(path, "r", encoding="utf-8", errors="surrogatepass") as fh:
        data = fh.read()
    changed = False

    # 2.1: add ohos-linux triplet after android-linux block. The generated
    # config.sub indents with tabs, so anchor on the android-linux case line
    # and the first `;;` that closes it (indentation-insensitive).
    if "ohos-linux" not in data:
        m = re.search(r"^[ \t]*android-linux\)[ \t]*\n", data, re.MULTILINE)
        if m:
            rest = data[m.end():]
            m2 = re.search(r"^[ \t]*;;[ \t]*\n", rest, re.MULTILINE)
            if m2:
                insert_at = m.end() + m2.end()
                ohos_block = (
                    "\tohos-linux)\n"
                    "\tbasic_machine=$field1-unknown\n"
                    "\tbasic_os=linux-ohos\n"
                    "\t;;\n")
                data = data[:insert_at] + ohos_block + data[insert_at:]
                changed = True

    # 2.2: add ohos* to OS type list
    if "gnu* | android* | ohos*" not in data:
        os_list = "gnu* | android*"
        if os_list in data:
            data = data.replace(os_list, os_list + " | ohos*")
            changed = True

    # 2.3: add linux-ohos to kernel-OS validation list
    if "linux-ohos*- )" not in data:
        for anchor in ("linux-uclibc*- )", "linux-mlibc*- )"):
            if anchor in data:
                data = data.replace(anchor,
                                    anchor.replace(" )", " | linux-ohos*- )", 1))
                changed = True
                break

    if changed:
        with open(path, "w", encoding="utf-8", errors="surrogatepass") as fh:
            fh.write(data)


def _patch_ohos_fkeyboard_init(path):
    """Disable optimization only for the OHOS keyboard-test fixture setup.

    On the HarmonyOS aarch64 Clang 15 Release build, FKeyboardTest::init()
    faults while copying its std::function callbacks. The same test translation
    unit passes when this single setup method is compiled without optimization.
    """
    with open(path, "r", encoding="utf-8", errors="surrogatepass", newline="") as fh:
        data = fh.read()
    if "__attribute__((optnone))" in data:
        return

    pattern = re.compile(r"(?m)^void FKeyboardTest::init\(\)(\r?\n)\{")
    match = pattern.search(data)
    if not match:
        raise RuntimeError("cannot locate FKeyboardTest::init() for OHOS test workaround")

    newline = match.group(1)
    replacement = (
        "#if defined(__OHOS__) && defined(__clang__)" + newline
        + "// Optimized OHOS aarch64 setup faults while copying std::function callbacks." + newline
        + "__attribute__((optnone))" + newline
        + "#endif" + newline
        + "void FKeyboardTest::init()" + newline
        + "{"
    )
    data = pattern.sub(lambda _: replacement, data, count=1)
    with open(path, "w", encoding="utf-8", errors="surrogatepass", newline="") as fh:
        fh.write(data)


class FinalcutConan(ConanFile):
    name = "finalcut"
    version = "0.9.1"
    description = "C++ text user interface (TUI) library with text-based widgets"
    license = "LGPL-3.0"
    homepage = "https://github.com/gansm/finalcut"
    url = "https://github.com/gansm/finalcut"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)
        # autoconf-archive macros used by configure.ac (AX_CXX_COMPILE_STDCXX_14)
        # are not present on the build host; ship them in m4/.
        copy(self, "m4/*", src=self.recipe_folder, dst=self.export_sources_folder)

    def requirements(self):
        # Termcap headers/library come from ncurses; E028 motivates keeping
        # finalcut itself static to avoid replacing system shared libraries.
        self.requires("ncurses/6.6")

    def build_requirements(self):
        # The official tarball ships configure.ac/Makefile.am but no generated
        # configure; build() runs autoreconf which needs automake/aclocal and
        # libtool/libtoolize. The remote CI worker only provides autoconf, so
        # declare the missing bootstrap tools as tool_requires (versions
        # verified available on ohpcd, R03 CI L1 fix). autoconf itself is NOT
        # declared: the host/CI already provide autoconf 2.72, and the conan
        # autoconf package bakes its scripts to conan perl 5.42.2 which is
        # incompatible with the host perl 5.42.0 that runs autoreconf/aclocal
        # (PERL5LIB XS mismatch). Keeping autoconf host-provided makes the
        # whole autoreconf→aclocal→autom4te chain run on one consistent perl.
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")
        # Build and run the upstream CppUnit suite in the Conan build folder.
        # This is build-only: CppUnit is not exposed to package consumers.
        self.tool_requires("cppunit/1.15.1")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # finalcut is a C++14-only codebase (configure.ac mandates
        # AX_CXX_COMPILE_STDCXX_14); the generic OHOS profile sets cppstd=17
        # which turns std::iterator (used in char_ringbuffer.h) into a
        # -Wdeprecated-declarations -Werror failure. Force -std=c++14 for the
        # final command line (appended after the profile's -std=c++17).
        tc.extra_cxxflags.append("-std=c++14")
        # AutotoolsToolchain does not inject dependency include/lib dirs into
        # CPPFLAGS/LDFLAGS for autotools consumers; add the termcap provider
        # (ncurses) paths explicitly so <term.h> and -lncursesw resolve.
        ncurses_dependency = self.dependencies["ncurses"]
        ncurses = ncurses_dependency.cpp_info
        for inc in ncurses.includedirs:
            tc.extra_cflags.append(f"-I{inc}")
            tc.extra_cxxflags.append(f"-I{inc}")
        for lib in ncurses.libdirs:
            tc.extra_ldflags.append(f"-L{lib}")
        tc.extra_ldflags.append("-lncursesw")

        # finalcut's --with-unit-test uses pkg-config. The published CppUnit
        # package has a non-relocatable prefix=/ and places -ldl in
        # Libs.private, which pkg-config omits for this static test link. Fix
        # only a generated copy in the build folder, leaving the dependency
        # package untouched.
        cppunit = self.dependencies.build["cppunit"]
        for inc in cppunit.cpp_info.includedirs:
            inc_dir = os.path.join(cppunit.package_folder, inc)
            tc.extra_cflags.append(f"-I{inc_dir}")
            tc.extra_cxxflags.append(f"-I{inc_dir}")
        cppunit_pc = os.path.join(
            cppunit.package_folder, "lib", "pkgconfig", "cppunit.pc"
        )
        with open(cppunit_pc, "r", encoding="utf-8") as fh:
            cppunit_pc_data = fh.read()
        cppunit_pc_data = re.sub(
            r"(?m)^prefix=/\s*$",
            f"prefix={cppunit.package_folder}",
            cppunit_pc_data,
            count=1,
        )
        private_libs = re.search(
            r"(?m)^Libs\.private:\s*(.*?)\s*$", cppunit_pc_data
        )
        if private_libs:
            private_flags = private_libs.group(1)
            cppunit_pc_data = (
                cppunit_pc_data[:private_libs.start()]
                + cppunit_pc_data[private_libs.end():]
            )
            cppunit_pc_data = re.sub(
                r"(?m)^Libs:(.*)$",
                lambda match: f"Libs:{match.group(1)} {private_flags}".rstrip(),
                cppunit_pc_data,
                count=1,
            )
        fixed_pc_dir = os.path.join(self.generators_folder, "finalcut-pkgconfig")
        os.makedirs(fixed_pc_dir, exist_ok=True)
        with open(
            os.path.join(fixed_pc_dir, "cppunit.pc"),
            "w",
            encoding="utf-8",
            newline="\n",
        ) as fh:
            fh.write(cppunit_pc_data)
        self.buildenv.prepend_path("PKG_CONFIG_PATH", fixed_pc_dir)

        # Upstream terminal tests query the ncurses terminfo database at run
        # time. These values are scoped to Conan's build/test environment.
        self.buildenv.define(
            "TERMINFO",
            os.path.join(ncurses_dependency.package_folder, "lib", "terminfo"),
        )
        self.buildenv.define("TERM", "xterm-256color")
        tc.configure_args.append("--with-unit-test")
        if not self.options.shared:
            tc.configure_args.append("--disable-shared")
            tc.configure_args.append("--enable-static")
        else:
            tc.configure_args.append("--enable-shared")
        # R03: automake/1.18 pulls perl/5.42.2 as a transitive tool_require whose
        # injected PERL5LIB points at the conan perl package. The host perl
        # 5.42.0 (used by the host autoreconf/aclocal shebang) cannot load the
        # 5.42.2 XS modules (Cwd.so: Perl_my_cxt_init symbol not found). Override
        # PERL5LIB to only the automake module dir (Automake::* lives there).
        # self.buildenv is applied AFTER the dependency-provided build env, so
        # this definition wins over the perl tool_require's PERL5LIB injection.
        automake = self.dependencies.build["automake"]
        am_share = os.path.join(automake.package_folder, "share", "automake-1.18")
        self.buildenv.define("PERL5LIB", am_share)
        # HNP bash cannot call getcwd reliably from Conan's deep HMDFS build
        # path when PWD still names Conan's parent directory. Keep its logical
        # working directory accurate for configure/config.status/make/check.
        self.buildenv.define("PWD", self.build_folder)
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        if str(self.settings.os) == "OHOS":
            _patch_ohos_fkeyboard_init(
                os.path.join(self.source_folder, "test", "fkeyboard-test.cpp")
            )
        # The official tarball ships configure.ac/Makefile.am but not the
        # generated configure script; bootstrap with the project's autogen.sh.
        autotools = Autotools(self)
        autotools.autoreconf()

        # ------------------------------------------------------------------
        # R04: all source text patching must be pure Python (no sed/perl).
        # The remote CI worker has a minimal PATH without sed/perl; calling
        # them via subprocess fails on CI even though the local interactive
        # shell provides them. Rewrite every textual transform with Python
        # file IO + str.replace, idempotent on re-run.
        # ------------------------------------------------------------------

        # E011: HMDFS umask 077 in generated configure makes config.status
        # unable to create/execute its temporary awk scripts (Permission
        # denied on subs1.awk). Relax the umask in the generated configure.
        configure = os.path.join(self.source_folder, "configure")
        if os.path.isfile(configure):
            _rewrite_text_file(configure, "umask 077", "umask 022")

        # E007: the autoreconf-generated config.guess/config.sub (libtool
        # 2023-08-22) cannot recognize HarmonyOS. Apply the OHOS patch logic
        # inline in Python, then add the missing kernel-OS validation branch
        # for linux-ohos.
        cg = os.path.join(self.source_folder, "config.guess")
        cs = os.path.join(self.source_folder, "config.sub")
        if os.path.isfile(cg):
            _patch_config_guess_ohos(cg)
        if os.path.isfile(cs):
            _patch_config_sub_ohos(cs)

        autotools.configure()
        # Parallel build to fit the library's ~60 translation units within the
        # worker's per-command budget; -j4 is deterministic (same output as -j1).
        autotools.make(args=["-j4"])
        # Run the full upstream suite as part of conan create. Keep it serial:
        # the HarmonyOS HNP temporary filesystem cannot create GNU make's
        # parallel jobserver FIFO. BSD-only tests are host-gated by patch 0006;
        # TIOCSTI-dependent cases are capability-gated by the same patch.
        self.output.info("Running upstream test suite: make -j1 check")
        autotools.make(target="check", args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.libs = ["final"]
        self.cpp_info.requires = ["ncurses::ncurses"]
        self.cpp_info.set_property("cmake_file_name", "finalcut")
        self.cpp_info.set_property("cmake_target_name", "finalcut::finalcut")
        self.cpp_info.set_property("pkg_config_name", "finalcut")
