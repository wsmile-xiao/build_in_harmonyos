#!/usr/bin/env python3
"""Conan test_package — fontopia 2.0 CLI verification (R34).

fontopia is an interactive ncurses TUI, so the consumer check drives the
installed binary in its non-interactive modes (`--version` / `--help`) and
asserts on the observed output (see test.sh). The shared GnuDOS library it
links (`libgnudos.so.2`) is resolved at runtime through the `conanrun`
environment generated by VirtualRunEnv.
"""
import os

from conan import ConanFile


class FontopiaTestConan(ConanFile):
    settings = "os", "compiler", "build_type", "arch"
    generators = "VirtualRunEnv"
    test_type = "explicit"

    def requirements(self):
        self.requires(self.tested_reference_str)

    def test(self):
        bash = os.environ.get("CONFIG_SHELL", "/data/service/hnp/bin/bash")
        self.run(f"{bash} test.sh", env="conanrun")
