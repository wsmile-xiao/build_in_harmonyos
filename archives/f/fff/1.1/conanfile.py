#!/usr/bin/env python3
"""Conan recipe — fff 1.1 (header-only, upstream Makefile test suite).

fff (Fake Function Framework) is a single-header C/C++ mocking framework.
It ships `fff.h` (pre-generated by `fakegen.rb`); consumers just include it,
no build system exists for the library itself.

The upstream `test/` suite (self-contained `c_test_framework.h` for C and a
vendored Google Test for C++) plus the three `examples/` mini-projects are
driven here through the `run_upstream_tests` option so CI and the device run
the same suites (R51). Build commands mirror upstream `test/Makefile` and
`buildandtest` (11 test binaries), with the OHOS toolchain taken from Conan
conf (R33) instead of the hardcoded gcc/g++.
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.build import can_run
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class FffConan(ConanFile):
    name = "fff"
    version = "1.1"
    description = "Fake Function Framework - a fake function mock library for C/C++ (header-only)"
    license = "MIT"
    homepage = "https://github.com/meekrosoft/fff"
    url = "https://github.com/meekrosoft/fff"
    topics = ("mock", "testing", "fake-functions", "header-only")
    package_type = "header-library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"run_upstream_tests": [True, False]}
    default_options = {"run_upstream_tests": True}

    def export_sources(self):
        export_conandata_patches(self)

    def package_id(self):
        self.info.clear()

    def validate(self):
        # R32: OHOS must be matched alongside Linux, never `== "Linux"`.
        if self.settings.os not in ("Linux", "OHOS", "Windows", "Macos", "FreeBSD"):
            raise ConanInvalidConfiguration(f"fff not validated for {self.settings.os}")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _compilers(self):
        # profile: tools.build:compiler_executables={"c": ..., "cpp": ...}（dict 型 conf）
        comp = self.conf.get("tools.build:compiler_executables", check_type=dict) or {}
        cc = comp.get("c") or "clang"
        cxx = comp.get("cpp") or "clang++"
        ar = comp.get("ar") or "llvm-ar"
        return cc, cxx, ar

    def build(self):
        apply_conandata_patches(self)
        if not self.options.run_upstream_tests:
            return
        cc, cxx, ar = self._compilers()
        src = self.source_folder
        bld = self.build_folder
        runnable = can_run(self)

        def c_compile(out, sources, extra=""):
            # 上游 test/Makefile: gcc -I../ -O0 -g3 -Wall -std=c99
            self.run(f'{cc} -I"{src}" -O0 -g -Wall -std=c99 {extra} {sources} -o "{bld}/{out}"')

        def cxx_object(out, source, extra=""):
            # 上游 Makefile C++ 规则: g++ -I../.. -O0 -g3 -Wall -DGTEST_USE_OWN_TR1_TUPLE=1
            self.run(f'{cxx} -I"{src}" -O0 -g -Wall -std=c++17 -DGTEST_USE_OWN_TR1_TUPLE=1 '
                     f'{extra} -c "{source}" -o "{bld}/{out}"')

        def c_object(out, source, extra=""):
            self.run(f'{cc} -I"{src}" -O0 -g -Wall -std=c99 {extra} -c "{source}" -o "{bld}/{out}"')

        def cxx_link(out, objs):
            # fff/gtest 未引用独立 pthread 符号（OHOS musl 线程符号内建 libc），
            # 故不复刻上游 LIBS=-lpthread。
            self.run(f'{cxx} -o "{bld}/{out}" {objs}')

        def run_target(target):
            if runnable:
                self.run(f'"./{target}"', cwd=bld)
            else:
                self.output.warning(f"{target}: built but not run (cross-can_run=False)")

        # ── vendored Google Test 编译一次，供全部 gtest 目标复用 ──
        cxx_object("gtest-all.o", f"{src}/gtest/gtest-all.cc")
        cxx_object("gtest-main.o", f"{src}/gtest/gtest-main.cc")
        gtest_objs = f'"{bld}/gtest-all.o" "{bld}/gtest-main.o"'

        # ── test/ 核心套件（上游 buildandtest 顺序）──
        # 1. fff_test_c（36 RUN_TEST，自制 C 框架）
        c_compile("fff_test_c", f'"{src}/test/fff_test_c.c"')
        run_target("fff_test_c")

        # 2. fff_test_cpp（45 gtest 用例 = test_cases.include 42 + 自有 3）
        cxx_object("fff_test_cpp.o", f"{src}/test/fff_test_cpp.cpp")
        cxx_link("fff_test_cpp", f'"{bld}/fff_test_cpp.o" {gtest_objs}')
        run_target("fff_test_cpp")

        # 3. fff_test_glob_c（35 RUN_TEST）
        c_compile("fff_test_glob_c",
                  f'"{src}/test/global_fakes.c" "{src}/test/fff_test_global_c.c"')
        run_target("fff_test_glob_c")

        # 4. fff_test_glob_cpp（42 gtest 用例）
        cxx_object("fff_test_global_cpp.o", f"{src}/test/fff_test_global_cpp.cpp")
        c_object("global_fakes.o", f"{src}/test/global_fakes.c")
        cxx_link("fff_test_glob_cpp", f'"{bld}/fff_test_global_cpp.o" "{bld}/global_fakes.o" {gtest_objs}')
        run_target("fff_test_glob_cpp")

        # ── examples/（上游 buildandtest 继续执行）──
        # 5. ui_test_ansic（11 RUN_TEST，纯 C）
        c_compile("ui_test_ansic",
                  f'"{src}/examples/embedded_ui/UI_test_ansic.c" '
                  f'"{src}/examples/embedded_ui/UI.c"')
        run_target("ui_test_ansic")

        # 6. ui_test_cpp（10 gtest 用例，复用 C 编译的 UI.o）
        c_object("UI.o", f"{src}/examples/embedded_ui/UI.c")
        cxx_object("UI_test_cpp.o", f"{src}/examples/embedded_ui/UI_test_cpp.cpp")
        cxx_link("ui_test_cpp", f'"{bld}/UI_test_cpp.o" "{bld}/UI.o" {gtest_objs}')
        run_target("ui_test_cpp")

        # 7/8. driver_testing 与 driver_testing_fff（2 + 3 gtest 用例）
        c_object("driver.o", f"{src}/examples/driver_testing/driver.c", extra="-DTESTING")
        cxx_object("driver.test.o", f"{src}/examples/driver_testing/driver.test.cpp", extra="-DTESTING")
        cxx_link("driver_testing", f'"{bld}/driver.test.o" "{bld}/driver.o" {gtest_objs}')
        run_target("driver_testing")

        cxx_object("driver.test.fff.o", f"{src}/examples/driver_testing/driver.test.fff.cpp", extra="-DTESTING")
        cxx_link("driver_testing_fff", f'"{bld}/driver.test.fff.o" "{bld}/driver.o" {gtest_objs}')
        run_target("driver_testing_fff")

        # 9-11. weak_linking 三例（assert 式单 main 程序）
        # 上游 Makefile: INCLUDE_DIRS=-I "../../" -I "./src/"（后者即 examples/weak_linking/src）
        # WEAK_FLAGS=-DFFF_GCC_FUNCTION_ATTRIBUTES="__attribute__((weak))"
        # libfakes.a = FAKE_OBJECTS 经 make $^ 去重后 5 成员（上游列表中 sensor.fake.o 重复一次）
        wk = '-DFFF_GCC_FUNCTION_ATTRIBUTES="__attribute__((weak))"'
        wk_inc = f'-I"{src}/examples/weak_linking/src" -I"{src}/examples/weak_linking/test"'
        for fake in ("display.fake", "sensor.fake", "error.fake", "bus.fake", "test_common"):
            c_object(f"{fake}.o", f"{src}/examples/weak_linking/test/{fake}.c", extra=f"{wk} {wk_inc}")
        self.run(f'{ar} rcs "{bld}/libfakes.a" "{bld}/display.fake.o" "{bld}/sensor.fake.o" '
                 f'"{bld}/error.fake.o" "{bld}/bus.fake.o" "{bld}/test_common.o"')
        wk_link = [
            ("test_display", "display.test.c", "src/display.c"),
            ("test_sensor", "sensor.test.c", "src/sensor.c"),
            ("test_main", "main.test.c", "src/main.c"),
        ]
        for out, test_src, impl_src in wk_link:
            self.run(f'{cc} -I"{src}" {wk_inc} -O0 -g -Wall -std=c99 {wk} '
                     f'"{src}/examples/weak_linking/test/{test_src}" "{bld}/libfakes.a" '
                     f'"{src}/examples/weak_linking/{impl_src}" -o "{bld}/{out}"')
            run_target(out)

    def package(self):
        copy(self, "fff.h", src=self.source_folder,
             dst=os.path.join(self.package_folder, "include"))
        copy(self, "LICENSE", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))
        copy(self, "README.md", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.libs = []
        self.cpp_info.bindirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.includedirs = ["include"]
