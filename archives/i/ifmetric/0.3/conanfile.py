#!/usr/bin/env python3
"""Conan recipe for ifmetric 0.3.

ifmetric is a small Linux command line tool that sets the metric (priority) of
every IPv4 route in the main routing table attached to a given network
interface, by dumping the table over rtnetlink and re-issuing RTM_DELROUTE +
RTM_NEWROUTE for each matching entry.
"""
import os
import stat

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    replace_in_file,
)
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class IfmetricConan(ConanFile):
    name = "ifmetric"
    version = "0.3"
    description = (
        "Command line tool to set the metric of all IPv4 routes attached to a "
        "given network interface at once"
    )
    license = "GPL-2.0-or-later"
    homepage = "https://0pointer.de/lennart/projects/ifmetric/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "application"
    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def validate(self):
        # rtnetlink (PF_NETLINK / NETLINK_ROUTE, RTM_GETLINK / RTM_GETROUTE) is a
        # Linux-kernel interface; there is no portable implementation elsewhere.
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"ifmetric needs the Linux rtnetlink routing API, got {self.settings.os}"
            )

    def source(self):
        get(self, **self.conan_data["sources"][self.version], strip_root=True)
        # E490/E543: HMDFS checks sources out with default mode 660, so the
        # Autotools helper scripts lose their execute bits and "sh configure"
        # fails before compiling anything. Restore them for the known helpers
        # only -- a blanket chmod -R +x is forbidden by E490.
        for name in ("configure", "config.guess", "config.sub", "install-sh", "missing", "mkinstalldirs"):
            for root, _dirs, files in os.walk(self.source_folder):
                if name in files:
                    path = os.path.join(root, name)
                    os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Upstream configure was generated by a 2004-era autoconf whose config.sub
        # cannot canonicalise an aarch64 OHOS host, so both triples are explicit.
        tc.configure_args.append("--build=aarch64-unknown-linux-gnu")
        tc.configure_args.append("--host=aarch64-unknown-linux-ohos")
        # Documentation-only tools: configure hard-aborts (AC_MSG_ERROR) when it
        # cannot find lynx, and xmltoman likewise gates the man page rebuild.
        # Neither affects the compiled binary, so both are turned off.
        tc.configure_args.append("--disable-lynx")
        tc.configure_args.append("--disable-xmltoman")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # E011/E114: configure's generated config.status creates its scratch dir
        # with "(umask 077 && mktemp -d ./confstatXXXXXX)". HMDFS forces setgid
        # on new directories, so that yields drwx--S--- which even the owning
        # process cannot write into -- every "config.status: creating ..." step
        # then dies with "Permission denied" and no Makefile is produced.
        # Relaxing the umask keeps the real temp-dir creation intact (precedent:
        # archives/i/iec16022 patches/0003).
        replace_in_file(
            self,
            os.path.join(self.source_folder, "configure"),
            "umask 077",
            "umask 022",
        )
        autotools = Autotools(self)
        autotools.configure()
        # A single job avoids make jobserver/FIFO failures on HMDFS (E074).
        autotools.make(args=["-j1"])
        # Upstream 0.3 ships no test entry point at all: src/Makefile.am declares
        # only "sbin_PROGRAMS = ifmetric" and neither Makefile.am in the tree
        # defines TESTS, check_PROGRAMS or a "check" target, and there is no test
        # directory. Therefore no upstream suite is executed (see notes.md).

    def package(self):
        Autotools(self).install()
        copy(
            self,
            "LICENSE",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "licenses"),
            keep_path=False,
        )

    def package_info(self):
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        # Upstream installs into $(sbindir); Conan's AutotoolsToolchain points
        # sbindir at <package_folder>/bin, but declare both so the tool resolves
        # whichever layout the build produces.
        self.cpp_info.bindirs = ["bin", "sbin"]
        for d in self.cpp_info.bindirs:
            self.runenv_info.prepend_path("PATH", os.path.join(self.package_folder, d))
