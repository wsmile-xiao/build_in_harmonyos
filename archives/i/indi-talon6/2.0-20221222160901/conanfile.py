#!/usr/bin/env python3
"""indi-talon6 — INDI driver for the Talon6 Roll Off Roof controller.

The driver lives in the indi-3rdparty monorepo (subdirectory indi-talon6/) and its
CMakeLists.txt appends "../cmake_modules" to CMAKE_MODULE_PATH, so the whole
repository tree has to be kept (source strip_root=True).

Adaptation points for OHOS (identical to the sibling driver indi-aok
2.0-20221222093242, which was built from the same 2022-12-22 snapshot):
  * indi-3rdparty's own cmake_modules/FindINDI.cmake locates the pre-built
    libindi through the INDI_ROOT hint -> exported from the dependency.
  * Neither the indi-3rdparty tree nor the libnova package ships a finder/config
    package for "Nova", while indi-talon6/CMakeLists.txt requires
    find_package(Nova).  A private NovaConfig.cmake is generated inside the build
    (generators) folder and every path in it comes from the libnova cpp_info (R49).

Upstream tests: none.  indi-talon6/CMakeLists.txt has no enable_testing()/add_test()
and the indi-3rdparty tree ships no test case for this driver, so build() runs no
upstream suite; the packaged artefacts are verified by test_package/check_driver.py.
"""
import os

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get, save


class Inditalon6Conan(ConanFile):
    name = "indi-talon6"
    version = "2.0-20221222160901"
    description = "INDI driver for the Talon6 Roll Off Roof observatory controller"
    license = "LGPL-2.1-or-later"
    homepage = "https://github.com/indilib/indi-3rdparty"
    url = "https://github.com/indilib/indi-3rdparty"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # 与 indi-talon6/CMakeLists.txt 的 find_package(INDI)/find_package(Nova) 对应；
        # 两包均已合入制品仓（libindi 2.2.2.1 / libnova 0.16，conan install 实测可解析）
        self.requires("libindi/2.2.2.1")
        self.requires("libnova/0.16")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = CMakeToolchain(self)

        indi = self.dependencies["libindi"]
        tc.variables["INDI_ROOT"] = indi.package_folder

        nova = self.dependencies["libnova"]
        nova_inc = os.path.join(nova.package_folder, nova.cpp_info.includedirs[0])
        nova_libdir = os.path.join(nova.package_folder, nova.cpp_info.libdirs[0])
        nova_lib = ""
        for name in list(nova.cpp_info.libs) + ["nova", "libnova"]:
            candidate = os.path.join(nova_libdir, "lib%s.a" % name)
            if os.path.exists(candidate):
                nova_lib = candidate
                break
        if not nova_lib:
            raise ConanException("libnova static archive not found in %s" % nova_libdir)

        # indi 头文件链包含 libnova 头（indidome.h -> libastro.h ->
        # <libnova/utility.h>），而 indi-talon6/CMakeLists.txt 只用
        # ${NOVA_LIBRARIES} 链接、并不把 NOVA_INCLUDE_DIRS 加进 include 路径，
        # 故必须显式注入 libnova 头目录（与 libindi 配方注入 fftw 头的既有做法
        # 一致；R33：走 Conan toolchain 参数而非裸 shell 环境变量）。
        tc.extra_cflags.append('-I"%s"' % nova_inc)
        tc.extra_cxxflags.append('-I"%s"' % nova_inc)

        nova_dir = os.path.join(self.generators_folder, "nova")
        save(self, os.path.join(nova_dir, "NovaConfig.cmake"), "\n".join([
            "# Generated by the indi-talon6 conan recipe (see conanfile.py docstring).",
            "set(NOVA_FOUND TRUE)",
            "set(Nova_FOUND TRUE)",
            'set(NOVA_INCLUDE_DIR "%s")' % nova_inc,
            'set(NOVA_INCLUDE_DIRS "%s")' % nova_inc,
            'set(NOVA_LIBRARIES "%s")' % nova_lib,
            "",
        ]))
        tc.variables["Nova_DIR"] = nova_dir

        # INDI 数据目录：FindINDI.cmake 用 find_path 在 INDI_ROOT 下找
        # share/indi（libindi 包内确有 drivers.xml 等），会把 INDI_DATA_DIR 定成
        # **libindi 包的绝对路径**——而驱动的 CMakeLists 用
        # install(FILES ... DESTINATION ${INDI_DATA_DIR})，那样 XML 会被写进
        # 依赖包而不是本包。这里预先把它设为相对路径（find_path 对已定义的变量
        # 直接跳过搜索），使 XML 落入本包 CMAKE_INSTALL_PREFIX 下的 share/indi。
        tc.variables["INDI_DATA_DIR"] = "share/indi"

        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        # 只构建 indi-talon6 子目录（单体仓内其余驱动不参与本包）
        cmake.configure(build_script_folder="indi-talon6")
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        # Only the driver executable and its INDI XML data are packaged.
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.resdirs = ["share"]
        # libindi 以静态优先发布（shared=False），Conan 不会把它的 lib 目录放进运行
        # 环境，而驱动实际链接 libindi 的 .so（libindidriver.so / libindilx200.so /
        # libindiclient.so）。此处声明运行期搜索路径，使 test_package 与下游消费者
        # 能真正加载驱动（同 indi-aok 的处理）。
        self.runenv_info.prepend_path("LD_LIBRARY_PATH",
                                      self.dependencies["libindi"].cpp_info.libdirs[0])
