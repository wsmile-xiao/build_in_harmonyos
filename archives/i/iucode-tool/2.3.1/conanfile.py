#!/usr/bin/env python3
"""Conan recipe for iucode-tool 2.3.1 on HarmonyOS PC.

The upstream utility parses and repackages Intel microcode bundles.  Its
x86-only CPUID scan is disabled on arm64; offline parsing and writing remain
available, while the recipe does not claim Intel kernel-update functionality.
"""
import glob
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    export_conandata_patches,
    get,
    replace_in_file,
)
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class IucodeToolConan(ConanFile):
    name = "iucode-tool"
    version = "2.3.1"
    description = "Tool to manipulate Intel IA32/X86_64 microcode bundles"
    license = "GPL-2.0-only"
    homepage = "https://gitlab.com/iucode-tool/iucode-tool"
    url = "https://gitlab.com/iucode-tool/iucode-tool"

    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    def validate(self):
        # This recipe intentionally targets the HarmonyOS PC profile.  The
        # configure triplet and HMDFS workarounds below are not a generic
        # native-Linux recipe path.
        if str(self.settings.os) != "OHOS":
            raise ConanInvalidConfiguration(
                f"iucode-tool recipe supports OHOS only, got {self.settings.os}"
            )

    def build_requirements(self):
        # The official GitLab archive contains configure.ac/Makefile.am but
        # not autoreconf output.  Keep bootstrap tools in the build context.
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")

    def requirements(self):
        # iucode_tool.c includes GNU Argp.  The OHOS libc may provide the
        # symbol, but not the public header; use the published standalone
        # implementation for a reproducible clean build.
        self.requires("argp-standalone/1.5.0")

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    @staticmethod
    def _relax_private_umask(path):
        if not os.path.isfile(path):
            return
        with open(path, "r", encoding="utf-8", errors="surrogateescape") as f:
            text = f.read()
        updated = text.replace("umask 077", "umask 022")
        if updated != text:
            with open(path, "w", encoding="utf-8", errors="surrogateescape") as f:
                f.write(updated)

    def generate(self):
        # Keep Autotools' temporary files inside the Conan build directory;
        # HarmonyOS /tmp is read-only on the target image.
        # The Conan cache is on HMDFS on the OHOS worker.  Autoconf's
        # config.guess/config.status create temporary files with mktemp;
        # place only those transient files on the writable build workspace.
        tmpdir = os.path.join(
            "/data/storage/el2/base/cache", f"iucode-tool-{self.version}-tmp"
        )
        os.makedirs(tmpdir, exist_ok=True)
        os.environ["TMPDIR"] = tmpdir
        os.environ["TMP"] = tmpdir
        os.environ["TEMP"] = tmpdir

        tc = AutotoolsToolchain(self)
        # The direct CPUID instruction and Linux cpuid device are x86-only.
        # The source fallback preserves offline bundle operations on arm64.
        tc.configure_args.extend(
            [
                "--disable-cpuid-device",
                "--build=aarch64-unknown-linux-ohos",
                "--host=aarch64-unknown-linux-ohos",
            ]
        )
        tc.generate()
        AutotoolsDeps(self).generate()

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)

        # GitLab source archives do not contain generated Autotools files.
        if not os.path.isfile(os.path.join(self.source_folder, "configure")):
            self.output.info("configure is absent; bootstrapping with autoreconf -fi")
            autotools.autoreconf()

        # HMDFS can reject the private temporary directory generated by
        # configure/config.status with umask 077.  This is a generated-file
        # runtime workaround, not a source patch.
        for cfg in glob.glob(
            os.path.join(self.source_folder, "**", "configure"), recursive=True
        ):
            self._relax_private_umask(cfg)
            # Autoconf normally probes the cwd with `pwd`.  HMDFS can lose
            # that probe after a child shell starts, while the shell-maintained
            # PWD remains the canonical Conan build directory.
            replace_in_file(
                self,
                cfg,
                'ac_pwd=`pwd` && test -n "$ac_pwd" &&',
                'ac_pwd=${PWD-} && test -n "$ac_pwd" &&',
            )

        # Preserve the canonical build path for Autoconf's cwd check even if
        # the worker's HMDFS getcwd implementation is unavailable.
        os.environ["PWD"] = self.build_folder
        autotools.configure()
        self._relax_private_umask(os.path.join(self.build_folder, "config.status"))
        autotools.make(args=["-j1"])

    def package(self):
        Autotools(self).install()

    def package_info(self):
        # AutotoolsToolchain maps both upstream sbin_PROGRAMS and bindir to
        # Conan's standard package bin/ directory; no library is exported.
        self.cpp_info.libs = []
        self.cpp_info.bindirs = ["bin"]
