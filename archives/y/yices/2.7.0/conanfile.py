#!/usr/bin/env python3
"""Conan recipe for yices 2.7.0 — SRI's SMT solver.

yices2 (SRI-CSL/yices2) is a C99 SMT solver: libyices plus the
yices/yices-smt2/yices-sat/yices-mkeq binaries.  Custom GNU make build
driven by a configure generated by pure autoconf (no automake/libtool);
the release tarball ships no pre-generated configure, so the recipe
bootstraps it with tool_requires autoconf/2.72 (published in the
artifact repo).  Only hard dependency is GMP (static, from the repo).

Platform notes:
- LD_LIBRARY_PATH is explicitly emptied during build: some CI workers
  carry an ambient LD pointing at /usr/local/lib whose incompatible
  libxml2.so.16 breaks the SDK's lld on every link (CI-021 build
  #48068 — mechanism documented in libodfgen/libabw).
- configure/make get stdin from /dev/null and SHELL/CONFIG_SHELL point
  at bash (toybox sh lacks IFS word splitting).
- Upstream tests: `make test` builds and runs tests/unit (~200 C
  programs against libyices.a); executed during build() with output
  redirected to a file (orphaned test processes holding a pipe would
  otherwise block conan forever — yash lesson), timed per-test by the
  suite itself.
"""

import os
import shlex
import subprocess

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import VirtualBuildEnv
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout

OHOS_SHELL_CANDIDATES = ("/data/service/hnp/bin/bash", "/usr/bin/zsh", "bash")


class YicesConan(ConanFile):
    name = "yices"
    version = "2.7.0"
    description = ("yices - Yices 2 SMT solver: library and command "
                   "line tools (yices, yices-smt2, yices-sat, ...)")
    license = "GPL-3.0-or-later"
    homepage = "https://github.com/SRI-CSL/yices2"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def requirements(self):
        self.requires("gmp/6.3.0")

    def build_requirements(self):
        # Release tarball ships configure.ac only; autoconf (no
        # automake/libtool needed) regenerates configure.
        self.tool_requires("autoconf/2.72")

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"yices is adapted for Linux and OHOS, not {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        # url may arrive as a candidate list (the CI pre-download step
        # rewrites conandata's url into [mirror, official]) — conan's
        # get() handles both shapes natively.
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        VirtualBuildEnv(self).generate()

    def build(self):
        apply_conandata_patches(self)
        build = self.build_folder
        self._copy_tree(self.source_folder, build)

        # Bootstrap configure from configure.ac.  Run autoconf under the
        # SYSTEM perl with an explicit inline env prefix (the conan perl
        # package's XS modules are ABI-broken on-device — Cwd.so fails to
        # relocate with "Perl_my_cxt_init: symbol not found"; apertium
        # precedent).  PERL5LIB must keep autoconf's pure-perl modules.
        # conanbuild re-injects PERL5LIB on self.run, so only an inline
        # override in the command itself is reliable.
        ac = self.dependencies.build["autoconf/2.72"]
        ac_share = os.path.join(ac.package_folder, "share", "autoconf")
        tmpdir = os.path.join(build, ".tmp")
        os.makedirs(tmpdir, exist_ok=True)
        self.run('PERL=perl PERL5LIB="%s" TMPDIR="%s" TMP="%s" TEMP="%s" '
                 'autoconf' % (ac_share, tmpdir, tmpdir, tmpdir),
                 cwd=build, env="conanbuild")

        gmp = self.dependencies["gmp"]
        gmp_lib = os.path.join(gmp.package_folder, "lib", "libgmp.a")
        gmp_inc = os.path.join(gmp.package_folder, "include")

        env = dict(os.environ)
        # lld/libxml2 shield — see class docstring.
        env["LD_LIBRARY_PATH"] = ""
        env["CC"] = self._cc()
        # configure still runs the default AC_CHECK_LIB(gmp) even with
        # --with-static-gmp — make -lgmp resolvable via LDFLAGS/CPPFLAGS.
        gmp_libdir = os.path.join(gmp.package_folder, "lib")
        env["CPPFLAGS"] = f"-I{gmp_inc}"
        env["LDFLAGS"] = f"-L{gmp_libdir} -Wl,-rpath,{gmp_libdir}"
        shell = self._resolve_shell()
        env["SHELL"] = shell
        env["CONFIG_SHELL"] = shell
        # NOTE: no --build/--host flags — configure.ac only calls
        # AC_CANONICAL_BUILD, and an extra --host breaks its
        # make.include naming.  The patched config.guess (patch 0001)
        # recognizes HarmonyOS and yields aarch64-unknown-linux-musl,
        # consistent between configure and the Makefile.
        cmd = (f"{shlex.quote(shell)} ./configure --prefix=/ "
               f"--with-static-gmp={shlex.quote(gmp_lib)} "
               f"--with-static-gmp-include-dir={shlex.quote(gmp_inc)} "
               "< /dev/null")
        completed = subprocess.run(cmd, shell=True, cwd=build, env=env)
        if completed.returncode != 0:
            self._dump_failure_diagnostics(build, env)
            raise ConanException(
                f"configure failed (rc={completed.returncode})")
        # STRIP=true: llvm-strip output is refused by this platform's
        # exec policy (Permission denied on execve; verified with a
        # hello-world: pre-strip runs, llvm-stripped denied).  Keep the
        # binaries unstripped.
        completed = subprocess.run("make -j2 STRIP=true < /dev/null",
                                   shell=True, cwd=build, env=env)
        if completed.returncode != 0:
            self._dump_failure_diagnostics(build, env)
            raise ConanException("make failed")
        self._run_upstream_tests(build, env)

    def _run_upstream_tests(self, build, env):
        """Run upstream's unit tests (tests/unit binaries).

        Note: upstream's `make test` only BUILDS the ~180 unit test
        programs; running them is on us.  Each test binary self-checks
        and its exit code is the verdict.  Output goes to a file, not
        the inherited stdout (orphaned test processes holding a pipe
        block conan forever — yash lesson); per-test timeout backstops
        hangs.
        """
        bindir = None
        # `make test` builds (not runs) the ~180 unit test programs
        test_build_log = os.path.join(build, "unit-build.log")
        with open(test_build_log, "w") as sink:
            tb = subprocess.run("make -j2 test < /dev/null", shell=True,
                                cwd=build, env=env,
                                stdout=sink, stderr=subprocess.STDOUT)
        if tb.returncode != 0:
            self._dump_failure_diagnostics(build, env)
            raise ConanException("make test (unit build) failed")
        # binaries land in build/<triplet>-release/bin/test_*
        for root, _, files in os.walk(build):
            if os.path.basename(root) == "bin" and any(
                    f.startswith("test_") for f in files):
                bindir = root
                break
        if not bindir:
            raise ConanException("unit test binaries not found")
        log = os.path.join(build, "unit-tests.log")
        # Per-test classification: exit 0 = pass; exit !=0 with a
        # "Usage:" line = needs an input file (upstream repo ships no
        # data files or runner for those — honestly counted separately,
        # not as failures); otherwise fail.
        runner = (
            'passed=0; failed=0; needinput=0; failed_names=""; '
            'input_names=""; '
            'for t in test_*; do '
            '  out=$(timeout -s KILL 120 "./$t" 2>&1); rc=$?; '
            '  if [ $rc -eq 0 ]; then passed=$((passed+1)); '
            '  elif echo "$out" | grep -qi "^Usage:"; then '
            '    needinput=$((needinput+1)); input_names="$input_names $t"; '
            '  else failed=$((failed+1)); failed_names="$failed_names $t"; '
            '  fi; '
            'done; '
            'echo "UNIT_RESULT passed=$passed failed=$failed '
            'needs_input=$needinput"; '
            'echo "UNIT_FAILED:$failed_names"; '
            'echo "UNIT_NEEDS_INPUT:$input_names"')
        with open(log, "w") as sink:
            subprocess.run(runner, shell=True, cwd=bindir, env=env,
                           stdout=sink, stderr=subprocess.STDOUT)
        subprocess.run("pkill -9 -f 'tests.*test_' 2>/dev/null; true",
                       shell=True, env=env)
        with open(log, errors="replace") as handle:
            content = handle.read()
        for line in content.splitlines():
            if line.startswith("UNIT_"):
                self.output.info("[upstream-tests] " + line)

    def package(self):
        build = self.build_folder
        inst = os.path.join(build, "inst")
        env = dict(os.environ)
        env["LD_LIBRARY_PATH"] = ""
        env["SHELL"] = self._resolve_shell()
        completed = subprocess.run(
            f"make install STRIP=true DESTDIR={shlex.quote(inst + os.sep)} "
            "< /dev/null",
            shell=True, cwd=build, env=env)
        if completed.returncode != 0:
            raise ConanException(
                f"make install failed (rc={completed.returncode})")
        copy(self, "*.h", src=os.path.join(inst, "include"),
             dst=os.path.join(self.package_folder, "include"),
             keep_path=True)
        copy(self, "*.a", src=os.path.join(inst, "lib"),
             dst=os.path.join(self.package_folder, "lib"),
             keep_path=False)
        copy(self, "yices*", src=os.path.join(inst, "bin"),
             dst=os.path.join(self.package_folder, "bin"),
             keep_path=False)
        copy(self, "LICENSE.txt", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"),
             keep_path=False)

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "yices")
        self.cpp_info.set_property("cmake_target_name", "yices::yices")
        self.cpp_info.set_property("pkg_config_name", "yices")
        self.cpp_info.libs = ["yices"]

    # ── helpers ─────────────────────────────────────────────────────────

    def _cc(self):
        compilers = self.conf.get("tools.build:compiler_executables",
                                  default=None)
        if compilers:
            if isinstance(compilers, str):
                import json
                try:
                    compilers = json.loads(compilers)
                except ValueError:
                    compilers = {}
            if compilers.get("c"):
                return compilers["c"]
        return "clang"

    def _resolve_shell(self):
        for candidate in OHOS_SHELL_CANDIDATES:
            if os.path.isfile(candidate):
                return candidate
        return "/bin/sh"

    def _copy_tree(self, src, dst):
        import shutil
        shutil.copytree(src, dst, dirs_exist_ok=True, symlinks=True)

    def _dump_failure_diagnostics(self, directory, environment):
        self.output.info("---- ohos diagnostics: environment ----")
        for name in ("CC", "CFLAGS", "CPPFLAGS", "LDFLAGS", "LDLIBS",
                     "TMPDIR", "LD_LIBRARY_PATH", "PATH", "SHELL"):
            if name in environment:
                self.output.info(f"{name}={environment[name]}")
        config_log = os.path.join(directory, "config.log")
        if os.path.isfile(config_log):
            with open(config_log, errors="replace") as handle:
                lines = handle.readlines()
            for line in lines[-25:]:
                self.output.info(line.rstrip())
