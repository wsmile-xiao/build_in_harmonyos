#!/usr/bin/env python3
"""Conan recipe for yazpp 1.9.2 (HarmonyOS PC adaptation).

Builds the static YAZ++ (libyazpp) C++ bindings library on top of the
packaged yaz/5.37.3.  The yaz package's own ``yaz-config`` bakes an empty
prefix ("/") and stale absolute paths (E355 family), so this recipe writes
a corrected ``yaz-config`` shim into its private build folder and points
configure at it via ``--with-yaz`` (R49: dependency injection through a
build-folder private prefix, no shared system paths).
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.build import can_run
from conan.tools.env import VirtualRunEnv
from conan.tools.files import (
    apply_conandata_patches,
    export_conandata_patches,
    get,
)
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class YazppConan(ConanFile):
    name = "yazpp"
    version = "1.9.2"
    description = "YAZ++: C++ bindings for the YAZ Z39.50/SRU toolkit"
    license = "BSD-3-Clause"
    homepage = "https://www.indexdata.com/resources/software/yazpp/"
    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("yazpp supports Linux and OHOS")

    def config_options(self):
        if self.options.shared:
            del self.options.fPIC

    def requirements(self):
        self.requires("yaz/5.37.3", transitive_headers=True, transitive_libs=True)

    def export_sources(self):
        export_conandata_patches(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def layout(self):
        basic_layout(self, src_folder=".")
        self.folders.build = "."

    def generate(self):
        # NOTE: no AutotoolsDeps here — it would export LIBS=-lyaz -lyaz_icu
        # -lyaz_server ... from yaz's package metadata into the build env;
        # libtool then resolves libyaz_icu.la whose dependency_libs embed the
        # broken baked '//lib/libyaz.la' path and dies.  The yaz-config shim
        # below supplies every flag configure needs (R49 private prefix).
        tc = AutotoolsToolchain(self)
        # The bundled config.guess/config.sub (2024 vintage) are taught the
        # HarmonyOS triplet by patches/000x, so configure detects the host
        # natively (no --build/--host bypass, E007 forbid_1).
        tc.extra_cxxflags.append("-std=c++14")
        tc.generate()

        # yaz-config shim: the yaz package's script bakes prefix="/" and
        # stale absolute libxml2 paths; regenerate it against the actual
        # dependency include/lib dirs inside our private build folder.
        yaz = self.dependencies["yaz"]
        xml = self.dependencies["libxml2"]
        yaz_version = str(yaz.ref.version)
        inc_flags = " ".join(
            "-I%s" % p
            for p in list(yaz.cpp_info.includedirs) + list(xml.cpp_info.includedirs)
        )
        lib_flags = " ".join(
            "-L%s" % p
            for p in list(yaz.cpp_info.libdirs) + list(xml.cpp_info.libdirs)
        )
        shim_dir = os.path.join(self.build_folder, "yazconf-shim", "bin")
        os.makedirs(shim_dir, exist_ok=True)
        shim = os.path.join(shim_dir, "yaz-config")
        with open(shim, "w") as f:
            f.write(
                "#!/bin/sh\n"
                "# Generated by the yazpp conan recipe: emits flags for the\n"
                "# conan-packaged yaz/libxml2 instead of the baked prefix=/\n"
                'INC="%s"\n'
                'LIBSFLAGS="%s"\n'
                'YAZVER="%s"\n'
                'case " $* " in\n'
                "  *cflags*)\n"
                '    echo "-DYAZ_POSIX_THREADS=1 -DYAZ_HAVE_XML2=1 $INC" ;;\n'
                "  *lalibs*|*libs*)\n"
                '    echo "$LIBSFLAGS -lyaz -lxml2 -lm -lpthread" ;;\n'
                "  *)\n"
                '    echo "$YAZVER" ;;\n'
                "esac\n" % (inc_flags, lib_flags, yaz_version)
            )
        os.chmod(shim, 0o755)
        self.yaz_shim_dir = shim_dir

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure(args=["--with-yaz=%s" % self.yaz_shim_dir])
        autotools.make(args=["-j1"])
        if can_run(self):
            self.run(
                "make -C src check -j1 TESTS=; status=$?; "
                "if [ $status -ne 0 ]; then "
                "find src -maxdepth 2 -type f -name '*.log' -print -exec cat {} \\;; "
                "fi; exit $status",
                env="conanbuild",
            )
            with VirtualRunEnv(self).vars().apply():
                self.run(
                    "make -C src check -j1; status=$?; "
                    "if [ $status -ne 0 ]; then "
                    "find src -maxdepth 2 -type f -name 'test-suite.log' -print -exec cat {} \\;; "
                    "fi; exit $status",
                    env="conanbuild",
                )

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        # Drop the libtool archives: they bake absolute libdir paths and
        # break downstream libtool probing (checklist #6).
        libdir = os.path.join(self.package_folder, "lib")
        if os.path.isdir(libdir):
            for name in os.listdir(libdir):
                if name.endswith(".la"):
                    os.remove(os.path.join(libdir, name))

    def package_info(self):
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libdirs = ["lib"]
        self.cpp_info.libs = ["yazpp"]
        self.cpp_info.set_property("cmake_file_name", "yazpp")
        self.cpp_info.set_property("cmake_target_name", "yazpp::yazpp")
