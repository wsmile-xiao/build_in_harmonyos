from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches, copy
from conan.tools.gnu import AutotoolsToolchain
from conan.tools.layout import basic_layout
import os


class TimblConan(ConanFile):
    name = "timbl"
    version = "6.1"
    description = "Tilburg Memory-Based Learner (TiMBL) - efficient tool for shallow parsing and memory-based learning"
    license = "GPL-3.0"
    homepage = "https://github.com/LanguageMachines/timbl"
    url = "https://github.com/LanguageMachines/timbl"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        if not self.options.shared:
            tc.configure_args.append("--enable-static")
            tc.configure_args.append("--disable-shared")
        tc.generate()

    def _read_build_env(self):
        """Read compiler settings from conanbuild.conf generated by AutotoolsToolchain."""
        env = {}
        conf_path = os.path.join(self.build_folder, "conanbuild.conf")
        if not os.path.exists(conf_path):
            conf_path = os.path.join(self.generators_folder, "conanbuild.conf")
        if os.path.exists(conf_path):
            with open(conf_path) as f:
                for line in f:
                    line = line.strip()
                    if "=" in line and not line.startswith("["):
                        key, val = line.split("=", 1)
                        env[key.strip()] = val.strip()
        return env

    def _generate_config_h(self, build_dir):
        """Generate a minimal config.h that would normally be created by configure."""
        config_h = """\
/* config.h - generated by Conan build (manual, bypassing autotools) */
#ifndef CONFIG_H
#define CONFIG_H

/* Package identification */
#define PACKAGE "timbl"
#define PACKAGE_NAME "Timbl"
#define PACKAGE_VERSION "6.1"
#define VERSION "6.1"
#define PACKAGE_STRING "Timbl 6.1"
#define PACKAGE_BUGREPORT "timbl@uvt.nl"
#define VERSION_ID "6.1"

/* Standard headers */
#define STDC_HEADERS 1
#define HAVE_UNISTD_H 1
#define HAVE_SYS_TYPES_H 1

/* Socket and network functions */
#define HAVE_GETADDRINFO 1
#define HAVE_CONNECT 1
#define HAVE_ACCEPT 1
#define HAVE_GETHOSTBYNAME 1
#define HAVE_SOCKET 1

/* socklen_t type - use the standard definition */
#define HAVE_SOCKLEN_T 1
#define TIMBL_SOCKETLEN_T socklen_t

/* Server mode with pthreads */
#define HAVE_PTHREAD 1
#define HAVE_LIBPTHREAD 1

#endif /* CONFIG_H */
"""
        config_path = os.path.join(build_dir, "config.h")
        with open(config_path, "w") as f:
            f.write(config_h)

    def build(self):
        apply_conandata_patches(self)
        src = self.source_folder
        include = os.path.join(src, "include")
        build_dir = self.build_folder

        # Generate config.h (normally done by configure)
        self._generate_config_h(build_dir)

        # Read compiler settings from conanbuild.conf
        env = self._read_build_env()
        cxx = env.get("CXX", "")
        if not cxx:
            try:
                comp_execs = self.conf.get("tools.build:compiler_executables", default={}) or {}
                cxx = comp_execs.get("cpp", "clang++")
            except Exception:
                cxx = "clang++"

        cxxflags = env.get("CXXFLAGS", "-fPIC -O2")
        # OHOS needs sys/time.h for timeval type used in TimblExperiment.h
        # Also need iomanip for setw/setfill used in IBprocs.cxx and others
        cxxflags = cxxflags + " -include sys/time.h -include iomanip"
        ldflags = env.get("LDFLAGS", "")
        ar = env.get("AR", "llvm-ar")

        # Library source files (from src/Makefile.am)
        lib_sources = [
            "BestArray.cxx", "CVExperiment.cxx", "Choppers.cxx",
            "CommandLine.cxx", "Common.cxx", "GetOptClass.cxx",
            "IBprocs.cxx", "IBtree.cxx", "IGExperiment.cxx",
            "Instance.cxx", "LOOExperiment.cxx", "LogBuffer.cxx",
            "LogStream.cxx", "MBLClass.cxx", "MsgClass.cxx",
            "ServerProcs.cxx", "SocketBasics.cxx", "Statistics.cxx",
            "StringOps.cxx", "TRIBLExperiments.cxx", "Testers.cxx",
            "TimblAPI.cxx", "TimblExperiment.cxx", "Tree.cxx",
            "Types.cxx", "neighborSet.cxx"
        ]

        # Compile all library source files
        # Include build_dir for config.h, include/ for timbl headers
        objs = []
        for s in lib_sources:
            obj = s.replace(".cxx", ".o")
            src_file = os.path.join(src, "src", s)
            self.run(f'"{cxx}" {cxxflags} -I"{include}" -I"{build_dir}" -c "{src_file}" -o "{obj}"')
            objs.append(obj)

        # Create static library
        objs_str = " ".join(f'"{o}"' for o in objs)
        self.run(f'{ar} rcs libTimbl.a {objs_str}')

        # Compile binaries (Timbl and TimblClient)
        timbl_src = os.path.join(src, "src", "Timbl.cxx")
        timblclient_src = os.path.join(src, "src", "TimblClient.cxx")
        self.run(f'"{cxx}" {cxxflags} -I"{include}" -I"{build_dir}" "{timbl_src}" -o Timbl -L. -lTimbl {ldflags} -lpthread')
        self.run(f'"{cxx}" {cxxflags} -I"{include}" -I"{build_dir}" "{timblclient_src}" -o TimblClient -L. -lTimbl {ldflags} -lpthread')

    def package(self):
        # Copy library
        copy(self, "libTimbl.a", src=self.build_folder, dst=os.path.join(self.package_folder, "lib"))
        # Copy binaries
        copy(self, "Timbl", src=self.build_folder, dst=os.path.join(self.package_folder, "bin"))
        copy(self, "TimblClient", src=self.build_folder, dst=os.path.join(self.package_folder, "bin"))
        # Copy headers (preserving include/timbl/ structure)
        copy(self, "*.h", src=os.path.join(self.source_folder, "include"), dst=os.path.join(self.package_folder, "include"))

    def package_info(self):
        self.cpp_info.libs = ["Timbl"]
        self.cpp_info.bindirs = ["bin"]
        if self.settings.os in ("Linux", "OHOS"):
            self.cpp_info.system_libs = ["pthread"]
