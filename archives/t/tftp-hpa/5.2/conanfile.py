#!/usr/bin/env python3
"""Conan recipe for tftp-hpa 5.2 — TFTP client and server (H. Peter Anvin).

tftp-hpa is the HP Labs TFTP suite: a TFTP client (tftp) and TFTP
daemon (tftpd/in.tftpd) for Unix systems.

OHOS adaptations:
  - configure: fix mktemp setgid issue (OHOS inherits setgid from parent dir;
    umask 077 turns setgid+execute into setgid-only, blocking file creation)
  - tftp/tftp.c: declare 'toplevel' as extern (duplicate symbol with lld linker)
  - aconfig.h.in: regenerated by autoheader (keeps timestamp consistent)
"""
from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain


class TftpHpaConan(ConanFile):
    name = "tftp-hpa"
    version = "5.2"
    description = "TFTP client and server (tftp-hpa by H. Peter Anvin)"
    license = "BSD-4-Clause"  # BSD with advertising clause
    homepage = "https://www.kernel.org/pub/software/network/tftp/tftp-hpa/"


    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        # tftp-hpa requires in-source build (Makefile in source root)
        self.folders.source = "."
        self.folders.build = "."
        self.folders.generators = "."

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        # tftp-hpa uses INSTALLROOT instead of DESTDIR for staging install
        autotools.install(args=[f"INSTALLROOT={self.package_folder}"])

    def package_info(self):
        self.cpp_info.bindirs = ["bin", "sbin"]
