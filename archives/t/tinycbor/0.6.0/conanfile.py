#!/usr/bin/env python3
"""Conan recipe for tinycbor 0.6.0 — CBOR (RFC 7049) encoding/decoding library.

Build system: plain Makefile (no configure script; `make configure` runs
feature probes into .config, then `make` builds static + shared lib and the
cbordump tool). No external dependency other than libm.
"""
import os

from conan import ConanFile
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout
from conan.tools.env import VirtualBuildEnv


class TinycborConan(ConanFile):
    name = "tinycbor"
    version = "0.6.0"
    description = "Tiny but powerful CBOR (RFC 7049) encoding/decoding library"
    license = "MIT"
    homepage = "https://github.com/intel/tinycbor"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # Inject CC/CXX/AR/RANLIB from the Conan toolchain into the build env.
        VirtualBuildEnv(self).generate()

    def build(self):
        apply_conandata_patches(self)
        # tinycbor's Makefile defaults `BUILD_SHARED` from /bin/sh ELF probing;
        # pin it explicitly to the Conan option so static/shared is reproducible.
        shared = "1" if self.options.shared else "0"
        static = "0" if self.options.shared else "1"
        make_args = (f"BUILD_STATIC={static} BUILD_SHARED={shared} "
                     "-j1 LDFLAGS=")
        # With basic_layout, self.run() executes in build_folder, while the
        # Makefile lives in source_folder — cd there first (same as abcm2ps).
        src = self.source_folder.replace("\\", "/")
        self.run(f"cd '{src}' && make configure {make_args}", env="conanbuild")
        self.run(f"cd '{src}' && make {make_args}", env="conanbuild")

    def package(self):
        # The upstream `install` rule shells out to the `install` binary, which
        # the OHOS sysroot does not ship; install artifacts manually.
        inc_dir = os.path.join(self.package_folder, "include", "tinycbor")
        lib_dir = os.path.join(self.package_folder, "lib")
        bin_dir = os.path.join(self.package_folder, "bin")
        pkg_dir = os.path.join(self.package_folder, "lib", "pkgconfig")
        os.makedirs(inc_dir, exist_ok=True)
        os.makedirs(lib_dir, exist_ok=True)
        os.makedirs(bin_dir, exist_ok=True)
        os.makedirs(pkg_dir, exist_ok=True)

        for hdr in ("cbor.h", "cborjson.h", "tinycbor-version.h"):
            copy(self, hdr, os.path.join(self.source_folder, "src"), inc_dir)
        if self.options.shared:
            copy(self, "libtinycbor.so*", os.path.join(self.source_folder, "lib"), lib_dir)
        else:
            copy(self, "libtinycbor.a", os.path.join(self.source_folder, "lib"), lib_dir)
        copy(self, "cbordump", os.path.join(self.source_folder, "bin"), bin_dir)
        # tinycbor.pc is regenerated by the Makefile with the build-time prefix;
        # write a package-relative .pc so pkg-config resolves consumers.
        pc = os.path.join(pkg_dir, "tinycbor.pc")
        with open(pc, "w", encoding="utf-8") as f:
            f.write(f"""prefix={self.package_folder}
exec_prefix=${{prefix}}
libdir=${{prefix}}/lib
includedir=${{prefix}}/include

Name: tinycbor
Description: Tiny but powerful CBOR (RFC 7049) encoding/decoding library
Version: {self.version}
Libs: -L${{libdir}} -ltinycbor
Cflags: -I${{includedir}}
""")

    def package_info(self):
        self.cpp_info.libs = ["tinycbor"]
        self.cpp_info.system_libs = ["m"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.bindirs = ["bin"]
        self.runenv_info.prepend_path("PATH", os.path.join(self.package_folder, "bin"))