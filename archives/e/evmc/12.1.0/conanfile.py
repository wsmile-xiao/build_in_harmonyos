#!/usr/bin/env python3
"""Conan recipe — evmc 12.1.0

EVMC: Ethereum Client-VM Connector API. Header-only public API (evmc/evmc.h)
plus four buildable static components (instructions, loader, tooling,
mocked_host) and two CLI tools (evmc, evmc-vmtester).

Upstream is a plain CMake project whose *runtime* test suite (146 CTest cases)
must execute on the target: the vmtester and the dynamic-loading example
dlopen() a VM shared library at run time, so cross-building alone is not enough
to claim a pass rate. Everything is therefore built for aarch64 and executed
under qemu with the OHOS musl run root.
"""
import os
import shutil

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.build import cross_building
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.files import (
    apply_conandata_patches,
    export_conandata_patches,
    get,
)

required_conan_version = ">=2.0"


# CMakeDeps emits a lowercase gtest-config.cmake exposing the target
# gtest::gtest, while EVMC's upstream CMakeLists (previously fed by Hunter)
# calls find_package(GTest CONFIG REQUIRED) and links GTest::gtest /
# GTest::gtest_main. This shim bridges the two naming schemes and additionally
# exports GTest::gtest_main, backed by the libgtest_main.a archive that the
# gtest Conan package does install but does not list in cpp_info.libs.
_GTEST_SHIM = """\
# Generated by the evmc Conan recipe — bridges Conan's lowercase gtest config
# package to the uppercase GTest:: names expected by EVMC's upstream
# CMakeLists (they came from Hunter).
if(NOT TARGET gtest::gtest)
    include("${CMAKE_CURRENT_LIST_DIR}/gtest-config.cmake")
endif()

if(NOT TARGET GTest::gtest)
    add_library(GTest::gtest INTERFACE IMPORTED)
    set_target_properties(GTest::gtest PROPERTIES
        INTERFACE_LINK_LIBRARIES gtest::gtest)
endif()

if(NOT TARGET GTest::gtest_main)
    add_library(GTest::gtest_main INTERFACE IMPORTED)
    set_target_properties(GTest::gtest_main PROPERTIES
        INTERFACE_LINK_LIBRARIES "gtest::gtest;@GTEST_MAIN_LIB@")
endif()

set(GTest_FOUND TRUE)
set(GTEST_FOUND TRUE)
set(GTest_VERSION_STRING "@GTEST_VERSION@")
"""

_GTEST_SHIM_VERSION = """\
# Deliberately reports no version: claiming PACKAGE_VERSION_EXACT/COMPATIBLE
# unconditionally would silently satisfy any find_package(GTest <ver> CONFIG)
# against whatever gtest version this recipe happens to require. Upstream only
# calls find_package(GTest CONFIG REQUIRED) without a version, so an unversioned
# config package is both correct and honest.
set(PACKAGE_VERSION "@GTEST_VERSION@")
"""


class EvmcConan(ConanFile):
    name = "evmc"
    version = "12.1.0"
    description = "Ethereum Client-VM Connector API"
    license = "Apache-2.0"
    homepage = "https://github.com/ethereum/evmc"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    exports_sources = "patches/*"

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        cmake_layout(self)

    def requirements(self):
        # GTest and CLI11 are upstream's build/test-time dependencies, obtained
        # by Hunter upstream. Hunter is a network-only bootstrap package manager
        # and cannot run in the offline OHOS cross-build, so they come from
        # Conan (see patch 0001). Both stay regular requirements so that the
        # generated CMakeDeps packages are present at configure time.
        self.requires("gtest/1.17.0")
        self.requires("cli11/2.7.2")

    def source(self):
        get(self, **self.conan_data["sources"][self.version], strip_root=True)

    def generate(self):
        deps = CMakeDeps(self)
        # Export the uppercase target names EVMC's CMakeLists asks for. The
        # lowercase gtest config package is still produced and is what the
        # GTest shim includes.
        deps.set_property("cli11", "cmake_file_name", "CLI11")
        deps.set_property("cli11", "cmake_target_name", "CLI11::CLI11")
        deps.set_property("gtest", "cmake_file_name", "gtest")
        deps.set_property("gtest", "cmake_target_name", "gtest::gtest")
        deps.generate()

        # The GTest shim is written straight into the CMakeDeps generator
        # folder, which Conan already puts on CMAKE_PREFIX_PATH via the
        # toolchain. find_package(GTest CONFIG) then resolves GTestConfig.cmake
        # from there and gets both the GTest:: names and, through the included
        # lowercase package, the real imported libraries.
        gtest_main = self._gtest_main_archive()
        gtest_version = str(self.dependencies["gtest"].ref.version)
        shim = self.generators_folder
        self._write_template(
            os.path.join(shim, "GTestConfig.cmake"),
            _GTEST_SHIM,
            GTEST_MAIN_LIB=gtest_main,
            GTEST_VERSION=gtest_version,
        )
        self._write_template(
            os.path.join(shim, "GTestConfigVersion.cmake"),
            _GTEST_SHIM_VERSION,
            GTEST_VERSION=gtest_version,
        )

        tc = CMakeToolchain(self)
        # These must be *cache* definitions, not toolchain "variables". The
        # upstream CMakeLists declares them with option(), and option() only
        # honours a pre-existing entry when that entry was itself created as a
        # cache entry of the same kind. Conan's tc.variables emits
        # `set(X ... CACHE STRING ...)`, which option() then discards in favour
        # of its own default, silently turning the test suite back off.
        tc.cache_variables["HUNTER_ENABLED"] = "OFF"
        # The whole test suite (unittests + tools + examples + vmtester) is what
        # rule 4 asks to execute, so all three switches are on. EVMC_TOOLS must
        # be ON as well: test/vmtester/CMakeLists.txt calls evmc_add_vm_test(),
        # which FATAL_ERRORs unless the evmc::evmc-vmtester target exists, and
        # that target is only created under tools/.
        tc.cache_variables["EVMC_TESTING"] = "ON"
        tc.cache_variables["EVMC_TOOLS"] = "ON"
        tc.cache_variables["EVMC_EXAMPLES"] = "ON"
        # Make sure the config packages win over any system find-module for
        # GTest/CLI11 on the build host.
        tc.cache_variables["CMAKE_FIND_PACKAGE_PREFER_CONFIG"] = "ON"
        # BUILD_SHARED_LIBS and the PIC setting are driven by the recipe
        # options, so they stay in the regular variables block.
        tc.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        tc.variables["CMAKE_POSITION_INDEPENDENT_CODE"] = "ON" if self.options.fPIC else "OFF"
        tc.generate()

    @staticmethod
    def _write_template(path, template, **values):
        """Render a template using @NAME@ placeholders.

        str.format() is unusable here because the generated CMake files contain
        ${...} variable references of their own.
        """
        text = template
        for key, value in values.items():
            text = text.replace("@{}@".format(key), str(value))
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)

    def _gtest_main_archive(self):
        """Absolute path of libgtest_main.a shipped by the gtest Conan package.

        The gtest recipe installs gtest_main but declares only `gtest` in
        cpp_info.libs, so CMakeDeps never emits a gtest::gtest_main target.
        EVMC's unittests link GTest::gtest_main, hence the shim has to point at
        the archive directly.
        """
        dep = self.dependencies["gtest"]
        libdirs = list(dep.cpp_info.libdirs) or ["lib"]
        searched = []
        for libdir in libdirs:
            for name in ("libgtest_main.a", "gtest_main.lib", "libgtest_main.so"):
                candidate = os.path.join(dep.package_folder, libdir, name)
                searched.append(candidate)
                if os.path.isfile(candidate):
                    return candidate.replace("\\", "/")
        raise ConanException(
            "gtest_main library not found in the gtest package; searched: %s" % searched
        )

    def _emulator(self):
        """The CMAKE_CROSSCOMPILING_EMULATOR configured for this build, if any.

        The ohos-aarch64-run profile wires up qemu together with the OHOS musl
        run root; the CI profile (ohos-aarch64) does not, because the CI worker
        *is* an OHOS aarch64 machine and executes the target binaries natively
        (ci/conan/build_and_test.sh relies on exactly that for its L2 gate,
        which runs `"$bin_file" --version` directly).
        """
        extra = self.conf.get(
            "tools.cmake.cmaketoolchain:extra_variables", default={}
        )
        emulator = extra.get("CMAKE_CROSSCOMPILING_EMULATOR")
        if not emulator:
            return None
        return emulator if isinstance(emulator, str) else ";".join(emulator)

    def _native_target_execution(self):
        """Whether the target binaries can run directly on this build machine.

        can_run() is not usable as the gate here: it is False whenever
        settings.os is OHOS, because OHOS is never the os of the machine running
        Conan -- including on the CI workers, which *are* OHOS aarch64 boxes and
        execute the freshly built target binaries natively. ci/conan/
        build_and_test.sh depends on exactly that for its L2 gate, which runs
        `"$bin_file" --version` on the built artifact with no emulator.

        So the decision is made from configuration plus a real execution probe:
          * a configured CMAKE_CROSSCOMPILING_EMULATOR means the caller already
            provided a way to run target binaries (handled before this method);
          * otherwise, when host and build profiles agree (cross_building() is
            False -- the CI passes the same profile to -pr:h and -pr:b), the
            target binaries are meant to run on this machine, which is verified
            by actually executing an already-built one rather than assumed.
        A genuine cross-build (different host/build profiles) with no emulator
        stays fail-closed, so no pass rate is ever claimed without being measured.
        """
        if cross_building(self):
            return False
        probe = self._built_probe_binary()
        if not probe:
            return False
        try:
            self.run('"{}" --version'.format(probe), ignore_errors=False)
        except ConanException:
            return False
        return True

    def _built_probe_binary(self):
        """A freshly built target executable used to probe native execution.

        evmc-tool is built whenever EVMC_TOOLS=ON and its --version needs no
        arguments, no VM shared library and no host environment, so it is a
        safe, side-effect-free probe.
        """
        for root, _dirs, files in os.walk(self.build_folder):
            for name in ("evmc", "evmc-tool"):
                candidate = os.path.join(root, name)
                if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
                    return candidate
        return None

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

        # Upstream CTest suite, executed for the real pass rate (rule 4).
        # Registered tests: 146 -- 115 evmc/unittests/, 14 evmc/evmc-tool/,
        # 9 evmc/vmtester/, 6 evmc/cmake_packge/, 2 evmc/examples/. These are the
        # counts of registered CTest cases measured from the run; see notes.md
        # and evidence/ for the full breakdown and the measured result.
        # Order matters: an emulator (when present) and native execution are
        # both real execution paths that yield a measured pass rate. Only a
        # genuine cross-build with no emulator is refused, and even then only
        # unless the caller explicitly opts out.
        if self._emulator() or self._native_target_execution():
            self._run_upstream_tests()
        elif self._allow_untested():
            # Explicit opt-in only: accepting a build with no measured pass rate
            # must never be the silent default, otherwise a green build would
            # claim coverage that was never produced.
            self.output.warning(
                "EVMC_ALLOW_UNTESTED is set: no emulator and no native target "
                "execution, upstream ctest suite NOT executed -- no pass rate "
                "was measured"
            )
        else:
            raise ConanException(
                "the target binaries cannot be executed here: this is a "
                "cross-build with no CMAKE_CROSSCOMPILING_EMULATOR configured, "
                "so the upstream ctest suite cannot run and no real pass rate "
                "can be measured. Build with the ohos-aarch64-run profile, or "
                "set EVMC_ALLOW_UNTESTED=1 to explicitly accept a build with no "
                "measured pass rate."
            )

    @staticmethod
    def _allow_untested():
        """Whether the caller explicitly accepted a build without test results.

        An environment variable is used rather than a custom Conan conf because
        Conan 2 rejects confs that are not registered in the global
        configuration (`conan config list`), and registering one would impose a
        machine-wide setting for what is a per-invocation decision.
        """
        return os.environ.get("EVMC_ALLOW_UNTESTED", "").strip().lower() in (
            "1",
            "true",
            "yes",
        )

    def _ctest_build_dir(self):
        """Directory holding the CTestTestfile.cmake generated by the build.

        cmake_layout() puts the build tree under <build_folder>/<build_type>,
        so the exact location is discovered rather than assumed.
        """
        for root, _dirs, files in os.walk(self.build_folder):
            if "CTestTestfile.cmake" in files:
                return root
        raise ConanException(
            "no CTestTestfile.cmake under %s: the upstream test suite was not "
            "configured (check EVMC_TESTING/EVMC_TOOLS)" % self.build_folder
        )

    def _run_upstream_tests(self):
        # ctest is invoked directly (not through cmake.test()) so that the
        # arguments reach ctest itself: cmake.test() forwards its extra
        # arguments to `cmake --build`, where an unquoted `|` inside a regex is
        # consumed by /bin/sh as a pipe.
        #
        # ctest is looked up next to the cmake that Conan used, because the OHOS
        # SDK ships its own cmake/ctest pair (the system ctest is unrelated and
        # may not exist on the build host).
        ctest = "ctest"
        cmake_program = self.conf.get("tools.cmake:cmake_program", default="")
        if cmake_program:
            candidate = os.path.join(os.path.dirname(cmake_program), "ctest")
            if os.path.isfile(candidate):
                ctest = candidate
        test_dir = self._ctest_build_dir()
        self.output.info("ctest dir: %s" % test_dir)
        self.run(
            '"{}" --test-dir "{}" --output-on-failure -j1'.format(ctest, test_dir)
        )

    def package(self):
        cmake = CMake(self)
        cmake.install()
        # Upstream's own lib/cmake/evmc/ files are dropped: Conan's CMakeDeps
        # generates the config package for consumers, and keeping both would put
        # two evmcConfig.cmake files on CMAKE_PREFIX_PATH.
        shutil.rmtree(os.path.join(self.package_folder, "lib", "cmake"), ignore_errors=True)

    def package_info(self):
        # EVMC's public surface is header-only (evmc::evmc / evmc::evmc_cpp are
        # INTERFACE targets upstream); the three static archives carry the
        # optional helpers. Conan models this as components so a consumer can
        # depend on exactly the pieces it needs.
        self.cpp_info.set_property("cmake_file_name", "evmc")
        self.cpp_info.set_property("cmake_target_name", "evmc::evmc")

        self.cpp_info.components["headers"].set_property(
            "cmake_target_name", "evmc::evmc"
        )
        self.cpp_info.components["headers"].libs = []

        self.cpp_info.components["cpp"].set_property("cmake_target_name", "evmc::evmc_cpp")
        self.cpp_info.components["cpp"].libs = []
        self.cpp_info.components["cpp"].requires = ["headers"]

        self.cpp_info.components["loader"].set_property(
            "cmake_target_name", "evmc::loader"
        )
        self.cpp_info.components["loader"].libs = ["evmc-loader"]
        self.cpp_info.components["loader"].system_libs = ["dl"]
        self.cpp_info.components["loader"].requires = ["headers"]

        self.cpp_info.components["instructions"].set_property(
            "cmake_target_name", "evmc::instructions"
        )
        self.cpp_info.components["instructions"].libs = ["evmc-instructions"]
        self.cpp_info.components["instructions"].requires = ["headers"]

        self.cpp_info.components["tooling"].set_property(
            "cmake_target_name", "evmc::tooling"
        )
        # Upstream's lib/tooling/CMakeLists.txt is the only one of the four
        # add_library() calls that does not set OUTPUT_NAME, so the archive is
        # installed as plain libtooling.a -- declaring "evmc-tooling" here makes
        # CMakeDeps fail with "Library 'evmc-tooling' not found in package".
        self.cpp_info.components["tooling"].libs = ["tooling"]
        self.cpp_info.components["tooling"].requires = ["cpp", "mocked_host"]

        self.cpp_info.components["mocked_host"].set_property(
            "cmake_target_name", "evmc::mocked_host"
        )
        self.cpp_info.components["mocked_host"].libs = []
        self.cpp_info.components["mocked_host"].requires = ["cpp"]
