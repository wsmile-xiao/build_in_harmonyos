#!/usr/bin/env python3
"""Conan recipe for exim 4.99.5 — Makefile project (custom build system).

Exim is the Internet mail transfer agent (MTA). It is a set of command-line
binaries (the exim MTA plus utilities such as exigrep, exiqgrep, eximstats,
exim_dbmbuild, exim_dumpdb, exim_fixdb, exim_lock). This recipe builds exim
and installs the binaries and the default runtime configuration file.

The exim build system is a hand-written Makefile: there is no configure
script. A `Local/Makefile` site configuration is generated by this recipe's
generate() step, then `make` (R9: -j1) builds and `make install` deploys.

Adaptations for HarmonyOS (OHOS) aarch64 are recorded in notes.md:
  - scripts/os-type maps `uname -s` == "HarmonyOS" to the "OHOS" os name
    (new OS file set OS/{Makefile,os.h,os.c}-OHOS, derived from Linux).
  - OHOS libc does not export the legacy `_res` resolver-state global nor
    `__res_state()`; os.c-OHOS provides a static resolver state and the
    os_get_dns_resolver_res() accessor (OS_GET_DNS_RESOLVER_RES defined).
  - OHOS NDK ships no <linux/ip.h>, so struct ip_options is incomplete;
    NO_IP_OPTIONS is defined (and GLIBC_IP_OPTIONS undefined) to skip the
    deprecated IPv4 source-route logging path.
"""
import os

from conan import ConanFile
from conan.tools.env import Environment
from conan.tools.files import (
    get, copy, apply_conandata_patches, export_conandata_patches,
)
from conan.tools.layout import basic_layout


class EximConan(ConanFile):
    name = "exim"
    version = "4.99.5"
    description = "Exim Internet mail transport agent (MTA) and utilities"
    license = "GPL-2.0-or-later"
    homepage = "https://www.exim.org/"
    url = ""  # CI fills this

    # exim ships only executables (no installable library)
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # All dependencies are managed by Conan (R26: static by default,
        # the conan profile builds them static). No system-name dynamic
        # linking.
        self.requires("pcre2/10.47")
        self.requires("openssl/3.5.6.1.1")
        self.requires("berkeley-db/4.8.30")
        self.requires("libxcrypt/4.5.2")
        self.requires("libiconv/1.17")
        self.requires("libtirpc/1.3.7")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _dep(self, name):
        """Return the package folder of a direct dependency."""
        deps = {d.ref.name: d for d in self.dependencies.values()}
        dep = deps[name]
        return dep.package_folder

    def generate(self):
        # R33: compiler/flags come from Conan conf, never from bare shell
        # environment variables. exim's Local/Makefile takes CC and CFLAGS
        # explicitly, so we read them from self.conf and the toolchain.
        comp_execs = self.conf.get("tools.build:compiler_executables",
                                default={}, check_type=dict)
        cc = comp_execs.get("c") or "clang"

        # PERL_COMMAND: exim Makefile rewrites the shebang of exigrep and
        # other scripts. A hardcoded path that exists locally but not in
        # CI ("bad interpreter: No such file or directory") aborts the
        # build. Derive perl from the same bin dir as CONFIG_SHELL (the
        # OHOS profile sets it to /data/service/hnp/bin/bash, and perl
        # lives alongside it as /data/service/hnp/bin/perl).
        import shutil
        config_shell = os.environ.get("CONFIG_SHELL", "/data/service/hnp/bin/bash")
        perl = os.path.join(os.path.dirname(config_shell), "perl")
        if not os.path.exists(perl):
            perl = shutil.which("perl") or "/usr/bin/perl"

        pcre2 = self._dep("pcre2")
        openssl = self._dep("openssl")
        bdb = self._dep("berkeley-db")
        libcrypt = self._dep("libxcrypt")
        libiconv = self._dep("libiconv")
        libtirpc = self._dep("libtirpc")

        # CFLAGS: align with the OHOS profile (fPIC, release) plus the
        # large-file flags exim expects on Linux-like systems.
        cflags = "-fPIC -O2 -D_FILE_OFFSET_BITS=64 -D_LARGEFILE_SOURCE"

        # Build the Local/Makefile site configuration.
        # OHOS has no root user; EXIM_USER/EXIM_GROUP use a numeric uid.
        lines = [
            # Bare install paths; exim_install prepends DESTDIR at install time.
            "BIN_DIRECTORY=/bin",
            "CONFIGURE_FILE=/etc/exim/exim.conf",
            "SPOOL_DIRECTORY=/var/spool/exim",
            "EXIM_USER=20020082",
            "EXIM_GROUP=20020082",
            f"CC={cc}",
            f"CFLAGS={cflags}",
            "LDFLAGS=",
            # --- PCRE2 (required) ---
            "PCRE2_CONFIG=no",
            f"PCRE_LIBS={pcre2}/lib/libpcre2-8.a",
            f"INCLUDE +=-I{pcre2}/include",
            # --- TLS: OpenSSL ---
            "USE_OPENSSL=yes",
            f"TLS_LIBS={openssl}/lib/libssl.a {openssl}/lib/libcrypto.a",
            f"INCLUDE +=-I{openssl}/include",
            # --- DANE (needs OpenSSL) ---
            "SUPPORT_DANE=yes",
            # --- DBM: Berkeley DB ---
            "USE_DB=yes",
            f"DBMLIB={bdb}/lib/libdb.a",
            f"INCLUDE +=-I{bdb}/include",
            # --- iconv ---
            "HAVE_ICONV=yes",
            f"INCLUDE +=-I{libiconv}/include",
            f"LDFLAGS +={libiconv}/lib/libiconv.a {libiconv}/lib/libcharset.a",
            # --- crypt (libxcrypt provides crypt()) ---
            f"LIBS +={libcrypt}/lib/libcrypt.a",
            # --- resolver / xdr headers (libtirpc) ---
            f"INCLUDE +=-I{libtirpc}/include",
            # --- Lookups (built-in) ---
            "LOOKUP_DBM=yes",
            "LOOKUP_LSEARCH=yes",
            "LOOKUP_DNSDB=yes",
            # --- Transports (built-in, from src/EDITME defaults) ---
            "TRANSPORT_APPENDFILE=yes",
            "TRANSPORT_AUTOREPLY=yes",
            "TRANSPORT_PIPE=yes",
            "TRANSPORT_SMTP=yes",
            # --- Routers (built-in, from src/EDITME defaults) ---
            "ROUTER_ACCEPT=yes",
            "ROUTER_DNSLOOKUP=yes",
            "ROUTER_IPLITERAL=yes",
            "ROUTER_MANUALROUTE=yes",
            "ROUTER_QUERYPROGRAM=yes",
            "ROUTER_REDIRECT=yes",
            # --- Misc commands ---
            "COMPRESS_COMMAND=/usr/bin/gzip",
            "ZCAT_COMMAND=/usr/bin/zcat",
            f"PERL_COMMAND={perl}",
        ]

        local_dir = os.path.join(self.source_folder, "Local")
        os.makedirs(local_dir, exist_ok=True)
        with open(os.path.join(local_dir, "Makefile"), "w") as f:
            f.write("# Local/Makefile for exim 4.99.5 (generated by Conan)\n")
            f.write("\n".join(lines) + "\n")

        # CI fix: the clang driver invokes lld to link; lld runtime-depends
        # on libxml2.so.16 which lives in the OHOS SDK llvm/lib dir. The CI
        # sandbox does not set LD_LIBRARY_PATH, so lld fails to load its
        # transitive .so deps and the link step crashes with "Error loading
        # shared library libxml2.so.16" / "symbol not found". Derive the SDK
        # lib dir from the compiler executable (resolving symlinks) and
        # prepend it to LD_LIBRARY_PATH for the build scope. This script is
        # auto-sourced by self.run(..., env="conanbuild") in build().
        env = Environment()
        cc_real = os.path.realpath(cc)
        llvm_bin = os.path.dirname(cc_real)
        llvm_lib = os.path.join(os.path.dirname(llvm_bin), "lib")
        if os.path.isdir(llvm_lib):
            env.prepend("LD_LIBRARY_PATH", llvm_lib)
        env.vars(self, scope="build").save_script("conanbuild_ldpath")

    def build(self):
        apply_conandata_patches(self)
        # OHOS: /system/bin/sh (mksh) cannot run exim's configure scripts;
        # use bash. (R5: CONFIG_SHELL.)
        config_shell = os.environ.get("CONFIG_SHELL", "/data/service/hnp/bin/bash")
        # The top-level Makefile invokes scripts/ which need a POSIX bash.
        self.run(f'make SHELL={config_shell} makefile', env="conanbuild",
                 cwd=self.source_folder)
        # R9: -j1 (exim's Makefile does not support parallel builds).
        self.run(f'make SHELL={config_shell} -j1', env="conanbuild",
                 cwd=self.source_folder)

    def package(self):
        # Deploy to a DESTDIR under the build folder, then copy the
        # installed tree. exim's install respects BIN_DIRECTORY etc. set in
        # Local/Makefile (which point at DESTDIR-relative paths).
        destdir = os.path.join(self.build_folder, "destdir")
        os.makedirs(destdir, exist_ok=True)
        config_shell = os.environ.get("CONFIG_SHELL", "/data/service/hnp/bin/bash")
        self.run(
            f'make SHELL={config_shell} install DESTDIR={destdir}',
            env="conanbuild", cwd=self.source_folder,
        )
        # Copy the installed bin/ etc/ var/ into the package.
        copy(self, "*", destdir, self.package_folder)

    def package_info(self):
        # exim is an application: expose its bin/ via bindirs so consumers
        # (and test_package) get the binaries on PATH via conanrun.
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        bin_dir = os.path.join(self.package_folder, "bin")
        if os.path.isdir(bin_dir):
            self.cpp_info.bindirs = [bin_dir]
