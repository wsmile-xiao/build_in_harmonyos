#!/usr/bin/env python3
"""Conan recipe — dcfldd 1.9.3 (Autotools)

dcfldd is an enhanced version of dd with hash verification (md5/sha1/sha256),
split writing, and progress display for forensic and security applications.
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class DcflddConan(ConanFile):
    name = "dcfldd"
    version = "1.9.3"
    description = "Enhanced dd with hash verification, split writing, and progress display"
    license = "GPL-2.0-or-later"
    homepage = "https://github.com/resurrecting-open-source-projects/dcfldd"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def validate(self):
        # R32: settings.os must be Linux or OHOS
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"os={self.settings.os} not supported")

    def export_sources(self):
        export_conandata_patches(self)

    def build_requirements(self):
        # GitHub archive 不含 configure（只是 git tree 快照），须 autoreconf 自举；
        # CI 设备缺 automake，通过 tool_requires 用 build profile 解析。
        self.tool_requires("automake/1.18")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Disable help2man and makeinfo (not available on OHOS)
        tc.configure_args.append("HELP2MAN=/bin/true")
        tc.configure_args.append("MAKEINFO=/bin/true")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)

        autotools = Autotools(self)

        # Source tarball (GitHub archive) lacks pre-built configure;
        # generate from configure.ac via autoreconf.
        if not os.path.isfile(os.path.join(self.source_folder, "configure")):
            self.output.info("Source tree has no configure (GitHub archive), running autoreconf")
            autotools.autoreconf()

        # E007: Replace config.guess/config.sub with OHOS-aware versions
        # autoreconf installs config.guess from automake/1.18 (2024-07-27),
        # which doesn't recognize HarmonyOS and fails to guess build type.
        self._replace_config_for_ohos()

        # E011: Fix umask 077 -> 022 for HMDFS compatibility
        self.run("sed -i 's/umask 077/umask 022/g' configure", cwd=self.source_folder)

        autotools.configure()

        # config.status (generated by configure) also has hardcoded umask 077
        self.run("sed -i 's/umask 077/umask 022/g' config.status")

        autotools.make()

    def _replace_config_for_ohos(self):
        """Replace config.guess/config.sub with OHOS-aware versions (E007)."""
        config_guess_path = os.path.join(self.source_folder, "config.guess")
        config_sub_path = os.path.join(self.source_folder, "config.sub")

        ohos_config_guess = (
            '#!/bin/sh\n'
            '# OHOS-aware config.guess (self-contained)\n'
            'machine=$(uname -m 2>/dev/null || echo unknown)\n'
            'system=$(uname -s 2>/dev/null || echo unknown)\n'
            'case "$system" in\n'
            '    HarmonyOS|OHOS)\n'
            '        echo "${machine}-unknown-linux-ohos"\n'
            '        ;;\n'
            '    *)\n'
            '        echo "${machine}-unknown-linux-gnu"\n'
            '        ;;\n'
            'esac\n'
            'exit 0\n'
        )
        with open(config_guess_path, "w") as f:
            f.write(ohos_config_guess)
        os.chmod(config_guess_path, 0o755)

        ohos_config_sub = (
            '#!/bin/sh\n'
            '# OHOS-aware config.sub (self-contained)\n'
            '# Always pass through the input triplet\n'
            'if [ $# -eq 0 ] || [ -z "$1" ]; then\n'
            '    echo "aarch64-unknown-linux-ohos"\n'
            '    exit 0\n'
            'fi\n'
            'echo "$1"\n'
            'exit 0\n'
        )
        with open(config_sub_path, "w") as f:
            f.write(ohos_config_sub)
        os.chmod(config_sub_path, 0o755)

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        # dcfldd is a CLI tool, not a library
        self.cpp_info.bindirs = ["bin"]
