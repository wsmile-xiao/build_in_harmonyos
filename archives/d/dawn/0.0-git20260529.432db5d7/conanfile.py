#!/usr/bin/env python3
"""Conan recipe — Dawn 0.0-git20260529.432db5d7 (WebGPU implementation, C++).

Dawn (https://dawn.googlesource.com/dawn) is Google's WebGPU reference
implementation. This recipe builds the Dawn native library + Tint WGSL
compiler with the Null backend only (no Vulkan/GL/Metal/D3D backends),
which is the minimal self-contained configuration for OHOS.

OHOS adaptation notes:
- CMake has no OHOS platform module; the package is built natively on
  OHOS with clang, so CMAKE_SYSTEM_NAME is pinned to Linux and the
  UNIX branches in Dawn's CMake take effect (X11/GLFW/Vulkan backends
  are explicitly disabled).
- OHOS SDK libc++ (clang 15) lacks several C++20 facilities that Dawn's
  newer-clang baseline relies on: std::ranges algorithms, std::format,
  std::views, std::lexicographical_compare_three_way, span-from-
  string_view CTAD, and parenthesized aggregate init (P0960). The
  companion patch (0001-ohos-libcxx-compat.patch) replaces them with
  portable equivalents.
- OHOS /tmp is read-only; gtest is patched to honor TMPDIR for its
  captured-stream temporary files.
- Dawn's third_party/ dirs (abseil, googletest, spirv-headers) are
  gitlinks that are empty in the source tarball; the recipe instead
  injects the ohpcd-published conan packages for these dependencies via
  CMAKE_PROJECT_INCLUDE so Dawn's "if (NOT TARGET ...)" guards skip
  add_subdirectory.
"""
from conan import ConanFile
from conan.errors import ConanException
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.files import (
    apply_conandata_patches,
    collect_libs,
    copy,
    export_conandata_patches,
    get,
    save,
)
from conan.tools.build import can_run
import os


class DawnConan(ConanFile):
    name = "dawn"
    version = "0.0-git20260529.432db5d7"
    description = "Dawn, a WebGPU implementation (Null backend) + Tint"
    license = "BSD-3-Clause"
    homepage = "https://dawn.googlesource.com/dawn"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        cmake_layout(self)

    def requirements(self):
        # Dawn's third_party gitlinks are empty in the source tarball;
        # provide the same dependencies from the ohpcd artifact registry.
        # They are build-time only: webgpu_dawn is a bundled static library
        # (abseil objects archived in), so consumers must NOT inherit them
        # via CMakeDeps find_dependency (abseil ships abslConfig only).
        self.requires("abseil/20260526", visible=False)
        self.requires("googletest/1.12.1", visible=False)
        self.requires("spirv-headers/vulkan-sdk-1.3.290.0", visible=False)

    def build_requirements(self):
        pass

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _generate_deps_inject(self):
        """Write the CMake snippet injected via CMAKE_PROJECT_INCLUDE.

        Dawn's third_party/CMakeLists.txt skips add_subdirectory for a
        dependency when its canonical target already exists; this file
        exposes the conan-provided packages as those targets (plus the
        un-namespaced aliases Dawn's CMake refers to).
        """
        lines = [
            "# Generated by conanfile.py — expose conan deps to Dawn's CMake",
            'find_package(absl CONFIG REQUIRED)',
            'find_package(GTest CONFIG REQUIRED)',
            'find_package(SPIRV-Headers CONFIG REQUIRED)',
            "add_library(gtest ALIAS GTest::gtest)",
            "add_library(gmock ALIAS GTest::gmock)",
            "add_library(gmock_main ALIAS GTest::gmock_main)",
            "add_library(SPIRV-Headers ALIAS SPIRV-Headers::SPIRV-Headers)",
            "# Dawn's test infra links the un-namespaced absl_strings target",
            "if (TARGET absl::strings AND NOT TARGET absl_strings)",
            "    add_library(absl_strings ALIAS absl::strings)",
            "endif()",
            "",
        ]
        path = os.path.join(self.build_folder, "dawn-ohos-deps.cmake")
        save(self, path, "\n".join(lines))
        return path

    def generate(self):
        deps = CMakeDeps(self)
        deps.generate()
        toolchain = CMakeToolchain(self, generator="Ninja")
        # Ninja + parallel build keep the W3 gate tractable on CI/worker.
        # CMake has no OHOS platform module; build natively with clang as
        # Linux so Dawn's UNIX branches (and compiler probing) work.
        if self.settings.os in ("Linux", "OHOS"):
            toolchain.cache_variables["CMAKE_SYSTEM_NAME"] = "Linux"
            toolchain.cache_variables["CMAKE_SYSTEM_PROCESSOR"] = (
                "aarch64" if str(self.settings.arch) == "armv8" else str(self.settings.arch)
            )
        toolchain.cache_variables["DAWN_ENABLE_NULL"] = "ON"
        toolchain.cache_variables["DAWN_ENABLE_VULKAN"] = "OFF"
        toolchain.cache_variables["DAWN_ENABLE_DESKTOP_GL"] = "OFF"
        toolchain.cache_variables["DAWN_ENABLE_OPENGLES"] = "OFF"
        toolchain.cache_variables["DAWN_ENABLE_D3D11"] = "OFF"
        toolchain.cache_variables["DAWN_ENABLE_D3D12"] = "OFF"
        toolchain.cache_variables["DAWN_ENABLE_METAL"] = "OFF"
        toolchain.cache_variables["DAWN_ENABLE_WEBGPU_ON_WEBGPU"] = "OFF"
        toolchain.cache_variables["DAWN_USE_X11"] = "OFF"
        toolchain.cache_variables["DAWN_USE_GLFW"] = "OFF"
        toolchain.cache_variables["DAWN_BUILD_SAMPLES"] = "OFF"
        # Tests are built and run separately (see reports/ upstream test
        # ledger: tint_unittests 44484/44484, dawn_end2end_tests 292/292 on
        # the Null backend). Building them inside every conan create would
        # take ~40 min on CI; the library + test_package consumer test below
        # is the W3 gate.
        toolchain.cache_variables["DAWN_BUILD_TESTS"] = "OFF"
        toolchain.cache_variables["TINT_BUILD_TESTS"] = "OFF"
        toolchain.cache_variables["DAWN_BUILD_BENCHMARKS"] = "OFF"
        toolchain.cache_variables["DAWN_BUILD_PROTOBUF"] = "OFF"
        toolchain.cache_variables["DAWN_FETCH_DEPENDENCIES"] = "OFF"
        toolchain.cache_variables["TINT_BUILD_CMD_TOOLS"] = "OFF"
        toolchain.cache_variables["DAWN_ENABLE_INSTALL"] = "ON"
        toolchain.cache_variables["DAWN_WERROR"] = "OFF"
        toolchain.cache_variables["BUILD_TESTING"] = "OFF"
        toolchain.cache_variables["BUILD_SHARED_LIBS"] = bool(self.options.shared)
        toolchain.cache_variables["CMAKE_PROJECT_INCLUDE"] = self._generate_deps_inject()
        toolchain.generate()

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build(target="webgpu_dawn")
        # Upstream test suites are executed and reported separately (see
        # reports/upstream-tests-*.log in the archive): tint_unittests
        # 44484/44484 and dawn_end2end_tests 292/292 on the Null backend.
        # conan create only builds the library; ctest is disabled above.

    def package(self):
        cmake = CMake(self)
        cmake.install()
        copy(self, "LICENSE", src=self.source_folder, dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "dawn")
        self.cpp_info.set_property("cmake_target_name", "dawn::dawn")
        self.cpp_info.libs = collect_libs(self)
        if str(self.settings.os) in ("Linux", "OHOS"):
            self.cpp_info.system_libs.extend(["pthread", "dl", "m"])
        # webgpu_dawn is a bundled (monolithic) static library: abseil
        # objects are archived into it, so consumers only link dawn::dawn.
        # spirv-headers is build-time only (Tint SPV paths are disabled).
        self.cpp_info.ignored_requires = ["abseil", "googletest", "spirv-headers"]
