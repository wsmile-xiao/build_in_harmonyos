#!/usr/bin/env python3
"""Conan recipe — desktop-file-utils 0.28 (meson)

.desktop 文件工具集（desktop-file-validate / desktop-file-install /
update-desktop-database），纯 CLI，唯一依赖 glib-2.0/gio-2.0。
"""
import os

from conan import ConanFile
from conan.tools.files import get
from conan.tools.meson import Meson, MesonToolchain
from conan.tools.gnu import PkgConfigDeps
from conan.tools.layout import basic_layout


class DesktopFileUtilsConan(ConanFile):
    name = "desktop-file-utils"
    version = "0.28"
    package_type = "application"
    settings = "os", "arch", "compiler", "build_type"
    exports_sources = "patches/*"

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def requirements(self):
        # glib-2.0/gio-2.0 由 glib 配方提供（meson 依赖声明 >=2.26）
        self.requires("glib/2.84.0", transitive_headers=True, transitive_libs=True)

    def layout(self):
        basic_layout(self, src_folder=".")

    def generate(self):
        PkgConfigDeps(self).generate()
        # 【OHOS musl gettext】glib 的 gi18n.h 里 `#define _(String) gettext(String)`，
        # 而 OHOS musl 无 gettext 隐式声明 → `_()` 返回 int 编译失败（20 处 -Wint-conversion）。
        # 同 glib 配方 proxy-libintl 方案：注入最小 libintl.h 声明（放到 generators 目录，
        # 经 c_args -I 引入），gettext 家族函数有原型即可。
        import os as _os
        _libintl = _os.path.join(self.generators_folder, "libintl.h")
        if not _os.path.isfile(_libintl):
            with open(_libintl, "w", encoding="utf-8") as _f:
                _f.write(
                    "#ifndef _LIBINTL_H\n#define _LIBINTL_H\n\n"
                    "#include <locale.h>\n\n"
                    "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n"
                    "extern char *gettext(const char *) __attribute__((__format_arg__(1)));\n"
                    "extern char *dgettext(const char *, const char *) __attribute__((__format_arg__(2)));\n"
                    "extern char *dcgettext(const char *, const char *, int) __attribute__((__format_arg__(2)));\n"
                    "extern char *ngettext(const char *, const char *, unsigned long);\n"
                    "extern char *dngettext(const char *, const char *, const char *, unsigned long);\n"
                    "extern char *dcngettext(const char *, const char *, const char *, unsigned long, int);\n"
                    "extern char *bind_textdomain_codeset(const char *, const char *);\n"
                    "extern char *bindtextdomain(const char *, const char *);\n"
                    "extern char *textdomain(const char *);\n\n"
                    "#ifdef __cplusplus\n}\n#endif\n\n#endif\n"
                )
        # 【skill: --alias-pc 生成】glib 配方的 PkgConfigDeps 只生成 glib-2.0.pc
        # （cpp_info.libs 合并 glib/gobject/gio），meson 需 dependency('gio-2.0')
        # 单独解析 → 生成转发型 gio-2.0.pc（Requires: glib-2.0，版本继承）。
        _src = _os.path.join(self.generators_folder, "glib-2.0.pc")
        _ver = "0"
        if _os.path.isfile(_src):
            with open(_src, encoding="utf-8") as _sf:
                for _line in _sf:
                    if _line.startswith("Version:"):
                        _ver = _line.split(":", 1)[1].strip()
                        break
        with open(_os.path.join(self.generators_folder, "gio-2.0.pc"), "w", encoding="utf-8") as _f:
            _f.write("Name: GIO\nDescription: forwarding .pc generated by recipe\n"
                     "Version: %s\nRequires: glib-2.0\n" % _ver)
        tc = MesonToolchain(self)
        # 禁止 meson 偷偷下 wrap 子项目：依赖一律走 conan
        tc.project_options["wrap_mode"] = "nodownload"
        # 注入 libintl.h 声明目录（所有 C 编译可见）
        tc.c_args.append("-I" + self.generators_folder)
        tc.generate()
        self._inject_meson_archiver()

    def _inject_meson_archiver(self):
        # 【OHOS 必需】conan 的 MesonToolchain 不把 tools.build:compiler_executables 里的 ar/ranlib
        # 写进 native file，meson 便按**裸名** llvm-ar 探归档器；而 clang 工具链在 /data/service/hnp/bin，
        # PATH 上没有 llvm-ar 时 meson configure 直接失败。这里把 ar/ranlib 全路径注入
        # conan_meson_native.ini，不污染 PATH。（cairo 1.18.4 / pango 1.56.4 实证）
        _ce = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict) or {}
        _ar, _rl = _ce.get("ar"), _ce.get("ranlib")
        # profile 通常只给 c/cpp：从 c 编译器同目录推导 llvm-ar / llvm-ranlib 全路径。
        if not _ar:
            _cc = _ce.get("c") or ""
            _bindir = os.path.dirname(_cc) if os.path.sep in _cc else ""
            if _bindir:
                _cand = os.path.join(_bindir, "llvm-ar")
                if os.path.isfile(_cand):
                    _ar = _cand
                    _rlc = os.path.join(_bindir, "llvm-ranlib")
                    if os.path.isfile(_rlc):
                        _rl = _rlc
        _nf = os.path.join(self.generators_folder, "conan_meson_native.ini")
        if not (_ar and os.path.isfile(_nf)):
            return
        with open(_nf, encoding="utf-8") as _f:
            _c = _f.read()
        if "\nar =" in _c or "[binaries]" not in _c:
            return
        _ins = "[binaries]\nar = '%s'\n" % _ar
        if _rl:
            _ins += "ranlib = '%s'\n" % _rl
        with open(_nf, "w", encoding="utf-8") as _f:
            _f.write(_c.replace("[binaries]\n", _ins, 1))

    def build(self):
        meson = Meson(self)
        meson.configure()
        meson.build()

    def package(self):
        Meson(self).install()
        # 纯 CLI 工具：产 bin/ 下可执行文件，无需签名动态库
        self._sign_binaries()

    def _is_elf(self, path):
        try:
            with open(path, "rb") as f:
                return f.read(4) == b"\x7fELF"
        except OSError:
            return False

    def _sign_binaries(self):
        # 鸿蒙 PC XPM 要求被 exec 的可执行文件代码签名（capstone/glib 同款）
        bindir = os.path.join(self.package_folder, "bin")
        if not os.path.isdir(bindir):
            return
        objcopy = "/data/service/hnp/bin/llvm-objcopy"
        signer = "/data/service/hnp/bin/binary-sign-tool"
        for name in os.listdir(bindir):
            p = os.path.join(bindir, name)
            if os.path.isfile(p) and not os.path.islink(p) and self._is_elf(p):
                self.run('{oc} --remove-section .codesign "{f}" 2>/dev/null || true'.format(oc=objcopy, f=p))
                self.run('{sg} sign -inFile "{f}" -outFile "{f}" -selfSign 1'.format(sg=signer, f=p))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
