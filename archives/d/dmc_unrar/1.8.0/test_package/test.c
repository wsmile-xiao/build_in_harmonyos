int main(void) {
    int failures = 0;
    char fixture_path[] = "fixture-rar5-crc.rar";
    FILE *f;
    dmc_unrar_archive archive;
    dmc_unrar_return rc;
    dmc_unrar_size_t i, count;

    /* 1. 写出夹具归档（当前目录，消费运行态） */
    f = fopen(fixture_path, "wb");
    if (!f) {
        printf("[FAIL] cannot create fixture file\n");
        return 1;
    }
    if (fwrite(rar5_fixture, 1, sizeof(rar5_fixture), f) != sizeof(rar5_fixture)) {
        printf("[FAIL] cannot write fixture\n");
        fclose(f);
        return 1;
    }
    fclose(f);

    /* 2. RAR 魔数识别（公开 API：dmc_unrar_is_rar_path） */
    if (!dmc_unrar_is_rar_path(fixture_path)) {
        printf("[FAIL] dmc_unrar_is_rar_path() returned false\n");
        failures++;
    }

    /* 3. 打开归档 */
    rc = dmc_unrar_archive_init(&archive);
    if (rc != DMC_UNRAR_OK) {
        printf("[FAIL] dmc_unrar_archive_init: %s\n", dmc_unrar_strerror(rc));
        return 1;
    }
    rc = dmc_unrar_archive_open_path(&archive, fixture_path);
    if (rc != DMC_UNRAR_OK) {
        printf("[FAIL] dmc_unrar_archive_open_path: %s\n", dmc_unrar_strerror(rc));
        failures++;
        dmc_unrar_archive_close(&archive);
        remove(fixture_path);
        return failures ? 1 : 0;
    }

    /* 4. 文件枚举 */
    count = dmc_unrar_get_file_count(&archive);
    printf("[INFO] archive has %llu files\n", (unsigned long long)count);
    if (count != 2) {
        printf("[FAIL] expected 2 files, got %llu\n", (unsigned long long)count);
        failures++;
    }

    /* 5. 逐个列出并解压，校验解压后的字节数（公开 API + 可观察结果） */
    for (i = 0; i < count; i++) {
        char filename[512];
        const dmc_unrar_file *stat = dmc_unrar_get_file_stat(&archive, i);
        char outname[256];
        dmc_unrar_size_t name_len;
        dmc_unrar_return erc;

        name_len = dmc_unrar_get_filename(&archive, i, filename, sizeof(filename));
        if (name_len == 0 || name_len >= sizeof(filename) || !stat) {
            printf("[FAIL] get_filename/get_file_stat failed at %llu\n", (unsigned long long)i);
            failures++;
            continue;
        }
        printf("[INFO] file %llu: %s (%llu bytes)\n",
               (unsigned long long)i, filename,
               (unsigned long long)stat->uncompressed_size);

        if (stat->uncompressed_size != 2048) {
            printf("[FAIL] unexpected uncompressed size\n");
            failures++;
        }

        snprintf(outname, sizeof(outname), "out_%s", filename);
        erc = dmc_unrar_extract_file_to_path(&archive, i, outname, NULL, true);
        if (erc != DMC_UNRAR_OK) {
            printf("[FAIL] extract %s: %s\n", filename, dmc_unrar_strerror(erc));
            failures++;
            continue;
        }
        /* 校验解压产物大小 */
        {
            FILE *out = fopen(outname, "rb");
            long size;
            if (!out) {
                printf("[FAIL] extracted file missing: %s\n", outname);
                failures++;
                continue;
            }
            fseek(out, 0, SEEK_END);
            size = ftell(out);
            fclose(out);
            printf("[INFO] extracted %s -> %ld bytes\n", outname, size);
            if (size != 2048) {
                printf("[FAIL] extracted size mismatch\n");
                failures++;
            }
            remove(outname);
        }
    }

    dmc_unrar_archive_close(&archive);
    remove(fixture_path);

    if (failures == 0) {
        printf("test_dmc_unrar: ALL CHECKS PASSED\n");
        return 0;
    }
    printf("test_dmc_unrar: %d FAILURE(S)\n", failures);
    return 1;
}