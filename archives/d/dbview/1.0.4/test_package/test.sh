#!/usr/bin/env bash
# test_package/test.sh — functional tests for the dbview executable (OHOS aarch64).
#
# Usage: bash test.sh <package_bin_dir>
#
# The binary is taken from the tested package's bin/ directory (never from
# PATH) so that the CI L1e negative test (package artifacts sabotaged and the
# test re-run) really fails when the package is broken.
#
# dbview 1.0.4 upstream ships no test suite at all, so every case here drives
# the packaged binary with a deterministic dBase III fixture and compares either
# the full stdout against a hand-checked golden file (expected/) or an exact
# string.
#
# The .dbf fixtures are BINARY files, and this repository must not carry new
# binary files in a PR: the CI `checkout-pr` step applies the platform-generated
# PR diff with `git apply`, and that diff contains no `GIT binary patch` data for
# newly added binary files ("error: missing binary patch data for ..."), so the
# step fails before the package is ever built. (Verified on run #44073 of
# PR #9495: 8 x "missing binary patch data" then "PR diff 无法应用".)
# Therefore fixtures are NOT committed; they are regenerated byte-identically at
# test time by the checked-in generator fixtures/make_fixtures.py, whose source
# the reviewer can read in the PR diff. `python3` is available in the conan/CI
# environment and is already used by other test_package scripts in this repo.
set -euo pipefail

BIN_DIR="${1:-}"
if [ -z "$BIN_DIR" ] || [ ! -d "$BIN_DIR" ]; then
    echo "[fail] dbview: package bin dir not found: '$BIN_DIR'"
    exit 1
fi

DBVIEW="$BIN_DIR/dbview"
if [ ! -f "$DBVIEW" ]; then
    echo "[fail] dbview: binary missing in package: $DBVIEW"
    exit 1
fi
if [ ! -x "$DBVIEW" ]; then
    echo "[fail] dbview: binary is not executable: $DBVIEW"
    exit 1
fi

HERE="$(cd "$(dirname "$0")" && pwd)"
GENERATOR="$HERE/fixtures/make_fixtures.py"
EXP="$HERE/expected"

# Work in a private temporary directory OUTSIDE the source tree whenever the
# platform allows it (CI workers: /tmp is writable), so that a killed run can
# never leave generated .dbf files inside the packaging checkout. Falls back to
# a directory next to this script only if mktemp is unavailable or unusable
# (OHOS mounts /tmp read-only).
WORK_DIR="$(mktemp -d 2>/dev/null || true)"
if [ -z "$WORK_DIR" ] || [ ! -d "$WORK_DIR" ]; then
    WORK_DIR="$HERE/dbview-test-work"
    rm -rf "$WORK_DIR"
    mkdir -p "$WORK_DIR"
fi
FIX="$WORK_DIR/fixtures"
mkdir -p "$FIX"
# EXIT alone does not cover a killed run, so also trap the usual termination signals.
trap 'rm -rf "$WORK_DIR"' EXIT INT TERM
echo "[step] dbview: work directory: $WORK_DIR"

# Regenerate the deterministic .dbf fixtures (see the note above on why they are
# not committed). Failing loudly here is intentional: a missing generator or a
# missing python3 must never be mistaken for "all tests passed".
if [ ! -f "$GENERATOR" ]; then
    echo "[fail] dbview: fixture generator not found: $GENERATOR"
    exit 1
fi
if ! command -v python3 > /dev/null 2>&1; then
    echo "[fail] dbview: python3 is required to generate the .dbf fixtures (see test.sh header)"
    exit 1
fi
if ! python3 "$GENERATOR" "$FIX"; then
    echo "[fail] dbview: fixture generation failed: $GENERATOR"
    exit 1
fi
FIXTURE_COUNT=$(ls -1 "$FIX"/*.dbf 2>/dev/null | wc -l)
if [ "$FIXTURE_COUNT" -ne 8 ]; then
    echo "[fail] dbview: expected 8 generated .dbf fixtures, found $FIXTURE_COUNT"
    exit 1
fi
echo "[step] dbview: generated $FIXTURE_COUNT .dbf fixtures in $FIX"

TOTAL=0
PASSED=0
FAILED=0

ok() {
    TOTAL=$((TOTAL + 1))
    PASSED=$((PASSED + 1))
    echo "        [ok] $1"
}

ko() {
    TOTAL=$((TOTAL + 1))
    FAILED=$((FAILED + 1))
    echo "        [fail] $1"
    if [ -n "${2:-}" ] && [ -f "$2" ]; then
        sed -n '1,20p' "$2"
    fi
}

# Run the package binary on a fixture; exit status ends up in RUN_RC, stdout in
# $WORK_DIR/actual.out and stderr in $WORK_DIR/actual.err.
# $1 = fixture file name (relative to fixtures/), remaining args = dbview options.
run_dbview() {
    local fixture="$1"
    shift
    set +e
    ( cd "$WORK_DIR" && "$DBVIEW" "$@" "$FIX/$fixture" ) \
        > "$WORK_DIR/actual.out" 2> "$WORK_DIR/actual.err"
    RUN_RC=$?
    set -e
}

# Compare the stdout of the last run against a golden file; $1 = case name,
# $2 = golden file name.
check_output() {
    local name="$1"
    local expected="$2"
    if [ "$RUN_RC" -ne 0 ]; then
        ko "$name: exit status $RUN_RC (expected 0)" "$WORK_DIR/actual.err"
        return
    fi
    if diff -u "$EXP/$expected" "$WORK_DIR/actual.out" > "$WORK_DIR/$name.diff" 2>&1; then
        ok "$name: output matches expected/$expected"
    else
        ko "$name: output differs from expected/$expected" "$WORK_DIR/$name.diff"
    fi
}

echo "[step] dbview test_package: running against $DBVIEW"

# ── Case 1: --version ────────────────────────────────────────────────────────
set +e
VERSION_OUT="$("$DBVIEW" --version < /dev/null 2>&1)"
VERSION_RC=$?
set -e
if [ "$VERSION_RC" -eq 0 ] && [ "$VERSION_OUT" = "dbview 1.0.4 - View dBase III files" ]; then
    ok "version_long: '$VERSION_OUT' (exit 0)"
else
    ko "version_long: rc=$VERSION_RC out='$VERSION_OUT'"
fi

# ── Case 2: -v ───────────────────────────────────────────────────────────────
set +e
VERSION_SHORT_OUT="$("$DBVIEW" -v < /dev/null 2>&1)"
VERSION_SHORT_RC=$?
set -e
if [ "$VERSION_SHORT_RC" -eq 0 ] && [ "$VERSION_SHORT_OUT" = "dbview 1.0.4 - View dBase III files" ]; then
    ok "version_short: -v prints the same version line (exit 0)"
else
    ko "version_short: rc=$VERSION_SHORT_RC out='$VERSION_SHORT_OUT'"
fi

# ── Case 3: --help lists every documented option ──────────────────────────────
set +e
"$DBVIEW" --help < /dev/null > "$WORK_DIR/help.out" 2>&1
HELP_RC=$?
set -e
HELP_MISSING=0
for opt in --browse --delimiter --description --help --info --deleted --omit --reserve --trim --version; do
    grep -q -- "$opt" "$WORK_DIR/help.out" || HELP_MISSING=$((HELP_MISSING + 1))
done
if [ "$HELP_RC" -eq 0 ] && [ "$HELP_MISSING" -eq 0 ]; then
    ok "help_long: exit 0 and all 10 long options documented"
else
    ko "help_long: rc=$HELP_RC missing_options=$HELP_MISSING" "$WORK_DIR/help.out"
fi

# ── Case 4: -h prints the short usage line ───────────────────────────────────
set +e
"$DBVIEW" -h < /dev/null > "$WORK_DIR/help_short.out" 2>&1
HELP_SHORT_RC=$?
set -e
if [ "$HELP_SHORT_RC" -eq 0 ] \
   && grep -q 'dbview \[-b \[-t\]\] \[-d delim\] \[-e\] \[-h\] \[-i\] \[-D\] \[-o\] \[-v\] dbfile' "$WORK_DIR/help_short.out"; then
    ok "help_short: usage line present (exit 0)"
else
    ko "help_short: rc=$HELP_SHORT_RC" "$WORK_DIR/help_short.out"
fi

# ── Case 5: no arguments prints the short usage ──────────────────────────────
set +e
"$DBVIEW" < /dev/null > "$WORK_DIR/noargs.out" 2>&1
NOARGS_RC=$?
set -e
if [ "$NOARGS_RC" -eq 0 ] && grep -q 'dbview \[-b \[-t\]\]' "$WORK_DIR/noargs.out"; then
    ok "no_args: usage printed, exit 0"
else
    ko "no_args: rc=$NOARGS_RC" "$WORK_DIR/noargs.out"
fi

# ── Case 6: default field/value view of a two-record database ────────────────
run_dbview basic.dbf
check_output "basic_default" "basic.default.out"

# ── Case 7: browse mode ──────────────────────────────────────────────────────
run_dbview basic.dbf -b
check_output "basic_browse" "basic.browse.out"

# ── Case 8: browse mode with trimmed fields ──────────────────────────────────
run_dbview basic.dbf -b -t
check_output "basic_browse_trim" "basic.browse_trim.out"

# ── Case 9: browse mode with a custom delimiter ──────────────────────────────
run_dbview basic.dbf -b -d '|'
check_output "basic_browse_delim" "basic.browse_delim.out"

# ── Case 10: --info prints the database header ───────────────────────────────
run_dbview basic.dbf -i
check_output "basic_info" "basic.info.out"

# ── Case 11: --description prints the field dictionary ───────────────────────
run_dbview basic.dbf -e
check_output "basic_descr" "basic.descr.out"

# ── Case 12: --omit suppresses the records ───────────────────────────────────
run_dbview basic.dbf -o
check_output "basic_omit" "basic.omit.out"

# ── Case 13: C/N/D/L field types and a non-zero decimal count ────────────────
run_dbview types.dbf
check_output "types_default" "types.default.out"

# ── Case 14: --deleted marks the deleted record ──────────────────────────────
run_dbview deleted.dbf -D
check_output "deleted_default" "deleted.default.out"

# ── Case 15: --deleted together with browse mode ─────────────────────────────
run_dbview deleted.dbf -b -D
check_output "deleted_browse" "deleted.browse.out"

# ── Case 16: dBase III+ version byte (0x83) is accepted ──────────────────────
run_dbview dbase3plus.dbf
check_output "dbase3plus_default" "dbase3plus.default.out"

# ── Case 17: field names are lowercased and '_' becomes ' ' ──────────────────
run_dbview names.dbf
check_output "names_default" "names.default.out"

# ── Case 18: --reserve keeps the original field names ────────────────────────
run_dbview names.dbf -r
check_output "names_reserve" "names.reserve.out"

# ── Case 19: a header with zero records prints nothing and succeeds ──────────
run_dbview empty.dbf
check_output "empty_db" "empty.default.out"

# ── Case 20: a truncated file stops after the records that are present ───────
run_dbview truncated.dbf
check_output "truncated_db" "truncated.default.out"

# ── Case 21: an unsupported version byte is reported ─────────────────────────
run_dbview badversion.dbf
if ! grep -q 'Version 139 not supported' "$WORK_DIR/actual.out"; then
    ko "badversion_reported: diagnostic missing" "$WORK_DIR/actual.out"
elif ! grep -q 'dBase IV - partially known' "$WORK_DIR/actual.out"; then
    ko "badversion_reported: dBase IV hint missing" "$WORK_DIR/actual.out"
else
    ok "badversion_reported: 'Version 139 not supported' + dBase IV hint"
fi

# ── Case 22: a missing database is reported with a non-zero exit status ──────
set +e
"$DBVIEW" "$WORK_DIR/does-not-exist.dbf" > "$WORK_DIR/missing.out" 2>&1
MISSING_RC=$?
set -e
if [ "$MISSING_RC" -ne 0 ] && grep -q "Unable to open file" "$WORK_DIR/missing.out"; then
    ok "missing_file_rejected: exit status $MISSING_RC with 'Unable to open file'"
else
    ko "missing_file_rejected: rc=$MISSING_RC (expected non-zero)" "$WORK_DIR/missing.out"
fi

echo "[step] dbview test_package summary: TOTAL=$TOTAL PASS=$PASSED FAIL=$FAILED"
if [ "$TOTAL" -eq 0 ] || [ "$FAILED" -ne 0 ]; then
    echo "[fail] dbview test_package: $FAILED of $TOTAL cases failed"
    exit 1
fi
echo "[ok] dbview test_package: all $TOTAL cases passed"
