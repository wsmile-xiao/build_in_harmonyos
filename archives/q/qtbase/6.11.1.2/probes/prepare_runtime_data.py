#!/usr/bin/env python3
"""Prepare XKB and Xcursor data from checksum-pinned upstream sources."""

import argparse
import ast
import hashlib
import json
from pathlib import Path
import re
import runpy
import shutil
import tempfile
import xml.etree.ElementTree as ET


def meson_literal(text, name, opening, closing, operator='='):
    pattern = (r'(?m)^\s*' + re.escape(name) + r'\s*' + re.escape(operator)
               + r'\s*(' + re.escape(opening) + r'.*?' + re.escape(closing) + ')')
    match = re.search(pattern, text, re.S)
    if not match:
        raise ValueError('Missing upstream Meson data: ' + name)
    return ast.literal_eval(match[1])


def copy_file(source, destination):
    if source.is_symlink() or not source.is_file():
        raise ValueError('Expected a regular upstream data file: ' + str(source))
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)


def write_inventory(source, destination):
    # The same model/layout/variant/option inventory as rules/xml2lst.pl;
    # ElementTree reads the pinned XML without adding a Perl build dependency.
    root = ET.parse(source).getroot()
    with destination.open('w', encoding='utf-8', newline='\n') as out:
        def row(item, width, prefix=''):
            name = item.findtext('name')
            description = item.findtext('description')
            if not name or description is None:
                raise ValueError('Incomplete XKB inventory item')
            out.write(f'  {name:<{width}} {prefix}{description}\n')
        out.write('! model\n')
        for item in root.findall('modelList/model/configItem'):
            row(item, 15)
        out.write('\n! layout\n')
        layouts = root.findall('layoutList/layout')
        for layout in layouts:
            row(layout.find('configItem'), 15)
        out.write('\n! variant\n')
        for layout in layouts:
            prefix = layout.findtext('configItem/name') + ': '
            for item in layout.findall('variantList/variant/configItem'):
                row(item, 15, prefix)
        out.write('\n! option\n')
        for group in root.findall('optionList/group'):
            row(group.find('configItem'), 20)
            for item in group.findall('option/configItem'):
                row(item, 20)


def prepare_xkb(source, destination):
    for directory in ('compat', 'geometry', 'keycodes', 'symbols', 'types'):
        for path in sorted((source / directory).rglob('*')):
            if path.is_file() and path.name not in ('Makefile.am', 'meson.build'):
                copy_file(path, destination / 'X11/xkb' / path.relative_to(source))
    rules = source / 'rules'
    output = destination / 'X11/xkb/rules'
    output.mkdir(parents=True, exist_ok=True)
    meson = (rules / 'meson.build').read_text(encoding='utf-8')
    parts = meson_literal(meson, 'parts', '[', ']')
    parts += meson_literal(meson, 'parts', '[', ']', '+=')
    map_variant = runpy.run_path(str(rules / 'compat/map-variants.py'))['map_variant']
    merge = runpy.run_path(str(rules / 'merge.py'))['merge']
    with tempfile.TemporaryDirectory(prefix='xkb-parts-', dir=destination) as temp:
        generated = []
        for want, variable, mappings in (
            ('mls', 'lvl_ml_s', ['layoutsMapping.lst', 'variantsMapping.lst']),
            ('mlvs', 'lvl_mlv_s', ['variantsMapping.lst']),
        ):
            names = meson_literal(meson, variable, '{', '}')
            for number in range(5):
                target = Path(temp) / names[str(number)]
                with target.open('w', encoding='utf-8', newline='\n') as stream:
                    map_variant(stream, [rules / 'compat' / name for name in mappings],
                                want, number)
                generated.append(target)
        for ruleset in ('base', 'evdev'):
            with (output / ruleset).open('w', encoding='utf-8', newline='\n') as stream:
                stream.write('// DO NOT EDIT THIS FILE - IT WAS AUTOGENERATED BY merge.py FROM rules/*.part\n//\n')
                merge(stream, [rules / name.replace('@0@', ruleset) for name in parts] + generated)
            for suffix in ('.xml', '.extras.xml'):
                copy_file(rules / ('base' + suffix), output / (ruleset + suffix))
            write_inventory(rules / 'base.xml', output / (ruleset + '.lst'))
    for name in ('README', 'xkb.dtd', 'xfree98'):
        copy_file(rules / name, output / name)
    for suffix in ('', '.lst', '.xml'):
        copy_file(output / ('base' + suffix), output / ('xorg' + suffix))
    copy_file(source / 'COPYING', destination / 'licenses/COPYING')


def prepare_cursors(source, destination):
    output = destination / 'Adwaita/cursors'
    output.mkdir(parents=True, exist_ok=True)
    for path in sorted((source / 'Adwaita/cursors').iterdir()):
        if path.is_file() and path.read_bytes()[:4] == b'Xcur':
            copy_file(path, output / path.name)
    aliases = meson_literal((source / 'meson.build').read_text(encoding='utf-8'),
                           'cursor_symlinks', '{', '}')
    for name, targets in aliases.items():
        for target in targets:
            if Path(target).name != target or (output / target).exists():
                raise ValueError('Invalid or duplicate cursor alias: ' + target)
            copy_file(output / name, output / target)
    copy_file(source / 'index.theme', destination / 'Adwaita/index.theme')
    for name in ('COPYING', 'COPYING_LGPL', 'COPYING_CCBYSA3'):
        copy_file(source / name, destination / 'licenses' / name)


def prepare(sources, destination):
    destination.mkdir(parents=True, exist_ok=True)
    # Stage new trees on each run to prevent old distro additions surviving an
    # incremental build. Replace only our two generated data directories.
    with tempfile.TemporaryDirectory(prefix='.data-', dir=destination) as temp:
        staged = Path(temp)
        prepare_xkb(sources / 'xkeyboard-config', staged / 'xkb')
        prepare_cursors(sources / 'adwaita', staged / 'cursors')
        records = {p.relative_to(staged).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                   for p in sorted(staged.rglob('*')) if p.is_file()}
        for name in ('xkb', 'cursors'):
            target = destination / name
            if target.exists():
                target.rename(staged / (name + '-previous'))
            (staged / name).rename(target)
    (destination / 'data-provenance.json').write_text(json.dumps(records, indent=2), encoding='utf-8')
    return records


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--sources', required=True, type=Path)
    parser.add_argument('--destination', required=True, type=Path)
    args = parser.parse_args()
    records = prepare(args.sources, args.destination)
    print(f'[PASS] Prepared {len(records)} upstream keyboard/cursor data files')
