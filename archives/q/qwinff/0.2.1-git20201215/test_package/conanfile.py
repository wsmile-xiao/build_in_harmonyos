import os

from conan import ConanFile
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout


class QwinffTestPackageConan(ConanFile):
    settings = "os", "compiler", "build_type", "arch"

    def requirements(self):
        self.requires(self.tested_reference_str)
        # Qt5 modules are used directly by this test package, so declare
        # qt5-qtbase as a direct requirement as well: CMakeDeps then emits a
        # complete aggregate Qt5Config (component include dirs populated).
        self.requires("qt5-qtbase/5.15.2.2")

    def layout(self):
        cmake_layout(self)

    def generate(self):
        # Use CMakeDeps' aggregate Qt5Config (cmake_file_name=Qt5), exactly
        # like the main recipe. Rationale: the qt5-qtbase package ships a real
        # Qt5Config.cmake in <pkg>/lib/cmake whose Qt5CoreConfigExtras hard-fails
        # when the file "<pkg>/../b/mkspecs/linux-clang" is missing (it only
        # exists in the CI worker's build folder, not in the package). The
        # aggregate config generated by CMakeDeps has no such build-time path
        # check, which keeps `conan create` reproducible on a fresh cache.
        deps = CMakeDeps(self)
        deps.set_property("qt5-qtbase", "cmake_file_name", "Qt5")
        deps.generate()

        tc = CMakeToolchain(self)
        tc.cache_variables["CMAKE_POLICY_VERSION_MINIMUM"] = "3.5"
        tc.variables["CMAKE_SYSTEM_NAME"] = "Linux"
        qt5_pkg = self.dependencies["qt5-qtbase"].package_folder
        tc.variables["CMAKE_AUTOMOC"] = "ON"
        tc.variables["CMAKE_AUTOMOC_EXECUTABLE"] = os.path.join(qt5_pkg, "bin", "moc")
        # E298: OHOS loader ignores LD_LIBRARY_PATH - give the build-tree test
        # executables an explicit rpath to the Qt5 lib dir.
        tc.variables["CMAKE_BUILD_RPATH"] = os.path.join(qt5_pkg, "lib")
        tc.generate()

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def test(self):
        # R34: verify the packaged qwinff executable artifact exists
        pkg = self.dependencies["qwinff"].package_folder
        exe = os.path.join(pkg, "bin", "qwinff")
        if not os.path.isfile(exe):
            raise Exception(f"qwinff executable not found in package: {exe}")

        # Run the upstream unit tests headlessly (no windowing system on OHOS).
        # QT_QPA_PLATFORM is passed inline (self.run env= replaces the whole
        # environment, losing conanrun vars - inline keeps them intact).
        bindir = self.cpp.build.bindir
        self.run(f"QT_QPA_PLATFORM=offscreen {os.path.join(bindir, 'testversioncompare')}")
        self.run(f"QT_QPA_PLATFORM=offscreen {os.path.join(bindir, 'testupdateinfoparser')}")
