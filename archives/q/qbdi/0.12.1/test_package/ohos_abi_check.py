#!/usr/bin/env python3
"""Pure-Python artifact inspection for the QBDI HarmonyOS package.

Runs on any host (no external tools) so a cross-building host still validates
the artifact instead of passing silently.

A1  include/QBDI.h and the public QBDI headers are present
A2  lib/libQBDI.a is an ar archive containing ELF64 AArch64 objects
A3  the PRIVATE LLVM really is inside it - that is the package's raison d'etre.
    Upstream states it statically links its own LLVM because QBDI uses LLVM
    private APIs not exported by stock LLVM; if this layer passes, that claim
    held on this build.
A4  no Mach-O / PE artifacts leaked into the package
"""
import argparse
import os
import sys

FAILS = []
CHECKS = 0

REQUIRED_HEADERS = [
    "QBDI.h",
    os.path.join("QBDI", "VM.h"),
    os.path.join("QBDI", "Callback.h"),
    # the C++ side of the API; QBDI.h includes it, and it is a .hpp so an
    # "*.h"-only package() glob silently drops it
    os.path.join("QBDI", "Memory.hpp"),
    # generated by configure_file() into the CMake build tree, NOT present in
    # the source archive - a package() that only copies <source>/include ships
    # a header set that cannot compile (QBDI/Platform.h includes Config.h)
    os.path.join("QBDI", "Config.h"),
    os.path.join("QBDI", "Version.h"),
    os.path.join("QBDI", "State.h"),
    os.path.join("QBDI", "Options.h"),
    os.path.join("QBDI", "arch", "AARCH64", "State.h"),
]

# Symbols that only exist if LLVM was linked in statically.  These are plain
# LLVM C++ mangled substrings, stable across LLVM 19.x.
LLVM_SYMBOLS = [b"LLVMCreate", b"LLVMDispose", b"llvm::", b"LLVMContext"]


def check(cond, name):
    global CHECKS
    CHECKS += 1
    if cond:
        print(f"  PASS  {name}")
    else:
        print(f"  FAIL  {name}")
        FAILS.append(name)


def read(path):
    with open(path, "rb") as fh:
        return fh.read()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--package", required=True)
    args = ap.parse_args()
    pkg = args.package

    print(f"qbdi OHOS ABI check: {pkg}")
    inc = os.path.join(pkg, "include")
    lib = os.path.join(pkg, "lib")

    for h in REQUIRED_HEADERS:
        check(os.path.isfile(os.path.join(inc, h)), f"A1 include/{h} present")

    sa = os.path.join(lib, "libQBDI.a")
    check(os.path.isfile(sa), "A2 lib/libQBDI.a present")
    if os.path.isfile(sa):
        blob = read(sa)
        check(blob[:8] == b"!<arch>\n", "A2 libQBDI.a has the ar magic")
        check(b"\x7fELF" in blob, "A2 libQBDI.a contains ELF objects")
        check(b"\xb7\x00" in blob, "A2 libQBDI.a contains AArch64 objects")
        found = [s.decode(errors="replace") for s in LLVM_SYMBOLS if s in blob]
        check(len(found) > 0,
              f"A3 private LLVM is statically inside libQBDI.a (matched {found})")

    leaked = []
    for root, _dirs, files in os.walk(pkg):
        for f in files:
            if f.endswith((".dll", ".dylib")):
                leaked.append(os.path.join(root, f))
    check(not leaked, f"A4 no Mach-O/PE artifacts leaked ({len(leaked)} found)")

    print(f"\nABI checks={CHECKS} failures={len(FAILS)}")
    if FAILS:
        for f in FAILS:
            print(f"  failed: {f}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
