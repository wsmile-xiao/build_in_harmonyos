#!/usr/bin/env python3
"""Conan recipe — rnnoise 0.2 (RNN-based noise suppression library, C).

rnnoise is an Autotools (configure/make) project. It builds the static/shared
librnnoise, the noinst dump_* training tools, and the rnnoise_demo example
(example only, not installed; the package contract installs include/rnnoise.h,
librnnoise, and rnnoise.pc).

v0.2 vs v0.1.1:
- New model APIs (rnnoise_model_from_file/buffer/filename, rnnoise_get_size/
  rnnoise_get_frame_size) and SSE4.1/AVX2 fast paths with run-time CPU
  detection (RTCD).
- On OHOS aarch64 the x86 fast paths are irrelevant: the recipe passes
  --disable-x86-rtcd (already the default) and the NEON path
  (src/vec_neon.h) is selected by the arch macros.
- Source: the GitHub release dist tarball (make dist 产物), which ships the
  generated configure, Makefile.in, package_version, and
  src/rnnoise_data.{c,h}. The gitlab /-/archive snapshot lacks
  rnnoise_data.{c,h} (generated from a ~22MB model download) and fails to
  compile; do not switch back.
- Because the dist tarball already ships configure, build() does NOT run
  autoreconf by default: the CI worker hit "can't fork - try again" /
  Out-of-memory while running autoreconf under load. autoreconf is only
  invoked as a fallback when configure is missing (tool_requires kept for
  that path).
- build() rewrites package_version to AUTO_UPDATE=no +
  PACKAGE_VERSION="0.2" so AC_INIT's m4_esyscmd probe and the make-time
  update_version rule are deterministic.
- Doxygen is absent from the OHOS sandbox, so configure gets --disable-doc.

R-notes: No runtime dependencies beyond libm. The recipe uses
AutotoolsToolchain, which maps os=OHOS to the HarmonyOS target via the
OHOS-adapted conan; pass the explicit --host for aarch64-linux-ohos so
config.guess/lt_cv produce a valid aarch64 host triple.
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration, ConanException
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class RnnoiseConan(ConanFile):
    name = "rnnoise"
    version = "0.2"
    description = "RNNoise - noise suppression library based on a recurrent neural network"
    license = "BSD-3-Clause"
    homepage = "https://gitlab.xiph.org/xiph/rnnoise"
    url = ""
    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("rnnoise is supported only on Linux/OHOS")
        if self.settings.arch != "armv8" and self.settings.os == "OHOS":
            raise ConanInvalidConfiguration("OHOS builds require armv8/aarch64")

    def export_sources(self):
        export_conandata_patches(self)

    def build_requirements(self):
        # Only needed for the autoreconf fallback path (when the source tree
        # ships no generated configure). The OHOS sandbox only has the
        # autoconf family under /data/service/hnp/bin, so pull automake/libtool
        # via tool_requires (same precedent as rnnoise/0.1.1: automake/1.18 +
        # libtool/2.5.4 from the ohpcd artifact registry).
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.configure_args.extend([
            "--disable-x86-rtcd",
            "--disable-doc",
        ])
        if str(self.settings.os) == "OHOS":
            tc.configure_args.extend([
                "--host=aarch64-unknown-linux-gnu",
                "--build=aarch64-unknown-linux-gnu",
            ])
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # Rewrite package_version (AUTO_UPDATE=no) so AC_INIT's m4_esyscmd
        # probe evaluates to "0.2" and the make-time update_version rule exits
        # without touching configure.ac (no mid-build autoconf regeneration
        # loop). The dist tarball ships a package_version without AUTO_UPDATE;
        # rewriting keeps it deterministic.
        _pkg_ver = os.path.join(self.source_folder, "package_version")
        with open(_pkg_ver, "w", encoding="utf-8") as _f:
            _f.write("# Automatically generated by update_version.\n")
            _f.write("AUTO_UPDATE=no\n")
            _f.write('PACKAGE_VERSION="0.2"\n')
        # The release dist tarball ships the generated configure/Makefile.in,
        # so autoreconf is NOT needed. Skip it (it is fork/memory heavy; the
        # CI worker previously died with "can't fork - try again" under load).
        # Fall back to autoreconf only if the source tree has no configure.
        _cfg_path = os.path.join(self.source_folder, "configure")
        if not os.path.exists(_cfg_path):
            self.run("autoreconf -fi", cwd=self.source_folder, env="conanbuild")

        if self.settings.os == "OHOS":
            # E114 (same as rnnoise/0.1.1): the OHOS security framework blocks
            # script subprocesses from creating temp dirs and writing files
            # there (config.status: ./confXXXXXX/subs1.awk: Permission denied).
            # Pre-create a writable dir, point TMPDIR at it, and repoint
            # configure's internal ac_tmp there; also stop the trap from
            # deleting the pre-created dir at exit.
            fixed_tmp = os.path.join(self.build_folder, "configure-ac-tmp")
            os.makedirs(fixed_tmp, exist_ok=True)
            os.environ["TMPDIR"] = fixed_tmp
            if os.path.exists(_cfg_path):
                with open(_cfg_path, "r", encoding="utf-8") as _f:
                    _cfg = _f.read()
                if "ac_tmp=$tmp" not in _cfg:
                    raise ConanException(
                        "E114: ac_tmp=$tmp pattern not found in configure; "
                        "autoconf may have changed the template")
                _cfg = _cfg.replace("ac_tmp=$tmp", "ac_tmp={}".format(fixed_tmp))
                _old_trap = '{ test ! -d "$ac_tmp" || rm -fr "$ac_tmp"; } && exit $exit_status'
                _new_trap = 'exit $exit_status'
                if _old_trap in _cfg:
                    _cfg = _cfg.replace(_old_trap, _new_trap)
                with open(_cfg_path, "w", encoding="utf-8") as _f:
                    _f.write(_cfg)
                os.chmod(_cfg_path, 0o755)
                self.output.info("  [ok] Patched configure: ac_tmp -> {} + TMPDIR (HMDFS)".format(fixed_tmp))

        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        import glob as _glob
        for _la in _glob.glob(os.path.join(self.package_folder, "lib", "*.la")):
            os.remove(_la)
        # rnnoise.h is the public contract of the package.
        copy(self, "rnnoise.h", src=os.path.join(self.source_folder, "include"),
             dst=os.path.join(self.package_folder, "include"))

    def package_info(self):
        self.cpp_info.libs = ["rnnoise"]
        self.cpp_info.system_libs = ["m"]
        self.cpp_info.set_property("pkg_config_name", "rnnoise")