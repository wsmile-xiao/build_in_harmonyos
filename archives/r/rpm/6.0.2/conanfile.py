#!/usr/bin/env python3
"""Conan recipe for RPM Package Manager 6.0.2 - CMake based build.

Dependencies (popt, zlib, bzip2, sqlite3, xz, zstd, openssl) are declared
as Conan requires for self-contained builds. libarchive and readline are
sourced from system packages when available.
"""
import os
from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout
from conan.tools.gnu import PkgConfigDeps


class RpmConan(ConanFile):
    name = "rpm"
    version = "6.0.2"
    description = "The RPM Package Manager"
    license = "GPL-2.0-or-later"
    homepage = "https://rpm.org"
    url = ""

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("popt/1.16")
        self.requires("zlib/1.3.1.1")
        self.requires("bzip2/1.0.8")
        self.requires("sqlite3/3.49.1")
        self.requires("xz/5.6.2")
        self.requires("zstd/1.5.6")
        self.requires("openssl/3.5.6")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        sys_prefix = (os.environ.get("HNP_PREFIX")
                      or os.environ.get("HNP_PUBLIC_HOME")
                      or os.path.join(os.path.expanduser("~"), "usr", "local"))
        home_prefix = os.path.join(os.path.expanduser("~"), "usr", "local")
        pc_paths = []
        for prefix in [sys_prefix, home_prefix]:
            pc_path = prefix + "/lib/pkgconfig"
            if os.path.exists(pc_path) and pc_path not in pc_paths:
                pc_paths.append(pc_path)
        if pc_paths:
            old = os.environ.get("PKG_CONFIG_PATH", "")
            new_path = ":".join(pc_paths)
            if old:
                new_path += ":" + old
            os.environ["PKG_CONFIG_PATH"] = new_path

        tc = CMakeToolchain(self)
        tc.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        if self.settings.os in ("Linux", "OHOS"):
            tc.cache_variables["CMAKE_SYSTEM_NAME"] = "Linux"
            tc.cache_variables["CMAKE_SYSTEM_PROCESSOR"] = str(self.settings.arch)
        # Include Conan-managed zlib/bzip2 package folders so find_package(ZLIB/BZip2) finds them
        # Conan paths first so they take priority over system-installed versions
        zlib_root = self.dependencies["zlib"].package_folder
        bzip2_root = self.dependencies["bzip2"].package_folder
        tc.cache_variables["CMAKE_PREFIX_PATH"] = (
            zlib_root + ";" + bzip2_root + ";" + sys_prefix + ";" + home_prefix
        )
        # Point OPENSSL_ROOT_DIR to Conan-managed OpenSSL so find_package(OpenSSL) finds it
        openssl_root = self.dependencies["openssl"].package_folder
        tc.cache_variables["OPENSSL_ROOT_DIR"] = openssl_root
        tc.variables["ENABLE_PYTHON"] = False
        tc.variables["ENABLE_PLUGINS"] = True
        tc.variables["ENABLE_TESTSUITE"] = False
        tc.variables["ENABLE_NLS"] = False
        tc.variables["ENABLE_OPENMP"] = False
        tc.variables["ENABLE_SQLITE"] = True
        tc.variables["WITH_CAP"] = False
        tc.variables["WITH_ACL"] = False
        tc.variables["WITH_SELINUX"] = False
        tc.variables["WITH_DBUS"] = False
        tc.variables["WITH_AUDIT"] = False
        tc.variables["WITH_FAPOLICYD"] = False
        tc.variables["WITH_SEQUOIA"] = False
        tc.variables["WITH_OPENSSL"] = True
        tc.variables["WITH_READLINE"] = False
        tc.variables["WITH_BZIP2"] = True
        tc.variables["WITH_ICONV"] = False
        tc.variables["WITH_ZSTD"] = True
        tc.variables["WITH_LIBDW"] = False
        tc.variables["WITH_LIBELF"] = False
        tc.variables["WITH_LIBLZMA"] = True
        tc.variables["WITH_LIBARCHIVE"] = True
        # Disable libmagic to prevent absolute-path linking to system libmagic.so
        tc.cache_variables["MAGIC_LIBRARY"] = ""
        tc.cache_variables["MAGIC_INCLUDE_DIR"] = ""
        tc.cache_variables["CMAKE_SKIP_BUILD_RPATH"] = "OFF"
        tc.cache_variables["CMAKE_BUILD_WITH_INSTALL_RPATH"] = "ON"
        tc.cache_variables["CMAKE_INSTALL_RPATH"] = "$ORIGIN/../lib"
        tc.variables["LUA_MATH_LIBRARY"] = ""
        tc.generate()

        pc = PkgConfigDeps(self)
        pc.generate()

        # Add generators folder to PKG_CONFIG_PATH so CMake's pkg_check_modules
        # can find the .pc files generated by PkgConfigDeps
        gen_folder = self.generators_folder
        pc_paths.insert(0, gen_folder)
        os.environ["PKG_CONFIG_PATH"] = ":".join(pc_paths)

        # Create liblzma.pc alias for xz package
        # (xz conan package generates xz.pc, but CMakeLists.txt looks for liblzma)
        gen_folder = self.generators_folder
        xz_pc = os.path.join(gen_folder, "xz.pc")
        liblzma_pc = os.path.join(gen_folder, "liblzma.pc")
        if os.path.exists(xz_pc) and not os.path.exists(liblzma_pc):
            with open(xz_pc) as f:
                content = f.read()
            content = content.replace("Name: xz", "Name: liblzma")
            with open(liblzma_pc, 'w') as f:
                f.write(content)

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.libs = ["rpm", "rpmio", "rpmbuild", "rpmsign"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libdirs = ["lib"]
        self.cpp_info.bindirs = ["bin"]
