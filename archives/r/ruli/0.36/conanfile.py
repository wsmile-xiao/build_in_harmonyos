#!/usr/bin/env python3
"""Conan recipe - ruli 0.36 (Resolver User Layer Interface, DNS query library).

ruli is a GPL DNS resolver library by Everton da Silva Marques.  It speaks DNS
itself over UDP/TCP port 53 (own packet builder/parser + SRV/A/AAAA state
machine) instead of going through libc's ``res_*``, and drives I/O through the
liboop event loop.

Upstream build system
---------------------
Bare recursive Makefiles only - there is no configure/Makefile.am/CMakeLists
anywhere in the release tarball, so nothing is generated by an autoconf step
and no ``DESTDIR``-style staging variable exists.  Every destination is a plain
make variable that can be overridden on the command line:

  * ``OOP_INCLUDE_DIR`` / ``OOP_LIB_DIR`` - where liboop is found
  * ``INSTALL_{INCLUDE,LIB,MAN3,BIN}_DIR`` - install destinations
  * ``CC`` / ``CFLAGS`` / ``LDFLAGS`` - toolchain (``CC`` and ``CFLAGS`` are
    *assigned* in the Makefile, so only a command-line override wins; because
    a command-line value is re-expanded by make, passing
    ``CFLAGS=...`` lets us drop upstream's ``-Werror`` without touching the
    source)

OHOS adaptations (all command-line level, zero source patches)
--------------------------------------------------------------
  * ``CC`` is forced to the Conan-resolved C compiler.  Upstream hard-codes
    ``CC = gcc`` and the target has no ``gcc`` (E092 family), so the assignment
    is overridden rather than patched (R33: the compiler comes from
    ``tools.build:compiler_executables``, never from a bare shell variable).
  * ``CFLAGS`` is replaced by an explicit flag set.  Upstream compiles with
    ``-Werror`` plus a 2002-era ``-pedantic -ansi`` warning bank, which turns
    every clang 15 diagnostic on this platform into a build error; the library
    sources themselves are unaffected.
  * ``OOP_INCLUDE_DIR`` / ``OOP_LIB_DIR`` point at the Conan ``liboop`` package
    instead of a hand-installed system tree (R49: no shared system prefix is
    written to or read from).
  * R32: ``settings.os`` checked with ``in ("Linux", "OHOS")``.
  * Upstream ships no automated test suite (audited in
    ``test_package/MANIFEST.yml``), so ``build()`` does not invoke any check
    target; ``HMBS_UPSTREAM_TEST_RESULT`` evidence is emitted by
    ``test_package`` on every run.
"""

import os
import shlex
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.env import VirtualBuildEnv
from conan.tools.files import (apply_conandata_patches, copy,
                               export_conandata_patches, get)
from conan.tools.layout import basic_layout


class RuliConan(ConanFile):
    name = "ruli"
    version = "0.36"
    description = ("Resolver User Layer Interface: an event-driven and "
                   "synchronous DNS resolver library (SRV/A/AAAA/SMTP/HTTP "
                   "lookups) that builds DNS packets itself and uses liboop "
                   "for the I/O loop")
    license = "GPL-2.0-or-later"
    homepage = "https://www.nongnu.org/ruli/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # liboop is a hard dependency, not an optional one:
        #   src/ruli_mem.c     -> oop_malloc() / oop_realloc() / oop_free()
        #   src/ruli_sync.c    -> oop_sys_new/source/run/delete()
        #   src/ruli_fsm.c     -> oop_source on_fd()/on_time() vtable
        # and the public header chain ruli.h -> ruli_res.h -> ruli_oop.h does
        # `#include <oop.h>`, so both the headers and the link library are
        # part of what a consumer of ruli needs.
        self.requires("liboop/1.0.1",
                      transitive_headers=True,
                      transitive_libs=True)

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def validate(self):
        # R32: never compare settings.os with ==
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "ruli is a POSIX-only DNS resolver (liboop select loop) and is "
                "not supported on %s" % self.settings.os)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    # ---- toolchain resolution -------------------------------------------

    def _conf_compiler(self, key, bare):
        """Resolve a compiler the way the CI profile expects (E092 family).

        The profile bakes an absolute toolchain path that may not exist inside
        a sandboxed preflight run.  Keep it when the file is really there so CI
        behaviour is unchanged, otherwise fall back to the PATH-visible
        equivalent.  Existence is probed with ``os.path.isfile`` only: HMDFS
        ignores chmod, so ``os.access(..., X_OK)`` is permanently False there
        (R49 3-forbidden-programs)."""
        try:
            exes = self.conf.get("tools.build:compiler_executables",
                                 default=None)
        except Exception:
            exes = None
        conf_val = None
        if isinstance(exes, dict):
            conf_val = exes.get(key)
        if conf_val and os.path.isfile(str(conf_val)):
            return str(conf_val)
        which = shutil.which(bare)
        if which:
            self.output.info("toolchain fallback: %s -> %s" % (bare, which))
            return which
        if conf_val:
            self.output.warning(
                "conf compiler %r unusable and no %r on PATH" % (conf_val, bare))
        return bare

    def _liboop_paths(self):
        cpp = self.dependencies["liboop"].cpp_info
        inc = os.path.abspath(cpp.includedirs[0])
        lib = os.path.abspath(cpp.libdirs[0])
        return inc, lib

    def generate(self):
        # Bare Makefile project: no toolchain file is consumed, but the profile
        # [buildenv] PATH (which carries make/ar/ld for the target toolchain)
        # must reach the build commands, so materialise conanbuild.sh.
        VirtualBuildEnv(self).generate()
        cc = self._conf_compiler("c", "clang")
        bindir = os.path.dirname(cc)
        if bindir and os.path.isdir(bindir):
            self.buildenv_info.prepend_path("PATH", bindir)

    def build(self):
        apply_conandata_patches(self)

        oop_inc, oop_lib = self._liboop_paths()
        cc = self._conf_compiler("c", "clang")
        srcdir = os.path.join(self.source_folder, "src")
        make = shutil.which("make") or "make"

        # Replaces upstream's `CFLAGS = $(WARN) -Werror $(FLAGS)`.  Kept as
        # close to the original flag set as possible: optimisation, the
        # reentrancy mark and the two include roots.  `-shared` stays because
        # upstream links libruli.so through the same variable.
        cflags = " ".join([
            "-O2", "-pipe", "-Wall", "-g", "-shared",
            "-D_REENTRANT", "-I.", "-I%s" % oop_inc,
        ])
        if self.options.get_safe("fPIC"):
            cflags += " -fPIC"

        args = [
            make, "-C", srcdir, "-j1",                      # R9: never -j$(nproc)
            "CC=%s" % cc,
            "OOP_INCLUDE_DIR=%s" % oop_inc,
            "OOP_LIB_DIR=%s" % oop_lib,
            "CFLAGS=%s" % cflags,
            "LDFLAGS=-L%s" % oop_lib,
        ]
        if not self.options.shared:
            # Static-only: skip the shared-object rules so no PIC-less object
            # is ever pulled into a DSO and no SONAME symlink is created.
            args.append("libruli.a")
        command = " ".join(shlex.quote(a) for a in args)
        self.output.info("ruli build: %s" % command)
        self.run(command, env="conanbuild")

        # Upstream has no automated suite (audited): there is no check/test
        # target in Makefile, src/Makefile, tools/Makefile or sample/Makefile,
        # so build() intentionally runs no test (upstream_test_in_build:
        # false).  HMBS_UPSTREAM_TEST_RESULT evidence comes from test_package.

    def package(self):
        pkg = self.package_folder
        srcdir = os.path.join(self.source_folder, "src")
        incdir = os.path.join(pkg, "include")
        libdir = os.path.join(pkg, "lib")

        # Public headers: ruli.h pulls in every other ruli_*.h, and
        # ruli_res.h -> ruli_oop.h -> <oop.h>, supplied transitively by the
        # liboop requirement declared above.
        copy(self, "*.h", src=srcdir, dst=incdir, keep_path=False)
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(pkg, "licenses"), keep_path=False)

        if self.options.shared:
            copy(self, "libruli.so.4", src=srcdir, dst=libdir, keep_path=False)
            so4 = os.path.join(libdir, "libruli.so.4")
            linker_name = os.path.join(libdir, "libruli.so")
            if os.path.isfile(so4):
                # HMDFS rule S1: never `ln -sf` over an existing entry.
                if os.path.islink(linker_name) or os.path.exists(linker_name):
                    try:
                        os.remove(linker_name)
                    except OSError:
                        pass
                try:
                    os.symlink("libruli.so.4", linker_name)
                except OSError:
                    self.output.warning(
                        "libruli.so symlink unavailable, copying instead")
                    copy(self, "libruli.so.4", src=srcdir, dst=libdir,
                         keep_path=False)
                    shutil.copyfile(so4, linker_name)
        else:
            copy(self, "libruli.a", src=srcdir, dst=libdir, keep_path=False)

        copy(self, "*.3", src=os.path.join(self.source_folder, "doc", "man"),
             dst=os.path.join(pkg, "share", "man", "man3"), keep_path=False)

    def package_info(self):
        self.cpp_info.libs = ["ruli"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libdirs = ["lib"]
        self.cpp_info.resdirs = ["share"]
        self.cpp_info.bindirs = []          # library package: no executables
        self.cpp_info.set_property("cmake_file_name", "ruli")
        self.cpp_info.set_property("cmake_target_name", "ruli::ruli")
        self.cpp_info.set_property("pkg_config_name", "ruli")
