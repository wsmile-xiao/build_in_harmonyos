#!/usr/bin/env python3
"""Conan recipe — redsocks 0.5

redsocks is a transparent TCP-to-proxy redirector. It redirects any TCP
connection to SOCKS4, SOCKS5 or HTTPS (HTTP/CONNECT) proxy server using
firewall rules.

Build system: plain Makefile (no configure script).
Produces a single executable `redsocks` installed to bin/.
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches, copy
from conan.tools.gnu import AutotoolsToolchain, AutotoolsDeps
from conan.tools.layout import basic_layout
from conan.tools.env import VirtualBuildEnv


class RedsocksConan(ConanFile):
    name = "redsocks"
    version = "0.5"
    description = "Transparent TCP-to-proxy redirector (SOCKS4/5, HTTPS)"
    license = "Apache-2.0"
    homepage = "https://github.com/darkk/redsocks"
    url = ""

    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # run=True: redsocks links the shared libevent libs, so consumers
        # (test_package / end users) need libevent's libdir in LD_LIBRARY_PATH
        # via VirtualRunEnv.
        self.requires("libevent/2.1.12", run=True)

    def layout(self):
        basic_layout(self)

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        env = VirtualBuildEnv(self)
        env.generate()
        tc = AutotoolsToolchain(self)
        # Embed RPATH to the shared libevent libs so the binary also runs
        # without LD_LIBRARY_PATH (e.g. smoke tests that run bin/ directly).
        libevent = self.dependencies["libevent"]
        libdir = os.path.join(libevent.package_folder, libevent.cpp_info.libdirs[0])
        tc.extra_ldflags.append(f"-Wl,-rpath,{libdir}")
        tc.generate()
        deps = AutotoolsDeps(self)
        deps.generate()

    def build(self):
        apply_conandata_patches(self)
        # Upstream Makefile defaults (LIBS := -levent_core, CFLAGS +=, env
        # CC/CPPFLAGS/LDFLAGS) combine with the conanbuild env generated by
        # AutotoolsToolchain/AutotoolsDeps: CC and -I/-L for libevent flow in
        # through the environment. libevent_core is sufficient for the default
        # build (evdns/evhttp are only referenced in debug builds).
        self.run("make -j1", cwd=self.source_folder, env="conanbuild")

    def package(self):
        copy(self, "redsocks", self.source_folder, os.path.join(self.package_folder, "bin"))
        copy(self, "redsocks.conf.example", self.source_folder, os.path.join(self.package_folder, "etc"))

    def package_info(self):
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
