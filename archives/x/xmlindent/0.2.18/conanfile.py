#!/usr/bin/env python3
"""Conan recipe — xmlindent 0.2.18 (upstream release, GPL-2.0-or-later).

XML Indent is an XML stream reformatter written in ANSI C (Pekka Enberg).  It
reads XML on stdin / from files and writes re-indented XML, handling XML
declarations, DOCTYPE, CDATA sections, comments, processing instructions,
attributes and character references.  The lexer is generated by **flex** from
`xmlindent.yy`; `indent.c` does `#include "lex.yy.c"`.

Build system: a plain Makefile (no autotools).

    1. `lex.yy.c: xmlindent.yy` -> `flex xmlindent.yy`
    2. `indent.c: lex.yy.c`     -> `touch indent.c`   (forces indent.o to rebuild)
    3. `.c.o` compiles buffer/error/indent/main
    4. link with `-Wl,-z,defs -Wl,-as-needed -Wl,--no-undefined`

FLEX IS A BUILD-TIME TOOL ONLY
------------------------------
flex is required to *generate* `lex.yy.c` during the build.  It is **not** a
runtime or package requirement: the packaged artifact is a single self-contained
executable with no flex, no libfl and no other library dependency (verified on
the OHOS target: the link succeeds under `-Wl,--no-undefined` with no `-lfl`,
because flex 2.6.4's generated scanner does not require an external `yywrap`).
It is therefore deliberately NOT declared as `requires()` / runtime dependency.

The Makefile hardcodes the command `flex`, so flex must be reachable on PATH
(the OpenHarmony build image provides flex 2.6.4 at /data/service/hnp/bin/flex);
`build()` fails early with an explicit message if it is missing.

OHOS ADAPTATION
---------------
None needed.  0.2.18 compiles, links and runs unmodified on
`aarch64-unknown-linux-ohos` with clang 15.0.4, and its upstream regression
fixture passes byte-for-byte.  No patches, no source rewrites.

UPSTREAM TESTS
--------------
upstream ships no `test`/`check` Makefile target and no runner script.  It does
ship exactly ONE regression fixture pair, added by the 2020-02-23 commit
"parse: Fix whitespace consumption within text nodes":

    tests/whitespace-in-content.orig.xml
    tests/whitespace-in-content.expected.xml

`run_upstream_tests.sh` executes that fixture (the complete upstream test set
for this version, `upstream_total = 1`) and is invoked from `build()` so the
result lands in the build log.  Nothing is skipped, filtered or excluded.
"""
import os
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class XmlindentConan(ConanFile):
    name = "xmlindent"
    version = "0.2.18"
    description = "XML stream reformatter (indents/reformats XML input)"
    license = "GPL-2.0-or-later"
    homepage = "http://xmlindent.sourceforge.net/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)
        # The upstream test runner lives next to the recipe, so it has to be
        # exported explicitly — conan only copies the recipe itself plus
        # whatever export_sources() selects into the build folder.
        copy(self, "run_upstream_tests.sh",
             src=self.recipe_folder, dst=self.export_sources_folder)

    def validate(self):
        # R32: settings.os check must be an explicit allow-list
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"xmlindent supports Linux and OHOS only, got {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)
        # xmlindent builds in-source (Makefile next to the sources)
        self.folders.build = "."

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _cc(self):
        # R33: take the compiler from Conan conf, never a bare env var
        compilers = self.conf.get("tools.build:compiler_executables", default={},
                                  check_type=dict)
        return compilers.get("c", "clang") if compilers else "clang"

    def _shell(self):
        # R5: OHOS has no guaranteed /bin/sh for complex scripts; use CONFIG_SHELL
        # (profile [buildenv]) and fall back to bash.
        return (os.environ.get("CONFIG_SHELL") or shutil.which("bash")
                or "/data/service/hnp/bin/bash")

    def build(self):
        # The upstream Makefile hardcodes the bare command `flex` for the
        # `lex.yy.c: xmlindent.yy` rule, so it has to be resolvable on PATH.
        if not shutil.which("flex"):
            raise ConanInvalidConfiguration(
                "xmlindent needs the `flex` lexer generator on PATH at build time "
                "(build-time tool only; not a package/runtime dependency)"
            )

        cc = self._cc()
        shell = self._shell()
        self.run(f"make CC={cc} SHELL={shell}", cwd=self.source_folder)

        # Complete upstream test set for this version (1 fixture pair).
        self.run(f"{shell} ./run_upstream_tests.sh",
                 cwd=self.source_folder)

    def package(self):
        src = self.source_folder
        bindir = os.path.join(self.package_folder, "bin")
        mandir = os.path.join(self.package_folder, "share", "man", "man1")
        for d in (bindir, mandir):
            os.makedirs(d, exist_ok=True)

        exe_dst = os.path.join(bindir, "xmlindent")
        shutil.copy2(os.path.join(src, "xmlindent"), exe_dst)
        os.chmod(exe_dst, 0o755)

        shutil.copy2(os.path.join(src, "xmlindent.1"),
                     os.path.join(mandir, "xmlindent.1"))

        copy(self, "LICENSE", src=src,
             dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        # xmlindent is a CLI tool, not a library
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
