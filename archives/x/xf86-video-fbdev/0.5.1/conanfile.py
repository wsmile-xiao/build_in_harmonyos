#!/usr/bin/env python3
"""Conan recipe for xf86-video-fbdev 0.5.1 — X.Org framebuffer video driver.

This driver is an X.Org video driver module (fbdev_drv.so) that provides
framebuffer device support. It is loaded by the X server at runtime as a
shared library module, not linked at compile time by applications.

Build approach:
  The source from GitLab does not include a pre-generated configure script.
  Since the build is simple (one C source file → one .so module), we use
  direct compilation instead of the full autotools machinery. This avoids
  the need for automake/libtool on the build machine.

  xorg-server SDK headers are set up from the xorg-server source tarball
  during the build step, as xorg-server is not available as a Conan package.

  pixman and xorgproto are provided via Conan requirements.
"""
import os
import shutil
from conan import ConanFile
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class Xf86VideoFbdevConan(ConanFile):
    name = "xf86-video-fbdev"
    version = "0.5.1"
    description = "X.Org framebuffer device video driver"
    license = "MIT"
    homepage = "https://gitlab.freedesktop.org/xorg/driver/xf86-video-fbdev"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    # This is a shared library module (X.Org driver), not a static library
    package_type = "shared-library"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # pixman and xorgproto are available as Conan packages
        self.requires("pixman/0.46.4")
        self.requires("xorgproto/2025.1")

    def layout(self):
        basic_layout(self)

    def source(self):
        # Download the driver source
        get(self, **self.conan_data["sources"], strip_root=True)

    def _get_compiler(self):
        """Get the C compiler path from Conan configuration."""
        compiler_info = self.conf_info.get("tools.build:compiler_executables")
        if compiler_info and "c" in compiler_info:
            return compiler_info["c"]
        return "clang"

    def _setup_xorg_sdk(self, sdk_dir):
        """Set up xorg-server SDK headers from source tarball.

        The xorg-server is not available as a Conan package, so we download
        the source and install the development headers manually.
        """
        xorg_data = self.conan_data.get("xorg_server", {})
        xorg_src = os.path.join(self.build_folder, "xorg-server-src")

        # Download xorg-server source
        get(self, url=xorg_data["url"], sha256=xorg_data["sha256"],
            strip_root=True, destination=xorg_src)

        # Create SDK include directory
        sdk_include = os.path.join(sdk_dir, "include", "xorg")
        os.makedirs(sdk_include, exist_ok=True)

        # Collect headers from key directories
        header_dirs = [
            "include", "fb", "mi", "Xext", "composite", "randr", "render",
            "Xi", "os", "dix", "damageext", "dbe", "xfixes", "xkb", "present",
            "hw/xfree86", "hw/xfree86/common", "hw/xfree86/os-support",
            "hw/xfree86/ddc", "hw/xfree86/fbdevhw", "hw/xfree86/parser",
            "hw/xfree86/ramdac", "hw/xfree86/shadowfb", "hw/xfree86/vgahw",
            "hw/xfree86/xkb", "miext/shadow", "miext/damage", "miext/sync",
        ]

        for d in header_dirs:
            full_dir = os.path.join(xorg_src, d)
            if os.path.isdir(full_dir):
                for f in os.listdir(full_dir):
                    if f.endswith(".h"):
                        src_file = os.path.join(full_dir, f)
                        dst_file = os.path.join(sdk_include, f)
                        if os.path.exists(dst_file):
                            os.remove(dst_file)
                        shutil.copy2(src_file, dst_file)

        # Create xorg-server.h configuration header
        xorg_server_h = os.path.join(sdk_include, "xorg-server.h")
        content_xorg_server_h = '''/*
 * xorg-server.h — Configuration header for xorg-server 21.1.15
 * Generated by Conan recipe for OpenHarmony aarch64.
 */
#ifndef _XORG_SERVER_H_
#define _XORG_SERVER_H_

#include <dix-config.h>

#define XORG_VERSION_CURRENT 12101015

#define X_BYTE_ORDER 1234
#define X_BIG_ENDIAN 4321
#define X_LITTLE_ENDIAN 1234

#define RANDR 1
#define RENDER 1
#define COMPOSITE 1
#define XINPUT 1
#define XV 1
#define DPMSExtension 1
#define DAMAGE 1
#define XFIXES 1
#define PANORAMIX 1
#define RES 1
#define SCREENSAVER 1
#define SHM 1
#define MITMISC 1
#define XSYNC 1
#define XCMISC 1
#define BIGREQS 1
#define HASXDMAUTH 1

#define ABI_ANSIC_VERSION SET_ABI_VERSION(0, 4)
#define ABI_VIDEODRV_VERSION SET_ABI_VERSION(25, 2)
#define ABI_XINPUT_VERSION SET_ABI_VERSION(24, 4)
#define ABI_EXTENSION_VERSION SET_ABI_VERSION(10, 0)

#define DRI3 1
#define PRESENT 1
#define HAS_SHM 1

/* Use libpciaccess path (avoids removed old PCI API) */
#define XSERVER_LIBPCIACCESS 1

#endif /* _XORG_SERVER_H_ */
'''
        with open(xorg_server_h, "w") as f:
            f.write(content_xorg_server_h)

        # Create dix-config.h
        dix_config_h = os.path.join(sdk_include, "dix-config.h")
        content_dix_config_h = '''/*
 * dix-config.h — Configuration for xorg-server 21.1.15
 * Generated by Conan recipe for OpenHarmony aarch64.
 */
#ifndef _DIX_CONFIG_H_
#define _DIX_CONFIG_H_

#define BIGREQS 1
#define COMPILEDDEFAULTFONTPATH "/usr/share/fonts/misc/"
#define SERVER_MISC_CONFIG_PATH "/usr/share/X11/xorg.conf.d"
#define COMPOSITE 1
#define DAMAGE 1
#define DDXOSVERRORF 1
#define DPMSExtension 1
#define DRI3 1
#define HAS_SHM 1
#define HAVE_EXECINFO_H 1
#define HAVE_FCNTL_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_MEMORY_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STRINGS_H 1
#define HAVE_STRING_H 1
#define HAVE_SYS_STAT_H 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_UNISTD_H 1
#define PRESENT 1
#define RANDR 1
#define RENDER 1
#define XFIXES 1
#define XINPUT 1
#define XV 1
#define MITMISC 1
#define XSYNC 1
#define XCMISC 1
#define XTEST 1
#define PANORAMIX 1
#define RES 1
#define SCREENSAVER 1
#define PACKAGE "xorg-server"
#define PACKAGE_VERSION "21.1.15"
#define STDC_HEADERS 1
#define VENDOR_NAME "OpenHarmony"
#define VENDOR_RELEASE 12101015
#define GLXEXT 0

#endif /* _DIX_CONFIG_H_ */
'''
        with open(dix_config_h, "w") as f:
            f.write(content_dix_config_h)

        # Create xorg-server.pc pkg-config file
        pkgconfig_dir = os.path.join(sdk_dir, "lib", "pkgconfig")
        os.makedirs(pkgconfig_dir, exist_ok=True)
        xorg_server_pc = os.path.join(pkgconfig_dir, "xorg-server.pc")
        content_pc = f"""prefix={sdk_dir}
exec_prefix=${{prefix}}
libdir=${{exec_prefix}}/lib
includedir=${{prefix}}/include
datarootdir=${{prefix}}/share
moduledir=${{libdir}}/xorg/modules
sdkdir=${{includedir}}/xorg
sysconfigdir=${{datarootdir}}/X11/xorg.conf.d

abi_ansic=0.4
abi_videodrv=25.2
abi_xinput=24.4
abi_extension=10.0

Name: xorg-server
Description: Modular X.Org X Server
Version: 21.1.15
Requires.private: pixman-1 xproto fontsproto randrproto renderproto videoproto
Cflags: -I${{sdkdir}}
Libs: -L${{libdir}}
"""
        with open(xorg_server_pc, "w") as f:
            f.write(content_pc)

        # Create pixman-1.pc (redirect to conan-provided pixman)
        pixman_pc = os.path.join(pkgconfig_dir, "pixman-1.pc")
        # We'll use conan's pixman via CPPFLAGS
        with open(pixman_pc, "w") as f:
            f.write(f"""prefix={sdk_dir}
includedir=${{prefix}}/include

Name: pixman-1
Description: The pixman library
Version: 0.46.4
Libs: -L${{prefix}}/lib -lpixman-1
Cflags: -I${{includedir}}/pixman-1
""")

        # Install pixman headers from conan dependency
        pixman_include = os.path.join(sdk_dir, "include", "pixman-1")
        os.makedirs(pixman_include, exist_ok=True)
        pixman_pkg = self.dependencies["pixman"]
        pixman_folder = pixman_pkg.package_folder
        for root, dirs, files in os.walk(pixman_folder):
            for fname in files:
                if fname.endswith(".h") and "pixman" in root:
                    src_h = os.path.join(root, fname)
                    dst_h = os.path.join(pixman_include, fname)
                    if os.path.exists(dst_h):
                        os.remove(dst_h)
                    shutil.copy2(src_h, dst_h)

        # Install xorgproto headers from conan dependency (recursive copy)
        xorgproto_pkg = self.dependencies["xorgproto"]
        xorgproto_folder = xorgproto_pkg.package_folder
        x11_src = os.path.join(xorgproto_folder, "include", "X11")
        x11_dst = os.path.join(sdk_dir, "include", "X11")
        if os.path.isdir(x11_src):
            # Use copytree but merge into existing directory
            for root, dirs, files in os.walk(x11_src):
                rel_path = os.path.relpath(root, x11_src)
                dst_dir = os.path.join(x11_dst, rel_path) if rel_path != "." else x11_dst
                os.makedirs(dst_dir, exist_ok=True)
                for fname in files:
                    src_f = os.path.join(root, fname)
                    dst_f = os.path.join(dst_dir, fname)
                    if os.path.exists(dst_f):
                        os.remove(dst_f)
                    shutil.copy2(src_f, dst_f)

        # Copy xorgproto pkgconfig files
        xorgproto_pc = os.path.join(xorgproto_folder, "share", "pkgconfig")
        if os.path.isdir(xorgproto_pc):
            for f in os.listdir(xorgproto_pc):
                if f.endswith(".pc"):
                    src_f = os.path.join(xorgproto_pc, f)
                    dst_f = os.path.join(pkgconfig_dir, f)
                    shutil.copy2(src_f, dst_f)

    def _setup_pciaccess(self, sdk_dir):
        """Install pciaccess.h from libpciaccess source."""
        pci_data = self.conan_data.get("libpciaccess", {})
        pci_src = os.path.join(self.build_folder, "libpciaccess-src")
        get(self, url=pci_data["url"], sha256=pci_data["sha256"],
            strip_root=True, destination=pci_src)

        # Copy pciaccess.h to include dir
        src_h = os.path.join(pci_src, "include", "pciaccess.h")
        dst_h = os.path.join(sdk_dir, "include", "pciaccess.h")
        if os.path.exists(dst_h):
            os.remove(dst_h)
        shutil.copy2(src_h, dst_h)

    def build(self):
        # Apply patches if any (from conandata.yml)
        apply_conandata_patches(self)

        sdk_dir = os.path.join(self.build_folder, "xorg-sdk")

        # Set up xorg-server SDK headers
        self._setup_xorg_sdk(sdk_dir)

        # Install pciaccess.h
        self._setup_pciaccess(sdk_dir)

        # Create config.h for the driver source
        config_h = os.path.join(self.source_folder, "config.h")
        content_config_h = """/* config.h — generated by Conan recipe */
#ifndef CONFIG_H
#define CONFIG_H

/* Must include xorg-server.h before any other xserver headers */
#include "xorg-server.h"

#define PACKAGE "xf86-video-fbdev"
#define PACKAGE_VERSION "0.5.1"
#define PACKAGE_NAME "xf86-video-fbdev"
#define PACKAGE_STRING "xf86-video-fbdev 0.5.1"
#define PACKAGE_BUGREPORT "https://gitlab.freedesktop.org/xorg/driver/xf86-video-fbdev/issues"
#define HAVE_CONFIG_H 1

#endif
"""
        with open(config_h, "w") as f:
            f.write(content_config_h)

        # Compile fbdev.c directly into a shared library module
        cc = self._get_compiler()
        sdk_include = os.path.join(sdk_dir, "include")

        # Build CFLAGS from include paths
        cflags = [
            "-fPIC",
            "-O2",
            f"-I{self.source_folder}",
            f"-I{sdk_include}/xorg",
            f"-I{sdk_include}/pixman-1",
            f"-I{sdk_include}",
            "-DHAVE_CONFIG_H",
            "-DXSERVER_LIBPCIACCESS",
        ]

        # Add compiler flags from settings
        if self.settings.build_type == "Release":
            cflags.append("-O2")
        elif self.settings.build_type == "Debug":
            cflags.append("-g")

        # Source file
        src_file = os.path.join(self.source_folder, "src", "fbdev.c")

        # Output module
        module_dir = os.path.join(self.build_folder, "lib", "xorg", "modules", "drivers")
        os.makedirs(module_dir, exist_ok=True)
        output_so = os.path.join(module_dir, "fbdev_drv.so")

        # Compile
        cmd = f"{cc} {' '.join(cflags)} -shared -o {output_so} {src_file}"
        self.run(cmd)

    def package(self):
        # Package the driver module - copy from build output to flat lib dir
        module_src = os.path.join(self.build_folder, "lib", "xorg", "modules", "drivers")
        if not os.path.isdir(module_src):
            # Fallback: search recursively
            module_src = os.path.join(self.build_folder, "lib")
        copy(self, "fbdev_drv.so",
             src=module_src,
             dst=os.path.join(self.package_folder, "lib"))

        # Package the man page if it exists
        man_src = os.path.join(self.source_folder, "man")
        if os.path.isdir(man_src):
            for f in os.listdir(man_src):
                if f.endswith(".4"):
                    copy(self, f, src=man_src,
                         dst=os.path.join(self.package_folder, "share", "man", "man4"))

    def package_info(self):
        # The driver module is installed to lib/xorg/modules/drivers/
        self.cpp_info.libs = ["fbdev_drv"]
        self.cpp_info.libdirs = ["lib"]
        # Module directory for X server to find the driver
        self.cpp_info.set_property("xorg_module_dir", "lib/xorg/modules/drivers")
