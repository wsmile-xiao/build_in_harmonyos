#!/usr/bin/env python3
"""Conan recipe — xmacro 0.3pre-20000911 (X11 宏录制/回放命令行工具)

上游: SourceForge xmacro 项目 (pre0.3, 2000-09-11 快照)
源码归档: Debian 官方 pool 的 orig tarball (与 SourceForge 上游发布一致,
  且 URL 带 .tar.gz 后缀, Conan get() 可识别格式; SourceForge 直链需重定向,
  codeload 无此项目)。
构建系统: 上游为硬编码 g++ /usr/X11R6 路径的原始 Makefile, 不适配交叉编译。
  本配方在 build() 中直接用 Conan 工具链编译器编译三个源文件
  (xmacroplay/xmacrorec/xmacrorec2), 不调用上游 Makefile。
依赖: libX11 (Xlibint/Xlib/keysymdef) + libXtst (XTest 扩展), 均取自制品仓
  conan 包 (CI worker 无本机 X11, R36)。
许可证: GPL-2.0-or-later (COPYING 为 GPL-2.0)。

版本说明: Conan 版本 0.3pre-20000911 与上游发布快照标识一致。
issue: 待补 (按当前任务要求, issue 编号暂不阻塞本机前置适配)。

测试说明: 上游无自动化测试套件 (无 make check / 测试目录), 提供的是手工
宏录制回放流程, 需要真实 X server 与键鼠事件授权。因此 build() 阶段以
"三个二进制全部编译链接成功" 作为上游验证; 消费验证在 test_package 中
执行 xmacroplay -v (打印版本, exit 0, 不需要 X server) 与无参调用
(stderr 输出 Usage:, exit 非 0) 两个确定性冒烟断言。XTest 事件注入路径
需真机 X 环境, 按平台限制降级, 不静默删除。
"""
import os
import shutil
import subprocess

from conan import ConanFile
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class XmacroConan(ConanFile):
    name = "xmacro"
    version = "0.3pre-20000911"
    description = "X11 macro record and play tools (XTest based)"
    license = "GPL-2.0-or-later"
    homepage = "https://sourceforge.net/projects/xmacro/"
    url = "https://sourceforge.net/projects/xmacro/"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        # 当前无补丁；conandata.yml 无 patches 段时为空操作
        export_conandata_patches(self)

    def requirements(self):
        # X11 头文件与库来自制品仓 conan 包 (R36)
        self.requires("libx11/6.4.0", transitive_headers=True, transitive_libs=True)
        self.requires("libxtst/1.2.5", transitive_headers=True, transitive_libs=True)
        # XTest.h 需要 X11/extensions/XInput.h (libXi), 本机 -fsyntax-only 实测发现
        self.requires("libxi/6.1.0", transitive_headers=True, transitive_libs=True)
        # X11/Xlibint.h / keysymdef.h 等协议头在 xorgproto 包
        self.requires("xorgproto/2025.1", transitive_headers=True)

    def layout(self):
        basic_layout(self)

    def source(self):
        # 源码来自 conandata.yml（url 带 .tar.gz 后缀, sha256 已实测）;
        # filename 显式指定以便 get() 识别归档格式
        get(
            self,
            **self.conan_data["sources"][self.version],
            strip_root=True,
            filename="xmacro_0.3pre-20000911.orig.tar.gz",
        )
        # 上游 2000 年代码在 iostream 分支中裸用 cerr/cout/cin/endl/hex/dec
        # (无 using namespace std / std:: 前缀), 现代 libc++ 下全部报
        # "use of undeclared identifier"。不改上游文件, 以强制包含的兼容头
        # 注入 using 声明 (build() 中 -include)。
        with open(os.path.join(self.source_folder, "xmacro_compat.h"), "w") as f:
            f.write("/* generated by conanfile.py — legacy iostream compat */\n")
            f.write("#pragma once\n")
            f.write("#include <iostream>\n")
            f.write("using std::cerr; using std::cout; using std::cin;\n")
            f.write("using std::endl; using std::hex; using std::dec;\n")

    def build(self):
        # 当前无补丁; conandata.yml 无 patches 段时为空操作
        apply_conandata_patches(self)
        # 上游无测试套件; 上游验证 = 三个二进制全部编译链接成功。
        # 上游 Makefile 硬编码 g++ 与 /usr/X11R6 路径, 不能用于交叉编译,
        # 改为直接调用 Conan 工具链编译器。
        # R33: 不用 shell 环境变量 $CXX (conanbuild 环境未导出, 实测为空),
        # 从 Conan conf 显式取编译器可执行文件。
        import shutil
        executables = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict) or {}
        cxx = executables.get("cpp") or executables.get("c") \
            or shutil.which("clang++") or shutil.which("c++") or "clang++"
        cxx = cxx.replace("\\", "/")
        self.output.info("CXX=%s" % cxx)
        src = self.source_folder
        dep_incs = " ".join(
            f"-I{os.path.join(dep.package_folder, inc)}"
            for dep in self.dependencies.values()
            if getattr(dep, "package_folder", None)
            for inc in dep.cpp_info.includedirs
        )
        dep_libs = " ".join(
            f"-L{os.path.join(dep.package_folder, libdir)}"
            for dep in self.dependencies.values()
            if getattr(dep, "package_folder", None)
            for libdir in dep.cpp_info.libdirs
        )
        for prog in ("xmacroplay", "xmacrorec", "xmacrorec2"):
            self.run(
                f'"{cxx}" -O2 {dep_incs} -Wall -DHAVE_IOSTREAM '
                f'-include "{src}/xmacro_compat.h" '
                f'-DVERSION=\'"0.3"\' "{src}/{prog}.cpp" -o "{prog}" '
                f'{dep_libs} -lXtst -lX11',
                cwd=src,
                env="conanbuild",
            )

    def package(self):
        copy(self, "xmacroplay", self.source_folder,
             os.path.join(self.package_folder, "bin"), keep_path=False)
        copy(self, "xmacrorec", self.source_folder,
             os.path.join(self.package_folder, "bin"), keep_path=False)
        copy(self, "xmacrorec2", self.source_folder,
             os.path.join(self.package_folder, "bin"), keep_path=False)
        copy(self, "COPYING", self.source_folder,
             os.path.join(self.package_folder, "licenses"), keep_path=False)
        copy(self, "README", self.source_folder,
             os.path.join(self.package_folder, "licenses"), keep_path=False)

    def package_info(self):
        # 命令行工具, 无可链接库; 只提供 bin/ (R38)
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
