#!/usr/bin/env python3
"""Conan recipe — perl-socket-getaddrinfo 0.22 (Perl EUMM build system).

XS getaddrinfo interface for Perl. Uses ExtUtils::MakeMaker (EUMM).
Original uses Module::Build::Compat but OHOS lacks Module::Build.
Rewritten Makefile.PL uses EUMM directly with HarmonyOS linker flags.

R1:  Only --prefix (PERL_MM_OPT)
R26: No system same-name library (Perl XS module, not a system lib)
R27: No external Conan dependencies
R32: settings.os in ("Linux", "OHOS")
"""
import os
import shutil
import subprocess

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class PerlSocketGetaddrinfoConan(ConanFile):
    name = "perl-socket-getaddrinfo"
    version = "0.22"
    description = "XS getaddrinfo interface for Perl (Socket::GetAddrInfo)"
    license = "Artistic-1.0-Perl"
    homepage = "https://metacpan.org/pod/Socket::GetAddrInfo"
    url = ""  # CI fills this

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    # R32: support both Linux (dev) and OHOS (target)
    def configure(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"Unsupported os: {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)

    def requirements(self):
        # R27: no external Conan dependencies
        pass

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _run_cmd(self, cmd, cwd=None, check=True):
        """Run a command with proper environment."""
        env = os.environ.copy()
        # Ensure Perl can find site_perl modules
        perl_lib = os.path.join(os.path.expanduser("~"), "usr", "local", "lib", "site_perl", "5.42.0")
        perl_arch = os.path.join(perl_lib, "aarch64-linux")
        env["PERL5LIB"] = f"{perl_lib}:{perl_arch}"
        self.output.info(f"Running: {cmd}")
        result = subprocess.run(cmd, shell=True, env=env, cwd=cwd,
                                capture_output=True, text=True, timeout=300)
        if result.stdout:
            self.output.info(result.stdout)
        if result.stderr:
            self.output.warning(result.stderr)
        if check and result.returncode != 0:
            raise Exception(f"Command failed (exit {result.returncode}): {cmd}")
        return result

    def build(self):
        apply_conandata_patches(self)
        src = self.source_folder

        # Create socket-gai-config.h (normally generated by ExtUtils::CChecker)
        # HarmonyOS has getaddrinfo() in libc, no sa_len field
        config_h = os.path.join(src, "socket-gai-config.h")
        with open(config_h, "w") as f:
            f.write("/* Auto-generated - HarmonyOS configuration */\n")
            f.write("#define HAS_GETADDRINFO 1\n")
            f.write("/* HAS_SOCKADDR_SA_LEN not defined - OHOS doesn't have sa_len */\n")

        # Rewrite Makefile.PL from Module::Build::Compat to EUMM
        makefile_pl = os.path.join(src, "Makefile.PL")
        with open(makefile_pl, "w") as f:
            f.write('''# Rewritten for HarmonyOS using ExtUtils::MakeMaker (EUMM)
use strict;
use warnings;
use ExtUtils::MakeMaker;

WriteMakefile(
    NAME          => 'Socket::GetAddrInfo',
    VERSION_FROM  => 'lib/Socket/GetAddrInfo.pm',
    ABSTRACT_FROM => 'lib/Socket/GetAddrInfo.pm',
    AUTHOR        => 'Paul Evans <leonerd@leonerd.org.uk>',
    LICENSE       => 'perl',
    PREREQ_PM     => {
        'Exporter'     => '5.57',
        'XSLoader'     => 0,
        'Scalar::Util' => 0,
    },
    TEST_REQUIRES => {
        'Scalar::Util' => 0,
        'Test::More'   => 0,
    },
    XS    => { 'lib/Socket/GetAddrInfo.xs' => 'lib/Socket/GetAddrInfo.c' },
    OBJECT => '$(O_FILES)',
    dynamic_lib => { OTHERLDFLAGS => '-nostartfiles -nodefaultlibs -lc' },
);
''')

        # perl Makefile.PL
        self._run_cmd("perl Makefile.PL", cwd=src)

        # make - first attempt compiles XS but may fail at linking
        # due to EUMM generating .o in CWD instead of lib/Socket/
        self._run_cmd("make -j1", cwd=src, check=False)

        # Fix the .o file path mismatch (EUMM generates .o in cwd, not in lib/Socket/)
        obj_src = os.path.join(src, "GetAddrInfo.o")
        obj_dst = os.path.join(src, "lib", "Socket", "GetAddrInfo.o")
        if os.path.exists(obj_src) and not os.path.exists(obj_dst):
            shutil.copy2(obj_src, obj_dst)
            # Re-run make to complete linking
            self._run_cmd("make -j1", cwd=src)
        elif os.path.exists(obj_dst):
            # .o already in place, try make again
            self._run_cmd("make -j1", cwd=src)
        else:
            raise Exception("XS compilation failed: no .o file produced")

    def package(self):
        src = self.source_folder
        pkg = self.package_folder

        # Install using make install with DESTDIR
        self._run_cmd(f'make install DESTDIR="{pkg}"', cwd=src)

        # Normalize: copy installed files from nested path to lib/
        nested = os.path.join(pkg, "data", "service", "hnp",
                              "perl.org", "perl_5.42.0", "lib", "site_perl")
        if os.path.exists(nested):
            target = os.path.join(pkg, "lib", "site_perl")
            os.makedirs(os.path.dirname(target), exist_ok=True)
            # Move the entire site_perl tree
            if os.path.exists(target):
                shutil.rmtree(target)
            shutil.move(nested, target)
            # Clean up empty parent dirs
            empty_root = os.path.join(pkg, "data")
            if os.path.exists(empty_root):
                shutil.rmtree(empty_root)

    def package_info(self):
        # Perl XS module — no C/C++ linkable libraries
        self.cpp_info.libs = []
        self.cpp_info.libdirs = []
