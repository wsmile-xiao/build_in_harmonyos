#!/usr/bin/env python3
"""Conan recipe — perl-mouse 2.6.0-r0 (Mouse Perl XS module).

Mouse is a lightweight Perl object-oriented framework, Moose-compatible but faster.
Build system: Module::Build (Build.PL) with Module::Build::XSUtil for XS compilation.
Since Module::Build and Module::Build::XSUtil are not available on the CI platform,
this recipe falls back to ExtUtils::MakeMaker (Makefile.PL) and pre-generates the
XS helper files that Module::Build::XSUtil would normally generate.

OHOS adaptations:
- Replace Module::Build with ExtUtils::MakeMaker (Makefile.PL)
- Pre-generate ppport.h using Devel::PPPort (core Perl module)
- Pre-generate xs_version.h
- Generate Mouse::Tiny using tool/generate-mouse-tiny.pl
- Copy XS sources to lib/ for MakeMaker's suffix rules
- Custom MY::postamble for cross-directory .c→.o compilation
- R32: settings.os check uses `in ("Linux", "OHOS")`
"""
import os
import shutil

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches


# xshelper.h — normally generated by Module::Build::XSUtil
# This is a static helper header that includes Perl headers and ppport.h
XSHelperHeader = r"""/* THIS FILE IS AUTOMATICALLY GENERATED BY Module::Build::XSUtil 0.19. */
#ifdef __cplusplus
extern "C" {
#endif

#define PERL_NO_GET_CONTEXT /* we want efficiency */
#include <EXTERN.h>
#include <perl.h>
#define NO_XSLOCKS /* for exceptions */
#include <XSUB.h>

#ifdef __cplusplus
} /* extern "C" */
#endif

#include "ppport.h"

#ifndef STATIC_INLINE
# if defined(__cplusplus) || (defined(__STDC_VERSION__) && (__STDC_VERSION__ >= 199901L))
#   define STATIC_INLINE static inline
# else
#   define STATIC_INLINE static
# endif
#endif

#ifndef __attribute__format__
#define __attribute__format__(a,b,c)
#endif

#ifndef LIKELY
#define LIKELY(x)   (!!(x))
#define UNLIKELY(x) (!!(x))
#endif

#ifndef newSVpvs_share
#define newSVpvs_share(s) Perl_newSVpvn_share(aTHX_ STR_WITH_LEN(s), 0U)
#endif

#ifndef get_cvs
#define get_cvs(name, flags) get_cv(name, flags)
#endif

#ifndef GvNAME_get
#define GvNAME_get GvNAME
#endif
#ifndef GvNAMELEN_get
#define GvNAMELEN_get GvNAMELEN
#endif

#ifndef CvGV_set
#define CvGV_set(cv, gv) (CvGV(cv) = (gv))
#endif

#if PERL_BCDVERSION >= 0x5008005
#define LooksLikeNumber(x) looks_like_number(x)
#else
#define LooksLikeNumber(x) (SvPOKp(x) ? looks_like_number(x) : (I32)SvNIOKp(x))
#endif

#define newAV_mortal()         (AV*)sv_2mortal((SV*)newAV())
#define newHV_mortal()         (HV*)sv_2mortal((SV*)newHV())
#define newRV_inc_mortal(sv)   sv_2mortal(newRV_inc(sv))
#define newRV_noinc_mortal(sv) sv_2mortal(newRV_noinc(sv))

#define DECL_BOOT(name) EXTERN_C XS(CAT2(boot_, name))
#define CALL_BOOT(name) STMT_START {            \
        PUSHMARK(SP);                           \
        CALL_FPTR(CAT2(boot_, name))(aTHX_ cv); \
    } STMT_END
"""


class PerlMouseConan(ConanFile):
    name = "perl-mouse"
    version = "2.6.0-r0"
    description = "Mouse - Lightweight Perl OO framework, Moose-compatible but faster"
    license = "perl_5"
    homepage = "https://metacpan.org/pod/Mouse"
    url = ""  # CI fills this

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # No Conan dependencies — only Perl core modules (Scalar::Util, XSLoader)
        pass

    def layout(self):
        from conan.tools.layout import basic_layout
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        pass

    def build(self):
        apply_conandata_patches(self)

        # R32: platform check
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanException(f"Unsupported OS: {self.settings.os}")

        src = self.source_folder
        xs_src = os.path.join(src, "xs-src")

        # Step 1: Generate ppport.h using Devel::PPPort (core Perl module)
        self.run(
            f'perl -MDevel::PPPort -e "Devel::PPPort::WriteFile(\'{xs_src}/ppport.h\')"',
            cwd=src,
        )

        # Step 2: Write xs_version.h (normally done by Module::Build::XSUtil)
        xs_version_path = os.path.join(xs_src, "xs_version.h")
        with open(xs_version_path, "w") as f:
            f.write('#ifndef XS_VERSION\n')
            f.write('#define XS_VERSION "v2.6.0"\n')
            f.write('#endif\n')

        # Step 2b: Write xshelper.h (normally generated by Module::Build::XSUtil)
        xshelper_path = os.path.join(xs_src, "xshelper.h")
        with open(xshelper_path, "w") as f:
            f.write(XSHelperHeader)

        # Step 3: Generate Mouse::Tiny from tool script
        self.run("perl tool/generate-mouse-tiny.pl", cwd=src)

        # Step 4: Copy XS source files to lib/ for MakeMaker
        # MakeMaker's suffix rules (.xs→.c→.o) only work when .xs files are
        # in the same directory as the expected .pm files.
        xs_names = ["Mouse", "MouseAccessor", "MouseAttribute",
                    "MouseTypeConstraints", "MouseUtil"]
        for name in xs_names:
            src_xs = os.path.join(xs_src, f"{name}.xs")
            dst_xs = os.path.join(src, "lib", f"{name}.xs")
            shutil.copy(src_xs, dst_xs)

        # Step 5: Create Makefile.PL (replaces Build.PL)
        # This Makefile.PL uses ExtUtils::MakeMaker with a custom postamble
        # to handle cross-directory .c→.o compilation (MakeMaker creates .o
        # in the current directory even when .c is in lib/).
        makefile_pl_content = """\
use strict;
use warnings;
use ExtUtils::MakeMaker;

WriteMakefile(
    NAME          => 'Mouse',
    VERSION_FROM  => 'lib/Mouse.pm',
    ABSTRACT_FROM => 'lib/Mouse.pm',
    LICENSE       => 'perl_5',
    AUTHOR         => 'Shawn M Moore <sartak at gmail.com>',

    PREREQ_PM => {
        'Scalar::Util' => 1.14,
        'XSLoader'     => 0.02,
    },

    XS => {
        'lib/Mouse.xs'                => 'lib/Mouse.c',
        'lib/MouseAccessor.xs'        => 'lib/MouseAccessor.c',
        'lib/MouseAttribute.xs'       => 'lib/MouseAttribute.c',
        'lib/MouseTypeConstraints.xs' => 'lib/MouseTypeConstraints.c',
        'lib/MouseUtil.xs'            => 'lib/MouseUtil.c',
    },
    OBJECT => q[Mouse$(OBJ_EXT) MouseAccessor$(OBJ_EXT) MouseAttribute$(OBJ_EXT) MouseTypeConstraints$(OBJ_EXT) MouseUtil$(OBJ_EXT)],
    INC    => '-Ixs-src',
    clean  => {
        FILES => 'xs-src/*.c xs-src/ppport.h xs-src/xs_version.h '
               . 'lib/Mouse*.c lib/Mouse*.xs lib/Mouse*.o '
               . '*.o'
    },
);

# Custom compile rules: .c (in lib/) -> .o (in current dir)
# MakeMaker's default .c->.o suffix rule doesn't handle cross-directory paths.
package MY;
sub postamble {
    my @rules;
    for my $name (qw(Mouse MouseAccessor MouseAttribute MouseTypeConstraints MouseUtil)) {
        my $obj = "$name\\$(OBJ_EXT)";
        my $src = "lib/$name.c";
        push @rules, "$obj: $src\\n\\t\\$(CCCMD) \\$(CCCDLFLAGS) \\"-I\\$(PERL_INC)\\" \\$(PASTHRU_DEFINE) \\$(DEFINE) -Ixs-src $src\\n";
    }
    return join("\\n\\n", @rules) . "\\n";
}
"""
        makefile_pl_path = os.path.join(src, "Makefile.PL")
        with open(makefile_pl_path, "w") as f:
            f.write(makefile_pl_content)

        # Step 6: Generate Makefile with INSTALL_BASE pointing to package dir
        # MakeMaker installs to INSTALL_BASE/lib/perl5/$arch/, so set INSTALL_BASE
        # to the package folder directly (not package_folder/lib/perl5)
        self.run(f'perl Makefile.PL INSTALL_BASE="{self.package_folder}"', cwd=src)
        self.run("make -j1", cwd=src)

    def package(self):
        src = self.source_folder
        # Install using the INSTALL_BASE set during Makefile.PL generation
        self.run("make install", cwd=src)

    def package_info(self):
        # Mouse.so is a Perl XS shared library loaded by XSLoader at runtime
        import glob
        perl_lib = os.path.join(self.package_folder, "lib", "perl5")

        # Find arch-specific directory (e.g., lib/perl5/aarch64-linux)
        arch_dirs = glob.glob(os.path.join(perl_lib, "*"))
        for d in arch_dirs:
            if os.path.isdir(d):
                self.runenv_info.append_path("PERL5LIB", d)
                self.output.info(f"PERL5LIB arch path: {d}")
                break

        # No cpp_info.libs — this is a Perl XS module, not a linkable C library
