#!/bin/sh
# pcb 4.3.0 test driver (test_package)
# Usage: run_pcb_tests.sh <pcb-binary> <data-dir>
#
# 测试构成（计数口径与 conanfile.py docstring / CMakeLists.txt /
# MANIFEST.yml / 版本 manifest.yaml / PR 描述五处同步，共 14 断言）:
#   [UP] 上游行为复现 3 场景 / 7 断言: 使用 pcb 官方 tests/inputs 输入 +
#        tests/golden 文本输出比对（归一化仅剔除 pcb 写出的时间戳/版本/
#        作者头行，语义与上游 run_tests.sh 的 awk 归一化一致）:
#          U1 hid_bom1    bom/xy 单次导出 == golden/hid_bom1   (导出+2 比对)
#          U2 hid_bom_md1 bom_md 导出 == golden/hid_bom_md1    (导出+1 比对)
#          U3 hid_ipcd3561 IPC-D-356 netlist == golden/hid_ipcd3561 (导出+1 比对)
#   [NEW] 新增错误路径/边界 7 断言 (上游回归套件未覆盖):
#          N1 --version 输出含 4.3.0
#          N2 --help 正常列出导出 HID（bom/gerber/IPC-D-356）
#          N3 缺输入文件 -> rc=0 无崩溃（上游 NULL 解引用修复回归守护）
#          N4 非法 PCB 内容 -> 非零退出
#          N5 未知导出驱动 -x nosuch -> 非零退出
#          N6 未知命令行选项 -> 非零退出
#          N7 空(0字节)输入文件 -> rc=0 无崩溃（上游 NULL 解引用修复回归守护）
set -u

PCB="$1"
DATADIR="$2"
WORKDIR="${TMPDIR:-.}/pcb_test_work"
rm -rf "$WORKDIR"
mkdir -p "$WORKDIR"

total=0
failed=0

note_fail() {
    name="$1"
    why="$2"
    failed=$((failed + 1))
    echo "FAIL [$name] $why"
}

# ---------- 归一化: 剔除时间戳/版本/作者头行 (上游 golden 由旧版 pcb 生成) ----------
norm() {
    grep -v '^G04 CreationDate:' "$1" \
        | grep -v '^# Date:' \
        | grep -v '^Date:' \
        | grep -v '^G04 Creator:' \
        | grep -v '^C  File created on' \
        | grep -v '^C  IPC-D-356 Netlist generated by' \
        | grep -v '^# Author:' \
        | grep -v '^Author:'
}

check_golden() {
    name="$1"
    outfile="$2"
    golden="$3"
    total=$((total + 1))
    if [ ! -f "$outfile" ]; then
        note_fail "$name" "output missing: $outfile"
        return
    fi
    norm "$outfile" >"$WORKDIR/$name.norm.out"
    norm "$golden" >"$WORKDIR/$name.norm.gold"
    if diff -u "$WORKDIR/$name.norm.gold" "$WORKDIR/$name.norm.out" >"$WORKDIR/$name.diff" 2>&1; then
        echo "PASS [$name] (upstream golden compare, date/version/author lines normalized)"
    else
        note_fail "$name" "golden mismatch (normalized)"
        head -24 "$WORKDIR/$name.diff" | sed 's/^/    | /'
    fi
}

expect_rc() {
    name="$1"
    expected="$2"
    shift 2
    if [ "$1" = "--" ]; then
        shift
    fi
    total=$((total + 1))
    "$@" >"$WORKDIR/$name.out" 2>"$WORKDIR/$name.err"
    rc=$?
    if [ "$rc" -eq "$expected" ]; then
        echo "PASS [$name] (rc=$rc)"
    else
        note_fail "$name" "expected rc=$expected got rc=$rc"
        sed 's/^/    | /' "$WORKDIR/$name.err" | head -12
    fi
}

# 每个 U 场景: 输入 .pcb 拷入 WORKDIR，相对路径运行（与上游 run_tests.sh
# 同款：导出文件名/内容取自输入 basename，IPC-D-356 JOB 行 = 相对文件名）

# ---------- U1: bom 单次导出 bom+xy (upstream tests/list hid_bom1) ----------
cp "$DATADIR/inputs/bom_general.pcb" "$WORKDIR/"
expect_rc U1_bom_export 0 -- sh -c "cd \"$WORKDIR\" && \"$PCB\" -x bom bom_general.pcb"
check_golden U1_bom_golden "$WORKDIR/bom_general.bom" "$DATADIR/golden/hid_bom1/bom_general.bom"
check_golden U1_xy_golden "$WORKDIR/bom_general.xy" "$DATADIR/golden/hid_bom1/bom_general.xy"

# ---------- U2: bom_md (upstream tests/list hid_bom_md1) ----------
expect_rc U2_bommd_export 0 -- sh -c "cd \"$WORKDIR\" && \"$PCB\" -x bom_md bom_general.pcb"
check_golden U2_bommd_golden "$WORKDIR/bom_general.bom.md" "$DATADIR/golden/hid_bom_md1/bom_general.bom.md"

# ---------- U3: IPC-D-356 netlist (upstream tests/list hid_ipcd3561) ----------
cp "$DATADIR/inputs/ipcd356_board.pcb" "$WORKDIR/"
expect_rc U3_ipcd_export 0 -- sh -c "cd \"$WORKDIR\" && \"$PCB\" -x IPC-D-356 ipcd356_board.pcb"
check_golden U3_ipcd356_golden "$WORKDIR/ipcd356_board.net" "$DATADIR/golden/hid_ipcd3561/ipcd356_board.net"

# ---------- N1: version 含 4.3.0 ----------
total=$((total + 1))
if "$PCB" --version >"$WORKDIR/n1.out" 2>&1 && grep -q '4\.3\.0' "$WORKDIR/n1.out"; then
    echo "PASS [N1_version]"
else
    note_fail N1_version "missing 4.3.0 in: $(head -2 "$WORKDIR/n1.out" | tr '\n' ' ')"
fi

# ---------- N2: help 列出导出 HID（上游 pcb --help 以 rc=1 退出为惯例） ----------
total=$((total + 1))
if "$PCB" --help >"$WORKDIR/n2.out" 2>&1; then
    n2_rc=0
else
    n2_rc=$?
fi
if [ "$n2_rc" -le 1 ] && grep -qE 'bom|gerber|IPC-D-356' "$WORKDIR/n2.out"; then
    echo "PASS [N2_help_export_hids] (rc=$n2_rc)"
else
    note_fail N2_help_export_hids "help rc=$n2_rc or export HIDs not listed"
fi

# ---------- N3: 缺输入文件 -> rc=0 无崩溃
# (上游 pcb_author/getpwuid 修复前该路径 SIGSEGV → 无崩溃回归守护) ----------
expect_rc N3_missing_input 0 -- sh -c "cd \"$WORKDIR\" && \"$PCB\" -x bom --bomfile x.bom no_such_file.pcb"

# ---------- N4: 非法 PCB 内容 -> 非零 ----------
printf 'this is not a pcb file at all\n%%%% garbage\n' >"$WORKDIR/bad.pcb"
expect_rc N4_bad_input 1 -- sh -c "cd \"$WORKDIR\" && \"$PCB\" -x bom --bomfile bad.bom bad.pcb"

# ---------- N5: 未知导出驱动 -> 非零 ----------
expect_rc N5_unknown_hid 1 -- "$PCB" -x nosuchdriver "$DATADIR/inputs/bom_general.pcb"

# ---------- N6: 未知选项 -> 非零 ----------
expect_rc N6_bad_option 1 -- "$PCB" --definitely-not-an-option

# ---------- N7: 空(0 字节)输入文件 -> rc=0 无崩溃（边界, 修复前 SIGSEGV） ----------
: >"$WORKDIR/empty.pcb"
expect_rc N7_empty_input 0 -- sh -c "cd \"$WORKDIR\" && \"$PCB\" -x bom --bomfile empty.bom empty.pcb"

echo "----------------------------------------------"
echo "pcb tests: total=$total failed=$failed (UP 7 + NEW 7)"
if [ "$failed" -ne 0 ]; then
    echo "pcb tests: FAILED"
    exit 1
fi
echo "pcb tests: ALL PASSED"
exit 0
