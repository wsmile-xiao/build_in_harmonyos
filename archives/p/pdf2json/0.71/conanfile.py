#!/usr/bin/env python3
"""Conan recipe — pdf2json 0.71 (Autotools)

PDF to JSON and XML converter based on XPDF 3.02.
Build system: autotools (configure + make).
The package produces command-line tools (pdf2json, pdftops, pdftotext,
pdfinfo, pdffonts, pdfimages) and a config file (xpdfrc).
License: GPL-2.0-only
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain


class Pdf2JsonConan(ConanFile):
    name = "pdf2json"
    version = "0.71"
    description = "PDF to JSON and XML converter based on XPDF 3.02"
    license = "GPL-2.0-only"
    homepage = "https://github.com/flexpaper/pdf2json"
    url = ""

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        # pdf2json does not support out-of-source builds.
        # Build in the source folder so Makefiles can find source files.
        self.folders.build = "."
        self.folders.generators = "."

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure()
        # Create empty Makefile.dep files required by sub-directory Makefiles.
        # These are normally generated by 'make depend' but are absent in
        # fresh source trees.
        for subdir in ["goo", "fofi", "splash", "xpdf"]:
            dep_file = os.path.join(self.build_folder, subdir, "Makefile.dep")
            if not os.path.exists(dep_file):
                with open(dep_file, "w") as f:
                    pass
        autotools.make(args=["-j1"])

    def package(self):
        # OHOS has no 'install' binary, so we manually copy build outputs
        # instead of running 'make install'.
        bin_dst = os.path.join(self.package_folder, "bin")
        etc_dst = os.path.join(self.package_folder, "etc")
        man1_dst = os.path.join(self.package_folder, "share", "man", "man1")
        man5_dst = os.path.join(self.package_folder, "share", "man", "man5")

        binaries = [
            "src/pdf2json",
            "xpdf/pdftops",
            "xpdf/pdftotext",
            "xpdf/pdfinfo",
            "xpdf/pdffonts",
            "xpdf/pdfimages",
        ]
        for binary in binaries:
            copy(self, os.path.basename(binary),
                 src=os.path.join(self.build_folder, os.path.dirname(binary)),
                 dst=bin_dst)

        # Copy xpdfrc config (renamed from sample-xpdfrc)
        copy(self, "sample-xpdfrc", src=os.path.join(self.build_folder, "doc"),
             dst=etc_dst)
        os.rename(os.path.join(etc_dst, "sample-xpdfrc"),
                  os.path.join(etc_dst, "xpdfrc"))

        man1_pages = ["pdftops.1", "pdftotext.1", "pdfinfo.1",
                      "pdffonts.1", "pdfimages.1"]
        for page in man1_pages:
            copy(self, page, src=os.path.join(self.build_folder, "doc"),
                 dst=man1_dst)

        copy(self, "xpdfrc.5", src=os.path.join(self.build_folder, "doc"),
             dst=man5_dst)

    def package_info(self):
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
