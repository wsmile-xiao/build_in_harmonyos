#!/usr/bin/env python3
"""Conan recipe — pamixer 1.6

Pulseaudio command line mixer.
A CLI tool to control the volume of PulseAudio sinks/sources.

Build system: meson (upstream), but we compile the four upstream sources
directly with the profile compiler (mirroring the upstream meson.build
source list) because OHOS CI workers resolve the meson/cmake compiler
probe through a broken linker environment (E501):

The OHOS SDK lld loads libxml2.so.16 via its RUNPATH ($ORIGIN/../lib).
Any LD_LIBRARY_PATH entry that shadows it with an unloadable copy
(e.g. a Conan-cached shared libxml2) breaks every link command with
"Error loading shared library libxml2.so.16". Prepending the SDK's own
llvm/lib dir to LD_LIBRARY_PATH around the link command neutralizes the
shadowing (validated pattern from lua/5.1, PR !4635 / knowledge E501).

Dependencies:
- pulseaudio/17.0 (provides libpulse headers and libs)
- cxxopts/3.3.1.1 (header-only command line parser, from ohpcd registry)
"""
import os
import shlex

from conan import ConanFile
from conan.tools.env import Environment
from conan.tools.files import get, copy, save, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class PamixerConan(ConanFile):
    name = "pamixer"
    version = "1.6"
    description = "Pulseaudio command line mixer"
    license = "GPL-3.0"
    homepage = "https://github.com/cdemoulins/pamixer"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("pulseaudio/17.0")
        self.requires("cxxopts/3.3.1.1")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _link_env(self):
        # E501: ensure lld finds the SDK's own libxml2.so.16 first,
        # before any LD_LIBRARY_PATH entry shadowing it.
        env = Environment()
        if self.settings.os == "OHOS":
            sdk_root = "/data/service/hnp/ohos-sdk.org"
            if os.path.isdir(sdk_root):
                for entry in sorted(os.listdir(sdk_root), reverse=True):
                    llvm_lib = os.path.join(sdk_root, entry, "ohos", "native", "llvm", "lib")
                    if os.path.isdir(llvm_lib):
                        env.prepend_path("LD_LIBRARY_PATH", llvm_lib)
                        break
        return env

    def build(self):
        apply_conandata_patches(self)

        # Create config.hh (normally generated by meson's configure_file)
        save(self, os.path.join(self.source_folder, "config.hh"),
             '#define VERSION "1.6"\n')

        # Collect include dirs, lib dirs, and lib names from dependencies
        pulse = self.dependencies["pulseaudio"]
        cxxopts = self.dependencies["cxxopts"]
        include_dirs = []
        lib_dirs = []
        lib_names = []
        system_libs = []

        for comp_name, comp in pulse.cpp_info.components.items():
            include_dirs.extend(comp.includedirs or [])
            lib_dirs.extend(comp.libdirs or [])
            lib_names.extend(comp.libs or [])
            system_libs.extend(comp.system_libs or [])

        include_dirs.extend(pulse.cpp_info.includedirs or [])
        lib_dirs.extend(pulse.cpp_info.libdirs or [])
        include_dirs.extend(cxxopts.cpp_info.includedirs or [])

        def unique(seq):
            seen = set()
            return [x for x in seq if not (x in seen or seen.add(x))]

        include_dirs = unique(include_dirs)
        lib_dirs = unique(lib_dirs)
        lib_names = unique(lib_names)
        system_libs = unique(system_libs)

        include_flags = " ".join(shlex.quote(f"-I{d}") for d in [
            self.source_folder,
            os.path.join(self.source_folder, "src"),
        ] + include_dirs)

        libdir_flags = " ".join(shlex.quote(f"-L{d}") for d in lib_dirs)
        lib_flags = " ".join(f"-l{l}" for l in lib_names + system_libs)

        src_dir = os.path.join(self.source_folder, "src")
        sources = " ".join(shlex.quote(os.path.join(src_dir, f)) for f in
                           ["callbacks.cc", "device.cc", "pamixer.cc", "pulseaudio.cc"])

        # R33: compiler from Conan conf, not from shell env
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        )
        cxx = compilers.get("cpp", "clang++")

        cmd = " ".join([
            shlex.quote(cxx), "-std=c++11", "-fPIC", "-O2",
            include_flags, sources, libdir_flags, lib_flags,
            "-o", "pamixer",
        ])
        # E501: wrap the link so lld finds the SDK's libxml2.so.16 first
        with self._link_env().vars(self).apply():
            self.run(cmd)

    def package(self):
        copy(self, "pamixer", self.build_folder, os.path.join(self.package_folder, "bin"))
        copy(self, "pamixer.1", self.source_folder,
             os.path.join(self.package_folder, "share", "man", "man1"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.requires = ["pulseaudio::pulse", "cxxopts::cxxopts"]
