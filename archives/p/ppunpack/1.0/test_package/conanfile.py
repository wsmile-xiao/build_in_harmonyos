#!/usr/bin/env python3
"""Conan test_package — ppunpack 1.0.

Upstream test (the only one): the Makefile target

      check: sf            sf: ppunpack
          diff sf sf.chk       ppunpack sf.pp sf

  Its data files sf.pp / sf.chk are not in ppsmall-1.0.tar.Z (the package
  source); Aminet ships them in the long ppunpack-1.0.tar.Z, whose program
  sources are byte-identical to ppsmall's.  test() downloads that archive from
  the official Aminet mirrors (sha256 pinned), takes only sf.pp and sf.chk,
  runs the installed bin/ppunpack exactly as the target does and compares the
  result byte for byte (what diff does).  Case U1 below.

Additional cases (PP20 inputs generated by pp20.py, restored byte for byte):

  1. usage banner: no arguments -> exit 1, "ppunpack 1.0" + "Usage:";
  2. text round trip (literal runs + 2/3/4-byte matches);
  3. 700 000-byte round trip that must use every code path of depack.c
     (literal runs, 2/3/4-byte matches, 5+ matches with 7-bit and 13-bit
     offsets) — the encoder reports which paths it emitted;
  4. one-byte payload (single literal, loop termination);
  5. a non-PP20 file -> exit 10, "not a powerpacked file", no output written;
  6. a missing input -> exit 10, "can't open input file";
  7. [HarmonyOS-specific] consumer flow on the OHOS toolchain:
     precondition — bin/ppunpack is the OHOS artefact (ELF64 AArch64, OHOS NDK
     ".note.ohos.ident", static PIE without PT_INTERP, so it does not need
     /lib/ld-musl-aarch64.so.1);
     a) consumer.c is PP20-packed and restored by ppunpack — the tool's output
        is the source that gets built, and must equal consumer.c byte for byte;
     b) the restored source is compiled with the profile's OHOS compiler
        (tools.build:compiler_executables) into an AArch64 static PIE;
     c) the consumer runs and drives ppunpack as a child process
        (fork/execv/waitpid on OHOS musl): it restores the 700 000-byte PP20
        file, memcmp()s the result, and checks that a plain file is refused
        with exit 10 and no output.

The binary runs natively on an AArch64 runner (the HarmonyOS CI device) and
through qemu-aarch64 elsewhere; a non-AArch64 runner without qemu-aarch64 is
a failure, never a skip.
"""
import io
import os
import platform
import shlex
import shutil
import sys
import tarfile

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.files import download
from conan.tools.layout import basic_layout

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pp20  # noqa: E402  (test helper next to this file)

EM_AARCH64 = 183
ET_DYN = 3

# Upstream test data: Aminet misc/unix/ppunpack-1.0.tar.Z ("long version").
UPSTREAM_TEST_URLS = [
    "https://ftp.fau.de/aminet/misc/unix/ppunpack-1.0.tar.Z",
    "https://aminet.net/misc/unix/ppunpack-1.0.tar.Z",
]
UPSTREAM_TEST_SHA256 = "1b06fd4d699b2e543ff06c6258082057098be0f379d815dae6925e4e8c9f13be"


def _payload_big():
    lines = [b"%06d the quick brown fox jumps over the lazy dog %s\n"
             % (i % 997, b"*" * (i % 23)) for i in range(12000)]
    blob = b"".join(lines)
    noise = bytes((i * 2654435761 >> 13) & 0xFF for i in range(40000))
    return (blob + noise + blob[:120000])[:700000]


class PpunpackTestConan(ConanFile):
    settings = "os", "arch", "compiler", "build_type"
    test_type = "explicit"

    def requirements(self):
        self.requires(self.tested_reference_str)

    def layout(self):
        # keeps the generated .pp/.out files out of the recipe directory
        basic_layout(self)

    def _fail(self, msg):
        raise ConanException("ppunpack test failed: " + msg)

    def _ppunpack(self, *args, cwd=None):
        cmd = " ".join([self._runner, shlex.quote(self._tool)]
                       + [shlex.quote(a) for a in args]).strip()
        out, err = io.StringIO(), io.StringIO()
        rc = self.run(cmd, stdout=out, stderr=err, ignore_errors=True,
                      env="conanrun", cwd=cwd)
        return rc, out.getvalue() + err.getvalue()

    def _upstream_check(self):
        """Upstream "make check": ppunpack sf.pp sf && diff sf sf.chk."""
        workdir = os.path.join(self.build_folder, "upstream-check")
        os.makedirs(workdir, exist_ok=True)
        archive = os.path.join(workdir, "ppunpack-1.0.tar.Z")
        download(self, UPSTREAM_TEST_URLS, archive, sha256=UPSTREAM_TEST_SHA256)
        with open(archive, "rb") as handle:
            tar_bytes = pp20.unlzw(handle.read())
        wanted = {"PPUnpack/sf.pp": "sf.pp", "PPUnpack/sf.chk": "sf.chk"}
        with tarfile.open(fileobj=io.BytesIO(tar_bytes)) as tar:
            for member, name in wanted.items():
                with open(os.path.join(workdir, name), "wb") as handle:
                    handle.write(tar.extractfile(member).read())
        result = os.path.join(workdir, "sf")
        if os.path.exists(result):
            os.remove(result)
        rc, log = self._ppunpack("sf.pp", "sf", cwd=workdir)
        if rc != 0:
            self._fail("upstream check: 'ppunpack sf.pp sf' exit %d: %s" % (rc, log))
        with open(result, "rb") as got, open(os.path.join(workdir, "sf.chk"), "rb") as exp:
            got_b, exp_b = got.read(), exp.read()
        if got_b != exp_b:
            self._fail("upstream check: sf (%d bytes) differs from sf.chk (%d bytes)"
                       % (len(got_b), len(exp_b)))
        self.output.info("ok   U1 upstream make check: ppunpack sf.pp sf -> %d bytes, "
                         "identical to sf.chk" % len(got_b))

    def _roundtrip(self, name, data, need_paths=()):
        blob, stats = pp20.encode(data)
        missing = [p for p in need_paths if not stats[p]]
        if missing:
            self._fail("%s: encoder did not emit %s (%s)" % (name, missing, stats))
        packed = os.path.join(self.build_folder, name + ".pp")
        unpacked = os.path.join(self.build_folder, name + ".out")
        with open(packed, "wb") as handle:
            handle.write(blob)
        if os.path.exists(unpacked):
            os.remove(unpacked)
        rc, log = self._ppunpack(packed, unpacked)
        if rc != 0:
            self._fail("%s: exit %d: %s" % (name, rc, log))
        with open(unpacked, "rb") as handle:
            got = handle.read()
        if got != data:
            self._fail("%s: %d bytes restored, %d expected, first diff at %s" % (
                name, len(got), len(data),
                next((i for i, (a, b) in enumerate(zip(got, data)) if a != b),
                     min(len(got), len(data)))))
        self.output.info("ok   %s: %d -> %d bytes PP20 restored exactly %s"
                         % (name, len(data), len(blob), stats))
        return packed, data

    def _consumer_case(self, big_pp, big_data):
        """Case 7: ppunpack output -> OHOS build -> run (see module docstring)."""
        workdir = os.path.join(self.build_folder, "consumer")
        os.makedirs(workdir, exist_ok=True)
        src = os.path.join(self.recipe_folder, "consumer.c")
        with open(src, "rb") as handle:
            source = handle.read()
        packed = os.path.join(workdir, "consumer.c.pp")
        restored = os.path.join(workdir, "consumer.c")
        with open(packed, "wb") as handle:
            handle.write(pp20.encode(source)[0])
        if os.path.exists(restored):
            os.remove(restored)
        rc, log = self._ppunpack(packed, restored)
        if rc != 0:
            self._fail("case 7a: ppunpack exit %d on consumer.c.pp: %s" % (rc, log))
        with open(restored, "rb") as handle:
            if handle.read() != source:
                self._fail("case 7a: restored consumer.c differs from the original")
        self.output.info("ok   7a consumer.c restored by ppunpack (%d bytes)" % len(source))

        compilers = self.conf.get("tools.build:compiler_executables",
                                  check_type=dict, default={})
        cc = compilers.get("c")
        if not cc:
            self._fail("case 7b: profile has no tools.build:compiler_executables c")
        exe = os.path.join(workdir, "ppunpack_consumer")
        if os.path.exists(exe):
            os.remove(exe)
        self.run("%s -O2 -fPIE -static-pie -o %s %s" % (
            shlex.quote(cc), shlex.quote(exe), shlex.quote(restored)), env="conanbuild")
        elf = pp20.elf_facts(exe)
        if (not elf.get("elf") or elf.get("e_machine") != EM_AARCH64
                or "OHOS" not in elf["note_owners"]
                or elf.get("e_type") != ET_DYN or elf.get("interp") is not None):
            self._fail("case 7b: consumer is not an OHOS AArch64 static PIE: %s" % elf)
        self.output.info("ok   7b consumer built with %s (OHOS AArch64 static PIE)" % cc)

        expected = os.path.join(workdir, "big.expected")
        with open(expected, "wb") as handle:
            handle.write(big_data)
        args = [exe, self._tool, big_pp, expected, workdir]
        if self._runner:
            args.append(self._qemu)
        cmd = " ".join(([self._runner] if self._runner else []) + [shlex.quote(a) for a in args])
        out = io.StringIO()
        rc = self.run(cmd, stdout=out, ignore_errors=True, env="conanrun")
        self.output.info(out.getvalue().rstrip())
        if rc != 0 or "consumer ok" not in out.getvalue():
            self._fail("case 7c: consumer exit %d" % rc)
        self.output.info("ok   7c consumer ran ppunpack via fork/execv and verified the output")

    def test(self):
        self._tool = os.path.join(
            self.dependencies["ppunpack"].package_folder, "bin", "ppunpack")
        if not os.path.isfile(self._tool):
            self._fail("bin/ppunpack not packaged")

        # 7 (precondition). the packaged binary is the OHOS artefact.
        elf = pp20.elf_facts(self._tool)
        if not (elf.get("elf") and elf.get("class64") and elf.get("le")):
            self._fail("bin/ppunpack is not an ELF64 little-endian file: %s" % elf)
        if elf["e_machine"] != EM_AARCH64:
            self._fail("e_machine %d, expected AArch64 (183)" % elf["e_machine"])
        if "OHOS" not in elf["note_owners"]:
            self._fail("no OHOS NDK .note.ohos.ident note (owners %s)" % elf["note_owners"])
        if elf["e_type"] != ET_DYN or elf["interp"] is not None:
            self._fail("expected a static PIE (ET_DYN, no PT_INTERP), got e_type=%d interp=%r"
                       % (elf["e_type"], elf["interp"]))
        self.output.info("ok   OHOS artefact: ELF64 AArch64, note owners %s, static PIE"
                         % elf["note_owners"])

        if platform.machine().lower() in ("aarch64", "arm64"):
            self._runner = self._qemu = ""
        else:
            qemu = shutil.which("qemu-aarch64")
            if not qemu:
                self._fail("non-AArch64 runner (%s) and no qemu-aarch64: "
                           "cannot execute the target binary" % platform.machine())
            self._qemu = qemu
            self._runner = shlex.quote(qemu)
        self.output.info("runner: %s" % (self._runner or "native"))

        # U1. upstream test
        self._upstream_check()

        # 1. usage banner
        rc, log = self._ppunpack()
        if rc != 1 or "ppunpack 1.0" not in log or "Usage:" not in log:
            self._fail("usage: exit %d, output %r" % (rc, log))
        self.output.info("ok   usage banner (exit 1)")

        # 2-4. round trips
        text = (b"PowerPacker was written on the Amiga by Nico Francois.\n"
                b"ppunpack decrunches PP20 data files on other machines.\n") * 12
        self._roundtrip("text", text, need_paths=("lit",))
        big_pp, big_data = self._roundtrip(
            "big", _payload_big(),
            need_paths=("lit", "m2", "m3", "m4", "m5_short", "m5_long"))
        self._roundtrip("one", b"Z", need_paths=("lit",))

        # 5. not a PowerPacker file
        plain = os.path.join(self.build_folder, "plain.txt")
        refused = os.path.join(self.build_folder, "plain.out")
        with open(plain, "wb") as handle:
            handle.write(b"PK\x03\x04 this is not PP20 data\n")
        if os.path.exists(refused):
            os.remove(refused)
        rc, log = self._ppunpack(plain, refused)
        if rc != 10 or "not a powerpacked file" not in log or os.path.exists(refused):
            self._fail("non-PP20 input: exit %d, output %r, out file %s"
                       % (rc, log, os.path.exists(refused)))
        self.output.info("ok   non-PP20 input refused (exit 10)")

        # 6. missing input
        rc, log = self._ppunpack(os.path.join(self.build_folder, "absent.pp"),
                                 os.path.join(self.build_folder, "absent.out"))
        if rc != 10 or "can't open input file" not in log:
            self._fail("missing input: exit %d, output %r" % (rc, log))
        self.output.info("ok   missing input refused (exit 10)")

        # 7. [HarmonyOS-specific] consumer flow
        self._consumer_case(big_pp, big_data)
        self.output.info("all 8 ppunpack checks passed (upstream 1/1, added 7/7)")
