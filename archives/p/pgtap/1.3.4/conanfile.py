#!/usr/bin/env python3
"""Conan recipe - pgTAP 1.3.4 (PostgreSQL TAP unit-testing extension).

pgTAP is a pure SQL / PLpgSQL PostgreSQL extension: the TAP-emitting
assertion API (plan / ok / is / has_table / col_not_null / ...) plus the TAP
harness functions (runtests / ckreserve).  There is no C module and no
compiled artifact - upstream builds it with plain PGXS, and the only "build"
work is generating the install SQL scripts with ``make all``:

  * ``sql/pgtap.sql``          full extension SQL (sql/pgtap.sql.in with
                               __OS__ / __VERSION__ substituted)
  * ``sql/pgtap--1.3.4.sql``   versioned install script (copy of the above)
  * ``sql/pgtap-core--1.3.4.sql`` / ``pgtap-schema--1.3.4.sql``
                               generated by compat/gencore (Perl)
  * ``sql/uninstall_pgtap.sql`` generated by an upstream Perl one-liner
  * ``sql/pgtap--*--*.sql``    historical upgrade scripts (copies of *.in)

OHOS PC adaptation notes (PG 18.3, clang 15, musl, HMDFS):

1. PostgreSQL is a ``tool_requires``.  The published ohpcd recipe
   ``postgresql/18.3`` is a complete PostgreSQL installation: ``bin/pg_config``,
   PGXS makefiles (``lib/postgresql/pgxs``), server headers and the
   ``postgres`` / ``initdb`` / ``pg_ctl`` / ``psql`` / ``createdb`` tools.
   pg_config is passed to make explicitly (same pattern as the pgvector and
   pgroonga recipes in this repository); no PostgreSQL source tree is
   vendored into this archive.

2. Perl is a ``tool_requires``.  ``sql/uninstall_pgtap.sql`` and the
   pgtap-core / pgtap-schema bundles are generated by upstream Perl scripts
   (``compat/gencore``).  The conan ``perl`` package is installed with an
   empty prefix, so its built-in @INC resolves to ``//lib/perl5/...``; the
   recipe therefore pins PERL5LIB to ``<perl package>/lib/perl5`` so that
   ``strict`` / ``warnings`` are found by the Perl scripts.

3. ``OSNAME=harmonyos`` is passed to make.  The upstream Makefile derives the
   body of ``os_name()`` from ``tools/getos.sh`` (a Perl Configure uname
   parser).  On OHOS that parser can emit nothing depending on the invoking
   shell (observed on device: ``command -v sed`` returns the shell's alias
   definition, so getos.sh runs ``alias sed=sed -e ...`` and fails), which
   makes ``os_name()`` return '' and breaks the upstream test
   ``matches(os_name(), '^[[:alnum:]]+$')``.  Pinning the documented make
   variable yields a deterministic, platform-truthful artifact on every build
   machine (device and CI alike).

4. Zero source patches: PostgreSQL 18.3 satisfies every Makefile version
   gate, so the ``compat/install-*.patch`` branches (PostgreSQL <= 10) are
   inactive and ``patches/`` does not exist.
"""
import os

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
)
from conan.tools.layout import basic_layout


class PgtapConan(ConanFile):
    name = "pgtap"
    version = "1.3.4"
    description = ("Unit testing for PostgreSQL: TAP-emitting SQL/PLpgSQL "
                   "assertion functions and TAP harness (pg_prove support)")
    license = "PostgreSQL"
    homepage = "https://pgtap.org/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    # The deliverable is an extension control file + SQL scripts consumed from
    # PostgreSQL's share/extension directory, not a link library.
    package_type = "library"
    # Conan requires the ``shared`` option for package_type="library"; it is
    # declarative only here (no compiled artifact exists either way).
    options = {"shared": [True, False]}
    default_options = {"shared": True}

    settings = "os", "arch", "compiler", "build_type"

    # Upstream regression assets vendored into the package for the consumer
    # harness (test_package): 37 pg_regress groups (test/sql + test/expected)
    # plus the psql/setup helpers and the static pgtap.sql used by build.sql.
    _UPSTREAM_TEST_DIRS = ("test/sql", "test/expected")

    def configure(self):
        # The OHOS profile declares settings.os.version=6.0, but neither the
        # build nor the package_id depends on it.  Drop it so the package is
        # not held invalid by an undeclared setting value (same pattern as
        # archives/p/pgvector/0.8.6).
        self.settings.rm_safe("os.version")

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def validate(self):
        # R32: the platform guard must accept Linux and OHOS alike
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "pgtap is only supported on Linux/OHOS, not "
                f"{self.settings.os}"
            )
        if self.settings.os == "OHOS" and self.settings.arch != "armv8":
            raise ConanInvalidConfiguration(
                "OHOS builds require armv8/aarch64"
            )

    def build_requirements(self):
        # pg_config + PGXS makefiles + (for test_package) a full server.
        self.tool_requires("postgresql/18.3")
        # Upstream generation scripts need Perl (compat/gencore + the
        # uninstall_pgtap.sql one-liner).
        self.tool_requires("perl/5.42.2.3")

    def source(self):
        sources = self.conan_data["sources"]
        url = sources["url"]
        sha256 = sources["sha256"]
        # ``url`` can be:
        #   * a plain string (normal recipe export, or conan-verify's
        #     temporarily ghfast.top-prefixed URL),
        #   * a list (the CI build_and_test.sh mirror fallback rewrites
        #     GitHub URLs into a mirror+official list, and its pre-download
        #     step then rewrites the entries to file:// paths).
        candidates = list(url) if isinstance(url, (list, tuple)) else [url]
        # When a candidate carries an embedded official GitHub URL behind a
        # mirror prefix (e.g. https://<mirror>/https://github.com/...), append
        # the plain official URL as a last-resort fallback.  The sha256 covers
        # the same bytes either way.
        for candidate in list(candidates):
            embedded = candidate.find("https://github.com")
            if embedded > 0:
                candidates.append(candidate[embedded:])
        # De-duplicate while preserving the configured order.
        ordered = []
        for candidate in candidates:
            if candidate not in ordered:
                ordered.append(candidate)

        last_error = None
        for candidate in ordered:
            try:
                get(self, url=candidate, sha256=sha256, strip_root=True)
                return
            except ConanException as exc:
                last_error = exc
                self.output.warning(f"source download failed ({candidate}): "
                                    f"{exc}")
        if last_error is not None:
            raise last_error
        raise ConanException("no source URL configured")

    def _bindir_of(self, name):
        """Absolute bin/ directory contributed by a tool_requires."""
        dep = self.dependencies.build[name]
        for bindir in dep.cpp_info.bindirs:
            if os.path.isdir(bindir):
                return bindir
        raise ConanException(
            f"{name} tool_requires did not contribute a bin/ directory"
        )

    def build(self):
        # No patches are carried (PostgreSQL 18.3 satisfies every Makefile
        # version gate); the call is the repository-standard entry point and
        # remains a no-op with an empty patch list.
        apply_conandata_patches(self)

        pg_bindir = self._bindir_of("postgresql")
        pg_config = os.path.join(pg_bindir, "pg_config")
        if not os.path.isfile(pg_config):
            raise ConanException(
                f"pg_config not found in postgresql package: {pg_bindir}"
            )

        perl_dep = self.dependencies.build["perl"]
        perl = os.path.join(self._bindir_of("perl"), "perl")
        if not os.path.isfile(perl):
            raise ConanException("perl executable not found in perl package")
        # The conan perl package is installed with an empty prefix: its built
        # in @INC points at ``//lib/perl5/...``.  Point PERL5LIB at the real
        # module tree so strict/warnings are found.
        perl5lib = os.path.join(perl_dep.package_folder, "lib", "perl5")

        jobs = max(1, os.cpu_count() or 1)
        # PERL5LIB is exported inline (the conan perl package is installed
        # with an empty prefix, so its built-in @INC points at
        # ``//lib/perl5/...``; compat/gencore needs strict/warnings).
        self.run(
            f'PERL5LIB="{perl5lib}" make PG_CONFIG="{pg_config}" '
            f'PERL="{perl}" OSNAME=harmonyos -j{jobs} all',
            cwd=self.source_folder,
        )

    def package(self):
        source = self.source_folder
        sql_dir = os.path.join(source, "sql")
        ext_dir = os.path.join(self.package_folder, "extension")

        # Extension control file.
        copy(self, "pgtap.control", source, ext_dir)

        # The exact file set upstream installs into share/extension:
        # versioned install scripts (pgtap--*, pgtap-core--*, pgtap-schema--*),
        # the full upgrade chain and the unversioned base bundles.
        copy(self, "pgtap--*.sql", sql_dir, ext_dir)
        copy(self, "pgtap-core--*.sql", sql_dir, ext_dir)
        copy(self, "pgtap-schema--*.sql", sql_dir, ext_dir)
        for name in ("pgtap.sql", "uninstall_pgtap.sql",
                     "pgtap-core.sql", "pgtap-schema.sql"):
            copy(self, name, sql_dir, ext_dir)

        # Documentation (upstream DOCS = doc/pgtap.mmd).  The upstream release
        # tarball ships no LICENSE file (the license is declared in META.json
        # and in the recipe's ``license`` attribute), so none is packaged.
        copy(self, "pgtap.mmd", os.path.join(source, "doc"),
             os.path.join(self.package_folder, "doc"))

        # Vendor the upstream regression assets for test_package.  build.sql
        # (generated by the upstream Makefile from test/schedule/build.sql)
        # sources sql/pgtap.sql, so the static script is vendored as well.
        for rel in self._UPSTREAM_TEST_DIRS:
            copy(self, "*", os.path.join(source, rel),
                 os.path.join(self.package_folder, "upstream", rel))
        for name in ("psql.sql", "setup.sql"):
            copy(self, name, os.path.join(source, "test"),
                 os.path.join(self.package_folder, "upstream", "test"))
        copy(self, "*", os.path.join(source, "test", "schedule"),
             os.path.join(self.package_folder, "upstream", "test", "schedule"))
        copy(self, "pgtap.sql", sql_dir,
             os.path.join(self.package_folder, "upstream", "sql"))

    def package_info(self):
        # pgTAP is a pure SQL extension: the consumer interface is
        # "extension/* -> $(pg_config --sharedir)/extension" (or, on PG 18,
        # extension_control_path => <package root>).  There is no library to
        # link against; see test_package/pgtap_test.py for the actual loading
        # mechanism.
        self.cpp_info.libs = []
        self.cpp_info.resdirs = ["extension"]
