#!/usr/bin/env python3
"""Conan recipe — pngmeta 1.11

pngmeta extracts the metadata of a PNG image (IHDR geometry, tEXt/zTXt/iTXt
keywords and the tIME chunk) and prints it as plain text, SOIF, HTML or
RDF/XML.

Upstream was written against libpng 1.0 and walks the chunk stream with
libpng internals (``PNG_INTERNAL``, ``png_handle_*``, direct ``png_ptr->``
field access) that stopped being public in libpng 1.4.  The patch in
``patches/`` ports the reader to the public libpng API so the program builds
and runs against libpng 1.6.
"""
import os
import platform

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class PngmetaConan(ConanFile):
    name = "pngmeta"
    version = "1.11"
    description = "Display metadata information from PNG images"
    license = "Libpng"
    homepage = "https://pmt.sourceforge.io/pngmeta/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    topics = ("png", "metadata", "image", "command-line")

    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    # The shipped configure is generated by autoconf 2.13 and only knows the
    # installation directory options below.  Options introduced later (most
    # notably --datarootdir, which Conan injects by default) make it abort
    # with "invalid option".
    _configure_args_whitelist = (
        "--prefix", "--exec-prefix", "--bindir", "--sbindir", "--libexecdir",
        "--datadir", "--sysconfdir", "--sharedstatedir", "--localstatedir",
        "--libdir", "--includedir", "--oldincludedir", "--infodir", "--mandir",
        "--srcdir", "--build", "--host", "--target",
    )

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("libpng/1.6.58.3")
        self.requires("zlib/1.3.2")

    def layout(self):
        basic_layout(self, src_folder="src")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.configure_args = [
            arg for arg in tc.configure_args
            if arg.split("=", 1)[0] in self._configure_args_whitelist
        ]
        tc.generate()
        AutotoolsDeps(self).generate()

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure()
        autotools.make()
        self._run_upstream_tests()

    def _run_upstream_tests(self):
        """Run the upstream automake suite (TESTS = test1 test2 test3 test4).

        Each test renders one of the four output formats and diffs it against
        a recorded expectation.  The scripts locate their expectation and
        sample files with ``for dir in . ..``, so in a VPATH build they have
        to be copied next to the freshly built binary first.

        The suite needs to execute the target binary.  A build machine of a
        different architecture (e.g. an x86_64 runner using the OHOS profile
        for both contexts) may be unable to, and only then are the tests
        skipped; on a machine of the target architecture a binary that does
        not run is a build failure.
        """
        for pattern in ("*.xpt", "*.png"):
            copy(self, pattern, src=self.source_folder, dst=self.build_folder)

        probe = os.path.join(self.build_folder, "pngmeta")
        sample = os.path.join(self.build_folder, "ct1n0g04.png")
        try:
            self.run(f'"{probe}" -quiet "{sample}"', env="conanrun")
        except ConanException:
            machine = platform.machine().lower()
            native = {"armv8": ("aarch64", "arm64"),
                      "x86_64": ("x86_64", "amd64")}.get(str(self.settings.arch), ())
            if machine in native:
                raise
            self.output.warning(
                f"Upstream tests (test1..test4) skipped: this {machine} build "
                f"machine cannot execute the {self.settings.arch} target binary.")
            return
        self.run("make check", cwd=self.build_folder, env="conanrun")

    def package(self):
        copy(self, "README", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.bindirs = ["bin"]
