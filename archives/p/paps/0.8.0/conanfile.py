#!/usr/bin/env python3
"""Conan recipe — paps 0.8.0 (Meson application).

paps — Pango to PostScript: a text-to-PostScript/PDF/SVG converter built on
Pango text layout and the Cairo vector backends. Adapted to HarmonyOS PC
(aarch64, musl, clang 15.0.4). See notes.md for the platform adaptations.

Upstream meson.build dependencies (resolved via pkg-config):
  fmt (>= 9, we use the published fmt/12.2.0 shared package),
  pangoft2 + pangocairo (pango/1.50.14.1.1 shared package),
  glib-2.0 / gobject-2.0 (glib/2.84.0.1 shared package, transitively
  provided by pango; declared explicitly for direct package_folder access).
"""
import os
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, save, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import PkgConfigDeps
from conan.tools.layout import basic_layout
from conan.tools.meson import Meson, MesonToolchain


class PapsConan(ConanFile):
    name = "paps"
    version = "0.8.0"
    description = "paps — text to PostScript/PDF/SVG converter using Pango for text layout"
    license = "LGPL-2.0-or-later"  # COPYING.LIB (LGPL 2.0全文); src代码含GPL注释仅历史遗留
    homepage = "https://github.com/dov/paps"
    url = "https://github.com/dov/paps"
    topics = ("postscript", "pango", "cairo", "text-rendering", "printing")
    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    # NOTE: keep this in sync with the actual dep list in generate()
    _direct_dep_names = ("fmt", "pango", "glib")

    exports_sources = "patches/*"

    def layout(self):
        basic_layout(self, src_folder=".")

    def requirements(self):
        # fmt: 上游 dependency('fmt')。制品仓 fmt/12.2.0 仅 shared binary
        # (libfmt.so.12)；paps 可执行文件 NEEDED libfmt.so.12，运行期随包携带。
        self.requires("fmt/12.2.0")
        # pangoft2/pangocairo：paps 文本排版核心（pango 1.50.14.1.1 shared 包
        # 提供 libpango/libpangoft2/libpangocairo .so 与全套 .pc 文件）。
        self.requires("pango/1.50.14.1.1")
        # glib-2.0/gobject-2.0：paps.cc 直接 include <glib/gstdio.h> 并调用
        # GOption/GMainLoop；glib/2.84.0.1 shared 包传递依赖于 pango，显式声明
        # 使 generate() 可直接取 package_folder 拼装 .pc 修复目录。
        self.requires("glib/2.84.0.1")

    def build_requirements(self):
        # meson probes `ninja --version` during configure. The build profile
        # already prepends /storage/Users/currentUser/usr/local/bin (static
        # ninja 1.13.1) and /data/service/hnp/bin on this host; the registry
        # ninja/1.12.1 binary needs libc++_shared.so at load time and fails
        # the probe in a clean env, so we deliberately do NOT tool_requires
        # it. CI workers ship their own system ninja. (same as gssdp/bali-phy)
        pass

    def export_sources(self):
        export_conandata_patches(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def generate(self):
        # The CI worker exports AR/AS/STRIP/NM/RANLIB as llvm-* names that are
        # NOT on its PATH — only the GNU binutils and ld.lld exist. meson
        # probes these and aborts at configure; pin the real tools by
        # ABSOLUTE PATH (resolved from PATH) and drop the broken env values.
        # (same fix as gssdp/glib2/libsoup3 recipes)
        for _var in ("AR", "AS", "STRIP", "NM", "RANLIB"):
            os.environ.pop(_var, None)
        tools = {name: shutil.which(name) for name in ("ar", "as", "strip", "nm", "ranlib")}
        missing = [name for name, path in tools.items() if path is None]
        if missing:
            raise ConanInvalidConfiguration(
                f"Required build tools not in PATH: {', '.join(missing)}"
            )

        PkgConfigDeps(self).generate()

        # ── .pc resolution strategy (attempt 3 fix) ───────────────────────
        # The earlier "pc-fix" approach (copy the glib/pango/fmt packages'
        # upstream .pc files, rewrite prefix=, prepend to pkg_config_path)
        # is REMOVED: those upstream .pc files carry cross-package
        # Requires(.private) chains (glib-2.0.pc -> libpcre2-8 in the pcre2
        # package, gobject-2.0.pc -> libffi, pango.pc -> harfbuzz/...) which
        # broke pkg-config with
        #   Package 'libpcre2-8', required by 'glib-2.0', not found
        # (libpcre2-8.pc/libffi.pc are NOT generated by PkgConfigDeps
        # because pcre2/libffi are invisible transitive static deps of glib).
        # Instead rely on the standard conan flow: PkgConfigDeps generates
        # component-level .pc files for the whole visible dependency graph
        # (pangoft2.pc / pangocairo.pc / glib-2.0.pc / gobject-2.0.pc /
        # fmt.pc / ... all present, prefixes already point at the real
        # package folders) and MesonToolchain defaults pkg_config_path to
        # the generators folder. Verified on device: pkg-config resolves
        # --cflags/--libs for all five meson dependencies from that folder
        # alone, with no broken Requires chains.

        tc = MesonToolchain(self)
        tc.ar = tools["ar"]
        tc.as_ = tools["as"]
        # ⚠️ 绝不可 strip 产物：OHOS loader 校验 .codesign 段内嵌哈希与文件内容
        # 是否一致，strip 会改写 ELF 内容导致哈希失配，运行时报 Permission
        # denied（gssdp/libsoup3 本地铁证，paps 可执行文件同理）。
        tc.strip = None
        tc.binaries["nm"] = tools["nm"]
        tc.binaries["ranlib"] = tools["ranlib"]
        # paps has no library target — the single executable links shared
        # deps; default_library is irrelevant but set explicitly for clarity.
        tc.project_options["default_library"] = "shared"
        # subprojects/fmt.wrap must never trigger a network download: the
        # dependency('fmt') is satisfied via pkg-config from the conan fmt
        # package (PC_PATH below). nodownload keeps the build hermetic.
        tc.project_options["wrap_mode"] = "nodownload"
        # glib tools (glib-mkenums etc.) are not needed by paps (no gnome.*
        # module usage); only the libraries are consumed.
        # ── libintl link fix ──────────────────────────────────────────────
        # paps.cc includes <libintl.h> for gettext()/bindtextdomain() and
        # glib/gstdio.h pulls the glib package's own libintl.h, which
        # #defines gettext -> g_libintl_gettext etc. (proxy-libintl).
        # The glib shared lib references libintl.so.8 (NEEDED) but the
        # PkgConfigDeps-generated glib-2.0.pc carries no -lintl (the glib
        # recipe's package_info does not declare it), so ld.lld fails with
        #   undefined symbol: g_libintl_textdomain / g_libintl_bindtextdomain
        #   / g_libintl_bind_textdomain_codeset / g_libintl_gettext
        # Add the glib package's bundled proxy-libintl (libintl.so in its
        # lib/ dir) to the link line explicitly.
        glib_dep = self.dependencies.get("glib")
        if glib_dep and glib_dep.package_folder:
            glib_libdir = os.path.join(glib_dep.package_folder, "lib")
            if os.path.isfile(os.path.join(glib_libdir, "libintl.so")):
                # -rpath is required for the SAME reason: meson's configure
                # sanity check links and RUNS a test binary; without rpath
                # the OHOS musl loader cannot find libintl.so.8 (it is not
                # in any default search dir) and configure aborts with
                # "Executables created by c compiler ... are not runnable".
                tc.extra_ldflags += [
                    "-L%s" % glib_libdir, "-lintl",
                    "-Wl,-rpath,%s" % glib_libdir,
                ]
        tc.generate()

    def build(self):
        meson = Meson(self)
        meson.configure()
        meson.build()

    def package(self):
        meson = Meson(self)
        meson.install()
        # Self-contained runtime: paps NEEDED libfmt.so.12 + the whole pango
        # shared stack (libpango*/libglib*/libgio*/libcairo/libharfbuzz/...).
        # Copy the direct deps' shared libs next to bin/ (lib/), and give the
        # executable a $ORIGIN/../lib DT_RUNPATH so it finds them without any
        # LD_LIBRARY_PATH setup.
        libdir = os.path.join(self.package_folder, "lib")
        os.makedirs(libdir, exist_ok=True)
        for depname in self._direct_dep_names:
            dep = self.dependencies.get(depname)
            if not dep or not dep.package_folder:
                continue
            src = os.path.join(dep.package_folder, "lib")
            if not os.path.isdir(src):
                continue
            for fn in os.listdir(src):
                if fn.endswith(".so") or (".so." in fn):
                    dst = os.path.join(libdir, fn)
                    if not os.path.exists(dst):
                        shutil.copy2(os.path.join(src, fn), dst)
        # fix symlink copy artifacts: shutil.copy2 on a symlink copies the
        # target content under the link name — rebuild the symlinks chain
        # (libfmt.so.12 -> libfmt.so.12.2.0 etc.) from the real files.
        self._relink(libdir)
        self._rpath_binaries()
        # fontconfig runtime config: pango's fontconfig finds NO fonts by
        # default on OHOS (the conan fontconfig package's fonts.conf only
        # lists /usr/share/fonts etc., which do not exist here) — every
        # conversion silently rendered as blank pages. Ship a fonts.conf
        # that adds the device font dirs (/system/fonts holds the full Noto
        # + HarmonyOS font set) and point FONTCONFIG_FILE at it via
        # runenv_info (package_info below), so the paps binary renders real
        # glyphs with zero user setup.
        res_dir = os.path.join(self.package_folder, "res")
        os.makedirs(res_dir, exist_ok=True)
        save(self, os.path.join(res_dir, "fonts.conf"),
             "<?xml version=\"1.0\"?>\n"
             "<!DOCTYPE fontconfig SYSTEM \"urn:fontconfig:fonts.dtd\">\n"
             "<fontconfig>\n"
             "  <dir>/system/fonts</dir>\n"
             "  <dir>~/.fonts</dir>\n"
             "  <cachedir prefix=\"xdg\">fontconfig</cachedir>\n"
             "</fontconfig>\n")
        license_src = os.path.join(self.source_folder, "COPYING.LIB")
        if os.path.isfile(license_src):
            from conan.tools.files import copy
            copy(self, "COPYING.LIB", src=self.source_folder,
                 dst=os.path.join(self.package_folder, "licenses"), keep_path=False)

    @staticmethod
    def _relink(libdir):
        # ensure the .so symlink chain matches the copied real files
        import glob as _glob
        for real in _glob.glob(os.path.join(libdir, "*.so.*.**")):
            base = os.path.basename(real)
            # libfmt.so.12.2.0 -> libfmt.so.12
            parts = base.rsplit(".", 2)
            if len(parts) == 3 and parts[1].isdigit() and parts[2].isdigit():
                link = os.path.join(libdir, "%s.%s" % (parts[0], parts[1]))
                if os.path.isfile(link) and not os.path.islink(link):
                    # copied as a regular file duplicating the target content;
                    # verify it really was meant to be a link (same size) —
                    # simply replace with a symlink
                    os.remove(link)
                    os.symlink(base, link)
        # libpango-1.0.so -> libpango-1.0.so.0 chain tail
        for so in _glob.glob(os.path.join(libdir, "*.so")):
            if os.path.islink(so):
                continue
            base = os.path.basename(so)
            candidates = sorted(_glob.glob(os.path.join(libdir, base + ".*")))
            real = next((c for c in candidates if os.path.isfile(c) and not os.path.islink(c)), None)
            if real:
                os.remove(so)
                os.symlink(os.path.basename(real), so)

    def _rpath_binaries(self):
        # Embed $ORIGIN/../lib DT_RUNPATH into the paps executable so it is
        # self-contained on OHOS (musl loader ignores LD_LIBRARY_PATH; see
        # bali-phy precedent). patchelf is used when present; the rpath
        # string MUST be escaped as \$ORIGIN — self.run() goes through a
        # shell where an unescaped "$ORIGIN" inside double quotes expands
        # to the empty environment variable, silently producing a broken
        # "/../lib" runpath (observed on device).
        patchelf = shutil.which("patchelf")
        if not patchelf:
            return
        bindir = os.path.join(self.package_folder, "bin")
        for fn in os.listdir(bindir):
            path = os.path.join(bindir, fn)
            if os.path.islink(path) or not os.path.isfile(path):
                continue
            with open(path, "rb") as fh:
                if fh.read(4) != b"\x7fELF":
                    continue
            self.run("%s --set-rpath '\\$ORIGIN/../lib' \"%s\"" % (patchelf, path))
        # OHOS loader verifies the .codesign section hash against the file
        # content: patchelf rewrote the ELF (runpath), so the executable
        # MUST be re-signed or every exec fails with "Operation not
        # permitted" (glib recipe _sign_shared_libs precedent).
        self._sign_binaries()

    def _sign_binaries(self):
        bindir = os.path.join(self.package_folder, "bin")
        signer = "/data/service/hnp/bin/binary-sign-tool"
        if not os.path.isfile(signer):
            self.output.warning("binary-sign-tool not found; skip OHOS codesign (cross/SDK env)")
            return
        candidates_objcopy = [
            "/data/service/hnp/bin/llvm-objcopy",
            shutil.which("llvm-objcopy") or "",
        ]
        ce = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict) or {}
        cc = ce.get("c") or ""
        if cc:
            candidates_objcopy.insert(0, os.path.join(os.path.dirname(cc), "llvm-objcopy"))
        objcopy = next((p for p in candidates_objcopy if p and os.path.isfile(p)), None)
        for fn in os.listdir(bindir):
            path = os.path.join(bindir, fn)
            if os.path.islink(path) or not os.path.isfile(path):
                continue
            with open(path, "rb") as fh:
                if fh.read(4) != b"\x7fELF":
                    continue
            if objcopy:
                self.run('"%s" --remove-section .codesign "%s" 2>/dev/null || true' % (objcopy, path))
            self.run('"%s" sign -inFile "%s" -outFile "%s" -selfSign 1' % (signer, path, path))

    def package_info(self):
        # application: no libs, only the paps executable
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = ["lib"]
        self.cpp_info.libs = []
        bindir = os.path.join(self.package_folder, "bin")
        self.buildenv_info.append_path("PATH", bindir)
        self.runenv_info.append_path("PATH", bindir)
        self.runenv_info.append_path("LD_LIBRARY_PATH", os.path.join(self.package_folder, "lib"))
        # fontconfig runtime config (see package()): without this pango finds
        # no fonts on OHOS and every paps conversion renders blank pages.
        fonts_conf = os.path.join(self.package_folder, "res", "fonts.conf")
        if os.path.isfile(fonts_conf):
            self.runenv_info.define_path("FONTCONFIG_FILE", fonts_conf)
        self.cpp_info.set_property("cmake_file_name", "paps")
        self.cpp_info.set_property("pkg_config_name", "paps")
