#!/usr/bin/env python3
"""Conan recipe for plasma-wayland-protocols 1.20.0 — CMake (ECM).

KDE Plasma 专用 Wayland 协议 XML 定义集合（30 个协议文件）。
纯数据包：无编译产物，CMake 仅安装 XML + CMake Config 包
（PlasmaWaylandProtocolsConfig.cmake）。

上游 autotests（BUILD_TESTING）需要 wayland-scanner + Wayland Client。
HMDFS 禁止动态加载共享库，制品仓 wayland 包的 scanner 二进制动态链
libexpat.so/libxml2.so 无法在 OHOS 执行。方案（wayland-protocols 1.36.1
先例）：从 wayland 1.22.0 源码静态编译 scanner（仅依赖 libc），
随包发布到 bin/，test_package 对全部 30 个协议 XML 执行上游同款
--strict 扫描（client-header/server-header/private-code），等价覆盖
上游 120 项 autotests 中的 90 项扫描测试。
"""
import os
import re
import shutil

from conan import ConanFile
from conan.tools.files import get, export_conandata_patches, apply_conandata_patches
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout


class PlasmaWaylandProtocolsConan(ConanFile):
    name = "plasma-wayland-protocols"
    version = "1.20.0"
    description = "Plasma specific protocols for Wayland (XML definitions)"
    license = "LGPL-2.1-or-later"
    homepage = "https://invent.kde.org/libraries/plasma-wayland-protocols"
    url = "https://invent.kde.org/libraries/plasma-wayland-protocols"

    package_type = "unknown"
    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # 上游 CMakeLists: find_package(ECM 5.69.0 NO_MODULE)（REQUIRED）
        # 提供 KDEInstallDirs/KDECMakeSettings/ECMSetupVersion 宏
        self.requires("extra-cmake-modules/6.29.0")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        # 下载 wayland 源码用于静态编译 wayland-scanner
        get(self, **self.conan_data["scanner_sources"],
            strip_root=True, destination="wayland-scanner-src")

    def generate(self):
        tc = CMakeToolchain(self)
        # ECM 的 KDEMetaInfoPlatformCheck 不认 HarmonyOS，KDE 官方变量绕过
        # （bluez-qt/6.28.0 先例）
        tc.variables["KF_IGNORE_PLATFORM_CHECK"] = "true"
        # ECM 打包产物缺 ecm_uninstall.cmake.in，跳过 uninstall target 生成
        tc.variables["KDE_SKIP_UNINSTALL_TARGET"] = "TRUE"
        # 上游 ctest 的 build 测试需链接 Wayland Client 共享库（HMDFS 禁
        # 动态加载）——configure 期禁用；扫描测试由 test_package 用随包
        # 静态 scanner 覆盖（见 _build_static_scanner / test_package）
        tc.variables["BUILD_TESTING"] = "OFF"
        tc.generate()

        # ECM 打包产物缺 ECMVersionHeader.h.in（ecm_setup_version 的
        # configure_file 需要），用 ECM 源码自带模板内容生成缺失文件
        # （if-not-exists 保护；bluez-qt/6.28.0 同款处理）
        ecm_modules = os.path.join(
            self.dependencies["extra-cmake-modules"].package_folder,
            "share", "ECM", "modules",
        )
        ecm_version_template = os.path.join(ecm_modules, "ECMVersionHeader.h.in")
        if not os.path.exists(ecm_version_template):
            with open(ecm_version_template, "w") as f:
                f.write(
                    "// This file was generated by ecm_setup_version(): DO NOT EDIT!\n\n"
                    "#ifndef @HEADER_PREFIX@_VERSION_H\n"
                    "#define @HEADER_PREFIX@_VERSION_H\n\n"
                    "#define @HEADER_PREFIX@_VERSION_STRING \"@HEADER_VERSION@\"\n"
                    "#define @HEADER_PREFIX@_VERSION_MAJOR @HEADER_VERSION_MAJOR@\n"
                    "#define @HEADER_PREFIX@_VERSION_MINOR @HEADER_VERSION_MINOR@\n"
                    "#define @HEADER_PREFIX@_VERSION_PATCH @HEADER_VERSION_PATCH@\n"
                    "#define @HEADER_PREFIX@_VERSION ((@HEADER_VERSION_MAJOR@<<16)"
                    "|(@HEADER_VERSION_MINOR@<<8)|(@HEADER_VERSION_PATCH@))\n\n#endif\n"
                )

    def _build_static_scanner(self):
        """从 wayland 1.22.0 源码静态编译 wayland-scanner。

        HMDFS 禁止从 Conan 缓存加载共享库；制品仓 wayland 包的 scanner
        链接 libexpat.so/libxml2.so 无法执行。静态编译只依赖 libc.so
        （wayland-protocols/1.36.1 已验证的方案）。
        """
        scanner_src = os.path.join(self.source_folder, "wayland-scanner-src")

        # 生成 config.h
        config_h = os.path.join(scanner_src, "config.h")
        with open(config_h, "w", encoding="utf-8") as f:
            f.write('#define HAVE_EXPAT 1\n'
                    '#define PACKAGE "wayland"\n'
                    '#define VERSION "1.22.0"\n')

        # 生成 wayland-version.h
        version_in = os.path.join(scanner_src, "src", "wayland-version.h.in")
        version_h = os.path.join(scanner_src, "src", "wayland-version.h")
        with open(version_in, "r", encoding="utf-8") as f:
            content = f.read()
        for key, val in [("@WAYLAND_VERSION@", "1.22.0"),
                         ("@WAYLAND_VERSION_MAJOR@", "1"),
                         ("@WAYLAND_VERSION_MINOR@", "22"),
                         ("@WAYLAND_VERSION_MICRO@", "0")]:
            content = content.replace(key, val)
        with open(version_h, "w", encoding="utf-8") as f:
            f.write(content)

        # 生成 wayland.dtd.h（embed.py 内嵌 DTD）
        dtd_h = os.path.join(scanner_src, "src", "wayland.dtd.h")
        self.run(
            f'python3 {scanner_src}/src/embed.py '
            f'{scanner_src}/protocol/wayland.dtd wayland_dtd > {dtd_h}',
            env="conanbuild",
        )

        # 静态编译 scanner（只依赖 libc.so；expat 用静态库）
        scanner_bin = os.path.join(self.generators_folder, "wayland-scanner")
        cc = shutil.which("clang") or "/data/service/hnp/bin/clang"
        expat_inc = "/data/service/hnp/expat.org/expat_2.7.3/include"
        expat_lib = "/data/service/hnp/expat.org/expat_2.7.3/lib/libexpat.a"
        self.run(
            f'{cc} -o {scanner_bin} '
            f'-include {config_h} '
            f'-I{scanner_src} -I{scanner_src}/src -I{scanner_src}/protocol '
            f'{scanner_src}/src/scanner.c {scanner_src}/src/wayland-util.c '
            f'-I{expat_inc} {expat_lib} '
            f'-lm -lpthread -static',
            env="conanbuild",
        )
        self.output.info("plasma-wayland-protocols: built static wayland-scanner")

    def build(self):
        # 先构建静态 scanner（test_package 上游等价扫描测试使用）
        self._build_static_scanner()
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        # 纯数据包，无编译产物；-j1 防 OHOS 沙箱 mkfifo 限制（opensp 先例）
        cmake.build(build_tool_args=["-j1"])

    def package(self):
        cmake = CMake(self)
        cmake.install()
        # 静态 scanner 随包发布到 bin/，供下游与 test_package 使用
        scanner_bin = os.path.join(self.generators_folder, "wayland-scanner")
        if os.path.isfile(scanner_bin):
            os.makedirs(os.path.join(self.package_folder, "bin"),
                        exist_ok=True)
            shutil.copy2(scanner_bin,
                         os.path.join(self.package_folder, "bin",
                                      "wayland-scanner"))
            os.chmod(os.path.join(self.package_folder, "bin",
                                  "wayland-scanner"), 0o755)

    def package_info(self):
        # 上游 1.20.0 无 pkg-config 文件（实测包产物仅 CMake Config + XML），
        # 唯一消费入口是 find_package(PlasmaWaylandProtocols) 取
        # ${PLASMA_WAYLAND_PROTOCOLS_DIR}——不伪造 .pc
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        # 静态 scanner 工具：下游可用 self.conf_info 获取路径
        self.conf_info.define("user.plasma-wayland-protocols:scanner",
                              os.path.join(self.package_folder, "bin",
                                           "wayland-scanner"))
