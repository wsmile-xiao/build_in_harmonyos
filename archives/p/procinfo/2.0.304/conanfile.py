#!/usr/bin/env python3
"""Conan recipe for procinfo 2.0.304 — /proc system monitor (procinfo-ng).

Build system: autoconf-generated configure + plain Makefile (single-binary
C++ project). Produces the `procinfo` executable; links ncursesw from the
conan ncurses/6.5 package (static, widec) for the full-screen mode.

Quirks handled here (evidence in notes.md):
- The bundled configure was generated by autoconf 2.61 (2009): its inline
  config.guess cannot classify `uname -s == HarmonyOS`, so the build supplies
  ac_cv_build instead of patching the guess.
- config.status creates its tmp dir with (umask 077 && mkdir), which the
  OHOS/HMDFS sandbox makes unwritable -> patched to umask 022 (same fix as
  the ncurses and a52dec recipes).
- Upstream configure.in hardcodes LDFLAGS="-s -lncurses" (drops inherited
  flags and links the non-wide library). Include/lib paths and -lncursesw
  are therefore injected as make command-line overrides (command-line
  variable assignments beat the Makefile's own assignments).
- The Makefile compile rule uses $(CXX) $(CFLAGS) only (no CXXFLAGS/
  CPPFLAGS), so the dependency include path rides on the CFLAGS override.
- Makefile.in has no srcdir/VPATH support: configure runs in-source.
"""
import os

from conan import ConanFile
from conan.tools.files import copy, get, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout
from conan.tools.microsoft import unix_path


class ProcinfoConan(ConanFile):
    name = "procinfo"
    version = "2.0.304"
    description = "procinfo - terminal monitor summarizing memory/CPU/disk/IRQ/net state from /proc (procinfo-ng)"
    license = "GPL-2.0-or-later"
    homepage = "http://procinfo-ng.sourceforge.net"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("ncurses/6.5")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)

        # E540/E524: the OHOS toolchain lives outside the default worker PATH
        # and the conanbuild env does not carry CC/CXX for this in-source flow;
        # read compilers from the profile conf and inject them explicitly (R33).
        compilers = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict)
        cc = compilers.get("c", "clang")
        cxx = compilers.get("cpp", "clang++")
        run_env = ('PATH=/data/service/hnp/bin:$PATH '
                   f'CC="{cc}" CXX="{cxx}" '
                   'CONFIG_SHELL=/data/service/hnp/bin/bash')

        dep = self.dependencies["ncurses"]
        inc = unix_path(self, os.path.join(dep.package_folder, dep.cpp_info.includedirs[0]))
        lib = unix_path(self, os.path.join(dep.package_folder, dep.cpp_info.libdirs[0]))

        # -Wno-c++11-narrowing: 2009-era sources narrow values in initializer
        # lists; modern clang rejects them (upstream has no -Werror).
        cflags = f"-O2 -pipe -Wall -Wno-c++11-narrowing -I{inc}"
        # Upstream LDFLAGS would be "-s -lncurses"; override with conan's
        # static wide-char ncurses plus the dependency lib dir.
        ldflags = f"-s -L{lib} -lncursesw"

        # ac_cv_build: the 2009 inline config.guess cannot classify the
        # HarmonyOS kernel; hand it a neutral modern triple (the generated
        # Makefile does not consume build/host at all).
        arch = {"armv8": "aarch64"}.get(str(self.settings.arch), str(self.settings.arch))
        self.run(
            f'{run_env} ac_cv_build={arch}-unknown-linux-gnu '
            f'./configure --prefix="{self.package_folder}"',
            cwd=self.source_folder)
        self.run(f'{run_env} make -j1 CFLAGS="{cflags}" LDFLAGS="{ldflags}"',
                 cwd=self.source_folder)

    def package(self):
        copy(self, "procinfo", self.source_folder,
             os.path.join(self.package_folder, "bin"), keep_path=False)
        copy(self, "procinfo.8", self.source_folder,
             os.path.join(self.package_folder, "share", "man", "man8"),
             keep_path=False)

    def package_info(self):
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
