"""Conan recipe for the upstream preseq 3.2.0 release archive."""

import os
import re
import shlex
import shutil
import stat
import subprocess
from pathlib import Path

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.env import VirtualBuildEnv, VirtualRunEnv
from conan.tools.files import apply_conandata_patches, copy, get
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class PreseqConan(ConanFile):
    name = "preseq"
    version = "3.2.0"
    package_type = "application"
    description = "Predict sequencing-library complexity and genomic coverage"
    license = "GPL-3.0-or-later"
    homepage = "https://github.com/smithlabcode/preseq"
    settings = "os", "compiler", "build_type", "arch"
    exports_sources = "patches/*"

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("preseq supports Linux and OHOS builds")

    def requirements(self):
        self.requires("zlib/1.3.1")
        self.requires("htslib/1.24-r0")

    def layout(self):
        basic_layout(self, src_folder=".")

    def source(self):
        # GitHub's autogenerated tag archive omits generated Autotools inputs.
        source = dict(self.conan_data["sources"][self.version])
        local_archive = os.environ.get("PRESEQ_SOURCE_ARCHIVE")
        if local_archive:
            archive = Path(local_archive).resolve(strict=True)
            if not archive.is_file():
                raise ConanInvalidConfiguration("PRESEQ_SOURCE_ARCHIVE is not a file")
            source["url"] = archive.as_uri()
            source["filename"] = archive.name
        get(self, **source, strip_root=True)
        apply_conandata_patches(self)

    def generate(self):
        AutotoolsDeps(self).generate()
        VirtualBuildEnv(self).generate()
        toolchain = AutotoolsToolchain(self)
        if str(self.settings.os) == "OHOS":
            # Unsigned configure probes cannot execute on the target. The
            # explicit host marks this as a cross-style Autoconf build.
            toolchain.configure_args.append("--host=aarch64-unknown-linux-ohos")
        toolchain.configure_args.append("--enable-hts")
        toolchain.generate()
        VirtualRunEnv(self).generate()

    @staticmethod
    def _sign_elf(filename):
        path = Path(filename)
        signer = shutil.which("binary-sign-tool")
        readelf = shutil.which("llvm-readelf")
        objcopy = shutil.which("llvm-objcopy")
        if not path.is_file() or not all((signer, readelf, objcopy)):
            raise ConanInvalidConfiguration("missing preseq ELF or OHOS signing tools")
        pending = path.with_name(path.name + ".preseq-signing")
        signed = path.with_name(path.name + ".preseq-signed")
        if pending.exists() or signed.exists():
            raise ConanInvalidConfiguration("stale preseq signing sibling")
        try:
            shutil.copy2(path, pending)
            before = subprocess.run(
                [readelf, "-S", str(pending)], capture_output=True, text=True,
                check=True, timeout=10,
            ).stdout
            if re.search(r"\s\.codesign\s", before):
                subprocess.run(
                    [objcopy, "--remove-section", ".codesign", str(pending)],
                    check=True, timeout=10,
                )
            subprocess.run(
                [signer, "sign", "-inFile", str(pending), "-outFile", str(signed), "-selfSign", "1"],
                check=True, capture_output=True, timeout=40,
            )
            after = subprocess.run(
                [readelf, "-S", str(signed)], capture_output=True, text=True,
                check=True, timeout=10,
            ).stdout
            if len(re.findall(r"\s\.codesign\s", after)) != 1:
                raise ConanInvalidConfiguration("signed preseq ELF lacks one .codesign section")
            signed.chmod(stat.S_IMODE(path.stat().st_mode) | stat.S_IXUSR)
            os.replace(signed, path)
        finally:
            for temporary in (pending, signed):
                if temporary.exists():
                    temporary.unlink()

    def build(self):
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j2"])
        # The release has a check target but registers zero Automake tests.
        autotools.make(target="check", args=["-j2"])
        preseq = os.path.join(self.build_folder, "preseq")
        to_mr = os.path.join(self.build_folder, "to-mr")
        if str(self.settings.os) == "OHOS":
            self._sign_elf(preseq)
            self._sign_elf(to_mr)
        data = os.path.join(self.source_folder, "data")
        examples = (
            ("mapped", "lc_extrap", (), "SRR1003759_5M_subset.mr"),
            ("bam", "lc_extrap", ("-B",), "SRR1106616_5M_subset.bam"),
            # The README names *_read.txt, which is absent from the release.
            ("hist", "lc_extrap", ("-H",), "SRR1301329_1M_hist.txt"),
            ("coverage", "gc_extrap", ("-B",), "SRR1003759_5M_subset.mr"),
        )
        for label, mode, options, fixture in examples:
            output = Path(self.build_folder, "preseq-" + label + ".tsv")
            if output.exists():
                raise ConanInvalidConfiguration("upstream example output already exists: " + str(output))
            command = " ".join(shlex.quote(item) for item in (
                preseq, mode, *options, "-o", str(output), os.path.join(data, fixture),
            ))
            self.run(command, cwd=self.build_folder, env="conanrun")
            if not output.is_file() or output.stat().st_size == 0:
                raise ConanInvalidConfiguration("upstream example produced no output: " + label)
            self.output.info("UPSTREAM_EXAMPLE_PASS: " + label)

    def package(self):
        Autotools(self).install()
        copy(self, "LICENSE", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))
        if str(self.settings.os) == "OHOS":
            for executable in ("preseq", "to-mr"):
                self._sign_elf(os.path.join(self.package_folder, "bin", executable))

    def package_info(self):
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
