#!/usr/bin/env python3
"""Conan recipe — pngnq 1.1 (PNG NeuQuant quantizer CLI, autotools).

pngnq quantizes 32-bit RGBA PNG images to 8-bit palette PNGs using the
NeuQuant neural-net quantization algorithm. It builds two command line
tools: `pngnq` (quantizer) and `pngcomp` (image comparison metrics).

Build notes:
- Upstream (2010) reads libpng compiler/linker flags through the
  `libpng-config` script via backtick substitution in src/Makefile.am
  (`` `libpng-config --I_opts` `` / `` `libpng-config --ldflags` ``),
  while configure itself uses PKG_CHECK_MODULES. The conan-hosted libpng
  package ships a libpng-config with a hardcoded prefix="/" that emits
  unusable paths, so build() writes a libpng-config wrapper pointing at
  the conan libpng/zlib package folders and prepends it to PATH.
- zlib is a transitive dependency of libpng; its headers/lib are also
  routed through the wrapper (src/rwpng.c includes <zlib.h>, and
  AM_LDFLAGS appends -lz without a -L path).
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout

# POSIX sh wrapper emulating libpng-config against conan package layout.
# Only the options invoked by src/Makefile.am are implemented
# (--I_opts via AM_CFLAGS, --ldflags via AM_LDFLAGS).
# NOTE: %-style formatting on purpose — the shell body uses ${...}
# parameter expansion, which str.format() would misinterpret.
_LIBPNG_CONFIG_TMPL = """\
#! /bin/sh
# libpng-config wrapper generated by conanfile.py (conan package layout)
png_version="%s"
prefix="%s"
libdir="%s"
includedir="%s"
zlib_libdir="%s"
zlib_incdir="%s"
libs="-lpng16"
all_libs="-lpng16 -lz"

case "$1" in
    --version) echo "${png_version}";;
    --prefix) echo "${prefix}";;
    --libdir) echo "${libdir}";;
    --I_opts|--cflags|--cppflags)
        echo "-I${includedir} -I${zlib_incdir}"
        ;;
    --L_opts|--R_opts|--ldopts)
        echo "-L${libdir} -L${zlib_libdir}"
        ;;
    --ldflags)
        echo "-L${libdir} -L${zlib_libdir} ${libs}"
        ;;
    --static)
        libs="${all_libs}"
        ;;
    *)
        echo "Usage: $0 [--prefix] [--version] [--libdir] [--I_opts] [--ldflags] [--static]" >&2
        exit 1
        ;;
esac
exit 0
"""


class PngnqConan(ConanFile):
    name = "pngnq"
    version = "1.1"
    description = ("PNG NeuQuant image quantizer: converts 32-bit RGBA PNG "
                   "images to 8-bit palette PNGs (CLI tools pngnq/pngcomp)")
    license = "Libpng"
    homepage = "https://pngnq.sourceforge.net/"
    url = "https://sourceforge.net/projects/pngnq/"

    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"
    # PkgConfigDeps: satisfies configure's PKG_CHECK_MODULES([PNG], [libpng >= 1.2.0])
    # (AutotoolsToolchain prepends the generators folder to PKG_CONFIG_PATH)
    generators = "PkgConfigDeps"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # zlib/1.3.1 comes in transitively through libpng
        self.requires("libpng/1.6.39")

    def validate(self):
        # R32: settings.os checks must use in ("Linux", "OHOS")
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"pngnq supports Linux/OHOS only, got {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # R1: minimal configure args (prefix/install dirs added by toolchain)
        tc.generate()

    def _write_libpng_config_wrapper(self):
        """Write a libpng-config wrapper pointing at the conan-hosted
        libpng/zlib packages and return its directory (to be prepended
        to PATH for configure/make, since src/Makefile.am resolves
        flags through `libpng-config` backticks)."""
        libpng = self.dependencies["libpng"]
        zlib = self.dependencies["zlib"]
        png_prefix = libpng.package_folder
        zlib_prefix = zlib.package_folder
        wrapper_dir = os.path.join(self.build_folder, "_conan_libpng_config")
        os.makedirs(wrapper_dir, exist_ok=True)
        wrapper = os.path.join(wrapper_dir, "libpng-config")
        content = _LIBPNG_CONFIG_TMPL % (
            libpng.ref.version,
            png_prefix,
            os.path.join(png_prefix, "lib"),
            os.path.join(png_prefix, "include"),
            os.path.join(zlib_prefix, "lib"),
            os.path.join(zlib_prefix, "include"),
        )
        with open(wrapper, "w") as f:
            f.write(content)
        os.chmod(wrapper, 0o755)
        return wrapper_dir

    def build(self):
        apply_conandata_patches(self)

        wrapper_dir = self._write_libpng_config_wrapper()
        libpng = self.dependencies["libpng"]
        zlib = self.dependencies["zlib"]
        env = Environment()
        env.prepend_path("PATH", wrapper_dir)
        # Deterministic -L for configure's AC_SEARCH_LIBS([zlibVersion],[z]):
        # resolve -lz against the conan static zlib, not any system copy.
        # Paths come from the conan dependency graph (R33: no bare ${CC}/
        # ${CFLAGS} style shell variables from the ambient environment).
        env.append("LDFLAGS", [
            "-L{}".format(os.path.join(zlib.package_folder, "lib")),
            "-L{}".format(os.path.join(libpng.package_folder, "lib")),
        ])
        with env.vars(self, scope="build").apply():
            autotools = Autotools(self)
            autotools.configure()
            autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        # CLI application: binaries only, no libraries exported
        self.cpp_info.bindirs = ["bin"]
