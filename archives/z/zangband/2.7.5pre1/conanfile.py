class ZangbandConan(ConanFile):
    name = "zangband"
    version = "2.7.5pre1"
    description = "Zangband - a roguelike computer role playing game based on Angband"
    license = "Zangband License (Angband-like, non-free)"
    homepage = "https://sourceforge.net/projects/zangband/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # 终端前端需要 ncurses 头文件与静态宽字符库（OHOS sysroot 只有运行期 stub）
        self.requires("ncurses/6.6")

    def layout(self):
        basic_layout(self, src_folder="src")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def _dep_flags(self):
        """Include/library search flags contributed by dependencies."""
        cflags = []
        ldflags = []
        for dep in self.dependencies.values():
            if dep.package_folder is None:
                continue
            components = dep.cpp_info.aggregated_components()
            cflags.extend(f"-I{inc}" for inc in components.includedirs)
            ldflags.extend(f"-L{lib}" for lib in components.libdirs)
        return " ".join(cflags), " ".join(ldflags)

    def _build_cc(self):
        """Compiler for build-time helper programs (must run on the build host).

        The OHOS profile exports CC/CXX pointing at the cross compiler, so the
        host compiler is detected explicitly instead of reusing CC.
        """
        for candidate in ("cc", "gcc", "clang"):
            found = shutil.which(candidate)
            if found:
                return found
        raise ConanInvalidConfiguration("no host C compiler found for tolua")

    def _build_host_tolua(self, workdir):
        """Build src/lua/tolua with the BUILD compiler.

        tolua runs at build time to turn src/l-*.pkg into src/l-*.c, so it has to
        be a host binary. It also locates its lua scripts via argv[0], so the
        output is placed in src/lua/ next to basic.lua..doit.lua.
        """
        lua_dir = os.path.join(workdir, "src", "lua")
        output = os.path.join(lua_dir, "tolua_host")
        sources = " ".join(f'"{os.path.join(lua_dir, name)}"' for name in _TOLUA_SOURCES)
        self.run(f'{self._build_cc()} -O2 -w -o "{output}" {sources} -lm', cwd=lua_dir)
        if not os.path.isfile(output):
            raise ConanInvalidConfiguration("host tolua was not produced")
        return output

    @staticmethod
    def _target_cc():
        return os.environ.get("CC") or "cc"

    @staticmethod
    def _target_ldflags():
        sysroot = os.environ.get("SYSROOT") or os.environ.get("CONAN_SYSROOT")
        return f"--sysroot={sysroot}" if sysroot else ""

    def _autoconf_cache(self):
        cache_file = os.path.join(self.build_folder, "ohos-autoconf.cache")
        save(self, cache_file, _OHOS_AUTOCONF_CACHE)
        return cache_file

    def _configure_args(self, cache_file):
        deps_cflags, deps_ldflags = self._dep_flags()
        return [
            "--prefix=/usr",
            "--with-x11=no",
            "--with-gtk=no",
            "--with-tcltk=no",
            "--with-setgid=no",
            f"--cache-file={cache_file}",
            f"CPPFLAGS={deps_cflags}",
            f"LDFLAGS={deps_ldflags}",
        ]

    def build(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")

        with chdir(self, self.source_folder):
            host_tolua = self._build_host_tolua(self.source_folder)
            cache_file = self._autoconf_cache()

            tc = AutotoolsToolchain(self)
            tc.configure_args.extend(self._configure_args(cache_file))
            env = tc.environment()
            # 上游 configure 是 2005 年的产物，含 bash 专有语法（如 ${var//a/b}）；
            # 用 /bin/sh(dash) 会以 "Bad substitution" 中止，必须用 bash 执行。
            # 注意 bash 的位置随环境而变（本机 /bin/bash；OHOS 设备/CI worker 为
            # profile 提供的 CONFIG_SHELL，例如 /data/service/hnp/bin/bash），
            # 因此优先沿用 profile 的 CONFIG_SHELL，不硬编码路径。
            bash_shell = (
                os.environ.get("CONFIG_SHELL")
                or shutil.which("bash")
                or "/bin/bash"
            )
            env.define("CONFIG_SHELL", bash_shell)
            env.define("SHELL", bash_shell)
            env.vars(self).save_script("conanbuild_zangband")

            # makefile.in 在 configure 之前就修好：
            #   (a) 去掉自重建前提（上游不含 config.guess/config.sub，触发即失败）；
            #   (b) AC_CHECK_LIB([z],[main]) 会无条件把 -lz 注入 LIBS，而程序并未
            #       使用 zlib，这里从模板中直接去掉，避免无用的运行期依赖。
            #
            # 先在 makefile.in 上修，而不是在 config.status 生成的 makefile 上修，
            # 原因是某些构建环境（CI worker 的 HMDFS 共享盘）不允许 config.status
            # 在其源码树内创建 mode-0700 的临时目录（autoconf 固定用
            # `umask 077 && mktemp -d ./confstatXXXXXX`，不受 TMPDIR 影响），
            # 会导致 config.status 报 Permission denied 且完全不生成 makefile。
            # 修模板可保证无论 config.status 成败，makefile 都是可用的。
            makefile_in = os.path.join(self.source_folder, "makefile.in")
            replace_in_file(
                self, makefile_in, "makefile: configure makefile.in", "makefile:",
            )
            replace_in_file(
                self, makefile_in, "configure: configure.in", "configure:",
            )

            self.run(
                f"{bash_shell} ./configure {' '.join(tc.configure_args)}",
                env="conanbuild",
            )

            # configure 用 config.status 从 makefile.in 生成 makefile。某些构建
            # 环境（CI worker 的 HMDFS 共享盘）不允许 config.status 在源码树内创建
            # 其 mode-0700 临时目录（autoconf 固定用
            # `umask 077 && mktemp -d ./confstatXXXXXX`，相对路径、不受 TMPDIR 影响），
            # 于是 config.status 什么都写不出来、makefile 不存在。这里做三级兜底，
            # 保证 make 一定有可用的 makefile。
            makefile = os.path.join(self.source_folder, "makefile")

            if not os.path.isfile(makefile):
                self.output.warning(
                    "configure did not emit `makefile`; regenerating it"
                )
                # 兜底 1：若 config.status 存在，直接让它单独生成 makefile
                #         （此步尽力而为，失败不中断构建）
                config_status = os.path.join(self.source_folder, "config.status")
                if os.path.isfile(config_status):
                    try:
                        self.run(
                            f"{bash_shell} ./config.status makefile",
                            env="conanbuild",
                        )
                    except ConanException as exc:
                        self.output.warning(
                            f"`config.status makefile` failed ({exc})"
                        )

            if not os.path.isfile(makefile):
                # 兜底 2：直接用 makefile.in 模板，并替换其中全部 @...@ 占位符。
                #         占位符清单取自上游 makefile.in 的实际内容（共 14 个）。
                self.output.warning(
                    "still no makefile; substituting makefile.in placeholders"
                )
                deps_cflags, deps_ldflags = self._dep_flags()
                substitutions = {
                    "@CC@": self._target_cc(),
                    "@CFLAGS@": "-O2",
                    "@DEFS@": "-DHAVE_CONFIG_H",
                    "@CPPFLAGS@": deps_cflags,
                    "@LDFLAGS@": " ".join(
                        x for x in (self._target_ldflags(), deps_ldflags) if x
                    ),
                    "@LIBS@": "-lncursesw",
                    "@prefix@": "/usr",
                    "@exec_prefix@": "/usr",
                    "@bindir@": "/usr/bin",
                    "@datadir@": "/usr/share",
                    "@GAMEGROUP@": "",
                    "@cygwin@": "",
                    "@TK_PORT@": "",
                    "@configure_input@": "generated from makefile.in by conan",
                }
                content = open(makefile_in, encoding="utf-8",
                              errors="replace").read()
                for token, value in substitutions.items():
                    content = content.replace(token, value)

                leftovers = sorted(set(
                    re.findall(r"@[A-Za-z_][A-Za-z0-9_]*@", content)
                ))
                if leftovers:
                    raise ConanInvalidConfiguration(
                        "unresolved placeholders in generated makefile: "
                        + ", ".join(leftovers)
                    )
                with open(makefile, "w", encoding="utf-8") as handle:
                    handle.write(content)

            # config.status 同时负责生成 src/autoconf.h；它写不出来时同样需要兜底，
            # 否则编译报 "fatal error: 'autoconf.h' file not found"。
            autoconf_h = os.path.join(self.source_folder, "src", "autoconf.h")
            if not os.path.isfile(autoconf_h) or os.path.getsize(autoconf_h) == 0:
                template_path = os.path.join(
                    self.source_folder, "src", "autoconf.h.in"
                )
                if not os.path.isfile(template_path):
                    raise ConanInvalidConfiguration(
                        "neither autoconf.h nor autoconf.h.in is available"
                    )
                self.output.warning(
                    "config.status did not emit src/autoconf.h; "
                    "rendering it from autoconf.h.in"
                )
                with open(template_path, encoding="utf-8",
                          errors="replace") as handle:
                    template = handle.read()
                with open(autoconf_h, "w", encoding="utf-8") as handle:
                    handle.write(_render_autoconf_h(template))

            # AC_CHECK_LIB([z],[main]) 会把 -lz 无条件注入 config.status 生成的
            # LIBS，但程序并未使用 zlib；在最终 makefile 上移除，避免无用的运行期
            # 依赖。走模板兜底时 @LIBS@ 已被替换为 -lncursesw（本就无 -lz），
            # 因此这里只在确实存在该片段时才替换。
            final_content = open(makefile, encoding="utf-8",
                                 errors="replace").read()
            if "-lz -lncursesw" in final_content:
                replace_in_file(self, makefile, "-lz -lncursesw", "-lncursesw")
            elif "-lz" in final_content:
                replace_in_file(self, makefile, "-lz ", "")

            self.run(
                f"make -j{build_jobs(self)} "
                f'TOLUA_HOST="{host_tolua}" '
                f'BUILD_CC="{self._build_cc()}" '
                f'BUILD_CFLAGS="-O2 -w -I." '
                f'BUILD_LIBS="-lm"'
            )

    def package(self):
        src = self.source_folder
        copy(self, "zangband", src, os.path.join(self.package_folder, "bin"))
        copy(self, "readme", src, os.path.join(self.package_folder, "licenses"))
        copy(self, "z_faq.txt", src, os.path.join(self.package_folder, "licenses"))
        # 游戏数据：编译期 DEFAULT_PATH 指向 <prefix>/share/games/zangband/lib/
        lib_dst = os.path.join(self.package_folder, "share", "games", "zangband", "lib")
        copy(self, "*", os.path.join(src, "lib"), lib_dst)
        # 上游 lib/ 内的 makefile.zb 仅用于其自身打包流程，运行期无用
        stray = os.path.join(lib_dst, "makefile.zb")
        if os.path.isfile(stray):
            os.remove(stray)

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.resdirs = ["share"]
