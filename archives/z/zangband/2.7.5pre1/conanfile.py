def _render_autoconf_h(template):
    """把 autoheader 的 autoconf.h.in 渲染成 config.status 会产出的 autoconf.h。

    autoconf.h.in 使用 `#undef NAME` 形式；config.status 依据 configure 的探测
    结果把它改成 `#define NAME value` 或注释掉的 `/* #undef NAME */`。
    这里用 _OHOS_AUTOCONF_DEFINES 作为探测结果，输出与实测一致的头部。
    """
    out = ["/* src/autoconf.h.  Generated by configure.  */"]
    for line in template.split("\n"):
        stripped = line.strip()
        if stripped.startswith("#undef "):
            name = stripped.split(None, 1)[1].strip()
            if name in _OHOS_AUTOCONF_DEFINES:
                out.append("#define %s %s" % (name, _OHOS_AUTOCONF_DEFINES[name]))
            else:
                out.append("/* #undef %s */" % name)
        else:
            out.append(line)
    return "\n".join(out)


