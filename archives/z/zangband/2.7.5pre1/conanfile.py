#!/usr/bin/env python3
"""Conan recipe - zangband 2.7.5pre1 (classic roguelike, old-style autoconf + hand-written makefile).

Zangband 使用旧式 autoconf（configure.in，非 automake）+ 手写 makefile.in 构建；
configure 生成顶层 makefile 并递归进入 lib/ 与 src/。

OHOS 适配要点（详见 notes.md）：
- 终端界面走 ncurses(GNU Curses) 端口，链接仓库现有 ncurses/6.6 静态宽字符库
  libncursesw.a。OHOS SDK 的 sysroot 只有运行期 stub libncurses.so.6（无头文件、
  无链接符号），因此必须依赖 Conan 提供的 ncurses。
- 旧式 autoconf 的 AC_CHECK_SIZEOF / AC_FUNC_* 需要**运行**测试程序，交叉编译下
  必须通过 --cache-file 注入已知值，否则 configure 直接失败。
- 上游 configure 脚本是 2005 年的产物，含 bash 专有语法，必须用 bash 而不是 dash。
- src/lua/tolua 是**构建期主机工具**（把 l-*.pkg 生成为 l-*.c），必须用构建机
  编译器编译；且 tolua.c 由 argv[0] 推导 .lua 脚本目录，所以主机版 tolua 必须
  放在 src/lua/ 内，否则静默失败（退出码 0）导致后续编译找不到 l-*.c。
- configure 会用 config.status 从 makefile.in 重新生成顶层 makefile，并复原其
  自重建规则；上游 tarball 不含 automake 辅助文件（config.guess/config.sub），
  一旦触发即失败，因此 make 之前需再次去掉这两条前提。
- configure.in 的 AC_CHECK_LIB([z],[main]) 会无条件引入 -lz，而二进制并不使用
  zlib（llvm-nm -u 验证无 inflate/deflate/crc32 符号）；去掉可避免真机上多一个
  无意义的运行库依赖。
"""

