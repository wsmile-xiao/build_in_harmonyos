#!/usr/bin/env python3
"""Conan recipe — zpaq 7.15 (journaling archiver, ZPAQ open standard).

zpaq 7.15 (Aug 2016, Matt Mahoney) is the reference implementation of the
ZPAQ open standard for highly compressed, deduplicated, self-describing
journaling archives.  Upstream ships exactly two translation units
(`zpaq.cpp` + `libzpaq.cpp`, resp. the CLI and the reusable library) plus a
plain GNU Makefile.  There are **no external library dependencies**: AES-256,
SHA-1/SHA-256 and scrypt are implemented inside `libzpaq.cpp`, divsufsort is
embedded in the same file, and the only system requirement is pthread.

The upstream build documented in `readme.txt` is

    g++ -O3 -march=native -Dunix zpaq.cpp libzpaq.cpp -pthread -o zpaq

This recipe reproduces that single command with the OHOS overrides below.
The upstream `Makefile` only wraps it into a `zpaq` target (`zpaq.o` +
`libzpaq.o` -> `zpaq`), so building both translation units in one `self.run()`
is equivalent, and it keeps the recipe independent of the flavour of shell that
the surrounding CI harness hands to `self.run()`.

OHOS adaptation notes:

* ``-DNOJIT`` **is mandatory, not cosmetic.**  ``libzpaq.cpp``'s
  ``ZPAQL::assemble()`` (lines 3035-4585) emits x86-32/x86-64 machine code at
  run time and jumps into it.  Measured on OHOS aarch64: a build without
  ``-DNOJIT`` compresses fine but dies with ``Illegal instruction (core
  dumped)`` the moment ``Predictor::predict()`` starts interpreting a
  ZPAQL-compressed block.  ``-DNOJIT`` selects the portable ``predict0()``
  interpreter instead.  (Upstream readme: "To compile for non x86 or x86-64
  hardware use option -DNOJIT".)
* ``-march=native`` is dropped: the package has to stay runnable across the
  aarch64 OHOS target matrix, and clang rejects ``-march=native`` when the
  compilation target is not the host CPU.
* ``-static-libstdc++`` bakes libc++ into the executable.  The OHOS SDK
  sysroot ships ``libc++_shared.so`` as a linker script (``INPUT(-lc++_shared)``)
  that the musl loader cannot resolve, so a dynamically linked C++ binary aborts
  at start-up with "Error loading shared library libc++_shared.so".  The
  resulting binary's only ``DT_NEEDED`` entry is ``libc.so``.
* ``-Dunix`` selects the POSIX code paths; upstream defaults to Windows.
* The compiler's stdout/stderr are redirected into a log file inside the build
  folder (and echoed afterwards).  With this platform's ``/system/bin/sh`` as
  the recipe shell, a compiler whose stdio is wired directly into the CI
  harness' capture pipe exits 1 **without any diagnostics**, while the identical
  command succeeds when its stdio is a regular file.  The redirect keeps the
  build working under both shells and preserves the diagnostics in the CI log.
* No patch is applied — the source is pristine.  ``apply_conandata_patches()`` is
  kept for contract consistency with the (empty) ``patches:`` list.

The package ships ``bin/zpaq`` plus the upstream licence text under
``licenses/COPYING`` (Unlicense; ``libzpaq.cpp`` additionally embeds a
divsufsort.c excerpt that is MIT).

The man page target (``zpaq.1``, generated by ``pod2man``) is deliberately not
built: it is optional documentation, not a package artifact, and upstream's
``install`` target is not used here.
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
)
from conan.tools.layout import basic_layout


class ZpaqConan(ConanFile):
    name = "zpaq"
    version = "7.15"
    description = (
        "zpaq 7.15 — journaling archiver for user-level incremental backup "
        "(AES-256 encryption, 5 compression levels, content-aware "
        "file-fragment deduplication, ZPAQ open format)"
    )
    license = "Unlicense"
    homepage = "https://github.com/zpaq/zpaq"
    url = "https://github.com/zpaq/zpaq"

    package_type = "application"
    topics = ("zpaq", "compression", "archiver", "backup", "deduplication")

    settings = "os", "compiler", "build_type", "arch"

    def validate(self):
        # R32: platform gate must accept both Linux and OHOS
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "zpaq is supported only on Linux/OHOS, not "
                + str(self.settings.os)
            )

    def export_sources(self):
        # No patches in this recipe: the source is pristine.  The call is kept
        # for the standard recipe contract, and so that the (currently empty)
        # conandata.yml patch list would be exported if one is added later.
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        # No patches in this recipe (pristine source); the call is kept for the
        # standard patch pipeline contract (no-op with an empty patches list).
        apply_conandata_patches(self)

        # R33: the C++ compiler comes from the Conan conf
        # (tools.build:compiler_executables), never from bare shell vars.
        comp = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        )
        cxx = comp.get("cpp") or "clang++"

        # Upstream readme.txt documents the whole build as a single manual
        # command (`g++ -O3 -march=native -Dunix zpaq.cpp libzpaq.cpp -pthread
        # -o zpaq`); the shipped Makefile only wraps it into the `zpaq` target.
        # Both translation units are therefore compiled and linked in one
        # invocation.
        #
        # The compiler's stdio is redirected into a log file: with this
        # platform's /system/bin/sh as the recipe shell, a compiler whose
        # stdout/stderr are wired straight into the CI harness' capture pipe
        # dies silently (exit 1, no diagnostics at all), while the identical
        # command succeeds when its stdio is a regular file.  The log is echoed
        # afterwards so the diagnostics stay visible in the conan / CI log.
        build_log = os.path.join(self.build_folder, "zpaq-build.log")
        self.run(
            f'{cxx} -O3 -DNDEBUG -Dunix -DNOJIT -static-libstdc++ '
            f'zpaq.cpp libzpaq.cpp -pthread -o zpaq > "{build_log}" 2>&1; '
            f'rc=$?; cat "{build_log}"; exit $rc',
            cwd=self.source_folder,
            env="conanbuild",
        )

    def package(self):
        # The only built artifact is the CLI; the Makefile's object files and
        # the (unbuilt) man page are intentionally not packaged.
        copy(
            self,
            "zpaq",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "bin"),
        )
        # Ship the upstream licence text.  COPYING is the Unlicense (public
        # domain); upstream additionally embeds a divsufsort.c excerpt inside
        # libzpaq.cpp, which is MIT — both are recorded here and in notes.md.
        copy(
            self,
            "COPYING",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "licenses"),
        )

    def package_info(self):
        # Command-line tool, not a library (no cpp_info.libs)
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
