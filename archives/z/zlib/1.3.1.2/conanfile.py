#!/usr/bin/env python3
"""Conan recipe for zlib 1.3.1 — Makefile build system.

zlib is a system same-name library (/lib/libz.so*), so it must be built
static-only (R26) to avoid polluting system library paths.
Build: ./configure --static && make -j1 (R9 parallel constraint).
"""
import os

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class ZlibConan(ConanFile):
    name = "zlib"
    version = "1.3.1.2"
    description = "Massively-used data compression library (DEFLATE/inflate)."
    license = "Zlib"
    homepage = "https://zlib.net/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)
        # zlib builds in-source (Makefile generated by configure in source dir)
        self.folders.build = "."

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)
        # R33: Get compiler from Conan conf, not shell env vars
        compilers = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict)
        cc = compilers.get("c", "clang") if compilers else "clang"
        # R26: zlib is a system same-name library (/lib/libz.so*),
        # must build static only to avoid polluting system lib paths.
        # CONFIG_SHELL is set by profile [buildenv] on OHOS;
        # default to OHOS bash path for safety (R5: OHOS has no /bin/sh)
        config_shell = os.environ.get("CONFIG_SHELL", "/data/service/hnp/bin/bash")
        # Set CC and CONFIG_SHELL explicitly for configure to pick up
        self.run(f"CONFIG_SHELL={config_shell} CC={cc} {config_shell} ./configure --static --prefix=/")
        # R9: Use -j1 for parallel constraint on OHOS platform
        self.run("make -j1")
        # L1: Run upstream official test suite (make check)
        # zlib 的 make check 会编译并运行 example.c 和 infcover.c
        self.run("make check")

    def package(self):
        # Install to Conan package folder via DESTDIR
        # With --prefix=/, files go to <package_folder>/lib and <package_folder>/include
        self.run("make install DESTDIR={}".format(self.package_folder))

    def package_info(self):
        # The library file is libz.a, so the lib name is "z" (not "zlib")
        self.cpp_info.libs = ["z"]
