#!/usr/bin/env python3
"""Conan recipe for KSyntaxHighlighting 5.116.0 (KDE Frameworks 5) on HarmonyOS PC.

KSyntaxHighlighting is the KDE syntax highlighting engine; this KF5 branch
builds libKF5SyntaxHighlighting on top of Qt5.

OHOS-specific adaptations (validated on sibling KF5 packages ki18n5/5.116.0
and attica-kf5/5.116.0):
  - QT_MAJOR_VERSION=5 so the project finds Qt5 (qt5-qtbase/5.15.2.2).
  - KF_IGNORE_PLATFORM_CHECK=TRUE to bypass KDE platform detection (OHOS is
    not in the KDE platform list).
  - KF_SKIP_PO_PROCESSING=ON skips ECMPoQmTools translation generation
    (ECMPoQmTools natively honours this option, so no poqm patch is needed).
  - BUILD_QCH=OFF skips optional API documentation generation.
  - QRC_SYNTAX=ON bundles the syntax and theme definitions into the library
    so consumers do not need external syntax data files. The definitions are
    generated by the katehighlightingindexer tool, which is built as a host
    executable and run at build time. On this target host==build (aarch64
    OHOS 真机), so the tool runs natively without KF5_HOST_TOOLING.
  - ecm is a tool_requires; ecm/6.26.0 satisfies find_package(ECM 5.116.0)
    (minimum-version semantics, same pattern as attica-kf5/5.116.0).
  - perl is a REQUIRED build tool: data/generators/*.pl generate the merged
    PHP syntax definition files; perl/5.42.2 supplies it (PERL_EXECUTABLE is
    pinned so the build does not depend on shell PATH).
  - qt5-qtbase ships per-module cmake configs but no aggregated Qt5Config;
    CMakeDeps regenerates one via cmake_file_name "Qt5" (attica-kf5 pattern).
  - CMAKE_AUTOMOC_EXECUTABLE / CMAKE_AUTORCC_EXECUTABLE point at the
    qt5-qtbase bin/moc and bin/rcc (CMakeDeps does not export Qt5::moc/rcc).
  - HarmonyOS does not map to the Linux CMake platform, so
    CMAKE_SHARED_LIBRARY_SONAME_<lang>_FLAG is undefined and produced .so
    files lack DT_SONAME (W3 CI L5 gate). Set the soname flag +
    CMAKE_PLATFORM_NO_VERSIONED_SONAME (ki18n5 validated pattern).
"""
import os
import shutil

from conan import ConanFile
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.env import Environment, VirtualBuildEnv
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get


class KsyntaxhighlightingConan(ConanFile):
    name = "ksyntax-highlighting"
    version = "5.116.0"
    description = "KDE Frameworks 5 - KDE syntax highlighting engine"
    license = "MIT"
    homepage = "https://invent.kde.org/frameworks/syntax-highlighting"
    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("qt5-qtbase/5.15.2.2")

    def build_requirements(self):
        self.tool_requires("ecm/6.26.0")
        self.tool_requires("perl/5.42.2")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        VirtualBuildEnv(self).generate()
        deps = CMakeDeps(self)
        # Regenerate a clean aggregated Qt5Config (qt5-qtbase only ships
        # per-module configs; find_package(Qt5 COMPONENTS ...) needs one).
        deps.set_property("qt5-qtbase", "cmake_file_name", "Qt5")
        deps.generate()

        tc = CMakeToolchain(self)
        tc.variables["QT_MAJOR_VERSION"] = "5"
        tc.variables["KF_IGNORE_PLATFORM_CHECK"] = "TRUE"
        tc.variables["BUILD_TESTING"] = "ON"
        tc.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        tc.variables["BUILD_QCH"] = "OFF"
        tc.variables["QRC_SYNTAX"] = "ON"
        tc.variables["KSYNTAXHIGHLIGHTING_USE_GUI"] = "ON"
        tc.variables["KF_SKIP_PO_PROCESSING"] = "ON"
        tc.variables["CMAKE_INSTALL_LIBDIR"] = "lib"
        # SONAME emission on OHOS (see module docstring).
        tc.variables["CMAKE_PLATFORM_NO_VERSIONED_SONAME"] = "TRUE"
        tc.variables["CMAKE_SHARED_LIBRARY_SONAME_C_FLAG"] = "-Wl,-soname,"
        tc.variables["CMAKE_SHARED_LIBRARY_SONAME_CXX_FLAG"] = "-Wl,-soname,"

        # ECM's CMakeDeps-generated ECMConfig.cmake does not propagate
        # ECM_MODULE_PATH; set it manually so KDE cmake modules
        # (KDEInstallDirs, KDECMakeSettings, ...) are found.
        ecm = self.dependencies.build.get("ecm")
        if ecm:
            ecm_share = os.path.join(ecm.package_folder, "share", "ECM")
            tc.variables["ECM_MODULE_PATH"] = ";".join([
                os.path.join(ecm_share, "modules"),
                os.path.join(ecm_share, "find-modules"),
                os.path.join(ecm_share, "kde-modules"),
            ])

        perl = self.dependencies.build.get("perl")
        if perl:
            tc.variables["PERL_EXECUTABLE"] = os.path.join(
                perl.package_folder, "bin", "perl"
            )

        qt5 = self.dependencies["qt5-qtbase"]
        moc_path = os.path.join(qt5.package_folder, "bin", "moc")
        rcc_path = os.path.join(qt5.package_folder, "bin", "rcc")
        if not os.path.isfile(moc_path):
            raise RuntimeError(
                "qt5-qtbase/5.15.2.2 does not provide the required bin/moc tool"
            )
        if not os.path.isfile(rcc_path):
            raise RuntimeError(
                "qt5-qtbase/5.15.2.2 does not provide the required bin/rcc tool"
            )
        tc.variables["CMAKE_AUTOMOC_EXECUTABLE"] = moc_path
        tc.variables["CMAKE_AUTORCC_EXECUTABLE"] = rcc_path

        self._prepare_qt_mkspec_compat(qt5.package_folder)

        tc.generate()
        self._write_cmake_paths(ecm, qt5)

    @staticmethod
    def _write_cmake_paths(ecm, qt5):
        lines = ["set(CMAKE_FIND_PACKAGE_PREFER_CONFIG ON)"]
        qt_pkg = qt5.package_folder
        lines.append('list(PREPEND CMAKE_PREFIX_PATH "%s/lib/cmake")' % qt_pkg)
        lines.append('list(PREPEND CMAKE_LIBRARY_PATH "%s/lib")' % qt_pkg)
        lines.append('list(PREPEND CMAKE_INCLUDE_PATH "%s/include")' % qt_pkg)
        if ecm:
            ecm_share = os.path.join(ecm.package_folder, "share", "ECM")
            lines.append('list(PREPEND CMAKE_MODULE_PATH "%s/cmake")' % ecm_share)
            lines.append('list(PREPEND CMAKE_MODULE_PATH "%s/modules")' % ecm_share)
            lines.append('list(PREPEND CMAKE_MODULE_PATH "%s/find-modules")' % ecm_share)
            lines.append('list(PREPEND CMAKE_MODULE_PATH "%s/kde-modules")' % ecm_share)
            lines.append('list(PREPEND CMAKE_PREFIX_PATH "%s/cmake")' % ecm_share)
        # The generators folder is where CMakeDeps saves Qt5Config.cmake.
        lines.append('list(PREPEND CMAKE_MODULE_PATH "${CMAKE_CURRENT_LIST_DIR}")')
        lines.append('list(PREPEND CMAKE_PREFIX_PATH "${CMAKE_CURRENT_LIST_DIR}")')
        paths_file = os.path.join(
            os.getcwd(), "conan_cmakedeps_paths.cmake"
        )
        with open(paths_file, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")

    @staticmethod
    def _prepare_qt_mkspec_compat(qt_package_folder):
        # Qt5CoreConfigExtrasMkspecDir.cmake hardcodes
        # <pkg>/../b/mkspecs/linux-clang (a build-tree path that does not
        # exist in the conan cache). attica-kf5/5.116.0 validated workaround:
        # copy the mkspecs tree from the package folder to the expected spot.
        source = os.path.join(qt_package_folder, "mkspecs", "linux-clang")
        expected = os.path.join(
            os.path.dirname(qt_package_folder), "b", "mkspecs", "linux-clang"
        )
        if os.path.isdir(source) and not os.path.exists(expected):
            os.makedirs(os.path.dirname(expected), exist_ok=True)
            shutil.copytree(source, expected)

    def build(self):
        if self.settings.os == "OHOS":
            apply_conandata_patches(self)
        cmake = CMake(self)
        with self._library_runtime_env().vars(self).apply():
            cmake.configure()
            cmake.build()
            self._run_upstream_tests()

    def _run_upstream_tests(self):
        test_env = self._library_runtime_env()
        test_env.define("CTEST_OUTPUT_ON_FAILURE", "1")
        test_env.define("CTEST_PARALLEL_LEVEL", "1")
        test_home = os.path.join(self.build_folder, "test-home")
        test_tmp = os.path.join(self.build_folder, "test-tmp")
        xdg_runtime = os.path.join(self.build_folder, "xdg-runtime")
        os.makedirs(test_home, exist_ok=True)
        os.makedirs(test_tmp, exist_ok=True)
        os.makedirs(xdg_runtime, exist_ok=True)
        os.chmod(xdg_runtime, 0o700)
        test_env.define("HOME", test_home)
        test_env.define("TMPDIR", test_tmp)
        test_env.define("TEMP", test_tmp)
        test_env.define("TMP", test_tmp)
        test_env.define("XDG_RUNTIME_DIR", xdg_runtime)
        test_env.define("XDG_CACHE_HOME", os.path.join(test_home, ".cache"))
        test_env.define("XDG_CONFIG_HOME", os.path.join(test_home, ".config"))
        test_env.define("XDG_DATA_HOME", os.path.join(test_home, ".local", "share"))
        with test_env.vars(self).apply():
            self.run(
                'ctest --test-dir "{}" --output-on-failure --no-tests=error --timeout 240'.format(
                    self.build_folder
                )
            )

    def _library_runtime_env(self):
        runtime_env = Environment()
        for dep in list(self.dependencies.values()) + list(self.dependencies.build.values()):
            if dep and dep.package_folder:
                runtime_env.prepend_path(
                    "LD_LIBRARY_PATH", os.path.join(dep.package_folder, "lib")
                )
                runtime_env.prepend_path(
                    "PATH", os.path.join(dep.package_folder, "bin")
                )
                runtime_env.prepend_path(
                    "QT_PLUGIN_PATH", os.path.join(dep.package_folder, "plugins")
                )
        for rel in ("bin", "lib", os.path.join("src", "lib")):
            runtime_env.prepend_path("LD_LIBRARY_PATH", os.path.join(self.build_folder, rel))
        return runtime_env

    def package(self):
        cmake = CMake(self)
        with self._library_runtime_env().vars(self).apply():
            cmake.install()

    def package_info(self):
        # The project installs its own KF5SyntaxHighlightingConfig.cmake with
        # proper dependency tracking (find_dependency on Qt5Core/Gui). Use
        # cmake_find_mode=none so CMakeDeps does not shadow it.
        self.cpp_info.set_property("cmake_find_mode", "none")
        self.cpp_info.builddirs = [os.path.join("lib", "cmake")]
        self.cpp_info.libs = ["KF5SyntaxHighlighting"]
        self.runenv_info.prepend_path(
            "LD_LIBRARY_PATH", os.path.join(self.package_folder, "lib")
        )
