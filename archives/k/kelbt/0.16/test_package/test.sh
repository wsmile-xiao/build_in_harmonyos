#!/bin/bash
# test_package/test.sh — consumer smoke test for kelbt.
# Runs in conanrun env (PATH includes the installed bin/).
set -euo pipefail

echo "[test] kelbt --version"
kelbt --version

echo "[test] version string contains 0.16"
kelbt --version 2>&1 | grep -q '0\.16'

echo "[test] kelbt generates parser header from .kh grammar"
kelbt -o test_gen.h test.kh

echo "[test] generated header is non-empty"
[ -s test_gen.h ] || { echo "test_gen.h is empty"; exit 1; }

echo "[test] generated header carries Kelbt marker"
grep -q 'Automatically generated by Kelbt' test_gen.h

echo "[test] generated header carries token definitions"
grep -q '#define KW_Parser' test_gen.h

echo "kelbt smoke test OK"
