#!/usr/bin/env python3
"""Conan recipe for kdc2tiff 0.35 — Kodak DC120 KDC -> TIFF/JPEG converter (CLI).

kdc2tiff converts Kodak DC120 ``.kdc`` raw files and, because it decodes TIFF
and JPEG through libtiff/libjpeg, ordinary images as well.  The output format is
picked from ``argv[0]``, so the package installs both ``kdc2tiff`` (TIFF writer)
and ``kdc2jpeg`` (JPEG writer).  Upstream creates the second name with
``ln -f``, which HMDFS rejects ("cannot create hard link ... Operation not
permitted"), hence patch 0002 turns it into ``cp -f``.

Build system: autotools — the tarball ships files pre-generated by Autoconf
2.58 + automake 1.4-p4 and has **no** ``config.guess``/``config.sub``, and its
``configure`` never invokes them, so the E007 recipe does not apply here.
The CI worker has no automake/autoconf/autoheader, so patch 0001 removes the
``umask 077`` that makes config.status' temp dir unwritable on HMDFS (E114),
and ``build()`` normalises autotools mtimes so no maintainer rule fires.

Dependencies (W0 evidence in notes.md, R35: proven by conan install):
  - libtiff/4.7.2        -> -ltiff   (configure.in: AC_CHECK_LIB(tiff,main))
  - libjpeg-turbo/3.2.0  -> -ljpeg   (configure.in: AC_CHECK_LIB(jpeg,main))
  - libm                 -> already exported by libtiff's cpp_info.system_libs
"""
import os
import time

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class Kdc2tiffConan(ConanFile):
    name = "kdc2tiff"
    version = "0.35"
    description = ("Command line converter from Kodak DC120 .kdc raw images "
                   "(and TIFF/JPEG input) into TIFF or JPEG")
    license = "GPL-2.0-or-later"
    homepage = "https://sourceforge.net/projects/kdc2tiff/"
    url = ""  # CI fills this

    # CLI tool, not a library (R38: commands.json declared at software level)
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # tiffio.h (GFile_TIFF.cpp, KDCFile.cpp) and jpeglib.h (GFile_JPEG.cpp,
        # KDCFile.cpp, kdc2tiff.cpp) are direct includes, and configure links
        # -ltiff / -ljpeg.  The jpeg provider is the very one libtiff/4.7.2
        # already pulls in, so the graph carries exactly one libjpeg.so.
        self.requires("libtiff/4.7.2")
        self.requires("libjpeg-turbo/3.2.0")

    def validate(self):
        # R32: the os test must accept OHOS next to Linux, never == "Linux"
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"kdc2tiff is only supported on Linux/OHOS, not {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _order_autotools_mtimes(self):
        """Keep generated autotools files newer than their maintainer inputs.

        automake-1.4 embeds rules such as ``$(srcdir)/Makefile.in: Makefile.am
        configure.in aclocal.m4`` that re-run automake / autoconf / autoheader
        as soon as a prerequisite looks newer.  Applying patches rewrites those
        mtimes, so the order is normalised explicitly (file contents untouched)
        instead of letting make call tools the CI worker does not ship.
        """
        ordered = ("configure.in", "Makefile.am", "aclocal.m4", "stamp-h.in",
                   "config.h.in", "Makefile.in", "configure")
        for name in ordered:
            path = os.path.join(self.source_folder, name)
            if os.path.exists(path):
                stamp = time.time()
                os.utime(path, (stamp, stamp))

    def generate(self):
        # AutotoolsDeps turns the libtiff/libjpeg graph into -I/-L/-l so that
        # configure's AC_CHECK_LIB probes and the final link both resolve.
        deps = AutotoolsDeps(self)
        deps.generate()
        tc = AutotoolsToolchain(self)
        tc.generate()
        # The OHOS loader does not look into the conan cache and libtiff /
        # libjpeg are shared objects here, so their lib dirs must be on
        # LD_LIBRARY_PATH for the conftest programs that configure executes.
        env = Environment()
        for dep in self.dependencies.values():
            for libdir in dep.cpp_info.libdirs:
                env.prepend_path("LD_LIBRARY_PATH", libdir)
        env.vars(self, scope="build").save_script("conanbuild_libdirs")

    def build(self):
        apply_conandata_patches(self)
        self._order_autotools_mtimes()
        autotools = Autotools(self)
        autotools.configure()
        # -j1: parallel make hits the HMDFS jobserver fifo (E074)
        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        # Standalone binaries; no C++/library surface to export (R34 is covered
        # by test_package, which executes the installed programs).
        self.cpp_info.libs = []
        self.cpp_info.bindirs = ["bin"]
