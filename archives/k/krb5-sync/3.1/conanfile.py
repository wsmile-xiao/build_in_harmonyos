#!/usr/bin/env python3
"""Conan recipe for krb5-sync: a Kerberos -> Active Directory synchronization
kadmin hook plugin plus the krb5-sync / krb5-sync-backend command-line tools.

First draft generated by `ohc-run.py conan-init` (autotools template), then
filled in per SKILL Step 2.5.  Dependency wiring follows the merged
krb5-strength/3.3 precedent from the same upstream author (same rra-c-util m4
macros): inject the Conan-managed krb5 package through --with-krb5-* so
configure never probes a host krb5-config, and true-cross for OHOS.
"""
import glob
import os
import shlex
import shutil
import subprocess

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    load,
    replace_in_file,
)
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class Krb5SyncConan(ConanFile):
    name = "krb5-sync"
    version = "3.1"
    description = ("Kerberos-to-Active-Directory synchronization toolkit: a kadmin "
                   "hook plugin for MIT/Heimdal plus krb5-sync command-line tools")
    license = "BSD-3-Clause"
    homepage = "https://www.eyrie.org/~eagle/software/krb5-sync/"
    url = ""  # CI fills this
    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("krb5-sync supported only on Linux/OHOS")
        if self.settings.os == "OHOS" and self.settings.arch != "armv8":
            raise ConanInvalidConfiguration("OHOS builds require armv8/aarch64")

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # Both verified published: real binary downloads from remote ohpcd under
        # the ohos-aarch64 profile (W0 evidence, see notes.md).
        self.requires("krb5/1.22.1")
        self.requires("openldap/2.6.7")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _extra_configure_args(self, ldap_libdir=None):
        # Single source of truth: reused by generate() and by the explicit
        # configure invocation in build() (the OHOS path cannot go through
        # Autotools.configure() because it cannot prefix CONFIG_SHELL).
        krb5 = self.dependencies["krb5"].cpp_info
        ldap = self.dependencies["openldap"].cpp_info
        # R49: private Conan-managed paths only.  Passing both --with-krb5-include
        # and --with-krb5-lib makes the rra krb5.m4 skip its krb5-config probe, so
        # a host krb5-config can never be picked up during a cross build.
        args = [
            "--with-krb5-include={}".format(krb5.includedirs[0]),
            "--with-krb5-lib={}".format(krb5.libdirs[0]),
            "--with-ldap-include={}".format(ldap.includedirs[0]),
            "--with-ldap-lib={}".format(ldap_libdir or ldap.libdirs[0]),
            # The toolchain default is --libdir=${prefix}/lib, which with the
            # Conan convention --prefix=/ normalizes to //lib: libtool then
            # bakes //lib into the plugin -rpath and into our own .la
            # metadata.  Pin one slash; install still goes through DESTDIR, so
            # the package layout (lib/) is unchanged.
            "--libdir=/lib",
        ]
        if self.settings.os == "OHOS":
            # True cross: upstream configure has runtime probes
            # (AC_CHECK_SIZEOF / AC_TYPE_LONG_LONG_INT); fake-native
            # (--build=--host) aborts at "cannot compute size of long", while
            # true cross makes autoconf fall back to compile-only checks.
            # config.sub is taught the ohos triplet by
            # patches/0001-config-sub-ohos.patch (E122 precedent).
            args.extend(["--host=aarch64-linux-ohos", "--build=x86_64-linux-gnu"])
        return args

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.configure_args.extend(self._extra_configure_args())
        tc.generate()
        # Emit -I/-L/-l for krb5 and openldap into conanautotoolsdeps.sh so the
        # kadm5srv / ldap AC_CHECK_LIB probes resolve without host prefixes.
        deps = AutotoolsDeps(self)
        deps.generate()

    def _pick_shell(self):
        """E386 capability-tested shell (knowledge/graph/E386.kv).

        The ci profile buildenv exports CONFIG_SHELL/SHELL as
        /data/service/hnp/bin/bash, whose getcwd() fails on HMDFS build dirs:
        it starts with a `shell-init: error retrieving current directory`
        diagnostic and leaves $PWD empty, so autoconf's own check aborts with
        "configure: error: working directory cannot be determined".  A shell is
        accepted only when `pwd` run from the real build directory exits 0,
        prints an absolute path and keeps stderr silent (E386 forbids trusting
        a noisy pwd probe or the executable bit / return code alone).
        """
        for cand in ("/bin/sh", "/system/bin/sh", "/data/service/hnp/bin/bash"):
            if not os.path.isfile(cand):
                continue
            proc = subprocess.run([cand, "-c", "pwd"], cwd=self.build_folder,
                                  stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            out = proc.stdout.decode("utf-8", "ignore").strip()
            err = proc.stderr.decode("utf-8", "ignore").strip()
            ok = proc.returncode == 0 and not err and out.startswith("/")
            self.output.info("E386 shell probe: {} rc={} pwd={} stderr={} -> {}".format(
                cand, proc.returncode, out or "<empty>", err or "<empty>",
                "accepted" if ok else "rejected"))
            if ok:
                return cand
        raise ConanException("no shell passes the E386 pwd probe in the HMDFS "
                             "build directory")

    def _la_free_dep_libdir(self, dep):
        """E236 scoped-la-free directory for a relocated dependency.

        openldap/2.6.7 ships installed Libtool metadata recorded under its
        own --prefix=/: both .la files carry libdir='//lib' and libldap.la
        even carries an absolute dependency_libs entry //lib/liblber.la.
        Libtool gives a visible .la precedence over the sibling .so, so the
        kadmin hook link died with
        "libtool: link: cannot find the library '//lib/liblber.la'"
        (reports/conan-create.log:344) while the real objects sat in the very
        same directory.  Mirror the payload without any .la file; the shared
        Conan package cache stays untouched (E236 forbid_1 forbids deleting
        or sed-ing .la files in the cache).
        """
        src = self.dependencies[dep].cpp_info.libdirs[0]
        dst = os.path.join(self.build_folder, ".la-free-libs")
        os.makedirs(dst, exist_ok=True)
        mirrored = []
        for name in sorted(os.listdir(src)):
            origin = os.path.join(src, name)
            if name.endswith(".la") or not os.path.isfile(origin):
                continue
            target = os.path.join(dst, name)
            if not os.path.lexists(target):
                try:
                    os.symlink(os.path.realpath(origin), target)
                except OSError:
                    shutil.copy2(origin, target)
            mirrored.append(name)
        self.output.info("E236 la-free mirror {} -> {} ({})".format(
            src, dst, ", ".join(mirrored) or "<none>"))
        return src, dst

    def _point_build_env_at_mirror(self, src, dst):
        """Keep every -L of the dependency lib dir out of the build env.

        AutotoolsDeps writes -L<src> into conan/conanautotoolsdeps.sh (LDFLAGS)
        and the toolchain records --with-ldap-lib=<src>; configure copies both
        into config.status and the generated Makefile, so patching the Makefile
        after configure would be undone by the next config.status run.  These
        env scripts are build-private files generated by this recipe, so the
        redirect happens once, before configure.
        """
        conan_dir = os.path.join(self.build_folder, "conan")
        patched = []
        for name in sorted(os.listdir(conan_dir)):
            path = os.path.join(conan_dir, name)
            if not os.path.isfile(path) or src not in load(self, path):
                continue
            replace_in_file(self, path, "-L{}".format(src),
                            "-L{}".format(dst), strict=False)
            replace_in_file(self, path, "--with-ldap-lib={}".format(src),
                            "--with-ldap-lib={}".format(dst), strict=False)
            patched.append(name)
        self.output.info("E236 -L/--with-ldap-lib redirect applied in: {}".format(
            ", ".join(patched) or "<none>"))

    def _recover_queuing_residue(self, check_log, libdirs):
        """Re-run the one test set that "make check" blocked on same-round residue.

        plugin/queue-only mkdirs $BUILD/tests/tmp/queue and then dies inside the
        set, so neither its own rmdir nor any harness cleanup runs; the directory
        survives *within the same make check pass*.  plugin/queuing is next in
        TESTS order and starts with test_tmpdir() + mkdir("queue"), so it aborts
        on "cannot mkdir queue: File exists" before its first assertion and
        runtests counts the whole set as 0 executed.  Wiping the directory before
        "make check" cannot fix that -- the residue is produced by that very run
        -- so the recovery belongs right after it: drop the residue, re-run only
        the set the log actually shows as blocked, and put that set's own verdict
        on the record (AGENTS 手册/04 §10: 0 执行不可交付).  No upstream test file
        is touched and no set is dropped or re-planned.
        """
        blocked_lines = []
        for line in load(self, check_log).splitlines():
            text = line.strip()
            if text.startswith("plugin/queuing") and "cannot mkdir queue" in text:
                blocked_lines.append(text)
        if not blocked_lines:
            self.output.info("queue hygiene: plugin/queuing was not blocked by a "
                             "leftover queue directory, nothing to recover")
            return
        residue = os.path.join(self.build_folder, "tests", "tmp", "queue")
        if os.path.isdir(residue):
            shutil.rmtree(residue)
        if os.path.lexists(residue):
            raise ConanException(
                "queue hygiene: {} is still present after removal, so plugin/queuing "
                "would abort on the same residue again".format(residue))
        self.output.info("queue hygiene: removed {} left behind by the same make "
                         "check run; blocked set was: {}".format(
                             residue, blocked_lines[0]))
        # Same inline LD_LIBRARY_PATH as the full pass: the drivers link against
        # the Conan krb5/openldap shared libraries (E386 forbid_2 -- never
        # os.environ / Environment().define, env="conanbuild" re-exports the
        # profile buildenv afterwards).  runtests takes the sets to run as
        # positional arguments, exactly like the -l TESTS invocation make check
        # uses; the compiled-in SOURCE/BUILD make the set name resolvable from
        # the tests directory.
        recovery_log = os.path.join(self.build_folder, "make-check-queuing.log")
        rc = self.run('LD_LIBRARY_PATH="{ld}" ./runtests plugin/queuing > {log} 2>&1'
                      .format(ld=":".join(libdirs), log=shlex.quote(recovery_log)),
                      cwd=os.path.join(self.build_folder, "tests"),
                      env="conanbuild", ignore_errors=True)
        verdict = ""
        batch = ""
        declared = 0
        recovery_text = ""
        if os.path.isfile(recovery_log):
            recovery_text = load(self, recovery_log)
        for line in recovery_text.splitlines():
            text = line.strip()
            # "plugin/queuing." anchors the per-set verdict; the "Failed Set"
            # table prints a second line starting with the same set name.
            if text.startswith("plugin/queuing.") and not verdict:
                verdict = text
            if text.startswith("Files="):
                for field in text.replace(",", " ").split():
                    if field.startswith("Tests="):
                        declared = int(field.split("=", 1)[1])
            first = text[len("Failed "):] if text.startswith("Failed ") else ""
            if (text.startswith("Aborted ") or text.startswith("All tests successful")
                    or (first[:1].isdigit() and " tests" in text)):
                batch = text
        # The recovery run is held to the same narrow bar as the full pass: it
        # must produce a completed verdict for the set and a plan count, and a
        # set that aborts, misses assertions or reports itself as skipped is an
        # error here rather than a number to file away.
        if not verdict or declared <= 0:
            raise ConanException(
                "queue hygiene: re-running plugin/queuing produced no completed "
                "runtests verdict (verdict={!r}, declared={}, rc={}, log={}), so "
                "its assertions would be declared without execution".format(
                    verdict, declared, rc, recovery_log))
        failed = None
        if "FAILED" in verdict:
            for token in batch.replace(",", " ").split():
                if "/" in token:
                    head, _, tail = token.partition("/")
                    if head.isdigit() and tail.isdigit():
                        failed = int(head)
                        if int(tail) != declared:
                            raise ConanException(
                                "queue hygiene: runtests summary {!r} disagrees with "
                                "the plan count {} of plugin/queuing".format(
                                    batch, declared))
                        break
            if failed is None:
                raise ConanException(
                    "queue hygiene: no failed/total count found in the recovery "
                    "summary {!r} (verdict={!r})".format(batch, verdict))
        elif verdict.endswith("ok"):
            failed = 0
        else:
            raise ConanException(
                "queue hygiene: plugin/queuing did not complete after removing the "
                "residue (verdict={!r}, summary={!r}, rc={})".format(
                    verdict, batch, rc))
        if failed:
            # Disclosed, not swallowed: these are real per-assertion results on
            # this platform and are itemized in notes.md, same as every other
            # set that "make check" reports.
            self.output.error("queue hygiene: plugin/queuing ran {} assertions and "
                              "{} failed -- {}".format(declared, failed, batch))
        self.output.info("KRB5_QUEUE_HYGIENE_RESULT=set=plugin/queuing discovered={} "
                         "executed={} failed={} passed={} declared={} rc={}".format(
                             len(blocked_lines), declared, failed, declared - failed,
                             declared, rc))

    def build(self):
        apply_conandata_patches(self)
        # E236: strip the non-relocatable dependency .la metadata from the
        # library search path before anything links against it.
        ldap_src, ldap_mirror = self._la_free_dep_libdir("openldap")
        self._point_build_env_at_mirror(ldap_src, ldap_mirror)
        autotools = Autotools(self)
        shell = self._pick_shell() if str(self.settings.os) == "OHOS" else None
        if shell is None:
            autotools.configure()
        else:
            # TMPDIR: /tmp is read-only on the build hosts (cvsgraph/1.7.0).
            tmpdir = os.path.join(self.build_folder, "tmp")
            os.makedirs(tmpdir, exist_ok=True)
            tc = AutotoolsToolchain(self)
            args = list(tc.configure_args) + self._extra_configure_args(ldap_mirror)
            if not any(a.startswith("--prefix=") for a in args):
                raise ConanException("AutotoolsToolchain default prefix args vanished; "
                                     "refusing to configure without --prefix")
            configure = os.path.join(self.source_folder, "configure")
            # The overrides must be inline: env="conanbuild" sources the profile
            # buildenv afterwards and would re-export the broken bash (cvsgraph
            # /1.7.0 + libfec real-device findings, cf. knowledge/drafts/
            # libfec-1.0-26-gc5d935f-configshell-bash-getcwd-hmdfs.md).
            self.run('TMPDIR={tmp} CONFIG_SHELL={sh} SHELL={sh} {sh} {cfg} {args}'
                     .format(tmp=shlex.quote(tmpdir), sh=shell,
                             cfg=shlex.quote(configure),
                             args=" ".join(shlex.quote(a) for a in args)),
                     env="conanbuild")
        # E236 guard: if the dependency .la directory leaked back into the
        # generated build system, name the file instead of letting libtool fail
        # on an //lib path three directories away from the real objects.
        makefile = os.path.join(self.build_folder, "Makefile")
        if os.path.isfile(makefile):
            leaked = load(self, makefile).count(ldap_src)
            if leaked:
                raise ConanException(
                    "E236 guard: {} still has {} hit(s) on the dependency .la "
                    "directory {}".format(makefile, leaked, ldap_src))
            self.output.info("E236 guard: 0 hits on {} in {}".format(
                ldap_src, makefile))
        # R9/-j1: OHOS make has no jobserver (mkfifo).  SHELL=<probed> is passed
        # down as insurance for rules config.status baked into the Makefiles.
        make_args = ["-j1"] if shell is None else ["-j1", "SHELL={}".format(shell)]
        autotools.make(args=make_args)
        # Upstream ships a C TAP harness suite (tests/runtests.c + 10 *-t.c
        # drivers + 17 entries in tests/TESTS; runtests expands those 17 files
        # into ~1250 TAP assertions).  Drivers are target binaries, so they need
        # the dependency shared libraries on LD_LIBRARY_PATH -- handled just below
        # by the inline prefix.  This block does NOT tolerate a missing run: a
        # runtests summary is required, while individual sets that are platform
        # limited are reported per item in notes.md (krb5-strength/3.3 precedent,
        # whose guard wording is conditional -- an unconditional swallow here would
        # also make the "compile failure still aborts" claim false).
        # E386 forbid_1: no blanket LOG_COMPILER shell dispatcher here, the
        # upstream suite has no suffixless shell drivers to route around.
        # Upstream tests must actually run (AGENTS 手册/04 §10: 0 执行不可交付).  The
        # C TAP drivers link against the Conan krb5/openldap shared libraries, and
        # the check recipe does not put those lib dirs on LD_LIBRARY_PATH, so the
        # bare "make check" died with rc=127 on "Error loading shared library
        # libgssapi_krb5.so.2".  Supply every requirement's libdir inline (never
        # os.environ / Environment().define -- E386 forbid_2: env="conanbuild"
        # re-exports the profile buildenv afterwards and would override it).
        libdirs = []
        for dep in self.dependencies.values():
            for d in dep.cpp_info.aggregated_components().libdirs:
                if d not in libdirs:
                    libdirs.append(d)
        check_log = os.path.join(self.build_folder, "make-check.log")
        rc = self.run('LD_LIBRARY_PATH="{ld}" make {args} check > {log} 2>&1'
                      .format(ld=":".join(libdirs),
                              args=" ".join(make_args),
                              log=shlex.quote(check_log)),
                      env="conanbuild", ignore_errors=True)
        summary = ""
        if os.path.isfile(check_log):
            for line in load(self, check_log).splitlines():
                if line.startswith("Aborted ") or line.startswith("Files="):
                    summary = line.strip()
                    break
        self.output.info("make check rc={}".format(rc))
        self.output.info("make check summary: {}".format(summary or "<none>"))
        # The guard is deliberately narrow: runtests must have loaded and walked its
        # TESTS list (that is what makes the declared numbers true).  Per-set
        # platform-limited outcomes are disclosed in notes.md item by item, not
        # swallowed here.
        if not summary:
            raise ConanException(
                "make check produced no runtests summary, so upstream tests would "
                "be declared without any execution (rc={}, log={})".format(rc, check_log))
        # Only now that the full pass has been proved to have walked its TESTS
        # list: recover the set that pass left un-executed because of residue.
        self._recover_queuing_residue(check_log, libdirs)

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        copy(self, "LICENSE", self.source_folder,
             os.path.join(self.package_folder, "licenses"))
        # Drop libtool wrappers so consumers never see them.
        for la in glob.glob(os.path.join(self.package_folder, "lib", "**", "*.la"),
                            recursive=True):
            os.remove(la)

    def package_info(self):
        # The deliverable is a dlopen'ed kadmin hook module (plugin/sync.la) plus
        # two command-line tools; no import library is exposed, so declaring
        # cpp_info.libs would make CMakeDeps look for a non-existent libsync.so
        # (digup/5.3.28 and krb5-strength/3.3 precedent for empty libs).
        self.cpp_info.libs = []
        # The upstream install set is one dlopen module plus two CLI tools: it
        # ships no public headers, so the package folder has no include/
        # directory.  Leaving the default includedirs makes the CMakeDeps config
        # point INTERFACE_INCLUDE_DIRECTORIES at a path that does not exist and
        # the test_package cmake configure aborts (G2 red).
        self.cpp_info.includedirs = []
        # R38: CLI tools are shipped, so the software-level commands.json is
        # mandatory and bindirs must be declared.
        # The Conan toolchain passes --sbindir=/bin, so upstream keeps
        # no sbin/: the two CLI tools really install into bin/ (verified against
        # the created package folder).  Declaring a phantom sbin/ dir and pointing
        # the runenv PATH at it made the test_package consumer look for
        # sbin/krb5-sync, which does not exist.
        self.cpp_info.bindirs = ["bin"]
        self.runenv_info.prepend_path("PATH",
                                      os.path.join(self.package_folder, "bin"))
