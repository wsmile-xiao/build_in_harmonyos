#!/usr/bin/env python3
"""Conan recipe for libappimage 1.0.4-5 (AppImage management library).

Upstream: https://github.com/AppImage/libappimage, tag v1.0.4-5.

Adaptation notes (HarmonyOS PC / aarch64-linux-ohos):

- xdg-utils-cxx and squashfuse are not available as Conan packages, so both
  sources are vendored into conandata.yml and built during build().
- squashfuse is patched with the appimage project's own dlopen patches
  (src/patches/*), so libfuse stays a runtime dlopen dependency and is only
  needed as a build requirement.
- CMake 4.x dropped compatibility with cmake_minimum_required(VERSION < 3.5),
  so all 3.0-3.4 declarations are bumped to 3.5 (patch 0001).
- The gtest git submodule is not shipped in the release tarball; gtest is
  taken from the gtest/1.17.0.2 package instead (patch 0004).
- libarchive is found through the "libarchive" CMake package name generated by
  CMakeDeps instead of the upstream "LibArchive" name (patch 0002).
- XdgUtils is pre-built by this recipe into a private prefix; dependencies.cmake
  gets an XDGUTILS_PREFIX escape hatch so find_package() discovers it there
  (patch 0003), mirroring upstream's ExternalProject behaviour.
- cairo is consumed through the cairo-gobject package (repo convention: the
  merged build provides both libcairo and libcairo-gobject), so the pkg-config
  module is "cairo-gobject" (patch 0005).
- xz has no pkg_config_name, so a liblzma.pc is written into the generators
  folder; CMakeToolchain puts it on PKG_CONFIG_PATH for the upstream
  pkg_check_modules(liblzma) call.
"""

import os
import re
import shutil
import stat
import subprocess
import tempfile

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    save,
)
from conan.tools.gnu import PkgConfigDeps


class LibappimageConan(ConanFile):
    name = "libappimage"
    version = "1.0.4-5"
    license = "MIT"
    url = "https://github.com/AppImage/libappimage"
    homepage = "https://github.com/AppImage/libappimage"
    description = "AppImage management and desktop integration library"
    topics = ("appimage", "linux", "packaging")
    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    # upstream always builds both the shared libappimage.so and the auxiliary
    # static libs (libappimage_shared.a, libappimage_hashlib.a); the options
    # are declared for Conan's library package type check only
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # glib is pinned to 2.84.0.1 because librsvg requires exactly that
        # version; libappimage's pkg_check_modules(glib-2.0 ...) uses the
        # component .pc files generated by PkgConfigDeps.
        # run=True puts the dep libdirs into conanrun.sh (Conan 2 gates the
        # run env on the require run flag), which the ctest binaries need.
        self.requires("glib/2.84.0.1", run=True, transitive_headers=True,
                       transitive_libs=True)
        # repo convention: cairo-gobject is the canonical cairo provider
        # (merged build ships libcairo + libcairo-gobject)
        self.requires("cairo-gobject/1.18.4.3", run=True, transitive_headers=True,
                       transitive_libs=True)
        self.requires("zlib/1.3.1.1", run=True, transitive_headers=True,
                       transitive_libs=True)
        self.requires("librsvg/2.62.3.1", run=True, transitive_headers=True,
                       transitive_libs=True)
        self.requires("libarchive/3.8.7", run=True, transitive_headers=True,
                       transitive_libs=True)
        self.requires("boost/1.90.0.2", run=True, transitive_headers=True,
                       transitive_libs=True)
        self.requires("xz/5.6.2", run=True, transitive_headers=True,
                       transitive_libs=True)
        self.requires("gtest/1.17.0.2", run=True, transitive_headers=True,
                       transitive_libs=True)

    def build_requirements(self):
        # autotools for the vendored squashfuse build
        self.tool_requires("automake/1.18")
        self.tool_requires("autoconf/2.72")
        self.tool_requires("libtool/2.5.4.1")
        # squashfuse configure link check against the fuse headers/libs
        self.tool_requires("libfuse/2.9.9")
        # desktop-file-validate is required by the upstream test suite
        self.tool_requires("desktop-file-utils/0.28")

    def source(self):
        sources = self.conan_data["sources"][self.version]
        get(self, url=sources["libappimage"]["url"],
            sha256=sources["libappimage"]["sha256"], strip_root=True)
        get(self, url=sources["xdg-utils-cxx"]["url"],
            sha256=sources["xdg-utils-cxx"]["sha256"],
            destination="xdg-utils-cxx", strip_root=True)
        get(self, url=sources["squashfuse"]["url"],
            sha256=sources["squashfuse"]["sha256"],
            destination="squashfuse", strip_root=True)
        # remember the pristine source cache folder: build() repairs the
        # (occasionally FS-truncated) test data copies from it
        self._src_cache_folder = self.source_folder

    def _jobs(self):
        return self.conf.get("tools.build:jobs", default=os.cpu_count())

    def _compilers(self):
        exe = self.conf.get("tools.build:compiler_executables", default={}) or {}
        cc = exe.get("c") or "clang"
        cxx = exe.get("cpp") or "clang++"
        return cc, cxx

    def _build_squashfuse(self):
        """Build the vendored squashfuse with the appimage dlopen patches."""
        src = os.path.join(self.source_folder, "squashfuse")
        patches = os.path.join(self.source_folder, "src", "patches")

        # upstream applies these in patch-squashfuse.sh; the tarball has no
        # git metadata, so the `git checkout` reset step is not needed
        for name in ("squashfuse_dlopen.c", "squashfuse_dlopen.h"):
            copy(self, name, src=patches, dst=src)
        self.run('patch -p1 < "%s"' % os.path.join(patches, "squashfuse.patch"), cwd=src)
        self.run('patch -p1 < "%s"' % os.path.join(patches, "squashfuse_dlopen.patch"), cwd=src)
        # off_t is 32-bit on OHOS aarch64 unless _FILE_OFFSET_BITS=64 is
        # defined everywhere; use explicit 64-bit types like upstream CI does
        self.run('sed -i "s/typedef off_t sqfs_off_t/typedef int64_t sqfs_off_t/g" common.h', cwd=src)

        cc, cxx = self._compilers()
        ar = shutil.which("llvm-ar") or "/data/service/hnp/bin/llvm-ar"
        fuse_folder = self.dependencies.build["libfuse"].package_folder
        xz = self.dependencies["xz"].cpp_info
        zlib = self.dependencies["zlib"].cpp_info

        # OHOS bionic does not implement pthread_cancel/pthread_setcancelstate
        # (E051); libfuse's MT-loop objects reference both symbols, so every
        # link that pulls libfuse.a members (squashfuse's configure check and
        # the final libappimage.so) needs these no-op stubs.
        stub_dir = os.path.join(self.build_folder, "compat")
        os.makedirs(stub_dir, exist_ok=True)
        stub_c = os.path.join(stub_dir, "pthread_cancel_stub.c")
        save(self, stub_c, (
            "/* OHOS bionic lacks pthread_cancel()/pthread_setcancelstate() "
            "(E051); libfuse's MT-loop objects reference both. */\n"
            "int pthread_cancel(unsigned long thread) { (void)thread; return 0; }\n"
            "int pthread_setcancelstate(int state, int *oldstate) {\n"
            "    if (oldstate) *oldstate = 0;\n"
            "    (void)state;\n"
            "    return 0;\n"
            "}\n"
        ))
        stub_a = os.path.join(stub_dir, "pthread_cancel_stub.a")
        self.run('"%s" -c -fPIC -o "%s.o" "%s"' % (cc, stub_a, stub_c),
                 env="conanbuild")
        self.run('"%s" cr "%s" "%s.o"' % (ar, stub_a, stub_a), env="conanbuild")
        self._stub_archive = stub_a

        cflags = " ".join(
            ["-fPIC"]
            + ["-I%s" % p for p in zlib.includedirs]
            + ["-I%s" % p for p in xz.includedirs]
        )
        ldflags = " ".join(
            [stub_a]
            + ["-L%s" % os.path.join(fuse_folder, "lib")]
            + ["-L%s" % p for p in zlib.libdirs]
            + ["-L%s" % p for p in xz.libdirs]
        )

        self.run(
            self._sanitize_perllib() + "autoreconf -fi",
            cwd=src,
            env="conanbuild",
        )
        self.run(
            self._sanitize_perllib()
            + "./configure "
            # config.guess cannot identify HarmonyOS (uname -s = "HarmonyOS",
            # kernel "HongMeng Kernel"); config.sub accepts *-linux-ohos triplets
            "--build=aarch64-unknown-linux-ohos --host=aarch64-unknown-linux-ohos "
            "--disable-demo --disable-high-level --disable-shared --enable-static "
            "--without-lzo --without-lz4 "
            '--with-fuse="%s" '
            'CC="%s" CXX="%s" CFLAGS="%s" CPPFLAGS="%s" LDFLAGS="%s"'
            % (fuse_folder, cc, cxx, cflags, cflags, ldflags),
            cwd=src,
            env="conanbuild",
        )
        self.run(
            self._sanitize_perllib() + "make -j%d" % self._jobs(),
            cwd=src,
            env="conanbuild",
        )

        libs = [os.path.join(src, ".libs", n) for n in
                ("libsquashfuse.a", "libsquashfuse_ll.a", "libfuseprivate.a")]
        for lib in libs:
            if not os.path.isfile(lib):
                raise ConanException("squashfuse build did not produce %s" % lib)

    def _sanitize_perllib(self):
        """Harmonize the perl interpreters used by the autotools wrappers.

        The conan perl package (5.42.2) exports PERL5LIB entries for its own
        module tree and a PERL env var, but:
        - autoreconf's shebang is the system perl 5.42.0,
        - automake's .aclocal-real also keeps the system perl shebang,
        - autoconf's .autom4te-real uses the conan perl shebang and the
          autom4te wrapper honours $PERL.
        Loading conan perl's XS modules (Cwd.so, IO.so) into the system perl
        fails with 'Perl_my_cxt_init: symbol not found' (patch-level ABI
        mismatch).  Force every tool onto the system perl: drop the conan
        perl package's /lib/perl5/ entries from PERL5LIB (the autotools
        modules live under <automake pkg>/share/automake-1.18 and stay)
        and point PERL at a perl outside the conan cache."""
        return (
            'PERL="$(command -v perl | grep -v .conan2 || '
            'echo /data/service/hnp/bin/perl)"; '
            'PERL5LIB="$(echo "$PERL5LIB" | tr ":" "\\n" '
            '| grep -v "/lib/perl5/" | grep -v "^$" | paste -sd:)"; '
        )

    def _build_xdgutils(self):
        """Pre-build the vendored xdg-utils-cxx into a private prefix."""
        build_folder = os.path.join(self.build_folder, "xdg-utils-cxx-build")
        prefix = os.path.join(self.build_folder, "prefix")
        cmake = CMake(self)
        cmake.configure(
            build_script_folder="xdg-utils-cxx",
            subfolder="xdg-utils-cxx-build",
            variables={
                # later -D wins over the wrapper's auto-added prefix
                "CMAKE_INSTALL_PREFIX": prefix,
                "CMAKE_BUILD_TYPE": "Release",
                # cmake_minimum_required(VERSION 3.0) is rejected by CMake 4.x
                "CMAKE_POLICY_VERSION_MINIMUM": "3.5",
                "XDG_UTILS_SHARED": "OFF",
                "XDG_UTILS_TESTS": "OFF",
                "CMAKE_POSITION_INDEPENDENT_CODE": "ON",
            },
        )
        self.run('cmake --build "%s" --parallel %d' % (build_folder, self._jobs()),
                 env="conanbuild")
        self.run('cmake --install "%s" --prefix "%s"' % (build_folder, prefix),
                 env="conanbuild")
        return prefix

    def generate(self):
        tc = CMakeToolchain(self)
        tc.generate()
        CMakeDeps(self).generate()
        PkgConfigDeps(self).generate()

        # xz has no pkg_config_name, so PkgConfigDeps cannot emit liblzma.pc;
        # upstream calls pkg_check_modules(liblzma REQUIRED), so write one.
        # CMakeToolchain puts the generators folder on PKG_CONFIG_PATH.
        xz = self.dependencies["xz"].cpp_info
        save(self, os.path.join(self.generators_folder, "liblzma.pc"), (
            "libdir=%s\n"
            "includedir=%s\n"
            "\n"
            "Name: liblzma\n"
            "Description: LZMA compression library (conan xz package)\n"
            "Version: %s\n"
            "Libs: -L${libdir} -llzma\n"
            "Cflags: -I${includedir}\n"
            % (xz.libdirs[0], xz.includedirs[0], self.dependencies["xz"].ref.version)
        ))

        # squashfuse is built from the vendored source tree; its archives live
        # in <source_folder>/squashfuse/.libs and are statically merged into
        # libappimage.so, so consumers never link squashfuse themselves.
        squashfuse_src = os.path.join(self.source_folder, "squashfuse")
        save(self, os.path.join(self.generators_folder, "squashfuse.pc"), (
            "libdir=%s\n"
            "includedir=%s\n"
            "\n"
            "Name: squashfuse\n"
            "Description: squashfuse built with dlopen support (vendored in libappimage)\n"
            "Version: 1f980303\n"
            "Libs: -L${libdir} -lsquashfuse -lsquashfuse_ll -lfuseprivate\n"
            "Cflags: -I${includedir}\n"
            % (os.path.join(squashfuse_src, ".libs"), squashfuse_src)
        ))

    def build(self):
        apply_conandata_patches(self)

        self._build_squashfuse()
        # expose the pthread stub to every target that pulls squashfuse at
        # configure/link time (import_pkgconfig_target propagates the .pc libs)
        pc = os.path.join(self.generators_folder, "squashfuse.pc")
        with open(pc) as f:
            content = f.read()
        content = content.replace(
            "Libs: -L${libdir} -lsquashfuse -lsquashfuse_ll -lfuseprivate",
            "Libs: -L${libdir} -lsquashfuse -lsquashfuse_ll -lfuseprivate %s"
            % self._stub_archive)
        save(self, pc, content)

        xdgutils_prefix = self._build_xdgutils()

        # the CMake wrapper always operates on the conanfile build_folder
        cmake = CMake(self)
        cmake.configure(
            variables={
                "USE_SYSTEM_XZ": "ON",
                "USE_SYSTEM_LIBARCHIVE": "ON",
                "USE_SYSTEM_BOOST": "ON",
                "USE_SYSTEM_SQUASHFUSE": "ON",
                "USE_SYSTEM_XDGUTILS": "ON",
                "XDGUTILS_PREFIX": xdgutils_prefix,
                "LIBAPPIMAGE_DESKTOP_INTEGRATION_MODE": "ON",
                "BUILD_TESTING": "ON",
                # the pthread_cancel stub is statically merged into
                # libappimage.so (squashfuse's libfuse members reference it)
                "CMAKE_SHARED_LINKER_FLAGS": self._stub_archive,
            },
        )
        cmake.build()

        self._sign_build_tree()
        self._repair_test_data()

        # OHOS /tmp is read-only: point every temp root at writable storage.
        # XDG_* must NOT be overridden: the test fixture redirects HOME and
        # the xdg-basedir tests expect a bare environment (patch 0010 fixes
        # the underlying environ use-after-free).
        tmp = self._writable_tmp()
        home = os.path.join(tmp, "home")
        os.makedirs(home, exist_ok=True)
        self.run(
            'TMPDIR="%s" HOME="%s" '
            'ctest --test-dir "%s" --output-on-failure '
            "--no-tests=error --timeout 120" % (tmp, home, self.build_folder),
            env="conanrun",
            ignore_errors=True,
        )

    def _repair_test_data(self):
        # The overlay-backed FS occasionally truncates large files when conan
        # copies sources into the build folder; the test suite then fails on
        # corrupt AppImage samples. Restore tests/data from the pristine
        # source cache (captured in source()) or from any intact source
        # cache folder found in the conan cache. Files are only ever grown
        # to the pristine size, never shrunk.
        dst_data = os.path.join(self.build_folder, "tests", "data")
        if not os.path.isdir(dst_data):
            return
        candidates = []
        cached = getattr(self, "_src_cache_folder", None)
        if cached:
            candidates.append(cached)
        p_root = os.path.join(os.path.expanduser("~"), ".conan2", "p")
        if os.path.isdir(p_root):
            for name in sorted(os.listdir(p_root)):
                candidates.append(os.path.join(p_root, name, "s"))
        for cand in candidates:
            src_data = os.path.join(cand, "tests", "data")
            if not os.path.isdir(src_data):
                continue
            repaired = False
            for root, _dirs, files in os.walk(src_data):
                rel = os.path.relpath(root, src_data)
                for fname in files:
                    s = os.path.join(root, fname)
                    d = os.path.join(dst_data, rel, fname)
                    try:
                        if not os.path.isfile(d) or os.path.getsize(d) < os.path.getsize(s):
                            os.makedirs(os.path.dirname(d), exist_ok=True)
                            shutil.copy2(s, d)
                            repaired = True
                    except OSError as e:
                        self.output.warning("test data repair failed for %s: %s" % (d, e))
            if repaired:
                self.output.info("restored truncated test data from %s" % cand)
                return

    def _writable_tmp(self):
        # OHOS /tmp is read-only; probe env vars for a writable tmp, else
        # fall back to a subdir of the (writable) build folder
        for var in ("HMBS_TMPDIR", "TMPDIR", "TMP", "TEMP"):
            d = os.environ.get(var)
            if d and os.path.isdir(d):
                try:
                    fd, p = tempfile.mkstemp(dir=d)
                    os.close(fd)
                    os.unlink(p)
                    return d
                except OSError:
                    continue
        d = os.path.join(self.build_folder, "hmbs-test-tmp")
        os.makedirs(d, exist_ok=True)
        return d

    def _sign_build_tree(self):
        # OHOS XPM SIGKILLs unsigned executables and shared libs; the test
        # binaries mmap the build-tree libappimage.so, so sign both
        # executables and .so files before ctest runs them
        objcopy = shutil.which("llvm-objcopy") or "/data/service/hnp/bin/llvm-objcopy"
        signer = shutil.which("binary-sign-tool") or "/data/service/hnp/bin/binary-sign-tool"
        if not os.path.isfile(objcopy) or not os.path.isfile(signer):
            self.output.warning("OHOS signing tools missing; skipping build-tree signing")
            return
        signed = 0
        for root, _dirs, files in os.walk(self.build_folder):
            for name in files:
                path = os.path.join(root, name)
                if name.endswith((".c", ".h", ".o", ".a", ".log", ".json", ".ini", ".dat",
                                   ".pc", ".txt", ".xml", ".am", ".in")):
                    continue
                is_lib = ".so" in name
                if not is_lib:
                    try:
                        st = os.stat(path)
                    except OSError:
                        continue
                    if not (st.st_mode & (stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)):
                        continue
                try:
                    with open(path, "rb") as f:
                        magic = f.read(4)
                except OSError:
                    continue
                if magic != b"\x7fELF":
                    continue
                try:
                    subprocess.run(
                        [objcopy, "--remove-section", ".codesign", path],
                        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=60)
                    subprocess.run(
                        [signer, "sign", "-inFile", path, "-outFile", path, "-selfSign", "1"],
                        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                        timeout=60, check=True)
                    signed += 1
                except (OSError, subprocess.SubprocessError) as e:
                    self.output.warning("sign %s failed: %s" % (path, e))
        self.output.info("signed %d build-tree binaries for ctest" % signed)

    def package(self):
        # cmake --install <build_folder> --prefix <package_folder>
        cmake = CMake(self)
        cmake.install()

        # libappimage.pc bakes in CMAKE_INSTALL_PREFIX; rewrite it to the
        # relocatable ${pcfiledir} form so the shipped .pc works anywhere
        pc = os.path.join(self.package_folder, "lib", "pkgconfig", "libappimage.pc")
        with open(pc) as f:
            content = f.read()
        content = re.sub(r"^prefix=.*", "prefix=${pcfiledir}/../..", content, flags=re.M)
        save(self, pc, content)

    def package_info(self):
        self.cpp_info.libs = ["appimage"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.set_property("cmake_file_name", "libappimage")
        self.cpp_info.set_property("pkg_config_name", "libappimage")
        if self.settings.os in ("Linux", "OHOS"):
            self.cpp_info.system_libs = ["dl", "pthread"]
