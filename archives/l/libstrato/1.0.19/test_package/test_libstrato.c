static const uint8_t GARBAGE[] = { 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07 };

static int failures;

static void
check(int cond, const char *msg)
{
	if (cond) {
		printf("ok   - %s\n", msg);
	} else {
		printf("FAIL - %s\n", msg);
		failures++;
	}
}

/* 统一的“解码出 2x2 并安全回收”检查 */
static void
check_decode(const char *what, int ok, struct hal_image *img)
{
	char buf[128];

	snprintf(buf, sizeof(buf), "%s 入口解码 2x2 图像成功", what);
	check(ok != 0, buf);
	if (ok == 0 || img == NULL) {
		check(0, "     （解码失败，尺寸断言无法进行）");
		return;
	}
	snprintf(buf, sizeof(buf), "%s 解码宽度 == 2", what);
	check(img->width == 2, buf);
	snprintf(buf, sizeof(buf), "%s 解码高度 == 2", what);
	check(img->height == 2, buf);
	snprintf(buf, sizeof(buf), "%s 解码像素缓冲非空", what);
	check(img->pixels != NULL, buf);
	hal_destroy_image(img);
}

int
main(void)
{
	struct hal_image *img;
	hal_pixel_t *pixels;
	int i, n, ok;

	/* ── 1. 像素缓冲路径：建立 / 清除 / 读回 ── */
	img = NULL;
	check(hal_create_image(3, 2, &img) == true, "hal_create_image(3,2) 返回 true");
	check(img != NULL, "hal_create_image 写出非空句柄");
	check(img->width == 3, "图像宽度 == 3");
	check(img->height == 2, "图像高度 == 2");

	pixels = img->pixels;
	check(pixels != NULL, "图像像素缓冲非空");

	hal_clear_image(img, (hal_pixel_t)0xFF112233u);
	n = 0;
	for (i = 0; i < 3 * 2; i++) {
		if (pixels[i] == (hal_pixel_t)0xFF112233u)
			n++;
	}
	check(n == 6, "hal_clear_image 后 6 个像素值 32 位往返一致");
	hal_destroy_image(img);

	/* ── 2. 三种真实解码格式 ── */
	img = NULL;
	ok = hal_create_image_with_png(TEST_PNG, sizeof(TEST_PNG), &img);
	check_decode("PNG", ok, img);

	img = NULL;
	ok = hal_create_image_with_jpeg(TEST_JPEG, sizeof(TEST_JPEG), &img);
	check_decode("JPEG", ok, img);

	img = NULL;
	ok = hal_create_image_with_webp(TEST_WEBP, sizeof(TEST_WEBP), &img);
	check_decode("WebP", ok, img);

	/* PNG 是无损路径，可做像素级精确断言（全白不透明） */
	img = NULL;
	if (hal_create_image_with_png(TEST_PNG, sizeof(TEST_PNG), &img) == true && img != NULL) {
		pixels = img->pixels;
		check(pixels != NULL && pixels[0] == (hal_pixel_t)0xFFFFFFFFu,
		      "PNG 首像素为不透明白 0xFFFFFFFF");
		hal_destroy_image(img);
	} else {
		check(0, "PNG 像素级断言前置解码失败");
	}

	/* ── 3. 畸形输入的安全失败路径 ── */
	img = NULL;
	check(hal_create_image_with_png(GARBAGE, sizeof(GARBAGE), &img) == false,
	      "畸形数据经 PNG 入口返回 false");
	check(img == NULL, "PNG 失败后句柄保持 NULL");

	img = NULL;
	check(hal_create_image_with_webp(GARBAGE, sizeof(GARBAGE), &img) == false,
	      "畸形数据经 WebP 入口返回 false");

	if (failures == 0) {
		printf("# ALL PASS\n");
	} else {
		printf("# FAILURES: %d\n", failures);
	}
	return failures == 0 ? 0 : 1;
}
