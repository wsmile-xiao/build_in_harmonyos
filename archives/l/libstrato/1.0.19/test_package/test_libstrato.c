/*
 * libstrato 1.0.19 — 消费者测试（L1：以库使用者身份编译 / 链接 / 调用公开 API）
 *
 * 断言对象是公开头文件 <strato/strato.h> 的 API 语义，覆盖四条真实调用路径：
 *   1) 像素缓冲路径：hal_create_image / hal_clear_image + struct hal_image 的
 *      公开成员 width / height / pixels
 *      （写入值与读回值做 32 位往返比对，与像素字节序无关）
 *   2) PNG 解码：hal_create_image_with_png（经 libpng）
 *   3) JPEG 解码：hal_create_image_with_jpeg（经 libjpeg-turbo）
 *   4) WebP 解码：hal_create_image_with_webp（经 libwebp）
 * 外加畸形输入的安全失败断言（PNG / WebP 入口）。
 *
 * 说明一：头文件声明的 hal_get_image_width / hal_get_image_height /
 * hal_get_image_pixels 在 tag v1.0.19 全源码树中**没有实现**（无定义符号），
 * 链接会报 undefined symbol ⇒ 消费者须直接读 struct hal_image 的公开成员
 * width / height / pixels（头文件已标注这三个成员为 public）。
 *
 * 说明二：JPEG 入口未做畸形输入断言——上游该函数把 libjpeg 的默认错误处理器
 * 装上以后直接 jpeg_read_header()，畸形输入会走 libjpeg 的 error_exit() 终止
 * 进程，属上游既有行为，不在本消费者测试的断言范围内（见 notes.md）。
 *
 * 测试向量：2x2 全白 PNG（无损，像素可精确断言）/ 2x2 全白 baseline JPEG /
 * 2x2 无损 WebP，均由 Pillow 生成后内嵌，无外部文件依赖。
 */
