#!/usr/bin/env python3
"""Conan recipe for libsvgtiny 0.1.8 (SVG Tiny 1.1 renderer, NetSurf project).

libsvgtiny 是 NetSurf 的 SVG Tiny 1.1 解析/渲染库。上游使用 NetSurf 自有构建
系统（Makefile include $(NSSHARED)/makefiles/Makefile.tools），本平台无
netsurf-buildsystem 包。补丁 0001-Makefile.patch 将顶层 Makefile 替换为
standalone Makefile（保留原编译标志、去除 -Werror 以兼容 clang 15，
与 libparserutils / libwapcaplet / libhubbub / libdom 历史适配一致）。

颜色查找表：上游由 gperf 从 src/colors.gperf 生成 src/autogenerated_colors.c
（svgtiny.c 以 #include 方式引入）。本平台构建 worker 不保证有 gperf host
工具，补丁 0002 预生成了同内容、同 static 变换的 autogenerated_colors.c；
Makefile 中保留 gperf 规则作为可选路径（gperf 可用时优先重新生成）。

构建：make && make install PREFIX=<package_folder>
依赖：libdom（DOM 解析，XML binding 提供 dom_xml_parser_*）、libwapcaplet
      （lwc_intern_string/lwc_string_unref 字符串驻留）。libsvgtiny.a 引用
      dom_* 与 lwc_* 符号，链接闭包由 cpp_info.requires 传递。
测试：上游 test/ 为 decode_svg.c + runtest.sh 驱动 test/data/*.svg（12）与
      test/ns-afl-svg/*.svg（2612）合计 2624 个 SVG。build() 内编译未修改的
      上游 harness 并用上游 runtest.sh 全量实跑（语料随官方 tarball 提供，
      非额外 vendor）；test_package 再以消费者视角 svgtiny_create/parse/free
      解析真实 SVG 并断言 shape 输出。
"""
from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout

import os
import re

# 上游 test/runtest.sh 覆盖的用例总数：test/data/*.svg (12) + test/ns-afl-svg/*.svg (2612)
UPSTREAM_TEST_TOTAL = 2624


class LibsvgtinyConan(ConanFile):
    name = "libsvgtiny"
    version = "0.1.8"
    description = "SVG Tiny 1.1 renderer (NetSurf project)"
    license = "MIT"
    homepage = "https://www.netsurf-browser.org/projects/libsvgtiny/"
    url = ""  # CI fills this

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("libdom/0.4.2")
        self.requires("libwapcaplet/0.4.3.1")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("libsvgtiny is supported only on Linux/OHOS")
        if self.settings.arch != "armv8" and self.settings.os == "OHOS":
            raise ConanInvalidConfiguration("OHOS builds require armv8/aarch64")

    def layout(self):
        basic_layout(self)
        # standalone Makefile builds in-source (objects next to sources)
        self.folders.build = "."

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)

        # E120: OHOS SDK lld links libxml2.so.16; inject its lib dir into
        # LD_LIBRARY_PATH so the linker runs on CI workers where the SDK
        # lib path is not on the default loader search path.
        llvm_lib = "/data/service/hnp/ohos-sdk.org/ohos-sdk_26.0.0.18/ohos/native/llvm/lib"
        if os.path.isdir(llvm_lib):
            os.environ["LD_LIBRARY_PATH"] = llvm_lib + ":" + os.environ.get("LD_LIBRARY_PATH", "")

        # R33: Get compiler/linker from Conan conf, never from shell env vars
        compilers = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict)
        cc = compilers.get("c", "clang") if compilers else "clang"
        ar = compilers.get("ar", "llvm-ar") if compilers else "llvm-ar"
        ranlib = compilers.get("ranlib", "llvm-ranlib") if compilers else "llvm-ranlib"

        # Dependency flags from cpp_info (headers at compile time).
        # svgtiny.c uses dom types + lwc_string, so both include dirs are needed.
        def dep_cflags(dep_name):
            dep = self.dependencies[dep_name]
            return " ".join(f"-I{d}" for d in dep.cpp_info.includedirs) if dep.cpp_info.includedirs else ""

        # R9: -j1 (HMDFS 上 make -j>1 jobserver mkfifo 报 EPERM, E074)
        self.run(
            f"make CC={cc} AR={ar} RANLIB={ranlib} "
            f"DOM_CFLAGS='{dep_cflags('libdom')}' "
            f"WAPCAPLET_CFLAGS='{dep_cflags('libwapcaplet')}' -j1"
        )

        self._run_upstream_tests(cc, dep_cflags)

    def _run_upstream_tests(self, cc, dep_cflags):
        """实跑上游全量测试（rule4「上游测试用例实跑」）。

        上游 test/runtest.sh 用 test_decode_svg 逐个解码 test/data/*.svg（12）
        与 test/ns-afl-svg/*.svg（2612），合计 2624 例。判据为逐例退出码
        （0 通过；1..127 失败；>127 错误），任一失败 runtest.sh 即以非零退出。
        2612 个 AFL fuzz 语料随官方源码 tarball 一同提供，无需另行 vendor。

        防「空转假绿」：glob 未命中时 runtest.sh 会以 Tests:0 正常退出 0，故
        这里额外校验汇总行必须是 2624/2624，否则显式失败。
        """
        # 收集全部（含传递）host 依赖的库搜索路径与库名，供 vendored 上游
        # harness 链接静态 libsvgtiny.a 的完整闭包（libdom / libparserutils /
        # libhubbub / libwapcaplet / libxml2 ...）。
        libdirs, libs, syslibs = [], [], []
        for dep in self.dependencies.host.values():
            cpp = dep.cpp_info.aggregated_components()
            for d in cpp.libdirs:
                if d and d not in libdirs:
                    libdirs.append(d)
            for lib in cpp.libs:
                if lib and lib not in libs:
                    libs.append(lib)
            for s in cpp.system_libs:
                if s and s not in syslibs:
                    syslibs.append(s)

        # 依赖闭包里可能有 shared 库（如 libxml2）；harness 运行时需要能在
        # 依赖的 lib 目录中找到它们（build() 只有 conanbuild 无 conanrun）。
        os.environ["LD_LIBRARY_PATH"] = ":".join(
            libdirs + [os.environ.get("LD_LIBRARY_PATH", "")]
        )

        link_flags = " ".join(
            [f"-L{d}" for d in libdirs]
            + ["-Wl,--start-group"]
            + [f"-l{lib}" for lib in libs]
            + ["-Wl,--end-group"]
            + [f"-l{s}" for s in syslibs]
        )

        # 编译未修改的上游 harness（test/decode_svg.c）。include/svgtiny.h
        # 无任何 #include，故只需 -Iinclude。
        self.run(
            f"{cc} -D_BSD_SOURCE -D_DEFAULT_SOURCE -std=c99 -Iinclude "
            f"{dep_cflags('libdom')} -o test_decode_svg "
            f"test/decode_svg.c libsvgtiny.a {link_flags}"
        )

        # 上游驱动脚本。TEST_PATH=. 时它调用 ./test_decode_svg，输出 mvg/ 与
        # test.log 于源码树内；stdout 仅有汇总行。
        self.run(
            "sh test/runtest.sh . > runtest.out 2>&1; rc=$?; "
            "cat runtest.out; exit $rc"
        )

        with open(os.path.join(self.build_folder, "runtest.out"),
                  encoding="utf-8", errors="replace") as fh:
            summary = fh.read()
        match = re.search(r"Tests:(\d+) Pass:(\d+) Fail:(\d+) Error:(\d+)", summary)
        if not match:
            raise ConanException(
                "upstream test/runtest.sh printed no summary line: "
                f"{summary.strip()!r}"
            )
        total, passed, failed, errored = (int(g) for g in match.groups())
        if total != UPSTREAM_TEST_TOTAL or passed != total or failed or errored:
            raise ConanException(
                "upstream test/runtest.sh did not run the full suite: "
                f"Tests:{total} Pass:{passed} Fail:{failed} Error:{errored} "
                f"(expected {UPSTREAM_TEST_TOTAL}/{UPSTREAM_TEST_TOTAL})"
            )
        self.output.info(
            f"upstream test/runtest.sh: Tests:{total} Pass:{passed} "
            f"Fail:{failed} Error:{errored}"
        )

    def package(self):
        # The standalone Makefile install target honours PREFIX/DESTDIR
        self.run(f"make install PREFIX={self.package_folder}")

    def package_info(self):
        self.cpp_info.libs = ["svgtiny"]
        # libsvgtiny.a references dom_* and lwc_* symbols; libdom's own
        # cpp_info.requires brings libparserutils/libhubbub/libwapcaplet
        # (and the XML binding backend) transitively.
        self.cpp_info.requires = [
            "libdom::libdom",
            "libwapcaplet::libwapcaplet",
        ]
        self.cpp_info.set_property("cmake_file_name", "LibSvgTiny")
        self.cpp_info.set_property("cmake_target_name", "LibSvgTiny::svgtiny")
        self.cpp_info.set_property("pkg_config_name", "libsvgtiny")
