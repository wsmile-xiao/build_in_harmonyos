#!/usr/bin/env python3
"""Conan recipe for libxdf — C++ library for loading XDF files (multimodal, multi-rate signals).

Upstream build system: CMake.
Consumes the platform-provided pugixml instead of the vendored copy
(see patches/, generated by refresh-patch --auto).
"""
import os

from conan import ConanFile
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get


class LibxdfConan(ConanFile):
    name = "libxdf"
    version = "0.99.10"
    description = ("C++ library for loading multimodal, multi-rate signals "
                   "stored in XDF files (Lab Streaming Layer / SigViewer format)")
    license = "BSD-2-Clause"
    homepage = "https://github.com/Yida-Lin/libxdf"
    url = "https://github.com/Yida-Lin/libxdf"

    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def requirements(self):
        # libxdf needs pugixml >= 1.9 for XML parsing; CMakeLists is patched so the
        # Conan-provided target is used instead of the vendored copy.
        self.requires("pugixml/1.16")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        deps = CMakeDeps(self)
        deps.generate()
        tc = CMakeToolchain(self)
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        copy(self, "LICENSE.txt", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.libs = ["xdf"]
        self.cpp_info.set_property("cmake_file_name", "libxdf")
        self.cpp_info.set_property("cmake_target_name", "libxdf::libxdf")
