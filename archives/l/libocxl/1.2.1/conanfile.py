#!/usr/bin/env python3
"""Conan recipe for libocxl 1.2.1 - userspace driver library for OpenCAPI accelerators.

libocxl opens an OpenCAPI AFU (``/dev/ocxl/...``), attaches a context, maps its
MMIO regions, allocates IRQs and reads/writes the AFU MMIO space.

OHOS notes
----------
* The upstream tree ships only a hand written Makefile.  The library is compiled
  directly, keeping the upstream flags (``-I src/include -I kernel/include
  -fPIC -D_FILE_OFFSET_BITS=64``); upstream does not use autotools.
* The Makefile downloads the kernel uapi header ``misc/ocxl.h`` with wget/curl
  at build time.  The recipe fetches a pinned copy (Linux v6.12) in ``source()``
  instead, so the build is reproducible and offline.
* ``src/libocxl_info.h`` is generated by ``version.pl`` (perl); the recipe runs
  it with the package version.
* Upstream unittests need FUSE (``unittests/virtocxl.c`` emulates an OCXL device
  through a FUSE filesystem), which OHOS user space does not provide.  The
  consumer test therefore covers the hardware independent API: errno strings,
  the info string, and the failed-open paths.
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import copy, download, get
from conan.tools.layout import basic_layout

required_conan_version = ">=2.0"

_SOURCES = ("afu", "internal", "irq", "mmio", "setup")
_VERSION = (1, 2, 1)


class LibocxlConan(ConanFile):
    name = "libocxl"
    version = "1.2.1"
    description = ("Userspace driver library for OpenCAPI accelerators: AFU open/"
                   "attach, MMIO map, IRQ allocation and AFU MMIO access")
    license = "Apache-2.0"
    homepage = "https://github.com/OpenPOWERFoundation/libocxl"
    url = ""

    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "libocxl OHOS adaptation is validated on Linux/OHOS, not "
                + str(self.settings.os))

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        # The uapi header is a plain file; download() avoids get()'s archive
        # handling, then move it into the Makefile's expected location.
        uapi = self.conan_data["ocxl_uapi"]
        download(self, uapi["url"], "ocxl.h", sha256=uapi["sha256"])
        dest = os.path.join(self.source_folder, "kernel", "include", "misc")
        os.makedirs(dest, exist_ok=True)
        os.replace(os.path.join(self.source_folder, "ocxl.h"),
                   os.path.join(dest, "ocxl.h"))

    def _compiler(self, name, fallback):
        executables = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict) or {}
        return executables.get(name) or fallback

    def build(self):
        cc = self._compiler("c", "clang")
        major, minor, patch = _VERSION

        # src/libocxl_info.h is generated by version.pl (perl).
        self.run('VERSION_MAJOR={} VERSION_MINOR={} VERSION_PATCH={} CC="{}" '
                 'CFLAGS="-O2 -std=c11 -fPIC" perl ./version.pl > src/libocxl_info.h'.format(
                     major, minor, patch, cc),
                 cwd=self.source_folder)

        objects = []
        for name in _SOURCES:
            obj = os.path.join(self.build_folder, name + ".o")
            self.run('"{}" -O2 -std=c11 -fPIC -D_FILE_OFFSET_BITS=64 '
                     '-DLIBOCXL_SUPPRESS_INACCESSIBLE_WARNINGS -I"{}" -I"{}" -c "{}" -o "{}"'.format(
                         cc,
                         os.path.join(self.source_folder, "src", "include"),
                         os.path.join(self.source_folder, "kernel", "include"),
                         os.path.join(self.source_folder, "src", name + ".c"), obj))
            objects.append(obj)

        quoted = " ".join('"{}"'.format(o) for o in objects)
        if self.options.shared:
            library = os.path.join(self.build_folder, "libocxl.so")
            # No -soname: this keeps NEEDED as "libocxl.so" so the loader finds
            # the file shipped in lib/ (a soname libocxl.so.1 would need an
            # extra versioned file+symlink).
            self.run('"{}" -shared -fPIC '
                     '-Wl,--version-script,"{}" -o "{}" {}'.format(
                         cc, os.path.join(self.source_folder, "symver.map"),
                         library, quoted))
        else:
            library = os.path.join(self.build_folder, "libocxl.a")
            self.run('llvm-ar rcs "{}" {}'.format(library, quoted))

    def package(self):
        copy(self, "libocxl.h", src=os.path.join(self.source_folder, "src", "include"),
             dst=os.path.join(self.package_folder, "include"))
        lib_dir = os.path.join(self.package_folder, "lib")
        if self.options.shared:
            copy(self, "libocxl.so", src=self.build_folder, dst=lib_dir)
        else:
            copy(self, "libocxl.a", src=self.build_folder, dst=lib_dir)
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"), keep_path=False)

    def package_info(self):
        self.cpp_info.libs = ["ocxl"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.set_property("cmake_file_name", "ocxl")
        self.cpp_info.set_property("cmake_target_name", "ocxl::ocxl")
