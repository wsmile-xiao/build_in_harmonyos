/*
 * lcmaps 1.6.7 test_package — OHOS (aarch64/musl) consumer smoke test.
 *
 * Verifies the packaged without-GSI artifacts and exercises the platform
 * adaptation points introduced by this port:
 *
 *  1. musl dynamic loading (OHOS adaptation, knowledge E013): the dl* API is
 *     provided by libc; dlopen/dlsym/dlclose must work on the packaged
 *     liblcmaps_without_gsi.so — this is the consumption mode used by the
 *     LCMAPS framework (dlsym of plugin entry points) and downstream clients.
 *  2. Installed header surface: <lcmaps/lcmaps_version.h> exposes the
 *     LCMAPS_API_{MAJOR,MINOR,PATCH}_VERSION macros generated by configure.
 *  3. Packaged metadata: lib/pkgconfig/lcmaps-basic-interface.pc (the
 *     headers-only interface consumed downstream via pkg-config) and
 *     lib/pkgconfig/lcmaps-without-gsi.pc (the link interface).
 *
 * Usage: test_lcmaps <package_root>
 */
#include <dlfcn.h>
#include <stdio.h>
#include <string.h>
#include <sys/stat.h>

#include <lcmaps/lcmaps_version.h>

static int check_file(const char *root, const char *rel, const char *what)
{
	char buf[1024];
	struct stat st;
	int ok;

	snprintf(buf, sizeof(buf), "%s/%s", root, rel);
	ok = stat(buf, &st) == 0;
	printf("%s: %s (%s)\n", ok ? "PASS" : "FAIL", what, buf);
	return ok ? 0 : 1;
}

static int try_dlsym(void *handle, const char *name)
{
	void *sym;

	dlerror(); /* clear pending error */
	sym = dlsym(handle, name);
	if (sym == NULL) {
		const char *err = dlerror();
		printf("FAIL: dlsym(%s): %s\n", name,
		       err ? err : "symbol is NULL");
		return 1;
	}
	printf("PASS: dlsym(%s) -> %p\n", name, sym);
	return 0;
}

int main(int argc, char *argv[])
{
	const char *root;
	char lib[1024];
	void *handle;
	int rc = 0;

	if (argc < 2) {
		fprintf(stderr, "usage: test_lcmaps <package_root>\n");
		return 2;
	}
	root = argv[1];

	/* 1. compile-time: installed generated version header */
	if (LCMAPS_API_MAJOR_VERSION != 1) {
		printf("FAIL: unexpected LCMAPS API major version %d\n",
		       LCMAPS_API_MAJOR_VERSION);
		return 1;
	}
	printf("PASS: lcmaps API version macros: %d.%d.%d\n",
	       LCMAPS_API_MAJOR_VERSION, LCMAPS_API_MINOR_VERSION,
	       LCMAPS_API_PATCH_VERSION);

	/* 2. packaged artifact manifest */
	rc |= check_file(root, "include/lcmaps/lcmaps.h",
			 "core API header");
	rc |= check_file(root, "include/lcmaps/lcmaps_modules.h",
			 "plugin API header");
	rc |= check_file(root, "include/lcmaps/lcmaps_version.h",
			 "generated version header");
	rc |= check_file(root, "lib/liblcmaps_without_gsi.so",
			 "without-GSI core shared library");
	rc |= check_file(root, "lib/pkgconfig/lcmaps-basic-interface.pc",
			 "basic interface pkg-config metadata");
	rc |= check_file(root, "lib/pkgconfig/lcmaps-without-gsi.pc",
			 "without-GSI pkg-config metadata");

	/* 3. runtime: musl dlopen + dlsym of the framework entry points */
	snprintf(lib, sizeof(lib), "%s/lib/liblcmaps_without_gsi.so", root);
	handle = dlopen(lib, RTLD_NOW | RTLD_LOCAL);
	if (handle == NULL) {
		const char *err = dlerror();
		if (err && strstr(err, "Permission denied")) {
			/* OHOS HMDFS refuses unsigned ELF (E046): platform
			 * limitation, not a packaging failure. */
			printf("SKIP: dlopen %s — unsigned ELF (%s)\n", lib,
			       err);
			return rc;
		}
		printf("FAIL: dlopen %s: %s\n", lib, err ? err : "?");
		return 1;
	}
	printf("PASS: dlopen %s\n", lib);
	rc |= try_dlsym(handle, "lcmaps_init");
	/* without-GSI flavour: the credential-free run entry replaces the
	 * GSI-mode lcmaps_run() */
	rc |= try_dlsym(handle,
			"lcmaps_run_without_credentials_and_return_username");
	rc |= try_dlsym(handle, "lcmaps_term");
	dlclose(handle);

	if (rc == 0)
		printf("All lcmaps smoke tests PASSED\n");
	else
		printf("lcmaps smoke tests FAILED (%d)\n", rc);
	return rc;
}
