#!/usr/bin/env python3
"""Conan recipe — letta-code 0.28.17 (npm prebuilt CLI).

Packages the prebuilt Letta Code CLI (@letta-ai/letta-code), a bun-bundled
single-file Node application (letta.js) plus its bundled vendor/skills/docs
assets. The bundle statically imports the bare ``ws`` module, which is the
only non-builtin bare import; it is vendored into ``node_modules/ws`` so the
CLI runs without a network install.

Runtime launch (see notes.md, "问题 1"):

* A foreign ``LD_LIBRARY_PATH`` leaking from the host toolchain is removed with
  ``env -u`` before node is started. The shell builtin ``unset`` is *not*
  enough on OHOS: ``/system/bin/sh`` keeps the variable in the environment it
  hands to children, and setting it empty is just as fatal.
* node is *not* started directly from the launcher shell. On this OHOS
  runtime the V8 code-range reservation aborts
  (``Check failed: 12 == (*__errno_location())``, Signal 5 / exit 133) when
  node is exec'ed straight from a system shell, while an extra exec through a
  helper binary installed on the user filesystem gives node an address-space
  layout in which the reservation succeeds. ``bin/letta-exec`` is that tiny
  re-exec trampoline; it also calls ``unsetenv("LD_LIBRARY_PATH")``.
* JIT is deliberately kept on (``--jitless`` is *not* used): yoga-layout's
  WASM, required by the ink UI, is unavailable without JIT.

There is no compilation of the npm release: the tarball is consumed as-is.
``build()`` still compiles the one-file ``letta-exec`` trampoline and then runs
the *real packaged launcher* over a runtime-equivalent staged tree as a smoke
check (``--version`` banner + ``--help`` sections), so that a launcher/trampoline
regression fails the build.
"""

import os
import re
import shutil
import subprocess

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import copy, export_conandata_patches, get, save
from conan.tools.layout import basic_layout

# Name of the staging directory that holds the vendored ``ws`` source inside
# the recipe source folder. It must not be confused with a real packaged entry.
VENDORED_WS_DIR = "ws"

# Exact banner this release prints for ``letta --version``.
EXPECTED_VERSION = "0.28.17 (Letta Code)"

# Name of the re-exec trampoline generated by build()/package().
TRAMPOLINE_NAME = "letta-exec"

# Relative path (from the launcher in bin/) of the bundled entry point.
BUNDLE_RELPATH = "../libexec/letta-code/letta.js"

# C source of the trampoline. Kept intentionally tiny and dependency-free.
TRAMPOLINE_SOURCE = """\
/* letta-exec — re-exec trampoline for the packaged letta CLI.
 *
 * It exists for two independent OHOS reasons:
 *
 *  1. It removes LD_LIBRARY_PATH from the environment before handing control
 *     to node (belt and braces with the launcher's `env -u`).
 *  2. It gives node a clean address-space layout. On this OHOS runtime the V8
 *     code-range reservation aborts when node is exec'ed directly from a
 *     system shell ("Check failed: 12 == (*__errno_location())", Signal 5),
 *     while an extra exec through a binary installed on the user filesystem
 *     succeeds. This binary is that extra exec.
 */
#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>

int main(int argc, char **argv)
{
    if (argc < 2) {
        fputs("letta-exec: missing command\\n", stderr);
        return 2;
    }
    unsetenv("LD_LIBRARY_PATH");
    execvp(argv[1], &argv[1]);
    perror("letta-exec");
    return 127;
}
"""

# POSIX sh launcher body shared by build() (smoke) and package(). Kept in one
# place so the smoke always exercises exactly what gets installed.
LAUNCHER_BODY = """\
#!{shell}
set -eu

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
bundle="$script_dir/{bundle_relpath}"
trampoline="$script_dir/{trampoline}"

# --- truly strip LD_LIBRARY_PATH -------------------------------------------
# A foreign LD_LIBRARY_PATH leaking in from the host toolchain makes the OHOS
# node abort during V8 startup. `unset` is NOT enough here: /system/bin/sh
# keeps the variable in the environment handed to children (verified on
# device), and assigning it an empty value is just as fatal. Only `env -u`
# removes it for real, so resolve an `env` that supports it and fail loudly
# otherwise rather than silently inheriting the polluted value.
env_bin=""
for candidate in /system/bin/env /usr/bin/env /bin/env; do
    if [ -x "$candidate" ]; then
        env_bin="$candidate"
        break
    fi
done
if [ -z "$env_bin" ]; then
    resolved=$(command -v env 2>/dev/null || true)
    case "$resolved" in
        /*) if [ -x "$resolved" ]; then env_bin="$resolved"; fi ;;
    esac
fi
if [ -z "$env_bin" ]; then
    echo "letta: no usable 'env' utility found; refusing to start node with an inherited LD_LIBRARY_PATH" >&2
    exit 1
fi
if ! "$env_bin" -u LD_LIBRARY_PATH >/dev/null 2>&1; then
    echo "letta: '$env_bin' does not support -u; refusing to start node with an inherited LD_LIBRARY_PATH" >&2
    exit 1
fi

# JIT is kept on purpose: yoga-layout's WASM (ink UI) needs it.
# The trampoline is what makes node start reliably on OHOS; if it is missing
# we still strip LD_LIBRARY_PATH faithfully (same `env -u`) instead of
# inheriting the polluted value.
if [ -x "$trampoline" ]; then
    exec "$trampoline" "$env_bin" -u LD_LIBRARY_PATH node "$bundle" "$@"
fi
exec "$env_bin" -u LD_LIBRARY_PATH node "$bundle" "$@"
"""


def render_launcher(shell):
    """Single source of truth for the generated bin/letta body."""
    return LAUNCHER_BODY.format(
        shell=shell, bundle_relpath=BUNDLE_RELPATH, trampoline=TRAMPOLINE_NAME
    )


class LettaCodeConan(ConanFile):
    name = "letta-code"
    version = "0.28.17"
    description = (
        "Stateful agent CLI for interacting with Letta agents from the terminal"
    )
    license = "Apache-2.0"
    homepage = "https://github.com/letta-ai/letta-code"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    topics = ("ai", "cli", "nodejs", "agent", "letta")
    package_type = "application"

    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        # No patches are shipped for this release; this stays a no-op unless a
        # `patches` entry is later added to conandata.yml.
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"letta-code is prepared for Linux/OHOS targets only, "
                f"got {self.settings.os}"
            )
        # Only OHOS is pinned to armv8; Linux is intentionally left arch-free so
        # the recipe can be exercised with a host (e.g. x86_64) simulation
        # profile without being rejected at validate() time.
        if str(self.settings.os) == "OHOS" and str(self.settings.arch) != "armv8":
            raise ConanInvalidConfiguration("letta-code supports OHOS armv8 only")

        node = shutil.which("node")
        if not node:
            raise ConanInvalidConfiguration(
                "letta-code requires Node.js >= 22.19.0 in PATH"
            )
        try:
            result = subprocess.run(
                [node, "--version"],
                check=True,
                capture_output=True,
                text=True,
                timeout=15,
            )
        except (OSError, subprocess.SubprocessError) as exc:
            raise ConanInvalidConfiguration(
                f"unable to execute Node.js: {exc}"
            ) from exc
        match = re.match(r"^v(\d+)\.(\d+)\.(\d+)", result.stdout.strip())
        if not match or tuple(int(g) for g in match.groups()) < (22, 19, 0):
            raise ConanInvalidConfiguration(
                f"letta-code requires Node.js >= 22.19.0, "
                f"found {result.stdout.strip()!r}"
            )

    def source(self):
        # Two npm tarballs, keyed by name in conandata.yml:
        #   * "letta-code" — the prebuilt bundle, unpacked at the source root.
        #   * "ws"         — the un-flattened bare import, unpacked into the
        #                    VENDORED_WS_DIR staging folder.
        sources = self.conan_data["sources"]
        get(self, **sources["letta-code"], strip_root=True)
        get(
            self,
            **sources[VENDORED_WS_DIR],
            strip_root=True,
            destination=VENDORED_WS_DIR,
        )

    # --- trampoline ---------------------------------------------------------

    def _compile_trampoline(self):
        """Compile the one-file letta-exec helper into the build folder."""
        cc = shutil.which("clang") or shutil.which("cc") or shutil.which("gcc")
        if not cc:
            raise ConanException(
                "letta-code requires a C compiler (clang/cc/gcc) in PATH to "
                "build the letta-exec trampoline"
            )
        src = os.path.join(self.build_folder, TRAMPOLINE_NAME + ".c")
        dst = os.path.join(self.build_folder, TRAMPOLINE_NAME)
        save(self, src, TRAMPOLINE_SOURCE)
        last_err = None
        # Static is preferred (no runtime loader dependency at all); fall back
        # to a normal dynamic link if the toolchain cannot produce it.
        for extra in (["-static"], []):
            cmd = [cc, "-O2", "-Wall"] + extra + [src, "-o", dst]
            try:
                subprocess.run(
                    cmd, check=True, capture_output=True, text=True, timeout=300
                )
                self.output.info(
                    "built letta-exec trampoline "
                    f"({'+'.join(extra) if extra else 'dynamic'}): {dst}"
                )
                return dst
            except (OSError, subprocess.SubprocessError) as exc:
                last_err = exc
                if os.path.exists(dst):
                    os.remove(dst)
        raise ConanException(f"cannot build letta-exec trampoline: {last_err}")

    # --- build smoke --------------------------------------------------------

    def _stage_runtime_tree(self, stage_dir, trampoline):
        """Lay out a runtime tree identical to the installed package."""
        shutil.rmtree(stage_dir, ignore_errors=True)
        bin_dir = os.path.join(stage_dir, "bin")
        app_dir = os.path.join(stage_dir, "libexec", "letta-code")
        os.makedirs(bin_dir)
        os.makedirs(os.path.join(app_dir, "node_modules"))

        shutil.copy2(
            os.path.join(self.source_folder, "letta.js"),
            os.path.join(app_dir, "letta.js"),
        )
        shutil.copytree(
            os.path.join(self.source_folder, VENDORED_WS_DIR),
            os.path.join(app_dir, "node_modules", VENDORED_WS_DIR),
        )
        launcher = os.path.join(bin_dir, "letta")
        shell = "/system/bin/sh" if str(self.settings.os) == "OHOS" else "/bin/sh"
        save(self, launcher, render_launcher(shell))
        os.chmod(launcher, 0o755)
        shutil.copy2(trampoline, os.path.join(bin_dir, TRAMPOLINE_NAME))
        os.chmod(os.path.join(bin_dir, TRAMPOLINE_NAME), 0o755)
        return launcher

    def build(self):
        # Prebuilt npm release: the JS itself is not compiled. Assert the bundle
        # and the vendored `ws` runtime are present, build the trampoline, then
        # exercise the *real* launcher over a runtime-equivalent staged tree.
        letta_js = os.path.join(self.source_folder, "letta.js")
        package_json = os.path.join(self.source_folder, "package.json")
        ws_dir = os.path.join(self.source_folder, VENDORED_WS_DIR)
        required = (
            letta_js,
            package_json,
            os.path.join(ws_dir, "index.js"),
            os.path.join(ws_dir, "package.json"),
        )
        for path in required:
            if not os.path.isfile(path):
                raise ConanException(
                    f"required npm release artifact is missing: {path}"
                )

        if not shutil.which("node"):
            raise ConanException(
                "letta-code build smoke requires Node.js >= 22.19.0 in PATH"
            )

        trampoline = self._compile_trampoline()
        stage_dir = os.path.join(self.build_folder, "smoke")
        launcher = self._stage_runtime_tree(stage_dir, trampoline)

        # The smoke deliberately keeps the *inherited* environment (including a
        # leaked LD_LIBRARY_PATH) and reproduces the consumer invocation depth
        # of test_package: an extra /bin/sh -c layer around the launcher, which
        # is exactly where a naive launcher (bare `exec node`, or a plain
        # `unset LD_LIBRARY_PATH`) aborts with Signal 5 on this runtime.
        # NOTE: --jitless is deliberately NOT used here (nor in the launcher):
        # yoga-layout's WASM, required by the ink UI, is unavailable without JIT.
        inherited_env = dict(os.environ)
        self.output.info(
            "build smoke: inherited LD_LIBRARY_PATH="
            f"{inherited_env.get('LD_LIBRARY_PATH', '<unset>')!r}"
        )

        def run_launcher(*args):
            quoted = " ".join("'{}'".format(a.replace("'", "'\\''")) for a in args)
            cmd = ['/bin/sh', '-c', f'"{launcher}" {quoted}']
            try:
                proc = subprocess.run(
                    cmd,
                    cwd=stage_dir,
                    env=inherited_env,
                    capture_output=True,
                    text=True,
                    timeout=120,
                )
            except (OSError, subprocess.SubprocessError) as exc:
                raise ConanException(f"cannot run {cmd!r}: {exc}") from exc
            combined = proc.stdout + proc.stderr
            if proc.returncode != 0:
                raise ConanException(
                    f"build smoke launcher failed ({proc.returncode}): {cmd!r}\n"
                    f"--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}"
                )
            return combined

        version_output = run_launcher("--version").strip()
        self.output.info(f"bin/letta --version -> {version_output!r}")
        if version_output != EXPECTED_VERSION:
            raise ConanException(
                f"unexpected --version output: {version_output!r} "
                f"(expected {EXPECTED_VERSION!r})"
            )

        help_output = run_launcher("--help")
        for needle in ("USAGE", "headless"):
            if needle not in help_output:
                raise ConanException(
                    f"--help output is missing {needle!r}; "
                    f"got:\n{help_output}"
                )
        self.output.info(
            "build smoke OK: packaged launcher --version banner and --help "
            "sections verified through an inherited (polluted) environment"
        )

    def _source_excludes(self):
        """Patterns that must never be packaged: the `ws` staging folder plus
        every Conan build artefact that shares the build/source root (the build
        folder itself, conaninfo.txt and the generated conan* env scripts)."""
        source = os.path.abspath(self.source_folder)
        excludes = [VENDORED_WS_DIR, VENDORED_WS_DIR + "/*"]
        build = os.path.abspath(self.build_folder)
        if build.startswith(source + os.sep):
            rel = os.path.relpath(build, source).replace(os.sep, "/")
            excludes += [rel, rel + "/*"]
        excludes += [
            "conaninfo.txt",
            "conanbuild.sh",
            "conanrun.sh",
            "conanbuildenv-*.sh",
            "conanrunenv-*.sh",
            "deactivate_conanbuild.sh",
            "deactivate_conanrun.sh",
            "deactivate_conanbuildenv-*.sh",
            "deactivate_conanrunenv-*.sh",
        ]
        return excludes

    def package(self):
        app_dir = os.path.join(self.package_folder, "libexec", "letta-code")

        # Lay out the npm package exactly as published (letta.js, dist/,
        # vendor/, skills/, docs/, scripts/, assets/, image-resize-worker.js,
        # package.json, LICENSE, README.md). The `ws` staging folder and every
        # Conan build artefact sharing the build/source root are excluded so no
        # build cache leaks into the package.
        copy(
            self,
            "*",
            src=self.source_folder,
            dst=app_dir,
            keep_path=True,
            excludes=self._source_excludes(),
        )

        # Vendor the `ws` runtime into node_modules/ws so letta.js's
        # `import ... from "ws"` resolves without a network install.
        copy(
            self,
            "*",
            src=os.path.join(self.source_folder, VENDORED_WS_DIR),
            dst=os.path.join(app_dir, "node_modules", VENDORED_WS_DIR),
            keep_path=True,
        )

        copy(self, "LICENSE", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"), keep_path=False)

        shell = "/system/bin/sh" if str(self.settings.os) == "OHOS" else "/bin/sh"

        # Re-exec trampoline compiled in build(); consumed by the launcher.
        trampoline = os.path.join(self.build_folder, TRAMPOLINE_NAME)
        if not os.path.isfile(trampoline):
            raise ConanException(
                f"{TRAMPOLINE_NAME} was not built by build(): {trampoline}"
            )
        bin_dir = os.path.join(self.package_folder, "bin")
        copy(self, TRAMPOLINE_NAME, src=self.build_folder, dst=bin_dir,
             keep_path=False)
        try:
            os.chmod(os.path.join(bin_dir, TRAMPOLINE_NAME), 0o755)
        except OSError:
            pass

        launcher = os.path.join(bin_dir, "letta")
        save(self, launcher, render_launcher(shell))
        try:
            os.chmod(launcher, 0o755)
        except OSError:
            # HMDFS/SELinux: chmod can be a silent no-op; the launcher is also
            # reachable via `sh <path>`, so a missing +x is non-fatal.
            pass

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.libs = []
