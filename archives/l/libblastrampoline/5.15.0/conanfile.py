#!/usr/bin/env python3
"""Conan recipe — libblastrampoline 5.15.0

libblastrampoline: a dynamic BLAS/LAPACK interposition layer that forwards
the full FORTRAN BLAS/LAPACK/LAPACKE API to one or more backend libraries
loaded at runtime via dlopen/dlsym.

Upstream: https://github.com/JuliaLinearAlgebra/libblastrampoline (MIT)

Build system: plain Makefile (src/Makefile + src/Make.inc).
Products:
  - libblastrampoline.so.5 (SONAME; 5384 exported trampoline symbols)

OHOS specifics (verified by exploratory build on HarmonyOS/aarch64):
  - `uname -s` == "HarmonyOS" != "Linux" -> upstream Make.inc takes the
    generic Unix branch: correct .so naming and SONAME, no -ldl needed
    (musl folds libdl into libc, dlopen/dlsym resolve from libc.so).
  - musl has no RTLD_DEEPBIND -> upstream compiles the deepbindless
    codepath (LBT_DEEPBINDLESS), LBT_BUILDFLAGS_DEEPBINDLESS is set.
  - aarch64 trampolines are hand-written assembly dispatched via x17 index
    + `br x16`; clang emits .note.GNU-stack implicitly so GNU_STACK is RW
    (NX) without extra LDFLAGS.
  - .codesign section is auto-generated by the OHOS toolchain and is not
    required for loadable shared libraries (musl loader ignores it).
  - No source patches needed for HarmonyOS/aarch64.

This package has NO requirements: backends are opened at runtime by the
consumer (LBT_DEFAULT_LIBS env var or lbt_forward() API), never linked.
"""
import os
import re

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get
from conan.tools.gnu import AutotoolsToolchain  # noqa: F401  (documentation anchor)
from conan.tools.layout import basic_layout
from conan.tools.microsoft import is_msvc


class LibblastrampolineConan(ConanFile):
    name = "libblastrampoline"
    version = "5.15.0"
    description = "Dynamic BLAS/LAPACK interposition layer with dlopen-based backend forwarding"
    license = "MIT"
    homepage = "https://github.com/JuliaLinearAlgebra/libblastrampoline"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": True}

    def export_sources(self):
        pass

    def layout(self):
        basic_layout(self)

    # R32: OHOS platform compatibility
    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")
        if self.settings.arch not in ("armv8", "x86_64"):
            raise ConanInvalidConfiguration(
                f"Unsupported arch for libblastrampoline trampolines: "
                f"{self.settings.arch}")
        if not self.options.shared:
            raise ConanInvalidConfiguration(
                "libblastrampoline is a runtime interposition layer and only "
                "makes sense as a shared library (static builds would have "
                "no effect on dynamically loaded backends)")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # Pure Makefile project: Make.inc honors CC from the environment, but
        # R33 requires reading the compiler from the Conan conf, done in
        # build()/package() via CC=... on the make command line.
        pass

    def _make(self, target):
        # R33: get compiler from Conan conf (never bare shell env vars).
        # Upstream default is `cc`, which does not exist on OHOS images.
        # Make.inc derives ARCH from `$(CC) -dumpmachine` and uses it to
        # select the aarch64 trampoline assembly.
        comp_execs = self.conf.get("tools.build:compiler_executables",
                                   default={}, check_type=dict)
        cc = comp_execs.get("c") or "clang"
        jobs = os.cpu_count() or 2
        self.run(
            f'make -C src -j{jobs} {target} CC="{cc}" '
            f'builddir="{self.build_folder}"',
            cwd=self.source_folder)

    def build(self):
        # Upstream Makefile builds out-of-tree: `make -C src builddir=OUT`
        # compiles from the source tree into OUT. basic_layout puts the
        # recipe's build folder at build/ (a sibling of the copied source
        # tree), so run make from the source folder with builddir pointing
        # at the conan build folder.
        self._make("all")

    def package(self):
        # `make install` target: installs lib + headers into prefix
        comp_execs = self.conf.get("tools.build:compiler_executables",
                                   default={}, check_type=dict)
        cc = comp_execs.get("c") or "clang"
        self.run(
            f'make -C src install CC="{cc}" '
            f'builddir="{self.build_folder}" '
            f'prefix="{self.package_folder}"',
            cwd=self.source_folder)

    def package_info(self):
        self.cpp_info.libs = ["blastrampoline"]
        self.cpp_info.includedirs = ["include"]
        # libblastrampoline.so.5 has NEEDED libc.so only; backends are
        # dlopened at runtime by the consumer, never a link-time dependency.
        self.cpp_info.system_libs = []
        self.cpp_info.set_property("pkg_config_name", "libblastrampoline")
