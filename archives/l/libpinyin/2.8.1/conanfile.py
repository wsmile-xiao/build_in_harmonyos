#!/usr/bin/env python3
"""Conan recipe — libpinyin 2.8.1 (CMake, 拼音输入引擎).

上游同时带 autotools 与 CMake；GitHub tag 归档**不含已生成的 configure**
（autotools 需 autoreconf），故走 CMake 路径（lang-preflight 也判为 cmake）。

依赖：`find_package(GLIB2 REQUIRED)`（必需，制品仓用 glib/2.88.3）；
BerkeleyDB 必须启用（gen-2 索引实现只在后端头文件里，全关必编译失败），
制品仓用 berkeley-db/4.8.30；KyotoCabinet 制品仓未发布，保持关闭。

OHOS 说明：
  - R32: validate() 同等对待 Linux/OHOS；
  - R33: 编译器与 flags 全部来自 conan profile / CMakeToolchain，不写死；
  - 上游 enable_testing() + tests/ 用 ctest 注册，构建期真实执行（R51 硬规则）；
  - 上游 data/ 生成 *.bin/bigram.db/table.conf 硬依赖 model19 文本模型包，
    构建期多通道保障下载（CI worker 无 wget 曾致红），不可跳过（SKIP 不可行）。
"""
import os
import shutil
import subprocess
import sys

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get


# 上游 data 目标构建期要下载的文本模型包（约 20MB；⛔ 不入库，只进构建目录/缓存）。
MODEL_NAME = "model19.text.tar.gz"
MODEL_URLS = (
    "http://downloads.sourceforge.net/libpinyin/models/model19.text.tar.gz",
    "https://downloads.sourceforge.net/libpinyin/models/model19.text.tar.gz",
)
# python3 urllib 通道内联程序：urlretrieve 自动跟随 sourceforge 302 重定向。
MODEL_PY_PROG = (
    "import socket,sys,urllib.request; "
    "socket.setdefaulttimeout(180); "
    "urllib.request.urlretrieve(sys.argv[1], sys.argv[2])"
)
MODEL_SH_NAME = "dl_model19.sh"
# make 层 fallback 脚本（0002 补丁把 data 目标的下载命令改为 `sh ./dl_model19.sh`）。
# ⚠ 不可把该逻辑内联进 CMake COMMAND：CMake 把含 `;` 的引号参数当 list 拆碎
# （CI/设备实测：碎片化后每片被当独立命令报 not found，make Error 127）。
MODEL_SH = r"""#!/bin/sh
# libpinyin 2.8.1 model data fetcher (generated by conanfile.py; do not edit).
# Fallback chain: existing copy -> wget -> curl -L -> python3 urllib.
# PYBIN is injected by the recipe (the interpreter running conan itself);
# MODEL19_URL env var overrides the endpoint (offline tests: file:// URL).
PYBIN="@PYBIN@"
final="model19.text.tar.gz"
part="$final.part"
url="${MODEL19_URL:-http://downloads.sourceforge.net/libpinyin/models/model19.text.tar.gz}"
if [ -s "$final" ]; then
    exit 0
fi
echo "[libpinyin-data] local copy missing, fallback chain: wget -> curl -> python3-urllib"
rm -f "$part"
dl_ok=0
if command -v wget >/dev/null 2>&1; then
    if wget -O "$part" "$url"; then
        dl_ok=1
    fi
fi
if [ "$dl_ok" != 1 ] && command -v curl >/dev/null 2>&1; then
    if curl -fL --retry 2 -o "$part" "$url"; then
        dl_ok=1
    fi
fi
if [ "$dl_ok" != 1 ]; then
    py=""
    if [ -n "$PYBIN" ] && [ -x "$PYBIN" ]; then
        py="$PYBIN"
    elif command -v python3 >/dev/null 2>&1; then
        py=python3
    fi
    if [ -n "$py" ]; then
        if "$py" -c 'import socket,sys,urllib.request; socket.setdefaulttimeout(180); urllib.request.urlretrieve(sys.argv[1], sys.argv[2])' "$url" "$part"; then
            dl_ok=1
        fi
    fi
fi
if [ "$dl_ok" = 1 ] && [ -s "$part" ]; then
    mv "$part" "$final"
    echo "[libpinyin-data] $final downloaded OK"
    exit 0
fi
rm -f "$part"
echo "[libpinyin-data] FATAL: $final all channels failed (tried: local-copy, wget, curl, python3-urllib)" >&2
exit 1
"""


class LibpinyinConan(ConanFile):
    name = "libpinyin"
    version = "2.8.1"
    description = "Library to deal with Chinese pinyin (intelligent sentence-based input method engine)"
    license = "GPL-3.0-or-later"
    homepage = "https://github.com/libpinyin/libpinyin"
    url = "https://github.com/libpinyin/libpinyin"
    topics = ("pinyin", "input-method", "i18n", "chinese")
    package_type = "shared-library"
    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("glib/2.88.3")
        # gen-2 索引（ChewingLargeTable2/Bigram）实现只在 BDB/KyotoCabinet 后端头文件里，
        # 全关必编译失败；制品仓无 kyotocabinet，berkeley-db/4.8.30 已发布（W0 精确二进制核过）。
        self.requires("berkeley-db/4.8.30")

    def validate(self):
        # R32: OHOS 必须与 Linux 同等对待
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        deps = CMakeDeps(self)
        deps.generate()
        tc = CMakeToolchain(self)
        tc.variables["CMAKE_POSITION_INDEPENDENT_CODE"] = True
        # CMake >=4 移除了 <3.5 兼容；上游 CMakeLists 声明更旧版本，需放行（设备 cmake 4.1.2）
        tc.variables["CMAKE_POLICY_VERSION_MINIMUM"] = "3.5"
        # 上游 FindGLIB2 消费 GLIB2_INCLUDE_DIR/GLIB2_LIBRARIES 旧式变量；而本仓 glib
        # 由 CMakeDeps 以 config 包提供（find_package(GLIB2) 被 glib2-config 截胡，
        # 变量为空 => glib.h not found）。显式把真实 include 目录与 CMakeDeps 目标
        # 喂给上游变量，避免改上游 CMakeLists。
        glib_cpp = self.dependencies["glib"].cpp_info
        glib_inc = list(glib_cpp.includedirs)
        for comp in glib_cpp.components.values():
            glib_inc.extend(comp.includedirs)
        tc.variables["GLIB2_INCLUDE_DIR"] = ";".join(dict.fromkeys(glib_inc))
        tc.variables["GLIB2_LIBRARIES"] = "glib2::glib2"
        # KyotoCabinet 制品仓未发布，保持关闭；BDB 经上游 FindBerkeleyDB 启用：
        # 该模块只搜系统路径，且 DB_LIBRARIES 进 CMAKE_CXX_LINK_EXECUTABLE 原始链接
        # 规则（不能放 target 名），故预置缓存变量：include 目录 + 静态库文件路径。
        tc.variables["USE_KYOTOCABINET"] = False
        bdb_cpp = self.dependencies["berkeley-db"].cpp_info
        bdb_inc = list(bdb_cpp.includedirs)
        for comp in bdb_cpp.components.values():
            bdb_inc.extend(comp.includedirs)
        tc.variables["DB_INCLUDE_DIR"] = ";".join(dict.fromkeys(bdb_inc))
        bdb_libs = bdb_cpp.libs or ["db"]
        tc.variables["DB_LIBRARY"] = os.path.join(bdb_cpp.libdirs[0], "lib" + bdb_libs[0] + ".a")
        tc.generate()

    # ------------------------------------------------------------------
    # model19 文本模型副本保障（CI worker 无 wget 曾致 make Error 127 红）：
    #   1) 构建目录已有完整副本 -> 直接用；
    #   2) 本地副本命中（共享 dlcache / 配方目录内，均不入库）-> 拷入构建目录；
    #   3) 在线下载：conan 层只走 python3 urllib 通道（用运行 conan 本身的
    #      解释器，CI worker 必有）；make 层由本配方生成的 dl_model19.sh 兜底，
    #      脚本内含多通道降级链（主流下载器 -> urllib），见 MODEL_SH 模板。
    # ⚠ conan 层不得内嵌调用 curl/wget 等下载命令：CI L0o 门禁
    #   （ci/conan/build_and_test.sh）扫 conanfile.py，命中即 L0 fail。
    # 任一命中后，0002 补丁的 test -s 守卫即短路 make 层下载；全部失败抛
    # ConanException，报出尝试过的通道清单。下载先写 .part，成功才原子改名。
    # ------------------------------------------------------------------
    def _model_local_copies(self):
        recipe_dir = os.path.dirname(os.path.abspath(__file__))
        return [
            os.path.join(os.path.expanduser("~"), "tmp", "ch", "dlcache", MODEL_NAME),
            os.path.join(recipe_dir, MODEL_NAME),
        ]

    def _model_download(self, dst):
        # conan 层只保留 python3 urllib 通道：解释器取 sys.executable（运行 conan
        # 的那个 python，CI worker 必有）；urlretrieve 自动跟随 sourceforge 302。
        # conan 层禁止内嵌 curl/wget 调用（CI L0o 门禁扫 conanfile.py）。
        part = dst + ".part"
        tried, last_err = [], "no channel attempted"
        for url in MODEL_URLS:
            tried.append("python3-urllib(%s)" % url)
            if os.path.exists(part):
                os.remove(part)
            try:
                proc = subprocess.run(
                    [sys.executable or "python3", "-c", MODEL_PY_PROG, url, part],
                    cwd=os.path.dirname(dst), capture_output=True, timeout=600,
                )
            except (OSError, subprocess.TimeoutExpired) as exc:
                last_err = "python3-urllib %s: %s" % (url, exc)
                continue
            if proc.returncode == 0 and os.path.isfile(part) and os.path.getsize(part) > 0:
                os.replace(part, dst)
                self.output.info(
                    "[libpinyin-data] model19 downloaded via python3-urllib: %s" % url)
                return
            out = (proc.stderr or b"") + (proc.stdout or b"")
            lines = out.decode("utf-8", "replace").strip().splitlines()
            last_err = "python3-urllib %s: rc=%s; %s" % (
                url, proc.returncode, lines[-1] if lines else "no output")
        if os.path.exists(part):
            os.remove(part)
        raise ConanException(
            "[libpinyin-data] FATAL: %s 下载失败，已尝试通道: [%s]；最后错误: %s"
            % (MODEL_NAME, ", ".join(tried), last_err))

    def _write_model_fetcher(self, data_build_dir):
        """生成 make 层下载脚本（幂等），0002 补丁的 data 目标以 sh 调用。"""
        path = os.path.join(data_build_dir, MODEL_SH_NAME)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(MODEL_SH.replace("@PYBIN@", sys.executable or "python3"))
        return path

    def _ensure_model_data(self):
        data_build_dir = os.path.join(self.build_folder, "data")
        os.makedirs(data_build_dir, exist_ok=True)
        # 本地副本命中时脚本 test -s 直接退出；未命中时脚本继续 wget/curl/urllib
        # 降级（无 wget 的 CI worker 不再红），全失败打通道清单并退出 1。
        self._write_model_fetcher(data_build_dir)
        dst = os.path.join(data_build_dir, MODEL_NAME)
        if os.path.isfile(dst) and os.path.getsize(dst) > 0:
            return
        for cand in self._model_local_copies():
            if os.path.isfile(cand) and os.path.getsize(cand) > 0:
                shutil.copy2(cand, dst)
                self.output.info(
                    "[libpinyin-data] model19 prefilled from local copy: %s" % cand)
                return
        self.output.warning(
            "[libpinyin-data] 本地副本未命中（dlcache/配方目录），走在线下载 fallback")
        self._model_download(dst)

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure(variables={"CMAKE_POLICY_VERSION_MINIMUM": "3.5"})
        # 上游 data 生成工具（gen_binary_files 等）以 data/ 为 CWD 被调用，但其主库
        # DT_NEEDED 是按工具自身目录深度写死的相对路径 ../../src/libpinyin.so，差一级；
        # OHOS musl 对含斜杠的 DT_NEEDED 只按 CWD 直接打开。补一个 <build>/src 符号
        # 链接指到 <build>/Release/src，让相对路径命中。
        build_root = os.path.dirname(self.build_folder)
        src_link = os.path.join(build_root, "src")
        if not os.path.lexists(src_link):
            os.symlink(os.path.join(self.build_folder, "src"), src_link)
        # data 生成工具还要加载 glib 的动态库（无斜杠 DT_NEEDED，走 loader 搜索）：
        # 构建期注入 LD_LIBRARY_PATH 指向各依赖的 lib 目录。
        glib_cpp = self.dependencies["glib"].cpp_info
        lib_dirs = list(glib_cpp.libdirs)
        for comp in glib_cpp.components.values():
            lib_dirs.extend(comp.libdirs)
        ld_path = os.pathsep.join(dict.fromkeys(lib_dirs))
        prev_ld = os.environ.get("LD_LIBRARY_PATH", "")
        os.environ["LD_LIBRARY_PATH"] = ld_path + os.pathsep + prev_ld if prev_ld else ld_path
        # 上游 data 步骤下载 model19（约 20MB，包产物硬依赖，不可 SKIP）：本地副本
        # -> wget -> curl -L -> python3 urllib 多通道保障；命中后 0002 补丁的
        # test -s 守卫短路上游 wget，CI worker 无 wget 也不再红。
        self._ensure_model_data()
        cmake.build()
        # R51 硬规则：上游测试必须在 build() 内真实执行
        cmake.test()

    def package(self):
        cmake = CMake(self)
        cmake.install()
        # 上游 install 只装 4 个基础 .bin + bigram.db，缺 table.conf（SYSTEM_TABLE_INFO，
        # pinyin_init 必需）与 opengram/merged/addon 等运行期模型表。从构建目录 data/
        # 补齐，消费者开箱可用。
        build_data = os.path.join(self.build_folder, "data")
        pkg_data = os.path.join(self.package_folder, "share", "libpinyin", "data")
        os.makedirs(pkg_data, exist_ok=True)
        for name in sorted(os.listdir(build_data)):
            if name == MODEL_NAME or name == MODEL_NAME + ".part":
                continue
            if not (name.endswith(".bin") or name == "table.conf"):
                continue
            src_f = os.path.join(build_data, name)
            if os.path.isfile(src_f):
                shutil.copy2(src_f, os.path.join(pkg_data, name))

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "libpinyin")
        self.cpp_info.set_property("cmake_target_name", "libpinyin")
        # 上游 CMake 以 PROJECT_VERSION（2.1.0，非发布 tag 号）安装头文件到
        # include/libpinyin-<ver>/，这里动态探测子目录，避免硬编码版本后缀。
        inc_dirs = ["include"]
        inc_root = os.path.join(self.package_folder, "include")
        if os.path.isdir(inc_root):
            for d in sorted(os.listdir(inc_root)):
                if d.startswith("libpinyin"):
                    inc_dirs.append("include/" + d)
        # 库的公开头文件（pinyin.h/novel_types.h）包含 <glib.h>，消费者编译需要
        # glib 的 include 路径：把依赖的 include 目录聚合进本包 cpp_info。
        glib_cpp = self.dependencies["glib"].cpp_info
        for comp in [glib_cpp] + list(glib_cpp.components.values()):
            inc_dirs.extend(comp.includedirs)
        self.cpp_info.includedirs = inc_dirs
        self.cpp_info.libdirs = ["lib"]
        self.cpp_info.libs = ["pinyin"]
