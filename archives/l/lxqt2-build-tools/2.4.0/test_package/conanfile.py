#!/usr/bin/env python3
"""Conan test_package for lxqt2-build-tools 2.4.0.

R34: the test genuinely depends on the tested package:
  - the CMake test project calls find_package(lxqt2-build-tools REQUIRED) and
    uses the lxqt_create_pkgconfig_file() module function shipped by the
    package to generate a pkg-config file;
  - the generated .pc file content is verified by a C program;
  - the installed bin/lxqt2-transupdate helper script is executed.
"""
import os
import shlex

from conan import ConanFile
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout


class Lxqt2BuildToolsTestConan(ConanFile):
    settings = "os", "compiler", "build_type", "arch"
    generators = "CMakeDeps"

    def requirements(self):
        self.requires(self.tested_reference_str)

    def layout(self):
        cmake_layout(self)

    def generate(self):
        # E225: CMakeToolchain would otherwise write CMakeUserPresets.json into
        # the test_package source dir; disable user presets to keep source clean.
        tc = CMakeToolchain(self)
        tc.user_presets_path = False
        tc.generate()

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def test(self):
        # 1. ctest: verify the .pc file generated by the package's CMake module
        cmake = CMake(self)
        cmake.test()

        # 2. Execute the installed helper script (R34: run the package binary).
        pkg_folder = self.dependencies["lxqt2-build-tools"].package_folder
        transupdate = os.path.join(pkg_folder, "bin", "lxqt2-transupdate")
        # lxqt2-transupdate operates on .ts files found below CWD; run it in an
        # empty temp dir where it has no work to do and must exit 0.
        tmp_dir = os.path.join(self.build_folder, "run_transupdate")
        os.makedirs(tmp_dir, exist_ok=True)
        self.run(
            f"cd {shlex.quote(tmp_dir)} && {shlex.quote(transupdate)}",
            env="conanrun",
            ignore_errors=False,
        )
