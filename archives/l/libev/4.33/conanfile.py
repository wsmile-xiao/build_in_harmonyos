#!/usr/bin/env python3
"""Conan recipe for libev 4.33 — CMake build (autotools has HMDFS issues on OHOS).

libev ships only autotools build files. On HarmonyOS, autotools config.status
fails due to HMDFS filesystem restrictions on temporary directory creation.
This recipe generates a CMakeLists.txt to build the library instead.
"""
import os
from conan import ConanFile
from conan.tools.files import get, save, export_conandata_patches, apply_conandata_patches
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout


class LibevConan(ConanFile):
    name = "libev"
    version = "4.33"
    description = "High-performance event loop library (epoll, kqueue, etc.)"
    license = "BSD-2-Clause"
    homepage = "http://software.schmorp.de/pkg/libev.html"
    url = ""

    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = CMakeToolchain(self)
        if self.options.shared:
            tc.variables["BUILD_SHARED_LIBS"] = True
        else:
            tc.variables["BUILD_SHARED_LIBS"] = False
        tc.generate()

    def build(self):
        apply_conandata_patches(self)

        # Generate CMake config template (cmakedefine syntax)
        config_h_cmake = """\
/* config.h — generated by CMake for libev 4.33 */
#define HAVE_CONFIG_H 1
#cmakedefine HAVE_CLOCK_GETTIME 1
#cmakedefine HAVE_DLFCN_H 1
#cmakedefine HAVE_EPOLL_CTL 1
#cmakedefine HAVE_EVENTFD 1
#cmakedefine HAVE_FLOOR 1
#cmakedefine HAVE_INOTIFY_INIT 1
#cmakedefine HAVE_INTTYPES_H 1
#cmakedefine HAVE_KERNEL_RWF_T 1
#cmakedefine HAVE_LIBRT 1
#cmakedefine HAVE_LINUX_AIO_ABI_H 1
#cmakedefine HAVE_LINUX_FS_H 1
#cmakedefine HAVE_MEMORY_H 1
#cmakedefine HAVE_NANOSLEEP 1
#cmakedefine HAVE_POLL 1
#cmakedefine HAVE_POLL_H 1
#cmakedefine HAVE_SELECT 1
#cmakedefine HAVE_SIGNALFD 1
#cmakedefine HAVE_STDINT_H 1
#cmakedefine HAVE_STDLIB_H 1
#cmakedefine HAVE_STRINGS_H 1
#cmakedefine HAVE_STRING_H 1
#cmakedefine HAVE_SYS_EPOLL_H 1
#cmakedefine HAVE_SYS_EVENTFD_H 1
#cmakedefine HAVE_SYS_INOTIFY_H 1
#cmakedefine HAVE_SYS_SELECT_H 1
#cmakedefine HAVE_SYS_SIGNALFD_H 1
#cmakedefine HAVE_SYS_STAT_H 1
#cmakedefine HAVE_SYS_TIMERFD_H 1
#cmakedefine HAVE_SYS_TYPES_H 1
#cmakedefine HAVE_UNISTD_H 1
#define LT_OBJDIR ".libs/"
#define PACKAGE "libev"
#define PACKAGE_BUGREPORT ""
#define PACKAGE_NAME "libev"
#define PACKAGE_STRING "libev 4.33"
#define PACKAGE_TARNAME "libev"
#define PACKAGE_URL ""
#define PACKAGE_VERSION "4.33"
#define STDC_HEADERS 1
#define VERSION "4.33"
"""
        save(self, os.path.join(self.source_folder, "config.h.cmake"), config_h_cmake)

        # Generate CMakeLists.txt
        cmake_content = """\
cmake_minimum_required(VERSION 3.15)
project(libev C)

option(BUILD_SHARED_LIBS "Build shared libraries" OFF)

include(CheckIncludeFile)
include(CheckFunctionExists)
include(CheckSymbolExists)

check_include_file("sys/epoll.h" HAVE_SYS_EPOLL_H)
check_include_file("sys/inotify.h" HAVE_SYS_INOTIFY_H)
check_include_file("poll.h" HAVE_POLL_H)
check_include_file("sys/select.h" HAVE_SYS_SELECT_H)
check_include_file("sys/eventfd.h" HAVE_SYS_EVENTFD_H)
check_include_file("sys/signalfd.h" HAVE_SYS_SIGNALFD_H)
check_include_file("sys/timerfd.h" HAVE_SYS_TIMERFD_H)
check_include_file("linux/aio_abi.h" HAVE_LINUX_AIO_ABI_H)
check_include_file("linux/fs.h" HAVE_LINUX_FS_H)
check_include_file("dlfcn.h" HAVE_DLFCN_H)
check_include_file("inttypes.h" HAVE_INTTYPES_H)
check_include_file("stdint.h" HAVE_STDINT_H)
check_include_file("stdlib.h" HAVE_STDLIB_H)
check_include_file("string.h" HAVE_STRING_H)
check_include_file("strings.h" HAVE_STRINGS_H)
check_include_file("memory.h" HAVE_MEMORY_H)
check_include_file("sys/stat.h" HAVE_SYS_STAT_H)
check_include_file("sys/types.h" HAVE_SYS_TYPES_H)
check_include_file("unistd.h" HAVE_UNISTD_H)

check_function_exists("clock_gettime" HAVE_CLOCK_GETTIME)
check_function_exists("nanosleep" HAVE_NANOSLEEP)
check_function_exists("inotify_init" HAVE_INOTIFY_INIT)
check_function_exists("epoll_ctl" HAVE_EPOLL_CTL)
check_function_exists("poll" HAVE_POLL)
check_function_exists("select" HAVE_SELECT)
check_function_exists("eventfd" HAVE_EVENTFD)
check_function_exists("signalfd" HAVE_SIGNALFD)
check_function_exists("floor" HAVE_FLOOR)

check_symbol_exists("__kernel_rwf_t" "linux/fs.h" HAVE_KERNEL_RWF_T)

configure_file("${CMAKE_CURRENT_SOURCE_DIR}/config.h.cmake" "${CMAKE_CURRENT_SOURCE_DIR}/config.h")

add_library(ev ev.c event.c)
target_include_directories(ev PUBLIC ${CMAKE_CURRENT_SOURCE_DIR})
set_target_properties(ev PROPERTIES OUTPUT_NAME "ev")

install(TARGETS ev
    ARCHIVE DESTINATION lib
    LIBRARY DESTINATION lib
    RUNTIME DESTINATION bin
)
install(FILES ev.h ev++.h event.h DESTINATION include)
"""
        save(self, os.path.join(self.source_folder, "CMakeLists.txt"), cmake_content)

        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.libs = ["ev"]
