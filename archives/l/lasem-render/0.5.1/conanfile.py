#!/usr/bin/env python3
"""Conan recipe — lasem-render 0.5.1 (autotools)

Lasem — SVG and MathML rendering library (DOM-like API) + lasem-render-0.6 CLI.
Upstream: GNOME lasem 0.5.1 (MathML/SVG -> cairo + pango math renderer, pure C).

OHOS adaptation notes (all verified on device):
- Upstream 0.5.1 uses IT_PROG_INTLTOOL/AM_GLIB_GNU_GETTEXT/GTK_DOC_CHECK macros;
  OHOS build host has no intltoolize/glib-gettextize/gtkdocize. Patch 0001
  comments them out and drops the po/ subdirectory (translations not needed
  for the library); docs/ manpage still installs.
- The GitHub tag archive (LASEM_0_5_1) is used because the GNOME dist tarball
  excludes tests/data entirely (1174 render test cases would be unrunnable).
  Tag archive carries the full data set, so the upstream suite is REAL.
- configure is generated by autoreconf inside build() (tag archive ships no
  configure). After autoreconf: config.sub gets linux-ohos appended and the
  generated configure's `umask 077` tmp-dir lines are rewritten to umask 022
  (HMDFS denies writes into 0700 dirs — E112/E114, same fix as gts 0.7.6).
- glib-mkenums shebang is /usr/bin/perl which does not exist on OHOS;
  make() passes GLIB_MKENUMS="perl <script>" to bypass the shebang.
- liblasem links fine, but lasem-render CLI needs glib's proxy-libintl
  (g_libintl_* symbols live in glib package's libintl.so): -lintl is appended
  to glib-2.0.pc Libs (same approach as gdk-pixbuf 2.44.6.1.1).
- make check: 4 gtester programs (dom/str/filter/suite). suite enumerates
  tests/data/**/*.{mml,svg} minus ignore-* prefixed files/images dir minus 4
  suite.ini ignore=true entries = 1174 render cases; all pass on device.
"""
import glob
import os
import re
import shutil
import subprocess

from conan import ConanFile
from conan.tools.env import Environment
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsToolchain, PkgConfigDeps
from conan.tools.layout import basic_layout


class LasemRenderConan(ConanFile):
    name = "lasem-render"
    version = "0.5.1"
    description = "Lasem — SVG and MathML rendering library (DOM-like API) with lasem-render CLI"
    license = "LGPL-2.1-or-later"
    homepage = "https://gitlab.gnome.org/GNOME/lasem"
    url = "https://github.com/LasemProject/lasem"
    package_type = "library"

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    exports_sources = "patches/*"

    def export_sources(self):
        export_conandata_patches(self)

    def configure(self):
        self.settings.rm_safe("compiler.cppstd")
        self.settings.rm_safe("compiler.libcxx")

    def requirements(self):
        # glib shared: the registry publishes glib/2.84.0.1 binaries as shared
        # only; forcing shared=False would trigger a from-source glib rebuild
        # whose own test suite has an environment-dependent failure. The
        # shared build satisfies everything lasem needs (verified on device).
        # transitive_headers=True: lasem's public headers #include <cairo.h> /
        # <pango/pangocairo.h> / <glib-object.h> — without the trait Conan 2
        # marks these requires headers=False for downstream consumers and
        # CMakeDeps emits empty *_INCLUDE_DIRS_RELEASE (same as gts 0.7.6).
        # harfbuzz: pango's public headers #include <hb.h>; lasem's consumers
        # compiling against <pango/pangocairo.h> (pulled by lsmdomview.h)
        # need harfbuzz headers too — it must be a direct require with the
        # trait or CMakeDeps leaves it header-less for consumers.
        self.requires("glib/2.84.0.1", transitive_headers=True)
        self.requires("cairo/1.18.4", transitive_headers=True)
        self.requires("pango/1.50.14", transitive_headers=True)
        self.requires("harfbuzz/14.2.0.1", transitive_headers=True)
        self.requires("gdk-pixbuf/2.44.6.1.1", transitive_headers=True)
        self.requires("libxml2/2.15.3", transitive_headers=True)

    def build_requirements(self):
        # The tag archive ships no configure — build() must run the full
        # autoreconf chain. The CI sandbox (USER=100) cannot see the
        # $HOME/.local automake install (ENOENT), and hnp/bin only carries
        # the autoconf family — so automake + libtool come in as tool_requires
        # (registry-published 1.18/2.5.4, same as the abiword-plugin series).
        # NOTE: autoconf/2.72 is deliberately NOT a tool_requires — it pulls
        # perl/5.42.2 whose XS modules fail to dlopen on HMDFS, and that perl
        # would shadow the working system perl; hnp's autoconf 2.72 is already
        # on the build profile PATH.
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")

    def layout(self):
        basic_layout(self, src_folder=".")

    def source(self):
        sources = dict(self.conan_data["sources"])
        mirror_url = sources.pop("mirror_url", None)
        try:
            get(self, **sources, strip_root=True)
        except Exception as e:
            if not mirror_url:
                raise
            self.output.warning(f"Primary source failed ({e}), trying mirror")
            get(self, url=mirror_url, sha256=sources["sha256"], strip_root=True)

    # ------------------------------------------------------------------
    # OHOS fix-ups applied after autoreconf (generated files, not patchable
    # at source level because tag archive ships no configure)
    # ------------------------------------------------------------------
    def _fix_config_sub(self):
        """Add linux-ohos to the config.sub installed by autoreconf/automake."""
        cs = os.path.join(self.source_folder, "config.sub")
        if not os.path.isfile(cs):
            return
        content = open(cs, encoding="utf-8", errors="replace").read()
        if "linux-ohos" in content:
            return
        content = content.replace(
            "| linux-newlib* | linux-musl* | linux-uclibc* | uclinux-uclibc*",
            "| linux-newlib* | linux-musl* | linux-uclibc* | linux-ohos* | uclinux-uclibc*",
        )
        content = content.replace(
            "| linux-newlib* | linux-musl* | linux-uclibc* \\\n",
            "| linux-newlib* | linux-musl* | linux-uclibc* | linux-ohos* \\\n",
        )
        open(cs, "w", encoding="utf-8").write(content)
        self.output.info("config.sub: appended linux-ohos recognition")

    def _fix_configure_umask(self):
        """HMDFS rejects writes into 0700 tmp dirs created by config.status
        (E112/E114). Rewrite `umask 077` -> `umask 022` in generated configure."""
        cfg = os.path.join(self.source_folder, "configure")
        if not os.path.isfile(cfg):
            return
        content = open(cfg, encoding="utf-8", errors="replace").read()
        if "umask 077" not in content:
            return
        content = content.replace("umask 077", "umask 022")
        open(cfg, "w", encoding="utf-8").write(content)
        self.output.info("configure: umask 077 -> 022 (HMDFS tmp dir fix)")

    def _stage_glib_mkenums(self):
        """glib-mkenums shebang is /usr/bin/perl which does not exist on OHOS.
        Copy the script into the build tree (the copy keeps the executable
        bit on HMDFS) and rewrite its shebang to the real perl interpreter,
        then hand configure/make the single staged path (a space-separated
        "perl script" value would break prerequisite lists in Makefile).
        """
        import stat
        candidates = [
            shutil.which("glib-mkenums") or "",
            os.path.join(
                self.dependencies["glib"].package_folder, "bin", "glib-mkenums"
            ),
        ]
        source = next((c for c in candidates if c and os.path.isfile(c)), None)
        if not source:
            self.output.warning("glib-mkenums not found; leaving default")
            return "glib-mkenums"
        perl = shutil.which("perl")
        if not perl:
            self.output.warning("perl not found; leaving glib-mkenums as-is")
            return "glib-mkenums"
        tools_dir = os.path.join(self.build_folder, ".glib-tools")
        os.makedirs(tools_dir, exist_ok=True)
        staged = os.path.join(tools_dir, "glib-mkenums")
        if not os.path.isfile(staged):
            shutil.copy2(source, staged)
            with open(staged, encoding="utf-8", errors="replace") as handle:
                lines = handle.readlines()
            if lines and lines[0].startswith("#!"):
                lines[0] = f"#!{perl}\n"
            with open(staged, "w", encoding="utf-8") as handle:
                handle.writelines(lines)
            try:
                os.chmod(staged, os.stat(staged).st_mode | stat.S_IEXEC)
            except OSError:
                # copy2 already preserved the exec bit; chmod is best-effort
                pass
        return staged

    def _patch_glib_pc_lintl(self):
        """glib's proxy-libintl exports g_libintl_* symbols through its
        libintl.so; PkgConfigDeps emits glib-2.0.pc without -lintl, so the
        lasem-render CLI link fails with undefined g_libintl_* symbols.
        Append -lintl to the Libs line (same approach as gdk-pixbuf recipe)."""
        pc = os.path.join(self.generators_folder, "glib-2.0.pc")
        if not os.path.isfile(pc):
            return
        with open(pc, encoding="utf-8") as handle:
            content = handle.read()
        if re.search(r"^Libs:.*-lintl", content, flags=re.M):
            return
        if re.search(r"^Libs:", content, flags=re.M):
            content = re.sub(
                r"^Libs:.*$", lambda m: m.group(0) + " -lintl", content, count=1, flags=re.M
            )
        with open(pc, "w", encoding="utf-8") as handle:
            handle.write(content)
        self.output.info("glib-2.0.pc: appended -lintl to Libs (proxy-libintl symbols)")

    # ------------------------------------------------------------------

    def generate(self):
        PkgConfigDeps(self).generate()
        self._patch_glib_pc_lintl()
        tc = AutotoolsToolchain(self)
        if not self.options.shared:
            tc.configure_args.append("--enable-static")
            tc.configure_args.append("--disable-shared")
        # Cross-build: explicit triplets skip config.guess detection of the
        # build host (aarch64 OHOS reports as aarch64-unknown-linux-ohos).
        tc.configure_args.append("--build=aarch64-linux")
        tc.configure_args.append("--host=aarch64-linux-ohos")
        tc.configure_args.append("--disable-gtk-doc")
        tc.generate()

    def _autoreconf(self):
        """Regenerate the build system (tag archive ships no configure).

        Runs the autoreconf chain step-by-step with tool_requires-provided
        automake/libtool (their package_info exports $ACLOCAL/$AUTOMAKE/
        $LIBTOOLIZE as absolute paths in the conanbuild env — bare `aclocal`
        is NOT on the CI sandbox PATH, CI-measured "Can't exec aclocal").
        autoconf/autoheader come from hnp (build profile PATH) — the local
        automake hard-codes /usr/local/bin/autoconf which does not exist, so
        AUTOCONF/AUTOHEADER/AUTOM4TE are exported explicitly. ACLOCAL_PATH
        additionally exposes hnp pkg-config's pkg.m4 (PKG_CHECK_MODULES);
        the tag archive's own m4/ covers libtool/introspection and patch 0001
        removes every other external macro.

        The full `autoreconf -fi` driver is avoided on purpose: on HMDFS the
        autoreconf chain hits autoconf.m4f load conflicts (same reasoning as
        the abiword-plugin recipes, which run the same stepwise chain).
        """
        aclocal_dirs = ["/data/service/hnp/pkg-config.org/pkg-config_0.29.2/share/aclocal"]
        existing = os.environ.get("ACLOCAL_PATH", "")
        if existing:
            aclocal_dirs.append(existing)
        prefix = (
            "export AUTOCONF=/data/service/hnp/bin/autoconf; "
            "export AUTOHEADER=/data/service/hnp/bin/autoheader; "
            "export AUTOM4TE=/data/service/hnp/bin/autom4te; "
            f'export ACLOCAL_PATH={":".join(aclocal_dirs)}; '
        )
        # Upstream autogen.sh synthesizes an empty gtk-doc.make when gtkdocize
        # is unavailable (tag archive ships none; docs/reference Makefile.am
        # includes it unconditionally at automake parse time even though the
        # reference subdir is gated behind BUILD_GTK_DOC=false).
        gtkdoc_make = os.path.join(self.source_folder, "gtk-doc.make")
        if not os.path.isfile(gtkdoc_make):
            with open(gtkdoc_make, "w", encoding="utf-8") as handle:
                handle.write("EXTRA_DIST =\n")
            self.output.info("synthesized empty gtk-doc.make (no gtkdocize on OHOS)")
        # Stepwise chain (each tool resolved via $VARS from tool_requires or
        # hnp; --force/--install mirror `autoreconf -fi`). libtoolize runs
        # FIRST so that m4/libtool.m4 is in place before aclocal scans,
        # otherwise automake reports "LIBTOOL is undefined":
        #   libtoolize -> aclocal -> autoconf -> autoheader -> automake
        self.run(
            prefix
            + 'set -e; '
            + '"$LIBTOOLIZE" --force --copy; '
            + '"$ACLOCAL" --force --install -I m4; '
            + 'autoconf --force; '
            + 'autoheader --force; '
            + '"$AUTOMAKE" --add-missing --foreign --copy --force-missing; '
            # GNU standard INSTALL doc is referenced by the top Makefile's
            # all-am but --add-missing skips it when absent — provide it.
            + 'test -f INSTALL || printf "Building this package requires GNU '
            'autotools; see README for details.\\n" > INSTALL; ',
            cwd=self.source_folder,
            env="conanbuild",
        )

    def _fix_makefile_mkenums(self, staged):
        """configure bakes the probed glib-mkenums path (bad shebang) into
        src/Makefile. Replace it with the staged working copy after configure,
        before make."""
        makefile = os.path.join(self.build_folder, "src", "Makefile")
        if not os.path.isfile(makefile):
            return
        with open(makefile, encoding="utf-8", errors="replace") as handle:
            content = handle.read()
        updated = re.sub(
            r"^GLIB_MKENUMS = .*$",
            f"GLIB_MKENUMS = {staged}",
            content,
            count=1,
            flags=re.M,
        )
        if updated != content:
            with open(makefile, "w", encoding="utf-8") as handle:
                handle.write(updated)
            self.output.info(f"src/Makefile: GLIB_MKENUMS -> {staged}")

    def _dependency_libdirs(self):
        """All dependency lib dirs (for LD_LIBRARY_PATH when running the
        upstream test binaries — they link against shared conan packages
        that the dynamic loader cannot find otherwise)."""
        dirs = []
        for _, dep in self.dependencies.items():
            if not dep.package_folder:
                continue
            for libdir in dep.cpp_info.libdirs:
                d = os.path.join(dep.package_folder, libdir)
                if d not in dirs:
                    dirs.append(d)
        return dirs

    def build(self):
        apply_conandata_patches(self)
        # 1) Regenerate the build system (tag archive ships no configure).
        #    Must run inside the source tree; self.run defaults to the build
        #    folder which is empty at this point (basic_layout src_folder=".").
        self._autoreconf()
        # 2) Fix generated artifacts for OHOS/HMDFS.
        self._fix_config_sub()
        self._fix_configure_umask()
        # 3) Configure + build.
        autotools = Autotools(self)
        autotools.configure()
        mkenums = self._stage_glib_mkenums()
        self._fix_makefile_mkenums(mkenums)
        autotools.make(args=["-j2", f"GLIB_MKENUMS={mkenums}"])
        # 4) Upstream test suite (dom/str/filter/suite via gtester). The test
        #    binaries link shared conan deps — inject their libdirs into
        #    LD_LIBRARY_PATH so the loader resolves glib/cairo/pango symbols.
        libdirs = self._dependency_libdirs()
        ld_path = ":".join(libdirs)
        self.run(
            f'export LD_LIBRARY_PATH="{ld_path}:$LD_LIBRARY_PATH"; '
            f'cd "{self.build_folder}" && make check -k SHELL=/bin/sh '
            f'GLIB_MKENUMS="{mkenums}"',
            env="conanbuild",
        )

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        self._sign_shared_libs()

    def _sign_shared_libs(self):
        """OHOS requires .so codesign sections (see pango/cairo recipes)."""
        libdir = os.path.join(self.package_folder, "lib")
        sos = glob.glob(os.path.join(libdir, "**", "*.so"), recursive=True)
        sos += glob.glob(os.path.join(libdir, "**", "*.so.*"), recursive=True)
        if not sos:
            return
        candidates_objcopy = [
            "/data/service/hnp/bin/llvm-objcopy",
            shutil.which("llvm-objcopy") or "",
        ]
        ce = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict) or {}
        cc = ce.get("c") or ""
        if cc:
            candidates_objcopy.insert(0, os.path.join(os.path.dirname(cc), "llvm-objcopy"))
        objcopy = next((p for p in candidates_objcopy if p and os.path.isfile(p)), None)
        signer = "/data/service/hnp/bin/binary-sign-tool"
        if not os.path.isfile(signer):
            self.output.warning("binary-sign-tool not found; skip OHOS codesign (cross/SDK env)")
            return
        for so in sos:
            if objcopy:
                self.run('{oc} --remove-section .codesign "{f}" 2>/dev/null || true'.format(oc=objcopy, f=so))
            self.run('{sg} sign -inFile "{f}" -outFile "{f}" -selfSign 1'.format(sg=signer, f=so))

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "lasem")
        self.cpp_info.set_property("pkg_config_name", "lasem-0.6-unofficial")
        self.cpp_info.libs = ["lasem-0.6"]
        # Headers install to include/lasem-0.6/lasem*.h
        self.cpp_info.includedirs = ["include", "include/lasem-0.6"]
        # lasem's public headers include <glib-object.h> / <gio/gio.h> /
        # <cairo.h> — propagate consumer requirements. gdk-pixbuf's recipe
        # defines no components (plain cpp_info.libs), so its default
        # component is the package name itself.
        self.cpp_info.requires = [
            "glib::glib-2.0",
            "glib::gobject-2.0",
            "glib::gio-2.0",
            "cairo::cairo",
            "pango::pangocairo",
            "harfbuzz::harfbuzz",
            "gdk-pixbuf::gdk-pixbuf",
            "libxml2::libxml2",
        ]
        if self.settings.os in ("Linux", "OHOS"):
            self.cpp_info.system_libs = ["m"]
