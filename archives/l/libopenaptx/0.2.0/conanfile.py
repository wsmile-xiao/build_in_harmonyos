#!/usr/bin/env python3
"""Conan recipe for libopenaptx 0.2.0 — Open Source aptX codec library.

libopenaptx (Pali Rohar) is derived from ffmpeg 4.0's aptX implementation and
provides:
  - libopenaptx.so / libopenaptx.a — the codec (aptX and aptX HD variants);
  - openaptxenc / openaptxdec — command line codec utilities (R38:
    commands.json declared at software level);
  - libopenaptx.pc — pkg-config file generated by `make install`.

The build is a plain Makefile (no configure step); it builds both the shared
and the static library plus the utilities.  `make install` honours PREFIX and
generates the .pc file, so packaging drives it with PREFIX=<package_folder>.

No external dependencies.  No patches required: the Makefile honours CC/AR
overrides and builds cleanly with the OHOS clang toolchain.
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class LibopenaptxConan(ConanFile):
    name = "libopenaptx"
    version = "0.2.0"
    description = "Open Source aptX codec library (aptX / aptX HD) with openaptxenc/openaptxdec utilities"
    license = "LGPL-2.1-or-later"
    homepage = "https://github.com/pali/libopenaptx"
    url = ""  # CI fills

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            self.options.rm_safe("fPIC")

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def validate(self):
        # R32: settings.os must check in ("Linux", "OHOS")
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"libopenaptx is only supported on Linux/OHOS, not {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)
        # The Makefile works fully in-tree (no VPATH support)
        self.folders.build = "."

    def export_sources(self):
        export_conandata_patches(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def build(self):
        # Upstream default CFLAGS (-W -Wall -O3) and LDFLAGS (-s) are used as
        # is; only the tool is overridden (there is no `cc` on OHOS).
        # R9: -j1 — parallel make hits the HMDFS jobserver fifo EPERM (E074).
        cc = os.environ.get("CC", "clang")
        ar = os.environ.get("AR", "llvm-ar")
        self.run(f"make -j1 CC='{cc}' AR='{ar}'")

    def package(self):
        # `make install` honours PREFIX and generates libopenaptx.pc with
        # prefix=<PREFIX>; DESTDIR is left empty so files land directly in
        # the package folder.
        prefix = self.package_folder.replace("\\", "/")
        self.run(f"make install PREFIX='{prefix}'")
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.libs = ["openaptx"]
        self.cpp_info.bindirs = ["bin"]
