#!/usr/bin/env python3
"""Conan recipe for libobjfwtls1 1.5.7 - ObjFW's TLS library (OpenSSL backend).

Builds the whole ObjFW source tree (Autotools), which produces libobjfw,
libobjfwrt and libobjfwtls. TLS support is enabled explicitly via
--with-tls=openssl against the published openssl/3.5.8.1 package: ObjFW's
configure probes openssl/ssl.h + -lssl/-lcrypto with plain -l flags, so
AutotoolsDeps injects the conan OpenSSL include/lib paths into the build.
"""
from conan import ConanFile
from conan.errors import ConanInvalidConfiguration, ConanException
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout

import json
import os
import re
import shutil
import socket
import stat


class Libobjfwtls1Conan(ConanFile):
    name = "libobjfwtls1"
    version = "1.5.7"
    description = "ObjFWTLS - ObjFW's TLS library (Objective-C, OpenSSL backend)"
    license = "LGPL-3.0"
    homepage = "https://objfw.nil.im/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # OpenSSL backend for ObjFWTLS (openssl/3.5.8.1 is published, W0 ok).
        self.requires("openssl/3.5.8.1")

    def configure(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"libobjfwtls1 supports Linux/OHOS targets, got {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)
        # ObjFW's Makefiles at every level (top/src/tests/utils) ship inside
        # the release tarball as static files, not generated by automake or
        # configure, so the build must run in-source. Otherwise the
        # out-of-tree build directory has no Makefile ("No targets specified
        # and no makefile found"). Same shape as the other in-source
        # autotools recipes in this repo.
        self.folders.build = "."

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Explicit OpenSSL backend: configure probes openssl/ssl.h plus
        # -lssl/-lcrypto, whose include/lib paths come from the conan
        # openssl package via AutotoolsDeps below. Explicit selection (rather
        # than configure's "yes" auto-probe) fails loudly if OpenSSL is not
        # found instead of silently building a TLS-less tree.
        tc.configure_args.append("--with-tls=openssl")
        if not self.options.shared:
            tc.configure_args.append("--enable-static")
            tc.configure_args.append("--disable-shared")
        tc.generate()
        # Inject the openssl dependency's -I/-L/-l into configure so the
        # AC_CHECK_HEADER(openssl/ssl.h) / AC_CHECK_LIB(ssl) probes succeed.
        AutotoolsDeps(self).generate()

    def _restore_autotools_helper_modes(self):
        # objfw-1.5.7.tar.gz carries build-aux/config.guess and
        # build-aux/config.sub without the executable bit, so configure's
        # system detection fails with "Permission denied" after extraction.
        # chmod +x the known helpers one by one (no chmod -R +x, which would
        # hide metadata problems). `missing` does not exist in this source
        # tree; the exists guard skips it quietly.
        helpers = ["configure", "config.guess", "config.sub", "install-sh", "missing"]
        for base in (self.source_folder, os.path.join(self.source_folder, "build-aux")):
            for name in helpers:
                path = os.path.join(base, name)
                if os.path.exists(path):
                    mode = os.stat(path).st_mode
                    os.chmod(path, mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    def _probe_tmp_capability(self, path):
        # Probe one tmp dir for the two platform sub-capabilities the 4
        # OFTests skips depend on: hardlink() and AF_UNIX bind(). Returns
        # (writable, hardlink_ok, unix_ok). All probes are best-effort and
        # clean up after themselves; any OSError means "not capable".
        writable, hardlink_ok, unix_ok = False, False, False
        try:
            probe = os.path.join(path, ".w")
            with open(probe, "w", encoding="utf-8") as f:
                f.write("w")
            os.remove(probe)
            writable = True
        except OSError:
            return (False, False, False)
        try:
            src = os.path.join(path, ".hmbs_hl_a")
            dst = os.path.join(path, ".hmbs_hl_b")
            for p in (src, dst):
                try:
                    os.remove(p)
                except OSError:
                    pass
            with open(src, "w", encoding="utf-8") as f:
                f.write("h")
            os.link(src, dst)
            hardlink_ok = os.path.isfile(dst)
        except OSError:
            hardlink_ok = False
        finally:
            for p in (os.path.join(path, ".hmbs_hl_a"),
                      os.path.join(path, ".hmbs_hl_b")):
                try:
                    os.remove(p)
                except OSError:
                    pass
        try:
            sock_path = os.path.join(path, ".hmbs_sk")
            try:
                os.remove(sock_path)
            except OSError:
                pass
            s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
            try:
                s.bind(sock_path)
                unix_ok = True
            finally:
                s.close()
        except OSError:
            unix_ok = False
        finally:
            try:
                os.remove(os.path.join(path, ".hmbs_sk"))
            except OSError:
                pass
        return (writable, hardlink_ok, unix_ok)

    def _short_tmp_for_unix_sockets(self):
        # HMBS injects a long TMPDIR
        # (/storage/.../runtime/libobjfwtls1-1.5.7/tmp, ~90 chars). ObjFW's
        # OFUNIX*SocketTests build their socket path as
        # temporaryDirectoryIRI + "/" + UUID(36) (OFSystemInfo prefers
        # XDG_RUNTIME_DIR, then TMPDIR, then /tmp). 90+1+36 overflows
        # sockaddr_un.sun_path (108) so OFSocketAddressMakeUNIX throws
        # OFOutOfRangeException ("Value out of range!"), which the tests do
        # NOT catch (they only skip on EAFNOSUPPORT/EPERM) -> 3 failures
        # where the sister --without-tls package skipped the same 3 tests.
        # Fix: point TMPDIR/TMP/TEMP+XDG_RUNTIME_DIR at a short writable dir
        # for the whole build; only the temp root is replaced, no test is
        # skipped or deleted.
        # E446 fallback (move-test-root-to-link-capable-filesystem):
        # HMBS reports HMBS_CAP_HARDLINK=0 on the injected /storage (HMDFS)
        # tmp, and HMDFS also rejects AF_UNIX socket nodes, so the 4th skip
        # (hardlink) plus the 3 socket skips persist even with a short
        # HMDFS path. Prefer a short dir on the link-capable local
        # filesystem (/data/local/tmp) when it is writable AND passes the
        # hardlink + AF_UNIX bind probes above; that turns the 4
        # platform-capability skips into real passes without touching any
        # test. HOME-based HMDFS dirs stay as fallback only.
        candidates = ["/data/local/tmp/hmbs-socktmp"]
        home = os.path.expanduser("~")
        if home and os.path.isabs(home):
            candidates.append(os.path.join(home, ".hmbs-socktmp"))
        for env_key in ("TMPDIR", "TMP", "TEMP"):
            base = os.environ.get(env_key)
            if base:
                cand = os.path.join(base, "socktmp-short")
                if cand not in candidates:
                    candidates.append(cand)
        first_writable = None
        for path in candidates:
            try:
                if len(path) + 38 >= 100:
                    continue
                os.makedirs(path, exist_ok=True)
            except OSError:
                continue
            writable, hardlink_ok, unix_ok = self._probe_tmp_capability(path)
            self.output.info(
                f"libobjfwtls1: tmp cap probe {path}: "
                f"writable={writable} hardlink={hardlink_ok} unix={unix_ok}"
            )
            if not writable:
                continue
            if first_writable is None:
                first_writable = path
            if hardlink_ok and unix_ok:
                for var in ("TMPDIR", "TMP", "TEMP", "XDG_RUNTIME_DIR"):
                    os.environ[var] = path
                self.output.info(
                    f"libobjfwtls1: short link-capable tmp for tests: {path}"
                )
                return path
        if first_writable is not None:
            for var in ("TMPDIR", "TMP", "TEMP", "XDG_RUNTIME_DIR"):
                os.environ[var] = first_writable
            self.output.warning(
                f"libobjfwtls1: no link-capable short tmp found, "
                f"keep writable {first_writable} (4 platform skips may remain)"
            )
            return first_writable
        # Fallback: keep HMBS values (build will show the real error).
        fallback = os.environ.get("TMPDIR", "/tmp")
        self.output.warning(
            f"libobjfwtls1: no short writable tmp found, keep {fallback}"
        )
        return fallback

    def _emit_upstream_result(self, result):
        line = "HMBS_UPSTREAM_TEST_RESULT=" + json.dumps(
            result, ensure_ascii=False
        )
        self.output.info(line)
        try:
            print(line, flush=True)
        except Exception:
            pass
        try:
            with open(
                os.path.join(str(self.build_folder), "hmbs_upstream.json"),
                "w",
                encoding="utf-8",
                newline="\n",
            ) as f:
                f.write(json.dumps(result, ensure_ascii=False))
        except OSError as exc:
            self.output.warning(f"persist hmbs_upstream.json failed: {exc!r}")

    def build(self):
        # Short writable tmp first: fixes both readonly /tmp and the
        # overlong HMBS TMPDIR that overflows sockaddr_un (see helper).
        short_tmp = self._short_tmp_for_unix_sockets()
        apply_conandata_patches(self)
        # Restore autotools helper executable bits before configure, otherwise
        # system detection fails with Permission denied.
        self._restore_autotools_helper_modes()
        # DRAFT-6487 / cvsgraph hnp-bash-getcwd: the ohos-aarch64 profile
        # [buildenv] injects CONFIG_SHELL=/data/service/hnp/bin/bash, which
        # fails inside the conan HMDFS build dir (configure[139]:
        # "/data/service/hnp/bin/bash: inaccessible or not found"). The
        # buildenv aggregate wins over toolchain env, so the override must be
        # an inline command-line assignment (akku/cursynth/dico precedent)
        # plus an explicit `sh` invocation (also dodges HMDFS shebang-exec
        # refusal). env="conanbuild" still provides CC/CFLAGS/CPPFLAGS and
        # the openssl -I/-L from AutotoolsDeps. Keep args in sync with
        # generate() above (--with-tls plus static toggles) and with the
        # Autotools defaults (--prefix=/ + bindir/sbindir/libdir/includedir).
        configure_path = os.path.join(self.source_folder, "configure")
        if not os.path.isfile(configure_path):
            configure_path = os.path.join(self.build_folder, "configure")
        extra_args = ["--with-tls=openssl"]
        if not self.options.shared:
            extra_args.append("--enable-static")
            extra_args.append("--disable-shared")
        self.run(
            f'CONFIG_SHELL=/bin/sh SHELL=/bin/sh sh "{configure_path}" '
            f"--prefix=/ '--bindir=${{prefix}}/bin' '--sbindir=${{prefix}}/bin' "
            f"'--libdir=${{prefix}}/lib' '--includedir=${{prefix}}/include' "
            f"'--oldincludedir=${{prefix}}/include' {' '.join(extra_args)}",
            env="conanbuild",
        )
        autotools = Autotools(self)
        # Serialize the build: make -jN jobserver mkfifo under TMPDIR reports
        # "Operation not permitted" on HMDFS, same as the other autotools
        # recipes in this repo. SHELL=/bin/sh keeps make/config.status off
        # the broken hnp bash baked via CONFIG_SHELL.
        autotools.make(args=["-j1", "SHELL=/bin/sh"])
        # Verify the TLS lib was actually built in-tree. If configure silently
        # built a TLS-less tree (openssl probes missed), src/tls/ holds no
        # libobjfwtls.* and the later package would lack it -> the observed
        # CMakeDeps "Library 'objfwtls' not found" failure. Fail loudly here
        # with a build-tree listing instead of shipping a broken package.
        try:
            hits = []
            for root, _, files in os.walk(str(self.build_folder)):
                for fn in files:
                    if fn.startswith("libobjfwtls.") and (
                        fn.endswith(".a") or ".so" in fn
                    ):
                        hits.append(os.path.join(root, fn))
            self.output.info(f"libobjfwtls1: built TLS lib hits: {hits}")
            if not hits:
                # Also surface configure's TLS verdict for the log.
                clog = ""
                try:
                    with open(
                        os.path.join(str(self.build_folder), "config.log"),
                        "r",
                        encoding="utf-8",
                        errors="replace",
                    ) as f:
                        data = f.read()
                    idx = data.find("TLS")
                    clog = data[max(0, idx - 500): idx + 1500] if idx >= 0 else data[-1500:]
                except OSError:
                    pass
                raise ConanException(
                    "libobjfwtls was not built in-tree (no libobjfwtls.a/.so "
                    "under build folder); TLS backend likely disabled. "
                    f"config.log excerpt: {clog[:1500]!r}"
                )
        except ConanException:
            raise
        except OSError as exc:
            self.output.warning(f"libobjfwtls1: TLS build check failed: {exc!r}")
        # Run the upstream suite inside build(): ObjFW's self-made OFTests
        # framework (single tests binary driven by `make check`, offline-safe:
        # HTTP client tests use a local 127.0.0.1 server). Same convention as
        # the libobjfwhid1 sister recipe. Tee to a log file so the
        # "N tests succeeded, M failed, K skipped" summary can be parsed
        # into the HMBS_UPSTREAM_TEST_RESULT machine marker; tee (not `>`
        # + trailing `cat`) keeps genuine lines on preflight stdout live.
        # Explicit TMPDIR/TMP/TEMP/XDG_RUNTIME_DIR prefix: env="conanbuild"
        # filters the outer environment, so the short tmp must ride on the
        # command line itself (ext4fuse precedent).
        check_log = os.path.join(str(self.build_folder), "hmbs_make_check.log")
        # Live-stream via tee (not `> log` + trailing `cat`): `> log` leaves
        # stdout silent for the whole OFTests run (~1200 cases), so the idle
        # SSH session is closed by the remote host ("Connection closed")
        # before the summary is ever printed. `| tee` keeps genuine test
        # lines flowing to preflight stdout (keep-alive) while still
        # capturing the file for summary parsing. Exit status is recovered
        # from the parsed summary below, so pipefail/PIPESTATUS (bash-only)
        # is intentionally not required here.
        self.run(
            f'TMPDIR="{short_tmp}" TMP="{short_tmp}" TEMP="{short_tmp}" '
            f'XDG_RUNTIME_DIR="{short_tmp}" '
            f'make check -j1 SHELL=/bin/sh 2>&1 | tee "{check_log}"',
            cwd=str(self.build_folder),
            env="conanbuild",
        )
        content = ""
        try:
            with open(check_log, "r", encoding="utf-8", errors="replace") as f:
                content = f.read()
        except OSError as exc:
            raise ConanException(f"cannot read make check log: {exc!r}")
        match = re.search(
            r"(\d+)\s+tests?\s+succeeded,\s*(\d+)\s+tests?\s+failed,\s*"
            r"(\d+)\s+tests?\s+skipped",
            content,
        )
        if not match:
            raise ConanException(
                "cannot parse upstream summary "
                "('N tests succeeded, M failed, K skipped') from make check log"
            )
        passed, failed, skipped = map(int, match.groups())
        discovered = passed + failed + skipped
        # rule4 identities: passed + failed == executed,
        # executed + skipped <= discovered, executed <= discovered.
        # Skipped tests were discovered but not executed, so executed is
        # passed + failed (not discovered). Previous round emitted
        # executed=discovered with skipped>0 (1242/1242/1238/0/4), which
        # violates both identities (1238+0 != 1242, 1242+4 > 1242).
        executed = passed + failed
        # rule4 status semantics: "passed" requires 100% (discovered ==
        # passed). Any gap (skip or failure) must not claim "passed"
        # (preflight 12:36 rejected 1242/1238/1238/0/4 with status=passed
        # as "passed 状态与上游结果矛盾"). failed>0 -> "failed";
        # skip-only partial -> "incomplete" (libm2k precedent: partial run
        # with gaps uses "incomplete", "skipped" is reserved for
        # executed==0). Single source is the summary regex above.
        if failed != 0:
            _status = "failed"
        elif discovered != passed:
            _status = "incomplete"
        else:
            _status = "passed"
        result = {
            "status": _status,
            "framework": "OFTests (make check)",
            "command": "make check -j1 SHELL=/bin/sh",
            "discovered": discovered,
            "executed": executed,
            "passed": passed,
            "failed": failed,
            "skipped": skipped,
        }
        if discovered != passed:
            # Log-grounded skip/failure attribution (no counting-scope change:
            # counts still come from the summary regex above). The previous
            # hardcoded reason asserted the sister-package shape without
            # quoting this run's log; instead, quote the actual skip lines
            # so the next preflight shows which tests skipped and why.
            # OFTests prints per-test skip notices; match them tolerantly
            # (format varies by test) and cap length so the marker stays
            # small. Gaps cover every non-pass case so that
            # sum(gaps.count) == discovered - passed even when failed > 0
            # (the old `failed == 0 and skipped` guard left failed>0 runs
            # without gaps and tripped the self-check assert below).
            skip_lines = []
            for line in content.splitlines():
                low = line.lower()
                if "skip" in low and ("test" in low or "unix" in low
                                      or "socket" in low or "link" in low
                                      or "hardlink" in low):
                    s = line.strip()
                    if s and s not in skip_lines:
                        skip_lines.append(s[:200])
                    if len(skip_lines) >= 8:
                        break
            for s in skip_lines:
                self.output.info(f"libobjfwtls1: upstream skip: {s}")
            self.output.info(
                f"libobjfwtls1: tmp cap at check time: TMPDIR="
                f"{os.environ.get('TMPDIR', '')} short_tmp={short_tmp}"
            )
            if skip_lines:
                result["reason"] = (
                    f"platform-capability skips ({skipped} skipped, "
                    f"{failed} failed, no test deleted): "
                    + " | ".join(skip_lines[:4])[:600]
                )
            else:
                result["reason"] = (
                    f"platform-capability skips ({skipped} skipped, "
                    f"{failed} failed, no test deleted; no per-test skip "
                    f"line matched in make check log, "
                    f"summary={passed}/{failed}/{skipped})"
                )
            # rule4 gaps: sum(gaps.count) must equal discovered - passed.
            # Skipped entries are upstream self-skips on platform
            # capabilities (hardlink + AF_UNIX), no test deleted, no missing
            # dependency. Failed entries (if any) use test_failure so the
            # marker never hides a real regression.
            evidence = " | ".join(skip_lines[:4])[:600] if skip_lines else (
                f"hmbs_make_check.log summary {passed} succeeded, "
                f"{failed} failed, {skipped} skipped"
            )
            gaps = []
            if skipped:
                gaps.append({
                    "count": int(skipped),
                    "category": "ohos_feature",
                    "detail": "OFTests platform-capability self-skips, no test "
                              "deleted: OFFileManager hardlink branch (Links not "
                              "supported) + OFUNIX*Socket branches (UNIX sockets "
                              "unsupported on HMDFS tmp)",
                    "evidence": evidence,
                })
            if failed:
                gaps.append({
                    "count": int(failed),
                    "category": "test_failure",
                    "detail": "OFTests reported failures; see hmbs_make_check.log "
                              "for the failing test names (no test deleted)",
                    "evidence": evidence,
                })
            result["gaps"] = gaps
        # Pre-emit self-check of rule4 identities; fix the source, never the
        # numbers. Single source is the summary regex above.
        assert isinstance(discovered, int) and discovered >= 0
        assert isinstance(executed, int) and executed >= 0
        assert passed + failed == executed, (passed, failed, executed)
        assert executed + skipped <= discovered, (executed, skipped, discovered)
        assert executed <= discovered
        if discovered != passed:
            assert "gaps" in result, "non-100% pass requires gaps"
            assert sum(g["count"] for g in result["gaps"]) == discovered - passed
        self._emit_upstream_result(result)
        if failed != 0:
            raise ConanException(f"upstream tests failed: {result}")

    def package(self):
        autotools = Autotools(self)
        autotools.install(args=["SHELL=/bin/sh"])
        # Diagnose the packaged lib dir: the test_package CMake failure
        # ("Library 'objfwtls' not found in package") means make install did
        # not place libobjfwtls.a/.so into package lib/. Log the actual
        # content so the next preflight shows what was installed.
        try:
            libdir = os.path.join(self.package_folder, "lib")
            names = sorted(os.listdir(libdir)) if os.path.isdir(libdir) else []
            self.output.info(f"libobjfwtls1: package lib/ content: {names}")
        except OSError as exc:
            self.output.warning(f"libobjfwtls1: list package lib failed: {exc!r}")
            names = []
        # Fallback: `make install` did not place any .a into package lib/
        # (preflight showed lib/ == ['cmake', 'objfw-config'] before the
        # TLS-only fallback, i.e. libobjfw/libobjfwrt were missing too, so
        # CMakeDeps fails with "Library 'objfw' not found"). Copy every
        # missing declared lib from the in-source build tree instead of
        # only libobjfwtls. Search both the build and source trees for
        # lib<name>.a / .so* / .dylib (in-source layout keeps artifacts in
        # either root depending on how conan maps folders.build) and copy
        # the best candidate per missing lib. This keeps the declared
        # cpp_info.libs truthful (no silent lib drop). Any lib still
        # missing after the search fails fast here with a full listing
        # instead of surfacing later as a cryptic CMakeDeps error.
        from conan.tools.files import copy as _copy2

        def _rank(p):
            if not self.options.shared and p.endswith(".a"):
                return 0
            if self.options.shared and ".so" in p:
                return 0
            return 1

        search_roots = []
        for _root in (str(self.build_folder), str(self.source_folder)):
            if _root and os.path.isdir(_root) and _root not in search_roots:
                search_roots.append(_root)
        self.output.info(
            f"libobjfwtls1: fallback search roots: {search_roots}"
        )
        still_missing = []
        for libname in ("objfwtls", "objfw", "objfwrt"):
            try:
                cur = sorted(os.listdir(libdir)) if os.path.isdir(libdir) else []
            except OSError:
                cur = []
            if any(n == f"lib{libname}.a" or n.startswith(f"lib{libname}.so") for n in cur):
                continue
            self.output.warning(
                f"libobjfwtls1: lib{libname}.* missing in package lib/, "
                "searching build/source trees for fallback copy"
            )
            candidates = []
            for _sroot in search_roots:
                for root, _, files in os.walk(_sroot):
                    for fn in files:
                        if fn.startswith(f"lib{libname}.") and (
                            fn.endswith(".a")
                            or ".so" in fn
                            or fn.endswith(".dylib")
                        ):
                            candidates.append(os.path.join(root, fn))
            candidates.sort(key=_rank)
            self.output.info(
                f"libobjfwtls1: search-roots {libname} candidates: {candidates}"
            )
            if candidates:
                src = candidates[0]
                self.output.info(f"libobjfwtls1: fallback copy {src} -> lib/")
                _copy2(
                    self,
                    os.path.basename(src),
                    src=os.path.dirname(src),
                    dst=os.path.join(self.package_folder, "lib"),
                )
            else:
                still_missing.append(libname)
                self.output.warning(
                    f"libobjfwtls1: no built lib{libname}.* found under "
                    f"{search_roots}; package would lack it"
                )
        names2 = []
        try:
            names2 = sorted(os.listdir(libdir)) if os.path.isdir(libdir) else []
            self.output.info(
                f"libobjfwtls1: package lib/ after fallback: {names2}"
            )
        except OSError:
            pass
        if still_missing:
            try:
                _tree = []
                for _r, _ds, _fs in os.walk(os.path.join(self.package_folder, "lib")):
                    for _fn in sorted(_fs):
                        _tree.append(os.path.relpath(os.path.join(_r, _fn), self.package_folder))
            except OSError:
                _tree = []
            raise ConanException(
                f"libobjfwtls1: cannot package declared lib(s) {still_missing}; "+
                f"searched {search_roots}, package lib/={names2}, tree={_tree[:40]}" +
                "refusing a broken package (CMakeDeps would fail downstream)"
            )
        # Header fallback: `make install` placed (practically) nothing into
        # the package (preflight lib/ == ['cmake', 'objfw-config'] before the
        # lib fallback; test_package then fails with
        # "fatal error: 'ObjFW/ObjFW.h' file not found"). Mirror upstream's
        # own install mapping (buildsys.mk INCLUDES/includesubdir):
        #   src/*.h + src/exceptions/*.h -> include/ObjFW/
        #   (umbrella ObjFW.h uses only quoted sibling imports, and the
        #   generic TLS headers OFTLSStream.h/OFX509Certificate.h/OFTLSKey.h
        #   live in src/ root)
        #   src/tls/ObjFWTLS.h     -> include/ObjFWTLS/
        #   src/runtime/ObjFWRT.h  -> include/ObjFWRT/
        # Only missing files are topped up; source roots go first so that
        # build-tree copies (generated headers like objfw-defs.h) win.
        # Fail fast if an umbrella is still missing afterwards.
        _incdir = os.path.join(self.package_folder, "include")
        try:
            _inc_top = sorted(os.listdir(_incdir)) if os.path.isdir(_incdir) else []
            self.output.info(f"libobjfwtls1: package include/ content: {_inc_top}")
        except OSError as exc:
            self.output.warning(f"libobjfwtls1: list package include failed: {exc!r}")
        _umbrellas = (
            ("ObjFW", "ObjFW.h"),
            ("ObjFWTLS", "ObjFWTLS.h"),
            ("ObjFWRT", "ObjFWRT.h"),
        )
        if any(
            not os.path.isfile(os.path.join(_incdir, _d, _u))
            for _d, _u in _umbrellas
        ):
            self.output.warning(
                "libobjfwtls1: umbrella header(s) missing in package include/, "
                "topping up from build/source trees"
            )
            _header_map = (
                ("ObjFW", ("src", "src/exceptions")),
                ("ObjFWTLS", ("src/tls",)),
                ("ObjFWRT", ("src/runtime",)),
            )
            for _dest, _rels in _header_map:
                for _sroot in reversed(search_roots):
                    for _rel in _rels:
                        _srcdir = os.path.join(_sroot, _rel)
                        if os.path.isdir(_srcdir):
                            try:
                                _copy2(
                                    self,
                                    "*.h",
                                    src=_srcdir,
                                    dst=os.path.join(_incdir, _dest),
                                )
                            except Exception as exc:
                                self.output.warning(
                                    f"libobjfwtls1: header top-up {_rel} -> {_dest} failed: {exc!r}"
                                )
            _missing_u = [
                f"{_d}/{_u}"
                for _d, _u in _umbrellas
                if not os.path.isfile(os.path.join(_incdir, _d, _u))
            ]
            try:
                _inc_tree = []
                for _r, _ds, _fs in os.walk(_incdir):
                    for _fn in sorted(_fs):
                        _inc_tree.append(os.path.relpath(os.path.join(_r, _fn), self.package_folder))
            except OSError:
                _inc_tree = []
            self.output.info(f"libobjfwtls1: package include/ after top-up: {_inc_tree[:40]}")
            if _missing_u:
                raise ConanException(
                    f"libobjfwtls1: umbrella header(s) still missing: {_missing_u}; " +
                    f"searched {search_roots}, tree={_inc_tree[:40]}; " +
                    "refusing a broken package (test_package would fail downstream)"
                )
        # Library package: drop the ObjFW dev/utility executables so the
        # package stays a pure library (R38: library type, no commands.json).
        for sub in ("bin", "sbin"):
            d = os.path.join(self.package_folder, sub)
            if os.path.isdir(d):
                shutil.rmtree(d)
        # Persist the measured upstream evidence so test_package can re-emit
        # the exact numbers on cache-hit rounds (zstr/isa-l precedent).
        try:
            from conan.tools.files import copy as _copy

            src = os.path.join(str(self.build_folder), "hmbs_upstream.json")
            if os.path.isfile(src):
                _copy(
                    self,
                    "hmbs_upstream.json",
                    src=str(self.build_folder),
                    dst=os.path.join(self.package_folder, "res"),
                )
        except Exception as exc:
            self.output.warning(f"persist upstream evidence failed: {exc!r}")

    def package_info(self):
        # ObjFWTLS links against libobjfw, which links against libobjfwrt.
        self.cpp_info.libs = ["objfwtls", "objfw", "objfwrt"]
        # Static consumers need -lssl -lcrypto after the ObjFW libs (the
        # installed lib/objfw-config/ObjFWTLS.oc records the same linkage).
        self.cpp_info.requires = ["openssl::openssl"]
