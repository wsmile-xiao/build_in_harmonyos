#!/usr/bin/env python3
"""Conan recipe — libbigwig 0.4.9 (CMake build, MIT).

libBigWig: a C library for parsing the bigWig and bigBed file formats.
Upstream CI/build is CMake (CMakeLists.txt project(libBigWig LANGUAGES C)).

Build notes:
- Requires zlib (published in ohpcd). WITH_ZLIBNG=OFF.
- WITH_CURL=OFF: curl is not published in ohpcd and is optional upstream;
  the source guards all curl paths with `#ifndef NOCURL`, so a curl-free
  build is a fully supported upstream configuration. Remote tests
  (testRemote*) are skipped in tests.
- ZLIB::ZLIB bridge: upsteam CMakeLists does find_package(ZLIB) +
  ZLIB::ZLIB, but Conan CMakeDeps generates zlib::zlib (lowercase config).
  The CMAKE_PROJECT_INCLUDE snippet materialises a ZLIBConfig.cmake and
  aliases ZLIB::ZLIB -> zlib::zlib (same pattern as libcurl recipe).
"""
from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches, save
from conan.tools.cmake import CMake, CMakeToolchain, CMakeDeps, cmake_layout
import os


class LibbigwigConan(ConanFile):
    name = "libbigwig"
    version = "0.4.9"
    description = "libBigWig - a C library for reading/writing the bigWig and bigBed formats"
    license = "MIT"
    homepage = "https://github.com/dpryan79/libBigWig"
    url = ""  # CI fills this

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    generators = "CMakeDeps"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("zlib/1.3.1")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = CMakeToolchain(self)
        tc.variables["WITH_CURL"] = "OFF"      # curl 未发布且上游可选 (NOCURL 守卫)
        tc.variables["WITH_ZLIBNG"] = "OFF"    # 使用标准 zlib
        tc.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        tc.variables["ENABLE_TESTING"] = "OFF"
        # ZLIB::ZLIB bridge (同 libcurl 配方思路): 上游 find_package(ZLIB)/ZLIB::ZLIB,
        # CMakeDeps 生成小写 zlib-config.cmake + zlib::zlib 目标。
        # 注意: 不能另写大写 ZLIBConfig.cmake —— 本机 HMDFS 大小写折叠会使其遮蔽
        # CMakeDeps 的 zlib-config.cmake (memory: HMDFS 大小写折叠), 导致真实目标
        # 不注册。桥接直接 include CMakeDeps 文件并 alias 大写目标即可。
        if "zlib" in self.dependencies:
            gen_dir = self.generators_folder
            os.makedirs(gen_dir, exist_ok=True)
            alias_file = os.path.join(gen_dir, "zlib-bridge.cmake")
            alias_content = (
                "# Auto-generated by conanfile.py — ZLIB::ZLIB bridge for libbigwig\n"
                "# 直接 include CMakeDeps 生成的 zlib-config.cmake, 注册 zlib::zlib\n"
                'include("${CMAKE_CURRENT_LIST_DIR}/zlib-config.cmake" OPTIONAL)\n'
                "if(TARGET zlib::zlib AND NOT TARGET ZLIB::ZLIB)\n"
                "  add_library(ZLIB::ZLIB ALIAS zlib::zlib)\n"
                "endif()\n"
            )
            save(self, alias_file, alias_content)
            tc.variables["CMAKE_PROJECT_INCLUDE"] = alias_file
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        # 库文件: libBigWig.a (target: BigWig)
        self.cpp_info.libs = ["BigWig"]
        self.cpp_info.requires = ["zlib::zlib"]
        # 上游把公共头安装到 include/libbigwig/，消费者以 #include "bigWig.h" 使用
        self.cpp_info.includedirs = ["include/libbigwig"]
        # WITH_CURL=OFF 时上游以 target_compile_definitions(BigWig PUBLIC NOCURL)
        # 传播宏，但该宏是 CMake 目标属性，install 后不随 CMake config 导出；
        # 消费者翻译单元 include bigWigIO.h 时若未定义 NOCURL 会走
        # `#include <curl/curl.h>` 分支。配方必须显式把 NOCURL 声明为消费方宏。
        self.cpp_info.defines = ["NOCURL"]