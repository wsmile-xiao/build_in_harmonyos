#!/usr/bin/env python3
"""Conan recipe — librepo 1.20.0 (CMake).

librepo is the RPM-stack repository downloader (used by dnf/libdnf): a C
library providing download of rpm-md repositories (repomd/metalink/mirrorlist)
on top of libcurl, with GPG signature verification via gpgme, metadata XML
parsing via libxml2, and GLib-based async infrastructure.

Adapted to HarmonyOS PC (aarch64, native build):
- All dependencies are resolved through pkg-config files generated by
  PkgConfigDeps (upstream CMake mixes FIND_PACKAGE(CURL) and a bundled
  KDE-era FindGpgme that requires a gpgme-config script, neither of which
  works reliably on OHOS) — see patches/0001.
- zchunk support is enabled via the ohpcd zchunk package.
- SELinux labels / python bindings / docs / examples are disabled
  (no libselinux, no python headers wiring, no doxygen on OHOS).
- Upstream C test suite (check-based, tests/test_main) is built and run.
"""
import os

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import PkgConfigDeps
from conan.tools.layout import basic_layout


class LibrepoConan(ConanFile):
    name = "librepo"
    version = "1.20.0"
    description = (
        "Library providing (libcURL-like) API to download rpm-md "
        "repositories with GPG verification (rpm-software-management/librepo)"
    )
    license = "LGPL-2.1"
    homepage = "https://github.com/rpm-software-management/librepo"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"

    # Upstream only builds a shared librepo.so (ADD_LIBRARY(librepo SHARED));
    # no BUILD_STATIC_LIBS switch exists in upstream CMake.
    options = {"shared": [True]}
    default_options = {"shared": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # glib 提供 glib-2.0 / gobject-2.0 / gio-2.0（CMakeLists 硬依赖 glib-2.0>=2.66 + gio-2.0）
        self.requires("glib/2.84.0.1", transitive_headers=True, transitive_libs=True)
        self.requires("libxml2/2.15.3", transitive_headers=True, transitive_libs=True)
        self.requires("curl/8.15.0.1", transitive_headers=True, transitive_libs=True)
        # libcrypto 用于校验和（PKG_SEARCH_MODULE libcrypto/openssl）
        self.requires("openssl/3.5.6.1", transitive_headers=True, transitive_libs=True)
        # OpenPGP 校验（USE_GPGME=ON 路径；内部依赖 libassuan/libgpg-error）
        self.requires("gpgme/1.24.0", transitive_headers=True, transitive_libs=True)
        # zchunk 分块下载（WITH_ZCHUNK=ON, zck>=0.9.11）
        self.requires("zchunk/1.5.2", transitive_headers=True, transitive_libs=True)
        # 上游测试框架：librepo 自己编译并运行 tests/test_main（check 框架），
        # 必须是普通 requires（test_requires 对 conan create 主构建不可见）；
        # headers/libs/visible 均为 False —— 仅本配方构建期使用，不传播给消费者
        self.requires("check/0.15.2", headers=False, libs=False, visible=False)

    def build_requirements(self):
        pass

    def layout(self):
        basic_layout(self, src_folder=".")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # librepo 的 CMake 用 PKG_CHECK_MODULES/PKG_SEARCH_MODULE 找依赖，
        # PkgConfigDeps 生成的 .pc 是唯一可靠入口
        PkgConfigDeps(self).generate()
        CMakeDeps(self).generate()

        tc = CMakeToolchain(self)
        tc.variables["USE_GPGME"] = True
        tc.variables["ENABLE_SELINUX"] = False  # OHOS 无 libselinux
        tc.variables["WITH_ZCHUNK"] = True
        tc.variables["ENABLE_PYTHON"] = False   # OHOS 不构建 python 绑定
        tc.variables["ENABLE_DOCS"] = False     # doc/ 需要 sphinx，跳过
        tc.variables["ENABLE_EXAMPLES"] = False
        tc.variables["ENABLE_TESTS"] = True     # 上游 check 测试套件
        tc.variables["CMAKE_INSTALL_LIBDIR"] = "lib"
        # librepo.so 运行期需要能找到依赖；不设置额外 rpath，交给 conan 环境
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()
        self._run_upstream_tests()

    def _run_upstream_tests(self):
        """OHOS: 依赖共享库不在默认搜索路径，且 conan buildenv 会覆盖
        LD_LIBRARY_PATH，故用 subprocess 携带完整环境（继承 conanbuild 的
        PATH，并显式注入依赖库目录）直接驱动 ctest。"""
        import subprocess
        import shutil

        cmake_prog = self.conf.get("tools.cmake:cmake_program") or shutil.which("cmake")
        ctest_prog = os.path.join(os.path.dirname(cmake_prog), "ctest") if cmake_prog else None
        if not ctest_prog or not os.path.isfile(ctest_prog):
            ctest_prog = shutil.which("ctest")
        if not ctest_prog:
            raise ConanException("ctest not found")

        env = dict(os.environ)
        env["LD_LIBRARY_PATH"] = self._runtime_library_path()
        # OHOS: check 框架按 TEMP -> P_tmpdir(/tmp) -> TMPDIR 顺序选临时目录，
        # musl 的 P_tmpdir 是不可写的 /tmp，故显式提供 TEMP
        tmpdir = os.environ.get("TMPDIR") or os.environ.get("TEMP") \
            or "/data/storage/el2/base/cache"
        env["TEMP"] = env.get("TEMP") or tmpdir
        env["TMPDIR"] = env.get("TMPDIR") or tmpdir
        # OHOS: 设备无 GnuPG 引擎二进制（gpg），跳过依赖 gpg 引擎的 3 个测试
        env["LIBREPO_SKIP_GPG_TESTS"] = "1"
        result = subprocess.run(
            [ctest_prog, "--test-dir", self.build_folder, "--output-on-failure"],
            env=env, capture_output=True, text=True,
        )
        self.output.info(result.stdout)
        if result.returncode != 0:
            raise ConanException("upstream ctest suite failed")

    def _runtime_library_path(self):
        dirs = [self._staged_dep_libs_dir()]
        for dep in self.dependencies.host.values():
            dirs.extend(dep.cpp_info.aggregated_components().libdirs)
        dirs.append(os.path.join(self.build_folder, "librepo"))
        return os.pathsep.join(dirs)

    def _staged_dep_libs_dir(self):
        """OHOS/HMDFS: 动态加载器无法对另一 uid 创建的 conan 缓存内共享库
        做 exec 映射（链接期读取没问题，dlopen 失败）。把依赖共享库解引用
        拷贝到本构建目录（与测试运行同一 uid/上下文）后即可正常加载。"""
        import glob
        import shutil

        stage = os.path.join(self.build_folder, "dep-libs")
        os.makedirs(stage, exist_ok=True)
        for dep in self.dependencies.host.values():
            for libdir in dep.cpp_info.aggregated_components().libdirs:
                for src in glob.glob(os.path.join(libdir, "*.so*")):
                    dst = os.path.join(stage, os.path.basename(src))
                    if not os.path.exists(dst):
                        try:
                            shutil.copy2(os.path.realpath(src), dst)
                        except OSError:
                            pass
        return stage

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.libs = ["repo"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.set_property("pkg_config_name", "librepo")
        # librepo.pc 的 Requires 由消费方经 pkg-config 解析；conan 侧显式声明
        self.cpp_info.requires = [
            "glib::glib", "libxml2::libxml2", "curl::curl",
            "openssl::openssl", "gpgme::gpgme", "zchunk::zchunk",
        ]
        if self.settings.os in ("Linux", "OHOS"):
            self.cpp_info.system_libs = ["m", "pthread"]
