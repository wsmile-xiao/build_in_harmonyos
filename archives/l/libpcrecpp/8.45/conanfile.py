#!/usr/bin/env python3
"""Conan recipe for libpcrecpp 8.45 — the C++ wrapper of PCRE (PCRE1, legacy).

libpcrecpp has no standalone upstream source repository; it is part of the
pcre-8.45 official source tarball (pcrecpp.cc / pcrecpp.h / pcre_scanner.* /
pcre_stringpiece.* / pcrecpparg.h.in in the source root).

Strategy:
  - Download the official pcre-8.45 tarball as the source.
  - Run the full autotools configure (generates config.h/pcre.h etc. needed
    by pcrecpp.cc), but build ONLY the pcrecpp component (libpcrecpp.la).
  - Package only libpcrecpp.a plus the pcrecpp headers.
  - The core libpcre (and pcre.h) comes from the published pcre/8.45
    prebuilt package in ohpcd (declared via requires).

Reference: archives/p/pcre/8.45/ (patches for OHOS config.guess/sub + umask)
"""
import os
from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches, copy
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class LibpcrecppConan(ConanFile):
    name = "libpcrecpp"
    version = "8.45"
    description = "C++ wrapper for PCRE (Perl Compatible Regular Expressions library, version 1, legacy)"
    license = "BSD-3-Clause"
    homepage = "https://www.pcre.org/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # pcrecpp is a C++ wrapper over the PCRE C core: reuse the published
        # pcre/8.45 prebuilt package for libpcre + pcre.h (R36: published first)
        self.requires("pcre/8.45")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # System-name library: build static only (R26)
        if not self.options.shared:
            tc.configure_args.append("--enable-static")
            tc.configure_args.append("--disable-shared")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # E011 umask 077→022 已由 0003-configure.patch 处理
        autotools = Autotools(self)
        autotools.configure()
        # Build only the pcrecpp component (its LIBADD pulls in libpcre.la,
        # which is fine locally; only pcrecpp artifacts get packaged).
        autotools.make(args=["libpcrecpp.la", "-j1"])

    def package(self):
        # Package only the pcrecpp artifacts; libpcre comes from pcre/8.45.
        # Note: out-of-source build — libpcrecpp.a is in build_folder/.libs,
        # pcrecpp.h is in source_folder (not generated), while pcre_stringpiece.h
        # and pcrecpparg.h are generated by configure in build_folder root.
        copy(self, "libpcrecpp.a",
             src=os.path.join(self.build_folder, ".libs"),
             dst=os.path.join(self.package_folder, "lib"))
        # Include pcre.h — pcrecpp.h directly #includes <pcre.h> and the
        # pcre/8.45 package's CMakeDeps may not export include dirs correctly.
        # Bundling pcre.h here ensures downstream consumers compile reliably.
        copy(self, "pcre.h",
             src=os.path.join(self.build_folder, ""),  # generated by configure
             dst=os.path.join(self.package_folder, "include"))
        # pcrecpp.h lives in source_folder (not generated by configure)
        copy(self, "pcrecpp.h",
             src=self.source_folder,
             dst=os.path.join(self.package_folder, "include"))
        # pcre_scanner.h is a plain source header (not generated by configure)
        copy(self, "pcre_scanner.h",
             src=self.source_folder,
             dst=os.path.join(self.package_folder, "include"))
        # These are generated by configure from .h.in templates in build_folder
        for hdr in ("pcre_stringpiece.h", "pcrecpparg.h"):
            copy(self, hdr,
                 src=self.build_folder,
                 dst=os.path.join(self.package_folder, "include"))

    def package_info(self):
        self.cpp_info.libs = ["pcrecpp"]
        # Keep downstream CMake naming as upstream (pcrecpp::pcrecpp),
        # matching Conan Center's libpcrecpp recipe conventions.
        self.cpp_info.set_property("cmake_file_name", "pcrecpp")
        self.cpp_info.set_property("cmake_target_name", "pcrecpp::pcrecpp")