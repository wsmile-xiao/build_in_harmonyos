#!/usr/bin/env python3
"""Deterministic test-image generator for the libsoil test_package.

The four test images (img_test.bmp/png/tga/dds) are BINARY files, and this
repository must not carry new binary files in a PR: the CI `checkout-pr` step
applies the platform-generated PR diff with `git apply`, and that diff contains
no `GIT binary patch` data for newly added binary files ("error: missing
binary patch data for ..."), so the step fails before the package is ever
built. (libsoil: CI #60156 / PR #12488; same root cause as dbview PR #9495 /
CI #44073 and knowledge/doc/E256.md.)

Therefore the images are NOT committed; they are regenerated byte-identically
at test-configure time by this checked-in generator, whose source the reviewer
can read in the PR diff. `python3` is available in the conan/CI environment.

Every image is 256x256 with the top-left pixel pure blue RGB(0,0,255), which
is exactly what test.c asserts:
  - img_test.bmp : 24-bit BGR, bottom-up rows            -> 3 channels
  - img_test.png : 32-bit RGBA (zlib-compressed, stdlib) -> 4 channels
  - img_test.tga : 32-bit BGRA, top-left origin          -> 4 channels
  - img_test.dds : uncompressed RGBA (BGR[A] byte order, DDPF_RGB|ALPHAPIXELS)
                                                          -> 4 channels

Usage: python3 make_images.py <output-dir>
"""
import os
import struct
import sys
import zlib

W = H = 256


def pixel_rgb(x, y):
    """Deterministic gradient; top-left (0,0) is exactly (0,0,255)."""
    if x == 0 and y == 0:
        return (0, 0, 255)
    return (x % 256, y % 256, (x + y) % 256)


# ── BMP (24-bit, bottom-up, BGR) ────────────────────────────────────────────
def write_bmp(path):
    row_size = W * 3  # 768, already a multiple of 4 -> no padding
    pixels = bytearray()
    for y in range(H - 1, -1, -1):  # bottom-up
        for x in range(W):
            r, g, b = pixel_rgb(x, y)
            pixels += bytes((b, g, r))
    file_size = 54 + len(pixels)
    header = b"BM" + struct.pack("<IHHI", file_size, 0, 0, 54)
    dib = struct.pack("<IiiHHIIiiII", 40, W, H, 1, 24, 0,
                      row_size * H, 2835, 2835, 0, 0)
    with open(path, "wb") as f:
        f.write(header + dib + bytes(pixels))


# ── PNG (32-bit RGBA, zlib via stdlib) ──────────────────────────────────────
def png_chunk(tag, data):
    return (struct.pack(">I", len(data)) + tag + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))


def write_png(path):
    raw = bytearray()
    for y in range(H):
        raw.append(0)  # filter type 0 (None)
        for x in range(W):
            r, g, b = pixel_rgb(x, y)
            raw += bytes((r, g, b, 255))
    ihdr = struct.pack(">IIBBBBB", W, H, 8, 6, 0, 0, 0)  # 8-bit RGBA
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(png_chunk(b"IHDR", ihdr))
        f.write(png_chunk(b"IDAT", zlib.compress(bytes(raw), 9)))
        f.write(png_chunk(b"IEND", b""))


# ── TGA (32-bit BGRA, top-left origin) ──────────────────────────────────────
def write_tga(path):
    header = struct.pack("<BBBHHBHHHHBB",
                         0, 0, 2, 0, 0, 0, 0, 0, W, H, 32, 0x28)
    pixels = bytearray()
    for y in range(H):  # top-left origin (descriptor 0x20)
        for x in range(W):
            r, g, b = pixel_rgb(x, y)
            pixels += bytes((b, g, r, 255))
    with open(path, "wb") as f:
        f.write(header + bytes(pixels))


# ── DDS (uncompressed RGBA, 128-byte header + BGR[A] data) ──────────────────
def write_dds(path):
    # stb's DDS loader (stbi_DDS_aug_c.h) drops a fully-opaque RGBA image to
    # 3 channels when req_comp == SOIL_LOAD_AUTO, so one deterministic pixel
    # (far from the asserted top-left corner) carries alpha=128 to keep the
    # 4-channel path.
    DDSD_CAPS = 0x1
    DDSD_HEIGHT = 0x2
    DDSD_WIDTH = 0x4
    DDSD_PITCH = 0x8
    DDSD_PIXELFORMAT = 0x1000
    DDSCAPS_TEXTURE = 0x1000
    DDPF_ALPHAPIXELS = 0x1
    DDPF_RGB = 0x40
    pitch = W * 4
    # Explicit 128-byte layout: magic(4)+size(4)+flags(4)+height(4)+width(4)
    # +pitch(4)+depth(4)+mipmaps(4)+reserved1(44)+ddspf(32)+caps1(4)+caps2(4)
    # +capsReserved(12)+reserved2(4) = 128
    buf = bytearray(128)
    struct.pack_into("<I", buf, 0, 0x20534444)
    struct.pack_into("<I", buf, 4, 124)
    struct.pack_into("<I", buf, 8, DDSD_CAPS | DDSD_HEIGHT | DDSD_WIDTH
                     | DDSD_PITCH | DDSD_PIXELFORMAT)
    struct.pack_into("<I", buf, 12, H)
    struct.pack_into("<I", buf, 16, W)
    struct.pack_into("<I", buf, 20, pitch)
    # dwMipMapCount stays 0 (no DDSD_MIPMAPCOUNT flag, no mip chain)
    # ddspf (offset 76, 32 bytes): dwSize, dwFlags, dwFourCC, dwRGBBitCount,
    # dwRBitMask, dwGBitMask, dwBBitMask, dwAlphaBitMask
    struct.pack_into("<IIIIIIII", buf, 76, 32, DDPF_RGB | DDPF_ALPHAPIXELS,
                     0, 32, 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000)
    struct.pack_into("<I", buf, 108, DDSCAPS_TEXTURE)
    pixels = bytearray()
    for y in range(H):
        for x in range(W):
            r, g, b = pixel_rgb(x, y)
            alpha = 128 if (x == 200 and y == 100) else 255
            pixels += bytes((b, g, r, alpha))  # reader swaps B<->R back
    with open(path, "wb") as f:
        f.write(bytes(buf) + bytes(pixels))


def main():
    if len(sys.argv) != 2:
        print("usage: make_images.py <output-dir>", file=sys.stderr)
        return 2
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    write_bmp(os.path.join(out, "img_test.bmp"))
    write_png(os.path.join(out, "img_test.png"))
    write_tga(os.path.join(out, "img_test.tga"))
    write_dds(os.path.join(out, "img_test.dds"))
    for name in ("img_test.bmp", "img_test.png", "img_test.tga", "img_test.dds"):
        p = os.path.join(out, name)
        if os.path.getsize(p) == 0:
            print("make_images: %s is empty" % name, file=sys.stderr)
            return 1
        print("make_images: generated %s (%d bytes)" % (p, os.path.getsize(p)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
