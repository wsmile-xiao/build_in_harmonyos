#!/usr/bin/env python3
"""Conan recipe - libaiff 6.0 (direct compile, no autotools).

LibAiff is a lightweight C library for transparent read/write of Audio
Interchange File Format (AIFF/AIFF-C) files, including LPCM, float32 and
G.711 sample conversion plus metadata/marker handling.

Upstream 6.0 (mtszb/libaiff tag v6.0) ships configure.ac + Makefile.am
without a pre-generated configure script. The previous revision ran
`autoreconf -fi` via tool_requires (automake/1.18 + autoconf/2.72 +
libtool/2.5.4, same approach as owamp/zzuf), but the preflight sandbox
cannot build the m4/1.4.19 tool dependency: its configure re-execs
/data/service/hnp/bin/bash ("inaccessible or not found") and the worker
/tmp is read-only, so the failure happens before this recipe ever runs.

This revision therefore drops autoreconf and all tool_requires and
compiles the 8 portable C sources directly with the Conan-configured
compiler (aarch64 generic path, no x86/ppc asm). Only config.h is
generated (standard HAVE_* defines for the OHOS libc, little-endian);
no configure/mktemp/perl/bash involvement remains. Upstream declares
no TESTS/check target and no test directory, so there is no `make
check` step; consumer coverage lives in test_package/.
"""

import json
import os
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import copy, get
from conan.tools.layout import basic_layout


SOURCES = (
    "aifx.c",
    "extended.c",
    "float32.c",
    "g711.c",
    "iff.c",
    "libaiff.c",
    "lpcm.c",
    "pascal.c",
)

# aarch64-OHOS is little-endian with a musl-derived libc: all standard
# headers/functions probed by configure.ac exist; the x86/ppc-specific
# optimisations and big-endian paths stay undefined (generic C code).
# PACKAGE_* mirrors AC_INIT([libaiff],[6.0],[marcotrillo@gmail.com]):
# libaiff.c AIFFAssertionFailed() prints PACKAGE_STRING/PACKAGE_BUGREPORT,
# which autoconf would emit into libaiff/config.h via autoheader.
CONFIG_H = """/* Generated by libaiff/6.0 recipe: replaces autoconf config.h. */
#pragma once
#define STDC_HEADERS 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_SYS_STAT_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STRING_H 1
#define HAVE_STRINGS_H 1
#define HAVE_MEMORY_H 1
#define HAVE_UNISTD_H 1
#define HAVE_STDINT_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_MEMSET 1
#define HAVE_ABORT 1
#define PACKAGE "libaiff"
#define PACKAGE_BUGREPORT "marcotrillo@gmail.com"
#define PACKAGE_NAME "libaiff"
#define PACKAGE_STRING "libaiff 6.0"
#define PACKAGE_TARNAME "libaiff"
#define PACKAGE_URL ""
#define PACKAGE_VERSION "6.0"
#define VERSION "6.0"
"""


class LibaiffConan(ConanFile):
    name = "libaiff"
    version = "6.0"
    description = "C library for transparent read/write of AIFF/AIFF-C audio files"
    license = "MIT"
    homepage = "https://github.com/mtszb/libaiff"
    url = "https://github.com/mtszb/libaiff"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "libaiff is only supported on Linux/OHOS, not "
                + str(self.settings.os)
            )

    def layout(self):
        basic_layout(self)

    def _writable_tmpdir(self):
        """HMBS readonly_tmp: reuse injected writable tmpdir (minimal).

        Priority: HMBS_TMPDIR > HMBS_PLATFORM_CAPABILITIES.tmpdir >
        already-exported TMPDIR/TMP/TEMP (bare /tmp is read-only erofs,
        must be skipped) > HMBS_AUTOCONF_MKTEMP_FALLBACK >
        build_folder/tmp. Probe-writes; only replaces the temp-file root.
        """
        candidates = []
        for key in ("HMBS_TMPDIR",):
            value = os.environ.get(key)
            if value:
                candidates.append(value)
        capabilities = os.environ.get("HMBS_PLATFORM_CAPABILITIES")
        if capabilities:
            try:
                obj = json.loads(capabilities)
                if isinstance(obj, dict) and obj.get("tmpdir"):
                    candidates.append(str(obj["tmpdir"]))
            except Exception:
                pass
        for key in ("TMPDIR", "TMP", "TEMP"):
            value = os.environ.get(key)
            if value and value != "/tmp" and value not in candidates:
                candidates.append(value)
        fallback = os.environ.get("HMBS_AUTOCONF_MKTEMP_FALLBACK")
        if fallback and fallback not in candidates:
            candidates.append(fallback)
        for base in (getattr(self, "build_folder", None),
                     getattr(self, "source_folder", None)):
            if base:
                candidates.append(os.path.join(str(base), "tmp"))
        for candidate in candidates:
            if not candidate:
                continue
            try:
                os.makedirs(candidate, exist_ok=True)
            except OSError:
                continue
            if not os.path.isdir(candidate):
                continue
            try:
                probe = os.path.join(candidate, ".hmbs_wtest")
                with open(probe, "w", encoding="utf-8") as handle:
                    handle.write("w")
                os.remove(probe)
                return candidate
            except OSError:
                continue
        fallback_dir = os.path.join(str(self.build_folder), "tmp")
        os.makedirs(fallback_dir, exist_ok=True)
        return fallback_dir

    def _ensure_tmp_env(self):
        """Redirect temp files off read-only /tmp; pin shell to /bin/sh."""
        tmp = self._writable_tmpdir()
        for key in ("TMPDIR", "TMP", "TEMP"):
            os.environ[key] = tmp
        os.environ["SHELL"] = "/bin/sh"
        os.environ["CONFIG_SHELL"] = "/bin/sh"
        try:
            os.umask(0o022)
        except Exception:
            pass
        return tmp

    def _usable_tool(self, path):
        # Preflight sandbox may list profile tools that are not mounted
        # (e.g. /data/service/hnp/bin/clang -> "inaccessible or not
        # found"); only accept a path that exists as a file.
        try:
            return bool(path) and os.path.isfile(path)
        except Exception:
            return False

    def _compiler(self):
        # R33: compiler from Conan conf dict, never bare ${CC} — but the
        # profile absolute path may be unmounted in the preflight sandbox
        # (this round: /data/service/hnp/bin/clang inaccessible), so probe
        # accessibility and prefer a PATH-discovered compiler instead of
        # blindly returning the conf value (previous round's root cause).
        try:
            exes = self.conf.get(
                "tools.build:compiler_executables", default={}, check_type=dict)
        except Exception:
            exes = {}
        conf_cc = exes.get("c") if isinstance(exes, dict) else None
        if self._usable_tool(conf_cc):
            return conf_cc
        if conf_cc:
            self.output.warning(
                "conf compiler not usable in sandbox, probing PATH: %s"
                % conf_cc)
        for env_key in ("CC",):
            env_cc = os.environ.get(env_key)
            if self._usable_tool(env_cc):
                return env_cc
        for name in ("clang", "cc", "gcc"):
            found = shutil.which(name)
            if found and self._usable_tool(found):
                return found
        # Last resort: bare name resolved via PATH at exec time (never an
        # unmounted absolute path).
        for name in ("clang", "cc", "gcc"):
            if shutil.which(name):
                return shutil.which(name)
        return "cc"

    def _archiver(self, cc):
        # Prefer llvm-ar next to a usable compiler, else PATH lookup.
        # Never return an unmounted absolute path.
        try:
            bindir = os.path.dirname(cc or "")
            if bindir:
                for name in ("llvm-ar", "ar"):
                    cand = os.path.join(bindir, name)
                    if self._usable_tool(cand):
                        return cand
        except Exception:
            pass
        for name in ("llvm-ar", "ar"):
            found = shutil.which(name)
            if found and self._usable_tool(found):
                return found
        return "ar"

    def source(self):
        # conan's get() stages via tempfile (honors TMPDIR); pin it to the
        # HMBS task-private dir so read-only /tmp cannot break the fetch.
        self._ensure_tmp_env()
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # No toolchain needed (direct cc compile), but still propagate the
        # writable tmp root + /bin/sh so compiler temp files never fall
        # back to read-only /tmp. Only replaces the temp-file root.
        tmp = self._writable_tmpdir()
        hmbs_env = Environment()
        hmbs_env.define("TMPDIR", tmp)
        hmbs_env.define("TMP", tmp)
        hmbs_env.define("TEMP", tmp)
        hmbs_env.define("SHELL", "/bin/sh")
        hmbs_env.define("CONFIG_SHELL", "/bin/sh")
        for key in ("HMBS_AUTOCONF_MKTEMP_FALLBACK", "HMBS_CAP_LOCAL_MKTEMP",
                    "HMBS_CAP_HARDLINK", "HMBS_CAP_CHMOD", "HMBS_CAP_SYMLINK",
                    "HMBS_TMPDIR", "HMBS_CMAKE", "HMBS_MAKE", "HMBS_NINJA",
                    "HMBS_PYTHON3"):
            value = os.environ.get(key)
            if value:
                hmbs_env.define(key, value)
        hmbs_env.vars(self, scope="build").save_script("hmbs_env")

    def build(self):
        self._ensure_tmp_env()
        obj_dir = os.path.join(self.build_folder, "objs")
        os.makedirs(obj_dir, exist_ok=True)
        # Generated config.h next to the shipped headers so both
        # <libaiff/config.h> (angle) and "private.h" resolve with -I src.
        config_path = os.path.join(self.source_folder, "libaiff", "config.h")
        with open(config_path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(CONFIG_H)
        cc = self._compiler()
        self.output.info("libaiff resolved compiler: %s (PATH=%s)"
                         % (cc, os.environ.get("PATH", "")))
        cflags = "-O2 -fPIC -I%s -DLIBAIFF" % self.source_folder
        if str(self.settings.build_type) == "Debug":
            cflags += " -g -O0"
        objects = []
        for src in SOURCES:
            obj = os.path.join(obj_dir, os.path.splitext(src)[0] + ".o")
            self.run(
                '%s %s -c "%s" -o "%s"'
                % (cc, cflags,
                   os.path.join(self.source_folder, src), obj),
                env="conanbuild",
            )
            objects.append('"%s"' % obj)
        lib_dir = os.path.join(self.build_folder, "hmbs-lib")
        os.makedirs(lib_dir, exist_ok=True)
        if self.options.shared:
            self.run(
                '%s -shared -o "%s" %s'
                % (cc, os.path.join(lib_dir, "libaiff.so"),
                   " ".join(objects)),
                env="conanbuild",
            )
        else:
            ar = self._archiver(cc)
            self.run(
                '%s rcs "%s" %s'
                % (ar, os.path.join(lib_dir, "libaiff.a"),
                   " ".join(objects)),
                env="conanbuild",
            )

    def package(self):
        copy(self, "libaiff.a", src=os.path.join(self.build_folder, "hmbs-lib"),
             dst=os.path.join(self.package_folder, "lib"))
        copy(self, "libaiff.so", src=os.path.join(self.build_folder, "hmbs-lib"),
             dst=os.path.join(self.package_folder, "lib"))
        copy(self, "*.h", src=os.path.join(self.source_folder, "libaiff"),
             dst=os.path.join(self.package_folder, "include", "libaiff"))

    def package_info(self):
        self.cpp_info.libs = ["aiff"]
        self.cpp_info.set_property("cmake_file_name", "libaiff")
        self.cpp_info.set_property("cmake_target_name", "libaiff::libaiff")
        self.cpp_info.set_property("pkg_config_name", "libaiff")
