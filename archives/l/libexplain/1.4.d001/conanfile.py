#!/usr/bin/env python3
"""Conan recipe for libexplain 1.4.d001 — explain errno failures verbosely.

libexplain (Peter Miller, sourceforge) is a C library that turns failed
syscalls into human-readable explanations, plus the `explain` CLI.
Autotools with a pre-generated configure (2014-era), a bison grammar
(libexplain/acl_grammar.y, regenerated by make), and a pre-libtool-macro
build that shells out to a `libtool` program for .lo objects.

Platform notes:
- config.guess is from 2012 and knows neither HarmonyOS nor
  aarch64-musl: patch 0001 adds an aarch64:HarmonyOS branch (the
  matching config.sub accepts aarch64-unknown-linux-gnu, which is what
  we emit — the triplet is only used for build-tree naming).
- bison and libtool come from the artifact repo as tool_requires
  (bison/3.8.2, libtool/2.5.4, both published).
- LD_LIBRARY_PATH is explicitly emptied during build (lld/libxml2
  shield — CI-021 build #48068, mechanism in libodfgen/libabw).
- Only all-bin is built: all-doc needs groff and all-i18n needs msgfmt,
  neither exists on the platform (documented degradation; library and
  CLI are unaffected).
- Nothing is stripped on install (llvm-strip output is refused by the
  platform's exec policy — yices 2.7.0 evidence + knowledge draft).
"""

import os
import shlex
import subprocess

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import VirtualBuildEnv
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout

OHOS_SHELL_CANDIDATES = ("/data/service/hnp/bin/bash", "/usr/bin/zsh", "bash")

ACL_SHIM = """#ifndef OHOS_COMPAT_SYS_ACL_H
#define OHOS_COMPAT_SYS_ACL_H
/* Minimal sys/acl.h shim for platforms without POSIX ACL (musl/OHOS):
 * type soup + ENOSYS stubs.  Generated by the conan recipe at build
 * time (not an upstream patch). */
#include <errno.h>
#include <sys/types.h>

typedef int acl_type_t;
typedef struct acl_t *acl_t;
typedef struct acl_entry_t *acl_entry_t;
typedef int acl_permset_t;
typedef unsigned int acl_perm_t;
typedef int acl_tag_t;

#define ACL_READ  4
#define ACL_WRITE 2
#define ACL_EXECUTE 1

#define ACL_FIRST_ENTRY 0
#define ACL_NEXT_ENTRY  1

#define ACL_USER_OBJ  0x01
#define ACL_USER      0x02
#define ACL_GROUP_OBJ 0x04
#define ACL_GROUP     0x08
#define ACL_MASK      0x10
#define ACL_OTHER     0x20

#define ACL_TYPE_ACCESS  0
#define ACL_TYPE_DEFAULT 1

#define ACL_UNDEFINED_ID (-1)

static inline acl_t acl_from_text(const char *s)
{ (void)s; errno = ENOSYS; return (acl_t)0; }
static inline char *acl_to_text(acl_t a, ssize_t *n)
{ (void)a; if (n) *n = 0; errno = ENOSYS; return (char *)0; }
static inline char *acl_to_any_text(acl_t a, const char *p, char c, int f)
{ (void)a; (void)p; (void)c; (void)f; errno = ENOSYS; return (char *)0; }
static inline acl_t acl_get_fd(int fd)
{ (void)fd; errno = ENOSYS; return (acl_t)0; }
static inline acl_t acl_get_file(const char *p, acl_type_t t)
{ (void)p; (void)t; errno = ENOSYS; return (acl_t)0; }
static inline int acl_set_fd(int fd, acl_t a)
{ (void)fd; (void)a; errno = ENOSYS; return -1; }
static inline int acl_set_file(const char *p, acl_type_t t, acl_t a)
{ (void)p; (void)t; (void)a; errno = ENOSYS; return -1; }
static inline int acl_free(void *p)
{ (void)p; return 0; }
static inline int acl_valid(acl_t a)
{ (void)a; errno = ENOSYS; return -1; }
static inline int acl_get_entry(acl_t a, int id, acl_entry_t *e)
{ (void)a; (void)id; (void)e; return 0; }

#endif /* OHOS_COMPAT_SYS_ACL_H */
"""


class LibexplainConan(ConanFile):
    name = "libexplain"
    version = "1.4.d001"
    description = ("libexplain - explain errno failures: library that "
                   "turns failed syscalls into human-readable messages, "
                   "plus the `explain` CLI")
    license = "GPL-3.0-or-later"
    homepage = "https://sourceforge.net/projects/libexplain/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # configure hard-requires libcap (cap_get_proc probe is fatal)
        self.requires("libcap/2.73")

    def build_requirements(self):
        # bison regenerates libexplain/acl_grammar.y; libexplain shells
        # out to a `libtool` program for .lo objects.
        self.tool_requires("bison/3.8.2")
        self.tool_requires("libtool/2.5.4")

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"libexplain is adapted for Linux and OHOS, not {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        # url may arrive as a candidate list (the CI pre-download step
        # rewrites conandata's url into [mirror, official]) — conan's
        # get() handles both shapes natively.
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        VirtualBuildEnv(self).generate()
        # dependency package folders are reliably populated in
        # generate(); persist them for build() (xlsxio-proven pattern —
        # reading self.dependencies in build() yielded empty
        # package_folder on this toolchain).
        lines = []
        for dep in ("bison/3.8.2", "libtool/2.5.4"):
            pf = self.dependencies.build[dep].package_folder
            lines.append(f"{dep}={pf}")
        cap = self.dependencies["libcap"]
        lines.append(f"libcap={cap.package_folder}")
        with open(os.path.join(self.generators_folder, "dep_paths.txt"),
                  "w") as fh:
            fh.write("\n".join(lines) + "\n")

    def build(self):
        apply_conandata_patches(self)
        build = self.build_folder
        self._copy_tree(self.source_folder, build)
        # umask 077 → 022 (hmdfs does not preserve permission bits; a
        # 077-created config.status temp dir ends up unwritable and
        # config.status dies with "./confXXXX/subs1.awk: Permission
        # denied".  configure embeds the config.status template, so
        # rewriting configure covers both.)
        for root, _, files in os.walk(build):
            for name in files:
                if name != "configure":
                    continue
                path = os.path.join(root, name)
                with open(path, encoding="utf-8", errors="replace") as fh:
                    content = fh.read()
                if "umask 077" in content:
                    with open(path, "w", encoding="utf-8",
                              newline="\n") as fh:
                        fh.write(content.replace("umask 077",
                                                 "umask 022"))
        self._write_acl_shim(build)

        env = dict(os.environ)
        # lld/libxml2 shield — see class docstring.
        env["LD_LIBRARY_PATH"] = ""
        env["CC"] = self._cc()
        shell = self._resolve_shell()
        env["SHELL"] = shell
        env["CONFIG_SHELL"] = shell
        # dependency paths persisted by generate()
        dep_paths = {}
        with open(os.path.join(self.generators_folder,
                               "dep_paths.txt")) as fh:
            for ln in fh:
                k, _, v = ln.strip().partition("=")
                dep_paths[k] = v
        # bison/libtool binaries from the build context on PATH
        path_add = [os.path.join(dep_paths[d], "bin")
                    for d in ("bison/3.8.2", "libtool/2.5.4")]
        env["PATH"] = ":".join(path_add) + ":" + env.get("PATH", "")
        # conan bison looks up its data dir at the packaged-in prefix
        # (/share/bison doesn't exist here) — point it at the package.
        env["BISON_PKGDATADIR"] = os.path.join(dep_paths["bison/3.8.2"],
                                               "share", "bison")
        tmpdir = os.path.join(build, ".tmp")
        os.makedirs(tmpdir, exist_ok=True)
        env["TMPDIR"] = tmpdir
        # libcap from the artifact repo (configure's cap_get_proc probe
        # is fatal without it); paths persisted by generate()
        dep_paths = {}
        with open(os.path.join(self.generators_folder,
                               "dep_paths.txt")) as fh:
            for ln in fh:
                k, _, v = ln.strip().partition("=")
                dep_paths[k] = v
        cap_inc = os.path.join(dep_paths["libcap"], "include")
        cap_lib = os.path.join(dep_paths["libcap"], "lib")
        env["CPPFLAGS"] = (f"-I{cap_inc} "
                           f"-I{os.path.join(build, '.acl-shim')} "
                           # musl's sys/param.h has no HZ (glibc-ism)
                           "-DHZ=100 "
                           # SDK 内核头 linux/socket.h 与 musl
                           # sys/socket.h 双向都不互认（libc-compat 不识
                           # musl）；0006 让 musl 侧先到位，再直接屏蔽
                           # 内核 socket 头（其内容 musl 已全覆盖）
                           "-D_UAPI_LINUX_SOCKET_H=1")
        env["LDFLAGS"] = f"-L{cap_lib} -Wl,-rpath,{cap_lib}"

        cmd = (f"{shlex.quote(shell)} ./configure "
               "--build=aarch64-unknown-linux-gnu "
               "--host=aarch64-unknown-linux-gnu --prefix=/ "
               "< /dev/null")
        completed = subprocess.run(cmd, shell=True, cwd=build, env=env)
        if completed.returncode != 0:
            self._dump_failure_diagnostics(build, env)
            raise ConanException(
                f"configure failed (rc={completed.returncode})")
        # all-bin only: all-doc needs groff, all-i18n needs msgfmt —
        # neither exists on this platform (library + CLI unaffected).
        completed = subprocess.run("make -j2 all-bin < /dev/null",
                                   shell=True, cwd=build, env=env)
        if completed.returncode != 0:
            self._dump_failure_diagnostics(build, env)
            raise ConanException("make failed")

    def package(self):
        build = self.build_folder
        inst = os.path.join(build, "inst")
        env = dict(os.environ)
        env["LD_LIBRARY_PATH"] = ""
        shell = self._resolve_shell()
        env["SHELL"] = shell
        # install rules invoke libtool (build-context tool) — same PATH
        # injection as build()
        dep_paths = {}
        with open(os.path.join(self.generators_folder,
                               "dep_paths.txt")) as fh:
            for ln in fh:
                k, _, v = ln.strip().partition("=")
                dep_paths[k] = v
        path_add = [os.path.join(dep_paths[d], "bin")
                    for d in ("bison/3.8.2", "libtool/2.5.4")]
        env["PATH"] = ":".join(path_add) + ":" + env.get("PATH", "")
        completed = subprocess.run(
            "make install-bin install-include install-libdir "
            f"DESTDIR={shlex.quote(inst + os.sep)} < /dev/null",
            shell=True, cwd=build, env=env)
        if completed.returncode != 0:
            raise ConanException(
                f"make install failed (rc={completed.returncode})")
        copy(self, "*.h", src=os.path.join(inst, "include"),
             dst=os.path.join(self.package_folder, "include"),
             keep_path=True)
        copy(self, "*.a", src=os.path.join(inst, "lib"),
             dst=os.path.join(self.package_folder, "lib"),
             keep_path=False)
        copy(self, "explain", src=os.path.join(inst, "bin"),
             dst=os.path.join(self.package_folder, "bin"),
             keep_path=False)
        # Static delivery (sbc/libabw precedent — this platform's loader
        # refuses shared-library resolution for these binaries): relink
        # the explain CLI against the static libexplain.a and drop the
        # shared library from the package entirely.
        dep_paths = {}
        with open(os.path.join(self.generators_folder,
                               "dep_paths.txt")) as fh:
            for ln in fh:
                k, _, v = ln.strip().partition("=")
                dep_paths[k] = v
        cap_lib = os.path.join(dep_paths["libcap"], "lib", "libcap.a")
        explain_objs = []
        for pattern_dir in ("explain", os.path.join("explain", "syscall")):
            subdir = os.path.join(build, pattern_dir)
            if os.path.isdir(subdir):
                explain_objs.extend(
                    os.path.join(subdir, f) for f in os.listdir(subdir)
                    if f.endswith(".o"))
        lib_a = None
        for root, _, files in os.walk(build):
            if "libexplain.a" in files:
                lib_a = os.path.join(root, "libexplain.a")
                break
        if not lib_a or not explain_objs:
            raise ConanException("static relink inputs missing")
        static_bin = os.path.join(self.package_folder, "bin", "explain")
        objs_str = " ".join(shlex.quote(o) for o in explain_objs)
        relink = (f"{shlex.quote(env['CC'])} -O2 -fPIC -o "
                  f"{shlex.quote(static_bin)} {objs_str} "
                  f"{shlex.quote(lib_a)} {shlex.quote(cap_lib)} -lm")
        completed = subprocess.run(relink, shell=True, cwd=build, env=env)
        if completed.returncode != 0:
            raise ConanException(
                f"static relink failed (rc={completed.returncode})")
        copy(self, "LICENSE", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"),
             keep_path=False)

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "libexplain")
        self.cpp_info.set_property("cmake_target_name", "libexplain::libexplain")
        self.cpp_info.set_property("pkg_config_name", "libexplain")
        self.cpp_info.libs = ["explain"]

    # ── helpers ─────────────────────────────────────────────────────────

    def _write_acl_shim(self, build):
        """Write a minimal sys/acl.h shim (types + ENOSYS stubs).

        The platform has no sys/acl.h at all, and libexplain's public
        headers include it unconditionally.  The shim provides the POSIX
        ACL type soup plus static-inline stubs that fail with ENOSYS —
        no valid acl_t can be produced on this platform, so the ACL
        explanation paths simply report the syscall failure (documented
        degradation).
        """
        shim_dir = os.path.join(build, ".acl-shim", "sys")
        os.makedirs(shim_dir, exist_ok=True)
        with open(os.path.join(shim_dir, "acl.h"), "w") as fh:
            fh.write(ACL_SHIM)

    def _cc(self):
        compilers = self.conf.get("tools.build:compiler_executables",
                                  default=None)
        if compilers:
            if isinstance(compilers, str):
                import json
                try:
                    compilers = json.loads(compilers)
                except ValueError:
                    compilers = {}
            if compilers.get("c"):
                return compilers["c"]
        return "clang"

    def _resolve_shell(self):
        for candidate in OHOS_SHELL_CANDIDATES:
            if os.path.isfile(candidate):
                return candidate
        return "/bin/sh"

    def _copy_tree(self, src, dst):
        import shutil
        shutil.copytree(src, dst, dirs_exist_ok=True, symlinks=True)

    def _dump_failure_diagnostics(self, directory, environment):
        self.output.info("---- ohos diagnostics: environment ----")
        for name in ("CC", "CFLAGS", "CPPFLAGS", "LDFLAGS", "LDLIBS",
                     "TMPDIR", "LD_LIBRARY_PATH", "PATH", "SHELL"):
            if name in environment:
                self.output.info(f"{name}={environment[name]}")
        config_log = os.path.join(directory, "config.log")
        if os.path.isfile(config_log):
            with open(config_log, errors="replace") as handle:
                lines = handle.readlines()
            for line in lines[-25:]:
                self.output.info(line.rstrip())
