#!/usr/bin/env python3
"""Conan recipe — libantlr3c 3.5.3 (ANTLR v3 C runtime).

libantlr3c is the C target runtime of the ANTLR v3 parser generator: input
streams, lexer/parser base infrastructure, token buffers, tree construction,
DFA/ATN driving, and error handling.  Parser source code generated by the
ANTLR *Java* tool only depends on this runtime's public headers — the
generator itself is a host-side development tool and is NOT a runtime
dependency of the produced library (see notes.md for the host/target split).

Upstream facts (audited 2026-09-03):
  - tag archive antlr3-3.5.3.tar.gz (SHA256 a0892bcf…) ships the runtime under
    runtime/C/ with configure.ac + Makefile.am but NO generated `configure`;
    the recipe bootstraps with `autoreconf -fi` in runtime/C.
  - license: BSD-3-Clause (runtime/C/COPYING, Jim Idle / Temporal Wave LLC);
    configure.ac embeds the same text in AC_COPYRIGHT.
  - runtime/C/Makefile.am registers no TESTS / check_PROGRAMS / check-local:
    upstream `make check` is a zero-test audit target (recorded in
    test_package/MANIFEST.yml); consumer-level validation lives in
    test_package/.
  - no third-party dependencies: libc only (memset/memmove/strdup), plus
    optional sys/socket + netinet/tcp probes for the ANTLR debugger socket.

OHOS adaptations:
  - E007/E514: pass --build/--host=aarch64-unknown-linux-ohos so configure
    never runs the config.guess probe (config.sub accepts *-linux-ohos);
  - E114: drop `umask 077` from the generated runtime/C/configure (HMDFS
    setgid turns the 0700 temp dir into an unwritable dir);
  - E074: `make -j1` (HMDFS jobserver fifo EPERM);
  - E443: the build host can expose `autoreconf` on PATH while the rest of
    the autotools closure (aclocal/automake/...) lives outside it.  autoreconf
    execs those tools by bare name, so build() rediscovers the whole closure
    from autoreconf's real location and applies it through a local Conan
    Environment — never by mutating os.environ;
  - --enable-64bit is required on AArch64: without it ANTLR3_MARKER is
    ANTLR3_INT32 and every pointer stored in a hash trie is truncated
    (antlr3defs.h `#ifdef ANTLR3_USE_64BIT`).  The 3.5.3 runtime code assumes
    64-bit markers on 64-bit platforms; enabling the macro keeps the ABI
    whole.  configure.ac adds no -m64 for clang (generic `*)` branch), so
    this flag only selects the typedef/macro branch.
"""
import os
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.env import Environment, VirtualBuildEnv
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


# Macros in configure.ac that make autoreconf run libtoolize.  Checked against
# the actual runtime/C/configure.ac of the 3.5.3 tag archive (see
# _needs_libtoolize); when in doubt keep the set broad — it only decides
# whether libtoolize must be discovered and validated too.
_LIBTOOL_MACROS = (
    "LT_INIT", "AC_PROG_LIBTOOL", "AM_PROG_LIBTOOL", "AC_LIBTOOL_DLOPEN",
    "AC_LIBTOOL_WIN32", "AC_LIBTOOL_RPATH", "LT_OUTPUT", "LTDL_INIT",
    "AC_LIB_LTDL", "LT_WITH_LTDL",
)

# autoreconf is a thin driver that execs these tools by bare name; this is
# the set it provably cannot run without when regenerating this source tree
# (configure.ac is autoconf/automake/libtool based; no other *-config tools
# are referenced).
_CLOSURE_TOOLS = ("aclocal", "automake", "autoconf", "autoheader", "autom4te")


def _needs_libtoolize(conanfile):
    """True when runtime/C/configure.ac actually uses libtool macros."""
    configure_ac = os.path.join(conanfile.source_folder, "runtime", "C",
                                "configure.ac")
    try:
        with open(configure_ac, "r", encoding="utf-8", errors="replace") as f:
            data = f.read()
    except OSError as exc:
        raise ConanInvalidConfiguration(
            "E443: cannot read %s to decide whether libtoolize is needed: %s"
            % (configure_ac, exc))
    return any(macro in data for macro in _LIBTOOL_MACROS)


def _autotools_closure(conanfile, effective_path):
    """E443: discover the host autotools tool closure.

    The build host may expose `autoreconf` on PATH while its siblings
    (aclocal, automake, ...) are reachable only via autoreconf's own private
    layout (wrapper scripts shipped next to them).  autoreconf execs those
    tools by bare name, so a PATH that resolves autoreconf but not aclocal
    fails with `Can't exec "aclocal"`.

    `effective_path` is the PATH seen after applying the Conan
    VirtualBuildEnv (profile [buildenv] PATH + tool_requires bindirs + the
    original base PATH); tools are resolved from it first.  Only when a
    tool is missing from that PATH do we fall back to a bounded set of
    candidate dirs derived from autoreconf's real location (its own dir
    plus `<ancestor>/bin` a few levels up) — the realpath walk is a
    last-resort fallback, never the primary source.  Returns
    (env, found, resolved_from) where env is a Conan Environment with the
    tool dirs prepended to PATH and absolute paths pinned for the tools
    autoreconf looks up through env vars, found maps tool name ->
    resolved path, and resolved_from maps tool name -> how it was found.
    """
    search_path = effective_path or os.environ.get("PATH", "")
    autoreconf = shutil.which("autoreconf", path=search_path)
    if not autoreconf:
        raise ConanInvalidConfiguration(
            "E443: autoreconf not found on effective PATH; install "
            "autoconf/automake on the build host or add automake/libtool "
            "as tool_requires")
    autoreconf_real = os.path.realpath(autoreconf)

    # Fallback candidate roots (used ONLY for tools missing from the
    # effective PATH): the directory holding the real autoreconf —
    # in every prefix-style layout the sibling tools (aclocal, automake, …)
    # sit right next to it.  Then, walking a bounded number of parents,
    # `<ancestor>/bin` — covers hosts where autoreconf is exposed through a
    # deeper nested dir while its siblings live in a plain bin/ above it.
    real_dir = os.path.dirname(autoreconf_real)
    candidates = [real_dir]
    walk = real_dir
    for _ in range(4):
        parent = os.path.dirname(walk)
        if parent == walk:
            break
        walk = parent
        candidates.append(os.path.join(walk, "bin"))
    # dedupe, keep order (nearest first)
    seen = set()
    candidate_bins = [c for c in candidates
                      if not (c in seen or seen.add(c))]
    conanfile.output.info(
        "E443: autoreconf=%s (real: %s); effective PATH (VirtualBuildEnv "
        "merged): %s; realpath fallback bins: %s"
        % (autoreconf, autoreconf_real, search_path, candidate_bins))

    needed = list(_CLOSURE_TOOLS)
    if _needs_libtoolize(conanfile):
        needed.append("libtoolize")

    found = {}
    resolved_from = {}
    for tool in needed:
        # Primary: the effective (VirtualBuildEnv-merged) PATH — the same
        # resolution autoreconf itself uses.  Fallback: the bounded
        # realpath candidate dirs above.
        path = shutil.which(tool, path=search_path)
        source = "effective PATH"
        if not path:
            for cand in candidate_bins:
                maybe = os.path.join(cand, tool)
                if os.path.isfile(maybe) and os.access(maybe, os.X_OK):
                    path = maybe
                    source = "realpath fallback (%s)" % cand
                    break
        if not path:
            detail = "; ".join(
                "%s=%s" % (t, found[t]) for t in found)
            raise ConanInvalidConfiguration(
                "E443: autotools closure incomplete: %s not found.  "
                "autoreconf resolved to %s; effective PATH: %s; "
                "realpath fallback bins: %s; already found: %s"
                % (tool, autoreconf_real, search_path, candidate_bins,
                   detail or "none"))
        found[tool] = os.path.realpath(path)
        resolved_from[tool] = source
        conanfile.output.info(
            "E443: %s -> %s (from %s)" % (tool, found[tool], source))

    # Also make sure autoreconf itself is reachable from the merged PATH:
    # pin it too so a PATH reorder in conanbuild cannot break it.
    if autoreconf_real not in found.values():
        found["autoreconf"] = autoreconf_real
        resolved_from["autoreconf"] = "effective PATH"

    tool_dirs = []
    seen = set()
    for path in found.values():
        d = os.path.dirname(path)
        if d not in seen:
            seen.add(d)
            tool_dirs.append(d)

    env = Environment()
    for d in tool_dirs:
        env.prepend_path("PATH", d)
    # autoreconf/autoconf honor these env vars for sibling lookups, so pin
    # absolute paths for the ones that were resolved; this keeps the closure
    # working even if the saved conanbuild env reorders PATH.
    for var, tool in (("ACLOCAL", "aclocal"), ("AUTOMAKE", "automake"),
                      ("AUTOCONF", "autoconf"), ("AUTOHEADER", "autoheader"),
                      ("AUTOM4TE", "autom4te"), ("LIBTOOLIZE", "libtoolize")):
        if tool in found:
            env.define(var, found[tool])
    return env, found, resolved_from


def _drop_umask_077(conanfile, path):
    """E114: HMDFS forces setgid on directories; `umask 077 && mktemp -d`
    creates a drwx--S--- temp dir that is not writable even by its owner."""
    with open(path, "r", encoding="utf-8") as f:
        data = f.read()
    data = data.replace(
        'tmp=`(umask 077 && mktemp -d "./confXXXXXX") 2>/dev/null`',
        'tmp=`mktemp -d "./confXXXXXX" 2>/dev/null`')
    data = data.replace('(umask 077 && mkdir "$tmp")', 'mkdir "$tmp"')
    with open(path, "w", encoding="utf-8") as f:
        f.write(data)


class Libantlr3cConan(ConanFile):
    name = "libantlr3c"
    version = "3.5.3"
    description = "C runtime library for parsers generated by ANTLR v3"
    license = "BSD-3-Clause"
    homepage = "https://www.antlr3.org/"
    url = ""  # CI fills this

    package_type = "library"
    languages = "C"
    settings = "os", "compiler", "build_type", "arch"
    options = {
        "shared": [True, False],
        "antlrdebug": [True, False],
    }
    default_options = {
        "shared": False,
        "antlrdebug": True,
    }

    implements = ["auto_shared_fpic"]

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        # R32: settings.os must check in ("Linux", "OHOS")
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "libantlr3c is only supported on Linux/OHOS, not "
                + str(self.settings.os))

    def layout(self):
        basic_layout(self)

    def build_requirements(self):
        # The tag archive ships configure.ac/Makefile.am but no generated
        # `configure`: the recipe bootstraps with `autoreconf -fi`, which
        # execs the whole autotools closure (aclocal/automake/autoconf/
        # autoheader/autom4te/libtoolize) by bare name.  automake and
        # libtool are provided as tool_requires so the closure is complete
        # regardless of what the build host has on its base PATH; autoconf
        # itself (autoreconf/autoheader/autom4te/autoconf) comes from the
        # SDK on the CI workers (same split as libdap/libzbar).
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # VirtualBuildEnv: inject profile [buildenv] PATH + tool_requires
        # (automake/libtool) bindirs into conanbuild so the autotools
        # closure is resolvable from the effective build environment.
        build_env = VirtualBuildEnv(self)
        build_env.generate()
        tc = AutotoolsToolchain(self)
        # E007/E514: config.guess cannot identify HarmonyOS.  The OHOS
        # profile makes Conan emit --host=aarch64-linux-ohos itself
        # (_get_triplets), but the build triplet would still be guessed by
        # the generated configure's config.guess; pin both explicitly so the
        # probe never runs (config.sub accepts *-linux-ohos).
        tc.configure_args.append("--build=aarch64-unknown-linux-ohos")
        tc.configure_args.append("--host=aarch64-unknown-linux-ohos")
        # AArch64 ILP64: 64-bit markers, or runtime pointer->marker casts
        # truncate (see module docstring)
        tc.configure_args.append("--enable-64bit")
        if self.options.antlrdebug:
            tc.configure_args.append("--enable-antlrdebug")
        else:
            tc.configure_args.append("--disable-antlrdebug")
        tc.generate()

    def build(self):
        # VPATH-safe AM_CPPFLAGS (see patches/0001)
        apply_conandata_patches(self)
        # E443: apply the Conan build environment first — VirtualBuildEnv
        # merges profile [buildenv] PATH + tool_requires bindirs + base PATH.
        # The autotools closure must be resolved from that effective PATH
        # (not from the recipe process's bare os.environ), or tool_requires
        # like automake/libtool would be invisible.  Never mutate
        # os.environ; the scope covers the whole build.
        build_env = VirtualBuildEnv(self).vars()
        with build_env.apply():
            self.output.info("E443: effective PATH (VirtualBuildEnv merged): %s"
                             % os.environ.get("PATH"))
            # Resolve the closure from the effective PATH (realpath walk is
            # fallback-only) and apply it nested inside the build env scope.
            env, found, resolved_from = _autotools_closure(
                self, os.environ.get("PATH"))
            with env.vars(self).apply():
                # fail closed: re-verify the closure through the merged env —
                # every tool must resolve to the path we discovered.
                missing = [t for t, p in found.items()
                           if os.path.realpath(shutil.which(t) or "") != p]
                if missing:
                    raise ConanInvalidConfiguration(
                        "E443: autotools closure broken after applying env: %s "
                        "(discovered: %s)" % (missing, found))
                self.output.info("E443: autotools closure: %s" % found)
                self.output.info("E443: closure sources: %s" % resolved_from)
                # Bootstrap via autoreconf with the DISCOVERED closure, not
                # the generated conanbuild.sh: conanfile.run() defaults to
                # env="conanbuild", and that script exports ACLOCAL/AUTOMAKE/
                # LIBTOOLIZE pointing at the tool_requires wrappers — which
                # would override the closure resolved above.  env=None keeps
                # the process environment (VirtualBuildEnv + closure vars,
                # both applied above), so autoreconf execs exactly the tools
                # we verified.
                self.run('autoreconf -f -i "%s"'
                         % os.path.join(self.source_folder, "runtime", "C"),
                         cwd=os.path.join(self.source_folder, "runtime", "C"),
                         env=None)
            # E114: drop umask 077 from the generated configure (HMDFS)
            _drop_umask_077(self, os.path.join(
                self.source_folder, "runtime", "C", "configure"))
            # VPATH (out-of-tree) build: conan runs configure with cwd = build
            # folder, srcdir = runtime/C inside the extracted archive.  The
            # original `INCLUDES = -Iinclude` only resolves in-tree; the
            # Makefile.am patch (patches/0001) rewrites it to VPATH-safe
            # AM_CPPFLAGS (-I$(top_srcdir)/include -I$(top_builddir)).
            with env.vars(self).apply():
                autotools = Autotools(self)
                autotools.configure(build_script_folder=os.path.join("runtime", "C"))
                # E074: HMDFS jobserver fifo EPERM
                autotools.make(args=["-j1"], target="all")

    def package(self):
        # Same combined environment as build(): VirtualBuildEnv (effective
        # PATH incl. tool_requires bindirs) + the discovered autotools
        # closure, so `make install` finds the same toolchain.
        build_env = VirtualBuildEnv(self).vars()
        with build_env.apply():
            env, found, _ = _autotools_closure(self, os.environ.get("PATH"))
            with env.vars(self).apply():
                autotools = Autotools(self)
                autotools.install()

    def package_info(self):
        self.cpp_info.libs = ["antlr3c"]
