/*
  test_librcd.c — librcd/0.1.14 消费者测试（Conan L1 `test_package`）

  目的：以**消费方视角**实质调用被测包导出的唯一公开 API
  `rcdGetRussianCharset()`，断言它对真实俄文/拉丁文文本的检测结果（R34）。

  为什么用显式字节数组而不是字符串字面量：被测库按**原始字节**做统计判定，
  本文件必须把每种编码的字节逐字节钉死，否则测试的期望值会随编译器/终端
  字符集变化。所有向量均由 Python 的标准编解码器生成（cp1251 / koi8-r /
  cp866 / utf-8 / iso-8859-1），每个数组末尾补 0x00 以支持 `len=0`（strlen 语义）。

  为什么用自带 CHECK 宏而不是 assert()：本仓库 profile 为 Release，`NDEBUG`
  生效会把 assert 编译掉，出现"断言数 > 0 但实际不判"的假绿；自带宏不受
  NDEBUG 影响，并把 `checks=<N> failures=0` 打成机器可读证据行。

  覆盖范围（共 34 项断言）：
    1. 公开枚举 `rcd_russian_charset` 的取值就是头文件承诺的 0..4（头文件指纹）；
    2. 同一句话在 CP1251 / KOI8-R / CP866 / UTF-8 四种编码下的判定结果；
    3. `len=0`（strlen 语义）与显式 `len=N` 两条入参路径结果一致；
    4. ISO-8859-1（非西里尔拉丁文）判定；
    5. 短词（6 字节）判定与结果值域、幂等性。
*/
#include <stdio.h>
