static int g_checks = 0;
static int g_failures = 0;

#define CHECK(cond, what)                                                       \
    do {                                                                        \
        g_checks++;                                                             \
        if (!(cond)) {                                                          \
            g_failures++;                                                       \
            printf("FAIL: %s\n", (what));                                       \
        }                                                                       \
    } while (0)

#define CHECK_IS(value, expected, what)                                         \
    CHECK((int)(value) == (int)(expected), (what))

