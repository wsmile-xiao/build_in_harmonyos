static int detect(const unsigned char *buf, int len)
{
    return (int)rcdGetRussianCharset((const char *)buf, len);
}

int main(void)
{
    int r_t2_cp1251_len0, r_t2_cp1251_lenN;

    /* --- 1. 公开枚举取值（头文件指纹：文档承诺 0=CP1251 1=KOI8-R 2=UTF8 3=CP866 4=ISO8859-1） --- */
    CHECK_IS(RUSSIAN_CHARSET_WIN, 0, "RUSSIAN_CHARSET_WIN == 0 (CP1251)");
    CHECK_IS(RUSSIAN_CHARSET_KOI, 1, "RUSSIAN_CHARSET_KOI == 1 (KOI8-R)");
    CHECK_IS(RUSSIAN_CHARSET_UTF8, 2, "RUSSIAN_CHARSET_UTF8 == 2");
    CHECK_IS(RUSSIAN_CHARSET_ALT, 3, "RUSSIAN_CHARSET_ALT == 3 (CP866)");
    CHECK_IS(RUSSIAN_CHARSET_LATIN, 4, "RUSSIAN_CHARSET_LATIN == 4 (ISO8859-1)");

    /* --- 2. T1：同一句话四种编码，len=0（strlen 语义） --- */
    CHECK_IS(detect(T1_CP1251, 0), RUSSIAN_CHARSET_WIN, "T1 cp1251 -> CP1251 (len=0)");
    CHECK_IS(detect(T1_KOI8R, 0), RUSSIAN_CHARSET_KOI, "T1 koi8-r -> KOI8-R (len=0)");
    CHECK_IS(detect(T1_CP866, 0), RUSSIAN_CHARSET_ALT, "T1 cp866 -> CP866 (len=0)");
    CHECK_IS(detect(T1_UTF8, 0), RUSSIAN_CHARSET_UTF8, "T1 utf-8 -> UTF8 (len=0)");

    /* --- 3. T1：显式 len=N 路径必须与 len=0 一致 --- */
    CHECK_IS(detect(T1_CP1251, (int)sizeof(T1_CP1251) - 1), RUSSIAN_CHARSET_WIN,
             "T1 cp1251 -> CP1251 (len=N)");
    CHECK_IS(detect(T1_KOI8R, (int)sizeof(T1_KOI8R) - 1), RUSSIAN_CHARSET_KOI,
             "T1 koi8-r -> KOI8-R (len=N)");
    CHECK_IS(detect(T1_CP866, (int)sizeof(T1_CP866) - 1), RUSSIAN_CHARSET_ALT,
             "T1 cp866 -> CP866 (len=N)");
    CHECK_IS(detect(T1_UTF8, (int)sizeof(T1_UTF8) - 1), RUSSIAN_CHARSET_UTF8,
             "T1 utf-8 -> UTF8 (len=N)");

    /* --- 4. T2：更长的句子（65 字节/单字节编码） --- */
    r_t2_cp1251_len0 = detect(T2_CP1251, 0);
    r_t2_cp1251_lenN = detect(T2_CP1251, (int)sizeof(T2_CP1251) - 1);
    CHECK_IS(r_t2_cp1251_len0, RUSSIAN_CHARSET_WIN, "T2 cp1251 -> CP1251 (len=0)");
    CHECK_IS(detect(T2_KOI8R, 0), RUSSIAN_CHARSET_KOI, "T2 koi8-r -> KOI8-R (len=0)");
    CHECK_IS(detect(T2_CP866, 0), RUSSIAN_CHARSET_ALT, "T2 cp866 -> CP866 (len=0)");
    CHECK_IS(detect(T2_UTF8, 0), RUSSIAN_CHARSET_UTF8, "T2 utf-8 -> UTF8 (len=0)");
    CHECK_IS(r_t2_cp1251_lenN, RUSSIAN_CHARSET_WIN, "T2 cp1251 -> CP1251 (len=N)");
    CHECK_IS(detect(T2_KOI8R, (int)sizeof(T2_KOI8R) - 1), RUSSIAN_CHARSET_KOI,
             "T2 koi8-r -> KOI8-R (len=N)");
    CHECK_IS(detect(T2_CP866, (int)sizeof(T2_CP866) - 1), RUSSIAN_CHARSET_ALT,
             "T2 cp866 -> CP866 (len=N)");
    CHECK_IS(detect(T2_UTF8, (int)sizeof(T2_UTF8) - 1), RUSSIAN_CHARSET_UTF8,
             "T2 utf-8 -> UTF8 (len=N)");

    /* --- 5. T3：6 字节短词（库自述的短标题场景） --- */
    CHECK_IS(detect(T3_CP1251, 0), RUSSIAN_CHARSET_WIN, "T3 short cp1251 -> CP1251");
    CHECK_IS(detect(T3_KOI8R, 0), RUSSIAN_CHARSET_KOI, "T3 short koi8-r -> KOI8-R");
    CHECK_IS(detect(T3_CP866, 0), RUSSIAN_CHARSET_ALT, "T3 short cp866 -> CP866");
    CHECK_IS(detect(T3_UTF8, 0), RUSSIAN_CHARSET_UTF8, "T3 short utf-8 -> UTF8");
    CHECK_IS(detect(T3_CP1251, (int)sizeof(T3_CP1251) - 1), RUSSIAN_CHARSET_WIN,
             "T3 short cp1251 -> CP1251 (len=N)");

    /* --- 6. T4：非西里尔拉丁文 -> ISO8859-1（两种输入字节形态） --- */
    CHECK_IS(detect(T4_ISO8859_1, 0), RUSSIAN_CHARSET_LATIN, "T4 iso-8859-1 -> ISO8859-1 (len=0)");
    CHECK_IS(detect(T4_ISO8859_1, (int)sizeof(T4_ISO8859_1) - 1), RUSSIAN_CHARSET_LATIN,
             "T4 iso-8859-1 -> ISO8859-1 (len=N)");
    CHECK_IS(detect(T4_UTF8, 0), RUSSIAN_CHARSET_LATIN, "T4 utf-8 latin -> ISO8859-1 (len=0)");

    /* --- 7. 返回码必须落在公开枚举的 5 个取值内（不越界） --- */
    CHECK(detect(T2_CP1251, 0) >= 0 && detect(T2_CP1251, 0) <= 4, "T2 cp1251 result inside [0,4]");
    CHECK(detect(T2_KOI8R, 0) >= 0 && detect(T2_KOI8R, 0) <= 4, "T2 koi8-r result inside [0,4]");
    CHECK(detect(T2_CP866, 0) >= 0 && detect(T2_CP866, 0) <= 4, "T2 cp866 result inside [0,4]");
    CHECK(detect(T2_UTF8, 0) >= 0 && detect(T2_UTF8, 0) <= 4, "T2 utf-8 result inside [0,4]");

    /* --- 8. 幂等性：同一输入连续两次判定结果一致 --- */
    CHECK_IS(detect(T2_CP1251, 0), r_t2_cp1251_len0, "T2 cp1251 detection is idempotent");

    printf("[test_librcd] checks=%d failures=%d\n", g_checks, g_failures);
    if (g_failures != 0) {
        printf("[test_librcd] FAILED\n");
        return 1;
    }
    printf("[test_librcd] OK\n");
    return 0;
}
