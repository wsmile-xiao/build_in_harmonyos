/* Consumer test for the installed libirman package.
 *
 * Everything checked here is deterministic without IR hardware: the rc-file
 * parser (name/code hash tables, aliases), the 6 byte code <-> text
 * conversion, the command registry and the error strings.  The serial
 * handshake itself is covered by upstream's --enable-swtest programs, which
 * the recipe runs from build().
 */
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include <irman.h>

static int checks;
static int failures;

static void check(int condition, const char *what)
{
    checks++;
    if (condition) {
        printf("ok   %s\n", what);
    } else {
        failures++;
        printf("FAIL %s\n", what);
    }
}

static const char *RC_FILE = "irman_consumer.rc";

static int write_rc_file(void)
{
    FILE *rc = fopen(RC_FILE, "w");

    if (!rc) {
        return 0;
    }
    fputs("# generated by test_irman.c\n"
          "bind POWER 010203040506\n"
          "bind PLAY aabbccddeeff\n"
          "alias ON POWER\n"
          "port /dev/irman-test\n", rc);
    fclose(rc);
    return 1;
}

int main(void)
{
    unsigned char *code;

    setvbuf(stdout, NULL, _IOLBF, 0);

    check(strcmp(ir_strerror(IR_ENOKEY), "Key not found") == 0,
          "ir_strerror maps IR_ENOKEY");
    check(strcmp(ir_strerror(IR_EBADCMD), "Invalid command code") == 0,
          "ir_strerror maps IR_EBADCMD");
    check(strcmp(ir_strerror(IR_EDUPKEY), "Key already exists") == 0,
          "ir_strerror maps IR_EDUPKEY");

    check(ir_valid_code((char *)"0123456789ab") == 1,
          "ir_valid_code accepts 12 hex digits");
    check(ir_valid_code((char *)"0123456789a") == 0,
          "ir_valid_code rejects 11 digits");
    check(ir_valid_code((char *)"0123456789ag") == 0,
          "ir_valid_code rejects non-hex digits");

    code = ir_text_to_code((char *)"A1B2C3D4E5F6");
    check(strcmp(ir_code_to_text(code), "a1b2c3d4e5f6") == 0,
          "ir_text_to_code/ir_code_to_text round trip");

    errno = 0;
    check(ir_get_code() == NULL && errno == IR_EDISABLED,
          "ir_get_code before ir_init reports IR_EDISABLED");
    errno = 0;
    check(ir_finish() == -1 && errno == IR_EDISABLED,
          "ir_finish before ir_init reports IR_EDISABLED");

    check(write_rc_file() == 1, "created the temporary irman rc file");

    check(ir_init_commands((char *)RC_FILE, 1) == 0,
          "ir_init_commands loads the rc file");
    errno = 0;
    check(ir_init_commands((char *)RC_FILE, 1) == -1 && errno == IR_EENABLED,
          "ir_init_commands is not re-entrant");

    check(strcmp(ir_name_to_text((char *)"POWER"), "010203040506") == 0,
          "ir_name_to_text resolves a bound name");
    check(strcmp(ir_text_to_name((char *)"010203040506"), "POWER") == 0,
          "ir_text_to_name resolves a bound code");
    check(strcmp(ir_name_to_text((char *)"ON"), "010203040506") == 0,
          "ir_name_to_text follows an alias");
    check(strcmp(ir_code_to_name(ir_text_to_code((char *)"aabbccddeeff")), "PLAY") == 0,
          "ir_code_to_name decodes the PLAY binding");
    check(strcmp(ir_default_portname(), "/dev/irman-test") == 0,
          "ir_default_portname returns the port from the rc file");

    errno = 0;
    check(ir_name_to_text((char *)"NOSUCHNAME") == NULL && errno == IR_ENOKEY,
          "ir_name_to_text rejects an unknown name");

    check(ir_register_command((char *)"POWER", 42) == 0,
          "ir_register_command binds a command number");
    errno = 0;
    check(ir_register_command((char *)"POWER", 43) == -1 && errno == IR_EDUPKEY,
          "ir_register_command rejects a duplicate command");
    errno = 0;
    check(ir_register_command((char *)"POWER", 0) == -1 && errno == IR_EBADCMD,
          "ir_register_command rejects a bad command number");
    check(ir_remove_command((char *)"PLAY") == 0,
          "ir_remove_command clears a command number");
    errno = 0;
    check(ir_remove_command((char *)"NOPE") == -1 && errno == IR_ENOKEY,
          "ir_remove_command rejects an unknown name");

    /* Upstream quirk: ir_free_commands() frees the name/text tables but never
     * clears the "commands enabled" flag, so the command layer cannot be
     * re-initialised afterwards (and a second ir_free_commands() would free
     * the same tables twice), hence the single call here. */
    ir_free_commands();
    errno = 0;
    check(ir_init_commands((char *)RC_FILE, 0) == -1 && errno == IR_EENABLED,
          "ir_init_commands stays IR_EENABLED after ir_free_commands (upstream quirk)");

    remove(RC_FILE);

    printf("checks: %d, failures: %d\n", checks, failures);
    return failures == 0 ? 0 : 1;
}
