#!/usr/bin/env python3
"""Conan recipe for libirman 0.5.2 - library for the Irman infrared receiver.

libirman is the userspace support library for the Irman infrared receiver (and
for hardware that emulates the Irman protocol, e.g. the irtoy).  It speaks the
Irman "IR" handshake over a serial port, decodes the 6 byte IR pseudo-codes and
binds them to names/commands loaded from a small rc file.

OHOS notes
----------
* Upstream ships a **pre-generated** autotools build (``configure`` from
  autoconf 2.69 plus ``Makefile.in`` and the libtool macros in ``m4/``), so the
  recipe never runs autoreconf/aclocal/automake.  That also keeps the
  automake-under-Conan-perl problems documented in archives/l/libhbaapi out of
  the picture - this tree needs nothing but ``./configure && make``.
* ``configure`` contains the usual ``umask 077 && mktemp -d`` pattern; HarmonyOS
  HMDFS is setgid mounted, so config.status cannot use its own temp directory
  and dies with ``config.status: error: could not setup config files
  machinery`` (E011).  ``build()`` relaxes ``umask 077`` to ``022`` in place.
* ``config.guess`` cannot identify HarmonyOS and its probe also fails under the
  HMDFS temporary directory (E007), so the recipe passes
  ``--build``/``--host`` explicitly and configure never has to guess.  The
  bundled ``config.sub`` is GNU config 2015-01-01, which predates OHOS and
  rejects the triplet outright, so ``patches/0001-config-sub-ohos.patch`` adds
  the ``linux-ohos*`` kernel-OS combination (same two-hunk approach as
  archives/a/aalib).
* The Irman hardware is discontinued and this repository has no serial device,
  so the recipe configures with ``--enable-swtest``.  Upstream then builds
  ``libirman_sw`` plus the ``test_name_sw``/``test_func_sw`` programs whose
  low-level I/O is replaced by a stdin-driven software backend (``irfunc.c``,
  ``#ifdef IR_SOFTWARE_TEST``).  ``build()`` feeds them a fixed code and checks
  the decoded name - deterministic upstream evidence on a machine without any
  IR hardware.
* The LIRC plugin needs ``lirc-driver`` and is disabled with
  ``--with-plugin=no``; ``irman.conf`` is still installed under ``etc/``.
"""
import glob
import os
import platform
import subprocess

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout

required_conan_version = ">=2.0"

# Fixed pseudo-codes used for the software-backend upstream check.
_SWTEST_RC = """\
# generated by the libirman Conan recipe
bind POWER 010203040506
bind PLAY aabbccddeeff
alias ON POWER
"""


class LibirmanConan(ConanFile):
    name = "libirman"
    version = "0.5.2"
    description = ("Library and tools for the Irman infrared receiver: serial IR "
                   "handshake, 6 byte code decoding and rc-file name bindings")
    license = "LGPL-2.1-or-later"
    homepage = "https://sourceforge.net/projects/libirman/"
    url = ""

    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "libirman talks to a serial IR receiver, not supported on "
                + str(self.settings.os))
        arch = str(self.settings.arch)
        if arch not in ("armv8", "aarch64", "x86_64", "x86"):
            raise ConanInvalidConfiguration(
                "libirman OHOS adaptation is validated on armv8/aarch64 and "
                "x86_64, not " + arch)

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        toolchain = AutotoolsToolchain(self)
        # E007: never let the 1999 config.guess probe run (it cannot create its
        # temporary file on HMDFS and does not know HarmonyOS).
        arch = str(self.settings.arch)
        cpu = "aarch64" if arch in ("armv8", "aarch64") else arch
        triplet = "{}-unknown-linux-ohos".format(cpu)
        toolchain.configure_args.extend([
            "--build={}".format(triplet),
            "--host={}".format(triplet),
            "--with-plugin=no",
            "--enable-swtest",
        ])
        toolchain.generate()

    def _relax_configure_umask(self):
        """E011: drop the ``umask 077`` used by config.status on HMDFS.

        The 0700 directory created by ``umask 077 && mktemp -d`` is not usable
        on the HarmonyOS HMDFS mount, so config.status aborts with
        ``could not setup config files machinery``.  Same in-place relaxation
        as archives/i/icoutils and archives/l/libhbaapi.
        """
        configure = os.path.join(self.source_folder, "configure")
        if not os.path.isfile(configure):
            raise ConanException("the pre-generated configure script is missing")
        with open(configure, "r", encoding="utf-8", errors="surrogateescape") as handle:
            content = handle.read()
        if "umask 077" in content:
            with open(configure, "w", encoding="utf-8",
                      errors="surrogateescape") as handle:
                handle.write(content.replace("umask 077", "umask 022"))
            self.output.info("relaxed umask 077 to 022 in the shipped configure")

    def build(self):
        apply_conandata_patches(self)
        self._relax_configure_umask()
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])
        self._run_software_backend_tests()

    def _run_software_backend_tests(self):
        """Run upstream's hardware-free tools and check their output.

        ``--enable-swtest`` builds ``test_name_sw``/``test_func_sw``.  Their
        ``ir_read_code()`` implementation reads 12 hex digits from stdin and
        the tools print the decoded name/text, so one fixed code exercises the
        whole rc-file -> hash table -> decode path without a serial device.
        """
        if str(self.settings.os) != "OHOS":
            return
        # autotools/VPATH: configure and make run in build_folder
        binary_dir = os.path.join(self.build_folder)
        rc_dir = os.path.join(self.build_folder, "swtest-home")
        os.makedirs(rc_dir, exist_ok=True)
        rc_path = os.path.join(rc_dir, ".irmanrc")
        with open(rc_path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(_SWTEST_RC)
        env = dict(os.environ)
        env["HOME"] = rc_dir
        env["LD_LIBRARY_PATH"] = os.path.join(binary_dir, ".libs")
        log = os.path.join(self.build_folder, "upstream-swtest.log")
        # The tools are interactive by design: they decode codes in an endless
        # for(;;) loop, so they are fed a batch of codes and stopped after a
        # few seconds.  What matters is that they decoded the code from the rc
        # file, which the captured output proves.
        payload = b"010203040506\n" * 200
        results = []
        for program, expected in (("test_name_sw", "rx `POWER'"),
                                  ("test_func_sw", "rx `010203040506'")):
            path = os.path.join(binary_dir, program)
            if not os.path.isfile(path):
                raise ConanException(
                    "upstream software-test program {} was not built".format(program))
            process = subprocess.Popen(
                [path, "/dev/null"], stdin=subprocess.PIPE, env=env,
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            try:
                output = process.communicate(input=payload, timeout=10)[0]
                note = "exit {}".format(process.returncode)
            except subprocess.TimeoutExpired:
                process.kill()
                output = process.communicate()[0]
                note = "stopped after 10 s (interactive loop, expected)"
            output = output.decode("utf-8", "replace")
            results.append("===== {} ({})\n{}".format(program, note, output))
            if expected not in output:
                raise ConanException(
                    "{} did not report {} under the software backend:\n{}".format(
                        program, expected, output[-2000:]))
        with open(log, "w", encoding="utf-8", newline="\n") as handle:
            handle.write("\n".join(results))
        self.output.info("upstream software-backend evidence captured: " +
                         " | ".join(line for line in results[0].splitlines()
                                    if "rx " in line)[:200])

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        for libtool_archive in glob.glob(os.path.join(self.package_folder, "lib", "*.la")):
            os.remove(libtool_archive)
        pkg_config = os.path.join(self.package_folder, "lib", "pkgconfig", "libirman.pc")
        if os.path.isfile(pkg_config):
            with open(pkg_config, "r", encoding="utf-8") as handle:
                content = handle.read()
            content = content.replace("prefix=/", "prefix=" + self.package_folder)
            content = content.replace("exec_prefix=/", "exec_prefix=" + self.package_folder)
            content = content.replace("libdir=/lib",
                                      "libdir=" + os.path.join(self.package_folder, "lib"))
            content = content.replace("includedir=/include",
                                      "includedir=" + os.path.join(self.package_folder, "include"))
            with open(pkg_config, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(content)
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"), keep_path=False)
        copy(self, "COPYING.lib", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"), keep_path=False)

    def package_info(self):
        self.cpp_info.libs = ["irman"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.set_property("cmake_file_name", "libirman")
        self.cpp_info.set_property("cmake_target_name", "libirman::libirman")
        self.cpp_info.set_property("pkg_config_name", "libirman")
