#!/usr/bin/env python3
"""Conan recipe — libelf 0.8.13 (CMake)

libelf is a free ELF object file access library. The upstream autotools
files are incomplete in the GitHub mirror, so this recipe generates a
CMakeLists.txt in build() to compile the source.
"""
import os

from conan import ConanFile
from conan.tools.files import get
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout


class LibelfConan(ConanFile):
    name = "libelf"
    version = "0.8.13"
    description = "ELF object file access library"
    license = "LGPL-2.0-or-later"
    homepage = "https://github.com/masc-ucsc/libelf"
    url = "https://cnb.cool/ohpcd/ohos-pc-archives/-/tree/main/archives/l/libelf/0.8.13"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = CMakeToolchain(self)
        tc.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        tc.generate()

    def build(self):
        # Generate CMakeLists.txt (upstream has no CMake build system)
        cml = """cmake_minimum_required(VERSION 3.15)
project(libelf C)
set(CMAKE_C_STANDARD 99)

# Generate config.h with platform defines (write to build dir, not source dir)
file(WRITE "${CMAKE_BINARY_DIR}/config.h"
"/* config.h - generated by CMake */\\n"
"#define HAVE_MMAP 1\\n"
"#define STDC_HEADERS 1\\n"
"#define HAVE_MEMSET 1\\n"
"#define HAVE_FTRUNCATE 1\\n"
"#define HAVE_GETPAGESIZE 1\\n"
"#define HAVE_MEMCMP 1\\n"
"#define HAVE_MEMCPY 1\\n"
"#define HAVE_MEMMOVE 1\\n"
"#define HAVE_AR_H 1\\n"
"#define HAVE_ELF_H 1\\n"
"#define HAVE_FCNTL_H 1\\n"
"#define HAVE_LINK_H 1\\n"
"#define HAVE_STDINT_H 1\\n"
"#define HAVE_UNISTD_H 1\\n"
"#define __LIBELF_HEADER_ELF_H <elf.h>\\n"
"#define __LIBELF64 1\\n"
"#define __LIBELF_SYMBOL_VERSIONS 1\\n"
"#define __LIBELF_GNU_SYMBOL_VERSIONS 1\\n"
"#define __libelf_i64_t long\\n"
"#define __libelf_u64_t unsigned long\\n"
"#define __libelf_i32_t int\\n"
"#define __libelf_u32_t unsigned int\\n"
"#define __libelf_i16_t short\\n"
"#define __libelf_u16_t unsigned short\\n"
"#define SIZEOF_INT 4\\n"
"#define SIZEOF_LONG 8\\n"
"#define SIZEOF_LONG_LONG 8\\n"
"#define SIZEOF_SHORT 2\\n"
"#define ENABLE_SANITY_CHECKS 1\\n"
)

file(GLOB LIBELF_SOURCES CONFIGURE_DEPENDS "${CMAKE_SOURCE_DIR}/libelf/*.c")

add_library(elf ${LIBELF_SOURCES})
target_include_directories(elf PUBLIC
    ${CMAKE_SOURCE_DIR}
    ${CMAKE_SOURCE_DIR}/libelf
    ${CMAKE_BINARY_DIR}
)
target_compile_definitions(elf PRIVATE HAVE_CONFIG_H)

include(GNUInstallDirs)
install(TARGETS elf
    ARCHIVE DESTINATION ${CMAKE_INSTALL_LIBDIR}
    LIBRARY DESTINATION ${CMAKE_INSTALL_LIBDIR}
)
install(FILES
    ${CMAKE_SOURCE_DIR}/libelf/libelf.h
    ${CMAKE_SOURCE_DIR}/libelf/gelf.h
    ${CMAKE_SOURCE_DIR}/libelf/sys_elf.h
    ${CMAKE_SOURCE_DIR}/libelf/elf_repl.h
    ${CMAKE_SOURCE_DIR}/libelf/libelf_config.h
    DESTINATION ${CMAKE_INSTALL_INCLUDEDIR}/libelf
)
# Also install at top level for #include <libelf.h> compatibility
install(FILES
    ${CMAKE_SOURCE_DIR}/libelf/libelf.h
    ${CMAKE_SOURCE_DIR}/libelf/gelf.h
    DESTINATION ${CMAKE_INSTALL_INCLUDEDIR}
)
"""
        cml_path = os.path.join(self.source_folder, "CMakeLists.txt")
        with open(cml_path, "w") as f:
            f.write(cml)

        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.libs = ["elf"]
        self.cpp_info.includedirs = ["include", "include/libelf"]
