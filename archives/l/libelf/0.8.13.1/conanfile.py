#!/usr/bin/env python3
"""Conan recipe — libelf 0.8.13.1 (CMake)

libelf is a free ELF object file access library. The upstream autotools
files are incomplete in the GitHub mirror, so this recipe generates a
CMakeLists.txt in build() to compile the source.

0.8.13.1 (OHOS port): completes the gelf API required by libbpf/libbpf-sys —
implements gelf_getnote/gelf_getversym/gelf_getverdef/gelf_getverdaux,
makes sys_elf.h use the system <elf.h> (avoids elf_repl.h redefinition),
and adds the missing GElf_Nhdr/GElf_Versym typedefs to gelf.h.
"""
import os

from conan import ConanFile
from conan.tools.files import get
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout


class LibelfConan(ConanFile):
    name = "libelf"
    version = "0.8.13.1"
    description = "ELF object file access library"
    license = "LGPL-2.0-or-later"
    homepage = "https://github.com/masc-ucsc/libelf"
    url = "https://cnb.cool/ohpcd/ohos-pc-archives/-/tree/main/archives/l/libelf/0.8.13.1"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = CMakeToolchain(self)
        tc.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        tc.generate()

    def build(self):
        # Generate CMakeLists.txt (upstream has no CMake build system)
        cml = """cmake_minimum_required(VERSION 3.15)
project(libelf C)
set(CMAKE_C_STANDARD 99)

# Generate config.h with platform defines (write to build dir, not source dir)
file(WRITE "${CMAKE_BINARY_DIR}/config.h"
"/* config.h - generated by CMake */\\n"
"#define HAVE_MMAP 1\\n"
"#define STDC_HEADERS 1\\n"
"#define HAVE_MEMSET 1\\n"
"#define HAVE_FTRUNCATE 1\\n"
"#define HAVE_GETPAGESIZE 1\\n"
"#define HAVE_MEMCMP 1\\n"
"#define HAVE_MEMCPY 1\\n"
"#define HAVE_MEMMOVE 1\\n"
"#define HAVE_AR_H 1\\n"
"#define HAVE_ELF_H 1\\n"
"#define HAVE_FCNTL_H 1\\n"
"#define HAVE_LINK_H 1\\n"
"#define HAVE_STDINT_H 1\\n"
"#define HAVE_UNISTD_H 1\\n"
"#define __LIBELF_HEADER_ELF_H <elf.h>\\n"
"#define __LIBELF64 1\\n"
"#define __LIBELF_SYMBOL_VERSIONS 1\\n"
"#define __LIBELF_GNU_SYMBOL_VERSIONS 1\\n"
"#define __libelf_i64_t long\\n"
"#define __libelf_u64_t unsigned long\\n"
"#define __libelf_i32_t int\\n"
"#define __libelf_u32_t unsigned int\\n"
"#define __libelf_i16_t short\\n"
"#define __libelf_u16_t unsigned short\\n"
"#define SIZEOF_INT 4\\n"
"#define SIZEOF_LONG 8\\n"
"#define SIZEOF_LONG_LONG 8\\n"
"#define SIZEOF_SHORT 2\\n"
"#define ENABLE_SANITY_CHECKS 1\\n"
)

file(GLOB LIBELF_SOURCES CONFIGURE_DEPENDS "${CMAKE_SOURCE_DIR}/libelf/*.c")

add_library(elf ${LIBELF_SOURCES})
target_include_directories(elf PUBLIC
    ${CMAKE_SOURCE_DIR}
    ${CMAKE_SOURCE_DIR}/libelf
    ${CMAKE_BINARY_DIR}
)
target_compile_definitions(elf PRIVATE HAVE_CONFIG_H)

include(GNUInstallDirs)
install(TARGETS elf
    ARCHIVE DESTINATION ${CMAKE_INSTALL_LIBDIR}
    LIBRARY DESTINATION ${CMAKE_INSTALL_LIBDIR}
)
install(FILES
    ${CMAKE_SOURCE_DIR}/libelf/libelf.h
    ${CMAKE_SOURCE_DIR}/libelf/gelf.h
    ${CMAKE_SOURCE_DIR}/libelf/sys_elf.h
    ${CMAKE_SOURCE_DIR}/libelf/elf_repl.h
    ${CMAKE_SOURCE_DIR}/libelf/libelf_config.h
    DESTINATION ${CMAKE_INSTALL_INCLUDEDIR}/libelf
)
# Also install at top level for #include <libelf.h> compatibility
install(FILES
    ${CMAKE_SOURCE_DIR}/libelf/libelf.h
    ${CMAKE_SOURCE_DIR}/libelf/gelf.h
    DESTINATION ${CMAKE_INSTALL_INCLUDEDIR}
)
"""
        cml_path = os.path.join(self.source_folder, "CMakeLists.txt")
        with open(cml_path, "w") as f:
            f.write(cml)

        # ── OHOS port (0.8.13.1): complete the gelf API required by libbpf ──
        # 1) gelfv.c: implement gelf_getnote/getversym/getverdef/getverdaux
        gelfv = r'''/*
 * gelfv.c - gelf versioning + note access functions (OHOS port).
 * Implements the GNU gelf API that upstream masc-ucsc libelf lacks but
 * libbpf (libbpf-sys) requires. Target: HarmonyOS PC aarch64 little-endian.
 */
#include <stdlib.h>
#include <private.h>

#if __LIBELF64

#define ALIGN_4(n)	(((n) + 3) & ~(size_t)3)

size_t
gelf_getnote(Elf_Data *data, size_t offset, GElf_Nhdr *result,
	     size_t *pname_off, size_t *pdesc_off) {
    GElf_Nhdr nhdr;
    size_t namesz, descsz, next;

    if (!data || !result) {
	seterr(ERROR_BADINDEX);
	return 0;
    }
    if (offset + sizeof(GElf_Nhdr) > data->d_size || !data->d_buf) {
	seterr(ERROR_BADINDEX);
	return 0;
    }
    nhdr = *(GElf_Nhdr*)((char*)data->d_buf + offset);
    namesz = nhdr.n_namesz;
    descsz = nhdr.n_descsz;
    next = offset + sizeof(GElf_Nhdr) + ALIGN_4(namesz) + ALIGN_4(descsz);
    if (next > data->d_size) {
	seterr(ERROR_BADINDEX);
	return 0;
    }
    *result = nhdr;
    if (pname_off) {
	*pname_off = offset + sizeof(GElf_Nhdr);
    }
    if (pdesc_off) {
	*pdesc_off = *pname_off + ALIGN_4(namesz);
    }
    return next;
}

GElf_Versym*
gelf_getversym(Elf_Data *src, int ndx, GElf_Versym *dst) {
    GElf_Versym buf;

    if (!dst) {
	dst = &buf;
    }
    if (!src || !src->d_buf || ndx < 0
     || (size_t)(ndx + 1) * sizeof(GElf_Versym) > src->d_size) {
	seterr(ERROR_BADINDEX);
	return NULL;
    }
    *dst = ((GElf_Versym*)src->d_buf)[ndx];
    if (dst == &buf) {
	GElf_Versym *tmp = (GElf_Versym*)malloc(sizeof(GElf_Versym));
	if (!tmp) {
	    seterr(ERROR_MEM_SYM);
	    return NULL;
	}
	*tmp = buf;
	return tmp;
    }
    return dst;
}

GElf_Verdef*
gelf_getverdef(Elf_Data *src, int ndx, GElf_Verdef *dst) {
    GElf_Verdef buf;
    size_t offset = 0;
    int n = ndx;

    if (!dst) {
	dst = &buf;
    }
    if (!src || !src->d_buf || ndx < 0) {
	seterr(ERROR_BADINDEX);
	return NULL;
    }
    for (;;) {
	GElf_Verdef *vd;
	if (offset + sizeof(GElf_Verdef) > src->d_size) {
	    seterr(ERROR_BADINDEX);
	    return NULL;
	}
	vd = (GElf_Verdef*)((char*)src->d_buf + offset);
	if (n == 0) {
	    *dst = *vd;
	    if (dst == &buf) {
		GElf_Verdef *tmp = (GElf_Verdef*)malloc(sizeof(GElf_Verdef));
		if (!tmp) {
		    seterr(ERROR_MEM_SYM);
		    return NULL;
		}
		*tmp = buf;
		return tmp;
	    }
	    return dst;
	}
	if (vd->vd_next == 0) {
	    seterr(ERROR_BADINDEX);
	    return NULL;
	}
	offset += vd->vd_next;
	n--;
    }
}

GElf_Verdaux*
gelf_getverdaux(Elf_Data *src, int offset, GElf_Verdaux *dst) {
    GElf_Verdaux buf;

    if (!dst) {
	dst = &buf;
    }
    if (!src || !src->d_buf || offset < 0
     || (size_t)offset + sizeof(GElf_Verdaux) > src->d_size) {
	seterr(ERROR_BADINDEX);
	return NULL;
    }
    *dst = *(GElf_Verdaux*)((char*)src->d_buf + offset);
    if (dst == &buf) {
	GElf_Verdaux *tmp = (GElf_Verdaux*)malloc(sizeof(GElf_Verdaux));
	if (!tmp) {
	    seterr(ERROR_MEM_SYM);
	    return NULL;
	}
	*tmp = buf;
	return tmp;
    }
    return dst;
}

#endif /* __LIBELF64 */
'''
        with open(os.path.join(self.source_folder, "libelf", "gelfv.c"), "w") as f:
            f.write(gelfv)

        # 2) sys_elf.h: use the system <elf.h> instead of elf_repl.h, and
        #    backfill the Solaris SHT_SUNW_* aliases that the OHOS sysroot
        #    elf.h omits (cook.c references them)
        se_path = os.path.join(self.source_folder, "libelf", "sys_elf.h")
        with open(se_path) as f:
            se = f.read()
        se = se.replace("/* #undef __LIBELF_HEADER_ELF_H */",
                        "#define __LIBELF_HEADER_ELF_H <elf.h>")
        se = se.replace(
            "#endif /* __LIBELF_HEADER_ELF_H */",
            "#endif /* __LIBELF_HEADER_ELF_H */\n\n"
            "/* OHOS port: Solaris SHT_SUNW_* aliases missing from the\n"
            " * system <elf.h> but referenced by libelf sources */\n"
            "#if defined(SHT_GNU_verdef) && !defined(SHT_SUNW_verdef)\n"
            "# define SHT_SUNW_verdef SHT_GNU_verdef\n"
            "#endif\n"
            "#if defined(SHT_GNU_verneed) && !defined(SHT_SUNW_verneed)\n"
            "# define SHT_SUNW_verneed SHT_GNU_verneed\n"
            "#endif\n"
            "#if defined(SHT_GNU_versym) && !defined(SHT_SUNW_versym)\n"
            "# define SHT_SUNW_versym SHT_GNU_versym\n"
            "#endif", 1)
        with open(se_path, "w") as f:
            f.write(se)

        # 3) gelf.h: add the missing GElf_Nhdr / GElf_Versym typedefs
        gh_path = os.path.join(self.source_folder, "libelf", "gelf.h")
        with open(gh_path) as f:
            gh = f.read()
        gh = gh.replace(
            "typedef Elf64_Sym\tGElf_Sym;",
            "typedef Elf64_Sym\tGElf_Sym;\n"
            "typedef Elf64_Nhdr\tGElf_Nhdr;\n"
            "typedef Elf64_Versym\tGElf_Versym;", 1)
        with open(gh_path, "w") as f:
            f.write(gh)

        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.libs = ["elf"]
        self.cpp_info.includedirs = ["include", "include/libelf"]
