#!/usr/bin/env python3
"""Conan recipe - librtas 2.0.4 (Autotools: autoreconf bootstrap + configure/make).

A user-space library for Run-Time Abstraction Services (RTAS) calls on ppc64,
plus the architecture-neutral librtasevent RTAS error-log event parser.

Platform note (read archives/l/librtas/2.0.4/notes.md for the full evidence):
librtas.so wraps the ppc64-only `rtas` kernel syscall (__NR_rtas 255), which
HarmonyOS aarch64 does not provide, so those entry points return librtas' own
documented negative error codes at runtime. librtasevent.so is architecture
neutral and fully functional. Both upstream libraries are delivered unmodified;
this recipe neither crops the package nor stubs the failing paths.

Rules honoured:
  R32  settings.os is compared against both Linux and OHOS.
  R33  build() takes no bare shell variables; AutotoolsToolchain drives the
       compiler and flags.
  R37  First adaptation of upstream 2.0.4, so the version is the upstream one.
  R38  Pure library (no bin/), so no commands.json is required.
  R49  No dependency injection, hence no shared /usr/local prefix.
"""
import os
import re

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


# HMDFS: a `umask 077 && mktemp -d ./confXXXXXX` scratch dir lands mode 2700
# under the shared owner (HMDFS ignores the requested mode), so config.status
# cannot write subs1.awk into it. Rewrite the scratch-dir mechanism to a fixed
# path created under umask 022. Applied to generated build files only, never to
# git-tracked sources, so no conandata `patches:` entry is required.
_HMDFS_REWRITES = (
    # primary branch: mktemp -d -> fixed writable dir, permissive umask
    (r'tmp=`\(umask 077 && mktemp -d "\./confXXXXXX"\) 2>/dev/null` &&\n'
     r'  test -d "\$tmp"',
     'tmp=./conftmp\n  (umask 022 && mkdir -p "$tmp")\n  test -d "$tmp"'),
    # non-mktemp fallback branch -> same fixed dir
    (r'tmp=\./conf\$\$-\$RANDOM', 'tmp=./conftmp'),
    # mkdir of that fallback -> permissive + -p so a rerun stays idempotent
    (r'\(umask 077 && mkdir "\$tmp"\)', '(umask 022 && mkdir -p "$tmp")'),
    # any residual umask 077 (config.status sub-shell, sub-project configure)
    (r'umask 077', 'umask 022'),
)


class LibrtasConan(ConanFile):
    name = "librtas"
    version = "2.0.4"
    description = (
        "User-space library for Run-Time Abstraction Services (RTAS) calls on "
        "ppc64, plus the librtasevent RTAS error-log event parser"
    )
    license = "LGPL-2.1-or-later"
    homepage = "https://github.com/ibm-power-utilities/librtas"
    url = "https://github.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": True}

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.shared

    def validate(self):
        # R32: settings.os must be tested against both Linux and OHOS.
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "librtas/2.0.4 supports only Linux/OHOS, not " + str(self.settings.os)
            )

    def build_requirements(self):
        # Upstream ships only configure.ac + autogen.sh; neither the GitHub tag
        # tarball nor the Debian orig tarball contains a pre-generated configure,
        # so the build must bootstrap itself with autoreconf. The CI sandbox
        # cannot see manually installed autotools, so they are pulled in as
        # conan tool_requires (same pattern as jool-modules-lts / jbig2enc).
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")

    def export_sources(self):
        # conandata.yml declares `patches: {}` (see notes.md §4.1 for why no
        # patch can apply here), so this is a no-op today. It is kept because
        # the recipe-completeness gate (conan-verify G1) requires the export /
        # apply pair to be present, and because it is the house convention in
        # every other autotools recipe in this repo -- it is what makes a later
        # patch addition work without touching the recipe's build() logic.
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        if self.settings.os == "OHOS":
            # config.guess does not recognise HarmonyOS, and the config.sub
            # generated by autoreconf does not accept an "-ohos" OS either, so
            # pass the plain aarch64-linux triplet: config.sub accepts it, and
            # the actual compiler/flags still come from the OHOS toolchain via
            # AutotoolsToolchain. Using the plain triplet avoids patching a
            # generated config.sub, whose line numbers drift between autoconf
            # releases.
            tc.configure_args.append("--build=aarch64-linux")
            tc.configure_args.append("--host=aarch64-linux")
        if not self.options.shared:
            tc.configure_args.append("--disable-shared")
            tc.configure_args.append("--enable-static")
        tc.generate()

    # ── HMDFS config.status scratch-dir fix (E011 / E129 family) ───────────
    def _hmdfs_fix(self, path, tag):
        """Neutralise the `umask 077` scratch-dir logic in ONE generated file.

        Returns the number of `umask 077` occurrences still left, and always
        prints a greppable line so a no-op can never be silent.
        """
        if not os.path.isfile(path):
            self.output.info(f"[hmdfs-fix] {tag}: SKIP not-found path={path}")
            return 0
        with open(path, "r", encoding="utf-8", errors="surrogateescape") as fh:
            text = fh.read()
        original = text
        hits = 0
        for pattern, repl in _HMDFS_REWRITES:
            text, n = re.subn(pattern, repl, text)
            hits += n
        if text != original:
            with open(path, "w", encoding="utf-8",
                      errors="surrogateescape", newline="") as fh:
                fh.write(text)
        residue = len(re.findall(r"umask 077", text))
        self.output.info(
            f"[hmdfs-fix] {tag}: conftmp={len(re.findall(r'conftmp', text))} "
            f"umask077_residue={residue} sub_hits={hits} path={path}"
        )
        return residue

    def build(self):
        apply_conandata_patches(self)   # no-op while conandata patches == {}
        autotools = Autotools(self)
        # Bootstrap: no configure in the tarball.
        autotools.autoreconf()

        if self.settings.os == "OHOS":
            # E011/E129: autoconf builds its scratch dir with
            #   `(umask 077 && mktemp -d "./confXXXXXX")`
            # HMDFS lands such a directory with mode 2700 under the shared
            # owner and ignores the requested mode, so the subsequent
            # `echo ... >"$ac_tmp/subs1.awk"` is refused and config.status dies
            # with "could not setup config files machinery".
            # Fix the *generated* configure before running it: configure copies
            # this block verbatim into the config.status it writes, so a single
            # pass repairs both (verified: 2 -> 0 occurrences in each file).
            # Nothing is committed to git -- this is a build-time fix on a
            # generated artefact, so conandata `patches:` stays empty (same
            # shape as the integrit / 4ti2 / libgta precedents).
            self._hmdfs_fix(os.path.join(self.source_folder, "configure"),
                            "pre-configure/configure")

        autotools.configure()

        if self.settings.os == "OHOS":
            # configure invokes ./config.status itself, so a failure above aborts
            # configure. This read-back is the anti-silent check: if a future
            # autoconf stops copying the block into config.status, the residue
            # is non-zero here and says so instead of failing mysteriously.
            residue = self._hmdfs_fix(
                os.path.join(self.build_folder, "config.status"),
                "post-configure/config.status")
            if residue:
                self.output.warn(
                    f"HMDFS: config.status still carries {residue} 'umask 077' "
                    "occurrence(s); config.status may fail on this filesystem"
                )
        # E074: HMDFS jobserver fifo EPERM - keep the single-job default.
        autotools.make(args=["-j1"])

    def package(self):
        Autotools(self).install()

    def package_info(self):
        # Upstream builds two libraries: librtas (the RTAS syscall wrappers) and
        # librtasevent (the arch-neutral RTAS event parser). Both are delivered.
        self.cpp_info.libs = ["rtas", "rtasevent"]
