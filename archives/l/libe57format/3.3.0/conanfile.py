# Static-build equivalent of CMake GenerateExportHeader output for E57_DLL.
# Upstream E57Exception.h includes E57Export.h; every public header uses
# E57_DLL. For static builds the macro is empty; the shared branch keeps
# the ELF visibility attribute and is activated by -DE57Format_EXPORTS
# (which upstream passes as a PRIVATE lib definition for shared builds).
_EXPORT_HEADER = """#pragma once
// NOTE: Generated by the conan recipe (direct-compile build, no CMake).
// Static/shared equivalent of CMake GenerateExportHeader output for E57_DLL.
#if defined(E57Format_EXPORTS)
#  define E57_DLL __attribute__((visibility("default")))
#else
#  define E57_DLL
#endif
#define E57_NO_EXPORT
#define E57_DEPRECATED
#define E57_DEPRECATED_EXPORT
#define E57_DEPRECATED_NO_EXPORT
"""


class Libe57formatConan(ConanFile):
    name = "libe57format"
    version = "3.3.0"
    description = "Library for reading and writing the E57 3D point cloud file format"
    license = "BSL-1.0"
    homepage = "https://github.com/asmaloney/libE57Format"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            self.options.rm_safe("fPIC")

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")
        # Safety net only: requirements() pins xerces-c to the ohpcd in-repo
        # revision, which has no 'network' option, so the block below is a
        # no-op in practice. It is kept so the recipe still configures if
        # the pin is ever lifted and a ConanCenter revision (whose
        # network_accessor=socket validate() is Linux/Mac/Android-only and
        # marks the package Invalid on OHOS) gets resolved: E57 XML parsing
        # is purely local, so xerces-c network support is dropped whenever
        # that option exists.
        try:
            self.options["xerces-c"].network = False
        except Exception:
            pass

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # RREV pin: bare "xerces-c/3.2.5" resolves to the ConanCenter recipe
        # whenever conancenter is enabled and ordered first (HMBS preflight).
        # Pin the ohpcd-published in-repo revision instead (adapted recipe +
        # published binary). Same pattern as atracdenc/libsndfile+gtest.
        # RREV is the ohpcd registry value (conan v2 revisions API,
        # 2026-09-14), never locally recomputed.
        self.requires("xerces-c/3.2.5#9086fe3ffea711440f8f71d66d6ca6d0")

    def build_requirements(self):
        # Only needed to compile the upstream test suite; never propagated.
        # Pinned for the same reason: bare gtest refs can resolve to the CCI
        # revision in preflight. RREV from ohpcd revisions API, 2026-09-14.
        self.test_requires("gtest/1.17.0.1#9ffddd9d9fcc4049457a71bc4b81d2ee")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        # Upstream keeps its test data (~1 MB of .e57 fixtures) in a separate
        # repo. Fetch it next to the sources so the *Data gtest suites really
        # run instead of being filtered out by testE57's main().
        test_data = self.conan_data.get("test_data")
        if test_data:
            get(self, url=test_data["url"], sha256=test_data["sha256"],
                destination=os.path.join(self.source_folder, "libE57Format-test-data"),
                strip_root=True)

    def _writable_tmpdir(self):
        # E002: OHOS /tmp is a read-only mount. Reuse the HMBS-injected task
        # temp dir (TMPDIR/TMP/TEMP first), then the autoconf fallback, else
        # a build_folder subdir. Cloned from the merged clamav-libunrar
        # recipe (same worker family, same readonly_tmp diagnosis).
        for var in ("TMPDIR", "TMP", "TEMP"):
            value = os.environ.get(var)
            if value and value != "/tmp":
                try:
                    os.makedirs(value, exist_ok=True)
                except OSError:
                    pass
                if os.path.isdir(value):
                    return value
        fallback = os.environ.get("HMBS_AUTOCONF_MKTEMP_FALLBACK")
        if fallback and fallback != "/tmp":
            try:
                os.makedirs(fallback, exist_ok=True)
            except OSError:
                pass
            if os.path.isdir(fallback):
                return fallback
        cand = os.path.join(self.build_folder, "tmp_hmbs")
        try:
            os.makedirs(cand, exist_ok=True)
        except OSError:
            return self.build_folder
        return cand

    def _cxx(self):
        # R33: compiler comes from the Conan conf (authoritative OHOS
        # profile value), never from a bare ${CXX} shell variable.
        # (ddate/clamav-libunrar/critnib precedent, adapted.)
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        ) or {}
        path = compilers.get("cpp")
        if path and os.path.isfile(path):
            return path
        if path:
            return shutil.which(os.path.basename(path)) or path
        return shutil.which("clang++") or "clang++"

    def _ar(self):
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        ) or {}
        path = compilers.get("ar", "")
        if path and os.path.isfile(path):
            return path
        for cand in ("llvm-ar", "ar"):
            resolved = shutil.which(cand)
            if resolved:
                return resolved
        return "llvm-ar"

    def _probe_toolchain(self, cxx):
        # critnib precedent: a trivial compile+link smoke test runs first so
        # a genuinely broken toolchain shows its real stderr here instead of
        # surfacing later as an opaque build failure (fail closed).
        probe_c = os.path.join(self.build_folder, "hmbs_cc_probe.cpp")
        probe_o = os.path.join(self.build_folder, "hmbs_cc_probe")
        with open(probe_c, "w") as f:
            f.write("int main(){return 0;}\n")
        cmd = [cxx, "-stdlib=libc++", probe_c, "-o", probe_o]
        proc = subprocess.run(cmd, stdout=subprocess.PIPE,
                              stderr=subprocess.STDOUT, text=True, timeout=300)
        self.output.info("toolchain probe: {0} rc={1}".format(" ".join(cmd),
                                                              proc.returncode))
        if proc.returncode != 0:
            raise ConanException(
                "OHOS toolchain probe failed (real stderr follows):\n{0}".format(proc.stdout))

    def _lib_flags(self):
        opt = "-O0 -g" if str(self.settings.build_type) == "Debug" else "-O2 -DNDEBUG"
        flags = "-std=c++14 -stdlib=libc++ -pthread {0}".format(opt)
        if self.options.get_safe("fPIC", True):
            flags += " -fPIC"
        if self.options.shared:
            # Mirrors upstream PRIVATE definition for shared builds.
            flags += " -DE57Format_EXPORTS"
        # Mirrors upstream option defaults (all OFF except diagnostic output
        # and validation level 1, same as upstream CI).
        flags += (' -DREVISION_ID=\\"E57Format-3.3.0-aarch64-OHOS-clang\\"'
                   " -DE57_VALIDATION_LEVEL=1 -DE57_ENABLE_DIAGNOSTIC_OUTPUT"
                   " -DCRCPP_USE_CPP11 -DCRCPP_BRANCHLESS")
        return flags

    def _lib_includes(self, gen_dir):
        src = self.source_folder
        return '-I"{0}" -I"{1}" -I"{2}" -I"{3}"'.format(
            os.path.join(src, "src"),
            os.path.join(src, "include"),
            os.path.join(src, "extern", "CRCpp", "inc"),
            gen_dir)

    def _dep_flags(self, dep_name, want_libs=True):
        # Include/lib search paths for a Conan dependency (pktanon
        # precedent): headers and archives come from the dependency's
        # cpp_info, never from hardcoded absolute paths.
        if dep_name not in self.dependencies:
            raise ConanException(
                "dependency '{0}' not in graph; cannot derive flags".format(dep_name))
        dep = self.dependencies[dep_name]
        incs = " ".join('"-I{0}"'.format(d) for d in dep.cpp_info.includedirs)
        if not want_libs:
            return incs
        libds = " ".join('"-L{0}"'.format(d) for d in dep.cpp_info.libdirs)
        libs = " ".join('"-l{0}"'.format(l) for l in dep.cpp_info.libs)
        return "{0} {1} {2}".format(incs, libds, libs).strip()

    def _dep_link(self, dep_name):
        # Link-only flags (-L/-l) for a dependency, derived from structured
        # cpp_info instead of string-splitting _dep_flags() output (whose
        # quoted tokens, e.g. '"-L/path"', never start with -L/-l and would
        # silently filter down to an empty string).
        if dep_name not in self.dependencies:
            raise ConanException(
                "dependency '{0}' not in graph; cannot derive flags".format(dep_name))
        dep = self.dependencies[dep_name]
        agg = dep.cpp_info.aggregated_components()
        libds = " ".join('"-L{0}"'.format(d) for d in agg.libdirs)
        libs = " ".join('"-l{0}"'.format(l) for l in agg.libs)
        syslibs = " ".join('"-l{0}"'.format(l) for l in agg.system_libs)
        flags = "{0} {1} {2}".format(libds, libs, syslibs).strip()
        if not libs:
            raise ConanException(
                "dependency '{0}' aggregated libs empty; cannot link".format(dep_name))
        self.output.info("{0} link: {1}".format(dep_name, flags))
        return flags

    def _gtest_includes(self):
        if "gtest" not in self.dependencies:
            raise ConanException("dependency 'gtest' not in graph; cannot derive flags")
        dep = self.dependencies["gtest"]
        # gtest recipe declares components (gtest/gtest_main/gmock/...), so the
        # top-level cpp_info.libs is empty; aggregated view merges components.
        agg = dep.cpp_info.aggregated_components()
        return " ".join('"-I{0}"'.format(d) for d in agg.includedirs)

    def _gtest_link(self):
        # Upstream test/src/main.cpp provides its own main() (with the
        # *Data filter), so only gtest itself is linked — never gtest_main
        # (linking both would duplicate main).
        if "gtest" not in self.dependencies:
            raise ConanException("dependency 'gtest' not in graph; cannot derive flags")
        dep = self.dependencies["gtest"]
        # Component recipe: aggregate gtest+gmock component libs/libdirs.
        agg = dep.cpp_info.aggregated_components()
        # Prefer the exact "gtest" lib (upstream provides its own main()).
        # Fall back to all non-main component libs if the name ever changes.
        if "gtest" in agg.libs:
            libs = ["gtest"]
        else:
            libs = [l for l in agg.libs if "main" not in l.lower()]
            if not libs:
                libs = list(agg.libs)
        if not libs:
            raise ConanException(
                "gtest aggregated libs empty; cannot link upstream tests")
        libds = " ".join('"-L{0}"'.format(d) for d in agg.libdirs)
        libnames = " ".join('"-l{0}"'.format(l) for l in libs)
        self.output.info("gtest libs used: {0}".format(" ".join(libs)))
        return "{0} {1}".format(libds, libnames).strip()

    def build(self):
        apply_conandata_patches(self)
        # E002: export the writable tmpdir before any child process (clang)
        # is spawned so no temp file falls back to read-only /tmp.
        writable_tmp = self._writable_tmpdir()
        for key in ("TMPDIR", "TMP", "TEMP"):
            os.environ[key] = writable_tmp
        self.output.info("[HMBS tmp] build TMPDIR={0}".format(writable_tmp))

        cxx = self._cxx()
        self.output.info("direct compile with cxx={0}".format(cxx))
        self._probe_toolchain(cxx)

        # Generated export header (GenerateExportHeader equivalent, see
        # module docstring). Installed to include/E57Format/ like upstream.
        gen_dir = os.path.join(self.build_folder, "gen_include")
        os.makedirs(gen_dir, exist_ok=True)
        with open(os.path.join(gen_dir, "E57Export.h"), "w", newline="\n") as f:
            f.write(_EXPORT_HEADER)

        obj_dir = os.path.join(self.build_folder, "obj")
        os.makedirs(obj_dir, exist_ok=True)
        flags = self._lib_flags()
        incs = self._lib_includes(gen_dir)
        xerces_inc = self._dep_flags("xerces-c", want_libs=False)

        objects = []
        missing = [s for s in _LIB_SOURCES
                   if not os.path.isfile(os.path.join(self.source_folder, "src", s))]
        if missing:
            raise ConanException("lib sources missing: {0}".format(", ".join(missing)))
        for src_file in _LIB_SOURCES:
            src_path = os.path.join(self.source_folder, "src", src_file)
            obj_path = os.path.join(obj_dir, src_file.replace(".cpp", ".o"))
            self.run('"{0}" {1} {2} {3} -c "{4}" -o "{5}"'.format(
                cxx, flags, incs, xerces_inc, src_path, obj_path))
            objects.append('"{0}"'.format(obj_path))
        self.output.info("libe57format objects compiled: {0}".format(len(objects)))

        lib_file = os.path.join(self.build_folder, "libE57Format.a")
        if self.options.shared:
            # Upstream VERSION 3.3.0 / SOVERSION 3 naming (clamav precedent
            # for the versioned .so + SONAME + tolerant signing flow).
            so_file = os.path.join(self.build_folder, "libE57Format.so.3.3.0")
            self.run('"{0}" -shared -stdlib=libc++ -Wl,-soname,libE57Format.so.3'
                     ' {1} -o "{2}"'.format(cxx, " ".join(objects), so_file))
            self._make_version_links(so_file)
            self._sign_shared_libs()
            lib_file = so_file
        else:
            ar = self._ar()
            self.output.info("archiving with ar={0}".format(ar))
            self.run('"{0}" rcs "{1}" {2}'.format(ar, lib_file, " ".join(objects)))

        self._build_and_run_upstream_tests(cxx, gen_dir, lib_file)

    def _build_and_run_upstream_tests(self, cxx, gen_dir, lib_file):
        test_src_dir = os.path.join(self.source_folder, "test", "src")
        test_inc_dir = os.path.join(self.source_folder, "test", "include")
        names = list(_TEST_SOURCES)
        if not self.options.shared:
            names += _TEST_SOURCES_STATIC_ONLY
        missing = [s for s in names if not os.path.isfile(os.path.join(test_src_dir, s))]
        if missing:
            raise ConanException("upstream test sources missing: {0}".format(", ".join(missing)))

        # Same value upstream find_path(E57_TEST_DATA_PATH ...) would produce
        # given our source() layout (fixtures live at
        # <source>/libE57Format-test-data).
        data_dir = os.path.join(self.source_folder, "libE57Format-test-data")
        if not os.path.isdir(data_dir):
            raise ConanException(
                "upstream test data missing at {0}; *Data suites must really run, "
                "never be silently filtered".format(data_dir))

        opt = "-O0 -g" if str(self.settings.build_type) == "Debug" else "-O2 -DNDEBUG"
        # C++17: GTest 1.17 headers require it (same reason the old CMake flow
        # raised the test target from upstream cxx_std_14).
        tflags = ("-std=c++17 -stdlib=libc++ -pthread {0} -DE57_VALIDATION_LEVEL=1"
                  " -DTEST_DATA_PATH='\"{1}\"'".format(opt, data_dir))
        tincs = ('-I"{0}" -I"{1}" -I"{2}" -I"{3}" -I"{4}"'.format(
            test_src_dir, test_inc_dir,
            os.path.join(self.source_folder, "src"),
            os.path.join(self.source_folder, "include"),
            gen_dir))
        gtest_flags = self._gtest_includes()
        xerces_inc = self._dep_flags("xerces-c", want_libs=False)

        test_obj_dir = os.path.join(self.build_folder, "test_obj")
        os.makedirs(test_obj_dir, exist_ok=True)
        test_objects = []
        for src_file in names:
            src_path = os.path.join(test_src_dir, src_file)
            obj_path = os.path.join(test_obj_dir, src_file.replace(".cpp", ".o"))
            self.run('"{0}" {1} {2} {3} {4} -c "{5}" -o "{6}"'.format(
                cxx, tflags, tincs, gtest_flags, xerces_inc, src_path, obj_path))
            test_objects.append('"{0}"'.format(obj_path))

        test_exe = os.path.join(self.build_folder, "testE57")
        xerces_link = self._dep_link("xerces-c")
        gtest_link = self._gtest_link()
        self.run('"{0}" -stdlib=libc++ -pthread {1} "{2}" {3} {4} -lpthread -lm'
                 ' -o "{5}"'.format(
                     cxx, " ".join(test_objects), lib_file,
                     xerces_link, gtest_link, test_exe))

        bash = os.environ.get("CONFIG_SHELL", "/data/service/hnp/bin/bash")
        # Shared mode: the test binary loads the just-built .so from the
        # build tree (no RPATH is emitted by the direct link); scope
        # LD_LIBRARY_PATH to the test invocations only (never exported).
        run_prefix = ('LD_LIBRARY_PATH="{0}" '.format(self.build_folder)
                      if self.options.shared else "")
        discovered = self._gtest_discovered(bash, test_exe, run_prefix)
        result = self._run_gtest(bash, test_exe, discovered, run_prefix)
        self.output.info("HMBS_UPSTREAM_TEST_RESULT=" + json.dumps(result))
        if result["status"] != "passed":
            raise ConanException("upstream tests failed: {0}".format(result))

    def _gtest_discovered(self, bash, test_exe, run_prefix=""):
        # Count first (gtest_list_tests), run second: a silent *Data filter
        # (missing fixtures) would show up as executed < discovered instead
        # of a fake full pass.
        env = dict(os.environ)
        for key in ("TMPDIR", "TMP", "TEMP"):
            if env.get(key, "/tmp") == "/tmp":
                env[key] = os.path.join(self.build_folder, "tmp_hmbs")
        try:
            os.makedirs(env.get("TMPDIR"), exist_ok=True)
        except OSError:
            pass
        proc = subprocess.run(
            [bash, "-c", '{0}"{1}" --gtest_list_tests'.format(run_prefix, test_exe)],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, timeout=300, cwd=self.build_folder, env=env)
        if proc.returncode != 0:
            raise ConanException(
                "testE57 --gtest_list_tests failed:\n{0}".format(proc.stdout))
        count = 0
        for line in proc.stdout.splitlines():
            if line.startswith("  ") and line.strip() and not line.strip().startswith("#"):
                count += 1
        self.output.info("upstream discovered TEST cases: {0}".format(count))
        if count == 0:
            raise ConanException("no upstream TEST cases discovered")
        return count

    def _run_gtest(self, bash, test_exe, discovered, run_prefix=""):
        # Writable TMPDIR is propagated explicitly (not only via os.environ)
        # so the test children never fall back to read-only /tmp (E002).
        # Only the temp-dir root is redirected; no test is skipped/removed.
        env = dict(os.environ)
        writable_tmp = (env.get("TMPDIR") or env.get("TMP") or env.get("TEMP")
                        or os.path.join(self.build_folder, "tmp_hmbs"))
        try:
            os.makedirs(writable_tmp, exist_ok=True)
        except OSError:
            writable_tmp = self.build_folder
        for key in ("TMPDIR", "TMP", "TEMP"):
            env[key] = writable_tmp
        self.output.info("[HMBS tmp] test TMPDIR={0}".format(writable_tmp))
        # --gtest_color=no overrides upstream main.cpp's FLAGS_gtest_color=yes
        # (parsed by InitGoogleTest after the assignment); output formatting
        # only, zero test-semantics change. Makes the summary regex robust.
        proc = subprocess.run(
            [bash, "-c", '{0}"{1}" --gtest_color=no'.format(run_prefix, test_exe)],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, timeout=1800, cwd=self.build_folder, env=env)
        output = proc.stdout or ""
        # Keep the transcript tail in the log as non-empty evidence.
        tail = output[-3000:] if len(output) > 3000 else output
        self.output.info("=== testE57 tail ===\n{0}".format(tail))
        import re
        # Strip ANSI color sequences (defensive: --gtest_color=no should
        # already disable them, but a forced color build must not break the
        # hard-gate counters into executed=0).
        clean = re.sub(r"\x1b\[[0-9;]*[mK]", "", output)
        ran = 0
        passed = 0
        skipped = 0
        failed_direct = None
        m = re.search(r"\[\s*==========\s*\]\s*(\d+)\s+tests?\s+from\s+.*\s+ran\.", clean)
        if m:
            ran = int(m.group(1))
        m = re.search(r"\[\s*PASSED\s*\]\s*(\d+)\s+tests?\.", clean)
        if m:
            passed = int(m.group(1))
        # GTest 1.17 prints "[  SKIPPED ] 1 test, listed below:" (comma);
        # accept '.' as well for other versions.
        m = re.search(r"\[\s*SKIPPED\s*\]\s*(\d+)\s+tests?[,.]", clean)
        if m:
            skipped = int(m.group(1))
        m = re.search(r"\[\s*FAILED\s*\]\s*(\d+)\s+tests?[,.\s]", clean)
        if m:
            failed_direct = int(m.group(1))
        if ran == 0:
            # Fallback: summary lines missing (crash/format change) must not
            # collapse into executed=0. Count per-test verdict lines instead
            # (truthful: each line is one really-executed TEST case).
            # Anchored on the trailing "(N ms)" so summary repeat lines
            # ("1 test, listed below:" / re-listed names without timing)
            # are never double-counted.
            ok_n = len(re.findall(r"\[\s*OK\s*\][^\n]*\(\d+ ms\)", clean))
            fail_n = len(re.findall(r"\[\s*FAILED\s*\][^\n]*\(\d+ ms\)", clean))
            skip_n = len(re.findall(r"\[\s*SKIPPED\s*\][^\n]*\(\d+ ms\)", clean))
            if ok_n + fail_n + skip_n > 0:
                ran = ok_n + fail_n + skip_n
                passed = ok_n
                if skipped == 0:
                    skipped = skip_n
                if ran > discovered:
                    ran = discovered
        failed = failed_direct if failed_direct is not None else (ran - passed - skipped)
        # A GTEST_SKIP (e.g. fr_FR locale missing on OHOS) is a legitimate
        # skip, not a failure: pass when everything ran and nothing failed.
        status = "passed" if (proc.returncode == 0 and ran > 0 and ran == discovered
                              and failed == 0 and passed + skipped == ran) else "failed"
        return {
            "status": status,
            "framework": "gtest",
            "command": "./testE57",
            "discovered": discovered,
            "executed": ran,
            "passed": passed,
            "failed": max(failed, 0),
            "skipped": skipped,
        }

    def _make_version_links(self, so_file):
        # Versioned .so symlink set (clamav precedent); falls back to copies
        # where the filesystem forbids symlinks (HMBS_CAP_SYMLINK).
        libdir = os.path.dirname(so_file)
        real = os.path.basename(so_file)
        for link in ("libE57Format.so.3", "libE57Format.so"):
            link_path = os.path.join(libdir, link)
            try:
                if os.path.islink(link_path) or os.path.isfile(link_path):
                    os.unlink(link_path)
            except OSError:
                pass
            try:
                os.symlink(real, link_path)
            except OSError:
                shutil.copy2(so_file, link_path)

    def _sign_shared_libs(self):
        # HarmonyOS PC requires code signing for .so loaded via dlopen
        # (clamav/zstd/expat precedent). Tolerant when the signing tools are
        # absent (e.g. Linux dev machine).
        import glob
        targets = glob.glob(os.path.join(self.build_folder, "*.so*"))
        targets = [t for t in targets if os.path.isfile(t) and not os.path.islink(t)]
        if not targets:
            return
        objcopy = os.environ.get("LLVM_OBJCOPY", "/data/service/hnp/bin/llvm-objcopy")
        signer = os.environ.get("BINARY_SIGN_TOOL", "/data/service/hnp/bin/binary-sign-tool")
        if not os.path.isfile(signer) and not shutil.which("binary-sign-tool"):
            self.output.warning("binary-sign-tool not found, skipping code signing")
            return
        if not os.path.isfile(objcopy) and not shutil.which("llvm-objcopy"):
            objcopy = "llvm-objcopy"
        for target in targets:
            self.run('{0} --remove-section .codesign "{1}" 2>/dev/null || true'.format(
                objcopy, target))
            self.run('{0} sign -inFile "{1}" -outFile "{1}" -selfSign 1'.format(signer, target))

    def package(self):
        if self.options.shared:
            # Ship the real versioned file, then (re)create the SONAME/dev
            # links in the package (clamav precedent): conan copy must not
            # be relied on to preserve build-tree symlinks.
            copy(self, "libE57Format.so.3.3.0", self.build_folder,
                 os.path.join(self.package_folder, "lib"))
            self._make_version_links(
                os.path.join(self.package_folder, "lib", "libE57Format.so.3.3.0"))
        else:
            copy(self, "libE57Format.a", self.build_folder,
                 os.path.join(self.package_folder, "lib"))
        # Upstream install() layout: public headers + generated export header
        # under include/E57Format/.
        copy(self, "*.h", os.path.join(self.source_folder, "include"),
             os.path.join(self.package_folder, "include", "E57Format"))
        copy(self, "E57Export.h", os.path.join(self.build_folder, "gen_include"),
             os.path.join(self.package_folder, "include", "E57Format"))
        copy(self, "LICENSE.md", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "e57format")
        self.cpp_info.set_property("cmake_target_name", "E57Format")
        self.cpp_info.libs = ["E57Format"]
        if self.settings.os in ("Linux", "OHOS"):
            self.cpp_info.system_libs.extend(["m", "pthread"])
