#!/usr/bin/env python3
"""Conan recipe — libe57format 3.3.0 (direct compile, no CMake project()).

E57 3D point-cloud file format library (Simple API + Foundation API).
XML parsing is provided by Xerces-C 3.2. The upstream GoogleTest suite
(test/testE57, 43 TEST cases) is compiled and executed directly during
build() so `conan create` really runs the official tests.

Build approach: direct compile with the Conan-configured OHOS clang++
(ddate/clamav-libunrar/critnib precedent). No CMake project() is executed
at all, so the preflight failure mode "compiler identification is unknown"
(CMake 4.x cannot identify the OHOS SDK clang: no Platform/HarmonyOS
module AND the Linux-override variant still fails ID) cannot occur. Three
independent recipes hit the same wall on this worker (ddate doc: 3 rounds
incl. Linux-mapping still red; critnib: Linux-override + writable TMPDIR
still red; this package: rounds 1-3), while direct-compile recipes merged
(clamav-libunrar 2026-09-10, critnib 2026-09-11).

Replicated upstream semantics (audited against v3.3.0 CMake files):
- Library: the exact 42 .cpp from src/CMakeLists.txt, C++14, -fPIC,
  -DREVISION_ID / -DE57_VALIDATION_LEVEL=1 / -DE57_ENABLE_DIAGNOSTIC_OUTPUT
  / -DCRCPP_USE_CPP11 / -DCRCPP_BRANCHLESS, -I src/include/extern-CRCpp.
  Static archive via llvm-ar (default); shared links -shared with the
  upstream SONAME when options.shared=True.
- E57Export.h: static/shared equivalent of CMake GenerateExportHeader
  output (E57_DLL empty for static), generated into the build tree and
  installed to include/E57Format/ like upstream.
- Tests: the exact test/src/*.cpp set (test_StringFunctions.cpp only for
  the static build, mirroring upstream), C++17 (GTest 1.17 requirement),
  -DTEST_DATA_PATH="<source>/libE57Format-test-data" (same value upstream
  find_path() would produce given our source() layout), linked against
  gtest (upstream's own main.cpp provides main(), so gtest_main is NOT
  linked) + the fresh static lib + xerces-c. Sanitizers/LTO/ccache and
  warning flags are build-environment ornamentation and are skipped
  (OHOS NDK has no ASan/UBSan runtime; -O2 used instead of LTO).
"""

