#!/usr/bin/env python3
"""Conan recipe for the libstroke 0.5.1 core gesture recognizer."""

import os
import shlex
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    save,
)
from conan.tools.layout import basic_layout


class LibstrokeConan(ConanFile):
    name = "libstroke"
    version = "0.5.1"
    package_type = "library"
    description = "Lightweight mouse and pen stroke translation library"
    license = "GPL-2.0-only"
    homepage = "https://www.etla.net/libstroke/"
    url = "https://atomgit.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("libstroke supports Linux and OHOS only")
        if self.settings.os == "OHOS" and self.settings.arch != "armv8":
            raise ConanInvalidConfiguration("OHOS builds require armv8/aarch64")

    def layout(self):
        basic_layout(self, src_folder="src")

    def source(self):
        get(
            self,
            **self.conan_data["sources"][str(self.version)],
            strip_root=True,
        )

    def _tools(self):
        executables = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        )
        cc = executables.get("c") or shutil.which("clang") or "clang"
        ar = executables.get("ar")
        if not ar:
            sibling_ar = os.path.join(os.path.dirname(cc), "llvm-ar")
            ar = sibling_ar if os.path.isfile(sibling_ar) else shutil.which("llvm-ar")
        if not ar:
            raise ConanInvalidConfiguration("llvm-ar is required to package libstroke")
        return cc, ar

    def build(self):
        apply_conandata_patches(self)
        cc, ar = self._tools()

        # Upstream's 2001 configure script always probes X11, although the core
        # recognizer is X11-independent unless STROKE_MOUSE_FOOTPRINTS is set.
        # Compile the one real core source directly with Conan's OHOS compiler.
        config_h = os.path.join(self.build_folder, "config.h")
        save(self, config_h, "/* Generated by the Conan recipe. */\n")
        source = os.path.join(self.source_folder, "libstroke", "stroke.c")
        obj = os.path.join(self.build_folder, "stroke.o")
        include_flags = [
            "-I" + self.build_folder,
            "-I" + os.path.join(self.source_folder, "libstroke"),
        ]
        flags = ["-std=c99", "-O2" if self.settings.build_type == "Release" else "-O0"]
        if self.options.get_safe("fPIC"):
            flags.append("-fPIC")

        compile_args = [cc, *include_flags, *flags, "-c", source, "-o", obj]
        self.run(" ".join(shlex.quote(str(arg)) for arg in compile_args), env="conanbuild")

        if self.options.shared:
            output = os.path.join(self.build_folder, "libstroke.so")
            link_args = [cc, "-shared", "-o", output, obj, "-lm"]
            self.run(" ".join(shlex.quote(str(arg)) for arg in link_args), env="conanbuild")
        else:
            output = os.path.join(self.build_folder, "libstroke.a")
            archive_args = [ar, "rcs", output, obj]
            self.run(" ".join(shlex.quote(str(arg)) for arg in archive_args), env="conanbuild")

        self.output.info(
            'HMBS_UPSTREAM_TEST_RESULT: {"framework":"none",'
            '"command":"source tree and Makefile audit: no automated test target",'
            '"discovered":0,"executed":0,"passed":0,"failed":0,"skipped":0}'
        )

    def package(self):
        extension = "so" if self.options.shared else "a"
        copy(
            self,
            "libstroke." + extension,
            self.build_folder,
            os.path.join(self.package_folder, "lib"),
        )
        copy(
            self,
            "stroke.h",
            os.path.join(self.source_folder, "libstroke"),
            os.path.join(self.package_folder, "include"),
        )
        copy(self, "COPYING", self.source_folder, os.path.join(self.package_folder, "licenses"))
        copy(self, "COPYRIGHT", self.source_folder, os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.libs = ["stroke"]
        self.cpp_info.system_libs = ["m"]
        self.cpp_info.set_property("cmake_file_name", "libstroke")
        self.cpp_info.set_property("cmake_target_name", "libstroke::libstroke")
        self.cpp_info.set_property("pkg_config_name", "libstroke")
