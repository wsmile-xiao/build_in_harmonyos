/* L1 consumer test for libpgm (OpenPGM 5.3.128).
 *
 * Exercises the installed public API and asserts values produced by the
 * library itself, so a stale/empty/faked package cannot pass:
 *   - version triple from version.c generated at build time;
 *   - deterministic GSI/TSI fingerprints produced by pgm_gsi_* / pgm_tsi_*;
 *   - engine start-up/shutdown through pgm_init()/pgm_shutdown().
 * On OHOS it additionally pins the build fingerprint reported by the library
 * (platform.system()/platform.machine() at build time).
 */
#include <stdio.h>
#include <string.h>

#include <pgm/pgm.h>

static unsigned failures;

static void check(int condition, const char* what)
{
    if (condition) {
        printf("ok   - %s\n", what);
    } else {
        printf("FAIL - %s\n", what);
        failures++;
    }
}

int main(void)
{
    char buf[128];

    /* version.c is generated by version_generator.py from the library sources */
    check(pgm_major_version == 5 && pgm_minor_version == 3 &&
          pgm_micro_version == 128,
          "version triple is 5.3.128");
    check(pgm_build_date != NULL && pgm_build_date[0] != '\0',
          "build date recorded in the artifact");
    check(pgm_build_machine != NULL && pgm_build_machine[0] != '\0',
          "build machine recorded in the artifact");

    /* GSI creation + deterministic textual fingerprint */
    const uint8_t data[6] = { 0x01, 0x02, 0x03, 0x04, 0x05, 0x06 };
    pgm_gsi_t gsi;
    check(pgm_gsi_create_from_data(&gsi, data, sizeof(data)),
          "pgm_gsi_create_from_data()");
    check(pgm_gsi_print_r(&gsi, buf, sizeof(buf)) > 0, "pgm_gsi_print_r()");
    check(strcmp(buf, "123.232.84.82.44.76") == 0,
          "GSI fingerprint of {1,2,3,4,5,6}");

    check(pgm_gsi_create_from_string(&gsi, "192.168.1.1", -1),
          "pgm_gsi_create_from_string(\"192.168.1.1\")");
    check(pgm_gsi_print_r(&gsi, buf, sizeof(buf)) > 0, "pgm_gsi_print_r() again");
    check(strcmp(buf, "39.27.71.212.86.219") == 0,
          "GSI fingerprint of 192.168.1.1");

    /* TSI = GSI + source port */
    pgm_tsi_t tsi;
    memset(&tsi, 0, sizeof(tsi));
    tsi.gsi = gsi;
    tsi.sport = 12345;
    check(pgm_tsi_print_r(&tsi, buf, sizeof(buf)) > 0, "pgm_tsi_print_r()");
    check(strcmp(buf, "39.27.71.212.86.219.14640") == 0,
          "TSI fingerprint of 192.168.1.1:12345");

#if defined(__OHOS__)
    /* HarmonyOS-specific: the artifact must have been built on this platform */
    check(pgm_build_system != NULL && strcmp(pgm_build_system, "HarmonyOS") == 0,
          "OHOS: artifact reports build system HarmonyOS");
    check(pgm_build_machine != NULL && strcmp(pgm_build_machine, "aarch64") == 0,
          "OHOS: artifact reports build machine aarch64");
#endif

    /* engine lifecycle through the public API */
    pgm_error_t* err = NULL;
    check(pgm_init(&err), "pgm_init()");
    if (err != NULL) {
        printf("     pgm_init error: %s\n", err->message ? err->message : "(null)");
        pgm_error_free(err);
        err = NULL;
    }
    check(pgm_shutdown(), "pgm_shutdown()");

    if (failures != 0) {
        printf("%u check(s) failed\n", failures);
        return 1;
    }
    printf("all checks passed\n");
    return 0;
}
