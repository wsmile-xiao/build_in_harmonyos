class LibmodplugTestConan(ConanFile):
    settings = "os", "compiler", "build_type", "arch"
    generators = "CMakeDeps", "CMakeToolchain"
    test_type = "explicit"

    def requirements(self):
        self.requires(self.tested_reference_str)

    def layout(self):
        cmake_layout(self)

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def test(self):
        VirtualRunEnv(self).generate()
        binary = os.path.join(self.cpp.build.bindirs[0], "test_modplug")

        fixture = os.path.join(os.path.dirname(binary), "ohpc_test.mod")
        data = base64.b64decode(_FIXTURE_B64, validate=True)
        if len(data) != _FIXTURE_SIZE:
            raise RuntimeError(
                f"fixture size mismatch: {len(data)} != {_FIXTURE_SIZE}"
            )

        digest = hashlib.sha256(data).hexdigest()
        if digest != _FIXTURE_SHA256:
            raise RuntimeError(
                f"fixture sha256 mismatch: {digest} != {_FIXTURE_SHA256}"
            )

        with open(fixture, "wb") as fh:
            fh.write(data)

        self.run(f'"{binary}" "{fixture}"', env="conanrun")
