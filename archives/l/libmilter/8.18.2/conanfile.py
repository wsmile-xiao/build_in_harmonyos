#!/usr/bin/env python3
"""Conan recipe — libmilter 8.18.2 (sendmail devtools Build system)."""
import glob
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class LibmilterConan(ConanFile):
    name = "libmilter"
    version = "8.18.2"
    description = "Sendmail mail filter API library (milter) for writing third-party mail filtering programs"
    license = "Sendmail Open Source License"
    homepage = "https://www.proofpoint.com/us/sendmail-open-source/"
    url = "https://mirrorservice.org/sites/ftp.sendmail.org/pub/sendmail/sendmail.8.18.2.tar.gz"

    package_type = "static-library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"fPIC": [True, False]}
    default_options = {"fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"libmilter is supported only on Linux/OHOS, got {self.settings.os}")

    def requirements(self):
        # Zero conan dependencies: libmilter is a self-contained static library.
        # The sendmail Build system compiles the two libsm helper sources
        # (errstring.c, strl.c) directly into libmilter.a via LIBMILTER_EXTRAS.
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        # Official upstream is ftp://ftp.sendmail.org (ftp-only, https path 404).
        # mirrorservice.org (UK Mirror Service) mirrors ftp.sendmail.org verbatim;
        # verified byte-identical (sha256) against the official ftp archive.
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # R33: compiler comes from the profile's tools.build:compiler_executables
        # conf (see ci/conan/profiles/ohos-aarch64), never from bare ${CC}.
        # The sendmail Build system reads the site config below via m4; we
        # inject the host compiler the same way an integrator would.
        comp = self.conf.get("tools.build:compiler_executables", check_type=dict) or {}
        cc = comp.get("c") or "clang"
        site_dir = os.path.join(self.source_folder, "devtools", "Site")
        os.makedirs(site_dir, exist_ok=True)
        site = os.path.join(site_dir, "site.config.m4")
        with open(site, "w", encoding="utf-8") as f:
            f.write("# Generated by conanfile.py (cross-build site config)\n")
            f.write("define(`confCC', `%s')\n" % cc)
            f.write("define(`confCCLINK', `%s')\n" % cc)

    def build(self):
        apply_conandata_patches(self)
        # sendmail's own Build system (not autotools/cmake):
        #   cd libmilter && ./Build
        # It detects the platform from uname (HarmonyOS) and picks the
        # devtools/OS/HarmonyOS config added by 0001 patch, runs m4 to
        # generate the Makefile in obj.HarmonyOS.*/libmilter, then makes.
        self.run("./Build", cwd=os.path.join(self.source_folder, "libmilter"))

    def package(self):
        # Static library + headers. libmilter has no install target suitable
        # for staging (install-mfapi assumes /usr/include layout), so copy
        # manually from the Build system's obj directory.
        lib = glob.glob(os.path.join(self.source_folder, "obj.*", "libmilter", "libmilter.a"))
        if not lib:
            raise Exception("build output libmilter.a not found under obj.*/libmilter")
        copy(self, "libmilter.a", src=os.path.dirname(lib[0]), dst=os.path.join(self.package_folder, "lib"))
        inc_src = os.path.join(self.source_folder, "include", "libmilter")
        copy(self, "*.h", src=inc_src, dst=os.path.join(self.package_folder, "include", "libmilter"))

    def package_info(self):
        self.cpp_info.libs = ["milter"]
        self.cpp_info.system_libs = ["pthread"]
