#!/usr/bin/env python3
"""test_package for ola 0.10.9 (OHOS PC).

R34 compliance: exercises real libolacommon / libola client APIs —
IPV4Address, MACAddress, RDM UID, DmxBuffer, StringUtils — plus an
OHOS-specific check that the /proc/net/route fallback (patch 0001)
gracefully returns false-or-true without crashing on a system without
netlink/sysctl (the DefaultRoute() code path this port added).

The test binary runs directly (self.run) so exit codes map 1:1.
"""
import os

from conan import ConanFile
from conan.tools.cmake import CMake, cmake_layout


class OlaTestConan(ConanFile):
    settings = "os", "compiler", "build_type", "arch"
    generators = "CMakeDeps", "CMakeToolchain"
    test_type = "explicit"

    def requirements(self):
        self.requires(self.tested_reference_str)
        # protobuf must be on the graph so its package folder resolves
        # (ola links libprotobuf symbols; the consumer needs it too).
        self.requires("protobuf/3.17.3")

    def layout(self):
        cmake_layout(self)

    def build(self):
        cmake = CMake(self)
        # protobuf/3.17.3 sets cmake_find_mode=none (keeps its own official
        # CMake config), so CMakeDeps emits no protobuf config — but
        # ola-config.cmake's find_dependency(protobuf) still wants one.
        # Pass the module path + library locations through the cache so the
        # Findprotobuf.cmake stand-in (written by generate() below) resolves
        # it before the CONFIG fallback fails.
        pb = self.dependencies["protobuf"].package_folder
        cmake.configure(cli_args=[
            "-DOLA_PROTOBUF_INCLUDE={}".format(os.path.join(pb, "include")),
            "-DOLA_PROTOBUF_LIB={}".format(
                os.path.join(pb, "lib", "libprotobuf.a")),
        ])
        cmake.build()

    def generate(self):
        # Write a Findprotobuf.cmake stand-in into the generators folder
        # (CMakeDeps put that folder on CMAKE_PREFIX_PATH; CMakeLists.txt
        # prepends it to CMAKE_MODULE_PATH before find_package(ola)).
        path = os.path.join(self.generators_folder, "Findprotobuf.cmake")
        module = """# Stand-in Findprotobuf (generated by test_package)
# protobuf/3.17.3 sets cmake_find_mode=none so CMakeDeps emits no config;
# this module answers the find_dependency(protobuf) call emitted by
# ola-config.cmake and wires the real conan paths passed via cache vars.
if(NOT TARGET protobuf::libprotobuf)
  add_library(protobuf::libprotobuf INTERFACE IMPORTED)
  if(OLA_PROTOBUF_INCLUDE)
    set_target_properties(protobuf::libprotobuf PROPERTIES
      INTERFACE_INCLUDE_DIRECTORIES "${OLA_PROTOBUF_INCLUDE}")
  endif()
  if(OLA_PROTOBUF_LIB)
    set_target_properties(protobuf::libprotobuf PROPERTIES
      INTERFACE_LINK_LIBRARIES "${OLA_PROTOBUF_LIB}")
  endif()
endif()
if(NOT TARGET protobuf::protobuf)
  add_library(protobuf::protobuf INTERFACE IMPORTED)
  target_link_libraries(protobuf::protobuf INTERFACE protobuf::libprotobuf)
endif()
set(protobuf_FOUND TRUE)
"""
        with open(path, "w", encoding="utf-8") as f:
            f.write(module)

    def test(self):
        cmd = os.path.join(self.cpp.build.bindirs[0], "test_ola")
        # Static test_ola still needs libc++_shared.so at load time; the
        # system copy is the real shared object (the SDK one under
        # llvm/lib/aarch64-linux-ohos is a linker INPUT script the loader
        # cannot use). Shell-prefix the LD_LIBRARY_PATH because self.run's
        # env= argument only accepts "conanbuild"/"conanrun" wrappers.
        ld = ("/system/lib64:/data/service/hnp/ohos-sdk.org/"
              "ohos-sdk_26.0.0.18/ohos/native/llvm/lib/aarch64-linux-ohos")
        extra = os.environ.get("LD_LIBRARY_PATH", "")
        full_ld = ld + ((":" + extra) if extra else "")
        self.output.info("run LD_LIBRARY_PATH: " + full_ld)
        self.run('LD_LIBRARY_PATH="{}" "{}"'.format(full_ld, cmd))
