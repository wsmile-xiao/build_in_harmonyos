#!/usr/bin/env python3
"""Conan recipe — osmfilter 0.9 (Makefile)

osmctools: OpenStreetMap data filtering, conversion and update tools.
Builds three CLI executables: osmfilter, osmconvert, osmupdate.
Source from GitLab git repo lacks pre-generated configure, so we build
with a generated Makefile instead of autotools (no automake available).
"""
import os

from conan import ConanFile
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class OsmfilterConan(ConanFile):
    name = "osmfilter"
    version = "0.9"
    description = "OpenStreetMap data filtering, conversion and update tools"
    license = "AGPL-3.0"
    homepage = "https://gitlab.com/osm-c-tools/osmctools"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # osmconvert depends on zlib for PBF format support
        self.requires("zlib/1.3.1")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # R33: Get compiler from Conan conf, never from shell env vars
        compiler_executables = self.conf.get("tools.build:compiler_executables", default={})
        cc = compiler_executables.get("c", "clang") if isinstance(compiler_executables, dict) else "clang"
        # Get zlib paths from dependency package folder
        zlib_pkg = self.dependencies["zlib"].package_folder
        zlib_inc = os.path.join(zlib_pkg, "include")
        zlib_lib = os.path.join(zlib_pkg, "lib")

        # Set CFLAGS based on build_type
        build_type = str(self.settings.build_type)
        if build_type == "Debug":
            cflags = "-g -O0 -Wall"
        elif build_type == "RelWithDebInfo":
            cflags = "-O2 -g -Wall"
        elif build_type == "MinSizeRel":
            cflags = "-Os -Wall -DNDEBUG"
        else:  # Release
            cflags = "-O2 -Wall -DNDEBUG"

        # Generate a simple Makefile — source from git has no configure
        makefile_content = f"""\
# Auto-generated by Conan — osmfilter 0.9
CC = {cc}
CFLAGS = {cflags}
CPPFLAGS = -I{zlib_inc}
LDFLAGS = -L{zlib_lib}

BINARIES = osmfilter osmconvert osmupdate

all: $(BINARIES)

osmfilter: src/osmfilter.c
\t$(CC) $(CFLAGS) -o $@ $<

osmconvert: src/osmconvert.c
\t$(CC) $(CFLAGS) -o $@ $< $(CPPFLAGS) $(LDFLAGS) -lz

osmupdate: src/osmupdate.c
\t$(CC) $(CFLAGS) -o $@ $<

install: all
\tinstall -d $(DESTDIR)$(PREFIX)/bin
\tinstall -m 755 osmfilter $(DESTDIR)$(PREFIX)/bin/
\tinstall -m 755 osmconvert $(DESTDIR)$(PREFIX)/bin/
\tinstall -m 755 osmupdate $(DESTDIR)$(PREFIX)/bin/

clean:
\trm -f $(BINARIES)

.PHONY: all install clean
"""
        with open(os.path.join(self.source_folder, "Makefile"), "w") as f:
            f.write(makefile_content)

    def build(self):
        apply_conandata_patches(self)
        self.run("make -j1", cwd=self.source_folder, env="conanbuild")

    def package(self):
        # Install to package bin directory
        copy(self, "osmfilter", self.source_folder, os.path.join(self.package_folder, "bin"))
        copy(self, "osmconvert", self.source_folder, os.path.join(self.package_folder, "bin"))
        copy(self, "osmupdate", self.source_folder, os.path.join(self.package_folder, "bin"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libs = []
