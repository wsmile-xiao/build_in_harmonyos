#!/usr/bin/env python3
"""Conan recipe for omega 2.0.0 (Xapian Omega, OHOS aarch64 port).

Omega is the Xapian project's CGI search application plus the omindex
file indexer.  Mandatory third-party dependencies are all consumed from
the ohpcd Conan registry:

  xapian-core/2.0.0  search engine library (configure requires >= 2.0.0)
  zlib/1.3.1.1       omindex links -lz; same pin as xapian-core/2.0.0
  pcre2/10.47        omega query transform engine (8-bit, static)
  libmagic/5.48      omindex MIME detection (static, magic.mgc database)
"""

import os
import shutil

from conan import ConanFile
from conan.tools.build import can_run, load_toolchain_args
from conan.tools.env import Environment
from conan.tools.files import (
    apply_conandata_patches,
    export_conandata_patches,
    get,
    load,
    save,
)
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain, PkgConfigDeps
from conan.tools.layout import basic_layout


class OmegaConan(ConanFile):
    name = "omega"
    version = "2.0.0"
    description = ("Xapian Omega - CGI search application and omindex "
                   "file indexer built on the Xapian search library")
    license = "GPL-2.0-or-later"
    homepage = "https://xapian.org/omega"
    url = "https://xapian.org/omega"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("xapian-core/2.0.0")
        self.requires("zlib/1.3.1.1")
        self.requires("pcre2/10.47")
        self.requires("libmagic/5.48")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _dep(self, name):
        return self.dependencies[name].package_folder

    def _make_working_xapian_config(self):
        """Materialise a xapian-config whose prefix points at the package.

        The published xapian-core package carries prefix="/" in
        bin/xapian-config (conan relocated the install prefix), so the
        script would report -I//include.  xapian.m4 refuses to build
        without an executable xapian-config, so rewrite the single prefix
        assignment into a private copy under the build folder (R49: never
        touch shared or system prefixes).
        """
        pkg = self._dep("xapian-core")
        real = os.path.join(pkg, "bin", "xapian-config")
        text = load(self, real)
        text = text.replace('\nprefix="/"\n', '\nprefix="{}"\n'.format(pkg), 1)
        target = os.path.join(self.build_folder, "bin", "xapian-config")
        save(self, target, text)
        os.chmod(target, 0o755)
        return target

    def generate(self):
        AutotoolsDeps(self).generate()
        PkgConfigDeps(self).generate()

        tc = AutotoolsToolchain(self)
        tc.generate()

        env = Environment()
        env.define("XAPIAN_CONFIG", self._make_working_xapian_config())
        # configure probes libpcre2-8/libmagic through pkg-config; the
        # .pc files generated by PkgConfigDeps live in generators_folder.
        env.prepend_path("PKG_CONFIG_PATH", self.generators_folder)
        # Static libmagic finds no compiled database by default on OHOS;
        # point it at the copy shipped by the libmagic package.
        env.define("MAGIC", os.path.join(self._dep("libmagic"), "share", "misc", "magic.mgc"))
        # Uninstalled check programs (make check) link against
        # libxapian.so from the dependency package folder.
        env.prepend_path("LD_LIBRARY_PATH", os.path.join(self._dep("xapian-core"), "lib"))
        env.vars(self, scope="build").save_script("omega_deps")

    def build(self):
        apply_conandata_patches(self)
        configure = os.path.join(self.source_folder, "configure")
        if os.path.isfile(configure):
            os.chmod(configure, 0o755)
        autotools = Autotools(self)
        configure_args = self._load_configure_args()
        if self.settings.os == "OHOS":
            # clang/clang++ on this port are shell wrapper scripts and
            # exec'ing configure directly is unreliable, so run through
            # bash and name the LLVM binutils the toolchain ships
            # (same workaround proven by xapian-core/2.0.0).
            config_shell = shutil.which("bash") or "/system/bin/sh"
            cc = shutil.which("clang") or "clang"
            cxx = shutil.which("clang++") or "clang++"
            ar = shutil.which("llvm-ar") or shutil.which("ar") or "ar"
            ranlib = shutil.which("llvm-ranlib") or shutil.which("ranlib") or "ranlib"
            nm = shutil.which("llvm-nm") or shutil.which("nm") or "nm"
            ld = shutil.which("ld.lld") or shutil.which("ld") or "ld"
            self.run(
                f'CC="{config_shell} {cc}" CXX="{config_shell} {cxx}" '
                f'AR="{ar}" RANLIB="{ranlib}" NM="{nm}" LD="{ld}" '
                f'CONFIG_SHELL="{config_shell}" '
                f'"{config_shell}" "{configure}" {configure_args}',
                env="conanbuild",
            )
        else:
            config_shell = shutil.which("bash") or "sh"
            self.run(
                f'CONFIG_SHELL="{config_shell}" '
                f'"{config_shell}" "{configure}" {configure_args}',
                env="conanbuild",
            )
        autotools.make()
        if can_run(self):
            # Upstream suite: 8 C++ unit programs + omegatest.pl +
            # sourcetest + omindextest (make check).  omindextest needs
            # MAGIC, which the omega_deps env script exports.
            autotools.make(target="check", args=["-j1"])

    def _load_configure_args(self):
        return load_toolchain_args(self.generators_folder).get("configure_args")

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        cgi_dir = os.path.join(self.package_folder, "lib", "xapian-omega", "bin")
        for tool in ("omega", "mhtml2html", "outlookmsg2html", "rfc822tohtml",
                     "vcard2text"):
            path = os.path.join(cgi_dir, tool)
            if os.path.isfile(path):
                os.chmod(path, 0o755)

    def package_info(self):
        # Application package: consumers get the CLI entries, nothing to
        # link against.
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
        # Upstream installs the omega CGI and the perl/awk filter helpers
        # under lib/xapian-omega/bin next to the libdir.
        self.runenv_info.prepend_path(
            "PATH", os.path.join(self.package_folder, "lib", "xapian-omega", "bin"))
