#!/usr/bin/env python3
"""Conan recipe for opensmtpd-table-socketmap — custom build (no autotools needed).

The upstream tarball does not include a pre-generated configure script.
Since automake/aclocal is not available on CI workers, we bypass autotools
and compile the C sources directly.

The binary is installed to libexec/smtpd/ (matching upstream Makefile.am).
R26: Terminal tools must be statically linked.
"""
import os

from conan import ConanFile
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class OpensmtpdTableSocketmapConan(ConanFile):
    name = "opensmtpd-table-socketmap"
    version = "1.1.1-r0"
    description = "OpenSMTPD socketmap table backend — proxies table lookups via Unix socket"
    license = "MIT"
    homepage = "https://github.com/OpenSMTPD/table-socketmap"
    url = ""  # CI fills this

    settings = "os", "compiler", "build_type", "arch"
    package_type = "application"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        pass

    def build(self):
        apply_conandata_patches(self)
        src = self.source_folder

        # Generate config.h (normally created by configure)
        config_h = os.path.join(src, "config.h")
        with open(config_h, "w") as f:
            f.write("/* Auto-generated by conanfile.py — no autotools */\n")
            f.write("#define PACKAGE_NAME \"table-socketmap\"\n")
            f.write("#define PACKAGE_VERSION \"1.1.1\"\n")
            f.write("#define HAVE_ASPRINTF 1\n")
            f.write("#define HAVE_ERR 1\n")
            f.write("#define HAVE_STRLCAT 1\n")
            f.write("#define HAVE_STRLCPY 1\n")
            f.write("#define HAVE_STRSEP 1\n")
            f.write("/* getprogname and strtonum not available on OHOS */\n")

        # Include paths
        includes = [
            f"-I{src}",
            f"-I{src}/openbsd-compat",
            f"-I{src}/openbsd-compat/tree",
        ]

        # Main source files (from Makefile.am: table_socketmap_SOURCES)
        main_sources = [
            "table_socketmap.c",
            "dict.c",
            "log.c",
            "table_stdio.c",
            "util.c",
        ]

        # openbsd-compat sources for missing functions
        compat_sources = [
            "openbsd-compat/getprogname.c",
            "openbsd-compat/strtonum.c",
        ]

        # Compile flags
        cflags = ["-DHAVE_CONFIG_H", "-fPIC", "-O2"] + includes
        # R26: static linking for terminal tools
        ldflags = ["-static"]

        # Compile all sources
        all_sources = main_sources + compat_sources
        obj_files = []
        for src_file in all_sources:
            obj_file = src_file.replace("/", "_").replace(".c", ".o")
            self.run(
                f"clang {' '.join(cflags)} -c {src_file} -o {obj_file}",
                env="conanbuild",
                cwd=src,
            )
            obj_files.append(obj_file)

        # Link
        self.run(
            f"clang {' '.join(ldflags)} -o table-socketmap {' '.join(obj_files)}",
            env="conanbuild",
            cwd=src,
        )

    def package(self):
        src = self.source_folder
        # Install binary to libexec/smtpd/ (matching upstream Makefile.am)
        copy(self, "table-socketmap", src, os.path.join(self.package_folder, "libexec", "smtpd"))
        # Also place binary in bin/ for PATH discoverability by consumers
        copy(self, "table-socketmap", src, os.path.join(self.package_folder, "bin"))
        # Install man page
        copy(self, "table-socketmap.5", src, os.path.join(self.package_folder, "share", "man", "man5"))

    def package_info(self):
        # Executable package: binary in bin/ for PATH
        self.cpp_info.bindirs = ["bin"]
