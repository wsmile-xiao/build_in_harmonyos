#!/usr/bin/env python3
"""Conan recipe for openiked 7.4 — OpenBSD IKEd (IPsec VPN) portable.

CMake multi-subdir project: bundled `compat` static lib + iked + ikectl;
parse.c is generated by bison (hnp toolchain provides yacc/bison 3.8.2 in
the conanbuild PATH).  Links util/event/crypto/ssl — event and crypto come
from the conan dependency packages; the CMakeLists' hardcoded /usr/local
paths are overridden by injecting CMAKE_C_FLAGS / CMAKE_EXE_LINKER_FLAGS
(no source patching).

E549: both produced ELFs (iked, ikectl) are self-signed with
binary-sign-tool before packaging.  iked is a root/pfkey VPN daemon —
the consumer test asserts the deterministic `iked -V` version banner
(rc=0) and `ikectl` no-arg usage (rc!=0), which prove the signed ELFs
execute and their crypto/event linkage resolves.
"""
import os
import shutil

from conan import ConanFile
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class OpenikedConan(ConanFile):
    name = "openiked"
    version = "7.4"
    description = "OpenBSD IKEd (Internet Key Exchange daemon) portable"
    license = "ISC"
    homepage = "https://github.com/openiked/openiked-portable"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("libevent/2.1.13")
        # OpenIKED 官方推荐 LibreSSL（portable CI 亦然）
        self.requires("libressl/3.9.1")

    def layout(self):
        basic_layout(self)

    def generate(self):
        tc = CMakeToolchain(self)
        # OHOS: CMake 不认识 OHOS 平台（rang/range-v3 仓内先例同款映射）
        tc.cache_variables["CMAKE_SYSTEM_NAME"] = "Linux"
        tc.cache_variables["CMAKE_SYSTEM_PROCESSOR"] = "aarch64"
        deps = self.dependencies.host
        ssl = deps["libressl"]
        event = deps["libevent"]
        ssl_inc = os.path.join(ssl.package_folder, ssl.cpp_info.includedirs[0])
        ssl_lib = os.path.join(ssl.package_folder, ssl.cpp_info.libdirs[0])
        event_inc = os.path.join(event.package_folder, event.cpp_info.includedirs[0])
        event_lib = os.path.join(event.package_folder, event.cpp_info.libdirs[0])
        # 覆盖 CMakeLists 硬编码的 /usr/local：conan 依赖路径前置注入
        tc.cache_variables["CMAKE_C_FLAGS"] = f"-I{ssl_inc} -I{event_inc}"
        tc.cache_variables["CMAKE_EXE_LINKER_FLAGS"] = f"-L{ssl_lib} -L{event_lib}"
        tc.generate()

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    # ── E549 ELF 签名（cc-connect 同款实现） ──────────────────────

    def _find_tool(self, name):
        import glob as g
        for d in sorted(g.glob("/data/service/hnp/ohos-sdk.org/*/ohos/native/llvm/bin")):
            p = os.path.join(d, name)
            if os.path.isfile(p):
                return p
        for d in ("/data/service/hnp/bin",):
            p = os.path.join(d, name)
            if os.path.isfile(p):
                return p
        return shutil.which(name)

    def _sign_elf(self, binary_path):
        from conan.errors import ConanException
        objcopy = self._find_tool("llvm-objcopy")
        sign_tool = self._find_tool("binary-sign-tool")
        if not sign_tool or not objcopy:
            raise ConanException("binary-sign-tool/llvm-objcopy not found (E549)")
        import subprocess
        subprocess.run(
            [objcopy, "--remove-section", ".codesign", binary_path],
            capture_output=True, timeout=30,
        )
        tmp = binary_path + ".signed.tmp"
        for _ in range(3):
            r = subprocess.run(
                [sign_tool, "sign", "-inFile", binary_path,
                 "-outFile", tmp, "-selfSign", "1"],
                capture_output=True, text=True, timeout=60,
            )
            if r.returncode == 0 and os.path.isfile(tmp):
                shutil.move(tmp, binary_path)
                os.chmod(binary_path, 0o775)
                return
        if os.path.exists(tmp):
            os.remove(tmp)
        raise ConanException(f"signing failed for {binary_path}")

    def package(self):
        build = self.build_folder
        for exe in ("iked", "ikectl"):
            src = None
            for root, _, files in os.walk(build):
                if exe in files:
                    src = os.path.join(root, exe)
                    break
            if not src:
                from conan.errors import ConanException
                raise ConanException(f"{exe} not found in build tree")
            self._sign_elf(src)
            copy(self, exe, src=os.path.dirname(src),
                 dst=os.path.join(self.package_folder, "bin"), keep_path=False)
        copy(self, "LICENSE",
             src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"), keep_path=False)

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
