#!/usr/bin/env python3
"""Conan test_package for otpw 1.5 — HarmonyOS consumer test via test.sh.

Upstream ships no test suite (see MANIFEST.yml and reports/upstream-test-scan.txt),
so every case in test.sh is a NEW consumer case that really executes the packaged
otpw-gen binary.

Driver responsibilities (Python only where needed):
  * resolve the packaged bindir by absolute path instead of trusting PATH
    (same shape as ttygif/1.5.0, alive/2.0.3, vamps/0.99.2);
  * seed a writable, per-process scratch TMPDIR: HarmonyOS /tmp is read-only
    (E002) and the ambient TMPDIR may be the home directory, so both are
    rejected in favour of the CI-injected temp dir or the build folder.
"""
import os

from conan import ConanFile
from conan.tools.build import can_run


class OtpwTestConan(ConanFile):
    settings = "os", "compiler", "build_type", "arch"
    generators = "VirtualRunEnv"
    test_type = "explicit"

    def requirements(self):
        # run=True: VirtualRunEnv only injects bin/ of run deps into PATH, and
        # otpw-gen is a CLI that test.sh must execute (E365/E442 shape).
        self.requires(self.tested_reference_str, run=True)

    def _scratch_dir(self):
        """A writable, per-process scratch dir owned by this test run.

        1. ambient TMPDIR/TMP/TEMP that exists, is writable and is not the
           home directory nor the read-only /tmp (CI/HMBS injects one);
        2. a per-pid directory under this test's build folder.
        """
        home = os.path.expanduser("~")
        rejected = (home, "/", "/tmp", "")
        for var in ("TMPDIR", "TMP", "TEMP"):
            cand = os.environ.get(var) or ""
            if cand in rejected or not os.path.isdir(cand):
                continue
            sub = os.path.join(cand, "otpw-test-%d" % os.getpid())
            try:
                os.makedirs(sub, exist_ok=True)
                return sub
            except OSError:
                continue
        # Last resort: a per-pid dir under ~/tmp -- deliberately OUTSIDE the
        # package tree, so runtime scratch can never leak into the PR diff
        # (the ttygif 1.5.0 lesson: run's package-level `git add` swallowed
        # two scratch trees generated by the L1e second conan test).
        cand = os.path.join(os.path.expanduser("~"), "tmp",
                            "otpw-scratch-%d" % os.getpid())
        try:
            os.makedirs(cand, exist_ok=True)
            return cand
        except OSError:
            return os.getcwd()

    def test(self):
        if not can_run(self):
            self.output.warning(
                "otpw test_package not executed: cannot run target binaries")
            return

        dep = self.dependencies.get("otpw")
        bin_dir = "bin"
        if dep is not None:
            try:
                rel = dep.cpp_info.bindirs[0] if dep.cpp_info.bindirs else "bin"
            except Exception:
                rel = "bin"
            if not os.path.isabs(rel):
                rel = os.path.join(dep.package_folder, rel)
            bin_dir = rel if os.path.isdir(rel) else os.path.join(
                dep.package_folder, "bin")
            self.output.info("otpw package_folder=%s bindir=%s" % (
                dep.package_folder, bin_dir))

        tmpdir = self._scratch_dir()
        for var in ("TMPDIR", "TMP", "TEMP", "TEMPDIR"):
            os.environ[var] = tmpdir
        self.output.info("test TMPDIR=%s" % tmpdir)

        script = os.path.join(os.path.dirname(__file__), "test.sh")
        shell = os.environ.get("CONFIG_SHELL") or "/bin/sh"
        self.run('"%s" "%s" "%s"' % (shell, script, bin_dir), env="conanrun")
