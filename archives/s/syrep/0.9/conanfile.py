#!/usr/bin/env python3
"""Conan recipe for syrep 0.9 - file repository synchronization tool.

syrep is a command-line tool (CLI), not a library: the package ships the
`syrep` binary. Build system is autotools (2005-era, generated by
autoconf 2.59), hardened for OHOS:

- Berkeley DB version check relaxed to >= 4.3 (upstream only knew 4.3/4.4)
- config.guess/sub taught to recognize HarmonyOS (patches)
- package.c link() falls back to copy on HMDFS (patch, E079)
- --disable-lynx: doc rendering tool is irrelevant and absent in CI
- generated files are outdated w.r.t. the OHOS environment: the shipped
  configure (autoconf 2.59) enforces Berkeley DB 4.3/4.4 only. CI must not
  re-run autotools (E041/E071: the repository builds without an
  autoconf/perl toolchain, and mingling the system autoconf with conan's
  perl fails outright), so the guard is fixed in both places: configure.ac
  (source) and the shipped configure (patch 0002). That 4-line patch replaces
  the former whole-file regeneration patch (14805 lines) - the regenerated
  configure was neither reproducible nor reviewable (R52/R6).
- HMDFS permission quirk: config.status creates its scratch dir with
  `(umask 077 && mktemp -d ./confXXXXXX)`; on HMDFS the new dir's owner is
  remapped to a fixed uid and the process is judged by the group bits, so
  writing `confXXXXXX/subs1.awk` fails with "Permission denied" and autoconf
  reports "could not setup config files machinery". build() therefore installs
  a group-writable mktemp shim (umask 002 + chmod 2770) and prepends it to PATH
  for configure/make. The same class of failure is documented for libydpdict
  (E543 family); the fix must live in the recipe, never in a machine-global
  PATH entry - a local shim made W3 green while CI (whose PATH lacks it) stayed red.
- profile [buildenv] exports SHELL/CONFIG_SHELL=hnp bash, which outranks recipe
  env; configure is therefore invoked with command-prefix assignments
  (POSIX: prefix assignment beats exported vars) to keep the whole
  configure -> config.status -> Makefile chain on /bin/sh.
- upstream tests: src/Makefile.am declares
  `noinst_PROGRAMS = rm-rf-test copy-fd-test` (they ARE wired into the build,
  but not into `make check`). build() really executes both binaries and
  asserts their outcome (R51).
"""
import hashlib
import os
import time

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.env import Environment
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout

required_conan_version = ">=2.0"


_MKTEMP_SHIM = r"""#!/bin/sh
# 本机(HMDFS/hmmac=use_task)兼容版 mktemp 垫片。
# 系统 mktemp -d 以 0700 建目录；本文件系统把新目录所有者映射为固定 uid，
# 进程 uid 与之一致性无法保证，0700 目录因此对当前进程不可写
# （autoconf config.status 的 ./confXXXXXX 临时目录即在此处失败）。
# 本垫片改为 umask 002 建目录/文件（组可写，实测 2771 可写），保持唯一性。
dir=0
dry=0
while [ $# -gt 0 ]; do
  case "$1" in
    -d) dir=1; shift ;;
    -u) dry=1; shift ;;
    -q) shift ;;
    --) shift; break ;;
    -*) shift ;;
    *) break ;;
  esac
done
tmpl="$1"
[ -n "$tmpl" ] || tmpl="${TMPDIR:-/tmp}/tmp.XXXXXX"
case "$tmpl" in
  *XXXXXX) pre="${tmpl%XXXXXX}" ;;
  *) pre="$tmpl" ;;
esac
i=0
while [ "$i" -le 500 ]; do
  cand="${pre}$$-$i"
  if [ "$dry" = 1 ]; then
    printf '%s\n' "$cand"
    exit 0
  fi
  if [ "$dir" = 1 ]; then
    if ( umask 002; mkdir "$cand" ) 2>/dev/null; then
      chmod 2770 "$cand" 2>/dev/null
      printf '%s\n' "$cand"
      exit 0
    fi
  else
    if ( umask 002; set -C; : > "$cand" ) 2>/dev/null; then
      printf '%s\n' "$cand"
      exit 0
    fi
  fi
  i=$((i + 1))
done
exit 1
"""


class SyrepConan(ConanFile):
    name = "syrep"
    version = "0.9"
    description = "generic file repository synchronization tool using patch files"
    license = "GPL-2.0-or-later"
    homepage = "http://0pointer.de/lennart/projects/syrep/"
    url = "http://0pointer.de/lennart/projects/syrep/"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # R36: both already published in the ohpcd artifact registry
        self.requires("berkeley-db/4.8.30")
        self.requires("zlib/1.3.1")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # AutotoolsDeps: feed -I/-L/-l from berkeley-db/zlib into configure/make
        deps = AutotoolsDeps(self)
        deps.generate()
        tc = AutotoolsToolchain(self)
        tc.configure_args.append("--disable-lynx")
        # 2005-era config.guess/sub: pass explicit triple, ohos recognition
        # comes from the patches (config.guess now understands HarmonyOS)
        tc.configure_args.append("--build=aarch64-unknown-ohos")
        tc.configure_args.append("--host=aarch64-unknown-ohos")
        tc.generate()
        # configure() is called manually in build() (see below), so stash the
        # toolchain-provided args here.
        self._ohc_configure_args = list(tc.configure_args)
        # HMDFS/E002: mkdtemp needs writable TMPDIR; expose via conanbuild env
        env = Environment()
        env.define("TMPDIR", self.build_folder)
        env.vars(self).save_script("conantmpdir")

    def _install_mktemp_shim(self):
        """HMDFS: install a group-writable mktemp and prepend it to PATH."""
        shim_bin = os.path.join(self.build_folder, "shimbin")
        os.makedirs(shim_bin, exist_ok=True)
        shim_path = os.path.join(shim_bin, "mktemp")
        with open(shim_path, "w") as fh:
            fh.write(_MKTEMP_SHIM)
        os.chmod(shim_path, 0o755)
        os.environ["PATH"] = shim_bin + os.pathsep + os.environ.get("PATH", "")
        return shim_bin

    def _run_upstream_tests(self):
        """R51: really execute the two upstream test programs.

        `src/Makefile.am` declares `noinst_PROGRAMS = rm-rf-test copy-fd-test`:
        they are built by `make`, but never registered in TESTS, so `make check`
        never runs them. They are executed here against real inputs:
          copy-fd-test <src> <dst>  -> util.c copy_fd() descriptor round-trip
          rm-rf-test   <dir>        -> util.c rm_rf() recursive removal
        """
        srcdir = os.path.join(self.build_folder, "src")
        workdir = os.path.join(self.build_folder, "upstream-tests")
        os.makedirs(workdir, exist_ok=True)

        # 1/2: copy-fd-test — byte-exact descriptor copy
        src = os.path.join(workdir, "copy-src.bin")
        dst = os.path.join(workdir, "copy-dst.bin")
        payload = bytes(range(256)) * 257  # 65,792 bytes
        with open(src, "wb") as fh:
            fh.write(payload)
        self.run('"./copy-fd-test" "{}" "{}"'.format(src, dst), cwd=srcdir)
        if not os.path.isfile(dst):
            raise ConanException("upstream test copy-fd-test did not create {}".format(dst))
        with open(dst, "rb") as fh:
            got = fh.read()
        if hashlib.sha256(got).hexdigest() != hashlib.sha256(payload).hexdigest():
            raise ConanException(
                "upstream test copy-fd-test: copied file differs from source "
                "({} bytes in, {} bytes out)".format(len(payload), len(got))
            )
        self.output.info(
            "[upstream test 1/2] copy-fd-test PASS ({} bytes, sha256 match)".format(len(payload))
        )

        # 2/2: rm-rf-test — recursive removal of a nested tree
        tree = os.path.join(workdir, "rm-rf-tree")
        for rel in ("f1.txt", "sub/f2.txt", "sub/deeper/f3.txt"):
            path = os.path.join(tree, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w") as fh:
                fh.write("syrep upstream test\n")
        self.run('"./rm-rf-test" "{}"'.format(tree), cwd=srcdir)
        if os.path.exists(tree):
            left = sorted(
                os.path.join(root, name)
                for root, _dirs, files in os.walk(tree)
                for name in files
            )
            raise ConanException(
                "upstream test rm-rf-test left the tree behind: {} ({} entries)".format(
                    tree, left
                )
            )
        self.output.info("[upstream test 2/2] rm-rf-test PASS (nested tree removed)")

    def build(self):
        apply_conandata_patches(self)

        # E248: the shipped Makefile.in rules re-run AUTOCONF/AUTOHEADER/AUTOMAKE
        # whenever configure.ac (which patch 0005 modifies) is newer than the
        # generated files - autotools are absent in CI. Touch every generated
        # file, and pin the regeneration programs to /bin/true as well
        # (E041/E071), so `make` can never trigger them.
        # NB: the timestamp must not be in the future - autoconf's configure
        # aborts with "newly created file is older than distributed files"
        # (system clock check) as soon as a distributed file is newer than the
        # files configure creates itself. Equal-to-now is newer than the
        # patched configure.ac and still in the past for that check.
        now = time.time()
        generated = [os.path.join(self.source_folder, "configure"),
                     os.path.join(self.source_folder, "config.h.in")]
        for root, _dirs, files in os.walk(self.source_folder):
            generated += [os.path.join(root, f) for f in files if f == "Makefile.in"]
        for path in generated:
            if os.path.exists(path):
                os.utime(path, (now, now))

        # HMDFS: config.status/make scratch dirs must be group writable
        os.umask(0o002)
        shim_bin = self._install_mktemp_shim()

        autotools = Autotools(self)
        configure = os.path.join(self.source_folder, "configure")
        args = " ".join(getattr(self, "_ohc_configure_args", []))
        # profile [buildenv] exports SHELL/CONFIG_SHELL=hnp bash, which outranks
        # recipe env; command-prefix assignment wins over exported variables and
        # keeps configure -> config.status -> Makefile on /bin/sh.
        self.run(
            'PATH="{}:$PATH" SHELL=/bin/sh CONFIG_SHELL=/bin/sh '
            'AUTOCONF=/bin/true AUTOHEADER=/bin/true AUTOMAKE=/bin/true ACLOCAL=/bin/true '
            '"{}" {}'.format(shim_bin, configure, args)
        )
        make_program = self.conf.get("tools.gnu:make_program", default="make")
        self.run('PATH="{}:$PATH" "{}" -j1'.format(shim_bin, make_program))

        self._run_upstream_tests()

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        bindir = os.path.join(self.package_folder, "bin")
        self.cpp_info.bindirs = [bindir]
        self.runenv_info.append_path("PATH", bindir)
