#!/usr/bin/env python3
"""Conan recipe — samtools 1.21 (CLI tool with bundled htslib).

samtools bundles htslib-1.21 and builds it as a static library.
On HarmonyOS the autotools config.status fails due to HMDFS temp dir
restrictions. This recipe bypasses configure and generates config.mk/
config.h directly, matching the proven adaptation approach.
"""
import os
import shutil
from pathlib import Path

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import (
    apply_conandata_patches,
    export_conandata_patches,
    get,
)



class SamtoolsConan(ConanFile):
    name = "samtools"
    version = "1.21"
    description = "Tools for manipulating next-generation sequencing data (SAM/BAM/CRAM)"
    license = "MIT"
    homepage = "https://www.htslib.org/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "application"

    settings = "os", "arch", "compiler", "build_type"

    _htslib_dir = "htslib-1.21"

    def export_sources(self):
        export_conandata_patches(self)

    def configure(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"samtools supports Linux and OHOS, not {self.settings.os}"
            )

    def requirements(self):
        self.requires("zlib/1.3.1.1")
        self.requires("bzip2/1.0.8")
        self.requires("ncurses/6.6")
        self.requires("curl/8.15.0")
        self.requires("liblzma/5.8.1")
        self.requires("openssl/3.5.6.1")

    def layout(self):
        self.folders.source = "src"
        self.folders.build = "src"
        self.folders.generators = "build-generators"

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def generate(self):
        if str(self.settings.compiler) != "clang":
            raise ConanInvalidConfiguration("samtools requires the OHOS Clang toolchain")
        configured = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        )
        if not configured.get("c"):
            raise ConanInvalidConfiguration(
                "tools.build:compiler_executables must define the C compiler"
            )

    @property
    def _compiler_tools(self):
        configured = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        )
        cc = configured["c"]
        tool_dir = Path(cc).parent
        return {
            "cc": cc,
            "ar": configured.get("ar", str(tool_dir / "llvm-ar")),
            "ranlib": configured.get("ranlib", str(tool_dir / "llvm-ranlib")),
        }

    @property
    def _cc(self):
        return self._compiler_tools["cc"]

    @property
    def _ar(self):
        return self._compiler_tools["ar"]

    @property
    def _ranlib(self):
        return self._compiler_tools["ranlib"]

    @property
    def _include_dirs(self):
        return [
            include_dir
            for dependency in self.dependencies.values()
            for include_dir in dependency.cpp_info.includedirs
        ]

    @property
    def _lib_dirs(self):
        return [
            lib_dir
            for dependency in self.dependencies.values()
            for lib_dir in dependency.cpp_info.libdirs
        ]

    @property
    def _cppflags(self):
        return " ".join(f"-I{d}" for d in self._include_dirs)

    @property
    def _ldflags(self):
        return " ".join(f"-L{d}" for d in self._lib_dirs)

    def build(self):
        src = Path(self.source_folder)

        # Generate config.mk manually (bypassing configure — HMDFS config.status issue)
        (src / "config.mk").write_text(self._generate_config_mk())

        # Generate config.h manually
        (src / "config.h").write_text(self._generate_config_h())

        # The OHOS SDK linker needs libxml2 from llvm/lib.  Some CI workers
        # set LD_LIBRARY_PATH globally, which takes precedence over lld's
        # RUNPATH and prevents it from finding the SDK copy.
        toolchain_lib = Path(self._cc).resolve().parent.parent / "lib"
        build_env = Environment()
        if toolchain_lib.is_dir():
            build_env.prepend_path("LD_LIBRARY_PATH", str(toolchain_lib))

        # Build with make
        with build_env.vars(self).apply():
            self.run(
                f'make -j1 CC="{self._cc}" AR="{self._ar}" '
                f'RANLIB="{self._ranlib}" CPPFLAGS="{self._cppflags}" '
                f'LDFLAGS="{self._ldflags}"',
                cwd=str(src),
            )

    def _generate_config_mk(self) -> str:
        return (
            "# config.mk \u2014 generated by conanfile.py for OHOS\n"
            f"prefix       = {self.package_folder}/bin\n"
            "exec_prefix  = $(prefix)\n"
            "bindir       = $(exec_prefix)\n"
            "datarootdir  = $(prefix)/share\n"
            "mandir       = $(datarootdir)/man\n"
            "\n"
            "AWK      = gawk\n"
            f"CC       = {self._cc}\n"
            f"CPPFLAGS = {self._cppflags}\n"
            "CFLAGS   = -fPIC -O2 -g -Wall\n"
            f"LDFLAGS  = {self._ldflags}\n"
            "LIBS     = -lz -lbz2 -lcurl -lssl -lcrypto -lpthread -llzma\n"
            "\n"
            f"HTSDIR = {self._htslib_dir}\n"
            "include $(HTSDIR)/htslib.mk\n"
            "include $(HTSDIR)/htslib_static.mk\n"
            "HTSLIB = $(HTSDIR)/libhts.a\n"
            "HTSLIB_LIB = $(HTSLIB) $(HTSLIB_static_LIBS)\n"
            "HTSLIB_LDFLAGS = $(HTSLIB_static_LDFLAGS)\n"
            "BGZIP = $(HTSDIR)/bgzip\n"
            "HTSLIB_CPPFLAGS = -I$(HTSDIR)\n"
            "\n"
            "CURSES_LIB = -lncursesw\n"
        )

    def _generate_config_h(self) -> str:
        return (
            "/* config.h \u2014 generated by conanfile.py for OHOS */\n"
            "\n"
            "#ifndef _XOPEN_SOURCE\n"
            "#define _XOPEN_SOURCE 600\n"
            "#endif\n"
            "\n"
            "#define HAVE_CURSES 1\n"
            "#define HAVE_CURSES_H 1\n"
            "#define HAVE_CURSES_COLOR 1\n"
            "#define HAVE_CURSES_ENHANCED 1\n"
            "#define HAVE_CURSES_OBSOLETE 1\n"
            "#define HAVE_LIBZ 1\n"
            "#define HAVE_NCURSES_H 1\n"
            "#define HAVE_LIBBZ2 1\n"
            "#define HAVE_LIBLZMA 1\n"
            "#ifndef __APPLE__\n"
            "#define HAVE_LZMA_H 1\n"
            "#endif\n"
            "#define HAVE_DRAND48 1\n"
            "#define HAVE_LIBCURL 1\n"
            "\n"
            "#if defined __x86_64__ || defined __arm__ || defined __aarch64__\n"
            "#define HAVE_ATTRIBUTE_CONSTRUCTOR 1\n"
            "#endif\n"
        )

    def package(self):
        src = Path(self.source_folder)
        bin_dir = Path(self.package_folder) / "bin"
        bin_dir.mkdir(parents=True, exist_ok=True)

        # Install main binary
        samtools = src / "samtools"
        if not samtools.is_file():
            raise ConanException(f"samtools binary missing after build: {samtools}")
        shutil.copy2(samtools, bin_dir / "samtools")

        # Install misc tools
        misc_dir = src / "misc"
        if misc_dir.exists():
            for name in ("ace2sam", "maq2sam-long", "maq2sam-short",
                         "md5fa", "md5sum-lite", "wgsim"):
                f = misc_dir / name
                if f.exists():
                    shutil.copy2(f, bin_dir / name)
            for name in ("blast2sam.pl", "bowtie2sam.pl", "export2sam.pl",
                         "fasta-sanitize.pl", "interpolate_sam.pl",
                         "novo2sam.pl", "plot-ampliconstats", "plot-bamstats",
                         "psl2sam.pl", "sam2vcf.pl", "samtools.pl",
                         "seq_cache_populate.pl", "soap2sam.pl",
                         "wgsim_eval.pl", "zoom2sam.pl"):
                f = misc_dir / name
                if f.exists():
                    shutil.copy2(f, bin_dir / name)

        # Install man pages
        man_dir = Path(self.package_folder) / "share" / "man" / "man1"
        man_dir.mkdir(parents=True, exist_ok=True)
        doc_dir = src / "doc"
        if doc_dir.exists():
            for f in doc_dir.glob("samtools*.1"):
                shutil.copy2(f, man_dir / f.name)
        wgsim_man = misc_dir / "wgsim.1"
        if wgsim_man.exists():
            shutil.copy2(wgsim_man, man_dir / "wgsim.1")

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libs = []

        # samtools is a dynamically linked OHOS application.  Its bundled
        # htslib uses curl, OpenSSL, zlib, bzip2 and liblzma at runtime;
        # expose their Conan libdirs to consumers through VirtualRunEnv.
        self.runenv_info.prepend_path("PATH", os.path.join(self.package_folder, "bin"))
        libdirs = []
        for dependency in self.dependencies.values():
            for libdir in dependency.cpp_info.libdirs:
                if libdir not in libdirs:
                    libdirs.append(libdir)
        for libdir in reversed(libdirs):
            self.runenv_info.prepend_path("LD_LIBRARY_PATH", libdir)
