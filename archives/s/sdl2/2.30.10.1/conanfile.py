#!/usr/bin/env python3
"""Conan recipe — SDL2 2.30.10.1 (shared-lib variant).

SDL2 (Simple DirectMedia Layer) cross-platform multimedia library.
2.30.10.1 is the shared variant (R37 suffix); static 2.30.10 retained.
Required by pygame so all pygame modules link one libSDL2.so instance.
"""

import os
import glob

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class Sdl2Conan(ConanFile):
    name = "sdl2"
    version = "2.30.10.1"
    description = "Simple DirectMedia Layer - cross-platform multimedia library"
    license = "MIT"
    homepage = "https://www.libsdl.org/"
    url = "https://github.com/libsdl-org/SDL"

    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # R26: System-name libraries default to static
        if not self.options.shared:
            tc.configure_args.append("--enable-static")
            tc.configure_args.append("--disable-shared")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # Fix umask 077 in configure script (HMDFS permission issue with temp dirs)
        configure_path = os.path.join(self.source_folder, "configure")
        if os.path.isfile(configure_path):
            with open(configure_path, "r") as f:
                content = f.read()
            content = content.replace("umask 077", "umask 022")
            with open(configure_path, "w") as f:
                f.write(content)
        # configure defaults C++ preprocessor to /lib/cpp (missing on OHOS)
        os.environ["CXXCPP"] = "/data/service/hnp/bin/clang++ -E"
        autotools = Autotools(self)
        autotools.configure()
        # Also fix config.status umask (generated by configure)
        config_status = os.path.join(self.source_folder, "config.status")
        if os.path.isfile(config_status):
            with open(config_status, "r") as f:
                content = f.read()
            content = content.replace("umask 077", "umask 022")
            with open(config_status, "w") as f:
                f.write(content)
        autotools.make(args=["-j1"])

        # Build and run upstream testautomation suite (306 test cases)
        self._run_testautomation()

    def _run_testautomation(self):
        """Compile and run SDL2's upstream testautomation test suite.

        SDL2 ships a testautomation suite (306 SDLTest_TestCaseReference
        entries across 23 source files) in test/testautomation*.c.
        It uses the SDL_test framework (src/test/*.c) and links libSDL2.
        Runs with dummy video/audio drivers (no display device needed).
        """
        _src = self.source_folder
        _bld = self.build_folder
        # Find libSDL2.a (autotools puts it in build-release/.libs/)
        _sdl_libs = glob.glob(
            os.path.join(_bld, "**", "libSDL2.a"), recursive=True
        )
        _sdl_lib = os.path.dirname(_sdl_libs[0]) if _sdl_libs else _bld
        _inc = os.path.join(_src, "include")
        # Get compiler from conan conf
        _compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        )
        _cc = _compilers.get("c", "clang")
        # Compile SDL_test library (test framework for testautomation)
        _test_src = os.path.join(_src, "src", "test")
        for cf in sorted(glob.glob(os.path.join(_test_src, "*.c"))):
            _obj = os.path.join(_bld, os.path.basename(cf).replace(".c", ".o"))
            self.run(
                f'{_cc} -fPIC -O2 -I{_inc} -c {cf} -o {_obj}',
                env="conanbuild",
            )
        self.run(
            f'llvm-ar rcs {_bld}/libSDL2_test.a {_bld}/SDL_test_*.o',
            env="conanbuild",
        )
        # Compile testautomation
        _auto_srcs = " ".join(
            sorted(glob.glob(os.path.join(_src, "test", "testautomation*.c")))
        )
        self.run(
            f'{_cc} -fPIC -O2 -I{_inc} {_auto_srcs}'
            f' -L{_bld} -L{_sdl_lib}'
            f' -lSDL2_test -lSDL2 -lpthread -lm -ldl'
            f' -o {_bld}/testautomation',
            env="conanbuild",
        )
        # Run with dummy drivers (no display/audio device needed)
        os.environ["SDL_VIDEODRIVER"] = "dummy"
        os.environ["SDL_AUDIODRIVER"] = "dummy"
        self.run(f'{_bld}/testautomation', env="conanrun")

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.libs = ["SDL2"]
        # SDL2 uses pthread (setcanceltype, sigmask), dlopen, etc.
        self.cpp_info.system_libs = ["pthread", "dl", "m"]
