#!/usr/bin/env python3
"""Conan recipe for soundtouch 2.0.0 — audio tempo/pitch/rate DSP library.

SoundTouch is an open-source audio processing library for changing the
tempo, pitch and playback rate of audio streams independently (WSOLA
algorithm).  Upstream ships autotools only (CMake support was added in
2.1.0, this 2.0.0 tag predates it), and the release archive contains
no generated configure — bootstrap via autoreconf is required.

OHOS adaptation notes (all verified locally on aarch64-linux-ohos):
  * bootstrap: `libtoolize --copy --force` (installs config/ltmain.sh)
    then `AUTOMAKE="<automake> --add-missing --foreign --copy"
    autoreconf -fisv` — the AUTOMAKE value must be the absolute path of
    the automake/1.18 wrapper from the build graph: autoreconf honours
    the AUTOMAKE env var, and a bare "automake" resolves through PATH to
    the host automake 1.17, producing "version mismatch" against the
    aclocal.m4 generated by aclocal 1.18.
  * libtoolize puts ltmain.sh in the project root while
    AC_CONFIG_AUX_DIR(config) expects it under config/ — move it before
    running autoreconf.
  * configure carries `(umask 077 && mktemp -d "./confXXXXXX")` /
    `(umask 077 && mkdir "$tmp")` in config.status; on HMDFS the 0700
    temp dir is unwritable and configure aborts — patch umask 077→000
    after bootstrap (same fix as E100/boa/catdoc/adplay).
  * config.guess of automake 1.18 recognises HarmonyOS
    (aarch64-unknown-linux-ohos), but the triplets are still passed
    explicitly (E205: never rely on guessing for cross builds).
  * --disable-x86-optimizations: MMX/SSE intrinsics do not exist on
    aarch64 (the configure probe would disable them anyway via the
    missing cpuid.h, but be explicit about it).
  * AC_DISABLE_STATIC in configure.ac means only the shared library is
    built; soundstretch CLI links it.
"""
import os

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, copy, \
    export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class SoundtouchConan(ConanFile):
    name = "soundtouch"
    version = "2.0.0"
    description = ("SoundTouch — open-source audio processing library for "
                   "changing tempo, pitch and playback rate of audio streams")
    license = "LGPL-2.1-or-later"
    homepage = "https://www.surina.net/soundtouch/"
    url = "https://gitlab.com/soundtouch/soundtouch"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": True}

    def export_sources(self):
        # conandata.yml declares no patches — OHOS fixes are applied to
        # generated files inside build() (configure umask fix), see
        # notes.md; the export/apply pair stays for G1 recipe completeness
        # and becomes live if a source patch is ever added.
        export_conandata_patches(self)

    def build_requirements(self):
        # CI clean PATH has SDK autoconf 2.72 / autoreconf / m4 under
        # /data/service/hnp/bin, but lacks aclocal/automake/libtoolize.
        # automake/1.18 ships aclocal+automake and libtool/2.5.4 ships
        # libtoolize (config/ltmain.sh required by AM_PROG_LIBTOOL).
        # autoconf/m4 intentionally NOT declared (SDK provides both;
        # declaring autoconf pulls a perl whose XS .so conflicts with the
        # SDK perl used by SDK autoreconf — accel-config precedent).
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"Unsupported OS: {self.settings.os}")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _gnu_triplet(self, arch=None):
        arch = str(arch or self.settings.arch)
        arch_triplets = {
            "armv8": "aarch64-unknown-linux-gnu",
            "armv8.3": "aarch64-unknown-linux-gnu",
            "aarch64": "aarch64-unknown-linux-gnu",
            "x86_64": "x86_64-unknown-linux-gnu",
        }
        triplet = arch_triplets.get(arch)
        if not triplet:
            raise ConanInvalidConfiguration(f"Unsupported arch: {arch}")
        return triplet

    def _tool_bin(self, package_name, binary):
        """Absolute path of a build tool from the tool graph.

        autoreconf honours $AUTOMAKE; passing a bare "automake" makes it
        resolve through PATH, where a host automake of a different minor
        version (1.17) may shadow the tool_requires one (1.18) and fail
        with "version mismatch" against the aclocal.m4 that aclocal 1.18
        just generated.  Always pin the wrapper from the dependency.
        """
        for dep in self.dependencies.build.values():
            if dep.ref.name == package_name:
                candidate = os.path.join(dep.package_folder, "bin", binary)
                if os.path.isfile(candidate):
                    return candidate
        return binary

    def generate(self):
        host_triplet = self._gnu_triplet()
        build_arch = (self.settings_build.get_safe("arch")
                      if self.settings_build else None)
        build_triplet = self._gnu_triplet(build_arch or self.settings.arch)
        tc = AutotoolsToolchain(self)
        tc.configure_args.extend([
            f"--build={build_triplet}",
            f"--host={host_triplet}",
            # MMX/SSE x86-only intrinsics — off for aarch64 OHOS
            "--disable-x86-optimizations",
        ])
        if not self.options.shared:
            tc.configure_args.extend(["--enable-static", "--disable-shared"])
        # configure compiles *and runs* conftest binaries (AC_FUNC_MALLOC /
        # AC_CHECK_LIB checks are not skipped for this old configure.ac —
        # it has no AC_COMPILE_IFELSE-only path).  On the OHOS build host
        # the freshly linked conftest needs libc++_shared.so from the SDK
        # llvm/lib/aarch64-linux-ohos dir (note: NOT the llvm/lib root that
        # babeltrace/libgsf prepend for lld's libxml2 — libc++_shared.so
        # lives in the target-triplet subdir).
        import glob as _glob
        env = tc.environment()
        if self.settings.os == "OHOS":
            _llvm_base = ("/data/service/hnp/ohos-sdk.org/"
                          "ohos-sdk_26.0.0.18/ohos/native/llvm/lib")
            if not os.path.isdir(_llvm_base):
                _cands = sorted(_glob.glob(
                    "/data/service/hnp/ohos-sdk.org/*/ohos/native/llvm/lib"))
                _llvm_base = _cands[0] if _cands else ""
            if _llvm_base:
                # clang -stdlib=libc++ links against libc++_shared.so in
                # the aarch64-linux-ohos triplet dir; c++/ is the
                # libc++ static/shared runtime fallback dir
                for _sub in ("aarch64-linux-ohos",
                             "aarch64-linux-ohos/c++"):
                    _d = os.path.join(_llvm_base, _sub)
                    if os.path.isdir(_d):
                        env.prepend_path("LD_LIBRARY_PATH", _d)
        tc.generate(env=env)

    def build(self):
        src = self.source_folder
        # 1) bootstrap — release tarball ships no configure (removed since
        #    1.6.0, see configure-file-README.txt)
        apply_conandata_patches(self)
        if not os.path.isfile(os.path.join(src, "configure")):
            libtoolize = self._tool_bin("libtool", "libtoolize")
            # libtoolize first: AM_PROG_LIBTOOL requires config/ltmain.sh
            # which `automake --add-missing` refuses to install by itself
            self.run(f"{libtoolize} --copy --force",
                     cwd=src, env="conanbuild")
            # ltmain.sh lands in project root, automake wants config/
            ltmain = os.path.join(src, "ltmain.sh")
            cfg_ltmain = os.path.join(src, "config", "ltmain.sh")
            if os.path.isfile(ltmain) and not os.path.isfile(cfg_ltmain):
                os.rename(ltmain, cfg_ltmain)
            # AC_CONFIG_MACRO_DIR([config/m4]) — make sure it exists for
            # aclocal -I (harmless if libtoolize already created it)
            os.makedirs(os.path.join(src, "config", "m4"), exist_ok=True)
            automake = self._tool_bin("automake", "automake")
            self.run(
                f'AUTOMAKE="{automake} --add-missing --foreign --copy" '
                "autoreconf -fisv",
                cwd=src, env="conanbuild",
            )
        if not os.path.isfile(os.path.join(src, "configure")):
            raise ConanException("autoreconf did not produce configure")

        # 2) patch the generated configure: umask 077 → 000 for the
        #    config.status temp machinery (HMDFS unwritable 0700 dirs)
        configure_path = os.path.join(src, "configure")
        with open(configure_path, "r", encoding="utf-8",
                  errors="replace") as f:
            content = f.read()
        patched = content.replace(
            '(umask 077 && mktemp -d "./confXXXXXX")',
            '(umask 000 && mktemp -d "./confXXXXXX")',
        ).replace(
            '(umask 077 && mkdir "$tmp")',
            '(umask 000 && mkdir "$tmp")',
        )
        if patched != content:
            with open(configure_path, "w", encoding="utf-8") as f:
                f.write(patched)

        # 3) configure + make
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        copy(self, "COPYING.TXT", src=self.source_folder,
             dst=f"{self.package_folder}/licenses", keep_path=False)

    def package_info(self):
        # library + CLI (soundstretch) both ship; consumers mainly link
        # libSoundTouch
        self.cpp_info.libs = ["SoundTouch"]
        self.cpp_info.set_property("pkg_config_name", "soundtouch")
        self.cpp_info.set_property("cmake_file_name", "SoundTouch")
        self.cpp_info.set_property("cmake_target_name", "SoundTouch::SoundTouch")
        # headers install under include/soundtouch/
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.system_libs = ["m"]
        # CLI shipped alongside the library (R38: commands.json declares it
        # at software level; binary consumers may use bindirs)
        self.cpp_info.bindirs = ["bin"]
