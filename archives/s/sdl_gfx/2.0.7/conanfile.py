#!/usr/bin/env python3
"""Conan recipe for SDL_gfx 2.0.7 — SDL 1.2 graphics drawing primitives.

SDL_gfx (by A. Schiffler) adds drawing primitives (lines/boxes/circles/polygons,
filled and anti-aliased variants), rotozoom/zoom transforms, a framerate manager
and MMX/C image filters on top of SDL 1.2 surfaces.

HarmonyOS (aarch64) adaptation notes
------------------------------------
1. Platform triplet: the bundled config.guess/config.sub are 2001 vintage and know
   neither aarch64 nor HarmonyOS — the top-level copies are patched by
   0003/0004 and the Test/ copies (used when building the upstream demo programs)
   by 0001/0002.
2. SDL discovery: ``configure.in`` requires SDL through ``AM_PATH_SDL``, which can
   only read cflags/libs from a ``sdl-config`` *script*.  The Conan ``sdl`` package
   ships headers/libs only, so ``generate()`` writes a ``sdl-config`` shim that
   points at the SDL package folder and exports ``SDL_CONFIG`` for configure.
3. MMX: configure defaults to ``--enable-mmx``, which injects x86 MMX inline
   assembly in ``SDL_imageFilter.c`` (clang/aarch64: "unrecognized instruction
   mnemonic").  Upstream README documents ``--disable-mmx`` for non-x86 targets,
   which is what this recipe does.
4. Static only: the bundled 2001-vintage libtool (ltconfig) has no dynamic-linker
   entry for OHOS ("checking dynamic linker characteristics... no"), so only
   ``libSDL_gfx.a`` can be produced — ``shared=True`` is rejected in ``validate()``.

R26: ``libSDL_gfx`` is not a system library name on OHOS — no collision.
R32: settings.os must check in ("Linux", "OHOS").
R38: library-only package — no commands.json.
"""
import os
import urllib.request

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import (apply_conandata_patches, check_sha256, chmod,
                               copy, export_conandata_patches, get, save, unzip)
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout

# AM_PATH_SDL calls: `sdl-config --cflags`, `sdl-config --libs`, `sdl-config --version`.
# The Conan sdl package has no such script, so we synthesize one.
_SDL_CONFIG_SHIM = """#!/bin/sh
# sdl-config shim generated by the sdl_gfx Conan recipe (AM_PATH_SDL needs a script).
prefix="{prefix}"
for arg in "$@"; do
    case "$arg" in
        --version)     echo "{sdl_version}" ;;
        --cflags)      echo "-I$prefix/include -I$prefix/include/SDL -D_GNU_SOURCE=1 -D_REENTRANT{static_define}" ;;
        --libs)        echo "-L$prefix/lib -lSDL{misc_libs}" ;;
        --static-libs) echo "-L$prefix/lib -lSDL{misc_libs}" ;;
        --prefix)      echo "$prefix" ;;
        --exec-prefix) echo "$prefix" ;;
    esac
done
exit 0
"""

_HEADERS = (
    "SDL_gfxPrimitives.h",
    "SDL_gfxPrimitives_font.h",
    "SDL_rotozoom.h",
    "SDL_framerate.h",
    "SDL_imageFilter.h",
)


class SdlGfxConan(ConanFile):
    name = "sdl_gfx"
    version = "2.0.7"
    description = ("SDL_gfx — graphics drawing primitives (lines, boxes, circles, "
                   "ellipses, polygons, bezier, anti-aliased variants), rotozoom/zoom "
                   "surface transforms, framerate control and image filters for SDL 1.2")
    license = "LGPL-2.1-or-later"
    homepage = "https://www.ferzkopp.net/Software/SDL_gfx-2.0/"
    url = "https://www.ferzkopp.net/Software/SDL_gfx-2.0/"

    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # AM_PATH_SDL($SDL_VERSION=1.2.0, ..., AC_MSG_ERROR([...not found!])) -> hard dependency.
        # transitive_headers=True: SDL_gfx's public headers do `#include <SDL/SDL.h>`, so DL
        # consumers need SDL's include dirs.  Without it Conan's static-package trait
        # optimization sets require.headers=False and CMakeDeps emits empty SDL include dirs
        # ("SDL/SDL.h not found" in test_package) — same pattern as at-spi2-core 2.60.5.
        self.requires("sdl/1.2.15", transitive_headers=True)

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")
        # SDL_gfx is a C library.
        self.settings.rm_safe("compiler.cppstd")
        self.settings.rm_safe("compiler.libcxx")

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")
        if self.options.shared:
            raise ConanInvalidConfiguration(
                "sdl_gfx 2.0.7 ships a 2001-vintage libtool (ltconfig) with no "
                "dynamic-linker entry for OHOS, so only the static library "
                "(libSDL_gfx.a) can be produced; build with -o shared=False"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        data = self.conan_data["sources"]
        try:
            get(self, **data, strip_root=True)
            return
        except ConanException as exc:
            # www.ferzkopp.net (Apache `AddEncoding x-gzip`) answers .tar.gz requests with
            # `Content-Encoding: x-gzip`.  Conan's requests/urllib3 based downloader honours
            # that header, transparently decodes the transfer and therefore hash-checks the
            # DECOMPRESSED tar stream against conandata.yml -> deterministic sha256 mismatch.
            # urllib does not decode Content-Encoding, so the raw published bytes land on
            # disk and the recorded sha256 applies.  Precedents: blepvco 0.1.0, irpas 0.10.
            self.output.warning(
                f"conan downloader failed ({exc}); retrying with urllib "
                "(server responds Content-Encoding: x-gzip)"
            )
        filename = data.get("filename") or data["url"].rsplit("/", 1)[-1]
        archive = os.path.join(self.source_folder, filename)
        with urllib.request.urlopen(data["url"], timeout=300) as resp:
            payload = resp.read()
        with open(archive, "wb") as handler:
            handler.write(payload)
        check_sha256(self, archive, data["sha256"])
        unzip(self, archive, destination=self.source_folder, strip_root=True)
        os.remove(archive)

    # ── build environment ────────────────────────────────────────────────

    def _sdl_config_shim(self):
        """Write a sdl-config shim pointing at the Conan sdl package."""
        sdl = self.dependencies["sdl"]
        prefix = sdl.package_folder.replace("\\", "/")
        shared = bool(sdl.options.shared)
        shim_dir = os.path.join(self.generators_folder, "sdl-config-shim")
        os.makedirs(shim_dir, exist_ok=True)
        shim = os.path.join(shim_dir, "sdl-config")
        save(self, shim, _SDL_CONFIG_SHIM.format(
            prefix=prefix,
            sdl_version=str(sdl.ref.version),
            static_define="" if shared else " -DSDL_STATIC",
            misc_libs=" -lm -ldl -pthread",
        ))
        chmod(self, shim, read=True, write=True, execute=True)   # AM_PATH_SDL executes it
        return shim

    def generate(self):
        shim = self._sdl_config_shim()
        self.output.info(f"SDL_CONFIG shim: {shim}")

        tc = AutotoolsToolchain(self)
        # aarch64 has no MMX: configure's default --enable-mmx injects x86 inline asm.
        tc.configure_args.append("--disable-mmx")
        if not self.options.shared:
            tc.configure_args.append("--disable-shared")
            tc.configure_args.append("--enable-static")
        tc.generate()

        # configure.in uses AM_PATH_SDL, which can only read cflags/libs from a
        # `sdl-config` script, so the shim must be visible to the configure call.
        # The Autotools helper runs configure/make with env="conanbuild"; scripts
        # registered here are aggregated into that file.
        env = Environment()
        env.define("SDL_CONFIG", shim)
        env.vars(self, scope="build").save_script("conanbuildenv-sdl_gfx_shim")

    # ── build ────────────────────────────────────────────────────────────

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])

    def package(self):
        for name in ("COPYING", "LICENSE"):
            copy(self, name, src=self.source_folder,
                 dst=os.path.join(self.package_folder, "licenses"), keep_path=False)
        for header in _HEADERS:
            copy(self, header, src=self.source_folder,
                 dst=os.path.join(self.package_folder, "include"))
        # 2001-vintage libtool puts the archive in .libs/ (the .la file is not shipped).
        # The Autotools helper builds out-of-source, so look in the build folder first.
        for lib_dir in (os.path.join(self.build_folder, ".libs"),
                        os.path.join(self.source_folder, ".libs")):
            if os.path.isdir(lib_dir):
                copy(self, "libSDL_gfx.a", src=lib_dir,
                     dst=os.path.join(self.package_folder, "lib"))

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "SDL_gfx")
        self.cpp_info.set_property("cmake_target_name", "SDL_gfx::SDL_gfx")
        self.cpp_info.set_property("pkg_config_name", "SDL_gfx")
        self.cpp_info.libs = ["SDL_gfx"]
        if str(self.settings.os) in ("Linux", "OHOS"):
            self.cpp_info.system_libs = ["m", "dl", "pthread"]
