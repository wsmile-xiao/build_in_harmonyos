#!/usr/bin/env python3
"""Conan recipe for shortfin web server.

Shortfin is a fast and lightweight static web server using C and autotools.
Since automake is not available on HarmonyOS, this recipe uses a custom
build method that generates config.h and a Makefile manually, then
compiles with the Conan-provided compiler environment.
"""
import os

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches, copy
from conan.tools.gnu import AutotoolsToolchain
from conan.tools.layout import basic_layout


class ShortfinConan(ConanFile):
    name = "shortfin"
    version = "1.0"
    description = "Shortfin is a fast and lightweight static web server"
    license = "MIT"
    homepage = "https://github.com/timothyej/Shortfin"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # Use AutotoolsToolchain just to generate compiler environment
        # (CC, CFLAGS, LDFLAGS from the Conan profile)
        tc = AutotoolsToolchain(self)
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        self._generate_config_h()
        self._generate_makefile()
        self.run("make -j1", cwd=self.source_folder, env="conanbuild")

    def _generate_config_h(self):
        """Generate config.h with appropriate defines for OHOS."""
        config_h = os.path.join(self.source_folder, "src", "config.h")
        content = '''/* config.h for shortfin on HarmonyOS */
#define PACKAGE_NAME "shortfin"
#define PACKAGE_TARNAME "shortfin"
#define PACKAGE_VERSION "1.0"
#define PACKAGE_STRING "shortfin 1.0"
#define PACKAGE_BUGREPORT "timothy.ejohansson@gmail.com"
#define PACKAGE_URL "https://github.com/timothyej/Shortfin"

#define HAVE_STDIO_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STRING_H 1
#define HAVE_STRINGS_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_STDINT_H 1
#define HAVE_UNISTD_H 1
#define HAVE_FCNTL_H 1
#define HAVE_PTHREAD_H 1
#define HAVE_LIBPTHREAD 1
#define HAVE_SIGNAL_H 1
#define HAVE_SCHED_H 1
#define HAVE_NETINET_TCP_H 1
#define HAVE_SYS_EPOLL_H 1
/* HAVE_SYS_EVENT_H not defined - no kqueue on OHOS */
#define HAVE_SYS_STAT_H 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_MEMORY_H 1
#define STDC_HEADERS 1
'''
        with open(config_h, "w") as f:
            f.write(content)

    def _generate_makefile(self):
        """Generate a simple Makefile since automake is not available."""
        makefile = os.path.join(self.source_folder, "Makefile")
        content = '''# Makefile for shortfin (generated by Conan recipe)

CC ?= clang
CFLAGS ?= -Wall -O2
LDFLAGS ?= -Wl,--no-as-needed -lpthread

prefix = /usr/local
exec_prefix = $(prefix)
bindir = $(exec_prefix)/bin
sysconfdir = $(prefix)/etc/shortfin
localstatedir = $(prefix)/var

SRCS = src/cache.c src/config_file.c src/connection.c src/events.c \\
       src/lock.c src/master_server.c src/mime_types.c src/proxy.c \\
       src/request.c src/response.c src/safe.c src/server.c \\
       src/socket.c src/status_codes.c src/worker.c

OBJS = $(SRCS:.c=.o)

BIN = shortfin

.PHONY: all clean install

all: $(BIN)

$(BIN): $(OBJS)
	$(CC) $(LDFLAGS) -o $@ $(OBJS)

%.o: %.c
	$(CC) $(CFLAGS) -I./src -c -o $@ $<

clean:
	rm -f $(OBJS) $(BIN)

install: all
	mkdir -p $(DESTDIR)$(bindir)
	mkdir -p $(DESTDIR)$(sysconfdir)
	mkdir -p $(DESTDIR)$(localstatedir)/logs/shortfin
	mkdir -p $(DESTDIR)$(localstatedir)/www
	mkdir -p $(DESTDIR)$(localstatedir)/www/cache
	install -m 755 $(BIN) $(DESTDIR)$(bindir)/$(BIN)
	install -m 644 config/shortfin.conf $(DESTDIR)$(sysconfdir)/shortfin.conf
'''
        with open(makefile, "w") as f:
            f.write(content)

    def package(self):
        copy(self, "shortfin", dst=os.path.join(self.package_folder, "bin"), src=self.source_folder)
        copy(self, "shortfin.conf", dst=os.path.join(self.package_folder, "etc", "shortfin"), src=os.path.join(self.source_folder, "config"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
