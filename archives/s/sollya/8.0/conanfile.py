#!/usr/bin/env python3
"""Conan recipe — sollya 8.0.

Sollya is a tool environment for safe floating-point code development
(certified infinity norm, automatic polynomial implementer, fast Remez
algorithm), shipping BOTH a shared/static library ``libsollya`` and a
command-line tool ``sollya`` (bin_PROGRAMS).

Build system: autotools.  The upstream archive ships **no pre-generated
``configure``** (only ``configure.ac`` + ``autogen.sh``), so build() must run
``autoreconf`` first — see the OHOS adaptations below.

OHOS / HarmonyOS adaptations
----------------------------
Two upstream-source patches (registered in conandata.yml, applied by
``apply_conandata_patches``) plus three build-time adjustments:

Patches (both touch **tarball upstream source files** => registered via
``refresh-patch`` + conandata, per the 2026-09-23 workspace ruling):

* ``0001-configure.ac-drop-lstdcxx.patch``
  ``ADD_LSTDC="yes" -> "no"``.  Upstream tests ``-lstdc++`` with
  ``AC_COMPILE_IFELSE`` (**compiles only, never links**), so the check always
  passes and ``LIBS`` permanently keeps ``-lstdc++`` (generated
  ``Makefile:425``).  Switching to ``AC_LINK_IFELSE`` would NOT help either:
  at configure time the probe runs under **bare clang** (no libtool
  ``-nostdlib``), so it still passes and cannot reproduce the make-time
  failure.  Hence the removal must be unconditional.
  Why it fails at make time (three stacked layers): (1) libtool links ``.so``
  with ``-nostdlib`` so the clang driver no longer injects standard-library
  handling nor its internal ``-lstdc++ -> libc++`` mapping; (2) the hardcoded
  ``-lstdc++`` appears **before** the SDK ``-L`` paths while lld resolves
  ``-L`` strictly left-to-right; (3) no ``libstdc++`` entity exists anywhere
  (``find -name 'libstdc++*'`` is empty; the SDK only ships ``libc++*``).
  Observed: ``ld.lld: error: unable to find library -lstdc++`` at
  ``libsollya.la``.

* ``0002-tests-lib-Makefile.am-lstdcxx-to-lc.patch``
  ``LDADD = ... -lstdc++ -> -lc++`` (clang/libc++ platform, correct runtime).

Build-time (in build(), regenerated every run, **not** registered as patches):

* ``_drop_umask_077()`` — **E114**.  The generated ``configure`` embeds
  ``tmp=`(umask 077 && mktemp -d "./confXXXXXX") ...`` for config.status's
  temp dir.  HMDFS forces setgid so it lands as ``drwx--S---`` (``0o2700``),
  and our euid is neither the owner nor in the file's group, so the "other"
  bit is empty => writing ``subs1.awk`` is refused:
  ``config.status: error: could not setup config files machinery``.  Measured
  A/B: ``(umask 077 && mktemp -d)`` -> ``mode=0o2700`` WRITE FAIL, plain
  ``mkdir 0700`` -> ``mode=0o2771`` (filesystem gains group rwx) WRITE OK.
  This only edits the **generated** file (never tracked, regenerated by every
  autoreconf) and is kept as reproducible code executed on every build() —
  hence exempt from refresh-patch registration (workspace ruling: generation +
  reproducible code + runs every rebuild, all three must hold).

* ``--build=aarch64-unknown-linux-ohos`` — upstream ``config.guess``
  (2026-05-17) cannot classify ``uname -s = HarmonyOS`` /
  ``uname -r = HongMeng Kernel 1.12.0``, so it falls back to a
  self-compiled ``dummy.c`` probe, which is then refused by the same HMDFS
  permission shape => ``configure: error: cannot guess build type; you must
  specify one``.  The triplet equals this machine's clang ``Target:`` (see
  device-facts appendix) and ``config.sub`` accepts it.  With ``--build``
  given, ``config.guess`` is never invoked at all.

* ``make check`` runs with ``env=["conanbuild", "conanrun"]`` — the check
  stage needs **runtime** shared libraries (``libfplll.so.9``,
  ``libxml2.so.16``, ``libmpfi.so.0``) that live in the conan cache, while
  compile-time ``-L`` only affects linking (the loader consults
  ``RPATH``/``LD_LIBRARY_PATH``/default paths only).  Measured: without
  ``conanrun`` the loader prints 6 ``Error loading shared library`` lines plus
  292 ``symbol not found``, ``.output`` stays empty, and tests-tool reports
  ``TOTAL 33 / PASS 0`` while tests-lib never even runs (top-level
  ``check-recursive`` exits early), i.e. N' collapses to 0.  Using conan's
  standard ``conanrun`` env keeps the recipe identical to CI (no
  "green locally, red in CI").

* ``make check`` additionally prefixes the **SDK's own ``llvm/lib``** onto
  ``LD_LIBRARY_PATH`` **inline on the command line** (``_sdk_xml2_libdir``).
  Reason: the env wrapper sources ``conanbuildenv`` (profile-injected
  ``llvm/lib``) first and ``conanrunenv`` second, and the runenv *prepends*
  the conan libxml2 package dir **ahead of** it.  On CI worker (build #59839,
  PR #12419) that leading ``libxml2.so.16`` entry was present but **not
  loadable**, and musl **hard-fails on the first unloadable same-named entry
  without falling back** to the later good copy in ``llvm/lib`` nor to
  RUNPATH → SDK ``lld`` cannot start → ``clang-15: error: unable to execute
  command`` → ``make: *** [Makefile:1287: libraryexample.a] Error 1``.
  Byte-identical local repro: an empty ``libxml2.so.16`` first in
  ``LD_LIBRARY_PATH`` prints the same 1 load line + the same 17
  ``Error relocating … symbol not found`` lines (rc=127); putting
  ``llvm/lib`` first makes it succeed even with the broken entry present.
  Locally the conan copy loads fine, which is exactly why the device round
  was green — "device green ≠ CI green".  An inline prefix (append
  semantics, ``${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}``) is used because the
  env scripts are sourced *before* the command: an outer ``Environment``
  definition would be overwritten by ``conanrunenv``'s export.
"""

import os
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


def _prepare_autotools_env(conanfile):
    """The conan-provided automake/libtoolize hardcode absolute paths for
    autoconf / autoheader / autom4te / sed that do not exist on this host.
    Point those env vars at whatever is actually on PATH (no-op if already
    set by the toolchain)."""
    for tool, var in (("autoconf", "AUTOCONF"),
                      ("autoheader", "AUTOHEADER"),
                      ("autom4te", "AUTOM4TE"),
                      ("sed", "SED")):
        if os.environ.get(var):
            continue
        path = shutil.which(tool)
        if path:
            os.environ[var] = path


def _drop_umask_077(conanfile, path):
    """E114 / HMDFS: strip ``umask 077`` from the generated configure so
    config.status can actually create and write its temp dir.

    Only touches the autoreconf **generated** file (untracked, regenerated on
    every run); the change lives here as reproducible code executed on every
    build(), so no patch registration is required (opposite boundary: edits to
    tarball upstream files such as config.guess/config.sub/Makefile.am would
    require refresh-patch)."""
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        data = f.read()
    original = data
    # Verbatim mirrors of the reference recipe
    # (archives/a/abiword-plugin-clarisworks/3.0.8/conanfile.py) — note the
    # replacement text must NOT keep a stray ")" : dropping `umask 077 && `
    # from inside `( ... )` also drops the parentheses, otherwise the
    # backquoted command becomes `mktemp -d "...") ...` (unbalanced).
    reps = (
        ('tmp=`(umask 077 && mktemp -d "./confXXXXXX") 2>/dev/null`',
         'tmp=`mktemp -d "./confXXXXXX" 2>/dev/null`'),
        ('(umask 077 && mkdir "$tmp")',
         'mkdir "$tmp"'),
    )
    for old, new in reps:
        data = data.replace(old, new)
    if data != original:
        conanfile.output.info("E114: dropped umask 077 from generated configure")
    with open(path, "w", encoding="utf-8") as f:
        f.write(data)
    # Self-check: no `umask 077 && mktemp|mkdir` left, and no unbalanced
    # `")` introduced by a sloppy replacement.
    left = data.count("umask 077 && mktemp") + data.count("umask 077 && mkdir")
    if left:
        raise ConanInvalidConfiguration(
            "E114: umask 077 still present in generated configure (%d)" % left)


def _sdk_xml2_libdir(conanfile):
    """Directory holding the **SDK's own** ``libxml2.so.16`` — the copy that is
    ABI-matched to the SDK ``lld`` (which NEEDs it at run time).

    Returns ``None`` when no candidate directory really contains the file
    (callers must then fall back to the ambient loader path and warn loudly).

    Derivation follows the established pattern (knowledge drafts E2175/E557 /
    E573): ``tools.build:compiler_executables["c"]`` (profile-set absolute
    path) → ``os.path.realpath`` (the compiler is a symlink into the SDK, and
    a symlinked shim would otherwise derive a wrong directory) → sibling
    ``lib`` of the binary's directory; existence-filtered on
    ``libxml2.so.16`` so we never prepend a directory that does not actually
    provide the library.  ``shutil.which("clang")`` is the fallback when the
    conf is absent (device-facts §一.14: bare command names in subprocesses
    are unreliable on OHOS Python, which is why ``shutil.which`` is used
    rather than trusting PATH lookups inside ``posix_spawn``)."""
    candidates = []
    exe = conanfile.conf.get("tools.build:compiler_executables")
    if isinstance(exe, dict) and exe.get("c"):
        candidates.append(exe["c"])
    for name in ("clang", "clang-15"):
        path = shutil.which(name)
        if path:
            candidates.append(path)
            break
    for c in candidates:
        real = os.path.realpath(c)
        libdir = os.path.normpath(
            os.path.join(os.path.dirname(real), "..", "lib"))
        if os.path.isfile(os.path.join(libdir, "libxml2.so.16")):
            return libdir
    return None


class SollyaConan(ConanFile):
    name = "sollya"
    version = "8.0"
    description = ("Tool environment for safe floating-point code development "
                   "(certified infinity norm, automatic polynomial implementer, "
                   "fast Remez algorithm) + libsollya library")
    license = "CeCILL-C"
    homepage = "https://www.sollya.org/"
    url = ""  # CI fills this
    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    # G2 round 1 failed at graph computation with:
    #   ERROR: sollya/8.0@ohpcd/stable: Package type is 'library', but no
    #          'shared' option declared
    # Conan 2 rule: package_type="library" REQUIRES a `shared` option to tell
    # the variants apart, otherwise the graph dies before download/patch/build
    # (that is why round 1 fast-failed in ~1min).  Added per the repo convention
    # (1611 recipes use package_type="library" + shared option; only 96 use
    # "shared-library"), mirroring archives/a/abgate/1.2.0 and a52dec.
    # default shared=True/fPIC=True matches the native exploration, where
    # libtool's defaults produced BOTH libsollya.so.8.0.0 and libsollya.a;
    # AutotoolsToolchain maps these options onto --enable-shared / -fPIC so
    # build() needs no manual handling.
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # Honesty note (workspace ruling): the dependency graph is NOT all
        # prebuilt.  fplll/5.5.0's only remote binary is bound to gmp/6.3.0
        # while mpfi/1.5.4 pins gmp/6.3.0.1 with force=True; with
        # --build=missing one of the two is compiled locally (+≈20min per
        # clean round).  CI's build_and_test.sh uses --build=missing too, so
        # the behavior is structurally identical.  Do not claim "all
        # dependencies are prebuilt".
        self.requires("gmp/6.3.0")
        self.requires("mpfr/4.2.2.1")
        self.requires("mpfi/1.5.4")
        self.requires("libxml2/2.15.3.1")
        self.requires("fplll/5.5.0")
        self.requires("zlib/1.3.1")

    def build_requirements(self):
        # The archive ships no pre-generated `configure`, so build() runs
        # `autoreconf`.  The build host (CI sandbox) lacks automake/aclocal/
        # libtoolize — only the autoconf suite exists under
        # /data/service/hnp/bin — so pull automake and libtool in as
        # tool_requires.  **Do NOT tool_requires autoconf**: conan's autoconf
        # drags perl/5.42.2 and exports PERL5LIB pointing at it, which ABI-
        # mismatches the HNP perl 5.42.0 and crashes autoreconf with
        # Perl_my_cxt_init (device-facts §1.23 poison pill).
        # tool_requires resolve with the *build* profile, so both -pr:h and
        # -pr:b must be passed to conan create (CI already does this at
        # build_and_test.sh:316).
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")

    def validate(self):
        # R32: settings.os must check in ("Linux", "OHOS")
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "sollya is only supported on Linux/OHOS, not "
                + str(self.settings.os))

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def generate(self):
        _prepare_autotools_env(self)
        tc = AutotoolsToolchain(self)
        # Workaround #1: skip config.guess entirely (HarmonyOS/HongMeng uname
        # + HMDFS temp-dir permission).  Triplet matches the host clang
        # `Target:` and config.sub accepts it.
        tc.configure_args.append("--build=aarch64-unknown-linux-ohos")
        # Locate each dependency by its conan package folder (configure's
        # AC_CHECK_LIB then finds headers/libs through the resulting -I/-L).
        dep_map = (("gmp", "gmp"),
                   ("mpfr", "mpfr"),
                   ("mpfi", "mpfi"),
                   ("libxml2", "xml2"),
                   ("fplll", "fplll"),
                   ("zlib", "z"))
        for pkg, opt in dep_map:
            tc.configure_args.append(
                "--with-{}={}".format(opt, self.dependencies[pkg].package_folder))
        tc.generate()

    def build(self):
        _prepare_autotools_env(self)
        # bootstrap: the archive ships no `configure`.
        self.run("autoreconf -i", cwd=self.source_folder, env="conanbuild")
        # Workaround #2 (E114): make the generated configure usable on HMDFS.
        _drop_umask_077(self, os.path.join(self.source_folder, "configure"))
        autotools = Autotools(self)
        autotools.configure()
        # -j1 (E074 HMDFS jobserver fifo EPERM; same as the reference
        # abiword-plugin recipe).  Parallelism only affects wall time, not
        # test semantics; the native exploration used -j4 with an injected
        # pipe jobserver, which is recorded in notes.md.
        autotools.make(args=["-j1"])
        # Upstream test suites: tests-tool (33: 32 regular + 1 MAYFAIL) and
        # tests-lib (348) => N = 381.  `conanrun` supplies the three runtime
        # shared libraries (fplll/libxml2/mpfi) or make check collapses to
        # 0 PASS with tests-lib never running.
        #
        # NOTE: this CANNOT be autotools.make(target=..., env=...) —— G2 round 3
        # failed with
        #   TypeError: Autotools.make() got an unexpected keyword argument 'env'
        # because conan 2.29's real signature is
        #   Autotools.make(self, target=None, args=None, makefile=None)
        # (no env).  ConanFile.run() DOES take env/cwd:
        #   run(self, command, stdout=None, cwd=None, ignore_errors=False,
        #       env='', quiet=False, shell=True, scope='build', stderr=None)
        # so drive `make check` through self.run() with both envs.
        #
        # cwd MUST be build_folder —— NOT source_folder: `conan create` runs an
        # OUT-OF-TREE build.  Autotools.configure()/make() execute inside
        # `<cache>/p/b/<pkg>/b/build-release`, and the log shows every step
        # `Leaving directory …/build-release` including `tests-lib` and
        # `tests-tool`, i.e. the Makefiles (and the `check` target) live
        # there.  Pointing cwd at source_folder made G2 round 4 fail with
        #   make: *** No rule to make target 'check'.  Stop.
        # (cwd/构建目录族 first red).  The native exploration R7 was an
        # IN-SOURCE build —— exactly why the two surfaces diverge: the same
        # call that works in the explorer breaks under conan create.
        #
        # Also: ConanFile.run(cwd=None) forwards None straight to subprocess,
        # whose None means "inherit conan create's own cwd" (NOT the build
        # dir), so cwd must be explicit rather than merely omitted.
        #
        # Inline LD_LIBRARY_PATH prefix (see module docstring, last bullet):
        # put the SDK llvm/lib — the lld-compatible libxml2.so.16 — FIRST for
        # this command and everything it spawns (linker invocations AND the
        # test binaries).  The prefix is applied on the command line, i.e.
        # AFTER the wrapper has sourced conanbuild.sh && conanrun.sh, so the
        # conanrun-fronted conan libxml2 dir can no longer shadow it (musl
        # hard-fails on an unloadable same-named entry without falling back;
        # CI build #59839).  Append semantics keep every conan runtime dir.
        xml2_lib = _sdk_xml2_libdir(self)
        if xml2_lib:
            check_cmd = ('LD_LIBRARY_PATH="%s${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" '
                         'make -j1 check' % xml2_lib)
        else:
            self.output.warning(
                "SDK libxml2.so.16 not found next to the configured C compiler; "
                "make check falls back to the ambient loader path, which fails "
                "on CI workers where the conan libxml2 dir shadows the SDK copy "
                "(Error loading shared library libxml2.so.16)")
            check_cmd = "make -j1 check"
        self.run(check_cmd, cwd=self.build_folder,
                 env=["conanbuild", "conanrun"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.set_property("pkg_config_name", "sollya")
        # libsollya.la -> consumers link with -lsollya
        self.cpp_info.libs = ["sollya"]
        # sollya.h + sollya-messages.h are installed by include_HEADERS
        self.cpp_info.includedirs = ["include"]
        # bin/sollya (command-line tool, see commands.json)
        self.cpp_info.bindirs = ["bin"]
        # The C++ runtime must be libc++ on this platform (clang/libc++),
        # never libstdc++ — see the two patches above.
        self.cpp_info.cxxflags = ["-std=c++11"]
