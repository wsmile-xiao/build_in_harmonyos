#!/usr/bin/env python3
"""Conan recipe for snek 1.13 (posix host interpreter, application package).

What is built: only ``ports/posix/snek``, the host-side Snek interpreter
binary. The top-level Makefile also drives embedded firmware targets
(avr/arm/riscv hex/uf2 blobs) and the snekde/doc/examples subdirs; those
need foreign cross toolchains and are intentionally not built here.

Zero conan dependencies:
  - readline is disabled (``STATIC=1`` with ``LIBS=-lm`` override, so no
    ``-lreadline`` and no ``-static`` link). Interactive line editing falls
    back to the in-source fgets reader; script execution is unaffected.
  - ``snek-gram.h`` is normally generated by the ``lola`` LL parser
    generator (Debian build-dep), which is not available on OHOS CI. This
    recipe ships the official lola 1.8 output as
    ``patches/0001-posix-pregenerated-snek-gram-h.patch``. The file is
    byte-reproducible with ``lola -DSNEK_SLICE -DSNEK_DICT -o snek-gram.h
    snek-gram.ll`` (the single ``#line`` path records the output file name,
    so the same output name yields identical bytes). ``snek-builtin.h`` is
    generated at build time by the in-source ``snek-builtin.py`` (stdlib
    only) using the HMBS-injected python3.

Upstream tests (layer 1): ``test/Makefile`` registers 35 ``pass-*.py``
(success expected, exit 0) and 16 ``fail-*.py`` (failure expected, exit 1,
including 3 ``fail-syntax-*.py``) — 51 files total. ``build()`` runs every
file with the freshly built ``ports/posix/snek`` binary (the posix leg of
``make check``; the qemu-arm/qemu-riscv legs need foreign-architecture
firmware that cannot be built or executed on OHOS aarch64, and the python3
leg only oracles the test files under CPython, not this product). Counts
come from parsing ``test/Makefile`` (single deterministic source) plus one
JSON results file written per run — never from grepping stdout. The real
result is dual-channel emitted as HMBS_UPSTREAM_TEST_RESULT and persisted
to ``res/hmbs_upstream.json`` in the package for cache-hit re-emit.
"""

import json
import os
import re
import shutil
import subprocess

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import VirtualBuildEnv
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


# Single counting source for the upstream suite: test/Makefile lists.
# SUCCESS_TESTS = 35 pass-*.py, FAIL_TESTS = 13 fail-*.py + $(SYNTAX_TESTS).
EXPECTED_UPSTREAM_TOTAL = 51


class SnekConan(ConanFile):
    name = "snek"
    version = "1.13"
    description = "Snek, a tiny Python-inspired language for embedded computing (posix host interpreter)"
    license = "GPL-3.0-or-later"
    homepage = "https://sneklang.org"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "snek is adapted for Linux and OHOS, not %s" % self.settings.os
            )

    def generate(self):
        VirtualBuildEnv(self).generate()

    def source(self):
        get(self, **self.conan_data["sources"][self.version], strip_root=True)

    def _resolve_tool(self, configured, names):
        if configured and os.path.exists(configured):
            return configured
        for cand in names:
            found = shutil.which(cand)
            if found:
                return found
        home_bin = os.path.join(os.path.expanduser("~"), "usr", "local", "bin")
        for cand in names:
            path = os.path.join(home_bin, cand)
            if os.path.exists(path):
                return path
        return configured or names[0]

    def _c_compiler(self):
        try:
            compilers = self.conf.get("tools.build:compiler_executables",
                                      default={}, check_type=dict) or {}
        except Exception:
            compilers = {}
        return self._resolve_tool(compilers.get("c"), ("clang", "cc"))

    def _python3(self):
        explicit = os.getenv("HMBS_PYTHON3")
        if explicit and os.path.exists(explicit):
            return explicit
        return self._resolve_tool(None, ("python3", "python"))

    def _parse_upstream_lists(self, test_makefile):
        with open(test_makefile, "r", encoding="utf-8", errors="replace") as handle:
            text = handle.read()

        def _var(name):
            match = re.search(name + r"\s*=\s*((?:[^\n\\]*\\\n)+[^\n]*)", text)
            if not match:
                raise ConanException("cannot find %s in %s" % (name, test_makefile))
            return match.group(1).replace("\\\n", " ").split()

        success = [t for t in _var("SUCCESS_TESTS") if t.endswith(".py")]
        fail_raw = _var("FAIL_TESTS")
        syntax = [t for t in _var("SYNTAX_TESTS") if t.endswith(".py")]
        fail = [t for t in fail_raw if t.endswith(".py")]
        if "$(SYNTAX_TESTS)" in fail_raw:
            fail = [t for t in fail if not t.startswith("$")] + syntax
        return success, fail

    def _run_upstream_tests(self, snek_bin, test_dir):
        """Run every registered upstream script once; record one JSON row each.

        pass-*.py must exit 0, fail-*.py must exit 1 (same oracle as
        ``test/Makefile`` check target, posix leg only). Returns a summary
        dict; also writes build_folder/hmbs_snek_results.json (the single
        deterministic counting source for the marker).
        """
        test_makefile = os.path.join(test_dir, "Makefile")
        success, fail = self._parse_upstream_lists(test_makefile)
        cases = [("pass", name) for name in success] + [("fail", name) for name in fail]
        if len(cases) != EXPECTED_UPSTREAM_TOTAL:
            raise ConanException(
                "upstream test count drift: Makefile lists %d cases, expected %d"
                % (len(cases), EXPECTED_UPSTREAM_TOTAL)
            )
        on_disk = set()
        for entry in os.listdir(test_dir):
            if (entry.startswith("pass-") or entry.startswith("fail-")) and entry.endswith(".py"):
                on_disk.add(entry)
        listed = set(name for _, name in cases)
        if on_disk != listed:
            raise ConanException(
                "upstream test set mismatch: Makefile lists %d files, disk has %d "
                "(missing=%s extra=%s)" % (
                    len(listed), len(on_disk),
                    sorted(listed - on_disk)[:5], sorted(on_disk - listed)[:5])
            )
        if os.path.getsize(snek_bin) == 0:
            raise ConanException("built snek binary is empty: %s" % snek_bin)

        rows = []
        for kind, name in cases:
            path = os.path.join(test_dir, name)
            if os.path.getsize(path) == 0:
                raise ConanException("upstream test file is empty: %s" % path)
            expect = 0 if kind == "pass" else 1
            out_bytes = b""
            try:
                proc = subprocess.run(
                    [snek_bin, path], timeout=120,
                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
                code = proc.returncode
                out_bytes = proc.stdout or b""
            except subprocess.TimeoutExpired as exc:
                code = "timeout"
                if isinstance(exc.stdout, bytes):
                    out_bytes = exc.stdout
            ok = (code == expect)
            text = out_bytes.decode("utf-8", errors="replace")
            snippet = text[-6000:] if len(text) > 6000 else text
            rows.append({"file": name, "kind": kind, "expected": expect,
                         "code": code, "ok": bool(ok), "output": snippet,
                         "detail": ""})
            self.output.info("HMBS diag upstream %s %s -> %s (expect %d)" % (
                kind, name, code, expect))
            if not ok:
                # Cycle-3 evidence route: the preflight summary truncates
                # multi-line per-failure dumps, so emit exactly ONE short
                # line per failure (last non-empty output line). Counting
                # and pass/fail semantics are untouched; this only makes
                # the failure cause survive summarization. The same detail
                # is embedded in the raised ConanException message below,
                # which the summary always quotes verbatim.
                nonempty = [line for line in text.splitlines() if line.strip()]
                tail = nonempty[-1][:220] if nonempty else "<empty stdout/stderr>"
                rows[-1]["detail"] = "rc=%s expect=%d last=%s" % (code, expect, tail)
                self.output.info("HMBS diag fail-detail %s: %s" % (name, rows[-1]["detail"]))

        results_path = os.path.join(self.build_folder, "hmbs_snek_results.json")
        with open(results_path, "w", encoding="utf-8") as handle:
            json.dump(rows, handle, indent=1)

        passed = sum(1 for row in rows if row["ok"])
        failed = len(rows) - passed
        return {"discovered": len(rows), "executed": len(rows),
                "passed": passed, "failed": failed, "skipped": 0,
                "failures": [row for row in rows if not row["ok"]]}

    def _emit_upstream(self, payload):
        for key in ("discovered", "executed", "passed", "failed", "skipped"):
            value = payload.get(key)
            if not isinstance(value, int) or value is None or value < 0:
                raise ConanException("upstream marker field %s is not a non-negative int" % key)
        if payload["passed"] + payload["failed"] != payload["executed"]:
            raise ConanException("upstream marker identity violated: passed + failed != executed")
        if not (payload["executed"] <= payload["discovered"]):
            raise ConanException("upstream marker identity violated: executed > discovered")
        if not (payload["executed"] + payload["skipped"] <= payload["discovered"]):
            raise ConanException("upstream marker identity violated: executed + skipped > discovered")
        line = "HMBS_UPSTREAM_TEST_RESULT=%s" % json.dumps(payload, separators=(",", ":"))
        self.output.info(line)
        try:
            print(line, flush=True)
        except Exception:
            pass
        try:
            with open(os.path.join(self.build_folder, "hmbs_upstream.json"),
                      "w", encoding="utf-8") as handle:
                json.dump(payload, handle)
        except Exception as exc:
            self.output.warning("HMBS diag persist upstream failed: %s" % exc)
        return line

    def _run_probe(self, snek_bin, script_text, tag):
        """Run one diagnostic variant script; never raises.

        Variants live in build_folder, are never counted, and never
        emit markers. Returns a short 'tag: rc=.. last=..' summary and
        emits a single HMBS diag probe line.
        """
        try:
            path = os.path.join(self.build_folder, "hmbs_probe_%s.py" % tag)
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(script_text)
            try:
                proc = subprocess.run(
                    [snek_bin, path], timeout=60,
                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
                code = proc.returncode
                out = (proc.stdout or b"").decode("utf-8", errors="replace")
            except subprocess.TimeoutExpired as exc:
                code = "timeout"
                if isinstance(exc.stdout, bytes):
                    out = exc.stdout.decode("utf-8", errors="replace")
                else:
                    out = ""
            nonempty = [line for line in out.splitlines() if line.strip()]
            tail = nonempty[-1][:200] if nonempty else "<empty>"
            summary = "%s: rc=%s last=%s" % (tag, code, tail)
            self.output.info("HMBS diag probe %s" % summary)
            return summary
        except Exception as exc:
            self.output.info("HMBS diag probe %s skipped: %s" % (tag, exc))
            return ""

    def _read_upstream_test(self, test_dir, name):
        with open(os.path.join(test_dir, name), "r", encoding="utf-8",
                  errors="replace") as handle:
            return handle.read()

    def _probe_silent_exits(self, snek_bin, test_dir, name, show_value=False):
        """Instrument a COPY of a silent-failing test so bare exit(1)
        announces itself on the same line (via ';', no line shifts).
        For pass-for-range.py the disputed product value is printed
        instead of a line tag.
        """
        try:
            text = self._read_upstream_test(test_dir, name)
            lines = text.split("\n")
            made = 0
            for idx, line in enumerate(lines):
                if line.strip() != "exit(1)":
                    continue
                indent = line[:len(line) - len(line.lstrip())]
                if show_value:
                    lines[idx] = "%sprint(product); exit(1)" % indent
                else:
                    lines[idx] = ("%sprint(\"HMBS diag probe %s line-%d\"); exit(1)"
                                  % (indent, name, idx + 1))
                made += 1
            if not made:
                return ""
            return self._run_probe(snek_bin, "\n".join(lines),
                                   "silent-" + name[:-3])
        except Exception as exc:
            self.output.info("HMBS diag probe %s silent skipped: %s" % (name, exc))
            return ""

    def _probe_variants(self, snek_bin, test_dir, failures):
        """Cycle-5 value-level probes: comparison-outcome evidence.

        Cycle-4 printed only last output lines / raw values, which cannot
        distinguish 'value corrupted' from 'comparison broken' (e.g.
        for-range prints 362880 yet `!= 362880` still true). These probes
        print COMPARISON outcomes and diffs (==, !=, minus, </>) plus
        lengths for strings, so the next preflight returns decisive
        value-vs-comparison evidence in single lines. Official counts,
        markers, and upstream files are untouched. Nothing here may
        raise.
        """
        notes = []
        try:
            failing = set(row["file"] for row in failures)

            def emit_note(summary):
                if summary:
                    notes.append(summary)

            # for-range: value AND comparison outcomes (distinguish
            # corrupted product from broken !=).
            if "pass-for-range.py" in failing:
                emit_note(self._run_probe(
                    snek_bin,
                    "product = 1\n"
                    "for i in range(1, 10, 1):\n"
                    "    product *= i\n"
                    "print(product)\n"
                    "print(product == 362880)\n"
                    "print(product != 362880)\n"
                    "print(product - 362880)\n",
                    "forrange-cmp"))
            # op is silent: keep line announcer for the pow block.
            for row in failures:
                name = row["file"]
                if (row.get("output") or "").strip():
                    continue
                if name == "pass-op.py":
                    emit_note(self._probe_silent_exits(snek_bin, test_dir, name))
            # op: pow value + comparison + diff.
            if "pass-op.py" in failing:
                emit_note(self._run_probe(
                    snek_bin,
                    "print((2**3) ** 4)\n"
                    "print(((2**3) ** 4) == 4096)\n"
                    "print(((2**3) ** 4) - 4096)\n",
                    "pow-cmp"))

            # math: value + comparison + diff (not just value).
            if "pass-math.py" in failing:
                emit_note(self._run_probe(
                    snek_bin,
                    "from math import *\n"
                    "print(factorial(9))\n"
                    "print(factorial(9) == 362880)\n"
                    "print(factorial(9) - 362880)\n",
                    "factorial-cmp"))

            # random: singleton + reversed tuple variants (value vs place).
            if "pass-random.py" in failing:
                try:
                    text = self._read_upstream_test(test_dir, "pass-random.py")
                    anchor = "for r in (2, 163844, 100000, 8388607):"
                    if anchor in text:
                        for tag, tup in (
                                ("rr-2", "(2,)"),
                                ("rr-163844", "(163844,)"),
                                ("rr-100000", "(100000,)"),
                                ("rr-8388607", "(8388607,)"),
                                ("rr-rev", "(8388607, 100000, 163844, 2)")):
                            emit_note(self._run_probe(
                                snek_bin, text.replace(anchor, "for r in %s:" % tup, 1),
                                tag))
                    else:
                        self.output.info("HMBS diag probe random anchor missing, skip")
                except Exception as exc:
                    self.output.info("HMBS diag probe random skipped: %s" % exc)

            # args: positional (control) vs named (mechanism) in one script.
            if "pass-args.py" in failing:
                emit_note(self._run_probe(
                    snek_bin,
                    "def req(x):\n    return x\n"
                    "print(req(2))\n"
                    "print(req(x=2))\n",
                    "named-posneg"))

            # interpolate: lengths + small-repeat variant (size dependence).
            if "pass-interpolate-str.py" in failing:
                emit_note(self._run_probe(
                    snek_bin,
                    'print(len("x" * 300))\n'
                    'print(len("%d" + "x" * 300 + "%d"))\n'
                    'print(("%d" + "x" * 300 + "%d") % (12, 34))\n',
                    "interp-len"))
                try:
                    text = self._read_upstream_test(test_dir, "pass-interpolate-str.py")
                    small_rhs = '"12' + 'x' * 30 + '34"'
                    vtext = text.replace('"x" * 300', '"x" * 30')
                    old_rhs = ') == "12xxxxxxxxxx" + "xx" * 140 + "xxxxxxxxxx34"'
                    if '"x" * 30' in vtext and old_rhs in vtext:
                        vtext = vtext.replace(old_rhs, ') == %s' % small_rhs, 1)
                        emit_note(self._run_probe(snek_bin, vtext, "interp-small"))
                    else:
                        self.output.info("HMBS diag probe interp anchors missing, skip")
                except Exception as exc:
                    self.output.info("HMBS diag probe interp skipped: %s" % exc)
        except Exception as exc:
            self.output.info("HMBS diag probe harness skipped: %s" % exc)
        appendix = "; ".join(note for note in notes if note)
        return appendix[:1200]

    def build(self):
        apply_conandata_patches(self)

        # snek.defs lists `-fstrict-flex-arrays=0` plus `--strict-flex-arrays=3`.
        # The double-dash form is a GCC alias that clang-15 rejects:
        # "unsupported option '--strict-flex-arrays=3'; did you mean
        # '-fstrict-flex-arrays=3'?", failing the posix build under -Werror.
        # The remaining `-fstrict-flex-arrays=0` is accepted by clang-15, and
        # the double-dash entry is warning-only, so drop exactly that line.
        defs_path = os.path.join(self.source_folder, "snek.defs")
        with open(defs_path, "r", encoding="utf-8", errors="replace") as handle:
            defs_text = handle.read()
        stripped, count = re.subn(
            r"^[ \t]*--strict-flex-arrays[^\n]*\n", "", defs_text,
            count=1, flags=re.MULTILINE)
        if count != 1:
            raise ConanException(
                "expected exactly one --strict-flex-arrays line in snek.defs, found %d"
                % count)
        if stripped != defs_text:
            with open(defs_path, "w", encoding="utf-8") as handle:
                handle.write(stripped)
            self.output.info("HMBS diag stripped --strict-flex-arrays from snek.defs")

        # snek-poly.c uses isnanf(), a glibc extension absent from the OHOS
        # libc math.h (clang: "call to undeclared function 'isnanf'"
        # under -Werror). isnan() is ISO C99 type-generic and handles float
        # identically, so use it portably instead of an ifdef ladder.
        poly_path = os.path.join(self.source_folder, "snek-poly.c")
        with open(poly_path, "r", encoding="utf-8", errors="replace") as handle:
            poly_text = handle.read()
        if "isnanf(" not in poly_text:
            raise ConanException(
                "expected isnanf( in snek-poly.c, anchor missing")
        poly_fixed = poly_text.replace("isnanf(", "isnan(")
        with open(poly_path, "w", encoding="utf-8") as handle:
            handle.write(poly_fixed)
        self.output.info("HMBS diag replaced isnanf with isnan in snek-poly.c")

        # snek-math.c has the same glibc-only spellings in its math table:
        # m1(math_isinf, isinff) on non-Windows/Apple plus
        # m1(math_isnan, isnanf) — here the names appear as macro
        # arguments WITHOUT a trailing paren, unlike the isnanf(f) call
        # in snek-poly.c. Upstream itself uses the generic isinf macro
        # on Windows/Apple and the generic isfinite macro everywhere
        # (m1(math_isfinite, isfinite)), so map both to their C99 generics.
        math_path = os.path.join(self.source_folder, "snek-math.c")
        with open(math_path, "r", encoding="utf-8", errors="replace") as handle:
            math_text = handle.read()
        if "isnanf" not in math_text or "isinff" not in math_text:
            raise ConanException(
                "expected isnanf/isinff anchors in snek-math.c, missing")
        math_fixed, n1 = re.subn(r"\bisnanf\b", "isnan", math_text)
        math_fixed, n2 = re.subn(r"\bisinff\b", "isinf", math_fixed)
        if n1 < 1 or n2 < 1:
            raise ConanException(
                "snek-math.c replacement count unexpected: isnanf=%d isinff=%d"
                % (n1, n2))
        with open(math_path, "w", encoding="utf-8") as handle:
            handle.write(math_fixed)
        self.output.info("HMBS diag replaced isnanf/isinff with isnan/isinf in snek-math.c")

        # snek-print.c uses strfromf()/strfromf_const() (ISO C23) to format
        # float values; the OHOS libc stdio.h does not declare them, so clang
        # under -Werror fails with "call to undeclared function 'strfromf'".
        # snprintf with a (double) cast is equivalent here: every binary32
        # value is exactly representable as binary64, so %e/%f/%g/%.9g render
        # identically. Replace both call sites portably.
        print_path = os.path.join(self.source_folder, "snek-print.c")
        with open(print_path, "r", encoding="utf-8", errors="replace") as handle:
            print_text = handle.read()
        if "strfromf(tmp," not in print_text or "strfromf_const(tmp," not in print_text:
            raise ConanException(
                "expected strfromf/strfromf_const anchors in snek-print.c, missing")
        print_fixed = print_text.replace(
            "strfromf(tmp, sizeof(tmp), format_string, snek_poly_to_float(a))",
            "snprintf(tmp, sizeof(tmp), format_string, (double) snek_poly_to_float(a))")
        print_fixed = print_fixed.replace(
            'strfromf_const(tmp, sizeof(tmp), "%.9g", snek_poly_to_float(a))',
            'snprintf(tmp, sizeof(tmp), "%.9g", (double) snek_poly_to_float(a))')
        if re.search(r"\bstrfromf(_const)?\s*\(", print_fixed):
            raise ConanException(
                "snek-print.c still references strfromf after replacement")
        with open(print_path, "w", encoding="utf-8") as handle:
            handle.write(print_fixed)
        self.output.info("HMBS diag replaced strfromf with snprintf in snek-print.c")

        # snek.h defaults strfromf_const to strfromf (ISO C23); upstream
        # explicitly guards it with #ifndef so packagers may override it.
        # Point only that documented macro at a snprintf fallback. Do NOT
        # define a bare strfromf macro: upstream provides no #ifndef guard
        # for it and a function-like macro could shadow a real libc symbol
        # on toolchains where it exists. snek-print.c no longer references
        # either symbol after the replacement above.
        header_path = os.path.join(self.source_folder, "snek.h")
        with open(header_path, "r", encoding="utf-8", errors="replace") as handle:
            header_text = handle.read()
        header_block = "#ifndef strfromf_const\n#define strfromf_const strfromf\n#endif"
        header_want = ("#ifndef strfromf_const\n"
                       "#define strfromf_const(dst, n, fmt, f)"
                       " (snprintf((dst), (n), (fmt), (double) (f)))\n"
                       "#endif")
        if header_block in header_text:
            header_fixed = header_text.replace(header_block, header_want, 1)
            with open(header_path, "w", encoding="utf-8") as handle:
                handle.write(header_fixed)
            self.output.info("HMBS diag added snprintf fallback for strfromf_const in snek.h")
        elif header_want in header_text and "strfromf(" not in header_text.replace(
                "strfromf_const(dst, n, fmt, f)", ""):
            self.output.info("HMBS diag snek.h strfromf_const fallback already applied, skip")
        else:
            raise ConanException(
                "expected strfromf_const default in snek.h, anchor missing")

        # snek_error_arg()/snek_undefined() pass snek_name_string() straight
        # to a "%s" format. snek_name_string() returns NULL when the id is
        # unknown (trailing return NULL), and puts_clean() dereferences it
        # unconditionally. Preflight evidence: the three fail-arg-* cases print
        # `bad arg "` and then die with SIGSEGV (rc -11) instead of the expected
        # clean exit(1). The duplicate/unknown detection itself works; only the
        # reporting crashes. Guard the reporting so an unresolvable id still
        # errors loudly with exit 1 instead of segfaulting. Detection logic is
        # untouched, and the guard is dormant whenever lookup succeeds, so the
        # 42 passing tests cannot be affected.
        err_path = os.path.join(self.source_folder, "snek-error.c")
        with open(err_path, "r", encoding="utf-8", errors="replace") as handle:
            err_text = handle.read()
        err_pristine = 'snek_error_arg(snek_id_t bad)\n{\n\treturn snek_error("bad arg \\"%s\\"", snek_name_string(bad));\n}'
        err_guarded = 'snek_error_arg(snek_id_t bad)\n{\n\tconst char *name = snek_name_string(bad);\n\tif (!name)\n\t\treturn snek_error("bad arg id %d", (int) bad);\n\treturn snek_error("bad arg \\"%s\\"", name);\n}'
        if err_pristine in err_text:
            with open(err_path, "w", encoding="utf-8") as handle:
                handle.write(err_text.replace(err_pristine, err_guarded, 1))
            self.output.info("HMBS diag guarded snek_error_arg against NULL name")
        elif err_guarded in err_text:
            self.output.info("HMBS diag snek_error_arg guard already applied, skip")
        else:
            raise ConanException(
                "expected snek_error_arg anchor in snek-error.c, missing")

        # snek-code.c omits snek_op_dict from snek_op_operand_size (returns 0
        # instead of sizeof(offset)). Code walkers (patch_forward, GC
        # mark/move, dump) then mis-traverse any bytecode containing a dict
        # literal. pass-interpolate-str.py ends with a dict literal
        # (`{1: 'hello', 2: 'world'}`), so keep the walker exact. Mirrors the
        # list/tuple arms with the same SNEK_NO_DICT guard upstream uses for
        # the opcode itself.
        code_path = os.path.join(self.source_folder, "snek-code.c")
        with open(code_path, "r", encoding="utf-8", errors="replace") as handle:
            code_text = handle.read()
        dict_pristine = ("\tcase snek_op_string:\n"
                         "\tcase snek_op_list:\n"
                         "\tcase snek_op_tuple:\n"
                         "\t\treturn sizeof (snek_offset_t);")
        dict_guarded = ("\tcase snek_op_string:\n"
                        "\tcase snek_op_list:\n"
                        "\tcase snek_op_tuple:\n"
                        "#ifndef SNEK_NO_DICT\n"
                        "\tcase snek_op_dict:\n"
                        "#endif\n"
                        "\t\treturn sizeof (snek_offset_t);")
        if dict_pristine in code_text:
            with open(code_path, "w", encoding="utf-8") as handle:
                handle.write(code_text.replace(dict_pristine, dict_guarded, 1))
            self.output.info("HMBS diag added snek_op_dict to operand_size in snek-code.c")
        elif dict_guarded in code_text:
            self.output.info("HMBS diag snek_op_dict operand_size already applied, skip")
        else:
            raise ConanException(
                "expected snek_op_string/list/tuple anchor in snek-code.c, missing")

        # snek_code_add_number() casts any float to int8_t BEFORE range
        # checking: `int8_t i8 = (int8_t) number` is UB for out-of-range
        # values (all literals >127 / <-128, e.g. 362880, 4096, 300,
        # 100000). Under clang -O3 on aarch64 the UB lets the optimizer
        # assume the value fits, mis-encoding large literals (small
        # literals like 30 stay correct -- exactly the observed
        # size-dependence: interp-small passes, interp-300 fails). Range
        # check in float domain first; dormant for in-range numbers.
        if "snek_code_add_number" not in code_text:
            raise ConanException("expected snek_code_add_number in snek-code.c, missing")
        with open(code_path, "r", encoding="utf-8", errors="replace") as handle:
            code_text2 = handle.read()
        num_pristine = ("void\n"
                        "snek_code_add_number(float number)\n"
                        "{\n"
                        "\tint8_t i8 = (int8_t) number;\n"
                        "\tif ((float) i8 == number) {")
        num_guarded = ("void\n"
                       "snek_code_add_number(float number)\n"
                       "{\n"
                       "\tif (number >= -128.0f && number <= 127.0f) {\n"
                       "\t\tint8_t i8 = (int8_t) number;\n"
                       "\t\tif ((float) i8 == number) {")
        if num_pristine in code_text2:
            # close the extra brace opened above: the original
            # `} else {` becomes `} } else {`? No -- restructure: wrap the
            # int-path in the range check, fall through to float path.
            # Original body:
            #   int8_t i8=...; if (...) { int-path } else { float-path }
            # New body:
            #   if (in-range) { int8_t i8=...; if (...) { int-path; return; } }
            #   float-path
            # So also patch the else to close correctly.
            patched = code_text2.replace(num_pristine, num_guarded, 1)
            else_anchor = ("\t\tsnek_code_add_op_uint8(snek_op_int, (uint8_t) i8);\n"
                           "\t} else {")
            else_want = ("\t\tsnek_code_add_op_uint8(snek_op_int, (uint8_t) i8);\n"
                         "\t\t\treturn;\n"
                         "\t\t}\n"
                         "\t}\n"
                         "\t{")
            if else_anchor not in patched:
                raise ConanException(
                    "expected snek_code_add_number else anchor in snek-code.c, missing")
            patched = patched.replace(else_anchor, else_want, 1)
            with open(code_path, "w", encoding="utf-8") as handle:
                handle.write(patched)
            self.output.info("HMBS diag range-guarded snek_code_add_number in snek-code.c")
        elif num_guarded in code_text2:
            self.output.info("HMBS diag snek_code_add_number guard already applied, skip")
        else:
            raise ConanException(
                "expected snek_code_add_number anchor in snek-code.c, missing")

        exec_path = os.path.join(self.source_folder, "snek-exec.c")
        with open(exec_path, "r", encoding="utf-8", errors="replace") as handle:
            exec_text = handle.read()
        undef_pristine = 'snek_undefined(snek_id_t id)\n{\n\tsnek_error("undefined: %s", snek_name_string(id));\n}'
        undef_guarded = 'snek_undefined(snek_id_t id)\n{\n\tconst char *name = snek_name_string(id);\n\tif (!name)\n\t\tsnek_error("undefined id %d", (int) id);\n\telse\n\t\tsnek_error("undefined: %s", name);\n}'
        if undef_pristine in exec_text:
            with open(exec_path, "w", encoding="utf-8") as handle:
                handle.write(exec_text.replace(undef_pristine, undef_guarded, 1))
            self.output.info("HMBS diag guarded snek_undefined against NULL name")
        elif undef_guarded in exec_text:
            self.output.info("HMBS diag snek_undefined guard already applied, skip")
        else:
            raise ConanException(
                "expected snek_undefined anchor in snek-exec.c, missing")

        posix_dir = os.path.join(self.source_folder, "ports", "posix")
        gram = os.path.join(posix_dir, "snek-gram.h")
        if not os.path.isfile(gram) or os.path.getsize(gram) == 0:
            raise ConanException(
                "ports/posix/snek-gram.h missing after patches; "
                "the lola pre-generation patch did not apply")
        test_dir = os.path.join(self.source_folder, "test")
        if not os.path.isdir(test_dir):
            raise ConanException("upstream test/ directory missing")

        # `snek-builtin.h` is generated by the in-source script with plain
        # `python3`; make sure the HMBS python resolves on PATH first.
        python3 = self._python3()
        bindir = os.path.dirname(python3)
        if bindir and os.path.isdir(bindir):
            os.environ["PATH"] = bindir + os.pathsep + os.environ.get("PATH", "")
            self.output.info("HMBS diag python3=%s" % python3)

        cc = self._c_compiler()
        self.output.info("HMBS diag compiler c=%s" % cc)
        # R33: compiler comes from Conan conf, never from shell env vars.
        # STATIC=1 drops the readline dependency; LIBS=-lm overrides the
        # Makefile's `-static` default (static libc is unavailable on OHOS).
        # R9: always -j1. Target `snek` only: no firmware/desktop subdirs.
        self.run('make -j1 V=1 CC="%s" STATIC=1 LIBS="-lm" snek' % cc, cwd=posix_dir)

        snek_bin = os.path.join(posix_dir, "snek")
        if not os.path.isfile(snek_bin):
            raise ConanException("build produced no ports/posix/snek binary")
        self.run('"%s" --version' % snek_bin, cwd=posix_dir)

        summary = self._run_upstream_tests(snek_bin, test_dir)
        payload = {
            "status": "passed" if summary["failed"] == 0 else "failed",
            "framework": "make check (custom shell harness)",
            "command": "ports/posix/snek test/<each of 51 scripts> (35 pass expect rc 0, 16 fail expect rc 1)",
            "discovered": summary["discovered"],
            "executed": summary["executed"],
            "passed": summary["passed"],
            "failed": summary["failed"],
            "skipped": summary["skipped"],
        }
        self._emit_upstream(payload)
        probe_notes = ""
        if summary["failed"]:
            try:
                probe_notes = self._probe_variants(
                    snek_bin, test_dir, summary["failures"])
            except Exception as exc:
                self.output.info("HMBS diag probe phase skipped: %s" % exc)
        if summary["failed"]:
            message = "upstream suite failures: %s" % "; ".join(
                "%s(%s)" % (row["file"], row.get("detail") or
                            "rc %s, expect %d" % (row["code"], row["expected"]))
                for row in summary["failures"][:10])
            if probe_notes:
                message += "; probe: " + probe_notes
            raise ConanException(message)

    def package(self):
        copy(self, "snek", src=os.path.join(self.source_folder, "ports", "posix"),
             dst=os.path.join(self.package_folder, "bin"))
        copy(self, "COPYING", src=self.source_folder, dst=os.path.join(self.package_folder, "licenses"))
        src = os.path.join(self.build_folder, "hmbs_upstream.json")
        if os.path.isfile(src):
            dst_dir = os.path.join(self.package_folder, "res")
            os.makedirs(dst_dir, exist_ok=True)
            shutil.copyfile(src, os.path.join(dst_dir, "hmbs_upstream.json"))
        else:
            self.output.warning("HMBS diag hmbs_upstream.json missing in package()")

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
