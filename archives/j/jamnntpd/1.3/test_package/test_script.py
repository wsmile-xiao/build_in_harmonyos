#!/usr/bin/env python3
"""Loopback NNTP protocol consumer test for jamnntpd + makechs assertions.

Run by test_package/conanfile.py via self.run() inside the conanrun env
(PATH contains the package bin/). Args: [package_folder].
"""
import os
import shutil
import socket
import subprocess
import sys
import time


def find_binary(name, pkg_folder):
    direct = os.path.join(pkg_folder or "", "bin", name)
    if pkg_folder and os.path.isfile(direct):
        return direct
    found = shutil.which(name)
    assert found, f"{name} not found (pkg_folder={pkg_folder!r}, PATH checked)"
    return found


def ask(port, cmds, timeout=5):
    s = socket.create_connection(("127.0.0.1", port), timeout=timeout)
    try:
        f = s.makefile("rb")
        replies = [f.readline().decode("utf-8", "replace").strip()]
        for cmd in cmds:
            s.sendall((cmd + "\r\n").encode())
            replies.append(f.readline().decode("utf-8", "replace").strip())
        return replies
    finally:
        s.close()


def main():
    pkg = sys.argv[1] if len(sys.argv) > 1 else ""
    jamnntpd = find_binary("jamnntpd", pkg)
    makechs = find_binary("makechs", pkg)

    # charset tables ship under <package>/res/xlat next to bin/
    base = os.path.dirname(os.path.dirname(jamnntpd))
    chsdir = os.path.join(base, "res", "xlat")
    assert os.path.isdir(chsdir), f"missing chsdir: {chsdir}"

    run = os.path.join(os.environ.get("TMPDIR", "/tmp"), f"jamnntpd-test.{os.getpid()}")
    os.makedirs(run, exist_ok=True)
    allow = os.path.join(run, "allow")
    groups = os.path.join(run, "groups")
    xlat = os.path.join(run, "xlat")
    log = os.path.join(run, "server.log")
    with open(allow, "w") as fh:
        fh.write("*\n")
    with open(groups, "w") as fh:
        fh.write("PROBE.GROUP A 1:1/1 %s\n" % os.path.join(run, "nonexistent.jam"))
    with open(xlat, "w") as fh:
        fh.write(
            "chsdir %s\n"
            "defaultread IBMPC\n"
            "read CP437 iso-8859-1 437_iso.chs\n"
            "defaultpost iso-8859-1\n"
            "post iso-8859-1 IBMPC iso_437.chs\n" % chsdir
        )

    # Never assume 119 or the 5000 default is bindable without root:
    # reserve a free ephemeral loopback port.
    probe = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    probe.bind(("127.0.0.1", 0))
    port = probe.getsockname()[1]
    probe.close()

    server = subprocess.Popen(
        [jamnntpd, "-port", str(port), "-allow", allow, "-groups", groups,
         "-xlat", xlat, "-logfile", log],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        deadline = time.time() + 15
        greeting = ""
        while time.time() < deadline:
            if server.poll() is not None:
                tail = open(log, errors="replace").read()[-400:] if os.path.exists(log) else ""
                raise AssertionError(
                    f"jamnntpd exited early rc={server.returncode} log:{tail}")
            try:
                greeting = ask(port, [])[0]
                if greeting:
                    break
            except OSError:
                time.sleep(0.25)
        assert greeting.startswith("200 Welcome to JamNNTPd"), \
            f"bad greeting: {greeting!r}"

        r = ask(port, ["NOSUCHCOMMAND"])[1]
        assert r.startswith("500 "), f"unknown-command reply: {r!r}"
        r = ask(port, ["GROUP NO.SUCH.GROUP"])[1]
        assert r.startswith("411 "), f"missing-group reply: {r!r}"
        r = ask(port, ["POST"])[1]
        assert r.startswith("340 "), f"POST reply: {r!r}"
        r = ask(port, ["QUIT"])[1]
        assert r.startswith("205 "), f"QUIT reply: {r!r}"
        print("jamnntpd loopback NNTP consumer tests passed: "
              "greeting 200 + 500 + 411 + 340 + 205")
    finally:
        if server.poll() is None:
            server.terminate()
        try:
            server.wait(timeout=10)
        except subprocess.TimeoutExpired:
            server.kill()

    # makechs consumer test: generate a real charset table and assert it.
    mapfile = os.path.join(run, "probe.map")
    with open(mapfile, "w") as fh:
        fh.write("0x41 0x62\n0x42 0x63 # shift one\n")
    out = os.path.join(run, "probe.chs")
    with open(out, "wb") as fh:
        rc = subprocess.call([makechs, "PROBEA", "PROBEB", mapfile], stdout=fh)
    assert rc == 0, f"makechs exited {rc}"
    with open(out, "r", errors="replace") as fh:
        data = fh.read()
    assert "Generated by makechs" in data, "makechs output lacks header"
    assert "PROBEA" in data and "PROBEB" in data, "makechs output lacks charset names"
    assert any(line.endswith("\tb") for line in data.splitlines()), \
        "makechs output lacks the 0x41->0x62 mapping entry"
    print("makechs generated-table consumer test passed")


if __name__ == "__main__":
    main()
