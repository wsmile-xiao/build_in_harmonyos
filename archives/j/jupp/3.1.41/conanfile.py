import glob
import os

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
)
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class JuppConan(ConanFile):
    name = "jupp"
    version = "3.1.41"
    description = ("jupiler, an improved version of the Joe word processor "
                   "(terminal text editor)")
    license = "GPL-1.0-only"
    homepage = "http://t2.io/sware/jupp"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    topics = ("editor", "terminal", "autotools", "cli")
    package_type = "application"
    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.configure_args = [a for a in tc.configure_args
                             if not a.startswith(("--host=", "--build=", "--prefix="))]
        # 三元组按 settings.arch 映射成 **autoconf 规范 CPU 名**（不是 conan 的 arch 字面值）：
        # conan 的 armv8 直接拼进三元组会被 config.sub 原样回显成 `armv8-unknown-linux-gnu`
        # —— 本轮实测到该现象（能编过，但非规范名，上游任何 `case $host in aarch64*)` 式分支
        # 都会漏），故必须显式映射 armv8 → aarch64。
        # 两侧同写 -linux-gnu 是**偏离**检查清单 §12.1 常规写法（ledmon 等用 -linux-ohos）
        # 的实测决定：本包 config.sub(2019) 逐字拒绝 -ohos（`Invalid configuration ...
        # machine 'aarch64-unknown-linux' not recognized`），且传 --build 同时绕开
        # config.guess 往 $HOME 根写 cgXXXX*/dummy.c 的不可写失败。
        cpu = {"armv8": "aarch64", "armv7": "arm",
               "x86_64": "x86_64"}.get(str(self.settings.arch))
        if cpu is None:
            raise ConanException("jupp: 未把 settings.arch=%s 映射到 autoconf CPU 名"
                                 % self.settings.arch)
        tc.configure_args.append("--build=%s-unknown-linux-gnu" % cpu)
        tc.configure_args.append("--host=%s-unknown-linux-gnu" % cpu)
        # ★jupp 的关键适配点（真机实测根因）：上游 `Makefile.in:270` 把数据目录**编进二进制**
        #   `INCLUDES = -DJOERC="\"$(sysconf_joedir)/\""`，而 `sysconf_joedir =
        #   $(sysconfdir)$(sysconfjoesubdir)`、真机 configure 代入值为 `sysconfjoesubdir = /joe`、
        #   `sysconfdir = ${prefix}/etc`。conan 默认
        #   `--prefix=/` ⇒ 编译期常量被烤成 `//etc/joe/`（本轮 `strings bin/joe` 实测到逐字
        #   `//etc/joe/`），而 `make install DESTDIR=<包>` 只把文件装进包里 ⇒ 消费者一跑就
        #   `Couldn't open '*joerc'` 并以 rc=1 退出（`--version` 都过不去）。
        #   `path.c:408 init_JOERC()` 的 argv[0] 兜底在 `#ifdef __cygwin32__` 里 ⇒ POSIX/OHOS
        #   **没有运行期搜索路径**，只能让 prefix 指到包目录本身，使编进去的常量与安装位置
        #   一致（同仓先例：`archives/c/cdebconf-entropy/0.6` 用 `@prefix@=package_folder` +
        #   `@sysconfdir@=${prefix}/etc`）。配套要求见 package() 里的 `DESTDIR=`（否则
        #   staging 会让落点比常量多一层）。代价：包内常量绑定构建期包目录，不可整体搬迁；
        #   对 application 型工具这是上游设计使然，非本配方可选。
        tc.configure_args.append("--prefix=" + self.package_folder.replace(os.sep, "/"))
        tc.generate()

    def _relax_umask(self, path):
        """E011：HMDFS 下 config.status 的 umask 077 临时目录不可写。"""
        try:
            with open(path, encoding="utf-8", errors="ignore") as handle:
                text = handle.read()
        except OSError:
            return
        if "umask 077" in text:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(text.replace("umask 077", "umask 022"))

    def build(self):
        apply_conandata_patches(self)
        cfg = os.path.join(self.source_folder, "configure")
        if os.path.isfile(cfg):
            self._relax_umask(cfg)
            # HMDFS 解包件常是 660（无执行位，E543 同族）；chmod 失败不致命，
            # Autotools.configure 走 `$SHELL ./configure`，真跑不起来时下面有兜底。
            try:
                os.chmod(cfg, 0o755)
            except OSError:
                pass
        regen_off = ["ACLOCAL=:", "AUTOMAKE=:", "AUTOCONF=:", "AUTOHEADER=:"]
        autotools = Autotools(self)
        autotools.configure(build_script_folder=self.source_folder)
        autotools.make(args=regen_off)
        # 上游无自动化测试入口（N_static=0，实测 Makefile.am 只有 noinst_HEADERS）⇒
        # 这里没有 `make check` 可跑；真实测试在 test_package（消费者测试），
        # 不在正文里声称跑过上游套件。

    def package(self):
        autotools = Autotools(self)
        # `DESTDIR=` 是必需的（不是笔误）：Autotools 构造的命令形如
        #   make install DESTDIR=<package_folder> <args...>
        # （conan/tools/gnu/autotools.py:87 `str_args` 在前、`args` 在后），而 GNU make
        # 规则是**同名变量后者胜出** ⇒ 传一个空的 DESTDIR= 就能把框架注入的 staging 前缀
        # 压掉，让文件按 `--prefix=<package_folder>` 直接落在包根。
        # 为什么必须压掉：上游把运行期数据目录**编进二进制**
        #   （Makefile.in:270 `INCLUDES = -DJOERC="\"$(sysconf_joedir)/\""`，
        #     sysconf_joedir = $(sysconfdir)$(sysconfjoesubdir)，实测代入 sysconfjoesubdir=/joe、
        #     sysconfdir=${prefix}/etc ⇒ prefix=/ 时得 //etc/joe），
        #   且 `rc.c:954 procrc()` 只是 jfopen(路径)、main.c 里 `*` 前缀并非"内建资源"机制，
        #   `path.c:408 init_JOERC()` 的 argv[0] 兜底整段在 `#ifdef __cygwin32__` 内
        #   ⇒ OHOS/POSIX **没有运行期搜索路径**。若保留 DESTDIR staging，安装落点会比
        #   编进去的常量多一层包目录（实测产物路径 <包>/<包>/bin/joe），消费者必然
        #   `Couldn't open '*joerc'` rc=1（连 `--version` 都过不去）。压掉后二者天然一致。
        autotools.install(args=["DESTDIR="] + ["ACLOCAL=:", "AUTOMAKE=:",
                                               "AUTOCONF=:", "AUTOHEADER=:"])
        for junk in glob.glob(os.path.join(self.package_folder, "lib", "**", "*.la"),
                              recursive=True):
            os.remove(junk)
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))
        # 交付的 CLI 必须自签（E077 顺序：先 objcopy 删掉链接期 4096B 占位 .codesign，
        # 再 binary-sign-tool selfSign；调用时剔除 LD_LIBRARY_PATH 否则签名器自身重定位失败）。
        self._sign_binaries()

    def _find_tool(self, name):
        for base in (os.path.expanduser("~/usr/local/bin"),
                     os.path.expanduser("~/.harmonybrew/bin"),
                     "/data/service/hnp/bin"):
            cand = os.path.join(base, name)
            if os.path.isfile(cand):
                return cand
        for path in os.environ.get("PATH", "").split(os.pathsep):
            cand = os.path.join(path or ".", name)
            if os.path.isfile(cand):
                return cand
        return None

    def _sign_binaries(self):
        signer = self._find_tool("binary-sign-tool")
        objcopy = self._find_tool("llvm-objcopy")
        bindir = os.path.join(self.package_folder, "bin")
        if not os.path.isdir(bindir):
            return
        if not signer:
            # 与同仓 ledmon/inhomog 一致的保护分支：非 OHOS 或工具缺失时不假装签过。
            self.output.warning("binary-sign-tool 不可用 ⇒ 跳过自签（不谎报已签）")
            return
        for name in sorted(os.listdir(bindir)):
            path = os.path.join(bindir, name)
            if os.path.islink(path) or not os.path.isfile(path):
                continue          # 别名都是符号链接，只签真身
            with open(path, "rb") as handle:
                if handle.read(4) != b"\x7fELF":
                    continue
            if objcopy:
                self.run('env -u LD_LIBRARY_PATH "{}" --remove-section .codesign "{}"'
                         ' 2>/dev/null || true'.format(objcopy, path))
            self.run('env -u LD_LIBRARY_PATH "{}" sign -inFile "{}" -outFile "{}"'
                     ' -selfSign 1'.format(signer, path, path))
            self.output.info(f"self-signed {name}")

    def package_info(self):
        # 上游 AC_INIT 名为 joe ⇒ 真 ELF 是 bin/joe，bin/{jupp,jmacs,jpico,jstar,rjoe}
        # 是指向它的符号链接（按 argv[0] 切模式），另有独立 ELF bin/termidx。
        self.cpp_info.bindirs = ["bin"]
        # application 型：包内只有 bin/etc/share/licenses（实测 34 个文件、无 include/、无 lib/）
        # ⇒ 显式清空，避免默认 cpp_info 暴露不存在的目录（同仓 ledmon/vramsteg 等一致写法）。
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.resdirs = []
