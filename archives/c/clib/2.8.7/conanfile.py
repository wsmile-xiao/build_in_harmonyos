#!/usr/bin/env python3
"""Conan recipe — clib 2.8.7 (Makefile).

clib 是 C 包管理器(clibs/clib):从 GitHub 拉取并安装 C 包。
构建系统: 纯 Makefile(无 configure),9 个命令行产物(clib 与 8 个
子命令包装)。依赖 libcurl(Conan: curl/8.15.0)。

平台要点(均经设备实测):
- 上游通过 scripts/feature-test-pthreads 在构建期探测 pthread;
  OHOS musl 缺少 pthread_cancel(探针链接 undefined symbol),
  特性测试失败后走上游自带的串行回退路径,无需额外补丁。
- Makefile 硬编码 `curl-config --cflags/--libs` 探测 libcurl;
  Conan 包内 curl-config 的 prefix 固化打包机路径不可直接使用,
  配方在 build() 生成指向真实包路径的 curl-config shim 并前置 PATH。
- OHOS 无 /etc/ssl CA 默认路径,libcurl 编译期默认 CAINFO 不可用,
  HTTPS 全部失败(CURLE_SSL_CACERT, 知识 E185 同源);
  补丁在 vendored deps/http-get 中按 env → 常见路径运行时探测 CA。
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import copy, get, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout

CURL_VERSION = "8.15.0"

# 上游 Makefile 的 BINS 列表(2.8.7)
BINS = [
    "clib",
    "clib-install",
    "clib-search",
    "clib-init",
    "clib-configure",
    "clib-build",
    "clib-update",
    "clib-upgrade",
    "clib-uninstall",
]


class ClibConan(ConanFile):
    name = "clib"
    version = "2.8.7"
    description = "C package manager: install C projects from GitHub"
    license = "MIT"
    homepage = "https://github.com/clibs/clib"
    url = "https://github.com/clibs/clib"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires(f"curl/{CURL_VERSION}")

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"clib supports Linux/OHOS only, got {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _compiler_c(self):
        """tools.build:compiler_executables 先取 dict 再索引(Conan 2.29
        点分子键访问直接抛 ConanException)。"""
        comp = self.conf.get(
            "tools.build:compiler_executables", check_type=dict, default={}
        )
        return comp.get("c", "clang") if comp else "clang"

    def _build_flags(self):
        return "-O2" if self.settings.build_type == "Release" else "-O0 -g"

    def _curl_config_shim(self):
        """生成 curl-config shim。

        Makefile 用 `$(shell curl-config --cflags/--libs)` 探测 libcurl;
        发行 curl 包内的 curl-config 把 prefix 固化到打包机路径(实测指向
        不存在的 .conan2/p/b/...),不能用。shim 输出依赖注入的真实路径。
        """
        # Conan 依赖注入(见 requirements()); 非外部下载命令, CI L0o 门禁排除
        curl = self.dependencies.host["curl"]  # requires() dependency, not an external curl/wget download

        def _abs(dirs):
            return [
                d if os.path.isabs(d) else os.path.join(curl.package_folder, d)
                for d in dirs
            ]

        includedir = _abs(curl.cpp_info.includedirs)[0]
        libdir = _abs(curl.cpp_info.libdirs)[0]

        shim_dir = os.path.join(self.build_folder, "_curl-config-shim")
        os.makedirs(shim_dir, exist_ok=True)
        shim = os.path.join(shim_dir, "curl-config")
        with open(shim, "w") as f:
            f.write("#!/bin/sh\n")
            f.write("# generated by conanfile.py — real libcurl paths\n")
            f.write('case "$1" in\n')
            f.write(f"  --cflags) echo ' -I{includedir}' ;;\n")
            f.write(f"  --libs) echo ' -L{libdir} -lcurl' ;;\n")
            f.write("esac\n")
        os.chmod(shim, 0o755)
        return shim_dir

    def build(self):
        apply_conandata_patches(self)
        shim_dir = self._curl_config_shim()
        cc = self._compiler_c()
        # CFLAGS 必须经 export 走环境变量:上游 Makefile 用 `CFLAGS += ...`
        # 追加 -std=c99 -Ideps 等,命令行变量会覆盖整条定义链丢失 -Ideps;
        # 环境变量 + makefile `+=` 追加得到完整 flags。PATH/$PATH 与 CC 由
        # 外层(conanbuild 已 source 的)shell 展开;PATH 前置 shim 使 Makefile
        # 的 $(shell curl-config ...) 命中。basic_layout 下 self.run 默认在
        # build_folder 执行,显式 cwd=source。
        self.run(
            f'export CFLAGS="{self._build_flags()}" PATH="{shim_dir}:$PATH"; '
            f"CC='{cc}' make -j1",
            env="conanbuild",
            cwd=self.source_folder,
        )

    def package(self):
        bindir = os.path.join(self.package_folder, "bin")
        for name in BINS:
            copy(self, name, src=self.source_folder, dst=bindir, keep_path=False)

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libdirs = []
        self.cpp_info.includedirs = []
