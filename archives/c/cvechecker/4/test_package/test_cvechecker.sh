#!/bin/sh
# test_cvechecker.sh — consumer functional test for the cvechecker 4 package.
#
#   sh test_cvechecker.sh <path-to-cvechecker-binary> <workdir>
#
# Runs the installed bin/cvechecker binary through 4 real invocations against a
# minimal sqlite-backed configuration and prints a machine-readable
# "RESULT: P passed, F failed" trailer line, which test_package/conanfile.py
# parses into HMBS_TEST_PACKAGE_RESULT.
#
# cvechecker initialises from a libconfig file (CVECHECKER_CONFFILE) before its
# argp CLI runs, so a minimal sqlite-backed configuration is written first.
# Case 4 is a negative control (an unknown option must be rejected by argp),
# proving the harness observes real failures instead of passing empty output.
#
# Upstream ships no test suite; this validates the packaged application.

set -u

BIN="$1"
WORKDIR="$2"

# Device HMFS /tmp may be read-only: prefer the HMBS-injected writable
# TMPDIR/TMP/TEMP, fall back to <workdir> (never a hardcoded /tmp).
_TMPBASE="${TMPDIR:-${TMP:-${TEMP:-.}}}"
mkdir -p "$_TMPBASE" 2>/dev/null || _TMPBASE="$WORKDIR"
mkdir -p "$WORKDIR" 2>/dev/null || true
OUT="$_TMPBASE/cvechecker-test-out.txt"
PASS=0
FAIL=0

report() {
    # $1 = case number, $2 = ok (0/1), $3 = label
    if [ "$2" -eq 0 ]; then
        echo "CASE $1 PASS: $3"
        PASS=$((PASS + 1))
    else
        echo "CASE $1 FAIL: $3"
        FAIL=$((FAIL + 1))
    fi
}

dump_out() {
    # $1 = exit code; print bounded output excerpt for diagnosis.
    # (Exit code alone cannot distinguish a loader failure from an app error.)
    echo "  exit=$1, output excerpt (first 12 lines of $OUT):"
    sed -n '1,12p' "$OUT" 2>/dev/null || echo "  (no output file)"
}

# --- Write a minimal sqlite-backed configuration -------------------------
CONF="$WORKDIR/cvechecker.conf"
cat > "$CONF" <<EOF
# minimal cvechecker.conf generated by the conan test_package
dbtype = "sqlite";
cvecache = "$WORKDIR/cache";
datadir = "$WORKDIR/data";
stringcmd = "/usr/bin/strings -n 3 '@file@'";
sqlite3: {
  localdb = "$WORKDIR/local";
  globaldb = "$WORKDIR/global.db";
};
EOF
export CVECHECKER_CONFFILE="$CONF"

# --- Case 1: --help exits 0 (argp's standard help path) -------------------
"$BIN" --help > "$OUT" 2>&1
rc=$?
if [ "$rc" -eq 0 ]; then
    report 1 0 "--help exits 0"
else
    dump_out "$rc"
    report 1 1 "--help exited $rc"
fi

# --- Case 2: --help produces non-empty output -----------------------------
if [ -s "$OUT" ]; then
    report 2 0 "--help output is non-empty"
else
    dump_out "$rc"
    report 2 1 "--help produced empty output"
fi

# --- Case 3: --help output reaches argp usage text ------------------------
if grep -q "Usage" "$OUT"; then
    report 3 0 "--help reaches argp usage output"
else
    dump_out "$rc"
    report 3 1 "--help output lacks argp usage text"
fi

# --- Case 4 (negative control): unknown option must be rejected -----------
"$BIN" --definitely-not-a-real-cvechecker-option > "$OUT" 2>&1
rc=$?
if [ "$rc" -ne 0 ]; then
    report 4 0 "unknown option rejected by argp (exit=$rc)"
else
    dump_out "$rc"
    report 4 1 "unknown option unexpectedly accepted (exit=0)"
fi

echo "RESULT: $PASS passed, $FAIL failed"
[ "$FAIL" -eq 0 ]
