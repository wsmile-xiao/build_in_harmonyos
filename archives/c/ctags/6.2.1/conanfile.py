#!/usr/bin/env python3
"""Conan recipe — ctags 6.2.1 (Universal Ctags).

Autotools project. Official release tarball includes pre-generated configure.
Platform adaptation: HMDFS umask 077 fix for config.status.
"""
import os

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class CtagsConan(ConanFile):
    name = "ctags"
    version = "6.2.1"
    description = "Universal Ctags - a multilanguage code indexing tool"
    license = "MIT"
    homepage = "https://ctags.io/"
    url = ""  # CI fills this

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # No external Conan dependencies required
        # ctags optionally uses libxml2, jansson, libseccomp, yaml, libpcre2
        # but all are optional and not required for basic functionality
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # R26: Terminal tools must be statically linked
        tc.extra_ldflags.append("-static")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)

        # Platform fix: HMDFS creates files with owner != current user.
        # autoconf's config.status (generated by configure) uses umask 077
        # which strips group permissions, making temp files inaccessible.
        # Patch configure to use umask 007 (preserves group access).
        configure_path = os.path.join(self.source_folder, "configure")
        self.run(f"sed -i 's/umask 077/umask 007/g' {configure_path}")

        autotools = Autotools(self)
        autotools.configure()
        autotools.make()

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        # ctags is a terminal tool, no shared libraries provided
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
