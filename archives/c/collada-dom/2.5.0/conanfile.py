#!/usr/bin/env python3
"""Conan recipe — collada-dom 2.5.0 (CMake, COLLADA DOM library).

Dependencies (OHOS PC / arm64):
  - boost/1.90.0.1   shared variant (ships libboost_filesystem.so). The plain
                     boost/1.90.0 registry package is headers-only (no compiled
                     filesystem lib) and its operations.hpp only declares the
                     filesystem operations, so consumers using
                     boost::filesystem would be left with undefined symbols.
  - libxml2/2.15.3 required by upstream CMake (non-MSVC falls back to bundled
                   sources only for zlib/minizip/pcre; libxml2 has no fallback).

Patches (generated by refresh-patch, applied by apply_conandata_patches):
  - 0001 CMakeLists.txt: shared boost (Boost::filesystem) link + include wiring
  - 0002 dom/include/dae.h: drop removed <boost/filesystem/convenience.hpp>
  - 0003 dom/src/dae/daeUtils.cpp: convenience.hpp -> <boost/filesystem.hpp>
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class ColladaDomConan(ConanFile):
    name = "collada-dom"
    version = "2.5.0"
    package_type = "library"
    description = "COLLADA Document Object Model (DOM) C++ library 2.5.0"
    license = "MIT"
    homepage = "https://github.com/rdiankov/collada-dom"
    url = ""
    topics = ("collada", "3d", "dom", "dae")

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False]}
    default_options = {"shared": True}

    exports_sources = "patches/*"

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.shared

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("collada-dom supports Linux/OHOS only")
        if self.settings.os == "OHOS" and self.settings.arch != "armv8":
            raise ConanInvalidConfiguration("collada-dom OHOS build requires armv8")

    def requirements(self):
        # Shared boost/1.90.0.1 ships libboost_filesystem.so (required by the
        # collada-dom filesystem usage); libxml2 is a hard CMake dep.
        self.requires("boost/1.90.0.1")
        self.requires("libxml2/2.15.3")

    def layout(self):
        basic_layout(self)

    def export_sources(self):
        export_conandata_patches(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        CMakeDeps(self).generate()
        tc = CMakeToolchain(self)
        # E103: CMake 4.x removed support for cmake_minimum_required < 3.5;
        # collada-dom 2.5.0's top-level CMakeLists.txt uses `cmake_minimum_required(VERSION 2.x)`.
        tc.variables["CMAKE_POLICY_VERSION_MINIMUM"] = "3.5"
        tc.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        # Upstream options (see top-level CMakeLists.txt).
        tc.variables["OPT_COLLADA14"] = "ON"
        tc.variables["OPT_COLLADA15"] = "ON"
        tc.variables["OPT_COMPILE_VIEWER"] = "OFF"
        tc.variables["OPT_COMPILE_FX"] = "OFF"
        tc.variables["OPT_COMPILE_RT"] = "OFF"
        tc.variables["OPT_COMPILE_TESTS"] = "OFF"
        tc.variables["OPT_BUILD_PACKAGES"] = "OFF"
        tc.variables["OPT_BUILD_PACKAGE_DEFAULT"] = "OFF"
        # Shared boost: point the upstream find/include directly at the boost
        # package's headers; the shared variant also carries libboost_filesystem
        # which is linked through the CMakeDeps boost::filesystem target.
        boost = self.dependencies["boost"]
        tc.variables["Boost_INCLUDE_DIR"] = boost.cpp_info.includedirs[0]
        tc.variables["Boost_INCLUDE_DIRS"] = boost.cpp_info.includedirs[0]
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        # Library is built with OUTPUT_NAME collada-dom2.5-dp (SOVERSION 2.5,
        # precision "dp" since OPT_DOUBLE_PRECISION defaults ON). Headers are
        # installed under include/collada-dom2.5/ (COLLADA_DOM_INCLUDE_INSTALL_DIR),
        # which is what upstream consumers put on the include path.
        self.cpp_info.libs = ["collada-dom2.5-dp"]
        self.cpp_info.includedirs = ["include/collada-dom2.5"]
        self.cpp_info.set_property("cmake_file_name", "collada_dom")
        self.cpp_info.set_property("cmake_target_name", "collada_dom")
        self.cpp_info.set_property("pkg_config_name", "collada-dom")
        # Public headers reference boost; libxml2 headers are pulled in by the
        # DOM include tree when DOM_INCLUDE_LIBXML is defined.
        self.cpp_info.requires = ["boost::boost", "libxml2::libxml2"]
