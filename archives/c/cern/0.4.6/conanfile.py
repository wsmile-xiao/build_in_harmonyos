#!/usr/bin/env python3
"""Conan recipe — cern 0.4.6 (direct compile, no CMake).

CERN VDT vectorised math library. Upstream builds via CMake, but CMake's
compiler detection (try_compile) fails on the HarmonyOS PC true machine
(compiler identification unknown under read-only /tmp), and CMake has no
HarmonyOS platform module (E092). The library itself is a single
translation unit, so compile it directly with the configured compiler,
replicating upstream CMakeLists semantics:

- src/vdtMath_signatures.cc generated by src/signatures_generator.py
  (PRELOAD=OFF, needs python3 from the machine)
- include/externalLibcfg.h generated with USE_VC=0 (USE_VC=OFF)
- flags (clang path, all SIMD OFF, DEBUG OFF): -O3 -std=c++11 -W -Wall
  -Werror -Wno-error=unused-parameter -D__extern_always_inline=inline
  plus -Winline for the library TU (VERBOSITY_OPT)
- headers installed to include/vdt, library libvdt.a (or .so)

All subprocesses run shell-free (list form, no /bin/sh -c) with the
HMBS writable TMPDIR forwarded, so nothing touches read-only /tmp.
"""

import glob
import hashlib
import json
import os
import shutil
import subprocess
import tarfile
import urllib.request

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.build import can_run
from conan.tools.files import copy
from conan.tools.layout import basic_layout

_UPSTREAM_TESTS = [
    "exp_test", "log_test", "sqrt_test", "sin_test", "cos_test",
    "inv_test", "tan_test", "tanh_test", "asin_test", "acos_test",
    "atan_test", "atan2_test",
]

_EXTERNAL_LIB_CFG = """/* Automatically generated for OHOS build (USE_VC=OFF). */

#ifndef _VDT_EXTERNAL_LIB_CFG_
#define _VDT_EXTERNAL_LIB_CFG_

//Vc usage setup
#define USE_VC 0
#if USE_VC
  //use this flag through the program
  #define _VC_AVAILABLE_
#endif

#endif
"""


class CernConan(ConanFile):
    name = "cern"
    version = "0.4.6"
    description = "CERN VDT vectorised math library, fast approximate transcendental functions"
    license = "LGPL-3.0-or-later"
    homepage = "https://github.com/dpiparo/vdt"
    url = "https://github.com/dpiparo/vdt"

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}
    exports_sources = "conandata.yml"

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "cern 0.4.6 is only supported on Linux/OHOS, got %s" % self.settings.os
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        # Pure-python download+extract (urllib + tarfile, no shell, no
        # external tar binary): the true machine's harmonybrew tar lacks
        # exec permission (sh: .../.harmonybrew/bin/tar: Operation not
        # permitted), so conan.tools.files.get() must not be used here.
        _tmp = (os.environ.get("TMPDIR") or os.environ.get("TMP")
                or os.environ.get("TEMP")
                or os.path.join(self.base_source_folder, "tmp"))
        try:
            os.makedirs(_tmp, exist_ok=True)
        except Exception:
            pass
        for _k in ("TMPDIR", "TMP", "TEMP"):
            os.environ[_k] = _tmp
        _src = self.conan_data["sources"]
        _raw_url = _src["url"]
        if isinstance(_raw_url, (list, tuple)):
            _urls = list(_raw_url)
        else:
            _urls = [_raw_url]
        _sha = _src.get("sha256")
        _dl = os.path.join(_tmp, "vdt-0.4.6.tar.gz")
        _last_err = None
        for _url in _urls:
            try:
                self.output.info("downloading %s" % _url)
                with urllib.request.urlopen(_url, timeout=30) as _r, open(_dl, "wb") as _f:
                    shutil.copyfileobj(_r, _f)
                _last_err = None
                break
            except Exception as _exc:
                _last_err = _exc
                self.output.warning("download failed for %s: %s" % (_url, _exc))
                try:
                    if os.path.isfile(_dl):
                        os.remove(_dl)
                except Exception:
                    pass
                continue
        if _last_err is not None:
            raise Exception("all download URLs failed: %s" % _last_err)
        if _sha:
            _h = hashlib.sha256()
            with open(_dl, "rb") as _f:
                for _chunk in iter(lambda: _f.read(65536), b""):
                    _h.update(_chunk)
            if _h.hexdigest().lower() != str(_sha).lower():
                raise Exception("sha256 mismatch for vdt source archive")
        with tarfile.open(_dl, "r:gz") as _tf:
            _members = _tf.getmembers()
            # Robust top-dir detection (no premature break): strip the
            # single top-level directory only when every entry shares it.
            # GitHub codeload archives use vdt-0.4.6/... but the first
            # member may be a bare directory entry, pax header, or './',
            # so scan all members instead of trusting index 0.
            _firsts = []
            for _m in _members:
                _name = (_m.name or "").strip()
                if not _name or _name in (".", "./"):
                    continue
                _stripped = _name.lstrip("./")
                if not _stripped or _stripped.startswith("/") or ".." in _stripped:
                    continue
                if "/" in _stripped:
                    _firsts.append(_stripped.split("/", 1)[0])
                else:
                    # A bare top-level file means there is no single
                    # top directory to strip.
                    _firsts.append(None)
            _top = None
            _cands = [_f for _f in _firsts if _f]
            if _cands and None not in _firsts and all(_f == _cands[0] for _f in _cands):
                _top = _cands[0]
            for _m in _members:
                _name = (_m.name or "").strip()
                if not _name or _name in (".", "./"):
                    continue
                _stripped = _name.lstrip("./")
                if not _stripped or _stripped.startswith("/") or ".." in _stripped:
                    continue
                # strip_root=True semantics: drop the top-level directory.
                if _top and _stripped.startswith(_top + "/"):
                    _rel = _stripped[len(_top) + 1:]
                elif _top and _stripped == _top:
                    continue
                else:
                    _rel = _stripped
                if not _rel:
                    continue
                _m.name = _rel
                _tf.extract(_m, path=self.source_folder)

    def generate(self):
        # Forward HMBS writable TMPDIR into buildenv so compiler temp files
        # never fall back to read-only /tmp.
        for _k in ("TMPDIR", "TMP", "TEMP"):
            _v = os.environ.get(_k)
            if _v:
                try:
                    os.makedirs(_v, exist_ok=True)
                except Exception:
                    pass
                self.buildenv_info.define(_k, _v)
        # E266: OHOS SDK lld links libxml2.so.16 dynamically; CI worker
        # default library search path misses SDK llvm/lib so lld cannot
        # start ("Error loading shared library libxml2.so.16 ... lld").
        # Prepend SDK llvm/lib to LD_LIBRARY_PATH (libgsf/babeltrace proven).
        # Never use -fuse-ld=GNU ld: its output is not executable in the
        # OHOS sandbox (Permission denied, exit 126, needs ELF signature).
        for _d in self._sdk_llvm_lib_dirs():
            try:
                self.buildenv_info.prepend_path("LD_LIBRARY_PATH", _d)
            except Exception:
                pass

    def _sdk_llvm_lib_dirs(self):
        _dirs = []
        _fixed = "/data/service/hnp/ohos-sdk.org/ohos-sdk_26.0.0.18/ohos/native/llvm/lib"
        try:
            _cands = sorted(glob.glob("/data/service/hnp/ohos-sdk.org/*/ohos/native/llvm/lib"))
        except Exception:
            _cands = []
        for _c in [_fixed] + _cands:
            if _c and os.path.isdir(_c) and _c not in _dirs:
                _dirs.append(_c)
        return _dirs

    def _link_env(self, env):
        # Ensure direct subprocess.run() invocations (which bypass conan
        # buildenv and only inherit os.environ) also see SDK llvm/lib first.
        _env = dict(env)
        _dirs = self._sdk_llvm_lib_dirs()
        if _dirs:
            _old = _env.get("LD_LIBRARY_PATH", "")
            _parts = [_p for _p in _old.split(":") if _p] if _old else []
            for _d in reversed(_dirs):
                if _d in _parts:
                    _parts.remove(_d)
                _parts.insert(0, _d)
            _env["LD_LIBRARY_PATH"] = ":".join(_parts)
        return _env

    def _writable_tmp(self):
        _tmp = (os.environ.get("TMPDIR") or os.environ.get("TMP")
                or os.environ.get("TEMP")
                or os.path.join(self.build_folder, "tmp"))
        try:
            os.makedirs(_tmp, exist_ok=True)
        except Exception:
            pass
        for _k in ("TMPDIR", "TMP", "TEMP"):
            os.environ[_k] = _tmp
        return _tmp

    def _resolve_tool(self, *candidates):
        # R33: conf value only when the file exists; otherwise PATH lookup
        # (hmbs prepends real tool dirs to buildenv PATH). No bare $CC/$CXX.
        for _c in candidates:
            if not _c:
                continue
            if os.path.isabs(_c):
                if os.path.isfile(_c):
                    return _c
                _w = shutil.which(os.path.basename(_c))
                if _w:
                    return _w
            else:
                _w = shutil.which(_c)
                if _w:
                    return _w
                if os.path.isfile(_c):
                    return _c
        for _c in candidates:
            if _c:
                return _c
        return "clang++"

    def _toolchain(self):
        compilers = self.conf.get("tools.build:compiler_executables",
                                  default={}, check_type=dict) or {}
        cxx = self._resolve_tool(
            compilers.get("cpp"), "clang++",
            "aarch64-linux-ohos-clang++", "c++", "g++",
            compilers.get("c"))
        cc = self._resolve_tool(
            compilers.get("c"), "clang",
            "aarch64-linux-ohos-clang", "cc", "gcc")
        ar = self._resolve_tool(
            compilers.get("ar"), "llvm-ar", "ar")
        ranlib = self._resolve_tool(
            compilers.get("ranlib"), "llvm-ranlib", "ranlib")
        hmbs_py = os.environ.get("HMBS_PYTHON3")
        python = self._resolve_tool(hmbs_py, "python3", "python")
        return cxx, cc, ar, ranlib, python

    def _run_noshell(self, args, cwd=None, capture=False):
        # Shell-free exec: bypass /bin/sh -c so dash never creates
        # /tmp/sh*.tmp on read-only /tmp. List form directly execs.
        _tmp = self._writable_tmp()
        _env = dict(os.environ)
        for _k in ("TMPDIR", "TMP", "TEMP"):
            _env[_k] = _tmp
        _env = self._link_env(_env)
        self.output.info("noshell: %s" % " ".join(args))
        return subprocess.run(args, check=True, cwd=cwd or self.build_folder,
                              env=_env, capture_output=capture, text=capture)

    def _find_upstream_file(self, filename):
        # self.source_folder in build() is the copy under the build cache
        # (base_build/...), while source() extracted under base_source.
        # Layout differences (basic_layout vs hmbs overrides) change the
        # exact subdir, so search all known roots instead of hardcoding
        # self.source_folder/src/<file>.
        _roots = []
        for _b in (getattr(self, "base_source_folder", None),
                   getattr(self, "source_folder", None),
                   getattr(self, "base_build_folder", None),
                   getattr(self, "build_folder", None)):
            if _b and os.path.isdir(_b) and _b not in _roots:
                _roots.append(_b)
        for _root in _roots:
            for _dir, _dirs, _files in os.walk(_root):
                if filename in _files:
                    return os.path.join(_dir, filename)
        return None

    def build(self):
        self._writable_tmp()
        cxx, _cc, ar, ranlib, python = self._toolchain()
        self.output.info("cern toolchain: CXX=%s AR=%s PY=%s" % (cxx, ar, python))

        # Locate the upstream tree robustly: the generator may live under
        # base_source/... or the build-cache copy, depending on layout.
        gen = self._find_upstream_file("signatures_generator.py")
        if gen is None or not os.path.isfile(gen):
            _roots = [str(getattr(self, "base_source_folder", None)),
                      str(getattr(self, "source_folder", None)),
                      str(getattr(self, "base_build_folder", None))]
            raise Exception("missing upstream generator: %s (searched %s)"
                            % (gen, ",".join(_roots)))
        src_dir = os.path.dirname(gen)
        # Upstream tree root holds src/, include/, progs/.
        tree_root = os.path.dirname(src_dir)
        if not os.path.isdir(os.path.join(tree_root, "include")):
            # Generator found in an unexpected nesting; climb until
            # include/ is found (max 3 levels) before failing.
            _cur = src_dir
            for _ in range(3):
                _cur = os.path.dirname(_cur)
                if os.path.isdir(os.path.join(_cur, "include")):
                    tree_root = _cur
                    break
        src = tree_root
        bdir = self.build_folder
        inc = os.path.join(src, "include")
        diag_inc = os.path.join(inc, "diagnostic")
        if not os.path.isdir(inc):
            raise Exception("missing upstream include dir: %s (tree root %s)"
                            % (inc, tree_root))
        self._run_noshell([python, gen, "-o", src_dir], cwd=src_dir)
        sig_cc = os.path.join(src_dir, "vdtMath_signatures.cc")
        if not os.path.isfile(sig_cc):
            raise Exception("signature generation failed, missing: %s" % sig_cc)

        # 2) Generate include/externalLibcfg.h with USE_VC=0
        #    (upstream configure_file of externalLibcfg.h.cmake, USE_VC=OFF).
        cfg = os.path.join(inc, "externalLibcfg.h")
        with open(cfg, "w", encoding="utf-8") as _f:
            _f.write(_EXTERNAL_LIB_CFG)

        # 3) Compile the library TU (upstream lib/CMakeLists LIB_FLAGS for
        #    clang, all SIMD OFF, DEBUG OFF):
        #    -Winline -O3 -std=c++11 -W -Wall -Werror
        #    -Wno-error=unused-parameter -D__extern_always_inline=inline
        obj = os.path.join(bdir, "vdtMath_signatures.o")
        cflags = ["-O3", "-std=c++11", "-W", "-Wall", "-Werror",
                  "-Wno-error=unused-parameter",
                  "-D__extern_always_inline=inline", "-Winline",
                  "-I%s" % inc]
        if self.options.shared:
            cflags.append("-fPIC")
        self._run_noshell([cxx, "-c", sig_cc, "-o", obj] + cflags)

        if self.options.shared:
            soname = os.path.join(bdir, "libvdt.so")
            self._run_noshell([cxx, "-shared", "-o", soname, obj])
        else:
            libsta = os.path.join(bdir, "libvdt.a")
            self._run_noshell([ar, "rcs", libsta, obj])
            self._run_noshell([ranlib, libsta])

        self._run_upstream_tests(cxx, inc, diag_inc, bdir, src)

    def _run_upstream_tests(self, cxx, inc, diag_inc, bdir, src):
        # Upstream VDT 0.4.6 ships 12 function unit tests under progs/units/
        # (exp/log/sqrt/sin/cos/inv/tan/tanh/asin/acos/atan/atan2). Each is a
        # standalone executable linked against vdt (DIAG_FLAGS, no librt
        # needed: clock APIs live in libc). Build each real binary with the
        # configured compiler and run it; counts come from actual execution.
        units = os.path.join(src, "progs", "units")
        bindir = os.path.join(bdir, "bin")
        try:
            os.makedirs(bindir, exist_ok=True)
        except Exception:
            pass
        tflags = ["-O3", "-std=c++11", "-W", "-Wall", "-Werror",
                  "-Wno-error=unused-parameter",
                  "-D__extern_always_inline=inline",
                  "-I%s" % inc, "-I%s" % diag_inc]
        if self.options.shared:
            lib_arg = os.path.join(bdir, "libvdt.so")
        else:
            lib_arg = os.path.join(bdir, "libvdt.a")
        if not os.path.isfile(lib_arg):
            raise Exception("library not built: %s" % lib_arg)

        discovered = len(_UPSTREAM_TESTS)
        executed = 0
        passed = 0
        failed = 0
        for name in _UPSTREAM_TESTS:
            cpp = os.path.join(units, name + ".cpp")
            if not os.path.isfile(cpp):
                continue
            exe = os.path.join(bindir, name)
            try:
                self._run_noshell([cxx, cpp, "-o", exe] + tflags + [lib_arg])
            except Exception as exc:
                failed += 1
                self.output.warning("upstream test %s compile failed: %s" % (name, exc))
                continue
            executed += 1
            try:
                _tmp = self._writable_tmp()
                _env = dict(os.environ)
                for _k in ("TMPDIR", "TMP", "TEMP"):
                    _env[_k] = _tmp
                _env = self._link_env(_env)
                self.output.info("noshell upstream: %s" % exe)
                _p = subprocess.run([exe], capture_output=True, text=True,
                                    timeout=120, env=_env)
                for _line in ((_p.stdout or "") + (_p.stderr or "")).splitlines()[-5:]:
                    self.output.info("[vdt %s] %s" % (name, _line))
                if _p.returncode != 0:
                    raise Exception("exit %d" % _p.returncode)
                passed += 1
            except Exception as exc:
                failed += 1
                self.output.warning("upstream test %s failed: %s" % (name, exc))
        skipped = discovered - executed
        ok = (executed == discovered and failed == 0)
        result = {
            "status": "passed" if ok else "failed",
            "framework": "custom",
            "command": "progs/units 12 function tests (direct compile)",
            "discovered": discovered,
            "executed": executed,
            "passed": passed,
            "failed": failed,
            "skipped": skipped,
        }
        msg = "HMBS_UPSTREAM_TEST_RESULT=" + json.dumps(result, ensure_ascii=False)
        print(msg, flush=True)
        self.output.info(msg)
        if can_run(self) and not ok:
            raise Exception("cern upstream tests failed: %d/%d passed"
                            % (passed, discovered))

    def package(self):
        # Mirror build()'s robust tree-root lookup: source may retain the
        # vdt-0.4.6/ top dir and live under base_source or the build-cache
        # copy (which also holds the generated externalLibcfg.h).
        _gen = self._find_upstream_file("signatures_generator.py")
        _inc = None
        if _gen:
            _root = os.path.dirname(os.path.dirname(_gen))
            _cur = os.path.dirname(_gen)
            for _ in range(3):
                _cur = os.path.dirname(_cur)
                if os.path.isdir(os.path.join(_cur, "include")):
                    _root = _cur
                    break
            _cand = os.path.join(_root, "include")
            if os.path.isdir(_cand):
                _inc = _cand
        if _inc is None:
            _cand = os.path.join(self.source_folder, "include")
            if os.path.isdir(_cand):
                _inc = _cand
        if _inc is None:
            _found = self._find_upstream_file("vdtMath.h")
            if _found:
                _inc = os.path.dirname(_found)
        if _inc is None:
            raise Exception("missing upstream include dir for packaging")
        # Upstream include/ is flat (vdtMath.h directly under include/);
        # consumers use #include \"vdt/vdtMath.h\", so stage under include/vdt.
        copy(self, "*.h", src=_inc,
             dst=os.path.join(self.package_folder, "include", "vdt"))
        if self.options.shared:
            copy(self, "libvdt.so*", src=self.build_folder,
                 dst=os.path.join(self.package_folder, "lib"))
        else:
            copy(self, "libvdt.a", src=self.build_folder,
                 dst=os.path.join(self.package_folder, "lib"))
        _lic = self._find_upstream_file("Licence.txt")
        if _lic is None:
            _lic_src = self.source_folder
        else:
            _lic_src = os.path.dirname(_lic)
        copy(self, "Licence.txt", src=_lic_src,
             dst=os.path.join(self.package_folder, "licenses"), keep_path=False)

    def package_info(self):
        self.cpp_info.libs = ["vdt"]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libdirs = ["lib"]
