#!/usr/bin/env python3
"""Conan recipe for choose-mirror 2.137 — OHOS (OpenHarmony) aarch64 adaptation.

choose-mirror is the Debian installer's mirror selection component: a
debconf-driven interactive state machine (choose protocol -> country ->
mirror -> suite, then validate the mirror by reading its Release file).
Source: https://salsa.debian.org/installer-team/choose-mirror (official, 2.137).

OHOS adaptation scope:
- Pure C single translation unit (choose-mirror.c + mirrors.h), plain Makefile
  build. Built with -DWITH_HTTP -DWITH_HTTPS -DWITH_FTP_MANUAL (upstream
  defaults; USE_FTP stays off -> mirrors_ftp.h not generated, WITH_FTP
  #ifdef-protected in the source).
- DEB_HOST_ARCH=arm64 passed explicitly (NOT "aarch64"): the Makefile line
  `DEB_HOST_ARCH ?= $(shell dpkg-architecture ...)` cannot run on OHOS (no
  dpkg). In Debian's main-architecture system the aarch64 hardware is named
  "arm64": the stable Release `Architectures:` line lists arm64 (no
  aarch64) and the binary directory is binary-arm64 (no binary-aarch64) —
  choose-mirror.c:361 (strstr(release->archs, ARCH_TEXT)) and
  choose-mirror.c:899 (dists/%s/main/binary-%s/Release) both require the
  "arm64" spelling. Same ABI as this repo's ohos-aarch64 target.
  Measured with masterlist 2.137: DEB_HOST_ARCH=arm64 generates 283 mirror
  entries (full deb.debian.org + ftp.xx.debian.org set); DEB_HOST_ARCH=
  aarch64 generates 0 (only the NULL terminator — the Ports-architecture
  list does not carry aarch64, so the arch filter empties the tables).
- mirrors_http.h / mirrors_https.h are generated by the upstream perl script
  ./mirrorlist (perl 5.42 available at /data/service/hnp/bin/perl on OHOS).
- debian/iso_3166.tab (upstream: `isoquery -c | cut -f 1,4 | sort`) is
  prepared from the iso-codes data package, falling back to the official
  iso-codes source XML — build data preparation, not a platform macro.
- Linking is static against the dependency archives
  (libdebconfclient.a + libdebian-installer.a + libsystem.a). The cdebconf
  package also ships .so files, but a dynamically linked binary would need
  RUNPATH + both dependency libdirs at OHOS runtime (fragile on HMDFS); the
  static binary is self-contained (NEEDED: libc.so only) and is self-signed
  before packaging so it can be executed on OHOS.

Upstream tests: NONE in the source tree (see notes.md, R51 inventory).
"""
import os

from conan import ConanFile
from conan.tools.files import copy, download
from conan.tools.layout import basic_layout


class ChooseMirrorConan(ConanFile):
    name = "choose-mirror"
    version = "2.137"
    description = ("Debian installer mirror selection component "
                   "(debconf-driven mirror/country/protocol/suite state machine)")
    license = "GPL-2.0-or-later"
    homepage = "https://salsa.debian.org/installer-team/choose-mirror"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    # conandata.yml must be exported for self.conan_data["sources"]
    exports_sources = "conandata.yml"

    def requirements(self):
        # cdebconf 0.283 provides libdebconfclient + cdebconf/debconfclient.h
        # (its package_info exposes no cpp_info — wired manually in build()).
        self.requires("cdebconf/0.283")
        # libdebian-installer 0.121 provides libdebian-installer.a (+ libsystem.a)
        # and include/debian-installer.h (cpp_info.libs = ["debian-installer"]).
        self.requires("libdebian-installer/0.121")

    def layout(self):
        basic_layout(self)

    def source(self):
        # conan.tools.files.get() raises PermissionError on this OHOS
        # environment (same finding as libdebian-installer notes.md) —
        # download() + manual tar/untar instead.
        tarball = os.path.join(self.source_folder,
                               "choose-mirror_2.137.tar.xz")
        download(self, self.conan_data["sources"]["url"], tarball,
                 sha256=self.conan_data["sources"]["sha256"])
        # This conan build has no conan.tools.files.untar — use tar directly
        # (--strip-components=1 flattens the top-level choose-mirror-2.137/
        # directory so the Makefile lands at the source root).
        self.run("tar -xJf choose-mirror_2.137.tar.xz --no-same-owner "
                 "--strip-components=1",
                 cwd=self.source_folder)
        os.remove(tarball)

    def _iso_tab(self):
        """Prepare debian/iso_3166.tab (format: `XX<TAB>Country name`, sorted).

        Upstream target: `isoquery -c | cut -f 1,4 | sort` (isoquery is a
        perl script from the iso-codes package — not executable on OHOS).
        Fallback: parse the official iso-codes source XML natively
        (isoquery itself only does cut/sort on that XML).
        """
        tab = os.path.join(self.source_folder, "debian", "iso_3166.tab")
        if os.path.isfile(tab) and os.path.getsize(tab) > 0:
            return tab

        os.makedirs(os.path.dirname(tab), exist_ok=True)
        try:
            self.run("isoquery -c | cut -f 1,4 | sort > %s" % tab)
            if os.path.getsize(tab) > 0:
                self.output.info("iso_3166.tab from system isoquery")
                return tab
        except Exception:
            pass  # expected on OHOS — no isoquery
        if os.path.isfile(tab):
            os.remove(tab)

        def write_rows(rows):
            with open(tab, "w", encoding="utf-8") as f:
                for code, name in sorted(rows):
                    f.write("%s\t%s\n" % (code, name))

        # Fallback: official iso-codes source (Debian pool, same pool as this
        # package's own source — R18/R39). iso-codes 4.20.1 ships
        # data/iso_3166-1.json; isoquery's `-c` output is the same
        # alpha_2 + name columns, so parsing the JSON yields the identical
        # `XX<TAB>name` rows.
        tarball = os.path.join(self.build_folder, "iso-codes.tar.xz")
        download(self,
                 "https://deb.debian.org/debian/pool/main/i/iso-codes/"
                 "iso-codes_4.20.1.orig.tar.xz",
                 tarball,
                 sha256="5d551f3ddb32548c4321e9011720fd97751af0107592f79ebffc939bd32f2268")
        self.run("tar -xJf %s --no-same-owner iso-codes-4.20.1/data/"
                 "iso_3166-1.json" % tarball, cwd=self.build_folder)
        import json as _json
        data = _json.load(open(os.path.join(
            self.build_folder, "iso-codes-4.20.1", "data", "iso_3166-1.json")))
        rows = [(c["alpha_2"], c["name"]) for c in data["3166-1"]]
        if not rows:
            raise RuntimeError("iso_3166-1.json yielded no countries")
        write_rows(rows)
        self.output.info("iso_3166.tab from official iso-codes source JSON "
                         "(%d entries)" % len(rows))
        return tab

    def build(self):
        # R33: compiler from Conan conf, never from raw shell env vars
        compilers = self.conf.get("tools.build:compiler_executables",
                                  default={}, check_type=dict) or {}
        cc = compilers.get("c", "clang")

        # OHOS has no dpkg-architecture — the Makefile's DEB_HOST_ARCH probe
        # cannot run, and mirrorlist falls back to it as well. Pass it
        # explicitly as "arm64": in Debian's main-architecture system the
        # aarch64 hardware is named arm64 (Release Architectures lists
        # arm64, not aarch64; the mirror path is binary-arm64). In
        # mirrorlist, $hostarch only selects the masterlist arch field
        # (archive branch + -architecture filter), unrelated to the hardware
        # ABI; arm64 here matches this repo's ohos-aarch64 target (same
        # ABI). Measured: arm64 -> 283 mirror entries, aarch64 -> 0.
        env = "DEB_HOST_ARCH=arm64 "

        # 1) debian/iso_3166.tab (build data, not a platform macro)
        self._iso_tab()

        # 2) Generate the compiled-in mirror tables via the upstream perl
        # script. Its shebang is #!/usr/bin/perl, which does not exist on
        # OHOS (perl lives in /data/service/hnp/bin) — invoke perl by
        # absolute path instead of relying on the shebang (no source edit).
        perl = "/data/service/hnp/bin/perl"
        for proto in ("http", "https"):
            self.run(env + '"%s" ./mirrorlist %s Mirrors.masterlist '
                      'debian/iso_3166.tab' % (perl, proto),
                     cwd=self.source_folder)

        # 3) Compile + link (single TU). -DWITH_FTP_MANUAL matches the
        # upstream Makefile default (USE_FTP_MANUAL=1); USE_FTP stays off so
        # mirrors_ftp.h is not generated and WITH_FTP remains #ifdef-gated.
        cdebconf = self.dependencies["cdebconf"].package_folder
        ldi = self.dependencies["libdebian-installer"].package_folder

        # ARCH_TEXT must be a C string literal (Makefile equivalent:
        # -DARCH_TEXT='"$(DEB_HOST_ARCH)"') and must use the Debian main
        # architecture spelling "arm64" for aarch64 hardware (Release
        # Architectures lines and binary-arm64 paths; see recipe docstring).
        # self.run goes through /bin/sh, so the quotes are shell-protected
        # with single quotes: the shell strips the outer single quotes and
        # passes "arm64" (with the C quotes) verbatim to the compiler.
        cflags = "-Wall -O2 -D_GNU_SOURCE"
        cflags += " -DARCH_TEXT='\"arm64\"'"
        cflags += " -DWITH_HTTP -DWITH_HTTPS -DWITH_FTP_MANUAL"
        inc = "-I%s/include -I%s/include" % (cdebconf, ldi)

        self.run(env + f'"{cc}" {cflags} {inc} -c choose-mirror.c '
                  "-o choose-mirror.o",
                 cwd=self.source_folder)

        # Static link against the dependency archives (see recipe docstring
        # for why not dynamic): explicit archive paths avoid the .so files
        # co-located in cdebconf's lib dir (linker prefers .so) and avoid
        # RUNPATH at runtime. Archive order matters: libdebian-installer.a
        # before libsystem.a (22 symbols shared, e.g. di_system_init).
        self.run(env + f'"{cc}" -o choose-mirror choose-mirror.o '
                  f"{cdebconf}/lib/libdebconfclient.a "
                  f"{ldi}/lib/libdebian-installer.a "
                  f"{ldi}/lib/libsystem.a -lm",
                 cwd=self.source_folder)

        # R51: upstream has no test suite (no tests/ dir, no make check /
        # make test target in the Makefile — inventory in notes.md). The
        # closest upstream artifact is `demo` (needs debconf frontend +
        # po2debconf, unavailable on OHOS) — not run. test_package provides
        # the real functional execution instead.

    def package(self):
        # R38: CLI tool -> bin/
        copy(self, "choose-mirror",
             src=self.source_folder,
             dst=os.path.join(self.package_folder, "bin"))
        # Mirrors.masterlist is upstream runtime/reference data (the file the
        # binary's compiled-in tables are generated from); shipped for audit
        # / tooling that may query it.
        copy(self, "Mirrors.masterlist",
             src=self.source_folder,
             dst=os.path.join(self.package_folder, "share", "choose-mirror"))

        # R7: self-sign the ELF for local execution on OHOS
        if self.settings.os in ("Linux", "OHOS"):
            pkg_path = os.path.join(self.package_folder, "bin",
                                    "choose-mirror")
            sign_tool = "/data/service/hnp/bin/binary-sign-tool"
            if os.path.isfile(sign_tool) and os.path.isfile(pkg_path):
                signed_path = f"{pkg_path}.signed"
                self.run(
                    f'{sign_tool} sign -inFile "{pkg_path}"'
                    f' -outFile "{signed_path}"'
                    f' -selfSign 1 -signAlg SHA256withECDSA',
                    quiet=True
                )
                if os.path.isfile(signed_path):
                    os.replace(signed_path, pkg_path)
                    os.chmod(pkg_path, 0o755)

    def package_info(self):
        # command-line tool, not a library
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
