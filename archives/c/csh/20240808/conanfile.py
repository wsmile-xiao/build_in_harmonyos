#!/usr/bin/env python3
"""Conan recipe for the OpenBSD-derived csh command interpreter.

The upstream tree is built with BSD make and includes OpenBSD libc headers
that are not present in the OHOS SDK.  This recipe keeps the upstream source
layout, generates the two BSD-make headers portably, and compiles the shell
with the OHOS toolchain directly.
"""

import os
import re
import shutil
import stat
import subprocess

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import Environment, VirtualBuildEnv
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    save,
)
from conan.tools.layout import basic_layout


class CshConan(ConanFile):
    name = "csh"
    version = "20240808"
    description = "The Berkeley C shell command interpreter"
    license = "BSD-3-Clause"
    homepage = "https://www.openbsd.org/cgi-bin/cvsweb/src/bin/csh/"
    url = "https://www.openbsd.org/cgi-bin/cvsweb/src/bin/csh/"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    exports_sources = "patches/*"

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "csh supports Linux and OHOS targets, got %s" % self.settings.os
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def generate(self):
        # The upstream Makefile is BSD make syntax and cannot be consumed by
        # GNU make.  Export only the selected compiler and flags; no autotools
        # configure or make helper is involved in this recipe.
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        ) or {}
        cflags = self.conf.get("tools.build:cflags", default=[], check_type=list) or []
        ldflags = self.conf.get(
            "tools.build:exelinkflags", default=[], check_type=list
        ) or []
        env = Environment()
        env.define("CC", compilers.get("c", "clang"))
        env.define("CXX", compilers.get("cpp", "clang++"))
        if cflags:
            env.define("CFLAGS", " ".join(str(flag) for flag in cflags))
        env.define("LDFLAGS", " ".join(["-static"] + [str(flag) for flag in ldflags]))
        env.vars(self).save_script("csh_toolchain")
        VirtualBuildEnv(self).generate()

    def _quote(self, value):
        return "'" + str(value).replace("'", "'\\''") + "'"

    def _generate_headers(self):
        """Reproduce the upstream error.h/const.h generation without BSD make."""
        src = self.source_folder
        build = self.build_folder
        error_header = os.path.join(build, "error.h")
        const_header = os.path.join(build, "const.h")

        error_defines = []
        with open(os.path.join(src, "error.c"), "r", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("#define") and "ERR_" in line:
                    error_defines.append(line.rstrip())
        if not error_defines:
            raise ConanException("error.c did not contain the expected ERR_* definitions")

        save(
            self,
            error_header,
            "/* Do not edit this file, the Conan recipe creates it. */\n"
            "#ifndef _h_sh_err\n"
            "#define _h_sh_err\n"
            + "\n".join(error_defines)
            + "\n#endif /* _h_sh_err */\n",
        )

        # csh.h includes const.h, so bootstrap it before preprocessing const.c.
        save(
            self,
            const_header,
            "/* Bootstrap header; replaced after const.c preprocessing. */\n",
        )
        preprocessed = os.path.join(build, "const.i")
        command = " ".join(
            [
                "$CC",
                "$CFLAGS",
                "-D_GNU_SOURCE",
                "-std=gnu17",
                "-I" + self._quote(src),
                "-I" + self._quote(build),
                "-include",
                self._quote(os.path.join(src, "ohos-compat.h")),
                "-E",
                self._quote(os.path.join(src, "const.c")),
                ">",
                self._quote(preprocessed),
            ]
        )
        self.run(command, env=["conanbuild", "csh_toolchain"])

        names = set()
        with open(preprocessed, "r", encoding="utf-8", errors="replace") as handle:
            for line in handle:
                match = re.match(r"^\s*Char\s+([A-Za-z_][A-Za-z0-9_]*)\s*\[", line)
                if match:
                    names.add(match.group(1))
        if not names:
            raise ConanException("const.c preprocessing produced no STR constants")

        declarations = [
            "/* Do not edit this file, the Conan recipe creates it. */",
            "#ifndef CSH_CONST_H",
            "#define CSH_CONST_H",
        ]
        declarations.extend("extern Char %s[];" % name for name in sorted(names))
        declarations.append("#endif /* CSH_CONST_H */")
        save(self, const_header, "\n".join(declarations) + "\n")

    def build(self):
        self._generate_headers()
        src = self.source_folder
        output = os.path.join(self.build_folder, "csh")
        sources = [
            "alloc.c",
            "char.c",
            "const.c",
            "csh.c",
            "dir.c",
            "dol.c",
            "error.c",
            "exec.c",
            "exp.c",
            "file.c",
            "func.c",
            "glob.c",
            "hist.c",
            "init.c",
            "lex.c",
            "misc.c",
            "ohos-compat.c",
            "parse.c",
            "proc.c",
            "sem.c",
            "set.c",
            "str.c",
            "time.c",
        ]
        source_args = " ".join(self._quote(os.path.join(src, name)) for name in sources)
        command = " ".join(
            [
                "$CC",
                "$CFLAGS",
                "-D_GNU_SOURCE",
                "-std=gnu17",
                "-fPIE",
                "-I" + self._quote(src),
                "-I" + self._quote(self.build_folder),
                "-include",
                self._quote(os.path.join(src, "ohos-compat.h")),
                "-O2" if str(self.settings.build_type) == "Release" else "-O0",
                "-g",
                "-static",
                "-o",
                self._quote(output),
                source_args,
                "$LDFLAGS",
            ]
        )
        self.run(command, env=["conanbuild", "csh_toolchain"])

    def _sign_ohos_elfs(self):
        if str(self.settings.os) != "OHOS":
            return

        objcopy = shutil.which("llvm-objcopy") or "/data/service/hnp/bin/llvm-objcopy"
        signer = shutil.which("binary-sign-tool") or "/data/service/hnp/bin/binary-sign-tool"
        readelf = (
            shutil.which("llvm-readelf")
            or shutil.which("readelf")
            or "/data/service/hnp/bin/llvm-readelf"
        )
        if not all(os.path.isfile(path) for path in (objcopy, signer, readelf)):
            raise ConanInvalidConfiguration(
                "llvm-objcopy, binary-sign-tool, and llvm-readelf are required "
                "to sign and verify OHOS ELF executables"
            )

        for root, _, files in os.walk(self.package_folder):
            for name in files:
                path = os.path.join(root, name)
                if os.path.islink(path):
                    continue
                try:
                    with open(path, "rb") as handle:
                        if handle.read(4) != b"\x7fELF":
                            continue
                except OSError:
                    continue

                removed = subprocess.run(
                    [objcopy, "--remove-section", ".codesign", path],
                    check=False,
                    capture_output=True,
                    text=True,
                    timeout=30,
                )
                if removed.returncode != 0:
                    raise ConanException(
                        "llvm-objcopy failed for %s: %s" % (path, removed.stderr[-500:])
                    )

                signed = path + ".signed"
                result = subprocess.run(
                    [signer, "sign", "-inFile", path, "-outFile", signed, "-selfSign", "1"],
                    check=False,
                    capture_output=True,
                    text=True,
                    timeout=30,
                )
                if result.returncode != 0 or not os.path.isfile(signed):
                    raise ConanException(
                        "binary-sign-tool failed for %s: %s" % (path, result.stderr[-500:])
                    )
                os.replace(signed, path)
                os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

                section_check = subprocess.run(
                    [readelf, "-S", path],
                    check=False,
                    capture_output=True,
                    text=True,
                    timeout=30,
                )
                if section_check.returncode != 0 or ".codesign" not in section_check.stdout:
                    raise ConanException("signed OHOS ELF has no .codesign section: %s" % path)
                self.output.info("Signed OHOS ELF and verified .codesign: %s" % path)

    def package(self):
        bindir = os.path.join(self.package_folder, "bin")
        copy(self, "csh", src=self.build_folder, dst=bindir, keep_path=False)
        copy(
            self,
            "csh.1",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "share", "man", "man1"),
            keep_path=False,
        )
        executable = os.path.join(bindir, "csh")
        if os.path.isfile(executable):
            os.chmod(executable, os.stat(executable).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        self._sign_ohos_elfs()

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libdirs = []
        self.cpp_info.libs = []
