#!/usr/bin/env python3
"""Conan recipe — UPSE 1.0.0 (custom C build)."""

import glob
import os
import platform
import shlex
import shutil
import subprocess

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    save,
)
from conan.tools.layout import basic_layout


class UpseConan(ConanFile):
    name = "upse"
    version = "1.0.0"
    description = "PlayStation Sound Format emulator library and player"
    license = "GPL-2.0-only"
    homepage = "https://www.nenolod.net/projects/upse/"
    url = "https://atomgit.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}
    generators = "VirtualBuildEnv"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("zlib/1.3.1.1")

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def layout(self):
        basic_layout(self, src_folder="src")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"UPSE supports Linux and OHOS, not {self.settings.os}"
            )

    def build(self):
        apply_conandata_patches(self)
        cc, ar = self._tools()
        zlib = self.dependencies["zlib"]
        source_dir = os.path.join(self.source_folder, "src", "libupse")
        object_dir = os.path.join(self.build_folder, "objects")
        os.makedirs(object_dir, exist_ok=True)

        config = (
            "/* Generated by the Conan recipe for the upstream C sources. */\n"
            '#define PACKAGE "upse"\n'
            '#define PACKAGE_NAME "upse"\n'
            '#define PACKAGE_VERSION "1.0.0"\n'
            '#define PACKAGE_BUGREPORT "nenolod+upse@sacredspiral.co.uk"\n'
            '#define VERSION "1.0.0"\n'
        )
        save(self, os.path.join(self.source_folder, "config.h"), config)

        include_flags = [
            "-I" + source_dir,
            "-I" + self.source_folder,
        ]
        for include_dir in zlib.cpp_info.includedirs:
            include_flags.append("-I" + include_dir)

        compile_flags = ["-std=gnu99", "-Wall"]
        compile_flags.append(
            "-O2" if str(self.settings.build_type) == "Release" else "-O0"
        )
        if self.options.get_safe("fPIC") or self.options.shared:
            compile_flags.append("-fPIC")

        objects = []
        for source in sorted(glob.glob(os.path.join(source_dir, "*.c"))):
            obj = os.path.join(
                object_dir, os.path.splitext(os.path.basename(source))[0] + ".o"
            )
            self._run(
                [cc, *compile_flags, *include_flags, "-c", source, "-o", obj]
            )
            objects.append(obj)

        zlib_library = self._library_file(zlib, ("libz.a", "libz.so"))
        if self.options.shared:
            library = os.path.join(self.build_folder, "libupse.so.2.0.0")
            self._run(
                [
                    cc,
                    "-shared",
                    "-Wl,-soname,libupse.so.2",
                    "-o",
                    library,
                    *objects,
                    zlib_library,
                    "-lm",
                ]
            )
        else:
            library = os.path.join(self.build_folder, "libupse.a")
            self._run([ar, "rcs", library, *objects])

        player_source = os.path.join(
            self.source_folder, "src", "upse123", "upse123_main.c"
        )
        player_object = os.path.join(object_dir, "upse123_main.o")
        self._run(
            [
                cc,
                *compile_flags,
                *include_flags,
                "-c",
                player_source,
                "-o",
                player_object,
            ]
        )
        player = os.path.join(self.build_folder, "upse123")
        self._run(
            [cc, "-o", player, player_object, library, zlib_library, "-lm"]
        )

        self.output.info(
            'HMBS_UPSTREAM_TEST_RESULT: {"framework":"none",'
            '"command":"source tree and Makefile audit: no automated test target",'
            '"discovered":0,"executed":0,"passed":0,"failed":0,"skipped":0}'
        )

    def package(self):
        library_name = (
            "libupse.so.2.0.0" if self.options.shared else "libupse.a"
        )
        copy(
            self,
            library_name,
            src=self.build_folder,
            dst=os.path.join(self.package_folder, "lib"),
        )
        if self.options.shared:
            lib_dir = os.path.join(self.package_folder, "lib")
            for link, target in (
                ("libupse.so.2", "libupse.so.2.0.0"),
                ("libupse.so", "libupse.so.2"),
            ):
                link_path = os.path.join(lib_dir, link)
                if os.path.lexists(link_path):
                    os.unlink(link_path)
                os.symlink(target, link_path)
        copy(
            self,
            "upse.h",
            src=os.path.join(self.source_folder, "src", "libupse"),
            dst=os.path.join(self.package_folder, "include", "upse"),
        )
        copy(
            self,
            "upse-types.h",
            src=os.path.join(self.source_folder, "src", "libupse"),
            dst=os.path.join(self.package_folder, "include", "upse"),
        )
        copy(
            self,
            "upse123",
            src=self.build_folder,
            dst=os.path.join(self.package_folder, "bin"),
        )
        self._sign_ohos_binary(
            os.path.join(self.package_folder, "bin", "upse123")
        )

    def package_info(self):
        self.cpp_info.includedirs = ["include/upse"]
        self.cpp_info.libs = ["upse"]
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.system_libs = ["m"]
        if not self.options.shared:
            self.cpp_info.requires = ["zlib::zlib"]
        self.cpp_info.set_property("cmake_file_name", "upse")
        self.cpp_info.set_property("cmake_target_name", "upse::upse")
        self.cpp_info.set_property("pkg_config_name", "upse")

    def _tools(self):
        executables = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        )
        cc = executables.get("c") or shutil.which("clang") or "clang"
        ar = executables.get("ar")
        if not ar:
            sibling_ar = os.path.join(os.path.dirname(cc), "llvm-ar")
            ar = sibling_ar if os.path.isfile(sibling_ar) else shutil.which("llvm-ar")
        if not ar:
            raise ConanInvalidConfiguration("llvm-ar is required to package UPSE")
        return cc, ar

    @staticmethod
    def _library_file(dependency, candidates):
        for lib_dir in dependency.cpp_info.libdirs:
            for candidate in candidates:
                path = os.path.join(lib_dir, candidate)
                if os.path.isfile(path):
                    return path
        raise ConanInvalidConfiguration("zlib library file was not found")

    def _run(self, arguments):
        command = " ".join(shlex.quote(str(argument)) for argument in arguments)
        self.run(command, env="conanbuild")

    @staticmethod
    def _sign_ohos_binary(binary):
        if not os.path.isfile(binary) or platform.system() != "HarmonyOS":
            return
        signer = shutil.which("binary-sign-tool")
        if not signer:
            return
        signed = binary + ".signed"
        result = subprocess.run(
            [
                signer,
                "sign",
                "-inFile",
                binary,
                "-outFile",
                signed,
                "-selfSign",
                "1",
            ],
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        if result.returncode == 0 and os.path.isfile(signed):
            os.replace(signed, binary)
            os.chmod(binary, 0o755)
