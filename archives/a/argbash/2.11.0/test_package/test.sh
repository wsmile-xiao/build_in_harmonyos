#!/usr/bin/env bash
# argbash smoke test: verify package argbash binary works
# Usage: test.sh <package_bin_dir>
# R34: must use package binary, not system PATH
# OHOS: chmod +x doesn't work (E046), so invoke via bash
set -euo pipefail

BIN_DIR="${1:-}"
if [ -z "$BIN_DIR" ] || [ ! -d "$BIN_DIR" ]; then
    echo "argbash: package bin dir not found: $BIN_DIR"
    exit 1
fi

ARGBASH="$BIN_DIR/argbash"
ARGBASH_INIT="$BIN_DIR/argbash-init"

if [ ! -f "$ARGBASH" ]; then
    echo "argbash: binary missing in package: $ARGBASH"
    exit 1
fi

echo "argbash: using package binary at $ARGBASH"

# OHOS: chmod +x doesn't work (E046, SELinux), so invoke via bash
BASH="${CONFIG_SHELL:-/data/service/hnp/bin/bash}"

# 1) Version check (smoke test)
VERSION_OUT="$("$BASH" "$ARGBASH" --version 2>&1)" || {
    echo "argbash: --version failed"
    exit 1
}
echo "argbash: --version -> $(echo "$VERSION_OUT" | head -1)"
if ! echo "$VERSION_OUT" | grep -q "2.11.0"; then
    echo "argbash: version mismatch, expected 2.11.0"
    exit 1
fi

# 2) Functional test: use argbash-init to create a template, then argbash to generate a script
TMPD="$(mktemp -d)"
trap 'rm -rf "$TMPD"' EXIT

# Create a minimal argbash template using argbash-init
if [ -f "$ARGBASH_INIT" ]; then
    "$BASH" "$ARGBASH_INIT" --pos "name" "$TMPD/test.m4" 2>&1 || {
        echo "argbash: argbash-init failed"
        exit 1
    }
    echo "argbash: argbash-init created template"

    # Generate a bash script from the template
    "$BASH" "$ARGBASH" "$TMPD/test.m4" -o "$TMPD/test.sh" 2>&1 || {
        echo "argbash: script generation failed"
        exit 1
    }
    echo "argbash: generated script from template"

    # Run the generated script with an argument
    OUTPUT="$("$BASH" "$TMPD/test.sh" hello 2>&1)" || {
        echo "argbash: generated script failed to run"
        exit 1
    }
    if ! echo "$OUTPUT" | grep -q "hello"; then
        echo "argbash: generated script did not pass positional argument correctly"
        echo "Output: $OUTPUT"
        exit 1
    fi
    echo "argbash: generated script correctly parsed positional argument"
else
    echo "argbash: argbash-init not available, skipping template generation test"
    # Fallback: test argbash on a simple m4 file
    cat > "$TMPD/simple.m4" <<'M4EOF'
# ARG_POSITIONAL_SINGLE([pos_arg], [A positional argument])
# ARG_DEFAULTS_POS([])
# ARG_HELP([Test script generated by argbash])
# ARGBASH_GO()
M4EOF
    "$BASH" "$ARGBASH" "$TMPD/simple.m4" -o "$TMPD/simple.sh" 2>&1 || {
        echo "argbash: simple script generation failed"
        exit 1
    }
    echo "argbash: generated simple script"
    OUTPUT="$("$BASH" "$TMPD/simple.sh" test_value 2>&1)" || {
        echo "argbash: simple generated script failed to run"
        exit 1
    }
    if ! echo "$OUTPUT" | grep -q "test_value"; then
        echo "argbash: simple script did not pass argument correctly"
        exit 1
    fi
    echo "argbash: simple script correctly parsed argument"
fi

echo "argbash test_package: PASS"
