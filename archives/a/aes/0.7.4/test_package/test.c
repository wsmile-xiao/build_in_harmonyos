static void mix_columns(uint8_t*s){for(int c=0;c<4;c++){
    uint8_t a0=s[4*c],a1=s[4*c+1],a2=s[4*c+2],a3=s[4*c+3];
    s[4*c]=gmul(a0,2)^gmul(a1,3)^a2^a3; s[4*c+1]=a0^gmul(a1,2)^gmul(a2,3)^a3;
    s[4*c+2]=a0^a1^gmul(a2,2)^gmul(a3,3); s[4*c+3]=gmul(a0,3)^a1^a2^gmul(a3,2);}}

static void inv_mix_columns(uint8_t*s){for(int c=0;c<4;c++){
    uint8_t a0=s[4*c],a1=s[4*c+1],a2=s[4*c+2],a3=s[4*c+3];
    s[4*c]=gmul(a0,0x0e)^gmul(a1,0x0b)^gmul(a2,0x0d)^gmul(a3,0x09);
    s[4*c+1]=gmul(a0,0x09)^gmul(a1,0x0e)^gmul(a2,0x0b)^gmul(a3,0x0d);
    s[4*c+2]=gmul(a0,0x0d)^gmul(a1,0x09)^gmul(a2,0x0e)^gmul(a3,0x0b);
    s[4*c+3]=gmul(a0,0x0b)^gmul(a1,0x0d)^gmul(a2,0x09)^gmul(a3,0x0e);}}

static void aes_encrypt(const uint8_t*rk,int nr,uint8_t*b){
    add_round_key(b,rk);
    for(int r=1;r<nr;r++){sub_bytes(b);shift_rows(b);mix_columns(b);add_round_key(b,rk+r*16);}
    sub_bytes(b);shift_rows(b);add_round_key(b,rk+nr*16);}

static void aes_decrypt(const uint8_t*rk,int nr,uint8_t*b){
    add_round_key(b,rk+nr*16);
    for(int r=nr-1;r>=1;r--){inv_shift_rows(b);inv_sub_bytes(b);add_round_key(b,rk+r*16);inv_mix_columns(b);}
    inv_shift_rows(b);inv_sub_bytes(b);add_round_key(b,rk);}

