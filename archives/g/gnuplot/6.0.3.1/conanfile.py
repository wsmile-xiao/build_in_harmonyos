#!/usr/bin/env python3
"""Conan recipe for gnuplot 6.0.3.1 (autotools build).

gnuplot is a command-line interactive plotting tool.
This recipe builds gnuplot with libgd support for PNG/JPEG/GIF image output.
Built on the zero-dependency 6.0.3 base, adding gd/2.3.3 for image terminals.
"""
from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain, AutotoolsDeps, PkgConfigDeps
from conan.tools.layout import basic_layout


class GnuplotConan(ConanFile):
    name = "gnuplot"
    version = "6.0.3.1"
    description = "Interactive plotting program that generates 2D and 3D plots"
    license = "gnuplot"
    homepage = "https://gnuplot.sourceforge.net/"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("gd/2.3.3")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Force cross-compile mode: build != host → configure skips run-test
        # (conftest links to Conan .so files not in default LD_LIBRARY_PATH)
        # --build is intentionally set to a different arch than --host to trigger
        # cross-compile mode; the actual CI build machine arch doesn't matter here
        # since configure only uses build!=host to decide whether to run conftest.
        tc.configure_args.append("--build=x86_64-pc-linux-gnu")
        tc.configure_args.append("--host=aarch64-unknown-linux-gnu")
        # gnuplot-specific configure options
        tc.configure_args.append("--with-readline=builtin")
        # Enable gd-based image terminals (PNG/JPEG/GIF/sixel)
        tc.configure_args.append("--with-gd")
        # Disable other optional terminals
        tc.configure_args.append("--without-cairo")
        tc.configure_args.append("--without-lua")
        tc.configure_args.append("--without-qt")
        tc.generate()

        # Generate CFLAGS/LDFLAGS from dependencies
        deps = AutotoolsDeps(self)
        deps.generate()

        # Generate .pc files for dependencies (gnuplot's configure uses PKG_CHECK_MODULES)
        pkg_config = PkgConfigDeps(self)
        pkg_config.generate()

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure()

        # After configure(), conanbuild.sh is generated by Autotools class.
        # Prepend LD_LIBRARY_PATH so build-time tools (doc2gih, etc.) can find
        # shared libs from Conan deps at runtime during make.
        import os
        lib_paths = []
        for _, dep in self.dependencies.items():
            libdir = dep.cpp_info.libdir
            if isinstance(libdir, str):
                libdir = [libdir]
            for d in libdir:
                lib_paths.append(str(d))
        ld_path = ":".join(lib_paths)
        build_sh = os.path.join(self.generators_folder, "conanbuild.sh")
        if os.path.exists(build_sh):
            with open(build_sh, "r") as f:
                content = f.read()
            with open(build_sh, "w") as f:
                f.write(f'export LD_LIBRARY_PATH="{ld_path}:${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}"\n')
                f.write(content)

        autotools.make(args=["-j2"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
