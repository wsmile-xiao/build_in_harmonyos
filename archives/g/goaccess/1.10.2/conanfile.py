#!/usr/bin/env python3
"""Conan recipe — goaccess 1.10.2 (autotools application).

GoAccess is an open source real-time web log analyzer and interactive viewer
that runs in a terminal on *nix systems. On HarmonyOS PC it is adapted as
follows (see notes.md for the full rationale):

  * ncurses (widechar) is not published to the Conan artifact repository, so
    it is installed via cmd-pkgs (prebuilt static libraries + bundled headers)
    at the user prefix. No external Conan dependency is required.
  * config.guess is patched for HarmonyOS platform recognition.
    config.sub already ships with OHOS support in the upstream tarball.
  * The configure script's umask 077 creates temp directories with
    permission 2700 (drwx--S---) under HMDFS, which non-owner users cannot
    write to. This is handled in the build() method by fixing config.status
    after configure generates it (E081).
  * config.status (generated by configure) is fixed inline as a fallback.

R26: Static linking for terminal tools (system same-name lib).
R32: settings.os must check in ("Linux", "OHOS").
R38: Command-line tool — commands.json declared at software level.

Patch declared in conandata.yml:
  0001-config.guess.patch — HarmonyOS platform recognition (E007)
"""
import os
import subprocess

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import (
    get, save, load, apply_conandata_patches,
    export_conandata_patches, copy,
)
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


def _get_prefix():
    """Get the prefix for installing/finding system dependencies.

    Always returns a user-writable path (never /usr/local).
    Uses DEFAULT_PREFIX env var (set by CI/HNP environment) or ~/usr/local.
    """
    prefix = os.environ.get("DEFAULT_PREFIX")
    if prefix:
        return prefix
    return os.path.join(os.path.expanduser("~"), "usr", "local")


def _is_ncurses_installed(prefix):
    """Check if ncurses library is installed at prefix."""
    for libname in ["libncursesw.a", "libncurses.a"]:
        if os.path.exists(os.path.join(prefix, "lib", libname)):
            return True
    return False


def _is_ncurses_headers_installed(prefix):
    """Check if ncurses headers are installed at prefix."""
    return os.path.exists(os.path.join(prefix, "include", "curses.h"))


def _install_cmd_pkg(name, version, prefix):
    """Download and install a cmd-pkgs prebuilt package."""
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/cmd-pkgs/releases/download/pkgs/install.sh"
    cmd = f'curl -fsSL {url} | sh -s -- {name} {version} {prefix}'
    subprocess.run(cmd, shell=True, timeout=300, capture_output=True, text=True)


def _install_ncurses_headers(prefix, header_tarball):
    """Install ncurses headers from bundled tarball (cmd-pkgs only ships libs)."""
    import tarfile
    inc_dst = os.path.join(prefix, "include")
    os.makedirs(inc_dst, exist_ok=True)
    if header_tarball and os.path.exists(header_tarball):
        with tarfile.open(header_tarball, "r:gz") as tar:
            tar.extractall(inc_dst)


class GoaccessConan(ConanFile):
    name = "goaccess"
    version = "1.10.2"
    description = "Open source real-time web log analyzer and interactive viewer"
    license = "MIT"
    homepage = "https://goaccess.io/"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)
        copy(self, "ncurses-headers.tar.gz", self.recipe_folder, self.export_sources_folder)

    def requirements(self):
        # ncurses is system-installed via cmd-pkgs, not a conan dependency.
        pass

    def validate(self):
        # R32: settings.os must check in ("Linux", "OHOS")
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "goaccess is only supported on Linux/OHOS, not " + str(self.settings.os)
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def generate(self):
        prefix = _get_prefix()
        hdr_tarball = os.path.join(self.source_folder, "ncurses-headers.tar.gz")

        # Ensure system ncurses is installed via cmd-pkgs
        if not _is_ncurses_installed(prefix):
            _install_cmd_pkg("ncurses", "6.4", prefix)
        # cmd-pkgs ncurses only ships library, not headers
        if not _is_ncurses_headers_installed(prefix):
            _install_ncurses_headers(prefix, hdr_tarball)

        tc = AutotoolsToolchain(self)
        # R26: Terminal tools - system same-name libs must be static
        tc.extra_ldflags.append("-static")
        # System-installed ncurses (via cmd-pkgs)
        inc = os.path.join(prefix, "include")
        lib = os.path.join(prefix, "lib")
        if os.path.isdir(inc):
            tc.extra_cflags.append("-I" + inc)
        if os.path.isdir(lib):
            tc.extra_ldflags.append("-L" + lib)
        # Configure options from historical adaptation
        tc.configure_args.append("--enable-utf8")
        tc.generate()

    def _fix_config_status(self, build):
        """Fix config.status: remove umask 077 for temp dir (HMDFS permission).

        config.status is a generated file (not in source tarball), so it
        cannot be patched via conandata.yml. This fix must be applied inline
        after configure generates it.
        """
        path = os.path.join(build, "config.status")
        if not os.path.exists(path):
            return
        content = load(self, path)
        content = content.replace("umask 077 && mktemp", "mktemp")
        content = content.replace("umask 077 && mkdir", "mkdir")
        content = content.replace(
            "ac_tmp=$tmp",
            'ac_tmp=$tmp\nchmod 755 "$tmp" 2>/dev/null'
        )
        save(self, path, content)

    def build(self):
        autotools = Autotools(self)
        # Configure may fail because config.status (generated by configure)
        # uses umask 077 which creates temp dirs with permission 2700 under
        # HMDFS that non-owner users cannot write to (E081).
        # We catch the failure, fix config.status, and re-run it.
        try:
            autotools.configure()
        except Exception as exc:
            # E081: HMDFS umask 077 permission trap
            # Fix config.status and re-run
            self._fix_config_status(self.build_folder)
            cs_path = os.path.join(self.build_folder, "config.status")
            if os.path.exists(cs_path):
                self.run(f'cd "{self.build_folder}" && bash config.status')
            else:
                raise
        # Also fix config.status as a fallback
        self._fix_config_status(self.build_folder)
        # If Makefile wasn't created, re-run fixed config.status
        mk_path = os.path.join(self.build_folder, "Makefile")
        if not os.path.exists(mk_path):
            self._fix_config_status(self.build_folder)
            self.run(f'cd "{self.build_folder}" && bash config.status')
        # Touch timestamp files to prevent autotools regeneration (automake missing)
        for f in ["aclocal.m4", "Makefile.in", "configure", "src/config.h.in"]:
            fp = os.path.join(self.build_folder, f)
            if os.path.exists(fp):
                self.run(f'touch "{fp}"')
        # Build with autotools regeneration disabled
        autotools.make(args=["-j1", "ACLOCAL=true", "AUTOCONF=true",
                             "AUTOMAKE=true", "AUTOHEADER=true"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        # goaccess is a standalone terminal binary, not a library
        self.cpp_info.libs = []
        self.cpp_info.bindirs = ["bin"]
        # Ensure goaccess binary is on PATH for VirtualRunEnv (test_package)
        self.runenv_info.prepend_path("PATH", os.path.join(self.package_folder, "bin"))
