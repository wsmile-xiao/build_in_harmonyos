#!/usr/bin/env python3
"""Conan recipe — graphene 1.10.8.1 (Meson).

Graphene is a thin layer of graphic data types: points, vectors, matrices,
quaternions, euler angles, planes, frusta, spheres, boxes, rays, rectangles,
triangles and sizes. Pure C, MIT license, depends only on GLib.
Adapted to HarmonyOS PC (aarch64). See notes.md for the platform notes.

1.10.8.1 is an adaptation fix over 1.10.8 (same upstream tarball): the glib
provider moves from glib2/2.88.0 to glib/2.84.0.1.1, which both drops the
zlib/1.3.1-vs-1.3.1.1 conflict graphene used to inject into consumer graphs
and makes the hand-written forwarding gobject-2.0.pc unnecessary.
"""
import os

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.build import cross_building
from conan.tools.files import get, apply_conandata_patches
from conan.tools.gnu import PkgConfigDeps
from conan.tools.layout import basic_layout
from conan.tools.meson import Meson, MesonToolchain


class GrapheneConan(ConanFile):
    name = "graphene"
    version = "1.10.8.1"
    description = "Thin layer of graphic data types for 2D/3D math (MIT)"
    license = "MIT"
    homepage = "https://github.com/ebassi/graphene"

    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}
    exports_sources = "patches/*"

    def config_options(self):
        if self.settings.os == "Windows":
            self.options.rm_safe("fPIC")

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def requirements(self):
        # graphene 上游只依赖 glib（gobject-2.0，>= 2.30）。1.10.8 用的是
        # glib2/2.88.0，它 requires zlib/1.3.1（无 fPIC 旧版），而 cairo/libpng
        # 链走 zlib/1.3.1.1 → 每个下游消费者都得自己加 zlib override 兜冲突
        # （gtk4、awf-gtk 均如此）。glib/2.84.0.1.1 requires zlib/1.3.1.1，
        # 且把 gobject-2.0 声明成带 pkg_config_name 的正式 component，
        # 冲突源与转发 .pc hack 一并消除。
        self.requires("glib/2.84.0.1.1", transitive_headers=True, transitive_libs=True)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def layout(self):
        basic_layout(self, src_folder=".")

    def generate(self):
        # glib/2.84.0.1.1 declares gobject-2.0 as a component with its own
        # pkg_config_name, so PkgConfigDeps emits gobject-2.0.pc directly.
        PkgConfigDeps(self).generate()
        # 配置阶段留证：meson 用 dependency('gobject-2.0')，命中的就是该 .pc。
        self._log_pc_version("gobject-2.0.pc")
        tc = MesonToolchain(self)
        tc.project_options["wrap_mode"] = "nodownload"
        tc.project_options["introspection"] = "disabled"
        tc.project_options["installed_tests"] = "false"
        tc.project_options["gtk_doc"] = "false"
        tc.project_options["tests"] = "true"
        tc.generate()
        self._inject_meson_archiver()

    def _log_pc_version(self, pc_name):
        """Print the Version line of a generated .pc as configure-stage evidence.

        gobject-2.0.pc now comes from the glib package's component instead of a
        recipe-authored forwarding file, so a missing .pc means the dependency
        side regressed — fail here rather than inside meson's dependency().
        """
        _pc = os.path.join(self.generators_folder, pc_name)
        if not os.path.isfile(_pc):
            raise ConanException(
                "%s was not generated by PkgConfigDeps. graphene needs "
                "dependency('gobject-2.0'); the glib package must expose "
                "gobject-2.0 as a component with pkg_config_name=gobject-2.0."
                % pc_name
            )
        with open(_pc, encoding="utf-8") as _f:
            for _line in _f:
                if _line.startswith("Version:"):
                    self.output.info("pkg-config evidence: %s %s" % (pc_name, _line.strip()))
                    return
        self.output.warning("pkg-config evidence: %s has no Version line" % pc_name)

    def _inject_meson_archiver(self):
        # 【OHOS 必需】conan 的 MesonToolchain 不把 tools.build:compiler_executables
        # 里的 ar/ranlib 写进 native file，meson 便按**裸名** llvm-ar 探归档器；
        # 而 clang 工具链在 /data/service/hnp/bin，PATH 上没有 llvm-ar 时
        # meson configure 直接失败。这里把 ar/ranlib 全路径注入
        # conan_meson_native.ini，不污染 PATH。
        _ce = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict) or {}
        _ar, _rl = _ce.get("ar"), _ce.get("ranlib")
        if not _ar:
            _cc = _ce.get("c") or ""
            _bindir = os.path.dirname(_cc) if os.path.sep in _cc else ""
            if _bindir:
                _cand = os.path.join(_bindir, "llvm-ar")
                if os.path.isfile(_cand):
                    _ar = _cand
                    _rlc = os.path.join(_bindir, "llvm-ranlib")
                    if os.path.isfile(_rlc):
                        _rl = _rlc
        _nf = os.path.join(self.generators_folder, "conan_meson_native.ini")
        if not (_ar and os.path.isfile(_nf)):
            return
        with open(_nf, encoding="utf-8") as _f:
            _c = _f.read()
        if "\nar =" in _c or "[binaries]" not in _c:
            return
        _ins = "[binaries]\nar = '%s'\n" % _ar
        if _rl:
            _ins += "ranlib = '%s'\n" % _rl
        with open(_nf, "w", encoding="utf-8") as _f:
            _f.write(_c.replace("[binaries]\n", _ins, 1))

    def build(self):
        apply_conandata_patches(self)
        meson = Meson(self)
        meson.configure()
        meson.build()
        if cross_building(self):
            self.output.info(
                "cross-building: skip meson.test() (OHOS binaries are not runnable on the build host)"
            )
        else:
            if hasattr(os, "uname") and os.uname().sysname in ("OHOS", "HarmonyOS"):
                build_folder = self.build_folder

                def _ohos_meson_test():
                    self.run(
                        'meson test -v -C "{}" --timeout-multiplier=16 '
                        "--no-rebuild --no-suite=failing".format(build_folder)
                    )

                meson.test = _ohos_meson_test

            meson.test()

    def package(self):
        meson = Meson(self)
        meson.install()
        # 静态构建不产 .la；meson 也不产。防御性清理（与仓内惯例一致）。
        import glob as _glob
        for _la in _glob.glob(os.path.join(self.package_folder, "lib", "*.la")):
            os.remove(_la)

    def package_info(self):
        # 公开头在 include/graphene-1.0；生成头 graphene-config.h 在
        # lib/graphene-1.0/include（meson install 落 libdir/graphene-1.0/include）。
        self.cpp_info.set_property("cmake_file_name", "graphene")
        self.cpp_info.set_property("pkg_config_name", "none")

        # The upstream install has two pkg-config entry points but only one
        # archive: graphene-gobject-1.0.pc is an interface over
        # graphene-1.0.pc. Keep that distinction in Conan components so both
        # names are generated without inventing a second library.
        include_dirs = ["include/graphene-1.0", "lib/graphene-1.0/include"]
        simd_pc_variables = {
            "graphene_has_sse2": "0",
            "graphene_has_gcc": "0",
            "graphene_has_neon": "1",
            "graphene_has_scalar": "1",
        }

        core = self.cpp_info.components["graphene-1.0"]
        core.includedirs = list(include_dirs)
        core.libs = ["graphene-1.0"]
        core.requires = ["glib::gobject-2.0"]
        core.system_libs = ["m", "pthread"]
        core.set_property("cmake_target_name", "graphene::graphene")
        core.set_property("pkg_config_name", "graphene-1.0")
        core.set_property("pkg_config_custom_content", simd_pc_variables)

        gobject = self.cpp_info.components["graphene-gobject-1.0"]
        gobject.includedirs = ["include/graphene-1.0"]
        gobject.libdirs = []
        gobject.libs = []
        gobject.requires = ["graphene-1.0", "glib::gobject-2.0"]
        gobject.set_property("cmake_target_name", "graphene::graphene-gobject")
        gobject.set_property("pkg_config_name", "graphene-gobject-1.0")
        gobject.set_property("pkg_config_custom_content", simd_pc_variables)
