#!/usr/bin/env python3
"""Conan recipe — greg7mdp-gtl 1.2.0 (CMake, header-only).

greg7mdp/gtl ("Greg's Template Library") is a header-only C++ library:
the delivery is `include/gtl/**` only, so `package_type` is
`header-library` and `package_id()` is cleared to a single ID.

The recipe does **not** modify the upstream sources: the upstream test
tree normally downloads googletest at configure time
(`cmake/DownloadGTest.cmake`, pinned to `GIT_TAG main`), which is both
non-reproducible and unusable in an offline CI worker.  Instead the
recipe feeds upstream's own documented opt-out variable
`GTL_GTEST_LIBS` through the toolchain and lets a small CMake fragment
(included through `CMAKE_PROJECT_INCLUDE` right after upstream's
`project(gtl ...)`) resolve those names against the Conan-provided
`gtest/1.17.0.2` package.  `GTL_GTEST_LIBS` being set makes upstream
skip `include(cmake/DownloadGTest.cmake)` entirely, so the downloaded
copy is never fetched and the source tree stays byte-identical to the
release tarball.
"""

import json
import os
import re
from pathlib import Path

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration, ConanException
from conan.tools.build import can_run
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    save,
)

# Included by CMAKE_PROJECT_INCLUDE immediately after upstream's
# project(gtl ...).  It only defines the GoogleTest targets that the
# upstream `gtl_cc_test(... DEPS ${GTL_GTEST_LIBS})` calls link against.
_GTEST_INJECT = """\
# Generated by the greg7mdp-gtl conan recipe (generate()).
# Upstream normally fetches googletest with cmake/DownloadGTest.cmake;
# here the GTest targets come from the conan-provided gtest package.
if(NOT TARGET GTest::gmock_main)
    find_package(GTest CONFIG REQUIRED)
endif()
"""

# Source-level gtest macro declarations (R51 candidate #1).  The
# registered case count is much larger because the typed-test headers
# are instantiated once per element type and several `parallel_*`
# targets re-include a shared test body.
_SOURCE_MACRO_RE = re.compile(
    r"(?m)^[ \t]*(?:TEST|TEST_F|TEST_P|TYPED_TEST|TYPED_TEST_P|TYPED_TEST_F)\s*\("
)

_RAN_RE = re.compile(r"^\[==========\] (\d+) tests? from \d+ test suites? ran\.", re.M)
_PASSED_RE = re.compile(r"^\[  PASSED  \] (\d+) tests?\.$", re.M)
_LISTED_RE = re.compile(r"(?m)^[ \t]+[A-Za-z0-9_]+")


class Greg7mdpGtlConan(ConanFile):
    name = "greg7mdp-gtl"
    version = "1.2.0"
    description = ("greg7mdp/gtl — header-only C++ containers: parallel hash "
                   "maps/sets, btree maps/sets, bit_vector, lru_cache, stopwatch")
    license = "MIT"
    homepage = "https://github.com/greg7mdp/gtl"
    url = "https://github.com/greg7mdp/gtl"
    topics = ("hash-map", "btree", "containers", "header-only")

    package_type = "header-library"
    settings = "os", "arch", "compiler", "build_type"
    no_copy_source = True

    def export_sources(self):
        # No patches are declared (conandata `patches: {}`), so this is a
        # no-op today; it keeps the recipe conformant with the standard
        # export/apply pair used across the archive.
        export_conandata_patches(self)

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                "greg7mdp-gtl is only validated on Linux/OHOS (device-tested there)")

    def build_requirements(self):
        # Test-only dependency: never part of the delivered package graph.
        self.test_requires("gtest/1.17.0.2")

    def layout(self):
        cmake_layout(self)

    def package_id(self):
        self.info.clear()

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)  # conandata `patches: {}` -> no-op

    def generate(self):
        CMakeDeps(self).generate()

        tc = CMakeToolchain(self)
        inject = os.path.join(self.build_folder, "gtl-gtest-inject.cmake")
        save(self, inject, _GTEST_INJECT)
        tc.cache_variables["CMAKE_PROJECT_INCLUDE"] = inject.replace("\\", "/")
        # Upstream skips cmake/DownloadGTest.cmake as soon as this is set.
        tc.cache_variables["GTL_GTEST_LIBS"] = "GTest::gmock_main"
        tc.cache_variables["GTL_BUILD_TESTS"] = "ON"
        tc.cache_variables["GTL_BUILD_EXAMPLES"] = "OFF"
        tc.cache_variables["GTL_BUILD_BENCHMARKS"] = "OFF"
        tc.generate()

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

        if can_run(self):
            self._run_upstream_tests()
        else:
            self.output.info(
                "Cross-building: upstream gtl tests were built but not executed")

    def _run_upstream_tests(self):
        """Run the complete upstream GoogleTest suite and report honest counts.

        Every binary is executed with --gtest_also_run_disabled_tests so that
        the two `DISABLED_*` cases upstream keeps off by default are covered
        too; a non-zero count or a failed case fails the build.
        """
        binaries = {}
        for path in sorted(Path(self.build_folder).rglob("test_*")):
            if path.is_file() and path.name.startswith("test_"):
                binaries.setdefault(path.name, str(path))
        if not binaries:
            raise ConanException(
                "no upstream test binary produced under " + str(self.build_folder))

        per_binary = {}
        registered = 0
        executed = 0
        passed = 0
        for name in sorted(binaries):
            list_out = os.path.join(self.build_folder, name + ".gtest-list.txt")
            self.run(
                f'"{binaries[name]}" --gtest_list_tests > "{list_out}" 2>&1',
                env="conanbuild",
            )
            listed = len(_LISTED_RE.findall(
                Path(list_out).read_text(encoding="utf-8", errors="replace")))
            registered += listed

            run_out = os.path.join(self.build_folder, name + ".gtest.txt")
            self.run(
                f'"{binaries[name]}" --gtest_also_run_disabled_tests'
                f' > "{run_out}" 2>&1; rc=$?; cat "{run_out}"; exit $rc',
                env="conanbuild",
            )
            text = Path(run_out).read_text(encoding="utf-8", errors="replace")
            m_run = _RAN_RE.search(text)
            m_pass = _PASSED_RE.search(text)
            if not m_run or not m_pass:
                raise ConanException(
                    f"cannot parse GoogleTest summary from {name} output")
            run_n, pass_n = int(m_run.group(1)), int(m_pass.group(1))
            if run_n != pass_n:
                raise ConanException(
                    f"{name}: {run_n} tests ran but only {pass_n} passed")
            if run_n != listed:
                raise ConanException(
                    f"{name}: listed {listed} cases but ran {run_n} — "
                    "registered/executed mismatch, refuse to claim a pass")
            per_binary[name] = run_n
            executed += run_n
            passed += pass_n

        declared = 0
        for src in sorted((Path(self.source_folder) / "tests").rglob("*")):
            if src.suffix in (".cpp", ".cc", ".cxx", ".hpp", ".h"):
                declared += len(_SOURCE_MACRO_RE.findall(
                    src.read_text(encoding="utf-8", errors="replace")))

        result = {
            "status": "passed",
            "framework": "gtest",
            "source_macro_total": declared,
            "registered_total": registered,
            "executed": executed,
            "passed": passed,
            "failed": executed - passed,
            "skipped": 0,
            "not_run": registered - executed,
            "binaries": per_binary,
        }
        self.output.info("HMBS_UPSTREAM_TEST_RESULT=" + json.dumps(result, ensure_ascii=False))

    def package(self):
        copy(
            self,
            "*",
            src=os.path.join(self.source_folder, "include"),
            dst=os.path.join(self.package_folder, "include"),
        )
        copy(
            self,
            "LICENSE*",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "licenses"),
            keep_path=False,
        )

    def package_info(self):
        # Mirrors the upstream CMake target name `gtl`
        # (upstream: add_library(gtl INTERFACE)).
        self.cpp_info.set_property("cmake_file_name", "gtl")
        self.cpp_info.set_property("cmake_target_name", "gtl::gtl")
        self.cpp_info.bindirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.libs = []
