#!/usr/bin/env python3
"""Conan recipe — gweather-locations 2026.2 (meson, pure data package)

GNOME locations database consumed by libgweather 4.x through
dependency('gweather-locations') + the pkg-config variable
`locations_db` (Locations.bin). Delivers:

  - lib/gweather-locations/Locations.bin  (GVariant normal form, built
    host-endian -> settings keep os/arch)
  - share/gweather-locations/Locations.xml + locations.dtd
  - share/locale/**/LC_MESSAGES/gweather-locations.mo (gettext)
  - share/pkgconfig/gweather-locations.pc (locations_db/locations_xml/
    locations_dtd variables, matching upstream meson pkgconfig.generate)

Build quirk: Locations.bin is generated by build-aux/gen_locations_variant.py,
which imports `gi.repository.GLib` (PyGObject) purely to construct
GLib.Variant values. PyGObject is not available on the OHOS build host, so
this recipe ships shim/ — a pure-python `gi` package implementing exactly
the GLib.Variant serialisation subset used by the generator (GVariant
normal form, little-endian; nested Variant embedding; dict entries).
PYTHONPATH points at shim/ for both the meson
`find_installation('python3', modules: ['gi'])` probe and the ninja-run
generator. On armv8 the generator's byteswap branch is dead code (upstream
comment), matching the shim's little-endian implementation.

Upstream tests: the tarball has no functional tests; data/meson.build only
conditionally registers lint tests. On hosts with xmllint on PATH the
"Valid Locations file" DTD validation runs for real via Meson.test() in
build() below (pylint stays unregistered when not installed).
"""
import os

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.meson import Meson, MesonToolchain
from conan.tools.files import get


class GweatherLocationsConan(ConanFile):
    name = "gweather-locations"
    version = "2026.2"
    description = "Locations database for libgweather (Locations.bin GVariant data)"
    license = "GPL-2.0-or-later"
    homepage = "https://gitlab.gnome.org/GNOME/gweather-locations"
    # compiler kept in settings only because MesonToolchain requires it;
    # nothing is compiled in this package (Locations.bin is host-endian
    # data, so os/arch still matter).
    settings = "os", "arch", "compiler", "build_type"
    exports_sources = "shim/gi/*.py"

    def layout(self):
        self.folders.source = "."
        self.folders.build = "build"

    def generate(self):
        tc = MesonToolchain(self)
        tc.generate()

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        shim = os.path.join(self.source_folder, "shim")
        if not os.path.isdir(os.path.join(shim, "gi")):
            raise ConanException("bundled gi shim missing from source folder")
        env = os.environ
        env["PYTHONPATH"] = shim + os.pathsep + env.get("PYTHONPATH", "")
        # meson backend: pin NINJA at the absolute path (OHOS musl python
        # subprocess cannot resolve bare-name PATH lookups for the hnp ninja
        # symlink; geocode-glib/3.26.4 precedent) and give the probe
        # /system/lib64 for libc++_shared.so.
        _ninja = "/storage/Users/currentUser/usr/local/bin/ninja"
        if not os.path.isfile(_ninja):
            _ninja = "/data/service/hnp/bin/ninja"
        if os.path.isfile(_ninja):
            env.setdefault("NINJA", _ninja)
        env["LD_LIBRARY_PATH"] = "/system/lib64" + os.pathsep + env.get("LD_LIBRARY_PATH", "")
        meson = Meson(self)
        meson.configure()
        meson.build()
        # Upstream test suite (lint-only, conditionally registered):
        # runs "Valid Locations file" (xmllint --valid against the bundled
        # locations.dtd) when xmllint is on PATH; no-op exit 0 otherwise.
        meson.test()

    def package(self):
        Meson(self).install()

    def package_info(self):
        # Data-only package: nothing on link/include surfaces, but keep the
        # default libdir/includedir entries so PkgConfigDeps emits a
        # standard-shaped gweather-locations.pc (libdir/datadir variable
        # lines) — pkg-config rejects pc files referencing undefined
        # variables, and libgweather's meson parses this one.
        self.cpp_info.set_property("pkg_config_name", "gweather-locations")
