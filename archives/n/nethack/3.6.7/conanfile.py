#!/usr/bin/env python3
"""Conan recipe — NetHack 3.6.7 (terminal roguelike, pure Makefile build).

NetHack 使用 sys/unix/setup.sh 从 hints 文件生成顶层与各子目录 Makefile，
然后 make 构建。OHOS 适配要点：
- 自研 hints 文件：tty + curses 图形界面，链接仓库自带的 ncurses/6.6
  （wide-char 静态库，-lncursesw），不依赖系统 ncurses/tinfo
- 关闭 setuid/games 安装逻辑（CHOWN/CHGRP=true），不生成 setgid 二进制
- 手动打包 src/nethack + dat 数据 + util/recover，避免上游 make install
  直接写入 HACKDIR（其不支持 DESTDIR 且会 rm -rf 安装目录）
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class NethackConan(ConanFile):
    name = "nethack"
    version = "3.6.7"
    description = "NetHack single-player roguelike dungeon exploration game"
    license = "Nethack General Public License"
    homepage = "https://www.nethack.org/"
    url = "https://www.nethack.org/"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("ncurses/6.6")

    def layout(self):
        basic_layout(self, src_folder="src")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _dep_flags(self):
        cppflags = []
        ldflags = []
        for dep in self.dependencies.values():
            if dep.package_folder is None:
                continue
            for include_dir in dep.cpp_info.includedirs:
                cppflags.append(f"-I{include_dir}")
            for lib_dir in dep.cpp_info.libdirs:
                ldflags.append(f"-L{lib_dir}")
        return " ".join(cppflags), " ".join(ldflags)

    def _write_hints(self):
        cppflags, ldflags = self._dep_flags()
        hints = f"""# NetHack 3.6.7 OHOS PC hints (generated by conan recipe)
#-PRE
# tty + curses build, links the packaged ncurses/6.6 (wide-char static lib)
PREFIX=/usr
HACKDIR=$(PREFIX)/share/nethack
SHELLDIR=$(PREFIX)/bin
INSTDIR=$(PREFIX)/share/nethack
VARDIR=$(PREFIX)/share/nethack

CFLAGS=-std=gnu89 -g -O2 -I../include -DNOTPARMDECL {cppflags}
CFLAGS+=-DSYSCF -DSYSCF_FILE=\\"$(HACKDIR)/sysconf\\" -DSECURE
CFLAGS+=-DTIMED_DELAY
CFLAGS+=-DHACKDIR=\\"$(HACKDIR)\\"
CFLAGS+=-DDUMPLOG
CFLAGS+=-DCONFIG_ERROR_SECURE=FALSE
CFLAGS+=-DCURSES_GRAPHICS

LINK=$(CC)
LFLAGS=

WINSRC = $(WINTTYSRC) $(WINCURSESSRC)
WINOBJ = $(WINTTYOBJ) $(WINCURSESOBJ)
WINLIB = $(WINTTYLIB) $(WINCURSESLIB)

CHOWN=true
CHGRP=true

VARDIRPERM = 0755
VARFILEPERM = 0600
GAMEPERM = 0755
#-POST
WINTTYLIB=-lncursesw {ldflags}
WINCURSESLIB=-lncursesw {ldflags}
"""
        hints_path = os.path.join(
            self.source_folder, "sys", "unix", "hints", "ohos-conan"
        )
        with open(hints_path, "w", encoding="utf-8") as handle:
            handle.write(hints)

    def build(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")
        self._write_hints()
        setup = os.path.join(self.source_folder, "sys", "unix", "setup.sh")
        self.run(
            f'sh "{setup}" "sys/unix/hints/ohos-conan"',
            cwd=self.source_folder,
            env="conanbuild",
        )
        self.run("make -j1", cwd=self.source_folder, env="conanbuild")

    def package(self):
        src = self.source_folder
        copy(self, "nethack", os.path.join(src, "src"), os.path.join(self.package_folder, "bin"))
        copy(self, "recover", os.path.join(src, "util"), os.path.join(self.package_folder, "bin"))
        copy(self, "*", os.path.join(src, "dat"), os.path.join(self.package_folder, "share", "nethack"))
        copy(self, "sysconf", os.path.join(src, "sys", "unix"), os.path.join(self.package_folder, "share", "nethack"))
        copy(self, "license", src, os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.resdirs = ["share"]