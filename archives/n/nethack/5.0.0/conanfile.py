#!/usr/bin/env python3
"""Conan recipe — NetHack 5.0.0 (terminal roguelike, pure Makefile build).

NetHack uses sys/unix/setup.sh from a hints file to generate top-level and
per-directory Makefiles, then make builds. OHOS adaptation notes:
- Derive hints from upstream sys/unix/hints/linux.500 (HINTSVERSION 500),
  forcing tty + curses window ports with curses default, linking the
  packaged ncurses/6.6 (wide-char static lib, -lncursesw) instead of the
  system ncurses/tinfo.
- Use packaged lua/5.4.8 as system Lua (WANT_SYSTEM_LUA equivalent):
  LUACFLAGS/LUALIBS/LUAHEADERS point at the conan package, LUATOPLIB empty
  so the bundled lib/lua build and `make fetch-lua` network fetch are
  skipped. NetHack 5.0 requires Lua 5.4.8 (see Makefile.top LUA_VERSION).
- Disable setuid/games install logic (CHOWN/CHGRP=true), no setgid binary.
- Manual packaging of src/nethack + dat playground + util/recover, avoiding
  upstream `make install` which supports no DESTDIR and would rm -rf HACKDIR.
"""

import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import copy, export_conandata_patches, get
from conan.tools.layout import basic_layout


class NethackConan(ConanFile):
    name = "nethack"
    version = "5.0.0"
    description = "NetHack single-player roguelike dungeon exploration game"
    license = "Nethack General Public License"
    homepage = "https://www.nethack.org/"
    url = "https://www.nethack.org/"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("ncurses/6.6")
        self.requires("lua/5.4.8")

    def layout(self):
        basic_layout(self, src_folder="src")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _dep_info(self, dep_name):
        dep = self.dependencies[dep_name]
        pkg = dep.package_folder
        incs = []
        libs = []
        if pkg is not None:
            for d in dep.cpp_info.includedirs:
                incs.append("-I{}".format(d))
            for d in dep.cpp_info.libdirs:
                libs.append("-L{}".format(d))
        return pkg, " ".join(incs), " ".join(libs)

    def _lua_lib_file(self):
        dep = self.dependencies["lua"]
        for libdir in dep.cpp_info.libdirs:
            for cand in (
                os.path.join(libdir, "liblua.a"),
                os.path.join(libdir, "liblua.so"),
                os.path.join(libdir, "lua.lib"),
            ):
                if os.path.isfile(cand):
                    return cand
        # Fall back to -llua link name resolved via libdirs at link time.
        return None

    def _write_hints(self):
        lua_pkg, lua_inc, lua_lib = self._dep_info("lua")
        curs_pkg, curs_inc, curs_lib = self._dep_info("ncurses")
        if lua_pkg is None or curs_pkg is None:
            raise ConanInvalidConfiguration("lua/ncurses package folder missing")
        lua_include_dir = None
        for cand in self.dependencies["lua"].cpp_info.includedirs:
            if os.path.isfile(os.path.join(cand, "lua.h")):
                lua_include_dir = cand
                break
        if lua_include_dir is None:
            raise ConanInvalidConfiguration("lua.h not found in lua package")
        linux_hints = os.path.join(
            self.source_folder, "sys", "unix", "hints", "linux.500"
        )
        with open(linux_hints, "r", encoding="utf-8") as handle:
            base = handle.read()
        # Force tty + curses window ports before multiw-2.500 evaluates them.
        # linux.500 leaves all WANT_WIN_* commented (defaults to tty only).
        marker = "#-INCLUDE multiw-2.500"
        force_win = "WANT_WIN_TTY=1\nWANT_WIN_CURSES=1\nWANT_DEFAULT=curses\n"
        if marker in base and "WANT_WIN_CURSES=1" not in base.split(marker)[0]:
            base = base.replace(marker, force_win + marker)
        else:
            base = force_win + base
        lua_lib_file = self._lua_lib_file()
        # TOPLUALIB is the top-Makefile variable that pulls the bundled
        # lib/lua build (via $(LUATOP)/liblua.a). Point it at the conan
        # lua archive when available; the post-setup patch below additionally
        # stubs the bundled build rules so no network fetch-lua is needed.
        if lua_lib_file is None:
            toplualib = "{} -llua".format(lua_lib)
        else:
            toplualib = lua_lib_file
        post = (
            "\n# --- OHOS conan overrides (generated by recipe, POST wins) ---\n"
            "PREFIX=/usr\n"
            "HACKDIR=$(PREFIX)/share/nethack\n"
            "SHELLDIR=$(PREFIX)/bin\n"
            "INSTDIR=$(PREFIX)/share/nethack\n"
            "VARDIR=$(PREFIX)/share/nethack\n"
            "MANDIR=$(PREFIX)/share/man/man6\n"
            "CHOWN=true\n"
            "CHGRP=true\n"
            "GAMEPERM = 0755\n"
            "VARFILEPERM = 0600\n"
            "VARDIRPERM = 0755\n"
            "LUACFLAGS = {}\n".format(lua_inc)
            + "LUAHEADERS = {}\n".format(lua_include_dir)
            + "LUATESTTARGET = {}/lua.h\n".format(lua_include_dir)
            + "LUATOP = {}\n".format(lua_include_dir)
            + "TOPLUALIB = {}\n".format(toplualib)
            + "LUALIB = {}\n".format(toplualib)
            + "LUALIBS = {} -llua -lm -ldl\n".format(lua_lib)
            + "LUAHPREFIX=\n"
            + "LUALIBBUILT=\n"
            + "CFLAGS += $(LUACFLAGS)\n"
            + "NCURSES_CFLAGS = {} -D_DEFAULT_SOURCE -D_XOPEN_SOURCE=600\n".format(curs_inc)
            + "CURSESLIB = {} -lncursesw\n".format(curs_lib)
            + "CFLAGS += {} {}\n".format(lua_inc, curs_inc)
            + "LFLAGS += {} {}\n".format(lua_lib, curs_lib)
            + "# OHOS: no glibc execinfo.h/backtrace, no xdg-open/gdb; "
            "disable crash-report stacktrace (config.h enables it on __linux__)\n"
            + "CFLAGS += -DNOCRASHREPORT -DNOPANICTRACE\n"
            + "CCXXFLAGS += -DNOCRASHREPORT -DNOPANICTRACE\n"
        )
        hints_path = os.path.join(
            self.source_folder, "sys", "unix", "hints", "ohos-conan"
        )
        with open(hints_path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(base + post)

    def _patch_system_lua(self):
        # Bypass the bundled lib/lua-5.4.8 build without network fetch-lua.
        # Generated top Makefile chain:
        #   $(GAME) -> lua_support -> include/nhlua.h -> $(TOPLUALIB)
        #   -> $(LUATOP)/liblua.a -> $(LUAHEADERS)/lua.h (fallback: fetch-lua)
        # With system lua we pre-generate include/nhlua.h from the conan
        # headers and drop the bundled prerequisites so make never touches
        # lib/lua-5.4.8. src/Makefile LUALIB/LUALIBS are pointed at conan lua.
        lua_inc_dir = None
        for cand in self.dependencies["lua"].cpp_info.includedirs:
            if os.path.isfile(os.path.join(cand, "lua.h")):
                lua_inc_dir = cand
                break
        if lua_inc_dir is None:
            return
        lua_lib_file = self._lua_lib_file()
        _, lua_inc, lua_lib = self._dep_info("lua")

        nhlua = os.path.join(self.source_folder, "include", "nhlua.h")
        try:
            with open(nhlua, "w", encoding="utf-8", newline="\n") as handle:
                handle.write("/* nhlua.h - generated by conan recipe (system lua) */\n")
                handle.write('#include "{}/lua.h"\n'.format(lua_inc_dir))
                with open(os.path.join(lua_inc_dir, "lua.h"), "r",
                           encoding="utf-8", errors="replace") as src:
                    for line in src:
                        if "(lua_error)" in line:
                            fixed = line.replace("LUA_API", "ATTRNORETURN LUA_API", 1)
                            fixed = fixed.replace(";", " NORETURN;", 1)
                            handle.write(fixed)
                            break
                handle.write('#include "{}/lualib.h"\n'.format(lua_inc_dir))
                handle.write('#include "{}/lauxlib.h"\n'.format(lua_inc_dir))
                handle.write("/*nhlua.h*/\n")
        except OSError:
            pass

        top_mk = os.path.join(self.source_folder, "Makefile")
        if os.path.isfile(top_mk):
            with open(top_mk, "r", encoding="utf-8", errors="replace") as handle:
                text = handle.read()
            # include/nhlua.h must not depend on the bundled TOPLUALIB.
            text = text.replace("include/nhlua.h: $(TOPLUALIB)",
                                "include/nhlua.h:")
            # Neutralize bundled lua archive build rules if present.
            text = text.replace("$(LUATOP)/liblua.a: $(LUAHEADERS)/lua.h",
                                "__ohos_bundled_lua_disabled__: ; @true\n"
                                "# disabled: $(LUATOP)/liblua.a: $(LUAHEADERS)/lua.h")
            text = text.replace("$(TOPLUALIB): $(LUATOP)/liblua.a",
                                "__ohos_toplualib_disabled__: ; @true\n"
                                "# disabled: $(TOPLUALIB): $(LUATOP)/liblua.a")
            with open(top_mk, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)

        src_mk = os.path.join(self.source_folder, "src", "Makefile")
        if os.path.isfile(src_mk):
            with open(src_mk, "r", encoding="utf-8", errors="replace") as handle:
                stext = handle.read()
            if lua_lib_file is not None:
                import re
                stext = re.sub(r"(?m)^LUALIB\s*=.*$",
                               "LUALIB = {}".format(lua_lib_file), stext)
                stext = re.sub(r"(?m)^LUALIBS\s*=.*$",
                               "LUALIBS = {} -lm -ldl".format(lua_lib_file), stext)
            with open(src_mk, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(stext)

    def _compiler_exe(self, kind, default):
        # conan 2.x: tools.build:compiler_executables is a dict
        # ({"c": ..., "cpp": ...}); the ":c"/":cpp" suffixed lookup is not a
        # registered conf and raises on some versions when unset, so probe
        # tolerantly and fall back to buildenv CC/CXX then plain defaults
        # (HMBS puts the OHOS toolchain on PATH).
        try:
            exes = self.conf.get("tools.build:compiler_executables")
        except Exception:
            exes = None
        if isinstance(exes, dict) and exes.get(kind):
            return exes[kind]
        env_key = "CC" if kind == "c" else "CXX"
        return os.environ.get(env_key, default)

    def build(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("Unsupported OS: {}".format(self.settings.os))
        self._write_hints()
        setup = os.path.join(self.source_folder, "sys", "unix", "setup.sh")
        self.run(
            'sh "{}" "sys/unix/hints/ohos-conan"'.format(setup),
            cwd=self.source_folder,
            env="conanbuild",
        )
        self._patch_system_lua()
        cc = self._compiler_exe("c", "clang")
        cxx = self._compiler_exe("cpp", "clang++")
        self.run(
            "make -j1 CC={} CXX={} WANT_WIN_TTY=1 WANT_WIN_CURSES=1 WANT_DEFAULT=curses".format(cc, cxx),
            cwd=self.source_folder,
            env="conanbuild",
        )

    def package(self):
        src = self.source_folder
        copy(self, "nethack", os.path.join(src, "src"), os.path.join(self.package_folder, "bin"))
        copy(self, "recover", os.path.join(src, "util"), os.path.join(self.package_folder, "bin"))
        copy(self, "*", os.path.join(src, "dat"), os.path.join(self.package_folder, "share", "nethack"))
        copy(self, "sysconf", os.path.join(src, "sys", "unix"), os.path.join(self.package_folder, "share", "nethack"))
        copy(self, "license", src, os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.resdirs = ["share"]
