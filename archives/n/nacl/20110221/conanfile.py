import glob
import os
from conan import ConanFile
from conan.errors import ConanException
from conan.tools.build import can_run
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get


class NaclConan(ConanFile):
    name = "nacl"
    version = "20110221"
    description = ("Networking and Cryptography library (NaCl): public-domain "
                   "high-level crypto - box, secretbox, sign, hash, onetimeauth, "
                   "scalarmult, stream, verify")
    homepage = "https://nacl.cr.yp.to"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    license = "Unlicense"
    package_type = "static-library"
    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        export_conandata_patches(self)

    def _source_entry(self):
        return self.conan_data["sources"][self.version][0]

    def source(self):
        get(self, **self._source_entry(), strip_root=True)

    def _compilers(self):
        exes = self.conf.get("tools.build:compiler_executables", default={}, check_type=dict)
        return exes.get("c") or "clang", exes.get("cpp") or "clang++"

    def _top(self):
        """Locate build/<shorthostname>/ that './do' creates; the abi subdir is chosen by
        upstream's own compiler probe (okcompilers maps OHOS aarch64 to 'default')."""
        hits = glob.glob(os.path.join(self.source_folder, "build", "*", "lib", "*", "libnacl.a"))
        if not hits:
            raise ConanException("upstream './do' produced no build/*/lib/*/libnacl.a")
        abidir = os.path.dirname(hits[0])
        top = os.path.dirname(os.path.dirname(abidir))
        return top, abidir, os.path.basename(abidir)

    def _archiver(self, top, abi):
        script = os.path.join(top, "bin", "okar-%s" % abi)
        try:
            with open(script, encoding="utf-8") as handle:
                lines = [line for line in handle.read().splitlines() if '"$@"' in line]
            return lines[-1].split(' "$@"')[0].strip()
        except OSError:
            return "ar"

    def _report_try(self, top):
        """'./do' self-checks every implementation against upstream's own checksum files
        before it is allowed into libnacl.a; report that verdict instead of dropping it."""
        data = os.path.join(top, "data")
        ok = mismatch = unknown = rejected = 0
        try:
            with open(data, encoding="utf-8") as handle:
                rows = handle.read().splitlines()
        except OSError:
            self.output.warning("no ./do data file, cannot report per-implementation self-checks")
            return
        for row in rows:
            fields = row.split()
            if "try" not in fields:
                continue
            index = fields.index("try")
            if len(fields) <= index + 2:
                continue
            verdict = fields[index + 2]
            if verdict == "ok":
                ok += 1
            elif verdict == "fails":
                mismatch += 1
            else:
                unknown += 1
        rejected = sum(1 for row in rows if "tryfails" in row.split())
        self.output.info("N5525_TRY selfcheck_ok=%d selfcheck_mismatch=%d "
                         "selfcheck_unknown=%d build_or_run_rejected=%d"
                         % (ok, mismatch, unknown, rejected))

    def _test_driver(self, top, abi):
        cc, cxx = self._compilers()
        inc = os.path.join(top, "include")
        incabi = os.path.join(inc, abi)
        abidir = os.path.join(top, "lib", abi)
        out = os.path.join(self.build_folder, "upstream_tests")
        objs = " ".join(os.path.join(abidir, "%s.o" % name)
                        for name in ("cpucycles", "randombytes")
                        if os.path.isfile(os.path.join(abidir, "%s.o" % name)))
        lines = [
            "#!/bin/sh",
            "# Generated by conanfile.py. Builds and runs upstream's tests/ suite the same",
            "# way ./do does (libnacl.a + in-tree cpucycles/randombytes objects) and writes",
            "# each program's stdout to <name>.got for a byte-exact comparison in python.",
            "# Paths here carry no spaces, so nothing is quoted inside variable expansions.",
            'SRC="%s"' % self.source_folder,
            'OUT="%s"' % out,
            'LIB="%s"' % os.path.join(abidir, "libnacl.a"),
            # Multi-word assignments must stay quoted: an unquoted "V=a b" line is parsed
            # by POSIX sh as an assignment followed by a *command*.
            'OBJS="%s"' % objs,
            'CC="%s"' % cc,
            'CXX="%s"' % cxx,
            'INCS="-I%s -I%s"' % (inc, incabi),
            'mkdir -p "$OUT"',
            'for f in "$SRC"/tests/*.c "$SRC"/tests/*.cpp; do',
            '  [ -f "$f" ] || continue',
            '  n=`basename "$f"`; n=`echo "$n" | sed \'s/\\.\\(c\\|cpp\\)$//\'`',
            '  case "$f" in',
            '    *.cpp) c="$CXX";;',
            '    *) c="$CC";;',
            '  esac',
            '  if ! $c $INCS -o "$OUT/$n" "$f" "$LIB" $OBJS -lm > "$OUT/$n.build" 2>&1; then',
            '    echo "N5525_TEST $n NOLINK"',
            '    continue',
            '  fi',
            '  "$OUT/$n" > "$OUT/$n.got" 2>&1',
            '  echo "N5525_TEST $n RAN rc=$?"',
            'done > "$OUT/results.txt"',
        ]
        return "\n".join(lines) + "\n", out, os.path.join(out, "results.txt")

    def build(self):
        apply_conandata_patches(self)
        if not os.path.isfile(os.path.join(self.source_folder, "do")):
            # conan may reuse an already-populated source folder without calling source()
            get(self, **self._source_entry(), strip_root=True)
            apply_conandata_patches(self)
        # './do' is upstream's whole pipeline: compiler probe, per-implementation build,
        # self-check against the shipped checksum files, libnacl.a, then tests/ and
        # commandline/. It reports failures in its log but still exits 0, so nothing here
        # trusts the return code.
        self.run("sh do", cwd=self.source_folder, env="conanbuild")
        top, abidir, abi = self._top()
        self.output.info("N5525_TOP %s abi=%s" % (top, abi))
        self._report_try(top)
        if not can_run(self):
            self.output.warning("not running on build host, upstream tests/ skipped")
            return
        driver, outdir, results = self._test_driver(top, abi)
        script = os.path.join(self.build_folder, "n5525_upstream_tests.sh")
        with open(script, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(driver)
        self.run('sh "%s"' % script, cwd=self.source_folder, env="conanbuild")
        with open(results, encoding="utf-8") as handle:
            report = handle.read()
        passed, failed, nolink = 0, [], []
        for line in report.splitlines():
            fields = line.split()
            if len(fields) < 3 or fields[0] != "N5525_TEST":
                continue
            name, state = fields[1], fields[2]
            if state == "NOLINK":
                nolink.append(name)
                continue
            with open(os.path.join(outdir, "%s.got" % name), "rb") as handle:
                got = handle.read()
            with open(os.path.join(self.source_folder, "tests", "%s.out" % name), "rb") as handle:
                want = handle.read()
            if got == want and fields[3] == "rc=0":
                passed += 1
            else:
                failed.append("%s(got=%dB want=%dB %s)"
                              % (name, len(got), len(want), fields[3]))
        self.output.info("N5525_UPSTREAM_TESTS runnable=%d pass=%d fail=%d nolink=%d"
                         % (passed + len(failed), passed, len(failed), len(nolink)))
        for name in nolink:
            buildlog = os.path.join(outdir, "%s.build" % name)
            reason = ""
            try:
                with open(buildlog, encoding="utf-8") as handle:
                    for line in handle:
                        if "error" in line or "undefined" in line:
                            reason = line.strip()
                            break
            except OSError:
                pass
            self.output.info("N5525_NOLINK %s %s" % (name, reason))
        if failed:
            raise ConanException("upstream tests failed: %s" % " ".join(failed))
        if passed == 0:
            raise ConanException("upstream tests/ built but none ran - './do' selected no "
                                 "implementation for any primitive")

    def package(self):
        top, abidir, abi = self._top()
        libdir = os.path.join(self.package_folder, "lib")
        incdir = os.path.join(self.package_folder, "include", "nacl")
        copy(self, "libnacl.a", abidir, libdir)
        # ./do links every consumer as "libnacl.a cpucycles.o randombytes.o -lm"; both
        # objects come from nacl's own tree, so they are folded into the delivered archive
        # and a consumer only ever needs -lnacl.
        objs = [os.path.join(abidir, "%s.o" % name) for name in ("randombytes", "cpucycles")
                if os.path.isfile(os.path.join(abidir, "%s.o" % name))]
        if not objs:
            raise ConanException("cpucycles.o/randombytes.o missing from %s" % abidir)
        quoted = " ".join('"%s"' % obj for obj in objs)
        self.run('%s rcs "%s" %s' % (self._archiver(top, abi),
                                     os.path.join(libdir, "libnacl.a"), quoted),
                 env="conanbuild")
        copy(self, "*.h", os.path.join(top, "include"), incdir)
        copy(self, "*.h", os.path.join(top, "include", abi), incdir)

    def package_info(self):
        self.cpp_info.includedirs = ["include", "include/nacl"]
        self.cpp_info.libs = ["nacl"]
        self.cpp_info.system_libs = ["m"]
