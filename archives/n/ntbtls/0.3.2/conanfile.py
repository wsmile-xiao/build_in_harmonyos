#!/usr/bin/env python3
"""Conan recipe for ntbtls 0.3.2 on OHOS arm64."""

import os
import stat

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import apply_conandata_patches, collect_libs, export_conandata_patches, get, rm
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class NtbtlsConan(ConanFile):
    name = "ntbtls"
    version = "0.3.2"
    description = "Not Too Bad TLS library - the TLS backend of the GnuPG stack"
    license = "GPL-3.0-or-later"
    homepage = "https://gnupg.org/software/ntbtls/"
    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if str(self.settings.os) != "OHOS" or str(self.settings.arch) != "armv8":
            raise ConanInvalidConfiguration("ntbtls recipe supports OHOS armv8 only")

    def requirements(self):
        # GnuPG family stack: gpg-error (runtime + estream), libgcrypt (crypto)
        # and libksba (X.509) are unconditional build and link dependencies.
        self.requires("libgpg-error/1.55", transitive_headers=True, transitive_libs=True)
        self.requires("libgcrypt/1.12.2", transitive_headers=True, transitive_libs=True)
        self.requires("libksba/1.6.7.1", transitive_headers=True, transitive_libs=True)
        # configure.ac advertises zlib as optional ("--with-zlib"), but
        # src/context.h includes <zlib.h> unconditionally and embeds z_stream
        # members, and src/protocol.c compares against Z_OK.  The header is a
        # hard compile dependency, so zlib is a real requirement.
        self.requires("zlib/1.3.2")

    def layout(self):
        basic_layout(self, src_folder=".")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    # ------------------------------------------------------------------ #
    # Dependency config scripts / libtool archives need repairs         #
    # ------------------------------------------------------------------ #
    def _overrides_dir(self):
        return os.path.join(self.build_folder, "config-overrides")

    def _write_config_script(self, path, version, package_folder, libname, api_version=None):
        """Write a minimal *-config replacement for a Conan dependency."""
        lines = [
            "#!/bin/sh",
            "while [ $# -gt 0 ]; do",
            '  case "$1" in',
            '    --version|--modversion) echo "%s"; exit 0 ;;' % version,
        ]
        if api_version is not None:
            lines.append('    --api-version) echo "%s"; exit 0 ;;' % api_version)
        lines += [
            '    --cflags) echo "-I%s/include"; exit 0 ;;' % package_folder,
            '    --libs) echo "-L%s/lib -l%s"; exit 0 ;;' % (package_folder, libname),
            '    --host) echo "aarch64-unknown-linux-ohos"; exit 0 ;;',
            "    --mt) shift ;;",
            "  esac",
            "  shift",
            "done",
            "exit 0",
            "",
        ]
        with open(path, "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines))
        os.chmod(path, 0o755)

    def _write_libtool_archive(self, path, dlname, library_names, version_info,
                               libdir, dependency_libs):
        """Rewrite a dependency .la whose dependency_libs point at //lib."""
        current, age, revision = version_info
        with open(path, "w", encoding="utf-8") as handle:
            # The '# Generated by ... <PACKAGE>' line must stay within the
            # first four lines: libtool's func_lalib_unsafe_p only accepts a
            # .la file when it finds it.
            handle.write(
                "# %s - a libtool library file\n"
                "# Generated by libtool (GNU libtool) 2.4.7\n"
                "# Repaired for OHOS: the published GnuPG packages were configured\n"
                "# with --prefix=/, so their .la files reference //lib and the\n"
                "# non-existent //lib/libgpg-error.la, which makes libtool abort\n"
                "# with 'is not a valid libtool archive'.\n"
                "dlname='%s'\n"
                "library_names='%s'\n"
                "old_library=''\n"
                "inherited_linker_flags=''\n"
                "dependency_libs='%s'\n"
                "weak_library_names=''\n"
                "current=%d\nage=%d\nrevision=%d\n"
                "installed=yes\nshouldnotlink=no\n"
                "dlopen=''\ndlpreopen=''\n"
                "libdir='%s'\n"
                % (os.path.basename(path), dlname, library_names,
                   dependency_libs, current, age, revision, libdir)
            )

    def _prepare_config_overrides(self):
        gpg_error = self.dependencies["libgpg-error"].package_folder
        libgcrypt = self.dependencies["libgcrypt"].package_folder
        libksba = self.dependencies["libksba"].package_folder
        overrides = self._overrides_dir()
        os.makedirs(os.path.join(overrides, "bin"), exist_ok=True)
        os.makedirs(os.path.join(overrides, "lib"), exist_ok=True)

        # 1) *-config replacements.
        #    libgpg-error 1.55 no longer installs gpg-error-config at all, and
        #    its successor gpgrt-config is unusable with a Conan layout: when
        #    the --libdir it is given does not contain the queried .pc file it
        #    re-executes itself, so `gpgrt-config --libdir=<lib> gpg-error
        #    --libs` never returns.  The shipped libgcrypt-config/ksba-config
        #    do return, but they report -I//include / -L//lib because their
        #    package was configured with --prefix=/.
        #    API versions are the ones ntbtls' configure.ac requires
        #    (NEED_LIBGCRYPT_API=1, NEED_KSBA_API=1) and match the api_version
        #    recorded in the corresponding .pc files.
        self._write_config_script(
            os.path.join(overrides, "bin", "gpg-error-config"),
            str(self.dependencies["libgpg-error"].ref.version), gpg_error, "gpg-error")
        self._write_config_script(
            os.path.join(overrides, "bin", "libgcrypt-config"),
            str(self.dependencies["libgcrypt"].ref.version), libgcrypt, "gcrypt", "1")
        self._write_config_script(
            os.path.join(overrides, "bin", "ksba-config"),
            str(self.dependencies["libksba"].ref.version), libksba, "ksba", "1")

        # 2) Repaired libtool archives.  libgcrypt's package ships no .la.
        self._write_libtool_archive(
            os.path.join(overrides, "lib", "libgpg-error.la"),
            "libgpg-error.so.0",
            "libgpg-error.so.0.39.3 libgpg-error.so.0 libgpg-error.so",
            (39, 39, 3), os.path.join(gpg_error, "lib"), "")
        self._write_libtool_archive(
            os.path.join(overrides, "lib", "libksba.la"),
            "libksba.so.8",
            "libksba.so.8.14.7 libksba.so.8 libksba.so",
            (22, 14, 7), os.path.join(libksba, "lib"),
            " -L%s/lib -lgpg-error" % gpg_error)

    def generate(self):
        self._prepare_config_overrides()
        deps = AutotoolsDeps(self)
        deps.generate()
        tc = AutotoolsToolchain(self)
        # --build is explicit on purpose: config.guess probes with mktemp and
        # fails on HMDFS ("unable to guess system type").  --host is still
        # canonicalized by config.sub, hence the HarmonyOS triplet patch.
        tc.configure_args.extend([
            "--build=aarch64-unknown-linux-gnu",
            "--host=aarch64-unknown-linux-ohos",
        ])
        tc.generate()
        overrides = self._overrides_dir()
        env = Environment()
        env.define_path("GPG_ERROR_CONFIG", os.path.join(overrides, "bin", "gpg-error-config"))
        env.define_path("LIBGCRYPT_CONFIG", os.path.join(overrides, "bin", "libgcrypt-config"))
        env.define_path("KSBA_CONFIG", os.path.join(overrides, "bin", "ksba-config"))
        # Keep the GnuPG m4 macros away from gpgrt-config.
        env.define("ac_cv_path_GPGRT_CONFIG", "no")
        # The repaired .la files must win over the published ones.
        env.prepend("LDFLAGS", "-L%s" % os.path.join(overrides, "lib"))
        env.vars(self, scope="build").save_script("conanbuild_runpath")

    def build(self):
        apply_conandata_patches(self)
        for relative in ("configure", "build-aux/config.guess", "build-aux/config.sub",
                         "build-aux/install-sh", "build-aux/missing"):
            path = os.path.join(self.source_folder, relative)
            if os.path.exists(path):
                os.chmod(path, os.stat(path).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        tmpdir = os.path.join(self.build_folder, "tmp")
        os.makedirs(tmpdir, exist_ok=True)
        os.environ["TMPDIR"] = tmpdir
        configure = os.path.join(self.source_folder, "configure")
        if os.path.exists(configure):
            with open(configure, encoding="utf-8") as handle:
                content = handle.read()
            content = content.replace("umask 077", "umask 022")
            with open(configure, "w", encoding="utf-8") as handle:
                handle.write(content)
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])

    def package(self):
        Autotools(self).install()
        # Build-machine specific libtool archives are useless to consumers.
        rm(self, "*.la", os.path.join(self.package_folder, "lib"))

    def package_info(self):
        self.cpp_info.libs = collect_libs(self) or ["ntbtls"]
        self.cpp_info.set_property("cmake_file_name", "ntbtls")
        self.cpp_info.set_property("cmake_target_name", "ntbtls::ntbtls")
        self.cpp_info.set_property("pkg_config_name", "ntbtls")
