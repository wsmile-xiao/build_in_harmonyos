#!/usr/bin/env python3
"""Conan recipe -- wandio 4.2.7 (direct build, no autotools).

Upstream's GitHub tag archive ships configure.ac + Makefile.am only (no
generated configure), and bootstrapping it on-device is not viable here:
it needs the full autotools suite plus a working perl and bash, while the
HarmonyOS build hosts provide none of them. The autoconf tool_require
pulls in m4, whose own configure re-execs $CONFIG_SHELL
(/data/service/hnp/bin/bash) -- a path that does not exist inside the
build sandbox, so even the toolchain fails to build (m4/1.4.19 configure
Error 127, preflight 2026-09-25).

Like cbm/0.4-1 ("Direct compilation bypassing autotools"), this recipe
therefore compiles the portable core directly with the Conan C compiler.
The source set mirrors lib/Makefile.am with every optional-backend
conditional empty (all --without-* equivalents):

  lib: wandio.c ior-peek.c ior-stdio.c ior-thread.c iow-stdio.c iow-thread.c
  tool: tools/wandiocat/wcat.c (links libwandio)

A minimal config.h (every HAVE_LIB*/HAVE_HTTP/HAVE_SYS_PRCTL_H = 0, plus
the WANDIO 4.2.7 version macros) is generated into the build folder. The
conditionals in wandio.c then degrade to the stdio fallback, exactly like
an upstream ./configure run with all backends disabled.
"""

import glob
import os
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import copy, export_conandata_patches, get
from conan.tools.layout import basic_layout

# Portable core: lib/Makefile.am with every HAVE_* conditional empty.
_LIB_SOURCES = [
    "wandio.c",
    "ior-peek.c",
    "ior-stdio.c",
    "ior-thread.c",
    "iow-stdio.c",
    "iow-thread.c",
]

# Mirrors what upstream configure would emit for a
# --without-bzip2/zlib/lzo/lzma/zstd/lz4/qatzip/http build on aarch64.
# HAVE_SYS_PRCTL_H is 0: only used for thread-renaming nicety.
_CONFIG_H = """\
/* Generated by the wandio/4.2.7 recipe (direct build, no autotools).
 * Equivalent to upstream configure with every optional backend disabled.
 */
#ifndef WANDIO_CONFIG_H
#define WANDIO_CONFIG_H 1

#define WANDIO_MAJOR 4
#define WANDIO_MID 2
#define WANDIO_MINOR 7

#define HAVE_LIBPTHREAD 1
#define HAVE_LIBBZ2 0
#define HAVE_LIBZ 0
#define HAVE_LIBLZO2 0
#define HAVE_LIBLZMA 0
#define HAVE_LIBZSTD 0
#define HAVE_LIBQATZIP 0
#define HAVE_LIBLZ4F 0
#define HAVE_LIBLZ4S 0
#define HAVE_HTTP 0
#define HAVE_SYS_PRCTL_H 0
#define STDC_HEADERS 1

#endif /* WANDIO_CONFIG_H */
"""


class WandioConan(ConanFile):
    name = "wandio"
    version = "4.2.7"
    description = "WAND network I/O library with transparent compression support"
    license = "LGPL-3.0-or-later"
    homepage = "https://github.com/LibtraceTeam/wandio"
    url = ""
    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("wandio is supported only on Linux/OHOS")
        if self.settings.os == "OHOS" and self.settings.arch != "armv8":
            raise ConanInvalidConfiguration("OHOS builds require armv8/aarch64")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _compiler_candidates(self):
        # R33: compiler comes from the Conan conf, never from bare shell
        # env alone -- but the conf absolute path is not guaranteed to be
        # executable inside the preflight build sandbox (2026-09-25:
        # /data/service/hnp/bin/clang -> "inaccessible or not found",
        # Error 127). Candidates are probed in order; the first that can
        # actually execute `--version` wins.
        execs = self.conf.get("tools.build:compiler_executables", default={},
                              check_type=dict)
        cands = []
        if execs.get("c"):
            cands.append(execs.get("c"))
        cc_env = os.environ.get("CC")
        if cc_env:
            cands.append(cc_env)
        # Accessible HMBS tools prefix before the hnp prefix.
        cands.append("/storage/Users/currentUser/usr/local/bin/clang")
        cands.append("/storage/Users/currentUser/usr/local/bin/cc")
        for bare in ("clang", "clang-15", "cc", "gcc"):
            cands.append(bare)
            w = shutil.which(bare)
            if w and w not in cands:
                cands.append(w)
        # OHOS SDK llvm (versioned dir may vary; glob at build time).
        try:
            for pat in glob.glob("/data/service/hnp/ohos-sdk*/ohos/native/llvm/bin/clang"):
                if pat not in cands:
                    cands.append(pat)
        except Exception:
            pass
        seen = set()
        ordered = []
        for c in cands:
            if c and c not in seen:
                seen.add(c)
                ordered.append(c)
        return ordered

    def _tool_works(self, tool, probe="--version"):
        # Filesystem pre-filter to avoid log spam for paths that clearly
        # do not exist on the build host; bare names are resolved via
        # shutil.which on the build host (authoritative for PATH).
        if os.path.isabs(tool):
            if not os.path.isfile(tool):
                return False
        else:
            if shutil.which(tool) is None:
                # Still allow shell PATH resolution at build time (PATH
                # differs between local Windows checkout and the Linux
                # preflight host), but only after absolute candidates fail.
                pass
        try:
            self.run(f'"{tool}" {probe}', env="conanbuild")
            return True
        except Exception:
            return False

    def _resolve_compiler(self):
        for cand in self._compiler_candidates():
            if self._tool_works(cand):
                self.output.info(f"wandio: selected C compiler '{cand}'")
                return cand
        execs = self.conf.get("tools.build:compiler_executables", default={},
                              check_type=dict)
        fallback = execs.get("c") or "clang"
        self.output.warning(f"wandio: no probed compiler worked, using '{fallback}'")
        return fallback

    def _archiver_candidates(self):
        execs = self.conf.get("tools.build:compiler_executables", default={},
                              check_type=dict)
        cands = []
        if execs.get("ar"):
            cands.append(execs.get("ar"))
        ar_env = os.environ.get("AR")
        if ar_env:
            cands.append(ar_env)
        cands.append("/storage/Users/currentUser/usr/local/bin/llvm-ar")
        for bare in ("llvm-ar", "ar"):
            cands.append(bare)
            w = shutil.which(bare)
            if w and w not in cands:
                cands.append(w)
        try:
            for pat in glob.glob("/data/service/hnp/ohos-sdk*/ohos/native/llvm/bin/llvm-ar"):
                if pat not in cands:
                    cands.append(pat)
        except Exception:
            pass
        seen = set()
        ordered = []
        for c in cands:
            if c and c not in seen:
                seen.add(c)
                ordered.append(c)
        return ordered

    def _resolve_archiver(self):
        for cand in self._archiver_candidates():
            if self._tool_works(cand):
                self.output.info(f"wandio: selected archiver '{cand}'")
                return cand
        execs = self.conf.get("tools.build:compiler_executables", default={},
                              check_type=dict)
        fallback = (execs.get("ar") or shutil.which("llvm-ar")
                    or shutil.which("ar") or "ar")
        self.output.warning(f"wandio: no probed archiver worked, using '{fallback}'")
        return fallback

    def build(self):
        src_lib = os.path.join(self.source_folder, "lib")
        cfg_dir = os.path.join(self.build_folder, "cfg")
        obj_dir = os.path.join(self.build_folder, "obj")
        os.makedirs(cfg_dir, exist_ok=True)
        os.makedirs(obj_dir, exist_ok=True)
        with open(os.path.join(cfg_dir, "config.h"), "w",
                  encoding="utf-8") as f:
            f.write(_CONFIG_H)

        cc = self._resolve_compiler()
        inc = f"-I\"{src_lib}\" -I\"{cfg_dir}\""
        cflags = "-O2 -fPIC"
        objs = []
        for src in _LIB_SOURCES:
            obj = os.path.join(obj_dir, src + ".o")
            self.run(f"\"{cc}\" {cflags} {inc} -c \"{src_lib}/{src}\" -o \"{obj}\"",
                     env="conanbuild")
            objs.append(f"\"{obj}\"")
        obj_list = " ".join(objs)
        if self.options.shared:
            self.run(f"\"{cc}\" -shared {cflags} {obj_list} -pthread "
                     f"-o \"{self.build_folder}/libwandio.so\"",
                     env="conanbuild")
        else:
            ar = self._resolve_archiver()
            self.run(f"\"{ar}\" rcs \"{self.build_folder}/libwandio.a\" {obj_list}",
                     env="conanbuild")
        # wandiocat CLI (tools/wandiocat/wcat.c), links the just-built lib.
        wcat = os.path.join(self.source_folder, "tools", "wandiocat", "wcat.c")
        self.run(f"\"{cc}\" {cflags} {inc} \"{wcat}\" "
                 f"\"{self.build_folder}/"
                 f"{'libwandio.so' if self.options.shared else 'libwandio.a'}\""
                 f" -pthread -o \"{self.build_folder}/wandiocat\"",
                 env="conanbuild")
        # Upstream defines no TESTS/check target (see test_package MANIFEST
        # audit), so there is no `make check` suite to invoke here.

    def package(self):
        if self.options.shared:
            copy(self, "libwandio.so", src=self.build_folder,
                 dst=os.path.join(self.package_folder, "lib"))
        else:
            copy(self, "libwandio.a", src=self.build_folder,
                 dst=os.path.join(self.package_folder, "lib"))
        copy(self, "wandio.h", src=os.path.join(self.source_folder, "lib"),
             dst=os.path.join(self.package_folder, "include"))
        copy(self, "wandiocat", src=self.build_folder,
             dst=os.path.join(self.package_folder, "bin"))
        copy(self, "COPYING*", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        self.cpp_info.libs = ["wandio"]
        self.cpp_info.system_libs = ["pthread"]
        self.cpp_info.bindirs = ["bin"]
