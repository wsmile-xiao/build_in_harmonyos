#!/usr/bin/env python3
"""Conan recipe — wmrack 1.4 (Window Maker Sound Control Panel).

WMRack is a Window Maker / AfterStep dock applet ("Wharf swallowable") written in
C on top of X11.  It controls the CD-ROM drive and the OSS mixer: track/time
display, play/pause/stop/eject/load, random play and play lists, volume, balance
and record-source selection.

Upstream builds with a hand-written Makefile driven by a ``configure`` script
generated by GNU Autoconf 2.61 (the 1997 ``configure.in`` was re-processed for the
1.4 release, so the ``configure`` shipped in the tarball is modern autoconf).

OHOS specifics
--------------
* ``AC_PATH_X`` only probes the traditional ``/usr/X11R6`` style locations.  On
  OHOS the X11 headers/libraries live inside Conan packages, so the recipe passes
  ``--x-includes`` / ``--x-libraries`` pointing at the libx11 package; without
  them ``configure`` aborts with ``WMRack needs X Windows!!!``.
* ``configure.in`` assembles the link line by itself: ``-lX11`` comes from the
  ``AC_PATH_X`` result and ``AC_CHECK_LIB`` appends ``-lXpm`` / ``-lXext``.  The
  generated Makefile never uses ``$(LDFLAGS)``, therefore the ``-L`` search paths
  of the Xpm/Xext packages have to be injected through ``LIBS`` (otherwise
  ``ld.lld`` reports ``unable to find library -lXpm/-lXext``).
* ``configure`` runs with ``--host=aarch64-linux-ohos``.  The explicit ``--host``
  makes autoconf take the "maybe cross compiling" path, so a worker that cannot
  execute an aarch64 conftest degrades to ``cross_compiling=yes`` instead of
  aborting with "cannot run C compiled programs".
* E114: the Autoconf scratch directories are created as
  ``(umask 077 && mktemp -d "./confXXXXXX")``.  On HMDFS such a directory can end
  up unwritable even for its owner, so both occurrences are rewritten to
  ``umask 022`` before ``configure`` is executed.
* E490: not every OHOS adaptation path preserves the executable bit of the
  Autotools helper scripts while copying their content, which makes ``./configure``
  fail with ``Permission denied`` (shell exit status 126).  The recipe restores
  the bit explicitly and verifies it right before ``configure`` is invoked.
* E002: ``/tmp`` is a read-only erofs mount, ``TMPDIR`` is redirected into the
  build folder.  E074: ``make`` must run with ``-j1`` (SELinux denies the FIFO
  jobserver used by parallel make).
"""

import os
import shlex
from pathlib import Path

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
)
from conan.tools.gnu import AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout

# wmrack is a GUI dock applet: the only binary it produces is `wmrack`
# (`xpmicon.c` #includes `XPM/standart.style`, which the Makefile materialises as a
# symbolic link to the selected style, so that target must be built as well).
_TARGET = "wmrack"
_OHOS_HOST_TRIPLET = "aarch64-linux-ohos"


class WmrackConan(ConanFile):
    name = "wmrack"
    version = "1.4"
    description = (
        "Window Maker / AfterStep dock applet (Wharf swallowable) that controls the "
        "CD-ROM drive and the OSS mixer: track & time display, play/pause/stop/eject/"
        "load, random play, play lists, volume, balance and record-source control"
    )
    license = "GPL-2.0-or-later"
    homepage = "https://sourceforge.net/projects/wmrack/"
    url = "https://sourceforge.net/projects/wmrack/"

    # GUI dock applet -> executable package, not a library (R38: commands.json is
    # declared at software level in archives/w/wmrack/commands.json).
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # libxpm pulls libx11/6.4.0 + xorgproto/2025.1 transitively, libxext adds
        # libx11 as well; the whole graph stays on the cmd-pkgs 6.4.0 track.
        self.requires("libxpm/3.5.17")
        self.requires("libxext/6.4.0.1")

    # R32: OHOS platform compatibility
    def validate(self):
        if str(self.settings.os) not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"wmrack supports Linux and OHOS, not {self.settings.os}"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # R33: the compiler and the base flags come from the Conan toolchain, never
        # from bare shell environment variables.
        AutotoolsToolchain(self).generate()

        # AutotoolsDeps exports CPPFLAGS/LDFLAGS/LIBS for the whole dependency
        # graph.  This project's Makefile ignores $(LDFLAGS) when linking and
        # AC_PATH_X only knows about the libx11 location, so the -L directories of
        # every X11 package are appended to LIBS as well.
        dependencies = AutotoolsDeps(self)
        environment = dependencies.environment
        environment.append("CPPFLAGS", self._dependency_flags("includedirs", "-I"))
        environment.append("LIBS", self._dependency_flags("libdirs", "-L"))
        dependencies.generate()

    def build(self):
        apply_conandata_patches(self)
        if str(self.settings.os) == "OHOS":
            self._relax_autoconf_scratch_umask()
            self._restore_autotools_script_modes()
        self._configure()
        # E074: SELinux forbids the FIFO jobserver, parallel make hangs -> -j1
        self.run(
            f"make -j1 standart.style {_TARGET}",
            cwd=self.source_folder,
            env="conanbuild",
        )

    def package(self):
        # The upstream Makefile honours $prefix only (it never references DESTDIR),
        # so configure is pointed straight at the package folder and a plain
        # `make install` populates bin/, share/man/man1/ and lib/WMRack/.
        self.run("make -j1 install", cwd=self.source_folder, env="conanbuild")
        copy(
            self,
            "COPYING",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "licenses"),
            keep_path=False,
        )

    def package_info(self):
        # Executable package: no headers, no libraries, only bin/
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.libs = []
        self.cpp_info.bindirs = ["bin"]

    # ── helpers ──────────────────────────────────────────────────────────────

    def _dependency_flags(self, attribute, prefix):
        """Absolute -I/-L flags for every host dependency (deduplicated, existing)."""
        seen = set()
        flags = []
        for dependency in self.dependencies.host.values():
            for directory in getattr(dependency.cpp_info, attribute):
                if not os.path.isabs(directory):
                    directory = os.path.join(dependency.package_folder, directory)
                if directory in seen or not os.path.isdir(directory):
                    continue
                seen.add(directory)
                flags.append(f"{prefix}{directory}")
        return flags

    def _package_directory(self, package, attribute):
        """First existing include/lib directory published by `package`."""
        dependency = self.dependencies[package]
        for directory in getattr(dependency.cpp_info, attribute):
            if not os.path.isabs(directory):
                directory = os.path.join(dependency.package_folder, directory)
            if os.path.isdir(directory):
                return directory
        raise ConanException(f"{package} does not expose a usable {attribute} directory")

    def _relax_autoconf_scratch_umask(self):
        """E114 — the umask 077 scratch dirs of Autoconf 2.61 are unusable on HMDFS."""
        configure = Path(self.source_folder, "configure")
        content = configure.read_text(encoding="utf-8")
        occurrences = content.count("umask 077")
        if occurrences != 2:
            raise ConanException(
                "unexpected 'umask 077' occurrence count in configure: "
                f"{occurrences} (E114 workaround)"
            )
        configure.write_text(
            content.replace("umask 077", "umask 022"), encoding="utf-8", newline="\n"
        )

    def _restore_autotools_script_modes(self):
        """E490 — restore the executable bit of the Autotools helper scripts.

        The tarball ships ``configure``/``install-sh`` as programs, but an OHOS
        adaptation path may copy their content without the exec bit, which makes
        ``./configure`` die with "Permission denied" (exit 126).  ``chmod`` is
        idempotent and the result is verified afterwards, so a silent loss is
        turned into a hard, self-explaining build failure.
        """
        scripts = ("configure", "config.guess", "config.sub", "install-sh", "missing")
        for name in scripts:
            path = Path(self.source_folder, name)
            if not path.is_file():
                continue  # this package only ships configure + install-sh
            path.chmod(path.stat().st_mode | 0o500)
            if not path.stat().st_mode & 0o111:
                raise ConanException(
                    f"E490: failed to restore the executable bit of {name}"
                )

    def _configure(self):
        command = [
            "./configure",
            f"--prefix={self.package_folder}",
            f"--x-includes={self._package_directory('libx11', 'includedirs')}",
            f"--x-libraries={self._package_directory('libx11', 'libdirs')}",
        ]
        if str(self.settings.os) == "OHOS":
            command.append(f"--host={_OHOS_HOST_TRIPLET}")
        self.run(
            " ".join(shlex.quote(argument) for argument in command),
            cwd=self.source_folder,
            env="conanbuild",
        )
