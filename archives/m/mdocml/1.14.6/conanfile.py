#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Conan recipe — mdocml 1.14.6（mandoc man page 编译器工具集，纯 C 手写 configure）.

上游事实
--------
* 官方发行渠道 <https://mandoc.bsd.lv/snapshots/mandoc-1.14.6.tar.gz>，
  与第二独立源（MacPorts distfiles）sha256 全等：
  8bf0d570f01e70a6e124884088870cbed7537f36328d512909eb10cd53179d9c。
  tarball 内证：顶层目录 mandoc-1.14.6、Makefile:18 `VERSION = 1.14.6`。
* **mdocml 是 mandoc 的旧名**（tarball `INSTALL:5` 原文：
  `The mandoc manpage compiler toolset (formerly called "mdocml")`）。
  仓库已有 `archives/m/mandoc/1.14.6/` 旧式归档（仅 manifest/notes/2 个
  Makefile.local 补丁，**缺 conanfile/conandata/test_package/commands.json
  四件套**），故本包 `archives/m/mdocml/1.14.6/` 是同软件的**首个完整 Conan
  配方**；两目录并存属「任务卡名 mdocml vs 历史归档名 mandoc」的冗余，
  别名同源关系已在 notes.md 问题表、manifest、PR 正文三处披露。

构建系统：手写 sh configure（非 autoconf）
------------------------------------------
configure 非 `generated by GNU Autoconf` 产物，源树无 aclocal.m4/
configure.ac/config.guess/config.sub → **不 autoreconf、零 config.sub 陈旧族风险**。
执行序：`sh ./configure` 读 `configure.local`（存在即 `. ./configure.local`）→
生成 `config.h` 与 `Makefile.local` → `make` 消费 Makefile.local。

三个设备/CI 缺口全部走 configure.local 显式注入（**零源码补丁**）
----------------------------------------------------------------
上游 configure.local.example 本就提供这些变量的官方注入位，故无需
refresh_patch 登记、无需改上游任何文件：

1. **CC/AR**：设备与 CI worker PATH 有 `clang` 无 `cc`，上游默认 `CC="cc"` →
   configure 全部 `tested *: no (compilation failed)` +
   `FATAL: no endian conversion functions found` + `FATAL: nanosleep: no`。
   → 从 profile 的 `tools.build:compiler_executables` 取（R33：绝不读
   shell 环境变量，CI worker 上为空）。
2. **LN**：HMDFS 不支持硬链接，`ln -f mandoc man` 报 `Operation not permitted`。
   → `LN="cp -f"`（官方 example 同款手段）。
   ⚠ **值必须加双引号**：裸 `LN=cp -f` 被 shell 解析成「前缀赋值 + 执行 `-f`」
   → configure 立即 rc=127（本任务实测踩过）。
3. **UTF8_LOCALE**：设备无 `locale` 命令 → configure 的 `locale -a` 取不到
   UTF-8 locale → `HAVE_WCHAR=0` → 上游 regress **19 个 `utf8:diff` 全失败**。
   设备实测 `setlocale(LC_CTYPE,"en_US.UTF-8")` 可用（`wcwidth(L' ')=1`、
   `sizeof(wchar_t)=4`）→ 手工 `UTF8_LOCALE="en_US.UTF-8"` → `HAVE_WCHAR=1`
   → **19 失败清零，1427/1427 全绿**。
   另 `STATIC=" "`（官方 example 置空写法）规避 `-static` 链接风险。

依赖：zlib
----------
`read.c:40` 无条件 `#include <zlib.h>`，configure 把 `-lz` 硬编码进
`LDADD`（configure:433）。配方显式 `requires("zlib/1.3.1")` 并把 conan
zlib 的 include/lib 注入 CFLAGS/LDFLAGS —— **不依赖设备 SDK sysroot 里
隐式可见的 zlib.h**（`.../ohos/native/sysroot/usr/include/zlib.h` 在
CI worker 上不保证存在）。

上游测试：make regress
----------------------
`regress: cd regress && ./regress.pl`（`#!/usr/bin/env perl`，perl 走 HNP
`/data/service/hnp/bin/perl` 5.42.0，**不 tool_requires**——conan perl 有
HMFS 不可用先例）。计数两栏（§3.5）：输入 `.in` **572**、期望输出 `.out_*`
**1189**、实跑 tests run **1427**（ascii565 + tag28 + man244 + utf821 +
html68 + markdown253 + lint248）。
"""
import os

from conan import ConanFile
from conan.tools.build import cross_building
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class MdocmlConan(ConanFile):
    name = "mdocml"
    version = "1.14.6"
    description = "mdocml (formerly mandoc) - portable man page compiler toolset providing mandoc, man, demandoc, soelim and the static libmandoc library"
    license = "ISC"
    homepage = "https://mandoc.bsd.lv/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    topics = ("man", "mdoc", "roff", "mandoc", "manual")

    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("zlib/1.3.1")

    def layout(self):
        # 上游是 in-source 构建：configure 生成 Makefile.local 后就地 make
        basic_layout(self, src_folder=".", build_folder=".")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)

        # R33：编译器/归档器从 conf 整体取 dict 再索引（点分子键写法在
        # Conan 2.29 抛 ConanException，check_type=str 会把 dict 转字符串）
        comp = self.conf.get("tools.build:compiler_executables",
                             default={}, check_type=dict)
        cc = comp.get("c") or "clang"
        ar = comp.get("ar") or "llvm-ar"

        # zlib 显式注入（不依赖 SDK sysroot 隐式可见的 zlib.h/libz）
        z_root = self.dependencies["zlib"].package_folder

        # CFLAGS 显式钉死（R33 防环境泄漏）+ 上游告警面 + zlib 头路径
        cflags = "-O3 -pipe -DNDEBUG -I{}".format(os.path.join(z_root, "include"))
        ldflags = "-L{}".format(os.path.join(z_root, "lib"))

        # 三个设备缺口 + CFLAGS/LDFLAGS 全走 configure.local（零源码补丁）。
        # ⚠ 每个含空格的值必须带双引号：裸 `LN=cp -f` 会被 shell 解析成
        #   「前缀赋值 + 执行 -f」→ configure rc=127（本任务实测踩过一次）。
        conf_local = (
            'CC="{cc}"\n'
            'AR="{ar}"\n'
            'LN="cp -f"\n'
            'STATIC=" "\n'
            'UTF8_LOCALE="en_US.UTF-8"\n'
            'CFLAGS="{cflags}"\n'
            'LDFLAGS="{ldflags}"\n'
        ).format(cc=cc, ar=ar, cflags=cflags, ldflags=ldflags)
        with open(os.path.join(self.source_folder, "configure.local"), "w") as fh:
            fh.write(conf_local)

        # 手写 configure：不 autoreconf、不传 autotools 标准目录参数
        # （上游 configure 只认 configure.local 里的变量赋值）
        self.run("sh ./configure", cwd=self.source_folder, env="conanbuild")
        # R9：-j1（上游 Makefile 无并行安全声明）
        self.run("make -j1", cwd=self.source_folder, env="conanbuild")

        # 上游官方测试入口 = make regress（非 make check，L1c 的 grep 不命中
        # 只打 [step] 提示不阻断；此处如实执行上游入口，不改名凑匹配）
        if cross_building(self):
            self.output.info("cross-building: upstream regress skipped (compile-only)")
        else:
            self.run("make regress", cwd=self.source_folder, env="conanbuild")

    def package(self):
        # 不走 `make install`：设备/CI 无 `install` 命令（实测
        # `make: install: No such file or directory` → Error 127），且上游
        # base-install 目标内含硬链接（HMDFS 不支持）与 PREFIX 绝对路径落盘。
        # 直接从源树收纳产物（mustach 先例同款）。
        if os.path.isfile(os.path.join(self.source_folder, "LICENSE")):
            copy(self, "LICENSE", self.source_folder,
                 os.path.join(self.package_folder, "licenses"))

        # 可执行件：mandoc 主程序 + demandoc + soelim
        for tool in ("mandoc", "demandoc", "soelim"):
            if os.path.isfile(os.path.join(self.source_folder, tool)):
                copy(self, tool, self.source_folder,
                     os.path.join(self.package_folder, "bin"))

        # man/apropos/whatis/makewhatis = mandoc 的别名
        # （上游 Makefile 用 `$(LN) mandoc <alias>`，LN=cp -f 后是独立副本）
        mandoc_src = os.path.join(self.source_folder, "mandoc")
        bin_dst = os.path.join(self.package_folder, "bin")
        if os.path.isfile(mandoc_src):
            with open(mandoc_src, "rb") as fin:
                blob = fin.read()
            for alias in ("man", "apropos", "whatis", "makewhatis"):
                with open(os.path.join(bin_dst, alias), "wb") as fout:
                    fout.write(blob)

        # 静态库（上游唯一库产物，R26：不产出系统同名 .so）
        if os.path.isfile(os.path.join(self.source_folder, "libmandoc.a")):
            copy(self, "libmandoc.a", self.source_folder,
                 os.path.join(self.package_folder, "lib"))

        # 对外头文件 = 上游 lib-install 安装清单（8 个）
        hdr_dst = os.path.join(self.package_folder, "include")
        for hdr in ("eqn.h", "man.h", "mandoc.h", "mandoc_aux.h",
                    "mandoc_parse.h", "mdoc.h", "roff.h", "tbl.h"):
            if os.path.isfile(os.path.join(self.source_folder, hdr)):
                copy(self, hdr, self.source_folder, hdr_dst)

        # man pages（上游 base-install 的 man1 子集）
        man1_dst = os.path.join(self.package_folder, "share", "man", "man1")
        for page in ("mandoc.1", "demandoc.1", "soelim.1", "man.1", "apropos.1"):
            if os.path.isfile(os.path.join(self.source_folder, page)):
                copy(self, page, self.source_folder, man1_dst)

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "mdocml")
        self.cpp_info.set_property("cmake_target_name", "mdocml::mdocml")
        self.cpp_info.set_property("pkg_config_name", "mdocml")

        self.cpp_info.includedirs = ["include"]
        # libmandoc.a 内 read.o 引用 zlib 符号 → 消费者需继承 zlib
        self.cpp_info.libs = ["mandoc"]
        self.cpp_info.requires.append("zlib::zlib")

        # R38/PF8：可执行件在 bin/ → bindirs 非空 → 软件级 commands.json 必备
        self.cpp_info.bindirs = ["bin"]
        self.runenv_info.append_path("PATH",
                                     os.path.join(self.package_folder, "bin"))
