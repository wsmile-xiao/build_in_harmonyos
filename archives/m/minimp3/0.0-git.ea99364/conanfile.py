#!/usr/bin/env python3
"""Conan recipe for minimp3 0.0-git.ea99364.

minimp3 is a minimalist single-file MP3 decoder (CC0 / public domain).
Upstream ships NO build system at all (no CMakeLists.txt / Makefile —
only minimp3.h + minimp3_ex.h headers plus a test driver and reference
vectors). This recipe:

  * generates a single amalgamated implementation TU (minimp3.c) that
    turns the header/source hybrid into a thin static library,
  * generates a minimal CMakeLists.txt (upstream has none),
  * compiles the UNMODIFIED upstream test driver minimp3_test.c and
    registers the upstream tests as CTest tests:
      - upstream_selftest        (-t: 72 API contract assertions +
                                   full reference-vector PSNR sweep)
      - upstream_vector_<name>   (83 reference vectors, decode +
                                   PSNR comparison vs reference PCM,
                                   same invocation as scripts/test.sh)
      - upstream_mode3_iterate / upstream_mode6_stream
                                  (mode samples, same invocation as
                                   scripts/test_mode.sh / build.sh)
    and runs them all via cmake.test() inside build().

Upstream snapshot: master @ ea99364f61c14656440e8d77e9c233ccf3124633
(the 7-hex prefix ea99364 is the version tag per the master-only
repository versioning rule 0.0-git.{hash7}).

Upstream test driver compiled with -std=c99 semantics
(CMAKE_C_STANDARD=99), zero third-party dependencies (libc/libm only).
"""
import os

from conan import ConanFile
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout
from conan.tools.files import get, save

MINIMP3_C = """\
/* Auto-generated by conanfile.py - single implementation translation unit.
 * MINIMP3_IMPLEMENTATION activates the implementation sections of both
 * minimp3.h and minimp3_ex.h (stdio file API left enabled). */
#define MINIMP3_IMPLEMENTATION
#include "minimp3_ex.h"
"""

CMAKELISTS = """\
cmake_minimum_required(VERSION 3.15)
project(minimp3 C)
set(CMAKE_C_STANDARD 99)
set(CMAKE_C_STANDARD_REQUIRED ON)

# Thin static library from the single amalgamated TU
add_library(minimp3 minimp3.c)
target_include_directories(minimp3 PUBLIC ${CMAKE_CURRENT_SOURCE_DIR})

# UNMODIFIED upstream test driver (self-contained TU, links libm only)
add_executable(minimp3_upstream_test minimp3_test.c)
target_link_libraries(minimp3_upstream_test PRIVATE m)

enable_testing()

# Upstream self-test: 72 API contract assertions + full vector PSNR sweep
add_test(NAME upstream_selftest
         COMMAND minimp3_upstream_test -t vectors/l3-si.bit
         WORKING_DIRECTORY ${CMAKE_CURRENT_SOURCE_DIR})

# Upstream scripts/test.sh semantics: decode each reference vector and
# compare against the shipped reference PCM (PSNR compliance check)
file(GLOB MINIMP3_VECTORS "${CMAKE_CURRENT_SOURCE_DIR}/vectors/*.bit")
foreach(vec IN LISTS MINIMP3_VECTORS)
    get_filename_component(vec_name ${vec} NAME_WE)
    add_test(NAME upstream_vector_${vec_name}
             COMMAND minimp3_upstream_test
                     ${vec}
                     ${CMAKE_CURRENT_SOURCE_DIR}/vectors/${vec_name}.pcm
             WORKING_DIRECTORY ${CMAKE_CURRENT_SOURCE_DIR})
endforeach()

# Upstream scripts/build.sh mode samples (iterate + stream modes)
add_test(NAME upstream_mode3_iterate
         COMMAND minimp3_upstream_test -m 3 -s 0 -p 0
                 vectors/l1-fl1.bit vectors/l1-fl1.pcm
         WORKING_DIRECTORY ${CMAKE_CURRENT_SOURCE_DIR})
add_test(NAME upstream_mode6_stream
         COMMAND minimp3_upstream_test -m 6 -s -1 -p -1
                 vectors/l2-test32.bit vectors/l2-test32.pcm
         WORKING_DIRECTORY ${CMAKE_CURRENT_SOURCE_DIR})

install(TARGETS minimp3
        ARCHIVE DESTINATION lib
        LIBRARY DESTINATION lib)
install(FILES minimp3.h minimp3_ex.h DESTINATION include)
"""


class Minimp3Conan(ConanFile):
    name = "minimp3"
    version = "0.0-git.ea99364"
    description = "Minimalist single-file MP3 decoder (header/source hybrid, CC0 public domain)"
    license = "CC0-1.0"
    homepage = "https://github.com/lieff/minimp3"
    url = "https://github.com/lieff/minimp3"

    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = CMakeToolchain(self)
        # CMake >= 4 workers break the compiler check on the OHOS-adapted
        # CMAKE_SYSTEM_NAME=HarmonyOS mapping (no Platform/HarmonyOS module
        # in CMake). OHOS is POSIX: force the Linux platform (chain-wide
        # convention; abcmidi/adios2/kpeople5 precedent).
        if str(self.settings.os) == "OHOS":
            tc.cache_variables["CMAKE_SYSTEM_NAME"] = "Linux"
            tc.cache_variables["CMAKE_SYSTEM_PROCESSOR"] = (
                "aarch64" if str(self.settings.arch) == "armv8" else str(self.settings.arch)
            )
        # R26: static by default — no system-name .so collision risk
        tc.variables["BUILD_SHARED_LIBS"] = self.options.shared
        # upstream test driver is compiled with c99 semantics
        tc.variables["CMAKE_C_STANDARD"] = "99"
        tc.variables["CMAKE_C_STANDARD_REQUIRED"] = "ON"
        tc.generate()

    def build(self):
        # 1) single amalgamated implementation TU (header/source hybrid)
        save(self, os.path.join(self.source_folder, "minimp3.c"), MINIMP3_C)
        # 2) thin CMake build (upstream ships no build system)
        save(self, os.path.join(self.source_folder, "CMakeLists.txt"), CMAKELISTS)

        cmake = CMake(self)
        cmake.configure()
        cmake.build()
        # 3) run the upstream tests registered as CTest tests
        #    (plain cmake.test(): canonical cross-generator invocation;
        #     ctest verbosity comes from CTEST_OUTPUT_ON_FAILURE env)
        cmake.test()

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.libs = ["minimp3"]
        # musl/OHOS folds libm into libc; the -lm link stays harmless there
        self.cpp_info.system_libs = ["m"]
