#!/usr/bin/env python3
"""Conan recipe — mkp224o 1.7.0 (v3 onion address generator).

mkp224o generates vanity .onion addresses for Tor hidden services
(v3, ed25519).  Upstream: https://github.com/cathugger/mkp224o

OHOS adaptation notes:
- Official release tarball (github release asset, not git archive) already
  ships a pregenerated `configure` script, so no autoreconf needed.
- Upstream configure defaults to the portable C ed25519-donna backend.
  The x86-64 asm backends (amd64-51-30k / amd64-64-24k / donna-sse2) are
  opt-in via --enable-* flags and are NOT enabled for aarch64.  There is
  no runtime CPU feature dispatch: cpucount.c only counts cores.
- Upstream configure injects `-march=native -O3` only when the user has
  not set CFLAGS; we always pass explicit CFLAGS from the Conan profile,
  so -march=native is never used.
- Upstream GNUmakefile has no `install` target; package() copies the
  built binaries manually.
- libsodium is a hard link dependency (-lsodium: sodium_init,
  randombytes_buf, crypto_pwhash for optional passphrase mode).  We keep
  the default ed25519-donna backend for the key math itself (NOT
  replaced by libsodium's crypto_sign) — this is what upstream ships and
  tests, and its test_ed25519 covers it against RFC 8032 test vectors.
- The linked-in OHOS SDK CRT objects (Scrt1.o etc.) ship DWARF that
  embeds the SDK build machine paths (DW_AT_comp_dir=/devcloud/...),
  so package() strips .debug_* sections with the target LLVM strip
  tool BEFORE signing: any binary rewrite AFTER signing invalidates
  .codesign and the kernel refuses to execute the binary
  (minisign 0.12 / E077 precedent).
"""
import os
import shutil
import subprocess

from conan import ConanFile
from conan.errors import ConanException
from conan.tools.files import apply_conandata_patches, copy, get
from conan.tools.gnu import Autotools, AutotoolsDeps, AutotoolsToolchain
from conan.tools.layout import basic_layout


class Mkp224oConan(ConanFile):
    name = "mkp224o"
    version = "1.7.0"
    description = "Vanity onion address (v3) generator for Tor hidden services"
    license = "CC0-1.0"
    homepage = "https://github.com/cathugger/mkp224o"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        # No patches: official 1.7.0 tarball builds cleanly with OHOS clang
        pass

    def requirements(self):
        # libsodium is published in the ohpcd registry as a bare ref
        # (no @ohpcd/stable channel) — same as et 7.0.0 usage.
        self.requires("libsodium/1.0.22")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        # conandata patches is [] (tarball builds clean); keep the
        # canonical patch-application call for future patch additions.
        apply_conandata_patches(self)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Keep the portable C ed25519-donna backend (upstream default).
        # NOTE: do NOT pass --disable-* for the other backends: upstream
        # configure.ac uses AC_ARG_ENABLE action-if-given without checking
        # the value, so `--disable-ref10` would actually SELECT ref10 and
        # then abort with "only one ed25519 implementation can be defined".
        # No backend flags at all => ed25519impl="" => falls back to donna.
        tc.generate()
        # Expose libsodium include/lib dirs to configure & make
        AutotoolsDeps(self).generate()

    def build(self):
        # E129: HMDFS umask issue — configure/config.status create their
        # temp dir (./confXXXXXX) with umask 077, and on HMDFS the
        # subs1.awk written inside then cannot be re-read ("Permission
        # denied: ./confXXXXXX/subs1.awk"). Patch the umask in the
        # source configure script (its embedded as_fn_* helpers are
        # copied into the generated config.status) before running it.
        # Same fix as macchanger 1.7.0-r3.
        cfg = os.path.join(self.source_folder, "configure")
        if os.path.isfile(cfg):
            with open(cfg, "r") as f:
                content = f.read()
            if "umask 077" in content:
                content = content.replace("umask 077", "umask 022")
                with open(cfg, "w") as f:
                    f.write(content)
        autotools = Autotools(self)
        autotools.configure()
        # config.status is generated by configure: patch its umask too
        # (it re-runs when make touches config files).
        status_path = os.path.join(self.build_folder, "config.status")
        if os.path.isfile(status_path):
            with open(status_path, "r") as f:
                content = f.read()
            if "umask 077" in content:
                content = content.replace("umask 077", "umask 022")
                with open(status_path, "w") as f:
                    f.write(content)
        # Build main binary (upstream GNUmakefile has no install target).
        autotools.make(args=["-j1", "mkp224o"])

        # Upstream official tests (GNUmakefile `test` target): make test
        # builds 4 known-answer test binaries; each is then executed
        # individually below (deterministic, seconds to run) so the
        # conan create log carries the evidence.
        test_libdirs = [
            dep.cpp_info.libdirs[0]
            for dep in self.dependencies.values()
            if dep.cpp_info.libdirs
        ]
        if test_libdirs:
            os.environ["LD_LIBRARY_PATH"] = os.pathsep.join(
                test_libdirs + [os.environ.get("LD_LIBRARY_PATH", "")]
            )
        autotools.make(args=["-j1", "test"])
        for tst in ("test_base16", "test_base32", "test_base64", "test_ed25519"):
            self.run(f"./{tst}", cwd=self.build_folder)

    def package(self):
        # GNUmakefile has no install target — copy artifacts manually.
        bindir = os.path.join(self.package_folder, "bin")
        os.makedirs(bindir, exist_ok=True)
        src = os.path.join(self.build_folder, "mkp224o")
        if not os.path.isfile(src):
            raise ConanException(f"built mkp224o binary not found: {src}")
        shutil.copy2(src, os.path.join(bindir, "mkp224o"))
        copy(
            self,
            "COPYING.txt",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "licenses"),
            keep_path=False,
        )
        if self.settings.os == "OHOS":
            # ORDER MATTERS: strip first, then sign. Any binary rewrite
            # AFTER signing invalidates .codesign (minisign 0.12 E077).
            self._strip_debug_ohos(os.path.join(bindir, "mkp224o"))
            self._sign_ohos_elf(os.path.join(bindir, "mkp224o"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]

    def _llvm_tool(self, name):
        # LLVM tool from the compiler's own toolchain dir when present
        # (aespipe 2.4h pattern), else first match on PATH (the profile
        # buildenv PATH carries the target LLVM bin dir).
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        )
        for key in ("c", "cpp"):
            compiler = compilers.get(key)
            if compiler and os.path.isfile(compiler):
                candidate = os.path.join(os.path.dirname(compiler), name)
                if os.path.isfile(candidate):
                    return candidate
        found = shutil.which(name)
        if found:
            return found
        raise ConanException(f"LLVM tool not found: {name}")

    def _strip_debug_ohos(self, path):
        # Strip .debug_* sections with the target LLVM strip tool.
        # The OHOS SDK CRT objects (Scrt1.o etc.) ship DWARF whose
        # DW_AT_comp_dir / DW_AT_name embed the SDK build machine's
        # paths (/devcloud/...); those must not leak into the package.
        # Must run BEFORE _sign_ohos_elf(): any binary rewrite after
        # signing invalidates .codesign and the kernel refuses to run
        # the binary (minisign 0.12 E077).
        # The OHOS clang wrapper links with -Wl,--code-sign, so the
        # fresh build product already carries a .codesign section
        # signed over the UNSTRIPPED image. Strip rewrites the file,
        # making that signature stale, and binary-sign-tool refuses to
        # re-sign a binary that already has the section ("section
        # already exists"). Drop the stale section here — the link-time
        # signature is invalid anyway — so _sign_ohos_elf() can apply
        # a fresh signature over the stripped image.
        # llvm-strip and llvm-objcopy are the same LLVM driver in
        # different modes; this toolchain ships only the llvm-objcopy
        # binary, so fall back to it — `llvm-objcopy --strip-debug` is
        # the exact equivalent of `llvm-strip --strip-debug`.
        try:
            strip = self._llvm_tool("llvm-strip")
        except ConanException:
            strip = self._llvm_tool("llvm-objcopy")
        subprocess.run(
            [strip, "--strip-debug", "--remove-section=.codesign", path],
            check=True,
            timeout=60,
        )
        sections = subprocess.run(
            [self._readelf_tool(), "-SW", path],
            check=True,
            capture_output=True,
            text=True,
            timeout=30,
        ).stdout
        if ".debug_" in sections:
            raise ConanException(
                f"{path} still carries .debug_* sections after strip"
            )

    @staticmethod
    def _readelf_tool():
        # Prefer llvm-readelf; fall back to GNU binutils readelf (both
        # print section names with -SW; only used to count sections).
        return (
            shutil.which("llvm-readelf")
            or shutil.which("readelf")
            or "/data/service/hnp/bin/llvm-readelf"
        )

    def _sign_ohos_elf(self, path):
        # .codesign self-signing, same procedure as abx/abbtr recipes.
        signer = shutil.which("binary-sign-tool") or "/data/service/hnp/bin/binary-sign-tool"
        readelf = self._readelf_tool()
        if not os.path.isfile(path):
            raise ConanException(f"Missing packaged executable: {path}")
        if not os.path.isfile(signer):
            raise ConanException(f"OHOS signing tool missing: {signer}")
        output = path + ".signed"
        subprocess.run(
            [signer, "sign", "-inFile", path, "-outFile", output, "-selfSign", "1"],
            check=True,
            timeout=60,
        )
        sections = subprocess.run(
            [readelf, "-SW", output],
            check=True,
            capture_output=True,
            text=True,
            timeout=30,
        ).stdout
        if sections.count(".codesign") != 1:
            raise ConanException("Signed packaged executable has invalid .codesign count")
        os.chmod(output, (os.stat(path).st_mode & 0o777) | 0o055)
        os.replace(output, path)
