"""Conan recipe for mdds/3.2.1 on HarmonyOS (OHOS) aarch64.

Builds and runs the full upstream ctest suite on the real OHOS aarch64 clang.
"""
import os
import shutil
import subprocess

from conan import ConanFile
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout
from conan.tools.files import get as _tools_get
from conan.tools.files import apply_conandata_patches
from conan.tools.files import copy as _tools_copy


class MddsRecipe(ConanFile):
    name = "mdds"
    version = "3.2.1"
    settings = "os", "arch", "compiler", "build_type"
    generators = "CMakeDeps"
    exports_sources = "patches/*"

    def export_sources(self):
        # Copy the patches dir to the export_sources_folder explicitly.
        # .gitignore line 2 (`*`) would otherwise cause Conan's default
        # export_sources handling to skip the gitignored patch file.
        _tools_copy(
            self,
            "patches/*",
            src=self.recipe_folder,
            dst=self.export_sources_folder,
        )

    def requirements(self):
        self.requires("boost/1.90.0")

    def layout(self):
        cmake_layout(self)

    def source(self):
        src = self.conan_data["sources"][self.version]
        _tools_get(
            self,
            src["url"],
            filename=os.path.basename(src["url"]),
            sha256=src["sha256"],
            strip_root=True,
        )

    def generate(self):
        tc = CMakeToolchain(self)
        raw = self.conf.get("tools.build:compiler_executables", check_type=dict)

        def resolve_compiler(lang):
            cand = None
            if raw:
                cand = raw.get(lang) or raw.get(lang.upper())
            if cand and os.path.isfile(cand):
                return cand
            base = os.path.basename(cand) if cand else (
                "clang" if lang == "c" else "clang++")
            return shutil.which(base)

        def assert_ohos_aarch64(path, label):
            assert path and os.path.isfile(path), \
                f"{label} not found: {path!r}"
            r = subprocess.run(
                [path, "-print-target-triple"],
                capture_output=True, text=True)
            triple = (r.stdout or "").strip()
            assert triple == "aarch64-unknown-linux-ohos", (
                f"{label} is not an OHOS aarch64 compiler "
                f"(triple={triple!r}, path={path!r})")
            assert r.returncode == 0, \
                f"{label} -print-target-triple failed"

        cc = resolve_compiler("c")
        cxx = resolve_compiler("cpp")
        assert_ohos_aarch64(cc, "CC")
        assert_ohos_aarch64(cxx, "CXX")
        tc.variables["CMAKE_C_COMPILER"] = cc
        tc.variables["CMAKE_CXX_COMPILER"] = cxx
        tc.variables["CMAKE_SYSTEM_PROCESSOR"] = "aarch64"
        # CMake 4.1 ships OHOS.cmake but no HarmonyOS.cmake. The profile
        # sets os=HarmonyOS -> CMAKE_SYSTEM_NAME=HarmonyOS, which CMake
        # rejects ("System is unknown"). Generate a minimal HarmonyOS.cmake
        # platform module in the private generators folder (never committed
        # to source) mirroring CMake's own OHOS.cmake (which just does
        # include(Platform/Linux)). This registers HarmonyOS as a
        # Linux-derived system exactly as CMake's native OHOS support does.
        platform_dir = os.path.join(self.generators_folder, "Platform")
        os.makedirs(platform_dir, exist_ok=True)
        with open(os.path.join(platform_dir, "HarmonyOS.cmake"), "w") as f:
            f.write("# Auto-generated by mdds/3.2.1 recipe.\n")
            f.write("# HarmonyOS is a Linux-derived system (cf. CMake OHOS.cmake).\n")
            f.write("include(Platform/Linux)\n")
        tc.variables["CMAKE_MODULE_PATH"] = self.generators_folder
        tc.generate()

    def build(self):
        # Apply the <execution> compat patch via Conan's standard
        # apply_conandata_patches. The patch uses #if __has_include(<execution>)
        # to fall back to plain std::transform when OHOS libc++ lacks
        # <execution>; test logic is unchanged.
        apply_conandata_patches(self)
        cmake = CMake(self)
        cmake.configure()
        cmake.build(target="check")

    def test(self):
        """Run the full upstream ctest suite on the real OHOS aarch64 clang."""
        cmake = CMake(self)
        cmake.test(cli_args=["--output-on-failure"])

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        # mdds is header-only: no static/shared lib is built or shipped.
        # Upstream installs headers to <prefix>/include/mdds-<API>/mdds/,
        # so set includedirs to the API-versioned subdirectory and clear
        # libs (CMakeDeps must not look for a 'mdds' library file).
        self.cpp_info.libdirs = []
        self.cpp_info.includedirs = ["include/mdds-3.0"]
        self.cpp_info.libs = []
        self.cpp_info.set_property("cmake_file_name", "mdds")
        self.cpp_info.set_property("cmake_target_name", "mdds::mdds")
        self.cpp_info.requires = ["boost::boost"]
