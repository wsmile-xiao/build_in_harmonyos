#!/usr/bin/env python3
"""Conan recipe for mdetect 0.5.2.6, a command-line mouse detector.

OHOS adaptations (evidence trail in notes.md):

  * The Debian source archive ships no generated ``configure``/``Makefile.in``,
    so ``build()`` bootstraps with ``autoreconf -fi`` and pulls ``automake/1.18``
    in as a ``tool_requires`` (the CI sandbox image only carries the autoconf
    suite; verified with ``--build=never`` against the ohpcd remote).
  * ``config.guess`` produced by the host autoconf has no ``HarmonyOS`` branch
    (``uname -s`` is ``HarmonyOS``), so native guessing aborts with
    ``cannot guess build type``.  The generated ``config.sub`` already accepts
    the OHOS OS name, so configure gets an explicit ``build == host`` triplet:
    ``config.guess`` is never consulted and ``cross_compiling`` stays ``no``
    (E007's ban on ``--build/--host`` covers the *differing* triplet case, which
    is what silently disables AC_RUN_IFELSE).
  * The OHOS conan profile exports ``SHELL``/``CONFIG_SHELL`` as the HNP bash,
    and that bash cannot complete ``getcwd()`` anywhere on HarmonyOS PC (probed
    in five separate directories, bogus rotating errno).  Configure therefore
    runs its startup ``pwd`` check under a shell that cannot report its own
    directory and aborts with ``working directory cannot be determined``.  A
    recipe-side ``Environment.unset`` does not help: conan sources the profile
    buildenv fragment *after* recipe-contributed scripts, so it re-exports both
    variables.  They are therefore unset inside the command string, which is
    ordering proof.  Assigning them an empty value is forbidden: an empty SHELL
    is AC_SUBST'ed into the generated Makefile and GNU make then execs ``-c``.
  * ``config.status`` then aborts, because configure creates its temporary dir
    with ``umask 077`` while HMDFS forces setgid on created directories, giving
    a ``drwx--S---`` directory that not even its owner can write into
    (E129/E114/E011); the bootstrap-generated configure is widened to
    ``umask 022``.
"""

import os
import shlex

from conan import ConanFile
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    load,
    save,
)
from conan.tools.gnu import AutotoolsToolchain
from conan.tools.layout import basic_layout
from conan.tools.microsoft import unix_path

# Resolved build == host triplet; accepted by the generated config.sub.
OHOS_TRIPLET = "aarch64-unknown-linux-ohos"

# Keep the HNP bash out of every child started below (see module docstring).
NO_HNP_BASH = "unset CONFIG_SHELL SHELL; "


def _relax_hmdfs_umask(conanfile, path):
    """E129/E114/E011: HMDFS forces the setgid bit onto created directories, so
    the ``umask 077 && mktemp -d ./confXXXXXX`` shortcut baked into the
    generated configure/config.status yields a ``drwx--S---`` directory that
    even its owner cannot write to::

        ./config.status[746]: can't create ./confXXXXXX/subs1.awk: Permission denied
        config.status: error: could not setup config files machinery

    Widen it to the knowledge base's prescribed 022.  The file edited here is
    generated by this recipe's own bootstrap step inside the build tree, not an
    upstream tracked source file.
    """
    data = load(conanfile, path)
    if "umask 077" not in data:
        return
    save(conanfile, path, data.replace("umask 077", "umask 022"))


class MdetectConan(ConanFile):
    name = "mdetect"
    version = "0.5.2.6"
    description = "Command-line utility for detecting mouse devices"
    license = "QPL-1.0 OR GPL-2.0-or-later"
    homepage = "https://tracker.debian.org/pkg/mdetect"
    url = "https://tracker.debian.org/pkg/mdetect"
    topics = ("mouse", "device-detection", "cli")

    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def build_requirements(self):
        # No generated configure in the archive, and the CI image has no
        # automake/aclocal: bootstrap needs them as build tools.
        self.tool_requires("automake/1.18")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def _toolchain(self):
        tc = AutotoolsToolchain(self)
        tc.configure_args.append(f"--build={OHOS_TRIPLET}")
        tc.configure_args.append(f"--host={OHOS_TRIPLET}")
        return tc

    def generate(self):
        self._toolchain().generate()

    def build(self):
        apply_conandata_patches(self)
        # Debian's source archive omits generated configure and Makefile files.
        self.run("autoreconf -fi", cwd=self.source_folder, env="conanbuild")
        configure = os.path.join(self.source_folder, "configure")
        _relax_hmdfs_umask(self, configure)
        args = " ".join(shlex.quote(a) for a in self._toolchain().configure_args)
        self.run(f'{NO_HNP_BASH}"{configure}" {args}',
                 cwd=self.build_folder, env="conanbuild")
        # E074: the HMDFS make jobserver fifo is rejected, so serialise.
        self.run(f"{NO_HNP_BASH}make -j1", cwd=self.build_folder, env="conanbuild")
        # The upstream Makefile.am registers no tests; run its check target as
        # required by the upstream-test policy.
        self.run(f"{NO_HNP_BASH}make -j1 check",
                 cwd=self.build_folder, env="conanbuild")

    def package(self):
        # --prefix=/ plus DESTDIR puts bin/mdetect straight into the package.
        destdir = unix_path(self, self.package_folder)
        self.run(f'{NO_HNP_BASH}make install DESTDIR="{destdir}"',
                 cwd=self.build_folder, env="conanbuild")
        copy(
            self,
            "copyright",
            src=os.path.join(self.source_folder, "debian"),
            dst=os.path.join(self.package_folder, "licenses"),
        )

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libs = []
