#!/usr/bin/env python3
"""Conan recipe — mmsrip 0.7.0 — MMS (Microsoft Media Services) protocol
stream ripper.

mmsrip connects to mms:// URLs and saves the ASF/WMV stream to a file.
Upstream: http://nbenoit.tuxfamily.org/projects.php?rq=mmsrip (dead since
the tuxfamily.org hosting shutdown; see conandata.yml for the verified
mirrors). Pure C, Autotools, no dependencies beyond libc.
"""
import glob
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get, rmdir
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class MmsripConan(ConanFile):
    name = "mmsrip"
    version = "0.7.0"
    description = "MMS (Microsoft Media Services) protocol stream ripper"
    license = "GPL-2.0-or-later"
    homepage = "https://nbenoit.tuxfamily.org/projects.php?rq=mmsrip"
    url = ""  # CI fills this

    package_type = "application"
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        # mmsrip uses BSD sockets + gethostbyname; Linux/OHOS both fine.
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("mmsrip is supported only on Linux/OHOS")
        if self.settings.os == "OHOS" and self.settings.arch != "armv8":
            raise ConanInvalidConfiguration("OHOS builds require armv8/aarch64")

    def layout(self):
        basic_layout(self)

    def source(self):
        # url is a list (official dead tuxfamily URL first for provenance,
        # then the verified FreeBSD distcache mirror); get() tries each
        # in order. See conandata.yml for the verification trail.
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # NOTE: the 2006 configure (autoconf 2.59) has NO AC_CANONICAL_HOST
        # and no config.guess/config.sub — it does not accept --host/--build.
        # The build machine IS the OHOS device here (native on-device build,
        # uname -s = "HarmonyOS"), so the default native flow works and the
        # AC_FUNC_MALLOC/AC_FUNC_REALLOC runtime probes run for real.
        # Passing a triplet here would error "unrecognized option: --host".
        #
        # char-signedness (E419 family): main.c stores the getopt_long()
        # return value in a plain `char` and loops `while (c != -1)`.
        # OHOS aarch64 clang defaults plain char to UNSIGNED, so the -1
        # return is truncated to 255 and the loop never exits — mmsrip
        # spins at 100% CPU on any invocation that reaches the end of the
        # argument list (e.g. no arguments: usage() never runs). Same
        # root cause as E419/DRAFT-clipp/DRAFT-etl; fix via the toolchain
        # so every translation unit uses one consistent signed-char mode.
        tc.extra_cflags.append("-fsigned-char")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure()
        # The patch above fixes configure; config.status (generated by the
        # patched configure) inherits umask 022 for its own confstat dir.
        # -j1: 2006-era automake fragments are not parallel-make safe with
        # this toolchain (same pattern as madplay/macchanger).
        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        # doc/ installs the whole GPL text + man pages into share/doc —
        # not needed in a Conan package.
        rmdir(self, os.path.join(self.package_folder, "share"))
        # libtool .la wrappers are not meaningful in a Conan package.
        for _la in glob.glob(os.path.join(self.package_folder, "lib", "*.la")):
            os.remove(_la)

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.runenv_info.prepend_path("PATH", os.path.join(self.package_folder, "bin"))
