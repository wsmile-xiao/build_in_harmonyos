#!/usr/bin/env python3
"""Conan recipe for mecab-unidic 2.1.2 — Japanese UniDic dictionary for MeCab.

NLP dictionary data package (E251 pattern). Source data (lex.csv, matrix.def,
char.def, unk.def, dicrc — UTF-8 encoded) is downloaded from the official OSDN
mirror of the upstream release zip via conandata.yml (SHA256 verified).
Binary indices (char.bin, matrix.bin, sys.dic, unk.dic) are generated by
mecab-dict-index from the tool_requires mecab/0.996 package — fail-closed:
a missing tool or failed index generation aborts the build.

Unlike mecab-ipadic (26 CSV + 8 DEF, EUC-JP), UniDic ships a single lex.csv
(756,463 entries) + one large matrix.def (514 MB, 131,610 x 131,610 matrix).
"""
import os

from conan import ConanFile
from conan.tools.files import get, copy
from conan.tools.layout import basic_layout


class MecabUnidicConan(ConanFile):
    name = "mecab-unidic"
    version = "2.1.2"
    description = "mecab-unidic — Japanese UniDic dictionary data for MeCab (morphological analysis)"
    license = "GPL-2.0-or-later OR LGPL-2.1-or-later OR BSD-3-Clause"
    homepage = "https://clrd.ninjal.ac.jp/unidic/"
    url = "https://osdn.net/projects/unidic/"

    # Data/dictionary package — no C/C++ compilation needed.
    # settings 保留四项以满足 CI L0p 门禁（数据包构建无编译，实际不依赖编译器）。
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        # No patches; test_package is exported automatically by conan create.
        pass

    def requirements(self):
        pass

    def build_requirements(self):
        # mecab-dict-index generates the binary dictionary indices. mecab/0.996
        # installs it under libexec/mecab/ (outside package_info bindirs), so
        # build() resolves it from the dependency package folder directly.
        self.tool_requires("mecab/0.996")

    def layout(self):
        basic_layout(self)

    def source(self):
        # Strict source integrity: download the upstream release zip (official
        # OSDN mirror via dotsrc) with SHA256 verification. Pre-populated data
        # is NOT accepted as a bypass.
        src_data = self.conan_data["sources"]
        import socket
        socket.setdefaulttimeout(30)
        get(self, **src_data, strip_root=True)
        self.output.info("Source downloaded and SHA256 verified from official OSDN mirror")

    def build(self):
        srcdir = self.source_folder

        self.output.info("=== mecab-unidic source data integrity check ===")

        # Core data files of the official unidic-mecab 2.1.2 release
        core_files = ['lex.csv', 'matrix.def', 'char.def', 'unk.def',
                      'left-id.def', 'right-id.def', 'rewrite.def',
                      'feature.def', 'dicrc']
        for fname in core_files:
            fpath = os.path.join(srcdir, fname)
            assert os.path.isfile(fpath), f"Missing: {fname}"
            assert os.path.getsize(fpath) > 0, f"Empty: {fname}"
        self.output.info(f"  Core files: {len(core_files)} present")

        # lex.csv: single lexicon file, official entry count 756,463
        lex_path = os.path.join(srcdir, 'lex.csv')
        with open(lex_path, encoding='utf-8') as f:
            lex_lines = sum(1 for _ in f)
        self.output.info(f"  lex.csv: {lex_lines} entries")
        assert lex_lines == 756463, f"lex.csv entries {lex_lines} != 756463"

        # matrix.def: 131,610 x 131,610 connection matrix (514 MB)
        matrix_path = os.path.join(srcdir, 'matrix.def')
        matrix_size = os.path.getsize(matrix_path)
        self.output.info(f"  matrix.def: {matrix_size} bytes")
        assert matrix_size > 500 * 1000 * 1000, f"matrix.def too small: {matrix_size}"

        # UTF-8 encoding validation (UniDic is UTF-8, unlike ipadic EUC-JP)
        utf8_ok = 0
        utf8_fail = 0
        for fname in core_files:
            fpath = os.path.join(srcdir, fname)
            try:
                with open(fpath, 'r', encoding='utf-8') as f:
                    # Read in chunks — matrix.def is 514 MB
                    while f.read(8 * 1024 * 1024):
                        pass
                utf8_ok += 1
            except UnicodeDecodeError:
                utf8_fail += 1
                self.output.warning(f"UTF-8 FAILED: {fname}")
        assert utf8_fail == 0, f"{utf8_fail} files have invalid UTF-8"
        self.output.info(f"  UTF-8 validation: {utf8_ok} OK, {utf8_fail} FAILED")

        # dicrc sanity: cost-factor and unidic output format
        with open(os.path.join(srcdir, 'dicrc'), encoding='utf-8') as f:
            dicrc = f.read()
        assert 'cost-factor = 700' in dicrc, "dicrc cost-factor != 700"
        assert 'output-format-type = unidic' in dicrc, "dicrc output-format-type != unidic"
        self.output.info("  dicrc: cost-factor=700, output-format-type=unidic")

        # Generate binary indices with mecab-dict-index from tool_requires
        # mecab/0.996 — fail-closed, indices are a required build product.
        mecab_dict_index = self._find_mecab_dict_index()
        self.output.info(f"mecab-dict-index: {mecab_dict_index}")
        self._build_indices(mecab_dict_index, srcdir)

        self.output.info("=== mecab-unidic integrity check PASSED ===")

    def _find_mecab_dict_index(self):
        """Resolve mecab-dict-index from the tool_requires mecab/0.996 package.

        mecab installs it to <pkg>/libexec/mecab/, which is not part of the
        mecab package_info bindirs — resolve from the package folder directly.
        """
        mecab = self.dependencies.build["mecab"]
        exe = os.path.join(mecab.package_folder, "libexec", "mecab", "mecab-dict-index")
        assert os.path.isfile(exe), f"mecab-dict-index not found in mecab package: {exe}"
        assert os.access(exe, os.X_OK), f"mecab-dict-index not executable: {exe}"
        return exe

    def _build_indices(self, exe_path, srcdir):
        """Generate binary indices (char.bin, matrix.bin, sys.dic, unk.dic).

        UniDic is UTF-8, so both -f and -t are utf8 (ipadic uses EUC-JP).
        """
        import subprocess
        result = subprocess.run(
            [exe_path, '-d', srcdir, '-o', srcdir, '-f', 'utf8', '-t', 'utf8'],
            capture_output=True, text=True, timeout=280
        )
        assert result.returncode == 0, (
            f"mecab-dict-index failed (RC={result.returncode}): {result.stderr[:500]}")

        binary_files = ['char.bin', 'matrix.bin', 'sys.dic', 'unk.dic']
        for fname in binary_files:
            fpath = os.path.join(srcdir, fname)
            assert os.path.isfile(fpath) and os.path.getsize(fpath) > 0, (
                f"mecab-dict-index succeeded but {fname} missing/empty")
            self.output.info(f"  Generated: {fname} ({os.path.getsize(fpath)} bytes)")
        self.output.info(f"  Binary indices: {len(binary_files)}/{len(binary_files)} generated")

    def package(self):
        # Copy source data files (lexicon, matrix, definitions, dicrc)
        for pattern in ['*.csv', '*.def', 'dicrc', 'COPYING', 'GPL', 'LGPL', 'BSD']:
            copy(self, pattern, src=self.source_folder, dst=os.path.join(self.package_folder, "dic"))

        # Copy binary indices (required build products — fail if missing)
        for fname in ['char.bin', 'matrix.bin', 'sys.dic', 'unk.dic']:
            fpath = os.path.join(self.source_folder, fname)
            assert os.path.isfile(fpath), f"binary index missing: {fpath}"
            copy(self, fname, src=self.source_folder, dst=os.path.join(self.package_folder, "dic"))
            assert os.path.isfile(os.path.join(self.package_folder, "dic", fname)), \
                f"binary index not packaged: {fname}"

    def package_info(self):
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = []
        dic_dir = os.path.join(self.package_folder, "dic")
        self.output.info(f"Dictionary installed to: {dic_dir}")
        self.output.info(f"  Use: mecab -d {dic_dir}")
