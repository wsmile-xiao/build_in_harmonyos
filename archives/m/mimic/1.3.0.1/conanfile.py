#!/usr/bin/env python3
"""Conan recipe for mimic 1.3.0.1 — Mycroft's TTS engine (mimic1).

mimic1 is a fast, lightweight TTS engine based on CMU Flite (forked at
2016) with HTS (HMM-based speech synthesis) support embedded. The public
API lives in libttsmimic (headers install to include/ttsmimic/).

Upstream build facts (verified against the 1.3.0.1 tag tarball):
  - Autotools project WITHOUT a pre-generated configure script:
    `./autogen.sh` (autoreconf -i) must run before configure. pkg.m4
    (from pkgconf/autoconf-archive) is required for PKG_CHECK_MODULES.
  - Hard dependency: pcre2 (libpcre2-8 via PKG_CHECK_MODULES).
  - `--with-audio=none` skips all audio backends (portaudio/pulse/alsa
    are desktop-only and not published for OHOS); synthesis-to-file and
    the API remain fully functional.
  - Default build is a static library set (libttsmimic*.a) + 5 CLI
    tools (mimic, mimic_time, mimicvox_info, t2p, compile_regexes) +
    one HTS voice data file (cmu_us_slt_hts.htsvoice). No shared
    library target exists upstream (LT_INIT default disable-shared).

OHOS adaptive build:
  - CC/flags come from AutotoolsToolchain (R33); --host=aarch64-linux-ohos
    with an explicit --build so config.guess is not consulted.
  - Upstream CFLAGS use -Werror; the OHOS clang wrapper injects
    `-Wl,--code-sign` into compile commands which trips
    -Werror=unused-command-line-argument → suppressed via cflags, not
    by patching the wrapper or sources. Same for a set-but-unused
    variable in audio.c (audio=none path).
  - pcre2 package in the ohpcd remote ships libpcre2-8.pc with
    prefix=/ (a path that does not exist on this machine), so
    pkg-config alone produces -I/include -L/lib. The recipe passes
    PCRE2_CFLAGS/PCRE2_LIBS explicitly from cpp_info (conan cache path
    independent, same approach as abiword-plugin-docbook).
  - Two minimal source patches (see conandata.yml): musl fpos_t/EOF
    fixes in HTS_misc.c and an extern declaration fix for
    cst_rx_not_indic (-fno-common, clang 11+ default).
  - E011: the configure regenerated by autogen.sh creates its
    config.status temp dirs under `umask 077`; on the HMDFS CI sandbox
    those dirs come out drwx--S--- (not writable even by the owner)
    and config.status aborts with "could not setup config files
    machinery" (PR #12398 CI #59438: ./confXXXXXX/subs1.awk:
    Permission denied). The generated configure is fixed in place
    (umask 022) after autogen.sh, before autotools.configure().
  - `make check` upstream unittests (9 programs) all pass on OHOS
    aarch64 (real run, evidence in test_package/MANIFEST.yml).
"""
import os

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import VirtualBuildEnv
from conan.tools.files import apply_conandata_patches, copy, get
from conan.tools.gnu import Autotools, AutotoolsToolchain, PkgConfigDeps
from conan.tools.layout import basic_layout


def _fix_config_status_tmpdir_umask(path):
    """E011 (PR #12398 CI #59438): HMDFS forces setgid on directories, so
    the `umask 077 && mktemp -d` temp-dir creation that the generated
    configure writes verbatim into config.status produces a drwx--S---
    dir that is not writable even by its owner; config.status then dies
    with "./confXXXXXX/subs1.awk: Permission denied" / "could not setup
    config files machinery". Same defect class as abiword-plugin-mswrite
    (_drop_umask_077, E114) and abiword-plugin-openwriter (E16), but
    mimic's autogen.sh regenerates configure on every build, so the fix
    must run after autogen.sh. The umask is widened to 022 (a52dec/m4
    precedent) instead of dropped: the temp dir stays owner-private
    while remaining writable on HMDFS.

    Scoped and fail-closed: only the payload after the config.status
    heredoc opener (the text configure writes into config.status) is
    touched. Every expected pattern must match exactly once, no umask
    077 may survive anywhere, and the write is read back — any
    deviation aborts the build instead of shipping a broken or
    unpatched configure.
    """
    if not os.path.isfile(path):
        raise ConanException(
            f"E011: generated configure not found at {path} "
            "(autogen.sh did not produce it)")
    with open(path, encoding="utf-8") as f:
        data = f.read()
    # configure builds config.status through heredocs; the first opener
    # marks the start of that section, so everything from there on is
    # (or belongs to) the config.status payload.
    pos = data.find("CONFIG_STATUS <<_ACEOF")
    if pos < 0:
        # other autoconf quoting: literal-only heredoc variant
        pos = data.find("CONFIG_STATUS <<\\_ACEOF")
    if pos < 0:
        raise ConanException(
            f"E011: config.status heredoc opener not found in {path}")
    head, payload = data[:pos], data[pos:]
    mk_old = 'tmp=`(umask 077 && mktemp -d "./confXXXXXX") 2>/dev/null`'
    mk_new = 'tmp=`(umask 022 && mktemp -d "./confXXXXXX") 2>/dev/null`'
    md_old = '(umask 077 && mkdir "$tmp")'
    md_new = '(umask 022 && mkdir "$tmp")'
    if payload.count(mk_old) != 1 or payload.count(md_old) != 1 \
            or payload.count("umask 077") != 2:
        raise ConanException(
            f"E011: expected 1 mktemp site, 1 mkdir site and 2 umask 077 "
            f"occurrences in the config.status payload of {path}, found "
            f"{payload.count(mk_old)}/{payload.count(md_old)}/"
            f"{payload.count('umask 077')} - refusing to patch")
    if head.count("umask 077") != 0:
        # umask 077 outside the payload means the layout changed (e.g. a
        # new autoconf moved the tmp-dir creation); do NOT patch blind.
        raise ConanException(
            f"E011: umask 077 found outside the config.status payload "
            f"of {path} - refusing to patch")
    payload = payload.replace(mk_old, mk_new).replace(md_old, md_new)
    if payload.count(mk_new) != 1 or payload.count(md_new) != 1 \
            or payload.count("umask 077") != 0:
        raise ConanException(
            f"E011: replacement verification failed for {path}")
    new = head + payload
    # 077 -> 022 is length-neutral; a size change means corruption.
    if len(new) != len(data):
        raise ConanException(f"E011: patched size mismatch for {path}")
    with open(path, "w", encoding="utf-8") as f:
        f.write(new)
    with open(path, encoding="utf-8") as f:
        if f.read() != new:
            raise ConanException(
                f"E011: write-back verification failed for {path}")


class MimicConan(ConanFile):
    name = "mimic"
    version = "1.3.0.1"
    package_type = "library"
    description = "Mycroft's fast, lightweight TTS engine (mimic1, CMU Flite fork with embedded HTS engine)"
    license = "MIT"  # upstream COPYING: MIT-like per-file (MIT/X11 style); see notes.md
    homepage = "https://github.com/MycroftAI/mimic1"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    topics = ("tts", "text-to-speech", "flite", "hts", "audio", "voice")

    settings = "os", "compiler", "build_type", "arch"

    # Upstream LT_INIT([dlopen win32-dll disable-static disable-shared]):
    # BOTH library forms are off by default; with neither enabled libtool
    # still archives every lib_LTLIBRARIES into .a (old_library in
    # libttsmimic.la, verified) and `make check` links against the .a.
    # We build with the upstream default (static archives only, no .so
    # is produced); no shared form is invented (R26).
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    exports_sources = "patches/*"

    def layout(self):
        basic_layout(self)

    def requirements(self):
        # configure.ac:101 PKG_CHECK_MODULES([PCRE2], [libpcre2-8]) — hard dep.
        self.requires("pcre2/10.40")

    def build_requirements(self):
        # Upstream tarball has no pre-generated configure: autogen.sh runs
        # autoreconf -i, which needs autoconf/automake/libtool + pkg.m4.
        # The CI sandbox cannot see $HOME/.local tools (same reason as
        # abiword recipes), so they come in as tool_requires.
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")
        self.tool_requires("pkgconf/3.0.5")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # PkgConfigDeps generates .pc files for requirements (pcre2).
        PkgConfigDeps(self).generate()
        VirtualBuildEnv(self).generate()
        tc = AutotoolsToolchain(self)
        # No audio backend on OHOS: portaudio/pulse/alsa unavailable.
        # Synthesis to file + full API still work (voice data included).
        tc.configure_args.append("--with-audio=none")
        # HTS engine is embedded in-tree (no external hts_engine dep).
        tc.configure_args.append("--with-hts")
        # config.guess does not know aarch64-linux-ohos; pass explicit
        # build/host so configure does not run it (same as abiword).
        tc.configure_args.append("--build=aarch64-linux")
        tc.configure_args.append("--host=aarch64-linux-ohos")
        # Upstream LT_INIT([... disable-static disable-shared]) turns BOTH
        # library forms off by default; libtool then still archives each
        # LTLIBRARY into .a for linking but installs nothing into lib/.
        # Enable static explicitly so `make install` ships the archives
        # (shared stays disabled: no .so is produced, R26).
        tc.configure_args.append("--enable-static")
        tc.configure_args.append("--disable-shared")
        # Upstream CFLAGS carry -Werror. The OHOS clang wrapper injects
        # `-Wl,--code-sign` at compile time → unused-command-line-argument
        # error; audio.c (audio=none) has a set-but-unused variable.
        # Suppress both instead of touching the wrapper or sources.
        # NOTE: tc.cflags is a computed property (returns a fresh list);
        # appends must go to tc.extra_cflags or they are silently lost.
        tc.extra_cflags.append("-Wno-error=unused-command-line-argument")
        tc.extra_cflags.append("-Wno-error=unused-but-set-variable")
        # pcre2 .pc in ohpcd has prefix=/ (nonexistent path) → the .pc
        # alone would give -I/include -L/lib. Pass PCRE2_CFLAGS/PCRE2_LIBS
        # explicitly from the dependency's cpp_info (cache-independent,
        # works on CI where package dirs differ; same pattern as the
        # abiword-plugin-* recipes).
        pcre2 = self.dependencies["pcre2"]
        pc_inc = [i if os.path.isabs(i) else os.path.join(
            pcre2.package_folder, i) for i in pcre2.cpp_info.includedirs]
        pc_lib = [l if os.path.isabs(l) else os.path.join(
            pcre2.package_folder, l) for l in pcre2.cpp_info.libdirs]
        tc.configure_args.append("PCRE2_CFLAGS={}".format(
            " ".join("-I{}".format(i) for i in pc_inc)))
        tc.configure_args.append("PCRE2_LIBS={}".format(
            " ".join("-L{}".format(l) for l in pc_lib) + " -lpcre2-8"))
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # No pre-generated configure in the tarball: bootstrap first.
        # autogen.sh (autoreconf -i) needs pkg.m4 for PKG_CHECK_MODULES;
        # it lives in the pkgconf tool_require package (share/aclocal).
        # Inline ACLOCAL_PATH injection on the command: buildenv_info
        # .append_path proved unreliable in CI (same lesson as
        # abiword-plugin-docbook, where aclocal could not see recipe m4
        # until the path was injected inline in the run command).
        m4_dirs = []
        for _, dep in self.dependencies.build.items():
            m4 = os.path.join(dep.package_folder, "share", "aclocal")
            if os.path.isfile(os.path.join(m4, "pkg.m4")):
                m4_dirs.append(m4)
        if not m4_dirs:
            raise ConanException("pkg.m4 not found in any build dependency")
        aclocal_paths = ":".join(m4_dirs + ["$ACLOCAL_PATH"])
        self.run(f'ACLOCAL_PATH="{aclocal_paths}" ./autogen.sh',
                 cwd=self.source_folder, env="conanbuild")
        # E011: fix the configure that autogen.sh JUST regenerated (it
        # would overwrite anything patched earlier) before configure
        # runs it and writes out config.status.
        _fix_config_status_tmpdir_umask(
            os.path.join(self.source_folder, "configure"))
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(target="all")
        # Upstream unittests: real run on the build machine (it IS the
        # OHOS aarch64 target). 9/9 PASS (R51 evidence in MANIFEST.yml).
        autotools.make(target="check")

    def package(self):
        autotools = Autotools(self)
        # staging install (DESTDIR) keeps the tree relocatable
        autotools.install()
        # libtool .la files are not packaged
        lad = os.path.join(self.package_folder, "lib")
        if os.path.isdir(lad):
            for f in os.listdir(lad):
                if f.endswith(".la"):
                    os.unlink(os.path.join(lad, f))

    def package_info(self):
        self.cpp_info.libs = ["ttsmimic_lang_all_voices",
                              "ttsmimic_lang_all_langs",
                              "ttsmimic_lang_usenglish",
                              "ttsmimic_lang_cmulex",
                              "ttsmimic_lang_cmu_grapheme_lang",
                              "ttsmimic_lang_cmu_grapheme_lex",
                              "ttsmimic_lang_cmu_indic_lang",
                              "ttsmimic_lang_cmu_indic_lex",
                              "ttsmimic_lang_cmu_us_slt_hts",
                              "ttsmimic"]
        self.cpp_info.includedirs = ["include/ttsmimic"]
        self.cpp_info.libdirs = ["lib"]
        self.cpp_info.resdirs = ["share"]
