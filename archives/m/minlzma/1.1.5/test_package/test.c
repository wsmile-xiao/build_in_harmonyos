static const unsigned int TEST_XZ_LEN = 132;
static const char TEST_EXPECTED[] = "minlzma HarmonyOS PC consumer test: LZMA2/XZ decode via public API works.";
static const unsigned int TEST_EXPECTED_LEN = 73;

int main(void) {
    uint32_t outSize = 0;
    uint8_t* out = NULL;

    /* 1. 查询解压后大小 */
    if (!XzDecode(TEST_XZ, TEST_XZ_LEN, NULL, &outSize)) {
        printf("FAIL: XzDecode size query failed\n");
        return 1;
    }
    if (outSize != TEST_EXPECTED_LEN) {
        printf("FAIL: expected size %u, got %u\n", TEST_EXPECTED_LEN, outSize);
        return 1;
    }

    /* 2. 实际解压 */
    out = (uint8_t*)malloc(outSize);
    if (out == NULL) {
        printf("FAIL: malloc\n");
        return 1;
    }
    if (!XzDecode(TEST_XZ, TEST_XZ_LEN, out, &outSize)) {
        printf("FAIL: XzDecode decode failed\n");
        free(out);
        return 1;
    }
    if (XzChecksumError()) {
        printf("FAIL: checksum error reported\n");
        free(out);
        return 1;
    }
    if (outSize != TEST_EXPECTED_LEN || memcmp(out, TEST_EXPECTED, TEST_EXPECTED_LEN) != 0) {
        printf("FAIL: decoded content mismatch\n");
        free(out);
        return 1;
    }

    printf("PASS: XzDecode round-trip ok (%u bytes)\n", outSize);
    free(out);
    return 0;
}
