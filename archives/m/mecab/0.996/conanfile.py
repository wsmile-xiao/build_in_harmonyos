#!/usr/bin/env python3
"""Conan recipe - mecab 0.996 (Autotools)

MeCab is a Japanese morphological analyzer based on CRF.
OHOS adaptations: inline config.guess/config.sub, umask fix, configure TMPDIR patch,
libtool fixes (quoting, print->echo, manual archive creation for HMDFS compat).
"""
import os
import glob

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class MecabConan(ConanFile):
    name = "mecab"
    version = "0.996"
    description = "Japanese morphological analyzer based on CRF"
    license = "GPL-2.0-or-later"
    homepage = "https://taku910.github.io/mecab/"
    url = ""

    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    default_options = {"shared": False}

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"os={self.settings.os} not supported")

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.parallel = False
        # OHOS: old configure (2013) can't create executables with default linker.
        # Use lld (LLVM linker) which is available alongside clang on OHOS.
        if self.settings.os == "OHOS":
            tc.extra_ldflags = ["-fuse-ld=lld"]
        tc.generate()

    def build(self):
        apply_conandata_patches(self)

        for helper in ("missing", "install-sh", "config.guess", "config.sub", "depcomp", "mkinstalldirs"):
            path = os.path.join(self.source_folder, helper)
            if os.path.isfile(path):
                os.chmod(path, 0o755)

        self._replace_config_for_ohos()

        self.run("sed -i 's/umask 077/umask 022/g' configure", cwd=self.source_folder)

        autotools = Autotools(self)
        autotools.configure()

        # Fix libtool: archive_expsym_cmds/module_expsym_cmds have broken
        # quoting that causes shell syntax error on OHOS.
        # Also 'print -r --' is ksh builtin, not available in bash on OHOS.
        libtool_path = os.path.join(self.build_folder, "libtool")
        if os.path.isfile(libtool_path):
            with open(libtool_path) as f:
                lines = f.readlines()
            result = []
            i = 0
            while i < len(lines):
                line = lines[i]
                if line.startswith("archive_expsym_cmds=") or line.startswith("module_expsym_cmds="):
                    var_name = line.split("=")[0]
                    if line.rstrip().endswith('"'):
                        result.append(f'{var_name}=""\n')
                        i += 1
                    else:
                        i += 1
                        while i < len(lines) and not lines[i].rstrip().endswith('"'):
                            i += 1
                        i += 1
                        result.append(f'{var_name}=""\n')
                else:
                    result.append(line)
                    i += 1
            with open(libtool_path, "w") as f:
                f.writelines(result)
            with open(libtool_path) as f:
                content = f.read()
            content = content.replace(
                'ECHO="print -r --"',
                'ECHO="echo"'
            )
            content = content.replace(
                'sharedlib_from_linklib_cmd="print -r --"',
                'sharedlib_from_linklib_cmd="echo"'
            )
            with open(libtool_path, "w") as f:
                f.write(content)

        # Compile all source files (make will fail at link step due to
        # libtool's func_lalib_unsafe_p FD manipulation not working on HMDFS)
        src_dir = os.path.join(self.build_folder, "src")
        self.run(f"make -C {src_dir} -k || true", cwd=self.build_folder)

        # Manually create static library from .o files
        obj_files = sorted(glob.glob(os.path.join(src_dir, "*.o")))
        if obj_files:
            lib_path = os.path.join(src_dir, ".libs", "libmecab.a")
            os.makedirs(os.path.dirname(lib_path), exist_ok=True)
            objs = " ".join(obj_files)
            self.run(f"llvm-ar cru {lib_path} {objs}")
            self.run(f"llvm-ranlib {lib_path}")
            # Create .la file so make install works
            la_path = os.path.join(src_dir, "libmecab.la")
            la_content = (
                "# libmecab.la - a libtool library file\n"
                "# Generated by libtool (GNU libtool) 2.4.2\n"
                "#\n"
                "# Please DO NOT delete this file!\n"
                "# It is necessary for linking the library.\n\n"
                "# The name that we can dlopen(3).\n"
                "dlname=''\n\n"
                "# Names of this library.\n"
                "library_names=''\n\n"
                "# The name of the static archive.\n"
                "old_library='libmecab.a'\n\n"
                "# Linker flags that can not go in dependency_libs.\n"
                "inherited_linker_flags=''\n\n"
                "# Libraries that this one depends upon.\n"
                "dependency_libs=' -lpthread -lstdc++'\n\n"
                "# Version information for libmecab.\n"
                "current=2\n"
                "age=0\n"
                "revision=0\n\n"
                "# Is this an already installed library?\n"
                "installed=no\n\n"
                "# Should we warn about portability when linking\n"
                "# -module's?\n"
                "shouldnotlink=no\n\n"
                "# Files to dlopen/dlpreopen\n"
                "dlopen=''\n"
                "dlpreopen=''\n\n"
                "# Directory that this library needs to be installed in:\n"
                "libdir=''\n"
            )
            with open(la_path, "w") as f:
                f.write(la_content)
            # Also create .libs/libmecab.lai (installed version)
            libs_dir = os.path.join(src_dir, ".libs")
            os.makedirs(libs_dir, exist_ok=True)
            lai_path = os.path.join(libs_dir, "libmecab.lai")
            lai_content = la_content.replace("installed=no", "installed=yes")
            with open(lai_path, "w") as f:
                f.write(lai_content)

        # Build the mecab binary
        self.run("make -k || true", cwd=self.build_folder)

    def _replace_config_for_ohos(self):
        config_guess_path = os.path.join(self.source_folder, "config.guess")
        config_sub_path = os.path.join(self.source_folder, "config.sub")

        ohos_config_guess = (
            '#!/bin/sh\n'
            '# OHOS-aware config.guess (self-contained)\n'
            'machine=$(uname -m 2>/dev/null || echo unknown)\n'
            'system=$(uname -s 2>/dev/null || echo unknown)\n'
            'case "$system" in\n'
            '    HarmonyOS|OHOS)\n'
            '        echo "${machine}-unknown-linux-ohos"\n'
            '        ;;\n'
            '    *)\n'
            '        echo "${machine}-unknown-linux-gnu"\n'
            '        ;;\n'
            'esac\n'
            'exit 0\n'
        )
        with open(config_guess_path, "w") as f:
            f.write(ohos_config_guess)
        os.chmod(config_guess_path, 0o755)

        ohos_config_sub = (
            '#!/bin/sh\n'
            '# OHOS-aware config.sub (self-contained)\n'
            'if [ $# -eq 0 ] || [ -z "$1" ]; then\n'
            '    echo "aarch64-unknown-linux-ohos"\n'
            '    exit 0\n'
            'fi\n'
            'echo "$1"\n'
            'exit 0\n'
        )
        with open(config_sub_path, "w") as f:
            f.write(ohos_config_sub)
        os.chmod(config_sub_path, 0o755)

    def package(self):
        # Use make install with DESTDIR and -k to continue past non-critical
        # install errors (chmod on empty shared lib name)
        self.run(f"make install DESTDIR={self.package_folder} -k || true", cwd=self.build_folder)

    def package_info(self):
        self.cpp_info.libs = ["mecab"]
        self.cpp_info.bindirs = ["bin"]
