#!/usr/bin/env python3
"""Conan recipe — mpck 0.21 (Checkmate MP3 Checker, command-line).

mpck reads MP3 files and checks them for errors: invalid frame headers,
truncated streams, bad frame CRCs, and unparseable ID3/APE metadata.

Build system: GNU Autotools (configure + make). The configure script ships
in the release tarball, so we do not require autoconf/automake at build
time. Upstream ships one test script, mpck/test/crctest.sh, but it lives
only in the git repo (NOT in the release tarball) and is not registered in
automake's TESTS, so `make check` is a no-op. crctest.sh is a fixture
generator: dd + toolame + lame produce 216 .mp2/.mp3 files over
(12 bitrate × 9 samplerate × 2 channels); it never calls mpck and has no
pass/fail assertion. It could not run on OHOS (toolame/lame CLI encoders
absent from the registry and PATH), so build() runs no `make check` —
test_package performs the real input test instead.

License: COPYING = GNU GPL v2 → "GPL-2.0-or-later" (per the SPDX-or-later
wording in each source header, matching Homebrew's license field).
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout

# The release tarball ships a configure generated by Autoconf 2.69. Its
# config.status creates the temp dir with `umask 077 && mktemp -d
# "./confXXXXXX"`, which on the HarmonyOS build filesystem (hmdfs,
# setgid-inherited) yields a mode-0700 owner dir that subsequent writes
# are denied into → "config.status: could not setup config files
# machinery". We fix this with a portability patch (0001-configure-umask-
# 022.patch) that relaxes the umask to 022, matching the established fix
# used elsewhere in this tree (a52dec 0002). Do NOT run autoreconf: it
# regenerates configure and would overwrite the patched bundled copy.
_AUTORECONF = False


class MpckConan(ConanFile):
    name = "mpck"
    version = "0.21"
    description = "Check MP3 files for errors (Checkmate command-line tool)"
    license = "GPL-2.0-or-later"
    homepage = "https://checkmate.gissen.nl/"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"mpck supports Linux/OHOS only, got {self.settings.os}"
            )
        if self.settings.os == "OHOS" and self.settings.arch != "armv8":
            raise ConanInvalidConfiguration(
                "OHOS builds require armv8/aarch64"
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # Regenerate configure with a modern autoconf (see _AUTORECONF note)
        # so config.status's temp-dir logic is compatible with the OHOS build
        # filesystem. --install supplies the missing install-sh/missing scripts
        # that the regenerated configure references.
        if _AUTORECONF:
            tc.autoreconf_args = ["--force", "--install"]
        # The configure script probes for a working C compiler and for
        # getopt_long (falling back to the bundled libgnugetopt-1.2). For
        # OHOS cross builds we must hand it the canonical GNU triplet so
        # AC_PROG_CC's "does it compile and run a trivial program?" test
        # (which uses the cross compiler) is satisfied.
        if str(self.settings.os) == "OHOS":
            tc.configure_args.extend([
                "--build=aarch64-unknown-linux-gnu",
                "--host=aarch64-unknown-linux-gnu",
            ])
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])
        # Upstream ships one script, mpck/test/crctest.sh, but it is NOT in
        # the release tarball and NOT registered in automake TESTS, so `make
        # check` is a no-op. crctest.sh is a fixture generator (dd + toolame
        # + lame → 216 .mp2/.mp3 over 12 bitrate × 9 samplerate × 2 channels),
        # never invokes mpck, and has no pass/fail assertion. It could not
        # run on OHOS anyway (toolame/lame CLI encoders absent from the
        # registry and PATH), so we skip the hollow `make check` here. The
        # real functional test lives in test_package.

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.runenv_info.prepend_path("PATH", os.path.join(self.package_folder, "bin"))
